function result = fuxianPaperMidamblePointDecodeV2( ...
    rxPhysical,config,layout)
%FUXIANPAPERMIDAMBLEPOINTDECODEV2 带因果更新时延的SF11论文接收机。

known = zeros(config.bootstrapPilotCount,1);
bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
    rxPhysical(layout.bootstrapRows,:),known,config);
nSymbols = size(rxPhysical,1);
requestedMask = false(nSymbols,1);
requestedMask(layout.bootstrapRows) = true;
requestedMask(layout.midambleRows) = true;
decisionBins = nan(nSymbols,1);
decisionBins(layout.midambleRows) = 0;
availabilityRows = (1:nSymbols).';
% Midamble后的第一个数据符号仍使用旧状态，更新从第二个数据符号开始生效。
availabilityRows(layout.midambleRows) = ...
    min(layout.midambleRows+2,nSymbols+1);

pointConfig = config;
pointConfig.virtualPilotHistoryLength = 1;
tracker = satelliteFig3RollingPilotTracker( ...
    rxPhysical,pointConfig,known, ...
    AcceptedMask=requestedMask, ...
    DecisionWaveformBins=decisionBins, ...
    PilotAvailabilityRows=availabilityRows, ...
    BootstrapOverride=bootstrap, ...
    ForceAccept=true, ...
    FreezeBootstrapRate=true, ...
    ReleaseBootstrapRateAfterVirtualPilotCount=nSymbols+1, ...
    RateDeviationLimitBinsPerSec=0, ...
    BootstrapRateOverrideBinsPerSec=0, ...
    ApplyVirtualPilotPhaseCorrection=true, ...
    VirtualPilotInnovationGain=1);
common = fuxianCommonPayloadDecode( ...
    tracker.compensatedSymbols,tracker.hardWaveformBins,layout,config);

result = common;
result.detectedWaveformBins = tracker.hardWaveformBins;
result.tracker = tracker;
result.bootstrap = bootstrap;
result.initialRateBinsPerSec = 0;
result.usesPayloadFeedback = false;
result.usesExplicitMidambles = true;
result.explicitMidambleRows = layout.midambleRows;
result.explicitMidambleAccepted = ...
    tracker.pilotAccepted(layout.midambleRows);
result.explicitMidambleAppliedAtRows = ...
    tracker.pilotAppliedAtRows(layout.midambleRows);
result.usesOrbitPrior = false;
result.algorithmProvenance = [ ...
    'SF11 Paper Midamble-Point V2；公共Stage55 bootstrap；' ...
    '原生残差估计；Midamble后一数据符号处理时延；n_int=48'];
end
