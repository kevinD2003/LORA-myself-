function report = run_fuxian_pilot_source_factorial(options)
%RUN_FUXIAN_PILOT_SOURCE_FACTORIAL 跨帧状态×导频来源的2×2消融。

arguments
    options.SnrDb (1,1) double = -21
    options.PassCount (1,1) double {mustBeInteger,mustBePositive} = 1
    options.FramesPerVisibleSegment (1,1) double ...
        {mustBeInteger,mustBePositive} = 2
    options.OutputFolderName (1,:) char = ...
        'pilot_source_crossframe_factorial_smoke'
end

comparisonRoot = fileparts(mfilename('fullpath'));
sourceRoot = fuxianSourceRoot(comparisonRoot);
savedPath = path;
restorePath = onCleanup(@() path(savedPath));
addpath(sourceRoot,'-begin');
experiment = fuxianComparisonConfig( ...
    MidambleSpacingMode="visible_rate_matched", ...
    IncludeTerminalMidamble=true);
config = experiment.physicalConfig;
schedule = satelliteFig3ContinuousPassSchedule(config);
edges = find(diff([false;schedule.fullyVisible(:);false]));
segments = reshape(edges,2,[]).'+[0 -1];
segments(:,2) = min(segments(:,2), ...
    segments(:,1)+options.FramesPerVisibleSegment-1);
methods = ["Midamble-isolated";"VP-isolated"; ...
    "Midamble-crossframe";"VP-crossframe"];
records = table();

for passIndex = 1:options.PassCount
    for segmentIndex = 1:size(segments,1)
        vpState = struct();
        midambleState = struct();
        phaseStateRad = 0;
        for frameIndex = segments(segmentIndex,1):segments(segmentIndex,2)
            payloadSeed = 2026751800 + 10000*passIndex + frameIndex;
            noiseSeed = 2026751900 + 10000*passIndex + frameIndex;
            payload = satelliteFig3GeneratePayload(config,payloadSeed);
            layout = fuxianMidambleLayout(payload.symbolBins,experiment);
            [rx,~,truth] = generateContinuousSatelliteFrame( ...
                layout.physicalBins,config, ...
                StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                SampleSnrDb=options.SnrDb,NoiseSeed=noiseSeed, ...
                InitialPhaseRad=phaseStateRad,NextSymbolBin=0);
            phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);
            midambleIsolated = fuxianKnownMidambleQualityDecode( ...
                rx,config,layout);
            vpIsolated = fuxianSenLoRaDecode(rx,config,layout);
            incomingMidambleState = midambleState;
            incomingVpState = vpState;
            midambleCross = fuxianKnownMidambleQualityDecode( ...
                rx,config,layout,FrameStartTimeSec= ...
                schedule.frameStartTimeSec(frameIndex), ...
                CrossFrameState=incomingMidambleState);
            vpCross = fuxianSenLoRaDecode( ...
                rx,config,layout,FrameStartTimeSec= ...
                schedule.frameStartTimeSec(frameIndex), ...
                CrossFrameState=incomingVpState);
            midambleState = midambleCross.crossFrameState;
            vpState = vpCross.crossFrameState;
            assert(isequaln(midambleState,vpState), ...
                '两种导频来源必须输出相同的跨帧bootstrap状态。');
            branches = {midambleIsolated,vpIsolated, ...
                midambleCross,vpCross};
            for methodIndex = 1:numel(methods)
                branch = branches{methodIndex};
                hardSymbols = branch.detectedWaveformBins(layout.dataRows);
                deliveredBits = branch.decodedDataBits(:);
                truthCfoBins = truth.trueDopplerHz(layout.dataRows)/ ...
                    config.fftBinSpacingHz;
                cfoError = branch.tracker.predictedCfoBins( ...
                    layout.dataRows)-truthCfoBins;
                newRow = table(options.SnrDb,passIndex,segmentIndex, ...
                    frameIndex,methods(methodIndex),payloadSeed,noiseSeed, ...
                    sum(hardSymbols ~= payload.symbolBins), ...
                    numel(payload.symbolBins), ...
                    sum(deliveredBits ~= payload.dataBits(:)), ...
                    numel(payload.dataBits),sum(cfoError.^2), ...
                    numel(cfoError),branch.usesCrossFrameState, ...
                    branch.usesExplicitMidambles, ...
                    'VariableNames',{'snrDb','passIndex','segmentIndex', ...
                    'frameIndex','method','payloadSeed','noiseSeed', ...
                    'symbolErrors','symbolCount','deliveredBitErrors', ...
                    'bitCount','cfoSseBins','cfoSampleCount', ...
                    'usesCrossFrameState','usesExplicitMidambles'});
                records = [records;newRow]; %#ok<AGROW>
            end
        end
    end
end

outputFolder = fullfile(comparisonRoot,'results', ...
    options.OutputFolderName);
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end
writetable(records,fullfile(outputFolder,'factorial_frame_records.csv'));
save(fullfile(outputFolder,'factorial_result.mat'), ...
    'records','experiment','config','schedule','segments','methods','options');
report = struct('records',records,'experiment',experiment, ...
    'outputFolder',outputFolder,'methods',methods);
fprintf('2×2导频来源/跨帧状态消融完成：%s\n',outputFolder);
end

function value = localWrapToPi(value)
value = mod(value+pi,2*pi)-pi;
end
