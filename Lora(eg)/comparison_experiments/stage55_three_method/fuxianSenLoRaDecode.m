function result = fuxianSenLoRaDecode( ...
    rxPhysical,config,layout,options)
%FUXIANSENLORADECODE Stage55 VP-quality with explicit pilots ignored.
% The tracker runs on physical symbol time. Hamming confidence and final
% decoding operate only on the original 112 data symbols.

arguments
    rxPhysical (:,:) double
    config (1,1) struct
    layout (1,1) struct
    options.FrameStartTimeSec (1,1) double = NaN
    options.CrossFrameState (1,1) struct = struct()
end

known = zeros(config.bootstrapPilotCount,1);
bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
    rxPhysical(layout.bootstrapRows,:),known,config);
fallbackRate = min(config.maxRateBinsPerSec,max( ...
    -config.maxRateBinsPerSec,bootstrap.jointRateBinsPerSec));
crossFrameState = options.CrossFrameState;
usesCrossFrameState = isfinite(options.FrameStartTimeSec);
if ~usesCrossFrameState && ~isempty(fieldnames(crossFrameState))
    error('FuxianDuibi:SenLoRaCrossFrameTime', ...
        'FrameStartTimeSec is required with cross-frame state.');
end
if usesCrossFrameState
    measurementTimeSec = options.FrameStartTimeSec + ...
        0.5*config.bootstrapPilotCount*config.symbolDurationSec;
    [initialRate,crossFrameState,rateDiagnostic] = ...
        satelliteFig3CrossFrameRateUpdate(crossFrameState, ...
        measurementTimeSec,bootstrap.epsilonHatBins, ...
        fallbackRate,config);
else
    initialRate = fallbackRate;
    rateDiagnostic = struct( ...
        'source','isolated-frame known-preamble phase fit', ...
        'historyCount',1,'rawRateBinsPerSec',fallbackRate, ...
        'rateBinsPerSec',fallbackRate, ...
        'usesTrajectoryPrior',false,'usesPayloadTruth',false);
end

result = localMappedIterative(rxPhysical,config,known,layout, ...
    bootstrap,initialRate,rateDiagnostic);
result.commonBootstrap = bootstrap;
result.bootstrap = bootstrap;
result.initialRateBinsPerSec = initialRate;
result.isolatedFrameRateBinsPerSec = fallbackRate;
result.crossFrameState = crossFrameState;
result.crossFrameRateDiagnostic = rateDiagnostic;
result.usesCrossFrameState = usesCrossFrameState;
result.usesOrbitPrior = false;
result.usesExplicitMidambles = false;
result.algorithmProvenance = [ ...
    'Frozen Stage55 VP-quality on physical symbol time; explicit ' ...
    'midamble rows excluded from confidence and tracking observations'];
end

function result = localMappedIterative( ...
        rxPhysical,config,known,layout,bootstrap,initialRate,rateDiagnostic)
nSymbols = size(rxPhysical,1);
bootstrapCount = numel(known);
mask = false(nSymbols,1);
mask(layout.bootstrapRows) = true;
pilotConfidence = nan(nSymbols,1);
pilotTau = NaN;
decisionBins = nan(nSymbols,1);
previousProposed = false(nSymbols,1);
previousDecisionBins = nan(nSymbols,1);
history = repmat(struct(),0,1);
converged = false;

pilotAvailabilityRows = (1:nSymbols).';
blockLength = 4+config.cr;
for dataIndex = 1:config.payloadSymbolCount
    blockEndData = min(config.payloadSymbolCount, ...
        ceil(dataIndex/blockLength)*blockLength);
    if blockEndData < config.payloadSymbolCount
        availability = layout.dataRows(blockEndData)+1;
    else
        availability = nSymbols+1;
    end
    pilotAvailabilityRows(layout.dataRows(dataIndex)) = availability;
end

useObservableVpRate = ...
    rateDiagnostic.historyCount < config.virtualPilotHistoryLength;
for iteration = 1:config.maxSenLoRaIterations
    tracker = satelliteFig3RollingPilotTracker( ...
        rxPhysical,config,known, ...
        AcceptedMask=mask, ...
        PilotConfidence=pilotConfidence, ...
        PilotThreshold=pilotTau, ...
        DecisionWaveformBins=decisionBins, ...
        PilotAvailabilityRows=pilotAvailabilityRows, ...
        InnovationLimitBins=config.confidenceInnovationLimitBins, ...
        FreezeBootstrapRate=true, ...
        ReleaseBootstrapRateAfterVirtualPilotCount=1e9, ...
        RateDeviationLimitBinsPerSec= ...
            config.senloraRateTrackingDeviationLimitBinsPerSec, ...
        BootstrapRateOverrideBinsPerSec=initialRate, ...
        BootstrapOverride=bootstrap, ...
        ApplyVirtualPilotPhaseCorrection=true, ...
        VirtualPilotInnovationGain= ...
            config.senloraVirtualPilotInnovationGain, ...
        EnableVirtualPilotPhasePairCfo=true, ...
        VirtualPilotPhasePairInnovationGain= ...
            config.senloraPhasePairInnovationGain, ...
        PhasePairInnovationLimitBins= ...
            config.senloraPhasePairInnovationLimitBins, ...
        PhasePairAgreementLimitBins= ...
            config.senloraPhasePairAgreementLimitBins, ...
        UseObservableVirtualPilotRate=useObservableVpRate, ...
        VirtualPilotCfoStdBins= ...
            config.senloraVirtualPilotCfoStdBins, ...
        VirtualPilotRateStdLimitBinsPerSec= ...
            config.senloraVirtualPilotRateStdLimitBinsPerSec);

    compact = tracker.compensatedSymbols(layout.compactRows,:);
    soft = satelliteFig3SenLoRaConfidence(compact,config, ...
        PreviousTauGlobal=NaN, ...
        AmendLlrMix=config.amendLlrMix);
    compactPayloadRows = (bootstrapCount+1: ...
        bootstrapCount+config.payloadSymbolCount).';
    proposedData = soft.confidentMask(compactPayloadRows) & ...
        soft.readyMask(compactPayloadRows);
    marginRatio = soft.symbolCodewordMargin(compactPayloadRows)./ ...
        max(soft.tauGlobal(compactPayloadRows),eps);
    proposedData = proposedData & ...
        marginRatio >= config.senloraMinimumMarginRatio;
    proposedData = proposedData & ...
        soft.decodedWaveformBins(compactPayloadRows) == ...
        tracker.hardWaveformBins(layout.dataRows);

    proposed = false(nSymbols,1);
    proposed(layout.bootstrapRows) = true;
    proposed(layout.dataRows) = proposedData;
    if iteration == 1
        stable = false(nSymbols,1);
    else
        sameDecision = false(nSymbols,1);
        sameDecision(layout.dataRows) = ...
            soft.decodedWaveformBins(compactPayloadRows) == ...
            previousDecisionBins(layout.dataRows);
        stable = proposed & previousProposed & sameDecision;
    end
    stable(layout.bootstrapRows) = true;
    stable(layout.midambleRows) = false;

    history(iteration).iteration = iteration;
    history(iteration).requestedMask = mask;
    history(iteration).proposedMask = proposed;
    history(iteration).stableMask = stable;
    history(iteration).tracker = tracker;
    history(iteration).soft = soft;
    nextMask = mask | stable;
    if iteration >= 2 && isequal(nextMask,mask)
        converged = true;
        break
    end
    mask = nextMask;
    pilotConfidence = nan(nSymbols,1);
    pilotConfidence(layout.dataRows) = ...
        soft.confidence(compactPayloadRows)./ ...
        max(soft.tauGlobal(compactPayloadRows),eps);
    pilotTau = 1;
    decisionBins = nan(nSymbols,1);
    previousProposed = proposed;
    previousDecisionBins = nan(nSymbols,1);
    previousDecisionBins(layout.dataRows) = ...
        soft.decodedWaveformBins(compactPayloadRows);
end

history = history(1:numel(history));
last = history(end);
finalTracker = last.tracker;
common = fuxianCommonPayloadDecode( ...
    finalTracker.compensatedSymbols, ...
    finalTracker.hardWaveformBins,layout,config);
result = common;
result.detectedWaveformBins = finalTracker.hardWaveformBins;
result.pilotAccepted = finalTracker.pilotAccepted;
result.tracker = finalTracker;
result.soft = last.soft;
result.iterationHistory = history;
result.iterations = numel(history);
result.converged = converged;
result.virtualPilotsEnabled = true;
result.qualityAwareVirtualPilotsEnabled = true;
end
