function figureManifest = fuxianPlotTrajectoryComparison( ...
    windowStatistics,records,config,schedule,experiment,outputFolder)
%FUXIANPLOTTRAJECTORYCOMPARISON Write only the SER and BER figures.

methods = experiment.methodNames;
labels = experiment.methodLabels;
colors = [0.84 0.18 0.13;0.00 0.38 0.78;0.30 0.65 0.25];
styles = {'s--','o-','d-.'};
snrGrid = unique(windowStatistics.snrDb,'stable').';
regions = {'high_doppler_rate','high_doppler_shift'};
specs = { ...
    'serShown','serLower95','serUpper95','SER',[1e-3 1], ...
        'sf11_stage55_three_method_ser_trajectory'; ...
    'deliveredBerShown','deliveredBerLower95', ...
        'deliveredBerUpper95','Delivered BER',[1e-5 1], ...
        'sf11_stage55_three_method_ber_trajectory'};
recordsOut = repmat(struct('metric','','pngFile','','figFile',''), ...
    size(specs,1),1);

for metricIndex = 1:size(specs,1)
    fig = figure('Visible','off','Color','w', ...
        'Position',[40 20 1760 1380]);
    closeFigure = onCleanup(@() close(fig));
    layout = tiledlayout(fig,3,2, ...
        'TileSpacing','compact','Padding','compact');
    % 左列对应高速率区域，右列对应高频移区域。
    rateAxes = nexttile(layout);
    shiftAxes = nexttile(layout);
    localPlotDopplerContext(shiftAxes,rateAxes,config,schedule);

    panelIndex = 0;
    metricAxes = gobjects(numel(snrGrid)*numel(regions),1);
    for snrDb = snrGrid
        for regionIndex = 1:numel(regions)
            panelIndex = panelIndex+1;
            ax = nexttile(layout);
            metricAxes(panelIndex) = ax;
            hold(ax,'on');
            set(ax,'YScale','log');
            for methodIndex = 1:numel(methods)
                rows = localWindowRows(windowStatistics,snrDb, ...
                    regions{regionIndex},methods{methodIndex});
                lower = max(rows.(specs{metricIndex,2}), ...
                    specs{metricIndex,5}(1));
                upper = max(rows.(specs{metricIndex,3}), ...
                    specs{metricIndex,5}(1));
                localBand(ax,rows.windowCenterTimeSec, ...
                    lower,upper,colors(methodIndex,:));
            end
            handles = gobjects(numel(methods),1);
            for methodIndex = 1:numel(methods)
                rows = localWindowRows(windowStatistics,snrDb, ...
                    regions{regionIndex},methods{methodIndex});
                handles(methodIndex) = plot(ax, ...
                    rows.windowCenterTimeSec, ...
                    rows.(specs{metricIndex,1}), ...
                    styles{methodIndex}, ...
                    'Color',colors(methodIndex,:), ...
                    'LineWidth',1.6,'MarkerSize',5, ...
                    'DisplayName',labels{methodIndex});
            end
            ylabel(ax,specs{metricIndex,4});
            xlabel(ax,'Time relative to closest approach (s)');
            ylim(ax,specs{metricIndex,5});
            xlim(ax,[schedule.passStartTimeSec schedule.passEndTimeSec]);
            grid(ax,'on');
            grid(ax,'minor');
            box(ax,'on');
            localShadeBlind(ax,schedule.window);
            selected = records.snrDb == snrDb & ...
                strcmp(records.region,regions{regionIndex}) & ...
                strcmp(records.method,methods{1});
            intervals = localRegionIntervals( ...
                unique(records.frameIndex(selected)),schedule);
            localTargetLines(ax,intervals);
            title(ax,sprintf('%.0f dB, %s',snrDb, ...
                localRegionLabel(regions{regionIndex},records, ...
                selected,config)),'FontWeight','normal');
            if panelIndex == 1
                legend(ax,handles,labels,'Location','southwest', ...
                    'FontSize',9,'Box','on');
            end
        end
    end
    set([shiftAxes;rateAxes;metricAxes], ...
        'FontName','Times New Roman','FontSize',10, ...
        'GridLineStyle',':','MinorGridLineStyle',':');
    sgtitle(layout,sprintf([ ...
        'SF=11 Stage55 common-frame comparison: %s\n' ...
        'same orbit, payload/noise seeds, continuous phase and decoder'], ...
        specs{metricIndex,4}), ...
        'FontWeight','normal','FontSize',14);

    baseName = specs{metricIndex,6};
    pngFile = fullfile(outputFolder,[baseName '.png']);
    figFile = fullfile(outputFolder,[baseName '.fig']);
    exportgraphics(fig,pngFile,'Resolution',220);
    savefig(fig,figFile);
    recordsOut(metricIndex) = struct( ...
        'metric',specs{metricIndex,4}, ...
        'pngFile',pngFile,'figFile',figFile);
    clear closeFigure
end
figureManifest = struct2table(recordsOut);
end

function localPlotDopplerContext(shiftAxes,rateAxes,config,schedule)
denseTime = linspace(schedule.passStartTimeSec, ...
    schedule.passEndTimeSec,1600).';
trajectory = satelliteFig3Trajectory(denseTime,config);
hold(shiftAxes,'on');
plot(shiftAxes,denseTime,trajectory.dopplerShiftHz/1e3, ...
    'Color',[0 0.45 0.74],'LineWidth',1.4, ...
    'DisplayName','Doppler shift');
ylabel(shiftAxes,'Shift (kHz)');
ylim(shiftAxes,[-20 20]);
xlim(shiftAxes,[schedule.passStartTimeSec schedule.passEndTimeSec]);
grid(shiftAxes,'on');
title(shiftAxes,'Project Doppler-shift trajectory', ...
    'FontWeight','normal');
localBlindLines(shiftAxes,schedule.window);

hold(rateAxes,'on');
plot(rateAxes,denseTime,trajectory.dopplerRateHzPerSec, ...
    'Color',[0.85 0.33 0.10],'LineWidth',1.4, ...
    'DisplayName','Doppler rate');
ylabel(rateAxes,'Rate (Hz/s)');
ylim(rateAxes,[-250 0]);
xlim(rateAxes,[schedule.passStartTimeSec schedule.passEndTimeSec]);
grid(rateAxes,'on');
title(rateAxes,'Project Doppler-rate trajectory', ...
    'FontWeight','normal');
localBlindLines(rateAxes,schedule.window);
end

function rows = localWindowRows(tableIn,snrDb,region,method)
rows = tableIn(tableIn.snrDb == snrDb & ...
    strcmp(tableIn.region,region) & ...
    strcmp(tableIn.method,method),:);
rows = sortrows(rows,'windowIndex');
end

function label = localRegionLabel(region,records,selected,config)
trajectory = satelliteFig3Trajectory( ...
    records.frameCenterTimeSec(selected),config);
if strcmp(region,'high_doppler_rate')
    label = sprintf('high rate |f''_D| %.1f--%.1f Hz/s', ...
        min(abs(trajectory.dopplerRateHzPerSec)), ...
        max(abs(trajectory.dopplerRateHzPerSec)));
else
    label = sprintf('high shift |f_D| %.1f--%.1f kHz', ...
        min(abs(trajectory.dopplerShiftHz))/1e3, ...
        max(abs(trajectory.dopplerShiftHz))/1e3);
end
end

function intervals = localRegionIntervals(frameIndices,schedule)
mask = false(schedule.frameCount,1);
mask(frameIndices) = true;
starts = find(mask & [true;~mask(1:end-1)]);
ends = find(mask & [~mask(2:end);true]);
intervals = [schedule.frameStartTimeSec(starts), ...
    schedule.frameEndTimeSec(ends)];
end

function localBand(ax,x,lower,upper,color)
valid = isfinite(x) & isfinite(lower) & ...
    isfinite(upper) & upper >= lower;
starts = find(valid & [true;~valid(1:end-1)]);
ends = find(valid & [~valid(2:end);true]);
for segment = 1:numel(starts)
    index = starts(segment):ends(segment);
    patch(ax,[x(index);flipud(x(index))], ...
        [lower(index);flipud(upper(index))],color, ...
        'FaceAlpha',0.07,'EdgeColor','none', ...
        'HandleVisibility','off');
end
end

function localShadeBlind(ax,window)
limits = ylim(ax);
blind = window.blindIntervalSec;
patch(ax,[blind(1) blind(2) blind(2) blind(1)], ...
    [limits(1) limits(1) limits(2) limits(2)], ...
    [0.88 0.88 0.88],'FaceAlpha',0.25, ...
    'EdgeColor','none','HandleVisibility','off');
localBlindLines(ax,window);
ylim(ax,limits);
end

function localBlindLines(ax,window)
xline(ax,window.blindIntervalSec(1), ...
    'Color',[0.45 0.45 0.45],'LineStyle',':', ...
    'HandleVisibility','off');
xline(ax,window.blindIntervalSec(2), ...
    'Color',[0.45 0.45 0.45],'LineStyle',':', ...
    'HandleVisibility','off');
end

function localTargetLines(ax,intervals)
for index = 1:size(intervals,1)
    xline(ax,intervals(index,1), ...
        'Color',[0.20 0.55 0.20],'LineStyle','--', ...
        'LineWidth',0.7,'HandleVisibility','off');
    xline(ax,intervals(index,2), ...
        'Color',[0.20 0.55 0.20],'LineStyle','--', ...
        'LineWidth',0.7,'HandleVisibility','off');
end
end
