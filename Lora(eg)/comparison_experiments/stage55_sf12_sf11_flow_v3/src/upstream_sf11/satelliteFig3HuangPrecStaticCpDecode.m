function result = satelliteFig3HuangPrecStaticCpDecode( ...
        rxSymbols,config,knownWaveformBins)
%SATELLITEFIG3HUANGPRECSTATICCPDECODE Static Huang-PREC CP baseline.
%   The receiver uses the continuous-phase adaptation of Huang's eight-
%   upchirp eta/FFT estimator once and freezes that CFO for the payload.
%   It has no payload feedback, Doppler-rate estimate, orbit prior, or
%   channel-truth input.

nSymbols = size(rxSymbols,1);
bootstrapCount = numel(knownWaveformBins);
if bootstrapCount ~= config.bootstrapPilotCount || ...
        bootstrapCount >= nSymbols
    error('SatelliteFig3:HuangPrecStaticBootstrap', ...
        'Static Huang PREC requires the configured eight upchirps.');
end

bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
    rxSymbols(1:bootstrapCount,:),knownWaveformBins,config);
requestedMask = false(nSymbols,1);
requestedMask(1:bootstrapCount) = true;
tracker = satelliteFig3RollingPilotTracker( ...
    rxSymbols,config,knownWaveformBins, ...
    AcceptedMask=requestedMask, ...
    BootstrapOverride=bootstrap, ...
    FreezeBootstrapRate=true, ...
    ReleaseBootstrapRateAfterVirtualPilotCount=nSymbols+1, ...
    RateDeviationLimitBinsPerSec=0, ...
    BootstrapRateOverrideBinsPerSec=0);

payloadRows = bootstrapCount+1:nSymbols;
decodedDataBits = satelliteFig3HardPayloadBits( ...
    tracker.hardWaveformBins(payloadRows),config);
result = struct( ...
    'detectedWaveformBins',tracker.hardWaveformBins, ...
    'decodedDataBits',decodedDataBits, ...
    'tracker',tracker, ...
    'bootstrap',bootstrap, ...
    'fixedPayloadCfoBins',tracker.predictedCfoBins(payloadRows(1)), ...
    'initialRateBinsPerSec',0, ...
    'usesPayloadFeedback',false, ...
    'usesDopplerRate',false, ...
    'usesOrbitPrior',false, ...
    'continuousPhaseAdapted',true, ...
    'algorithmProvenance', ...
        'Huang PREC/PRC eta estimator; CP power combining; frozen CFO');
end
