function metrics = v3EvaluateFrame(receiver,truth,config)
%V3EVALUATEFRAME Outer truth-only evaluator for one paired frame.

symbolErrors = sum(receiver.detectedPhysicalBins ~= truth.payloadPhysicalBins);
hardBitErrors = sum(receiver.hardDecodedDataBits(:) ~= truth.dataBits(:));
softBitErrors = sum(receiver.softDecodedDataBits(:) ~= truth.dataBits(:));
cfoError = receiver.estimatedCfoBins-truth.dataCfoBins;
metrics = struct('methodName',receiver.methodName, ...
    'symbolErrors',symbolErrors,'symbolCount',config.payloadSymbolCount, ...
    'ser',symbolErrors/config.payloadSymbolCount, ...
    'hardBitErrors',hardBitErrors,'hardBitCount',config.informationBitCount, ...
    'hardBer',hardBitErrors/config.informationBitCount, ...
    'softBitErrors',softBitErrors,'softBitCount',config.informationBitCount, ...
    'softBer',softBitErrors/config.informationBitCount, ...
    'packetError',double(softBitErrors > 0),'per',double(softBitErrors > 0), ...
    'cfoSquaredErrorSum',sum(cfoError.^2), ...
    'cfoRmseBins',sqrt(mean(cfoError.^2)), ...
    'fftCount',receiver.fftCount);
end

