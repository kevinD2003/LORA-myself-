function audit = auditV4BCaseAnchorV4(variant)
if nargin < 1,variant = 'v4';end
switch lower(variant)
    case 'v4'
        fileStem = 'B_CASE_ANCHOR_AWGN_V4';
        dataIdentity = 'B-case-anchor-AWGN-v4-paper-native-extended';
        auditIdentity = 'B-case-anchor-AWGN-v4-audit';
        previousStem = 'B_CASE_ANCHOR_AWGN_V3';
        previousExpectedStatus = 'PASS';
        knownProfileExpected = false;
    case 'v5'
        fileStem = 'B_CASE_ANCHOR_AWGN_V5';
        dataIdentity = 'B-case-anchor-AWGN-v5-robust-regime-paper-native';
        auditIdentity = 'B-case-anchor-AWGN-v5-audit';
        previousStem = 'B_CASE_ANCHOR_AWGN_V4';
        previousExpectedStatus = 'FAIL';
        knownProfileExpected = false;
    case 'v6'
        fileStem = 'B_CASE_ANCHOR_AWGN_V6';
        dataIdentity = 'B-case-anchor-AWGN-v6-known-case-profile';
        auditIdentity = 'B-case-anchor-AWGN-v6-audit';
        previousStem = 'B_CASE_ANCHOR_AWGN_V5';
        previousExpectedStatus = 'FAIL';
        knownProfileExpected = true;
    otherwise
        error('V4:BCaseAnchorAuditVariant','Unknown audit variant %s.',variant);
end
root = v4SetupPaths();
loaded = load(fullfile(root,'results','reports', ...
    [fileStem '_REPORT.mat']),'report');
report = loaded.report;cellRaw = zeros(2,16,3,4);
cellDen = zeros(2,16,3,4);sourceHashes = strings(2,16);
cellChecks = true(2,16);profileChecks = true(2,16);
for caseIndex = 1:2
    for snrIndex = 1:16
        snrDb = -31+snrIndex;
        path = fullfile(root,'results','case_anchor_b', ...
            dataIdentity, ...
            sprintf('case_%d',caseIndex),sprintf('snr_%+03d',snrDb), ...
            'formal_cell.mat');
        x = load(path,'cellResult');r = x.cellResult;
        recomputed = squeeze(sum(double(r.packetErrors),1));
        cellChecks(caseIndex,snrIndex) = strcmp(r.status,'PASS') && ...
            r.fixedPackets == 200 && r.completedPackets == 200 && ...
            isequal(recomputed,r.rawErrors) && ~r.usesCrossPacketHistory && ...
            ~r.usesPayloadTruthForSelection && ~r.usesOrbitTruthForSelection && ...
            strcmp(r.paperAlgorithmVersion, ...
                'Paper-Midamble-Point-integer-full-FFT-v2');
        cellRaw(caseIndex,snrIndex,:,:) = reshape(r.rawErrors,1,1,3,4);
        cellDen(caseIndex,snrIndex,:,:) = reshape(r.denominators,1,1,3,4);
        sourceHashes(caseIndex,snrIndex) = r.sourceHash;
        if knownProfileExpected
            expectedProfile = {'case1-static','case2-dynamic'};
            profileChecks(caseIndex,snrIndex) = r.usesKnownCaseProfile && ...
                r.simulationReused && strcmp(r.caseProfile, ...
                expectedProfile{caseIndex});
            if caseIndex == 1
                profileChecks(caseIndex,snrIndex) = ...
                    profileChecks(caseIndex,snrIndex) && ...
                    isequal(r.packetErrors(:,2,:),r.packetErrors(:,1,:));
            else
                parentPath = fullfile(root,'results','case_anchor_b', ...
                    'B-case-anchor-AWGN-v5-robust-regime-paper-native', ...
                    sprintf('case_%d',caseIndex), ...
                    sprintf('snr_%+03d',snrDb),'formal_cell.mat');
                parentLoaded = load(parentPath,'cellResult');
                profileChecks(caseIndex,snrIndex) = ...
                    profileChecks(caseIndex,snrIndex) && ...
                    isequal(r.packetErrors(:,2,:), ...
                    parentLoaded.cellResult.packetErrors(:,2,:)) && ...
                    strcmp(r.derivedFromSignature, ...
                    parentLoaded.cellResult.signature);
            end
        end
    end
end
baseline = struct( ...
    'originalPaper',v4Sha256(fullfile(root,'src','paper', ...
        'v4PaperMidambleDecode.m')), ...
    'huang',v4Sha256(fullfile(root,'src','stage55', ...
        'v4HuangStaticDecode.m')));
baselinePass = strcmp(baseline.originalPaper, ...
    'f2b8fee79b6920118710cb3e380f461d3e821f8c532034bb4b328594600e690f') && ...
    strcmp(baseline.huang, ...
    '27dc3630f976428efbd999126b01d7a88129f98a42c6c53946543a7fc878cef2');
paperSource = fileread(fullfile(root,'src','paper', ...
    'v4PaperMidamblePointDecodeV2.m'));
paperIsolationPass = ~contains(paperSource,'caseIndex') && ...
    ~contains(paperSource,'frame.truth') && ...
    ~contains(paperSource,'v4PhaseRotationEstimate') && ...
    contains(paperSource,'v4PaperIntegerPointEstimate');
recomputedGate = v4BCaseAnchorExtendedAdmissionV4(cellRaw,cellDen);
reportRecomputePass = isequal(cellRaw,report.rawErrors) && ...
    recomputedGate.overallPass;
previousReport = jsondecode(fileread(fullfile(root,'results','reports', ...
    [previousStem '_REPORT.json'])));
previousEvidencePreserved = strcmp(previousReport.status,previousExpectedStatus);
artifactPaths = { ...
    fullfile(root,'results','reports',[fileStem '_REPORT.json']), ...
    fullfile(root,'results','reports',[fileStem '_SUMMARY.csv']), ...
    fullfile(root,'results','reports',[fileStem '_ORDERING.csv']), ...
    fullfile(root,'results','reports',[fileStem '_SER.png']), ...
    fullfile(root,'results','reports',[fileStem '_BER.png'])};
artifactHashes = struct();
for k = 1:numel(artifactPaths)
    [~,name,extension] = fileparts(artifactPaths{k});
    artifactHashes.(matlab.lang.makeValidName([name extension])) = ...
        v4Sha256(artifactPaths{k});
end
checks = struct( ...
    'all32CellsRecomputed',all(cellChecks,'all'), ...
    'singleSourceHash',numel(unique(sourceHashes)) == 1, ...
    'reportRawCountsRecomputed',reportRecomputePass, ...
    'case1AdmissionPass',report.admissionGate.case1Pass, ...
    'case2AdmissionPass',report.admissionGate.case2Pass, ...
    'paperCurvePass',report.admissionGate.paperCurvePass, ...
    'case2BerTargetPass',report.admissionGate.targetBerPass, ...
    'regimeIdentityPass',report.regimePass, ...
    'originalBaselinesUnchanged',baselinePass, ...
    'paperIntegerEstimatorIsolationPass',paperIsolationPass, ...
    'knownCaseProfileAuthorizationPass', ...
        ~knownProfileExpected || ...
        (report.usesKnownCaseProfile && all(profileChecks,'all')), ...
    'previousV3EvidencePreserved',previousEvidencePreserved);
if all(structfun(@(x)logical(x),checks)) && strcmp(report.status,'PASS')
    status = 'PASS';
else
    status = 'FAIL';
end
paperPdf = 'D:\codex\参考论文\Doppler_Estimation_and_Compensation_Techniques_in_LoRa_Direct-to-Satellite_Communications.pdf';
audit = struct('status',status,'identity',auditIdentity, ...
    'algorithmVersion',report.algorithmVersion, ...
    'paperAlgorithmVersion',report.paperAlgorithmVersion, ...
    'usesKnownCaseProfile',knownProfileExpected, ...
    'fixedCells',32,'fixedPacketsPerCell',200,'totalPairedPackets',6400, ...
    'snrDb',-30:-15,'bootstrapDrawsPerPoint',10000,'checks',checks, ...
    'sourceHash',char(sourceHashes(1,1)),'baselineHashes',baseline, ...
    'paperReferenceSha256',v4Sha256(paperPdf), ...
    'artifactHashes',artifactHashes, ...
    'zeroErrorFloorRule',report.admissionGate.zeroErrorFloorRule);
jsonPath = fullfile(root,'results','reports', ...
    [fileStem '_AUDIT.json']);
mdPath = fullfile(root,'results','reports',[fileStem '_AUDIT.md']);
localWrite(jsonPath,jsonencode(audit,'PrettyPrint',true));
localWriteMarkdown(mdPath,audit);end

function localWrite(path,text)
file = fopen(path,'w','n','UTF-8');cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',text);clear cleaner
end
function localWriteMarkdown(path,audit)
file = fopen(path,'w','n','UTF-8');cleaner = onCleanup(@()fclose(file));
fprintf(file,'# %s\n\nStatus: **%s**\n\n',audit.identity,audit.status);
fprintf(file,'- Stage algorithm: `%s`\n',audit.algorithmVersion);
fprintf(file,'- Paper algorithm: `%s`\n',audit.paperAlgorithmVersion);
fprintf(file,'- Unchanged conditions: SF12, BW/Fs 125 kHz, no-LDRO, CR3, 112 data symbols, 768 information bits, AWGN, Case -366/0 s, 200 paired packets/cell.\n');
fprintf(file,'- Requested SNR extension: -30:-15 dB.\n');
fprintf(file,'- Total: %d cells, %d paired packets, %d bootstrap draws/point.\n', ...
    audit.fixedCells,audit.totalPairedPackets,audit.bootstrapDrawsPerPoint);
names = fieldnames(audit.checks);
for k = 1:numel(names)
    if audit.checks.(names{k}),value='PASS';else,value='FAIL';end
    fprintf(file,'- %s: %s\n',names{k},value);
end
fprintf(file,'- Zero floor: %s\n',audit.zeroErrorFloorRule);clear cleaner
end
