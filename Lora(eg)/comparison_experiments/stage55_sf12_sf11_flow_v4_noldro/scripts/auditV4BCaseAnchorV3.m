function audit = auditV4BCaseAnchorV3()
root = v4SetupPaths();
reportPath = fullfile(root,'results','reports', ...
    'B_CASE_ANCHOR_AWGN_V3_REPORT.mat');
loaded = load(reportPath,'report');report = loaded.report;
cellRaw = zeros(2,10,3,4);sourceHashes = strings(2,10);
cellChecks = true(2,10);
for caseIndex = 1:2
    for snrIndex = 1:10
        snrDb = -31+snrIndex;
        path = fullfile(root,'results','case_anchor_b', ...
            'B-case-anchor-AWGN-v3-CFO-regime', ...
            sprintf('case_%d',caseIndex),sprintf('snr_%+03d',snrDb), ...
            'formal_cell.mat');
        x = load(path,'cellResult');r = x.cellResult;
        recomputed = squeeze(sum(double(r.packetErrors),1));
        cellChecks(caseIndex,snrIndex) = ...
            strcmp(r.status,'PASS') && r.fixedPackets == 200 && ...
            r.completedPackets == 200 && isequal(recomputed,r.rawErrors) && ...
            ~r.usesCrossPacketHistory && ~r.usesPayloadTruthForSelection && ...
            ~r.usesOrbitTruthForSelection;
        cellRaw(caseIndex,snrIndex,:,:) = reshape(r.rawErrors,1,1,3,4);
        sourceHashes(caseIndex,snrIndex) = r.sourceHash;
    end
end
baseline = struct( ...
    'paper',v4Sha256(fullfile(root,'src','paper','v4PaperMidambleDecode.m')), ...
    'huang',v4Sha256(fullfile(root,'src','stage55','v4HuangStaticDecode.m')));
baselinePass = strcmp(baseline.paper, ...
    'f2b8fee79b6920118710cb3e380f461d3e821f8c532034bb4b328594600e690f') && ...
    strcmp(baseline.huang, ...
    '27dc3630f976428efbd999126b01d7a88129f98a42c6c53946543a7fc878cef2');
source = fileread(fullfile(root,'src','stage55','v4Stage55CaseAnchorDecodeV6.m'));
sourceIsolationPass = ~contains(source,'caseIndex') && ...
    ~contains(source,'frame.truth') && ~contains(source,'observation.truth');
reportRecomputePass = isequal(cellRaw,report.rawErrors) && ...
    v4BCaseAnchorAdmissionV2(cellRaw).overallPass;
v5FailurePath = fullfile(root,'results','reports', ...
    'B_CASE_ANCHOR_AWGN_V2_REPORT.json');
v5 = jsondecode(fileread(v5FailurePath));
v5FailurePreserved = strcmp(v5.status,'FAIL');
artifactPaths = { ...
    fullfile(root,'results','reports','B_CASE_ANCHOR_AWGN_V3_REPORT.json'), ...
    fullfile(root,'results','reports','B_CASE_ANCHOR_AWGN_V3_SUMMARY.csv'), ...
    fullfile(root,'results','reports','B_CASE_ANCHOR_AWGN_V3_ORDERING.csv'), ...
    fullfile(root,'results','reports','B_CASE_ANCHOR_AWGN_V3_SER.png'), ...
    fullfile(root,'results','reports','B_CASE_ANCHOR_AWGN_V3_BER.png')};
artifactHashes = struct();
for k = 1:numel(artifactPaths)
    [~,name,extension] = fileparts(artifactPaths{k});
    artifactHashes.(matlab.lang.makeValidName([name extension])) = ...
        v4Sha256(artifactPaths{k});
end
checks = struct( ...
    'all20CellsRecomputed',all(cellChecks,'all'), ...
    'singleSourceHash',numel(unique(sourceHashes)) == 1, ...
    'reportRawCountsRecomputed',reportRecomputePass, ...
    'case1AdmissionPass',report.admissionGate.case1Pass, ...
    'case2AdmissionPass',report.admissionGate.case2Pass, ...
    'regimeIdentityPass',report.regimePass, ...
    'frozenBaselinesPass',baselinePass, ...
    'noCaseOrTruthSwitchPass',sourceIsolationPass, ...
    'v5FailureEvidencePreserved',v5FailurePreserved);
if all(structfun(@(x)logical(x),checks)) && strcmp(report.status,'PASS')
    status = 'PASS';
else
    status = 'FAIL';
end
audit = struct('status',status, ...
    'identity','B-case-anchor-AWGN-v3-audit', ...
    'algorithmVersion',report.algorithmVersion, ...
    'fixedCells',20,'fixedPacketsPerCell',200,'totalPairedPackets',4000, ...
    'bootstrapDrawsPerPoint',10000,'checks',checks, ...
    'sourceHash',char(sourceHashes(1,1)),'baselineHashes',baseline, ...
    'artifactHashes',artifactHashes, ...
    'zeroErrorFloorRule',report.admissionGate.zeroErrorFloorRule);
jsonPath = fullfile(root,'results','reports', ...
    'B_CASE_ANCHOR_AWGN_V3_AUDIT.json');
mdPath = fullfile(root,'results','reports', ...
    'B_CASE_ANCHOR_AWGN_V3_AUDIT.md');
localWrite(jsonPath,jsonencode(audit,'PrettyPrint',true));
localWriteMarkdown(mdPath,audit);
end

function localWrite(path,text)
file = fopen(path,'w','n','UTF-8');cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',text);clear cleaner
end

function localWriteMarkdown(path,audit)
file = fopen(path,'w','n','UTF-8');cleaner = onCleanup(@()fclose(file));
fprintf(file,'# B Case-anchor AWGN V3 audit\n\n');
fprintf(file,'Status: **%s**\n\n',audit.status);
fprintf(file,'- Algorithm: `%s`\n',audit.algorithmVersion);
fprintf(file,'- Sample: %d cells, %d paired packets/cell, %d total.\n', ...
    audit.fixedCells,audit.fixedPacketsPerCell,audit.totalPairedPackets);
fprintf(file,'- Paired bootstrap: %d draws/point.\n',audit.bootstrapDrawsPerPoint);
names = fieldnames(audit.checks);
for k = 1:numel(names)
    fprintf(file,'- %s: %s\n',names{k},localStatus(audit.checks.(names{k})));
end
fprintf(file,'- Zero floor: %s\n',audit.zeroErrorFloorRule);
clear cleaner
end

function value = localStatus(pass)
if pass,value = 'PASS';else,value = 'FAIL';end
end
