function audit=auditV4Stage3RMechanism()
root=v4SetupPaths();results=runV4Stage3RMechanismTests();source=v4VerifyReadOnlySources(root);
old=jsondecode(fileread(fullfile(root,'config','r3_failure_evidence_manifest.json')));
oldOk=true;for i=1:numel(old.files),oldOk=oldOk&&strcmp(v4Sha256(fullfile(root,old.files(i).path)),old.files(i).sha256);end
passed=all([results.Passed])&&source.passed&&oldOk;
audit=struct('stage','STAGE_03R_02_MECHANISM_AUDIT','overall',status(passed), ...
    'planSha256',v4Sha256(fullfile(root,'SF12无LDRO双轨完整实验V4方案.md')), ...
    'items',struct('newMechanismTests',status(all([results.Passed])), ...
    'sourceBoundary',status(source.passed),'r3FailureEvidence',status(oldOk), ...
    'calibration','NOT_APPLICABLE','validation','NOT_APPLICABLE','smoke','NOT_APPLICABLE'), ...
    'testNames',{string({results.Name})},'testPassed',[results.Passed], ...
    'knownLimitation','Locally self-consistent wrong branches remain possible and must be counted by validation.', ...
    'admission',ternary(passed,'ADMIT_STAGE_03R_CALIBRATION','DO_NOT_ADMIT_STAGE_03R_CALIBRATION'));
folder=fullfile(root,'results','stage3r','audits');
localWrite(fullfile(folder,'STAGE_03R_02_MECHANISM_AUDIT.json'),jsonencode(audit,'PrettyPrint',true));
localWrite(fullfile(folder,'STAGE_03R_02_MECHANISM_AUDIT.md'),sprintf('# Stage 3R-02 mechanism audit\n\nOverall: `%s`.\n\nSixteen new/inherited mechanism tests were executed. Test PASS does not imply validation PASS.\n',audit.overall));
if ~passed,error('V4:Stage3RMechanismAudit','Mechanism audit failed.');end
end
function value=status(ok),if ok,value='PASS';else,value='FAIL';end,end
function value=ternary(ok,a,b),if ok,value=a;else,value=b;end,end
function localWrite(path,text),f=fopen(path,'w','n','UTF-8');c=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear c,end
