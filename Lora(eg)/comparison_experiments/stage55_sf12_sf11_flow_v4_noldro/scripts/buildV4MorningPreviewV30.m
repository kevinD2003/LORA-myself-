function preview=buildV4MorningPreviewV30()
root=v4SetupPaths();snrs=(-30:-21).';groups={'B_AWGN_CONTROLLED','B_AWGN_NATIVE','B_RICIAN_CONTROLLED','B_RICIAN_NATIVE'};
groupRecords=cell(4,1);
for gi=1:4
 rows=repmat(struct('snrDb',0,'passes',2,'methodMetrics',[],'stageMinusPaper',[], ...
  'stageBetterSer',false,'stageBetterHardBer',false,'stageBetterMlBer',false, ...
  'meanGoodputBps',[],'systemPerMl',[]),10,1);
 for si=1:10
  passMetric=zeros(2,3,4);goodput=zeros(3,2);systemPer=zeros(3,2);
  for pi=1:2
   path=fullfile(root,'results','formal','track_b',groups{gi},sprintf('snr_%+03d',snrs(si)), ...
    'passes',sprintf('pass_%02d.mat',pi));
   if ~isfile(path),error('V4:PreviewIncomplete','Missing %s SNR %g pass %d.',groups{gi},snrs(si),pi);end
   x=load(path,'result');r=x.result;
   if ndims(r.metrics)==2,m=r.metrics;else,m=squeeze(r.metrics(:,:,3));end
   passMetric(pi,:,:)=reshape(m,1,3,4);goodput(:,pi)=r.goodputBps;systemPer(:,pi)=r.systemPerMl;
  end
  meanMetric=squeeze(mean(passMetric,1));delta=meanMetric(2,1:3)-meanMetric(3,1:3);
  rows(si)=struct('snrDb',snrs(si),'passes',2,'methodMetrics',meanMetric, ...
   'stageMinusPaper',delta,'stageBetterSer',delta(1)<0, ...
   'stageBetterHardBer',delta(2)<0,'stageBetterMlBer',delta(3)<0, ...
   'meanGoodputBps',mean(goodput,2),'systemPerMl',mean(systemPer,2));
 end
 groupRecords{gi}=struct('groupName',groups{gi},'points',rows, ...
  'stageBetterPointCounts',[sum([rows.stageBetterSer]) sum([rows.stageBetterHardBer]) sum([rows.stageBetterMlBer])]);
end
preview=struct('status','PROVISIONAL_PREVIEW_NOT_FORMAL_COMPLETE', ...
 'planVersion','V4-noLDRO-plan-R3-project-aligned', ...
 'algorithmVersion','Stage55-B-startup-observability-v30', ...
 'passesPerGroupSnr',2,'formalRequirementPerGroupSnr',50, ...
 'groups',[groupRecords{:}].','fixedConditionsChanged',false, ...
 'samplesReusableByFormal',true,'confidenceIntervalsValid',false, ...
 'warning','Two complete passes per SNR are insufficient for formal paired-cluster confidence claims.');
folder=fullfile(root,'results','reports');save(fullfile(folder,'V30_MORNING_PREVIEW.mat'),'preview','-v7.3');
write(fullfile(folder,'V30_MORNING_PREVIEW.json'),jsonencode(preview,'PrettyPrint',true));
text=sprintf(['# V30 morning preview\n\nStatus: `PROVISIONAL_PREVIEW_NOT_FORMAL_COMPLETE`.\n\n' ...
 'This preview uses the first 2 registered formal passes for every group/SNR. No physical, algorithm, ' ...
 'seed or denominator condition was changed. The required budget remains 50 passes/group/SNR. ' ...
 'Two passes are insufficient for formal confidence intervals.\n\n']);
for gi=1:4
 g=preview.groups(gi);text=[text sprintf('## %s\n\nStage55-better point counts for SER/hard BER/ML BER: %d/10, %d/10, %d/10.\n\n', ...
  g.groupName,g.stageBetterPointCounts(1),g.stageBetterPointCounts(2),g.stageBetterPointCounts(3))]; %#ok<AGROW>
end
write(fullfile(folder,'V30_MORNING_PREVIEW.md'),text);
end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
