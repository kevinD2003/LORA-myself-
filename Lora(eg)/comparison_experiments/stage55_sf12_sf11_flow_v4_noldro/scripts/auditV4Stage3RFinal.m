function audit=auditV4Stage3RFinal()
root=v4SetupPaths();base=fullfile(root,'results','stage3r','Stage55-A-causal-pending-lock-v1');
p1=fullfile(base,'A-3R-param-v01','calibration','stage3r_calibration.json');
p2=fullfile(base,'A-3R-param-v02','calibration','stage3r_calibration.json');
a1=jsondecode(fileread(p1));a2=jsondecode(fileread(p2));source=v4VerifyReadOnlySources(root);
old=jsondecode(fileread(fullfile(root,'config','r3_failure_evidence_manifest.json')));
oldOk=true;for i=1:numel(old.files),oldOk=oldOk&&strcmp(v4Sha256(fullfile(root,old.files(i).path)),old.files(i).sha256);end
roundsExhausted=strcmp(a1.status,'FAIL')&&strcmp(a2.status,'FAIL');
audit=struct('stage','STAGE_03R_EXPERIMENT_A_REDESIGN_AUDIT','overall','FAIL', ...
    'planVersion','V4-noLDRO-plan-R4-track-a-stage3r', ...
    'planSha256',v4Sha256(fullfile(root,'SF12无LDRO双轨完整实验V4方案.md')), ...
    'algorithmVersion','Stage55-A-causal-pending-lock-v1', ...
    'items',struct('r4Freeze','PASS','mechanismAndCausalityTests','PASS', ...
        'calibrationV1',a1.status,'calibrationV2',a2.status, ...
        'validation','BLOCKED','lowSnrSafety','NOT_APPLICABLE', ...
        'smoke','BLOCKED','formal','NOT_APPLICABLE', ...
        'sourceBoundary',status(source.passed),'r3FailureEvidence',status(oldOk)), ...
    'round1',struct('artifactHash',v4Sha256(p1),'algorithmSignature',a1.algorithmSignature, ...
        'candidateTableHash',a1.candidateTableHash,'physicalPackets',1000, ...
        'candidatePacketEvaluations',32000,'selectedCandidateIndex',a1.selectedCandidateIndex, ...
        'case0FalseAcceptanceRange',[0.925594671741199 0.961728395061728]), ...
    'round2',struct('artifactHash',v4Sha256(p2),'algorithmSignature',a2.algorithmSignature, ...
        'candidateTableHash',a2.candidateTableHash,'physicalPackets',1000, ...
        'candidatePacketEvaluations',32000,'selectedCandidateIndex',a2.selectedCandidateIndex, ...
        'case0FalseAcceptanceRange',[0.930658356057655 0.989619377162630]), ...
    'budget',struct('maximumRounds',2,'roundsExecuted',2,'candidatesPerRound',32, ...
        'packetsPerCandidateCase',500,'roundsExhausted',roundsExhausted), ...
    'issuesAndFixes',{{ ...
        'An ambiguity unit-test vector initially represented one unique valid pair; the fixture was corrected to a genuinely inconsistent-rate construction. No algorithm or experiment result was affected.', ...
        'Canonical JSON initially rejected struct arrays; it was fixed before calibration began. No calibration result was affected.', ...
        'The final-audit writer had a missing parenthesis on its first invocation; the syntax was corrected and the audit was regenerated from unchanged signed artifacts.'}}, ...
    'unresolvedIssues',{{ ...
        'The causal two-measurement mechanism still locks to locally self-consistent wrong branches in Case 0.', ...
        'No candidate met both Case gates within the two-round budget.'}}, ...
    'admission','DO_NOT_ADMIT_STAGE_4','experimentBAdmission','BLOCKED_REQUIRE_A_PASS', ...
    'conclusion','Stop after Stage 3R; do not run validation, safety, smoke, formal, or Experiment B.');
folder=fullfile(root,'results','stage3r','audits');jsonPath=fullfile(folder,'STAGE_03R_EXPERIMENT_A_REDESIGN_AUDIT.json');
localWrite(jsonPath,jsonencode(audit,'PrettyPrint',true));
md=sprintf(['# Stage 3R Experiment A redesign audit\n\nOverall: `FAIL`. Admission: `DO_NOT_ADMIT_STAGE_4`.\n\n' ...
    '## Evidence\n\n- R4 freeze: PASS.\n- New/inherited mechanism and causality tests: 16/16 PASS.\n' ...
    '- Calibration v1: FAIL; 32 candidates, 500 packets per Case, artifact `%s`.\n' ...
    '- Calibration v2: FAIL; 32 candidates, 500 packets per Case, artifact `%s`.\n' ...
    '- Source/read-only boundary: %s. R3 failure evidence: %s.\n\n' ...
    'Across the two rounds, 2000 physical packets and 64000 candidate-packet receiver evaluations were completed. No candidate passed both Cases. ' ...
    'Case 0 false-acceptance ranged from 92.56%% to 96.17%% in v1 and 93.07%% to 98.96%% in v2.\n\n' ...
    '## Gate decision\n\nValidation: `BLOCKED`; low-SNR safety: `NOT_APPLICABLE`; smoke: `BLOCKED`; formal: `NOT_APPLICABLE`; Experiment B: `BLOCKED_REQUIRE_A_PASS`.\n\n' ...
    'The adverse result is retained. No threshold, denominator, candidate table, sample count, or round budget was relaxed.\n'], ...
    audit.round1.artifactHash,audit.round2.artifactHash,audit.items.sourceBoundary,audit.items.r3FailureEvidence);
localWrite(fullfile(folder,'STAGE_03R_EXPERIMENT_A_REDESIGN_AUDIT.md'),md);
end
function value=status(ok),if ok,value='PASS';else,value='FAIL';end,end
