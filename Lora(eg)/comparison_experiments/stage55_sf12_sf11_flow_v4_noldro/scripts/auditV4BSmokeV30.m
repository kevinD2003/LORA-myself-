function [audit,cost]=auditV4BSmokeV30()
root=v4SetupPaths();groups={ ...
 'controlled_awgn','controlled_rician','native_awgn','native_rician'};
records=repmat(struct('group','','status','','runSignature','','wallTimeSec',0, ...
 'matlabMemoryBytes',0,'artifactBytes',0,'allFinite',false,'deadlineMiss',[], ...
 'matSha256','','jsonSha256',''),4,1);
before=cell(4,2);
for i=1:4
 folder=fullfile(root,'results','smoke','track_b',groups{i});mp=fullfile(folder,'pass_01.mat');jp=fullfile(folder,'pass_01.json');
 x=load(mp,'result');r=x.result;d1=dir(mp);d2=dir(jp);before(i,:)={v4Sha256(mp),v4Sha256(jp)};
 records(i)=struct('group',groups{i},'status',r.status,'runSignature',r.runSignature, ...
  'wallTimeSec',r.wallTimeSec,'matlabMemoryBytes',r.matlabMemoryBytes, ...
  'artifactBytes',d1.bytes+d2.bytes,'allFinite',r.allFinite,'deadlineMiss',r.deadlineMiss, ...
  'matSha256',before{i,1},'jsonSha256',before{i,2});
end
resume={runV4BControlledSmokeV30('AWGN'),runV4BControlledSmokeV30('Rician'), ...
 runV4BNativeSmokeV30('AWGN'),runV4BNativeSmokeV30('Rician')};
resumeOk=true;hashStable=true;
for i=1:4
 resumeOk=resumeOk&&resume{i}.resumedWithoutRecount;
 folder=fullfile(root,'results','smoke','track_b',groups{i});
 hashStable=hashStable&&strcmp(before{i,1},v4Sha256(fullfile(folder,'pass_01.mat')))&& ...
  strcmp(before{i,2},v4Sha256(fullfile(folder,'pass_01.json')));
end
signatures={records.runSignature};uniqueOk=numel(unique(signatures))==4;
[~,sys]=memory;totalRam=sys.PhysicalMemory.Total;availableRam=sys.PhysicalMemory.Available;
peak=max([records.matlabMemoryBytes]);coreCount=feature('numcores');formulaWorkerCount=max(1,min([4 coreCount floor(0.70*totalRam/peak)]));
freeWorkerCount=max(1,floor(0.85*availableRam/peak));workerCount=min(formulaWorkerCount,freeWorkerCount);
drive=java.io.File(root(1:3));freeDisk=drive.getFreeSpace();
for i=1:4
 records(i).estimatedFormalArtifactBytes=500*records(i).artifactBytes;
 records(i).conservativeFormalWallSec=1.25*500*records(i).wallTimeSec/workerCount;
end
estimatedStorage=sum([records.estimatedFormalArtifactBytes]);diskOk=double(freeDisk)>=1.5*estimatedStorage;
memoryOk=workerCount*peak<=0.70*totalRam;
cost=struct('status',ternary(diskOk&&memoryOk,'PASS','BLOCKED'), ...
 'algorithmVersion','Stage55-B-startup-observability-v30','formalPassesPerGroup',500, ...
 'groupCount',4,'workerCount',workerCount,'formulaWorkerCount',formulaWorkerCount, ...
 'freeMemoryWorkerCount',freeWorkerCount,'physicalCoreCount',coreCount, ...
 'totalPhysicalRamBytes',totalRam,'availableRamBytes',availableRam, ...
 'singleWorkerPeakBytes',peak,'workerPeakLimitBytes',0.70*totalRam, ...
 'freeDiskBytes',double(freeDisk),'estimatedArtifactBytes',estimatedStorage, ...
 'requiredDiskBytes',1.5*estimatedStorage,'diskGate',status(diskOk), ...
 'memoryGate',status(memoryOk),'groups',records, ...
 'conservativeTotalWallSec',sum([records.conservativeFormalWallSec]));
auditPassed=all(strcmp({records.status},'PASS'))&&all([records.allFinite])&& ...
 uniqueOk&&resumeOk&&hashStable&&diskOk&&memoryOk;
audit=struct('status',ternary(auditPassed,'PASS','FAIL'), ...
 'planVersion','V4-noLDRO-plan-R3-project-aligned', ...
 'algorithmVersion','Stage55-B-startup-observability-v30','groupCount',4, ...
 'uniqueSignatures',status(uniqueOk),'allFinite',status(all([records.allFinite])), ...
 'checkpointResumeWithoutRecount',status(resumeOk),'checkpointHashesStable',status(hashStable), ...
 'resourceGate',cost.status,'groups',records,'admission', ...
 ternary(auditPassed,'ADMIT_B_FORMAL_GROUP_1','DO_NOT_ADMIT'));
reportDir=fullfile(root,'results','reports');auditDir=fullfile(root,'results','audits');
write(fullfile(reportDir,'RUN_COST_ESTIMATE_B.json'),jsonencode(cost,'PrettyPrint',true));
hours=cost.conservativeTotalWallSec/3600;
md=sprintf(['# Experiment B formal run cost estimate\n\nStatus: `%s`.\n\n' ...
 '- Four smoke groups completed with one full pass each.\n' ...
 '- Effective worker count: %d (formula maximum %d; current-free-memory cap %d); single-worker observed MATLAB memory: %.3f GB.\n' ...
 '- Conservative total formal wall time: %.2f hours for 2000 passes.\n' ...
 '- Estimated checkpoint storage: %.3f GB; free disk: %.3f GB.\n' ...
 '- Memory gate: `%s`; disk gate: `%s`.\n'],cost.status,workerCount,formulaWorkerCount,freeWorkerCount,peak/2^30,hours,estimatedStorage/2^30,double(freeDisk)/2^30,cost.memoryGate,cost.diskGate);
write(fullfile(reportDir,'RUN_COST_ESTIMATE_B.md'),md);
write(fullfile(auditDir,'STAGE_07_EXPERIMENT_B_SMOKE_AUDIT.json'),jsonencode(audit,'PrettyPrint',true));
write(fullfile(auditDir,'STAGE_07_EXPERIMENT_B_SMOKE_AUDIT.md'),sprintf(['# Stage 07 Experiment B smoke audit\n\n' ...
 'Overall status: `%s`.\n\nFour independent groups completed. Signatures: `%s`; finite metrics: `%s`; ' ...
 'checkpoint recovery without recount: `%s`; artifact hashes stable: `%s`; resource gate: `%s`.\n\nAdmission: `%s`.\n'], ...
 audit.status,audit.uniqueSignatures,audit.allFinite,audit.checkpointResumeWithoutRecount, ...
 audit.checkpointHashesStable,audit.resourceGate,audit.admission));
if ~auditPassed,error('V4:SmokeAudit','B smoke/resource audit failed.');end
end
function x=status(ok),x=ternary(ok,'PASS','FAIL');end
function x=ternary(ok,a,b),if ok,x=a;else,x=b;end,end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
