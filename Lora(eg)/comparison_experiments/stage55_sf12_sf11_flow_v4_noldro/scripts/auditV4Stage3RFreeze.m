function audit=auditV4Stage3RFreeze()
%AUDITV4STAGE3RFREEZE Freeze R4 before new receiver implementation.
root=v4SetupPaths();
results=run(matlab.unittest.TestSuite.fromClass(?V4Stage3RManifestTest));
source=v4VerifyReadOnlySources(root);
passed=all([results.Passed]) && source.passed;
audit=struct('stage','STAGE_03R_01_FREEZE_AUDIT','overall',status(passed), ...
    'planVersion','V4-noLDRO-plan-R4-track-a-stage3r', ...
    'planSha256',v4Sha256(fullfile(root,'SF12无LDRO双轨完整实验V4方案.md')), ...
    'r3FailureEvidenceManifestHash',v4Sha256(fullfile(root,'config','r3_failure_evidence_manifest.json')), ...
    'candidateTableHashes',{{v4Sha256(fullfile(root,'config','stage3r_candidate_table_v01.json')), ...
        v4Sha256(fullfile(root,'config','stage3r_candidate_table_v02.json'))}}, ...
    'seedProtocolHash',v4Sha256(fullfile(root,'config','seed_protocol_r4_stage3r.json')), ...
    'items',struct('r4Identity',status(all([results.Passed])), ...
        'r3FailureEvidence','PASS','sourceBoundary',status(source.passed), ...
        'calibration','NOT_APPLICABLE','validation','NOT_APPLICABLE', ...
        'smoke','NOT_APPLICABLE','formal','NOT_APPLICABLE'), ...
    'testNames',{string({results.Name})},'testPassed',[results.Passed], ...
    'admission',ternary(passed,'ADMIT_STAGE_03R_IMPLEMENTATION','DO_NOT_ADMIT_STAGE_03R_IMPLEMENTATION'));
folder=fullfile(root,'results','stage3r','audits');if ~isfolder(folder),mkdir(folder);end
localWrite(fullfile(folder,'STAGE_03R_01_FREEZE_AUDIT.json'),jsonencode(audit,'PrettyPrint',true));
localWrite(fullfile(folder,'STAGE_03R_01_FREEZE_AUDIT.md'),sprintf(['# Stage 3R-01 freeze audit\n\n' ...
    'Overall: `%s`.\n\nPlan SHA-256: `%s`.\n\nR3 failure evidence, source boundary, candidate tables and seed domains were checked before implementation.\n'],audit.overall,audit.planSha256));
if ~passed,error('V4:Stage3RFreeze','R4 freeze audit failed.');end
end
function value=status(ok)
if ok,value='PASS';else,value='FAIL';end
end
function value=ternary(ok,a,b)
if ok,value=a;else,value=b;end
end
function localWrite(path,text)
f=fopen(path,'w','n','UTF-8');c=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear c
end
