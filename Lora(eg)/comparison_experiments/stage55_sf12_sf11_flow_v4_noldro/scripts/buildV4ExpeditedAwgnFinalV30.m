function delivery=buildV4ExpeditedAwgnFinalV30()
root=v4SetupPaths();c=sf12NoLdroSf11FlowConfig();snrs=(-30:-21).';
groups={'B_AWGN_CONTROLLED','B_AWGN_NATIVE'};bootstrapRoots=[561000000 562000000];
groupResults=cell(2,1);allComplete=true;allUnique=true;
for gi=1:2
 points=repmat(struct('snrDb',0,'passes',5,'methodMetrics',[],'rawErrors',[], ...
  'denominators',[],'stageMinusPaper',[],'lower95',[],'upper95',[], ...
  'halfWidth',[],'precisionLabel',{{}},'stageBetter',[]),10,1);
 signatures=cell(50,1);row=0;
 for si=1:10
  passMetrics=zeros(5,3,5);raw=zeros(3,4);den=zeros(3,4);
  for pi=1:5
   path=fullfile(root,'results','formal','track_b',groups{gi},sprintf('snr_%+03d',snrs(si)),'passes',sprintf('pass_%02d.mat',pi));
   if ~isfile(path),allComplete=false;continue,end
   x=load(path,'result');r=x.result;row=row+1;signatures{row}=r.runSignature;
   if ndims(r.metrics)==2,m=r.metrics;e=r.rawErrors;d=repmat(r.denominators,3,1);else,m=squeeze(r.metrics(:,:,3));e=squeeze(r.rawErrors(:,:,3));d=squeeze(r.denominators(:,:,3));end
   passMetrics(pi,:,1:4)=reshape(m,1,3,4);passMetrics(pi,:,5)=reshape(r.goodputBps,1,3,1);raw=raw+e;den=den+d;
  end
  meanMetrics=squeeze(mean(passMetrics,1));delta=meanMetrics(2,:)-meanMetrics(3,:);
  key=struct('planVersion','V4-noLDRO-plan-R3-project-aligned-expedited-AWGN-v1', ...
   'phase','expedited-awgn-bootstrap','track','B','channel','AWGN','comparisonMode',groups{gi}, ...
   'snrDb',snrs(si),'replicateId',0,'packetId',0,'eventType','paired-pass-bootstrap', ...
   'eventIndex',si,'sampleIndex',0,'component','resample');
  stream=RandStream('mt19937ar','Seed',v4KeyedSeed(bootstrapRoots(gi),key));draws=zeros(10000,5);
  for b=1:10000,idx=randi(stream,5,5,1);sample=mean(passMetrics(idx,:,:),1);draws(b,:)=reshape(sample(1,2,:)-sample(1,3,:),1,5);end
  bounds=prctile(draws,[2.5 97.5]);half=(bounds(2,:)-bounds(1,:))/2;limits=[.02 .01 .01 .05 10];labels=cell(1,5);
  for k=1:5,if half(k)<=limits(k),labels{k}='precision-sufficient';else,labels{k}='precision-inconclusive';end,end
  points(si)=struct('snrDb',snrs(si),'passes',5,'methodMetrics',meanMetrics,'rawErrors',raw, ...
   'denominators',den,'stageMinusPaper',delta,'lower95',bounds(1,:),'upper95',bounds(2,:), ...
   'halfWidth',half,'precisionLabel',{labels},'stageBetter',delta<0);
 end
 signatures=signatures(1:row);uniqueOk=numel(unique(signatures))==50;allUnique=allUnique&&uniqueOk;
 counts=zeros(1,5);for k=1:5,counts(k)=sum(arrayfun(@(p)p.stageBetter(k),points));end
 groupResults{gi}=struct('groupName',groups{gi},'status',ternary(row==50&&uniqueOk,'PASS','FAIL'), ...
  'completedPasses',row,'plannedPasses',50,'points',points,'stageBetterPointCounts',counts, ...
  'signatureSetHash',v4Sha256(strjoin(sort(signatures),'')));
end
boundary=v4VerifyReadOnlySources(root);passed=allComplete&&allUnique&&boundary.passed;
delivery=struct('status',ternary(passed,'PASS','FAIL'), ...
 'planVersion','V4-noLDRO-plan-R3-project-aligned-expedited-AWGN-v1', ...
 'parentPlanVersion','V4-noLDRO-plan-R3-project-aligned', ...
 'algorithmVersion','Stage55-B-startup-observability-v30', ...
 'actualCompletePassesPerGroupSnr',5,'parentBudgetPassesPerGroupSnr',50, ...
 'groups',[groupResults{:}].','ricianStatus','NOT_APPLICABLE_BY_USER_SCOPE_AMENDMENT', ...
 'readOnlyBoundary',ternary(boundary.passed,'PASS','FAIL'), ...
 'precisionWarning','Five complete passes per SNR provide limited cluster precision.', ...
 'parentPlanComplete',false,'conditionsOtherThanBudgetAndChannelScopeChanged',false);
reportDir=fullfile(root,'results','reports');save(fullfile(reportDir,'EXPERIMENT_B_AWGN_EXPEDITED_V1.mat'),'delivery','-v7.3');
write(fullfile(reportDir,'EXPERIMENT_B_AWGN_EXPEDITED_V1.json'),jsonencode(delivery,'PrettyPrint',true));
md=sprintf(['# Experiment B expedited AWGN report\n\nStatus under revised scope: `%s`.\n\n' ...
 'Plan: `V4-noLDRO-plan-R3-project-aligned-expedited-AWGN-v1`. Actual sample size is 5 complete passes per mode/SNR; parent budget was 50. ' ...
 'Rician groups are `NOT_APPLICABLE` by explicit user scope amendment. This is not completion of the parent R3 formal budget.\n\n']);
for gi=1:2,g=delivery.groups(gi);md=[md sprintf('## %s\n\nStage55-better point counts (SER/hard BER/ML BER/PER/goodput): %d/10, %d/10, %d/10, %d/10, %d/10.\n\n',g.groupName,g.stageBetterPointCounts)];end %#ok<AGROW>
md=[md sprintf('Read-only boundary: `%s`. Reduced-cluster precision and all CI crossings remain reported in the JSON artifact.\n',delivery.readOnlyBoundary)];
write(fullfile(reportDir,'EXPERIMENT_B_AWGN_EXPEDITED_V1.md'),md);
audit=struct('status',delivery.status,'experimentA','PASS_R14_FROZEN', ...
 'experimentBControlledAwgn',delivery.groups(1).status,'experimentBNativeAwgn',delivery.groups(2).status, ...
 'rician','NOT_APPLICABLE_BY_USER_SCOPE_AMENDMENT','actualPassesPerGroupSnr',5, ...
 'parentPassesPerGroupSnr',50,'parentPlanComplete',false,'readOnlyBoundary',delivery.readOnlyBoundary);
write(fullfile(reportDir,'V4_FINAL_AUDIT_EXPEDITED_AWGN_V1.json'),jsonencode(audit,'PrettyPrint',true));
write(fullfile(reportDir,'V4_FINAL_AUDIT_EXPEDITED_AWGN_V1.md'),sprintf(['# V4 final audit — expedited AWGN v1\n\n' ...
 'Overall revised-scope status: `%s`. Experiment A R14 remains frozen PASS. AWGN controlled: `%s`; AWGN native: `%s`; ' ...
 'Rician: `NOT_APPLICABLE` by user amendment. Actual/parent passes per group/SNR: 5/50. Parent R3 plan remains incomplete.\n'], ...
 audit.status,audit.experimentBControlledAwgn,audit.experimentBNativeAwgn));
if ~passed,error('V4:ExpeditedDelivery','Expedited AWGN delivery audit failed.');end
end
function x=ternary(ok,a,b),if ok,x=a;else,x=b;end,end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
