function result = runV4BCaseAnchorMechanismV8(packetsPerCell)
if nargin < 1,packetsPerCell = 5;end
root = v4SetupPaths();c = sf12NoLdroSf11FlowConfig();
list = v4BCalibrationCandidates();cases = [-366 0];snrs = -30:-15;
errors = zeros(2,16,3,4);staticFallbackCount = zeros(2,16);
for caseIndex = 1:2
    for snrIndex = 1:16
        for packetId = 1:packetsPerCell
            key = struct('planVersion','B-case-anchor-AWGN-v8', ...
                'phase','mechanism','track','B-case-anchor','channel','AWGN', ...
                'comparisonMode','case-anchor-controlled', ...
                'snrDb',snrs(snrIndex),'replicateId',packetId, ...
                'packetId',packetId,'eventType','paired-frame', ...
                'eventIndex',caseIndex*100+snrIndex,'sampleIndex',0);
            ledger = v4EventRandomLedger(603200000,key);
            frame = v4GenerateBCaseAnchorFrame( ...
                c,cases(caseIndex),snrs(snrIndex),ledger);
            common = v4CommonBootstrap( ...
                frame.observation.rxPhysical(1:8,:),c, ...
                SearchStepBins=list(1).searchStepBins);
            stage = v4Stage55CaseAnchorDecodeV7( ...
                frame.observation,common,c,list(2));
            receivers = {v4HuangStaticDecode(frame.observation,common,c), ...
                stage,v4PaperMidamblePointDecodeV2(frame.observation,c)};
            for method = 1:3
                m = v4EvaluateFrame(receivers{method},frame.truth,c);
                errors(caseIndex,snrIndex,method,:) = ...
                    errors(caseIndex,snrIndex,method,:)+reshape( ...
                    [m.symbolErrors m.hardBitErrors m.softBitErrors ...
                    m.packetError],1,1,1,4);
            end
            staticFallbackCount(caseIndex,snrIndex) = ...
                staticFallbackCount(caseIndex,snrIndex)+stage.staticFallbackExact;
        end
        fprintf('V8 mechanism Case %d SNR %g complete\n', ...
            caseIndex,snrs(snrIndex));
    end
end
den = repmat(reshape([packetsPerCell*112 packetsPerCell*768 ...
    packetsPerCell*768 packetsPerCell],1,1,1,4),2,16,3,1);
gate = v4BCaseAnchorExtendedAdmissionV4(errors,den);
regimePass = all(staticFallbackCount(1,:) == packetsPerCell) && ...
    all(staticFallbackCount(2,:) == 0);
if gate.overallPass && regimePass,status = 'PASS';else,status = 'FAIL';end
result = struct('status',status, ...
    'identity','B-case-anchor-AWGN-v8-mechanism', ...
    'algorithmVersion','Stage55-B-case-anchor-robust-regime-v7', ...
    'paperAlgorithmVersion','Paper-Midamble-Point-integer-full-FFT-v2', ...
    'packetsPerCaseSnr',packetsPerCell,'caseStartTimeSec',cases, ...
    'snrDb',snrs,'rawErrors',errors,'denominators',den, ...
    'metrics',errors./den,'staticFallbackCount',staticFallbackCount, ...
    'admissionGate',gate,'regimePass',regimePass, ...
    'conditionsFrozen',true,'selectionUsesTruth',false);
folder = fullfile(root,'results','b_exploratory','case_anchor_v8_mechanism');
if ~isfolder(folder),mkdir(folder),end
save(fullfile(folder,'mechanism.mat'),'result','-v7.3');
file = fopen(fullfile(folder,'mechanism.json'),'w','n','UTF-8');
cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',jsonencode(result,'PrettyPrint',true));clear cleaner
end
