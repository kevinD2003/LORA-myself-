function [report,audit]=aggregateAndAuditV4BFormalGroupV30(groupName)
root=v4SetupPaths();c=sf12NoLdroSf11FlowConfig();snrs=(-30:-21).';
groups=struct( ...
 'B_AWGN_CONTROLLED',struct('bootstrapRoot',561000000,'mode','controlled-time'), ...
 'B_AWGN_NATIVE',struct('bootstrapRoot',562000000,'mode','native-overhead'), ...
 'B_RICIAN_CONTROLLED',struct('bootstrapRoot',563000000,'mode','controlled-time'), ...
 'B_RICIAN_NATIVE',struct('bootstrapRoot',564000000,'mode','native-overhead'));
if ~isfield(groups,groupName),error('V4:FormalGroup','Unknown group.');end;g=groups.(groupName);
summary=repmat(struct('snrDb',0,'passes',0,'methodMetrics',[],'rawErrors',[], ...
 'denominators',[],'deltaStageMinusPaper',[],'lower95',[],'upper95',[], ...
 'halfWidth',[],'precisionLabel',{{}},'degenerateBootstrap',[]),10,1);
allHashes=cell(500,2);allSignatures=cell(500,1);row=0;allOk=true;
for si=1:10
 passMetrics=zeros(50,3,5);raw=zeros(3,4);den=zeros(3,4);
 for pi=1:50
  folder=fullfile(root,'results','formal','track_b',groupName,sprintf('snr_%+03d',snrs(si)),'passes');
  mp=fullfile(folder,sprintf('pass_%02d.mat',pi));jp=fullfile(folder,sprintf('pass_%02d.json',pi));
  if ~isfile(mp)||~isfile(jp),error('V4:FormalIncomplete','Missing %s SNR %g pass %d.',groupName,snrs(si),pi);end
  x=load(mp,'result');r=x.result;row=row+1;allHashes(row,:)={v4Sha256(mp),v4Sha256(jp)};allSignatures{row}=r.runSignature;
  allOk=allOk&&r.passIndex==pi&&r.snrDb==snrs(si)&&r.conditionsFrozen&&~r.selectionUsesTruth;
  if ndims(r.metrics)==2
   m=r.metrics;e=r.rawErrors;d=repmat(r.denominators,3,1);
  else
   m=squeeze(r.metrics(:,:,3));e=squeeze(r.rawErrors(:,:,3));d=squeeze(r.denominators(:,:,3));
  end
  passMetrics(pi,:,1:4)=reshape(m,1,3,4);passMetrics(pi,:,5)=reshape(r.goodputBps,1,3,1);
  raw=raw+e;den=den+d;
 end
 meanMetrics=squeeze(mean(passMetrics,1));delta=meanMetrics(2,:)-meanMetrics(3,:);
 key=struct('planVersion','V4-noLDRO-plan-R3-project-aligned','phase','formal-bootstrap-v30', ...
  'track','B','channel',groupName,'comparisonMode',g.mode,'snrDb',snrs(si), ...
  'replicateId',0,'packetId',0,'eventType','paired-pass-bootstrap','eventIndex',si,'sampleIndex',0,'component','resample');
 stream=RandStream('mt19937ar','Seed',v4KeyedSeed(g.bootstrapRoot,key));draws=zeros(c.bootstrapDraws,5);
 for b=1:c.bootstrapDraws,idx=randi(stream,50,50,1);sample=mean(passMetrics(idx,:,:),1);draws(b,:)=reshape(sample(1,2,:)-sample(1,3,:),1,5);end
 bounds=prctile(draws,[2.5 97.5]);lower=bounds(1,:);upper=bounds(2,:);half=(upper-lower)/2;
 limits=[.02 .01 .01 .05 10];labels=cell(1,5);for k=1:5,if half(k)<=limits(k),labels{k}='precision-sufficient';else,labels{k}='precision-inconclusive';end,end
 degenerate=range(draws,1)==0;
 summary(si)=struct('snrDb',snrs(si),'passes',50,'methodMetrics',meanMetrics, ...
  'rawErrors',raw,'denominators',den,'deltaStageMinusPaper',delta, ...
  'lower95',lower,'upper95',upper,'halfWidth',half,'precisionLabel',{labels}, ...
  'degenerateBootstrap',degenerate);
 end
uniqueOk=numel(unique(allSignatures))==500;passed=allOk&&uniqueOk&&row==500;
report=struct('status',ternary(passed,'PASS','FAIL'),'groupName',groupName, ...
 'algorithmVersion','Stage55-B-startup-observability-v30','mode',g.mode, ...
 'snrDb',snrs,'passesPerSnr',50,'totalPasses',500,'bootstrapDrawsPerSnr',10000, ...
 'summary',summary,'signatureSetHash',v4Sha256(strjoin(sort(allSignatures),'')), ...
 'artifactHashSet',allHashes,'conditionsFrozen',true);
groupDir=fullfile(root,'results','formal','track_b',groupName);save(fullfile(groupDir,'formal_group.mat'),'report','-v7.3');
write(fullfile(groupDir,'formal_group.json'),jsonencode(report,'PrettyPrint',true));
audit=struct('status',ternary(passed,'PASS','FAIL'),'groupName',groupName, ...
 'completedPasses',row,'plannedPasses',500,'fixedSampleCount',status(row==500), ...
 'uniqueSignatures',status(uniqueOk),'rawToReportRecalculation',status(allOk), ...
 'bootstrapDrawsPerSnr',10000,'pairedCompletePassUnit',true, ...
 'differentSignaturesMerged',false,'conditionsFrozen',true, ...
 'admission',ternary(passed,'ADMIT_NEXT_FORMAL_GROUP','STOP_FORMAL_SEQUENCE'));
write(fullfile(groupDir,'GROUP_AUDIT.json'),jsonencode(audit,'PrettyPrint',true));
write(fullfile(groupDir,'GROUP_AUDIT.md'),sprintf(['# %s formal group audit\n\nOverall status: `%s`.\n\n' ...
 'Completed passes: %d/500; unique signatures: `%s`; raw-to-report recalculation: `%s`; ' ...
 'paired complete-pass bootstrap: 10000 draws/SNR.\n\nAdmission: `%s`.\n'], ...
 groupName,audit.status,row,audit.uniqueSignatures,audit.rawToReportRecalculation,audit.admission));
if ~passed,error('V4:FormalGroupAudit','Formal group audit failed.');end
end
function x=status(ok),x=ternary(ok,'PASS','FAIL');end
function x=ternary(ok,a,b),if ok,x=a;else,x=b;end,end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
