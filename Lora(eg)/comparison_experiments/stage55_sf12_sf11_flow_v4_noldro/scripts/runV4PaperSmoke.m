function summary = runV4PaperSmoke()
%RUNV4PAPERSMOKE Sixteen paired packets per case with frozen parameters.
root=v4SetupPaths(); config=sf12NoLdroSf11FlowConfig();
manifest=jsondecode(fileread(fullfile(root,'config','paperReceiverParameterManifest.json')));
if ~strcmp(manifest.status,'frozen'),error('V4:TrackASmokeState','Track A parameters are not frozen.');end
cases=[-366 0]; records=cell(32,1); row=0; bytesBefore=localFolderBytes(root); ticId=tic;
for caseIndex=1:2
    for packetId=1:16
        row=row+1;
        records{row}=v4RunTrackAPairedPacket(config,cases(caseIndex),-21,packetId, ...
            440000000+100000*caseIndex,manifest.parameters);
    end
end
wallSec=toc(ticId); runtime=cell2mat(cellfun(@(x)x.runtimeSec,records,'UniformOutput',false));
summary=struct('status','PASS','seedDomain','a_smoke','packetCount',32, ...
    'wallSec',wallSec,'meanWallSecPerPacket',wallSec/32,'receiverRuntimeSec',runtime, ...
    'p95ReceiverRuntimeSec',prctile(runtime(:),95),'deadlineSec',config.symbolDurationSec, ...
    'deadlineMissCount',sum(runtime(:)>config.symbolDurationSec),'records',{records});
folder=fullfile(root,'results','smoke','track_a',manifest.parameterVersion);
if ~isfolder(folder),mkdir(folder);end
save(fullfile(folder,'track_a_smoke.mat'),'summary','-v7.3');
bytesAfter=localFolderBytes(root); bytesPerPacket=max(1,(bytesAfter-bytesBefore)/32);
estimate=struct('measuredPackets',32,'formalPackets',400000, ...
    'meanSecPerPacket',wallSec/32,'p95ReceiverRuntimeSec',summary.p95ReceiverRuntimeSec, ...
    'conservativeRuntimeHours',1.25*(wallSec/32)*400000/3600, ...
    'measuredBytesPerPacket',bytesPerPacket, ...
    'conservativeStorageGB',1.25*bytesPerPacket*400000/2^30);
reportFolder=fullfile(root,'results','reports');if ~isfolder(reportFolder),mkdir(reportFolder);end
localWrite(fullfile(reportFolder,'RUN_COST_ESTIMATE_A.json'),jsonencode(estimate,'PrettyPrint',true));
localWrite(fullfile(reportFolder,'RUN_COST_ESTIMATE_A.md'),sprintf(['# Track A run cost estimate\n\n' ...
    '- Measured smoke packets: 32\n- Formal packets: 400000\n' ...
    '- Conservative runtime: %.3f hours\n- Conservative storage: %.3f GiB\n' ...
    '- Fixed budget is not reduced by this estimate.\n'], ...
    estimate.conservativeRuntimeHours,estimate.conservativeStorageGB));
end
function bytes=localFolderBytes(root),f=dir(fullfile(root,'results','**','*'));f=f(~[f.isdir]);bytes=sum([f.bytes]);end
