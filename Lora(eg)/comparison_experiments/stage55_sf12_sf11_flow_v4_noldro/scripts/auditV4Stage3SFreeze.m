function audit=auditV4Stage3SFreeze()
root=v4SetupPaths();r=run(matlab.unittest.TestSuite.fromClass(?V4Stage3SManifestTest));s=v4VerifyReadOnlySources(root);
passed=all([r.Passed])&&s.passed;audit=struct('stage','STAGE_03S_01_FREEZE_AUDIT','overall',status(passed), ...
    'planVersion','V4-noLDRO-plan-R5-track-a-point-anchored-lock', ...
    'planSha256',v4Sha256(fullfile(root,'SF12无LDRO双轨完整实验V4方案_R5_STAGE3S.md')), ...
    'r3EvidenceManifestHash',v4Sha256(fullfile(root,'config','r3_failure_evidence_manifest.json')), ...
    'r4EvidenceManifestHash',v4Sha256(fullfile(root,'config','r4_failure_evidence_manifest.json')), ...
    'sourceBoundary',status(s.passed),'testPassed',[r.Passed], ...
    'admission',ternary(passed,'ADMIT_STAGE_03S_IMPLEMENTATION','DO_NOT_ADMIT_STAGE_03S_IMPLEMENTATION'));
folder=fullfile(root,'results','stage3s','audits');if ~isfolder(folder),mkdir(folder);end
write(fullfile(folder,'STAGE_03S_01_FREEZE_AUDIT.json'),jsonencode(audit,'PrettyPrint',true));
write(fullfile(folder,'STAGE_03S_01_FREEZE_AUDIT.md'),sprintf('# Stage 3S-01 freeze audit\n\nOverall: `%s`. Admission: `%s`.\n',audit.overall,audit.admission));
if ~passed,error('V4:Stage3SFreeze','Stage 3S freeze failed.');end
end
function x=status(ok),if ok,x='PASS';else,x='FAIL';end,end
function x=ternary(ok,a,b),if ok,x=a;else,x=b;end,end
function write(path,text),f=fopen(path,'w','n','UTF-8');c=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear c,end
