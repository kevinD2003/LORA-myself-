function result = runV4PaperCurveValidationV7()
root = v4SetupPaths();c = sf12NoLdroSf11FlowConfig();
list = v4BCalibrationCandidates();snrs = -30:-21;n = 50;
errors = zeros(10,3,3);
for snrIndex = 1:10
    for packetId = 1:n
        key = struct('planVersion','B-paper-curve-v7-validation', ...
            'phase','validation','track','B-case-anchor','channel','AWGN', ...
            'comparisonMode','case-anchor-controlled','snrDb',snrs(snrIndex), ...
            'replicateId',packetId,'packetId',packetId, ...
            'eventType','paired-frame','eventIndex',snrIndex,'sampleIndex',0);
        ledger = v4EventRandomLedger(621000000,key);
        frame = v4GenerateBCaseAnchorFrame(c,0,snrs(snrIndex),ledger);
        common = v4CommonBootstrap(frame.observation.rxPhysical(1:8,:),c, ...
            SearchStepBins=list(1).searchStepBins);
        receivers = {v4HuangStaticDecode(frame.observation,common,c), ...
            v4Stage55CaseProfileDecodeV8( ...
                frame.observation,common,c,list(2),"case2-dynamic"), ...
            v4PaperMidamblePointTrendDecodeV3(frame.observation,c)};
        for method = 1:3
            m = v4EvaluateFrame(receivers{method},frame.truth,c);
            errors(snrIndex,method,:) = errors(snrIndex,method,:)+ ...
                reshape([m.symbolErrors m.hardBitErrors m.softBitErrors],1,1,3);
        end
    end
    fprintf('Paper curve validation SNR %g complete\n',snrs(snrIndex));
end
den = reshape([n*112 n*768 n*768],1,1,3);
metrics = errors./den;
paperSer = metrics(:,3,1);stageSer = metrics(:,2,1);
referenceSer = [1 .99 .94 .86 .72 .56 .43 .29 .14 .05].';
strictStage = squeeze(errors(:,2,:)<errors(:,1,:) & ...
    errors(:,2,:)<errors(:,3,:));
paperTrend = paperSer(end)<paperSer(1) && ...
    numel(unique(errors(:,3,1)))>=6;
referenceLogRmse = sqrt(mean((log10(max(paperSer,1/(n*112)))- ...
    log10(referenceSer)).^2));
pass = all(strictStage,'all') && paperTrend && ...
    paperSer(end)>=0.02 && paperSer(end)<=0.08;
if pass,status='PASS';else,status='FAIL';end
result = struct('status',status,'identity','B-paper-curve-v7-validation', ...
    'paperAlgorithmVersion','Paper-Midamble-Point-local-trend-v5', ...
    'stageAlgorithmVersion','Stage55-B-known-case-profile-v8', ...
    'packetsPerSnr',n,'snrDb',snrs,'rawErrors',errors, ...
    'metrics',metrics,'paperSer',paperSer,'stageSer',stageSer, ...
    'referenceSerApproximate',referenceSer, ...
    'referenceLog10Rmse',referenceLogRmse, ...
    'stageStrictBetterAllMetrics',strictStage, ...
    'paperTrendPass',paperTrend,'endpointRange',[0.02 0.08], ...
    'conditionsFrozen',true,'stage55Modified',false);
folder = fullfile(root,'results','b_exploratory','paper_curve_v7_validation');
if ~isfolder(folder),mkdir(folder),end
save(fullfile(folder,'validation.mat'),'result','-v7.3');
file = fopen(fullfile(folder,'validation.json'),'w','n','UTF-8');
cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',jsonencode(result,'PrettyPrint',true));clear cleaner
end
