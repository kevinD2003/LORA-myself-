function audit = auditV4Stage1()
%AUDITV4STAGE1 Audit source freeze and contracts without running experiments.
root = v4SetupPaths();
source = v4VerifyReadOnlySources(root);
baseline = jsondecode(fileread(fullfile(root,'config','readonly_baseline.json')));
readonlyActual = repmat(struct('path','','fileCount',0,'sha256',''),numel(baseline.roots),1);
readonlyOk = false(numel(baseline.roots),1);
for index = 1:numel(baseline.roots)
    readonlyActual(index) = v4DirectoryDigest(baseline.roots(index).path);
    readonlyOk(index) = readonlyActual(index).fileCount == baseline.roots(index).fileCount && ...
        strcmp(readonlyActual(index).sha256,baseline.roots(index).sha256);
end
required = {'source_manifest.json','plan_manifest.json','result_contract.json', ...
    'seed_protocol.json','calibration_protocol.json','frame_timing_manifest.json', ...
    'readonly_baseline.json'};
exists = cellfun(@(x)isfile(fullfile(root,'config',x)),required);
suite = matlab.unittest.TestSuite.fromClass(?V4SourceFreezeTest);
suite = [suite matlab.unittest.TestSuite.fromClass(?V4ResultContractTest) ...
    matlab.unittest.TestSuite.fromClass(?V4SeedDomainTest)];
testResults = run(suite);
items = struct( ...
    'sourceHashes',localStatus(source.passed), ...
    'readOnlyBaselines',localStatus(all(readonlyOk)), ...
    'contractFiles',localStatus(all(exists)), ...
    'stageTests',localStatus(all([testResults.Passed])), ...
    'calibration','NOT_APPLICABLE','validation','NOT_APPLICABLE', ...
    'smoke','NOT_APPLICABLE','formal','NOT_APPLICABLE');
passed = source.passed && all(readonlyOk) && all(exists) && all([testResults.Passed]);
audit = struct('stage','STAGE_01_SOURCE_AND_INTERFACE_AUDIT', ...
    'overall',localStatus(passed),'planVersion','V4-noLDRO-plan-R3-project-aligned', ...
    'timestampUtc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd''T''HH:mm:ssXXX')), ...
    'items',items,'sourceFileCount',source.fileCount, ...
    'readOnlyActual',readonlyActual, ...
    'testNames',{string({testResults.Name})},'testPassed',[testResults.Passed], ...
    'commands',{{'auditV4Stage1'}}, ...
    'unresolvedIssues',{{'No implementation-stage evidence is claimed by Stage 1.'}}, ...
    'admission',ternary(passed,'ADMIT_STAGE_2','DO_NOT_ADMIT_STAGE_2'));
v4WriteAuditEvidence(root,audit.stage,audit);
if ~passed, error('V4:Stage1Audit','Stage 1 audit did not pass.'); end
end

function value = localStatus(ok)
if ok, value = 'PASS'; else, value = 'FAIL'; end
end

function value = ternary(condition,a,b)
if condition, value = a; else, value = b; end
end
