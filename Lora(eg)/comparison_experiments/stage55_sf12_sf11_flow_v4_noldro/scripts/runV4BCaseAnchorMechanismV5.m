function result = runV4BCaseAnchorMechanismV5(packetsPerCell)
if nargin < 1
    packetsPerCell = 10;
end
root = v4SetupPaths();
c = sf12NoLdroSf11FlowConfig();
list = v4BCalibrationCandidates();
cases = [-366 0];
snrs = -30:-21;
errors = zeros(2,10,3,4);
staticFallbackCount = zeros(2,10);
rateSum = zeros(2,10);
for caseIndex = 1:2
    for snrIndex = 1:10
        for packetId = 1:packetsPerCell
            key = struct('planVersion','B-case-anchor-AWGN-v5', ...
                'phase','mechanism','track','B-case-anchor', ...
                'channel','AWGN','comparisonMode','case-anchor-controlled', ...
                'snrDb',snrs(snrIndex),'replicateId',packetId, ...
                'packetId',packetId,'eventType','paired-frame', ...
                'eventIndex',caseIndex*100+snrIndex,'sampleIndex',0);
            ledger = v4EventRandomLedger(589000000,key);
            frame = v4GenerateBCaseAnchorFrame( ...
                c,cases(caseIndex),snrs(snrIndex),ledger);
            common = v4CommonBootstrap( ...
                frame.observation.rxPhysical(1:8,:),c, ...
                SearchStepBins=list(1).searchStepBins);
            stage = v4Stage55CaseAnchorDecodeV5( ...
                frame.observation,common,c,list(2));
            receivers = {v4HuangStaticDecode(frame.observation,common,c), ...
                stage,v4PaperMidambleDecode(frame.observation,common,c,list(1))};
            for method = 1:3
                metrics = v4EvaluateFrame(receivers{method},frame.truth,c);
                errors(caseIndex,snrIndex,method,:) = ...
                    errors(caseIndex,snrIndex,method,:)+reshape( ...
                    [metrics.symbolErrors metrics.hardBitErrors ...
                    metrics.softBitErrors metrics.packetError],1,1,1,4);
            end
            staticFallbackCount(caseIndex,snrIndex) = ...
                staticFallbackCount(caseIndex,snrIndex)+stage.staticFallbackExact;
            rateSum(caseIndex,snrIndex) = rateSum(caseIndex,snrIndex)+ ...
                stage.observableRateBinsPerSec;
        end
        fprintf('V5 mechanism Case %d SNR %g complete\n', ...
            caseIndex,snrs(snrIndex));
    end
end

denominators = reshape([packetsPerCell*112 packetsPerCell*768 ...
    packetsPerCell*768 packetsPerCell],1,1,1,4);
metrics = errors./denominators;
gate = v4BCaseAnchorAdmissionV2(errors);
admissionPass = gate.overallPass;
if admissionPass
    status = 'PASS';
else
    status = 'FAIL';
end

result = struct('status',status, ...
    'identity','B-case-anchor-AWGN-v5-mechanism', ...
    'algorithmVersion','Stage55-B-case-anchor-joint-preamble-v5', ...
    'packetsPerCaseSnr',packetsPerCell,'caseStartTimeSec',cases, ...
    'snrDb',snrs,'rawErrors',errors,'denominators',denominators, ...
    'metrics',metrics,'staticFallbackCount',staticFallbackCount, ...
    'meanObservableRateBinsPerSec',rateSum/packetsPerCell, ...
    'admissionGate',gate, ...
    'admissionPass',admissionPass,'conditionsFrozen',true, ...
    'selectionUsesTruth',false);
folder = fullfile(root,'results','b_exploratory', ...
    'case_anchor_v5_mechanism');
if ~isfolder(folder),mkdir(folder),end
save(fullfile(folder,'mechanism.mat'),'result','-v7.3');
text = jsonencode(result,'PrettyPrint',true);
file = fopen(fullfile(folder,'mechanism.json'),'w','n','UTF-8');
cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',text);
clear cleaner
end
