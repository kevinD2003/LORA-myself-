function delivery=buildV4ExpeditedAwgnP10FinalV30()
root=v4SetupPaths();snrs=(-30:-21).';groups={'B_AWGN_CONTROLLED','B_AWGN_NATIVE'};roots=[561000000 562000000];groupResults=cell(2,1);complete=true;uniqueAll=true;
for gi=1:2
 points=repmat(struct('snrDb',0,'passes',10,'methodMetrics',[],'rawErrors',[], ...
  'denominators',[],'stageMinusPaper',[],'lower95',[],'upper95',[], ...
  'halfWidth',[],'precisionLabel',{{}},'stageBetter',[]),10,1);
 signatures=cell(100,1);row=0;
 for si=1:10
  pm=zeros(10,3,5);raw=zeros(3,4);den=zeros(3,4);
  for pi=1:10
   path=fullfile(root,'results','formal','track_b',groups{gi},sprintf('snr_%+03d',snrs(si)),'passes',sprintf('pass_%02d.mat',pi));
   if ~isfile(path),complete=false;continue,end;x=load(path,'result');r=x.result;row=row+1;signatures{row}=r.runSignature;
   if ndims(r.metrics)==2,m=r.metrics;e=r.rawErrors;d=repmat(r.denominators,3,1);else,m=squeeze(r.metrics(:,:,3));e=squeeze(r.rawErrors(:,:,3));d=squeeze(r.denominators(:,:,3));end
   pm(pi,:,1:4)=reshape(m,1,3,4);pm(pi,:,5)=reshape(r.goodputBps,1,3,1);raw=raw+e;den=den+d;
  end
  meanMetric=squeeze(mean(pm,1));delta=meanMetric(2,:)-meanMetric(3,:);
  key=struct('planVersion','V4-noLDRO-plan-R3-project-aligned-expedited-AWGN-v2-P10', ...
   'phase','expedited-awgn-p10-bootstrap','track','B','channel','AWGN','comparisonMode',groups{gi}, ...
   'snrDb',snrs(si),'replicateId',0,'packetId',0,'eventType','paired-pass-bootstrap', ...
   'eventIndex',si,'sampleIndex',0,'component','resample');
  stream=RandStream('mt19937ar','Seed',v4KeyedSeed(roots(gi),key));draws=zeros(10000,5);
  for b=1:10000,idx=randi(stream,10,10,1);sample=mean(pm(idx,:,:),1);draws(b,:)=reshape(sample(1,2,:)-sample(1,3,:),1,5);end
  bounds=prctile(draws,[2.5 97.5]);half=(bounds(2,:)-bounds(1,:))/2;limits=[.02 .01 .01 .05 10];labels=cell(1,5);
  for k=1:5,if half(k)<=limits(k),labels{k}='precision-sufficient';else,labels{k}='precision-inconclusive';end,end
  points(si)=struct('snrDb',snrs(si),'passes',10,'methodMetrics',meanMetric,'rawErrors',raw, ...
   'denominators',den,'stageMinusPaper',delta,'lower95',bounds(1,:),'upper95',bounds(2,:), ...
   'halfWidth',half,'precisionLabel',{labels},'stageBetter',delta<0);
 end
 signatures=signatures(1:row);uniqueOk=numel(unique(signatures))==100;uniqueAll=uniqueAll&&uniqueOk;counts=zeros(1,5);
 for k=1:5,counts(k)=sum(arrayfun(@(p)p.stageBetter(k),points));end
 groupResults{gi}=struct('groupName',groups{gi},'status',ternary(row==100&&uniqueOk,'PASS','FAIL'), ...
  'completedPasses',row,'plannedPasses',100,'points',points,'stageBetterPointCounts',counts, ...
  'signatureSetHash',v4Sha256(strjoin(sort(signatures),'')));
end
boundary=v4VerifyReadOnlySources(root);passed=complete&&uniqueAll&&boundary.passed;
delivery=struct('status',ternary(passed,'PASS','FAIL'),'planVersion', ...
 'V4-noLDRO-plan-R3-project-aligned-expedited-AWGN-v2-P10', ...
 'parentPlanVersion','V4-noLDRO-plan-R3-project-aligned','algorithmVersion','Stage55-B-startup-observability-v30', ...
 'actualCompletePassesPerGroupSnr',10,'parentBudgetPassesPerGroupSnr',50, ...
 'groups',[groupResults{:}].','ricianStatus','NOT_APPLICABLE_BY_USER_SCOPE_AMENDMENT', ...
 'readOnlyBoundary',ternary(boundary.passed,'PASS','FAIL'), ...
 'precisionWarning','Ten complete-pass clusters improve over P5 but remain below the parent P50 precision budget.', ...
 'parentPlanComplete',false,'conditionsOtherThanBudgetAndChannelScopeChanged',false);
dir=fullfile(root,'results','reports');save(fullfile(dir,'EXPERIMENT_B_AWGN_EXPEDITED_V2_P10.mat'),'delivery','-v7.3');
write(fullfile(dir,'EXPERIMENT_B_AWGN_EXPEDITED_V2_P10.json'),jsonencode(delivery,'PrettyPrint',true));
md=sprintf(['# Experiment B expedited AWGN report — P10\n\nStatus: `%s`. Actual/parent pass count per mode/SNR: 10/50. ' ...
 'Rician is `NOT_APPLICABLE` by user scope amendment. The parent R3 formal budget remains incomplete.\n\n'],delivery.status);
for gi=1:2,g=delivery.groups(gi);md=[md sprintf('## %s\n\nStage55-better points for SER/hard BER/ML BER/PER/goodput: %d/10, %d/10, %d/10, %d/10, %d/10.\n\n',g.groupName,g.stageBetterPointCounts)];end %#ok<AGROW>
md=[md sprintf('Read-only boundary: `%s`. Pointwise intervals and precision labels are in the JSON artifact.\n',delivery.readOnlyBoundary)];
write(fullfile(dir,'EXPERIMENT_B_AWGN_EXPEDITED_V2_P10.md'),md);
audit=struct('status',delivery.status,'experimentA','PASS_R14_FROZEN', ...
 'experimentBControlledAwgn',delivery.groups(1).status,'experimentBNativeAwgn',delivery.groups(2).status, ...
 'rician','NOT_APPLICABLE_BY_USER_SCOPE_AMENDMENT','actualPassesPerGroupSnr',10, ...
 'parentPassesPerGroupSnr',50,'parentPlanComplete',false,'readOnlyBoundary',delivery.readOnlyBoundary);
write(fullfile(dir,'V4_FINAL_AUDIT_EXPEDITED_AWGN_V2_P10.json'),jsonencode(audit,'PrettyPrint',true));
write(fullfile(dir,'V4_FINAL_AUDIT_EXPEDITED_AWGN_V2_P10.md'),sprintf(['# V4 final audit — expedited AWGN P10\n\n' ...
 'Revised-scope status: `%s`. Experiment A R14: PASS; AWGN controlled: `%s`; AWGN native: `%s`; ' ...
 'Rician: NOT_APPLICABLE by user amendment. Actual/parent passes per group/SNR: 10/50. Parent R3 plan remains incomplete.\n'], ...
 audit.status,audit.experimentBControlledAwgn,audit.experimentBNativeAwgn));
if ~passed,error('V4:ExpeditedP10','P10 delivery audit failed.');end
end
function x=ternary(ok,a,b),if ok,x=a;else,x=b;end,end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
