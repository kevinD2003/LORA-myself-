function audit = auditV4PaperCurveV7()
root=v4SetupPaths();x=load(fullfile(root,'results','reports', ...
    'B_CASE2_PAPER_FIG11_ALIGNED_V7_REPORT.mat'),'report');r=x.report;
snrs=-30:-21;cellChecks=true(10,1);hashes=strings(10,1);
for i=1:10
    p=fullfile(root,'results','paper_curve_v7','formal', ...
        sprintf('snr_%+03d',snrs(i)),'formal_cell.mat');
    q=load(p,'cellResult');c=q.cellResult;
    cellChecks(i)=c.fixedPackets==200 && c.completedPackets==200 && ...
        isequal(sum(double(c.packetErrors),1),c.rawErrors) && ...
        c.pairedPacketKeysReused && ~c.stage55Recomputed && ...
        ~c.stage55Modified && c.conditionsFrozen;
    hashes(i)=c.sourceHash;
end
stageFiles={'src/stage55/v4Stage55CaseProfileDecodeV8.m', ...
 'src/stage55/v4Stage55JointPreambleMlBootstrap.m', ...
 'src/stage55/v4Stage55BootstrapFromJointPreambleMl.m', ...
 'src/stage55/v4Stage55Decode.m','src/stage55/v4RollingTrackerPass.m'};
stageHashes=struct();for i=1:numel(stageFiles)
 [~,name]=fileparts(stageFiles{i});stageHashes.(name)=v4Sha256(fullfile(root,stageFiles{i}));
end
checks=struct('all10PaperCellsRecomputed',all(cellChecks), ...
 'singlePaperSourceHash',numel(unique(hashes))==1, ...
 'reportPass',strcmp(r.status,'PASS'),'paperCurvePass',r.paperCurvePass, ...
 'stageStrictBetterAllCase2Points',all(r.stageStrictBetterCase2AllMetrics,'all'), ...
 'stage55Modified',r.stage55Modified,'case1Modified',r.case1Modified, ...
 'conditionsChanged',r.conditionsChanged);
pass=checks.all10PaperCellsRecomputed&&checks.singlePaperSourceHash&& ...
 checks.reportPass&&checks.paperCurvePass&&checks.stageStrictBetterAllCase2Points&& ...
 ~checks.stage55Modified&&~checks.case1Modified&&~checks.conditionsChanged;
if pass,status='PASS';else,status='FAIL';end
audit=struct('status',status,'identity','B-paper-curve-v7-audit', ...
 'checks',checks,'paperSourceHash',char(hashes(1)), ...
 'stageSourceHashes',stageHashes,'referenceLog10Rmse',r.referenceLog10Rmse, ...
 'pairedPacketsPerSnr',200,'bootstrapDraws',10000);
out=fullfile(root,'results','reports');
localWrite(fullfile(out,'B_CASE2_PAPER_FIG11_ALIGNED_V7_AUDIT.json'), ...
 jsonencode(audit,'PrettyPrint',true));
file=fopen(fullfile(out,'B_CASE2_PAPER_FIG11_ALIGNED_V7_AUDIT.md'),'w','n','UTF-8');
cleaner=onCleanup(@()fclose(file));fprintf(file,'# Case 2 Paper Figure 11 audit\n\nStatus: **%s**\n\n',status);
names=fieldnames(checks);for i=1:numel(names),fprintf(file,'- %s: %d\n',names{i},checks.(names{i}));end
clear cleaner
end
function localWrite(path,text)
file=fopen(path,'w','n','UTF-8');cleaner=onCleanup(@()fclose(file));
fprintf(file,'%s\n',text);clear cleaner
end
