function schedule=v4NativeOverheadSchedule(c,methodType)
arguments
 c (1,1) struct
 methodType (1,:) char {mustBeMember(methodType,{'short','paper'})}
end
[window,~]=v4VisibilityWindow(c);passStart=-window.deltaTimeOutSec;passEnd=window.deltaTimeOutSec;
if strcmp(methodType,'paper'),symbolCount=c.commonTimelineSymbolCount;else,symbolCount=c.noMidambleFrameSymbolCount;end
duration=symbolCount*c.symbolDurationSec;count=floor((passEnd-passStart)/duration+10*eps);
index=(1:count).';start=passStart+(index-1)*duration;finish=start+duration;center=(start+finish)/2;
visible=zeros(count,1);for k=1:size(window.intervalsSec,1),visible=visible+max(0,min(finish,window.intervalsSec(k,2))-max(start,window.intervalsSec(k,1)));end
fraction=min(1,max(0,visible/duration));tol=100*eps(max(1,duration));fullyVisible=fraction>=1-tol;fullyBlind=fraction<=tol;
layout=v4BuildNativeFrameLayout(c,strcmp(methodType,'paper'));
schedule=struct('timelineMode','native-overhead','scheduleType','back_to_back','methodType',methodType, ...
 'passStartTimeSec',passStart,'passEndTimeSec',passEnd,'passDurationSec',passEnd-passStart, ...
 'interFrameGapSec',0,'frameDurationSec',duration,'frameSymbolCount',symbolCount,'frameCount',count, ...
 'frameIndex',index,'frameStartTimeSec',start,'frameCenterTimeSec',center,'frameEndTimeSec',finish, ...
 'payloadStartTimeSec',start+c.bootstrapPilotCount*c.symbolDurationSec, ...
 'payloadSymbolOffsetSec',layout.dataStartTimeSec,'midambleOffsetSec',layout.physicalStartTimeSec(layout.midambleRows), ...
 'visibleFraction',fraction,'fullyVisible',fullyVisible,'fullyBlind',fullyBlind, ...
 'transitionFrame',~fullyVisible&~fullyBlind,'metricEligible',fullyVisible,'window',window);
end
