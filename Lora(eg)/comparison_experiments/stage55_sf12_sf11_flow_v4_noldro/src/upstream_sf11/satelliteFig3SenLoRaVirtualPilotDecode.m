function result = satelliteFig3SenLoRaVirtualPilotDecode( ...
        rxSymbols,config,knownWaveformBins,options)
%SATELLITEFIG3SENLORAVIRTUALPILOTDECODE No-orbit-prior SenLoRa path.
%   It starts from exactly the same Huang-PREC CP CFO and start phase as
%   the static baseline.  In a continuous pass, up to eight preceding
%   frame-preamble CFO observations provide a causal rate estimate; an
%   isolated frame falls back to its own known-preamble phase rate.  The
%   payload then uses two-pass-confirmed causal virtual-pilot updates.

arguments
    rxSymbols (:,:) double
    config (1,1) struct
    knownWaveformBins (:,1) double
    options.FrameStartTimeSec (1,1) double = NaN
    options.CrossFrameState (1,1) struct = struct()
    options.EnableVirtualPilots (1,1) logical = true
    options.EnableVirtualPilotRateUpdate (1,1) logical = true
    options.ApplyVirtualPilotPhaseCorrection (1,1) logical = true
    options.UseQualityAwareVirtualPilots (1,1) logical = true
end

bootstrapCount = numel(knownWaveformBins);
if bootstrapCount ~= config.bootstrapPilotCount || ...
        bootstrapCount >= size(rxSymbols,1)
    error('SatelliteFig3:SenLoRaVpBootstrap', ...
        'SenLoRa-VP requires the configured eight upchirps.');
end

bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
    rxSymbols(1:bootstrapCount,:),knownWaveformBins,config);
fallbackRate = min(config.maxRateBinsPerSec,max( ...
    -config.maxRateBinsPerSec,bootstrap.jointRateBinsPerSec));
crossFrameState = options.CrossFrameState;
usesCrossFrameState = isfinite(options.FrameStartTimeSec);
if ~usesCrossFrameState && ~isempty(fieldnames(crossFrameState))
    error('SatelliteFig3:SenLoRaVpCrossFrameTime', ...
        'FrameStartTimeSec is required when CrossFrameState is supplied.');
end
if usesCrossFrameState
    measurementTimeSec = options.FrameStartTimeSec+ ...
        0.5*bootstrapCount*config.symbolDurationSec;
    [initialRate,crossFrameState,rateDiagnostic] = ...
        satelliteFig3CrossFrameRateUpdate(crossFrameState, ...
        measurementTimeSec,bootstrap.epsilonHatBins,fallbackRate,config);
else
    initialRate = fallbackRate;
    rateDiagnostic = struct( ...
        'source','isolated-frame known-preamble phase fit', ...
        'historyCount',1, ...
        'rawRateBinsPerSec',fallbackRate, ...
        'rateBinsPerSec',fallbackRate, ...
        'usesTrajectoryPrior',false, ...
        'usesPayloadTruth',false);
end
rateReleasePilotCount = config.senloraRateReleasePilotCount;
if ~options.EnableVirtualPilotRateUpdate || ...
        options.UseQualityAwareVirtualPilots
    rateReleasePilotCount = 1e9;
end
useObservableVpRate = options.UseQualityAwareVirtualPilots && ...
    options.EnableVirtualPilotRateUpdate && ...
    rateDiagnostic.historyCount < config.virtualPilotHistoryLength;
virtualPilotInnovationGain = 1;
virtualPilotPhasePairInnovationGain = 1;
if options.UseQualityAwareVirtualPilots
    virtualPilotInnovationGain = ...
        config.senloraVirtualPilotInnovationGain;
    virtualPilotPhasePairInnovationGain = ...
        config.senloraPhasePairInnovationGain;
end
result = satelliteFig3SenLoRaIterativeDecode( ...
    rxSymbols,config,knownWaveformBins, ...
    UseEstimatedSnrGate=false, ...
    MinimumCodewordMarginRatio=config.senloraMinimumMarginRatio, ...
    RequireSoftHardAgreement=config.senloraRequireSoftHardAgreement, ...
    UseSoftDecodedPilotLabels=config.senloraUseSoftDecodedPilotLabels, ...
    UseCausalConfidenceTiming=config.senloraUseCausalConfidenceTiming, ...
    EnableVirtualPilots=options.EnableVirtualPilots, ...
    InnovationLimitBins=config.confidenceInnovationLimitBins, ...
    FreezeBootstrapRate=true, ...
    ReleaseBootstrapRateAfterVirtualPilotCount= ...
        rateReleasePilotCount, ...
    RateDeviationLimitBinsPerSec= ...
        config.senloraRateTrackingDeviationLimitBinsPerSec, ...
    BootstrapRateOverrideBinsPerSec=initialRate, ...
    BootstrapOverride=bootstrap, ...
    ApplyVirtualPilotPhaseCorrection= ...
        options.ApplyVirtualPilotPhaseCorrection, ...
    VirtualPilotInnovationGain=virtualPilotInnovationGain, ...
    EnableVirtualPilotPhasePairCfo= ...
        options.UseQualityAwareVirtualPilots, ...
    VirtualPilotPhasePairInnovationGain= ...
        virtualPilotPhasePairInnovationGain, ...
    PhasePairInnovationLimitBins= ...
        config.senloraPhasePairInnovationLimitBins, ...
    PhasePairAgreementLimitBins= ...
        config.senloraPhasePairAgreementLimitBins, ...
    UseObservableVirtualPilotRate=useObservableVpRate, ...
    VirtualPilotCfoStdBins=config.senloraVirtualPilotCfoStdBins, ...
    VirtualPilotRateStdLimitBinsPerSec= ...
        config.senloraVirtualPilotRateStdLimitBinsPerSec);
result.commonBootstrap = bootstrap;
result.initialRateBinsPerSec = initialRate;
result.isolatedFrameRateBinsPerSec = fallbackRate;
result.crossFrameState = crossFrameState;
result.crossFrameRateDiagnostic = rateDiagnostic;
result.usesCrossFrameState = usesCrossFrameState;
result.usesOrbitPrior = false;
result.virtualPilotsEnabled = options.EnableVirtualPilots;
result.virtualPilotRateUpdateEnabled = ...
    options.EnableVirtualPilotRateUpdate;
result.virtualPilotPhaseCorrectionEnabled = ...
    options.ApplyVirtualPilotPhaseCorrection;
result.qualityAwareVirtualPilotsEnabled = ...
    options.UseQualityAwareVirtualPilots;
result.observableVirtualPilotRateEnabled = useObservableVpRate;
if usesCrossFrameState
    rateProvenance = 'causal rolling-8 cross-frame preamble-CFO rate; ';
else
    rateProvenance = 'isolated-frame known-preamble phase rate; ';
end
if options.EnableVirtualPilots
    payloadProvenance = 'SenLoRa confidence virtual pilots enabled; ';
else
    payloadProvenance = 'control branch with payload virtual pilots disabled; ';
end
if options.EnableVirtualPilotRateUpdate
    rateProvenanceVp = 'VP rate release enabled; ';
else
    rateProvenanceVp = 'VP rate release disabled for ablation; ';
end
if options.ApplyVirtualPilotPhaseCorrection
    phaseProvenanceVp = 'VP phase correction enabled; ';
else
    phaseProvenanceVp = 'VP phase correction disabled for ablation; ';
end
if options.UseQualityAwareVirtualPilots
    qualityProvenanceVp = [ ...
        'quality-aware VP CFO fusion and guarded phase pairs enabled; ' ...
        'VP rate requires receiver-visible slope observability; '];
else
    qualityProvenanceVp = 'legacy unit-gain VP CFO observations; ';
end
result.algorithmProvenance = [payloadProvenance ...
    rateProvenanceVp phaseProvenanceVp qualityProvenanceVp ...
    'common Huang-PREC CP bootstrap; ' rateProvenance ...
    'no orbit rate prior; final ML soft Hamming decode'];
end
