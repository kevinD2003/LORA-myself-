function result = satelliteFig3HardPrecDecode(rxSymbols,config,knownWaveformBins)
%SATELLITEFIG3HARDPRECDECODE Hard-decision rolling-8 PREC receiver.
%   Every payload hard decision may request a virtual-pilot update, but the
%   rolling tracker accepts it only after the common peak, boundary, and
%   residual-innovation checks.  No transmitted payload labels or channel
%   truth are accepted by this interface.

nSymbols = size(rxSymbols,1);
bootstrapCount = numel(knownWaveformBins);
if bootstrapCount ~= config.bootstrapPilotCount || ...
        bootstrapCount >= nSymbols
    error('SatelliteFig3:HardPrecBootstrap', ...
        'Hard PREC requires the configured eight-symbol preamble.');
end

requestedMask = true(nSymbols,1);
bootstrap = satelliteFig3BootstrapEstimate( ...
    rxSymbols(1:bootstrapCount,:),knownWaveformBins,config);
orbitPrior = satelliteFig3OrbitRatePriorFromCfo( ...
    bootstrap.coarseCfoBins,config);
tracker = satelliteFig3RollingPilotTracker( ...
    rxSymbols,config,knownWaveformBins, ...
    AcceptedMask=requestedMask, ...
    InnovationLimitBins=config.confidenceInnovationLimitBins, ...
    FreezeBootstrapRate=true, ...
    ReleaseBootstrapRateAfterVirtualPilotCount= ...
        config.hardPrecRateReleasePilotCount, ...
    RateDeviationLimitBinsPerSec= ...
        config.hardPrecRateTrackingDeviationLimitBinsPerSec, ...
    BootstrapRateOverrideBinsPerSec=orbitPrior.rateBinsPerSec);

payloadRows = bootstrapCount+1:nSymbols;
decodedDataBits = satelliteFig3HardPayloadBits( ...
    tracker.detectedWaveformBins(payloadRows),config);

result = struct( ...
    'detectedWaveformBins',tracker.detectedWaveformBins, ...
    'decodedDataBits',decodedDataBits, ...
    'requestedMask',tracker.requestedMask, ...
    'pilotAccepted',tracker.pilotAccepted, ...
    'orbitPrior',orbitPrior, ...
    'tracker',tracker);
end
