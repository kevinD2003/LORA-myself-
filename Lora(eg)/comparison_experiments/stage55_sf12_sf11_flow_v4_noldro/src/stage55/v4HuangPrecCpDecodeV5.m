function result=v4HuangPrecCpDecodeV5(observation,c)
%V4HUANGPRECCPDECODEV5 Continuous-phase adaptation of eight-upchirp PREC.
%   The senior PREC code complex-averages eight phase-reset preambles before
%   its eta/FFT search. The physical project keeps carrier phase continuous
%   across symbols, so the equivalent receiver-observable adaptation sums
%   the eight per-preamble FFT powers. The original eta grid and one fixed
%   CFO estimate for the complete payload are otherwise unchanged.

pilots=observation.rxPhysical(1:c.bootstrapPilotCount,:);
known=v4ModulateSymbol(0,c);downchirp=conj(known);
n=0:c.samplesPerSymbol-1;
etaCandidates=(0:0.1:0.9).';
combinedPower=zeros(numel(etaCandidates),c.samplesPerSymbol);
for etaIndex=1:numel(etaCandidates)
    rotation=exp(1i*2*pi*etaCandidates(etaIndex)*n/c.samplesPerSymbol);
    for pilot=1:c.bootstrapPilotCount
        spectrum=fft(pilots(pilot,:).*rotation.*downchirp);
        combinedPower(etaIndex,:)=combinedPower(etaIndex,:)+ ...
            abs(spectrum).^2;
    end
end
[peakPerEta,binPerEta]=max(combinedPower,[],2);
[bestMetric,bestEtaIndex]=max(peakPerEta);
bestEta=etaCandidates(bestEtaIndex);bestBin=binPerEta(bestEtaIndex)-1;
if bestBin>=c.samplesPerSymbol/2,bestBin=bestBin-c.samplesPerSymbol;end
fixedCfoBins=bestBin-bestEta;

compensatedData=complex(zeros(c.payloadSymbolCount,c.samplesPerSymbol));
estimatedCfoBins=repmat(fixedCfoBins,c.payloadSymbolCount,1);
layout=observation.layout;
for data=1:c.payloadSymbolCount
    row=layout.dataRows(data);
    compensatedData(data,:)=v4CompensateSymbol( ...
        observation.rxPhysical(row,:),0,fixedCfoBins,0,c);
end
decoded=v4DecodePayload(compensatedData,c,observation.noiseVariance);
result=struct('methodName',c.methodNames{1}, ...
    'methodId','huang-prec-cp-v5', ...
    'algorithmVersion','Huang-PREC-continuous-phase-power-combined-v5', ...
    'detectedPhysicalBins',decoded.hardPhysicalBins, ...
    'hardDecodedDataBits',decoded.hardDataBits, ...
    'softDecodedDataBits',decoded.softDataBits, ...
    'estimatedCfoBins',estimatedCfoBins, ...
    'virtualPilotAccepted',false(c.payloadSymbolCount,1), ...
    'explicitMidambleAccepted',false(c.paperMidambleCount,1), ...
    'etaCandidates',etaCandidates,'etaHatBins',bestEta, ...
    'integerCfoBin',bestBin,'epsilonHatBins',fixedCfoBins, ...
    'peakMetric',bestMetric,'peakPerEta',peakPerEta, ...
    'combinedPower',combinedPower, ...
    'preambleAverageCount',c.bootstrapPilotCount, ...
    'preambleCombination','sum-per-preamble-fft-power', ...
    'continuousPhaseAdaptation',true, ...
    'usesPayloadFeedback',false,'usesDopplerRate',false, ...
    'sameEntryAcrossCases',true,'usesCaseIdentity',false, ...
    'usesSnrInput',false,'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'fftCount',numel(etaCandidates)*c.bootstrapPilotCount+ ...
        c.payloadSymbolCount);
end
