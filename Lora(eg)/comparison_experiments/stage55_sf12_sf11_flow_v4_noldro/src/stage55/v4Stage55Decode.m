function result = v4Stage55Decode(observation,bootstrap,config,parameters,options)
%V4STAGE55DECODE Up to five confidence replays with hard-label VPs.

arguments
    observation (1,1) struct
    bootstrap (1,1) struct
    config (1,1) struct
    parameters (1,1) struct
    options.CrossFrameRateBinsPerSec (1,1) double = NaN
    options.CrossFrameHistoryCount (1,1) double {mustBeInteger,mustBeNonnegative} = 0
end

v4ValidateReceiverParameters(parameters);
candidateMask = false(config.payloadSymbolCount,1);
previousProposed = false(config.payloadSymbolCount,1);
previousHard = nan(config.payloadSymbolCount,1);
history = repmat(struct(),0,1);
converged = false;
for iteration = 1:config.maxSenLoRaIterations
    tracker = v4RollingTrackerPass(observation,bootstrap,config,parameters,candidateMask, ...
        InitialRateBinsPerSec=options.CrossFrameRateBinsPerSec);
    decoded = v4DecodePayload(tracker.compensatedData,config,bootstrap.noisePower);
    confidence = v4Stage55Confidence(decoded,config,parameters);
    promotionEnabled = true;
    proposed = confidence.confidentMask;
    if iteration == 1
        stable = false(config.payloadSymbolCount,1);
    else
        stable = proposed & previousProposed & ...
            tracker.hardPhysicalBins == previousHard;
    end
    nextMask = candidateMask | stable;
    history(iteration).iteration = iteration;
    history(iteration).requestedMask = candidateMask;
    history(iteration).proposedMask = proposed;
    history(iteration).stableMask = stable;
    history(iteration).acceptedMask = tracker.pilotAccepted;
    if iteration >= 2 && isequal(nextMask,candidateMask), converged = true; end
    candidateMask = nextMask;
    previousProposed = proposed;
    previousHard = tracker.hardPhysicalBins;
end
result = struct('methodName',config.methodNames{2}, ...
    'detectedPhysicalBins',decoded.hardPhysicalBins, ...
    'hardDecodedDataBits',decoded.hardDataBits, ...
    'softDecodedDataBits',decoded.softDataBits, ...
    'estimatedCfoBins',tracker.predictedCfoBins, ...
    'virtualPilotAccepted',tracker.pilotAccepted, ...
    'explicitMidambleAccepted',false(config.paperMidambleCount,1), ...
    'pilotFirstEffectivePhysicalRow',tracker.pilotAppliedAtPhysicalRow, ...
    'pilotAvailabilityPhysicalRow',tracker.pilotAvailabilityPhysicalRow, ...
    'activeHistoryCount',tracker.activeHistoryCount, ...
    'phasePairUsed',tracker.phasePairUsed,'iterations',numel(history), ...
    'converged',converged,'iterationHistory',history,'tracker',tracker, ...
    'initialRateBinsPerSec',tracker.initialRateBinsPerSec, ...
    'usesCrossFrameState',tracker.usesCrossFrameRate, ...
    'crossFrameHistoryCount',options.CrossFrameHistoryCount, ...
    'virtualPilotPromotionEnabled',promotionEnabled, ...
    'bootstrap',bootstrap,'virtualPilotLabelSource','hard LoRa decision', ...
    'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'usesSoftInformationOnlyForAdmission',true, ...
    'fftCount',numel(history)*config.payloadSymbolCount);
end
