function small = v4RunBCaseAnchorCellV2(root,c,lowP,highP,caseIndex,snrIndex)
%V4RUNBCASEANCHORCELLV2 Fixed 200-packet V5 case/SNR cell.

cases = [-366 0];
snrs = -30:-21;
n = 200;
caseTime = cases(caseIndex);
snrDb = snrs(snrIndex);
sourceFiles = { ...
    'src/phy/v4GenerateBCaseAnchorFrame.m', ...
    'src/phy/v4CommonBootstrap.m', ...
    'src/stage55/v4Stage55JointPreambleMlBootstrap.m', ...
    'src/stage55/v4Stage55BootstrapFromJointPreambleMl.m', ...
    'src/stage55/v4Stage55CaseAnchorDecodeV5.m', ...
    'src/stage55/v4Stage55Decode.m', ...
    'src/stage55/v4RollingTrackerPass.m', ...
    'src/stage55/v4HuangStaticDecode.m', ...
    'src/paper/v4PaperMidambleDecode.m', ...
    'src/coding/v4DecodePayload.m', ...
    'src/statistics/v4EvaluateFrame.m', ...
    'config/sf12NoLdroSf11FlowConfig.m', ...
    'config/v4BCalibrationCandidates.m'};
hashText = '';
for k = 1:numel(sourceFiles)
    hashText = [hashText sourceFiles{k} '=' ...
        v4Sha256(fullfile(root,sourceFiles{k})) ';']; %#ok<AGROW>
end
sourceHash = v4Sha256(hashText);
signature = v4Sha256(sprintf( ...
    'B-case-anchor-AWGN-v2|source=%s|case=%d|snr=%d|N=200|root=590000000', ...
    sourceHash,caseIndex,snrDb));
folder = fullfile(root,'results','case_anchor_b', ...
    'B-case-anchor-AWGN-v2-joint-preamble',sprintf('case_%d',caseIndex), ...
    sprintf('snr_%+03d',snrDb));
if ~isfolder(folder),mkdir(folder),end
finalPath = fullfile(folder,'formal_cell.mat');
checkpointPath = fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    loaded = load(finalPath,'cellResult');
    if strcmp(loaded.cellResult.signature,signature)
        small = rmfield(loaded.cellResult, ...
            {'packetErrors','observableRateBinsPerSec'});
        jsonPath = fullfile(folder,'formal_cell.json');
        if ~isfile(jsonPath)
            localWrite(jsonPath,jsonencode(small,'PrettyPrint',true));
        end
        return
    end
    error('V4:BCaseAnchorV2Signature','Final signature mismatch.');
end
if isfile(checkpointPath)
    state = v4LoadCheckpoint(checkpointPath,signature);
else
    state = struct('completed',0, ...
        'packetErrors',zeros(n,3,4,'uint16'), ...
        'staticFallback',false(n,1), ...
        'observableRateBinsPerSec',nan(n,1));
end

for packetId = state.completed+1:n
    key = struct('planVersion','B-case-anchor-AWGN-v2', ...
        'phase','formal','track','B-case-anchor','channel','AWGN', ...
        'comparisonMode','case-anchor-controlled','snrDb',snrDb, ...
        'replicateId',packetId,'packetId',packetId, ...
        'eventType','paired-frame','eventIndex',caseIndex*100+snrIndex, ...
        'sampleIndex',0);
    ledger = v4EventRandomLedger(590000000,key);
    frame = v4GenerateBCaseAnchorFrame(c,caseTime,snrDb,ledger);
    common = v4CommonBootstrap(frame.observation.rxPhysical(1:8,:),c, ...
        SearchStepBins=lowP.searchStepBins);
    stage = v4Stage55CaseAnchorDecodeV5( ...
        frame.observation,common,c,highP);
    receivers = {v4HuangStaticDecode(frame.observation,common,c), ...
        stage,v4PaperMidambleDecode(frame.observation,common,c,lowP)};
    for method = 1:3
        metrics = v4EvaluateFrame(receivers{method},frame.truth,c);
        state.packetErrors(packetId,method,:) = uint16( ...
            [metrics.symbolErrors metrics.hardBitErrors ...
            metrics.softBitErrors metrics.packetError]);
    end
    state.staticFallback(packetId) = stage.staticFallbackExact;
    state.observableRateBinsPerSec(packetId) = ...
        stage.observableRateBinsPerSec;
    state.completed = packetId;
    if mod(packetId,25) == 0 || packetId == n
        v4WriteCheckpointAtomic(checkpointPath,state,signature);
    end
end

orbit = v4TrackAOrbit([caseTime-.01;caseTime;caseTime+.01],c);
rateHzPerSec = (orbit.dopplerHz(3)-orbit.dopplerHz(1))/.02;
raw = squeeze(sum(double(state.packetErrors),1));
denominators = repmat([n*112 n*768 n*768 n],3,1);
metrics = raw./denominators;
cellResult = struct('status','PASS', ...
    'identity','B-case-anchor-AWGN-v2-joint-preamble', ...
    'algorithmVersion','Stage55-B-case-anchor-joint-preamble-v5', ...
    'caseIndex',caseIndex,'caseStartTimeSec',caseTime,'snrDb',snrDb, ...
    'fixedPackets',n,'completedPackets',n,'signature',signature, ...
    'sourceHash',sourceHash,'sourceFiles',{sourceFiles}, ...
    'initialCfoHz',orbit.dopplerHz(2), ...
    'initialCfoBins',orbit.dopplerHz(2)/c.fftBinSpacingHz, ...
    'initialRateHzPerSec',rateHzPerSec, ...
    'initialRateBinsPerSec',rateHzPerSec/c.fftBinSpacingHz, ...
    'rawErrors',raw,'denominators',denominators,'metrics',metrics, ...
    'packetErrors',state.packetErrors, ...
    'staticFallbackCount',sum(state.staticFallback), ...
    'observableRateMeanBinsPerSec', ...
        mean(state.observableRateBinsPerSec), ...
    'observableRateStdBinsPerSec', ...
        std(state.observableRateBinsPerSec), ...
    'observableRateBinsPerSec',state.observableRateBinsPerSec, ...
    'conditionsFrozen',true,'usesCrossPacketHistory',false, ...
    'usesPayloadTruthForSelection',false,'usesOrbitTruthForSelection',false);
save(finalPath,'cellResult','-v7.3');
small = rmfield(cellResult,{'packetErrors','observableRateBinsPerSec'});
localWrite(fullfile(folder,'formal_cell.json'), ...
    jsonencode(small,'PrettyPrint',true));
end

function localWrite(path,text)
file = fopen(path,'w','n','UTF-8');
cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',text);
clear cleaner
end
