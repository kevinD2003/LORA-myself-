function result=v4RunUnifiedV16TestCell(caseIndex,snrIndex)
%V4RUNUNIFIEDV16TESTCELL Fixed 1000-packet three-method paired cell.
root=v4SetupPaths();c=sf12NoLdroSf11FlowConfig();snrs=-30:-21;
cases=[-366 0];n=1000;snrDb=snrs(snrIndex);
sourceFiles={'src/stage55/v4HuangUnifiedDecodeV2.m', ...
    'src/stage55/v4Stage55UnifiedDecodeV16.m', ...
    'src/paper/v4PaperMidamblePointUnifiedV6.m'};
hashText='';
for k=1:numel(sourceFiles)
    hashText=[hashText sourceFiles{k} '=' ...
        v4Sha256(fullfile(root,sourceFiles{k})) ';']; %#ok<AGROW>
end
sourceHash=v4Sha256(hashText);
signature=v4Sha256(sprintf('unified-v16-test|source=%s|case=%d|snr=%d|N=%d', ...
    sourceHash,caseIndex,snrDb,n));
folder=fullfile(root,'results','method_aligned','unified_v16_test', ...
    sprintf('case%d',caseIndex),sprintf('snr_%+03d',snrDb));
if ~isfolder(folder),mkdir(folder),end
finalPath=fullfile(folder,'test_cell.mat');checkpoint=fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    x=load(finalPath,'result');
    if strcmp(x.result.signature,signature),result=x.result;return,end
    error('V4:UnifiedV16TestSignature','Existing test signature mismatch.');
end
if isfile(checkpoint)
    state=v4LoadCheckpoint(checkpoint,signature);
else
    state=struct('completed',0,'packetErrors',zeros(n,3,2,'uint16'), ...
        'stageAcceptedVp',zeros(n,1,'uint16'), ...
        'stageFalseVp',zeros(n,1,'uint16'), ...
        'case1StageHuangMismatch',false(n,1), ...
        'paperDynamic',false(n,1),'huangDynamic',false(n,1), ...
        'stageDynamic',false(n,1));
end
p=v4LoadMethodAlignedR3ParametersV1();
for packetId=state.completed+1:n
    key=struct('planVersion','unified-v16-test','phase','paired-grid', ...
        'track','B-method-aligned','channel','AWGN', ...
        'comparisonMode','case-anchor-controlled','snrDb',snrDb, ...
        'replicateId',packetId,'packetId',packetId, ...
        'eventType','paired-frame','eventIndex',caseIndex*100+snrIndex, ...
        'sampleIndex',0);
    ledger=v4EventRandomLedger(884000000,key);
    frame=v4GenerateBCaseAnchorFrame(c,cases(caseIndex),snrDb,ledger);
    common=v4CommonBootstrap(frame.observation.rxPhysical(1:8,:),c, ...
        SearchStepBins=p.searchStepBins);
    receivers={v4HuangUnifiedDecodeV2(frame.observation,common,c), ...
        v4Stage55UnifiedDecodeV16(frame.observation,common,c), ...
        v4PaperMidamblePointUnifiedV6(frame.observation,common,c)};
    for method=1:3
        state.packetErrors(packetId,method,1)=uint16(sum( ...
            receivers{method}.detectedPhysicalBins~=frame.truth.payloadPhysicalBins));
        state.packetErrors(packetId,method,2)=uint16(sum( ...
            receivers{method}.hardDecodedDataBits(:)~=frame.truth.dataBits(:)));
    end
    stage=receivers{2};vp=stage.virtualPilotAccepted(:);
    state.stageAcceptedVp(packetId)=uint16(sum(vp));
    if isfield(stage,'tracker')
        state.stageFalseVp(packetId)=uint16(sum(vp& ...
            stage.tracker.hardPhysicalBins~=frame.truth.payloadPhysicalBins));
    end
    state.case1StageHuangMismatch(packetId)=caseIndex==1&& ...
        ~isequal(receivers{1}.detectedPhysicalBins,receivers{2}.detectedPhysicalBins);
    state.huangDynamic(packetId)=strcmp(receivers{1}.huangRegime, ...
        'preamble-rate-prec-dynamic-observable');
    state.stageDynamic(packetId)=strcmp(receivers{2}.stageRegime, ...
        'joint-preamble-vp-dynamic-observable');
    state.paperDynamic(packetId)=strcmp(receivers{3}.paperRegime, ...
        'trend-point-dynamic-observable');
    state.completed=packetId;
    if mod(packetId,25)==0||packetId==n
        v4WriteCheckpointAtomic(checkpoint,state,signature);
        fprintf('Unified V16 test Case %d SNR %g: %d/%d\n', ...
            caseIndex,snrDb,packetId,n);
    end
end
raw=squeeze(sum(double(state.packetErrors),1));
den=repmat([n*112 n*768],3,1);
result=struct('status','COMPLETE','identity','unified-v16-test', ...
    'caseIndex',caseIndex,'caseStartTimeSec',cases(caseIndex), ...
    'snrDb',snrDb,'fixedPackets',n,'signature',signature, ...
    'sourceHash',sourceHash,'methodIds',{{'huang-unified-v2', ...
    'stage55-unified-v16','paper-midamble-adapted-v6'}}, ...
    'rawErrors',raw,'denominators',den,'metrics',raw./den, ...
    'packetErrors',state.packetErrors, ...
    'stageAcceptedVp',sum(state.stageAcceptedVp), ...
    'stageFalseVp',sum(state.stageFalseVp), ...
    'case1StageHuangMismatchPackets',sum(state.case1StageHuangMismatch), ...
    'huangDynamicPackets',sum(state.huangDynamic), ...
    'stageDynamicPackets',sum(state.stageDynamic), ...
    'paperDynamicPackets',sum(state.paperDynamic), ...
    'mlBerComputed',false,'conditionsFrozen',true);
save(finalPath,'result','-v7.3');small=rmfield(result,'packetErrors');
file=fopen(fullfile(folder,'test_cell.json'),'w','n','UTF-8');
cleaner=onCleanup(@()fclose(file));fprintf(file,'%s\n', ...
    jsonencode(small,'PrettyPrint',true));clear cleaner
end
