function gate = v4BCaseAnchorAdmissionV2(rawErrors)
%V4BCASEANCHORADMISSIONV2 Evaluate the preregistered pointwise ordering.
%
% Method order is Huang, Stage55, Paper.  Metrics are SER, hard BER and
% ML BER.  A strict comparison against an observed zero is impossible, so
% the Case-1 Paper gate accepts equality only when Paper and Stage both
% have zero errors.  Case 2 has no zero-floor exception.

arguments
    rawErrors (:,:,:,:) double
end
if ~isequal(size(rawErrors),[2 10 3 4])
    error('V4:BCaseAnchorAdmissionShape', ...
        'Expected raw errors with shape 2x10x3x4.');
end

stage = squeeze(rawErrors(:,:,2,1:3));
huang = squeeze(rawErrors(:,:,1,1:3));
paper = squeeze(rawErrors(:,:,3,1:3));
case1NotWorseHuang = stage(1,:,:) <= huang(1,:,:);
case1BetterPaper = stage(1,:,:) < paper(1,:,:) | ...
    (paper(1,:,:) == 0 & stage(1,:,:) == 0);
case2StrictBoth = stage(2,:,:) < huang(2,:,:) & ...
    stage(2,:,:) < paper(2,:,:);

gate = struct( ...
    'case1NotWorseHuang',case1NotWorseHuang, ...
    'case1BetterPaperWithZeroFloor',case1BetterPaper, ...
    'case2StrictBetterBoth',case2StrictBoth, ...
    'case1Pass',all(case1NotWorseHuang,'all') && ...
        all(case1BetterPaper,'all'), ...
    'case2Pass',all(case2StrictBoth,'all'), ...
    'zeroErrorFloorRule', ...
        'If Paper has zero Case-1 errors, Stage must also have zero; strict inequality is mathematically impossible.', ...
    'metricOrder',{{'SER','hard-BER','ML-BER'}});
gate.overallPass = gate.case1Pass && gate.case2Pass;
end
