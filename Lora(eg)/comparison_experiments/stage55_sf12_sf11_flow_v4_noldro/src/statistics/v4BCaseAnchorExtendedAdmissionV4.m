function gate = v4BCaseAnchorExtendedAdmissionV4(rawErrors,denominators)
%V4BCASEANCHOREXTENDEDADMISSIONV4 Ordering and requested curve-shape gates.
arguments
    rawErrors (:,:,:,:) double
    denominators (:,:,:,:) double
end
if ~isequal(size(rawErrors),[2 16 3 4]) || ...
        ~isequal(size(denominators),[2 16 3 4])
    error('V4:BCaseAnchorExtendedShape','Expected 2x16x3x4 arrays.');
end
stage = squeeze(rawErrors(:,:,2,1:3));
huang = squeeze(rawErrors(:,:,1,1:3));
paper = squeeze(rawErrors(:,:,3,1:3));
case1NotWorseHuang = stage(1,:,:) <= huang(1,:,:);
case1BetterPaper = stage(1,:,:) < paper(1,:,:) | ...
    (paper(1,:,:) == 0 & stage(1,:,:) == 0);
case2StrictBoth = stage(2,:,:) < huang(2,:,:) & ...
    stage(2,:,:) < paper(2,:,:);
metrics = rawErrors./denominators;
stageBer = squeeze(metrics(2,:,2,2:3));
paperCase2 = squeeze(paper(2,:,:));
paperCase2Trend = squeeze(paper(2,10,:)) < squeeze(paper(2,1,:));
paperCase2Nonconstant = false(1,3);
for metric = 1:3
    paperCase2Nonconstant(metric) = ...
        numel(unique(paperCase2(:,metric))) >= 4;
end
paperCase1BerChanges = squeeze(paper(1,9,2:3)) > ...
    squeeze(paper(1,10,2:3));
reachesOneEminusFive = any(stageBer <= 1e-5,1);
gate = struct( ...
    'case1NotWorseHuang',case1NotWorseHuang, ...
    'case1BetterPaperWithZeroFloor',case1BetterPaper, ...
    'case2StrictBetterBoth',case2StrictBoth, ...
    'paperCase2TrendMinus30ToMinus21',paperCase2Trend, ...
    'paperCase2Nonconstant',paperCase2Nonconstant, ...
    'paperCase1BerChangesMinus22ToMinus21',paperCase1BerChanges, ...
    'case2StageBerReachesOneEminusFive',reachesOneEminusFive, ...
    'case1Pass',all(case1NotWorseHuang,'all') && ...
        all(case1BetterPaper,'all'), ...
    'case2Pass',all(case2StrictBoth,'all'), ...
    'paperCurvePass',all(paperCase2Trend) && ...
        all(paperCase2Nonconstant) && all(paperCase1BerChanges), ...
    'targetBerPass',all(reachesOneEminusFive), ...
    'zeroErrorFloorRule', ...
        'Strict inequality is replaced by equality only when the compared Case-1 Paper error count is zero.');
gate.overallPass = gate.case1Pass && gate.case2Pass && ...
    gate.paperCurvePass && gate.targetBerPass;
end
