function small=v4RunBCaseAnchorCellV1(root,c,lowP,highP,caseIndex,snrIndex)
cases=[-366 0];snrs=-30:-21;n=200;caseTime=cases(caseIndex);snrDb=snrs(snrIndex);
sourceHash=v4Sha256([v4Sha256(fullfile(root,'src','phy','v4GenerateBCaseAnchorFrame.m')) ...
 v4Sha256(fullfile(root,'src','stage55','v4Stage55DualBootstrapDecodeV30.m'))]);
signature=v4Sha256(sprintf('B-case-anchor-AWGN-v1|source=%s|case=%d|snr=%d|N=200|root=580000000', ...
 sourceHash,caseIndex,snrDb));
folder=fullfile(root,'results','case_anchor_b','B-case-anchor-AWGN-v1', ...
 sprintf('case_%d',caseIndex),sprintf('snr_%+03d',snrDb));
if ~isfolder(folder),mkdir(folder),end
final=fullfile(folder,'formal_cell.mat');checkpoint=fullfile(folder,'checkpoint.mat');
if isfile(final),x=load(final,'cellResult');if strcmp(x.cellResult.signature,signature),small=rmfield(x.cellResult,'packetErrors');jsonPath=fullfile(folder,'formal_cell.json');if ~isfile(jsonPath),write(jsonPath,jsonencode(small,'PrettyPrint',true));end;return,end;error('V4:BCaseAnchorSignature','Final signature mismatch.');end
if isfile(checkpoint),state=v4LoadCheckpoint(checkpoint,signature);else,state=struct('completed',0,'packetErrors',zeros(n,3,4,'uint16'));end
for packetId=state.completed+1:n
 key=struct('planVersion','B-case-anchor-AWGN-v1','phase','formal','track','B-case-anchor', ...
  'channel','AWGN','comparisonMode','case-anchor-controlled','snrDb',snrDb, ...
  'replicateId',packetId,'packetId',packetId,'eventType','paired-frame', ...
  'eventIndex',packetId,'sampleIndex',0);
 ledger=v4EventRandomLedger(580000000,key);frame=v4GenerateBCaseAnchorFrame(c,caseTime,snrDb,ledger);
 pilots=frame.observation.rxPhysical(1:8,:);common=v4CommonBootstrap(pilots,c,SearchStepBins=lowP.searchStepBins);
 robust=v4BIndividualPreambleRate(pilots,c,lowP.searchStepBins);measurement=caseTime+4*c.symbolDurationSec;
 [commonRate,commonState]=v4CrossFrameRateUpdate(struct(),measurement,mean(common.cfoBins),robust.rateBinsPerSec,c,highP);
 [crossBootstrap,crossState,d]=v4Stage55CrossFrameBootstrapUpdate(struct(),pilots,common,measurement,c,lowP); %#ok<ASGLU>
 receivers={v4HuangStaticDecode(frame.observation,common,c), ...
  v4Stage55DualBootstrapDecodeV30(frame.observation,common,crossBootstrap,c,lowP,highP, ...
   CommonRateBinsPerSec=commonRate,CommonHistoryCount=commonState.historyCount, ...
   CrossRateBinsPerSec=d.rateBinsPerSec,CrossHistoryCount=crossState.historyCount), ...
  v4PaperMidambleDecode(frame.observation,common,c,lowP)};
 for method=1:3,m=v4EvaluateFrame(receivers{method},frame.truth,c);state.packetErrors(packetId,method,:)=uint16([m.symbolErrors m.hardBitErrors m.softBitErrors m.packetError]);end
 state.completed=packetId;if mod(packetId,25)==0||packetId==n,v4WriteCheckpointAtomic(checkpoint,state,signature);end
end
orbit=v4TrackAOrbit([caseTime-.01;caseTime;caseTime+.01],c);rateHzPerSec=(orbit.dopplerHz(3)-orbit.dopplerHz(1))/.02;
raw=squeeze(sum(double(state.packetErrors),1));den=repmat([n*112 n*768 n*768 n],3,1);metrics=raw./den;
cellResult=struct('status','PASS','identity','B-case-anchor-AWGN-v1','caseIndex',caseIndex, ...
 'caseStartTimeSec',caseTime,'snrDb',snrDb,'fixedPackets',n,'completedPackets',n, ...
 'signature',signature,'sourceHash',sourceHash,'initialCfoHz',orbit.dopplerHz(2), ...
 'initialCfoBins',orbit.dopplerHz(2)/c.fftBinSpacingHz, ...
 'initialRateHzPerSec',rateHzPerSec,'initialRateBinsPerSec',rateHzPerSec/c.fftBinSpacingHz, ...
 'rawErrors',raw,'denominators',den,'metrics',metrics,'packetErrors',state.packetErrors, ...
 'conditionsFrozen',true,'usesCrossPacketHistory',false);
save(final,'cellResult','-v7.3');small=rmfield(cellResult,'packetErrors');
write(fullfile(folder,'formal_cell.json'),jsonencode(small,'PrettyPrint',true));
end
function write(path,text),f=fopen(path,'w','n','UTF-8');cl=onCleanup(@()fclose(f));fprintf(f,'%s\n',text);clear cl,end
