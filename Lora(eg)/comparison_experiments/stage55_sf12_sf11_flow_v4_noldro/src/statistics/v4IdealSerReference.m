function reference=v4IdealSerReference(root)
%V4IDEALSERREFERENCE Load and verify the read-only Ideal Oracle SER curve.
manifestPath=fullfile(root,'config','ideal_reference_manifest_v1.json');
manifest=jsondecode(fileread(manifestPath));
for index=1:numel(manifest.files)
    if ~strcmp(v4Sha256(manifest.files(index).path), ...
            manifest.files(index).sha256)
        error('V4:IdealReferenceHash','Ideal reference hash mismatch: %s', ...
            manifest.files(index).path);
    end
end
tableData=readtable(manifest.files(1).path);
anchor=logical(tableData.isStage55Anchor);
reference=struct('identity',manifest.identity,'metric','SER', ...
    'snrDb',tableData.snrDb(anchor),'ser',tableData.ser(anchor), ...
    'commonAcrossCases',manifest.commonAcrossCases, ...
    'readOnly',manifest.readOnly,'manifestPath',manifestPath, ...
    'manifestSha256',v4Sha256(manifestPath), ...
    'curveSha256',manifest.files(1).sha256);
end

