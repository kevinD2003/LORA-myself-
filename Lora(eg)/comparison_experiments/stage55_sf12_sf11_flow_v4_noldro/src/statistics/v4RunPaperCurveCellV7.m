function small = v4RunPaperCurveCellV7(root,c,snrIndex)
%V4RUNPAPERCURVECELLV7 Paper-only Case2 formal cell on V6 paired packets.
snrs = -30:-21;n = 200;snrDb = snrs(snrIndex);caseTime = 0;
sourceFiles = { ...
 'src/phy/v4GenerateBCaseAnchorFrame.m', ...
 'src/paper/v4PaperIntegerPointEstimate.m', ...
 'src/paper/v4PaperRefinedPointEstimate.m', ...
 'src/paper/v4PaperLocalResidualEstimate.m', ...
 'src/paper/v4PaperMidamblePointTrendDecodeV3.m', ...
 'src/coding/v4DecodePayload.m', ...
 'src/statistics/v4EvaluateFrame.m', ...
 'src/statistics/v4RunPaperCurveCellV7.m', ...
 'config/sf12NoLdroSf11FlowConfig.m'};
hashText = '';
for k = 1:numel(sourceFiles)
    hashText = [hashText sourceFiles{k} '=' ...
        v4Sha256(fullfile(root,sourceFiles{k})) ';']; %#ok<AGROW>
end
sourceHash = v4Sha256(hashText);
signature = v4Sha256(sprintf( ...
    'B-paper-curve-v7|source=%s|snr=%d|N=200|parentRoot=604000000', ...
    sourceHash,snrDb));
folder = fullfile(root,'results','paper_curve_v7','formal', ...
    sprintf('snr_%+03d',snrDb));
if ~isfolder(folder),mkdir(folder),end
finalPath = fullfile(folder,'formal_cell.mat');
checkpointPath = fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    loaded = load(finalPath,'cellResult');
    if strcmp(loaded.cellResult.signature,signature)
        small = rmfield(loaded.cellResult,'packetErrors');return
    end
    error('V4:PaperCurveV7Signature','Final signature mismatch.');
end
if isfile(checkpointPath)
    state = v4LoadCheckpoint(checkpointPath,signature);
else
    state = struct('completed',0,'packetErrors',zeros(n,3,'uint16'));
end
for packetId = state.completed+1:n
    % Exact V5/V6 paired-packet key: only the Paper receiver is recomputed.
    key = struct('planVersion','B-case-anchor-AWGN-v5', ...
        'phase','formal','track','B-case-anchor','channel','AWGN', ...
        'comparisonMode','case-anchor-controlled','snrDb',snrDb, ...
        'replicateId',packetId,'packetId',packetId, ...
        'eventType','paired-frame','eventIndex',200+snrIndex, ...
        'sampleIndex',0);
    ledger = v4EventRandomLedger(604000000,key);
    frame = v4GenerateBCaseAnchorFrame(c,caseTime,snrDb,ledger);
    paper = v4PaperMidamblePointTrendDecodeV3(frame.observation,c);
    m = v4EvaluateFrame(paper,frame.truth,c);
    state.packetErrors(packetId,:) = uint16( ...
        [m.symbolErrors m.hardBitErrors m.softBitErrors]);
    state.completed = packetId;
    if mod(packetId,25)==0 || packetId==n
        v4WriteCheckpointAtomic(checkpointPath,state,signature);
    end
end
rawErrors = sum(double(state.packetErrors),1);
denominators = [n*112 n*768 n*768];
cellResult = struct('status','PASS','identity','B-paper-curve-v7', ...
    'paperAlgorithmVersion','Paper-Midamble-Point-local-trend-v5', ...
    'caseIndex',2,'caseStartTimeSec',caseTime,'snrDb',snrDb, ...
    'fixedPackets',n,'completedPackets',n,'signature',signature, ...
    'sourceHash',sourceHash,'sourceFiles',{sourceFiles}, ...
    'rawErrors',rawErrors,'denominators',denominators, ...
    'metrics',rawErrors./denominators,'packetErrors',state.packetErrors, ...
    'parentIdentity','B-case-anchor-AWGN-v6-known-case-profile', ...
    'parentSeedRoot',604000000,'pairedPacketKeysReused',true, ...
    'stage55Recomputed',false,'stage55Modified',false, ...
    'conditionsFrozen',true,'usesPayloadTruthForSelection',false, ...
    'usesOrbitTruthForSelection',false);
save(finalPath,'cellResult','-v7.3');
small = rmfield(cellResult,'packetErrors');
file = fopen(fullfile(folder,'formal_cell.json'),'w','n','UTF-8');
cleaner = onCleanup(@()fclose(file));
fprintf(file,'%s\n',jsonencode(small,'PrettyPrint',true));clear cleaner
end
