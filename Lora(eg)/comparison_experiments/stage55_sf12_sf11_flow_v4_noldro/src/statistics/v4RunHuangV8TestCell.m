function result=v4RunHuangV8TestCell(caseIndex,snrIndex)
%V4RUNHUANGV8TESTCELL Fixed 1000-packet frozen Huang cell.
root=v4SetupPaths();c=sf12NoLdroSf11FlowConfig();snrs=-30:-21;
cases=[-366 0];n=1000;snrDb=snrs(snrIndex);
sourceFiles={'src/stage55/v4HuangPrecUnifiedDecodeV8.m', ...
    'src/stage55/v4HuangPrecDecodeV3.m', ...
    'src/stage55/v4HuangStaticDecode.m', ...
    'src/stage55/v4Stage55ObservableModeSelectorV10.m', ...
    'src/stage55/v4Stage55PreambleRegimeClassifier.m', ...
    'src/phy/v4CommonBootstrap.m', ...
    'src/phy/v4BootstrapJointPhaseEstimate.m', ...
    'src/phy/v4BootstrapStateAtSymbol.m', ...
    'src/phy/v4CompensateSymbol.m','src/coding/v4DecodePayload.m', ...
    'src/phy/v4GenerateBCaseAnchorFrame.m', ...
    'config/v4LoadMethodAlignedParametersV1.m', ...
    'config/v4LoadMethodAlignedR3ParametersV1.m', ...
    'config/method_aligned_r3_selected_parameters_v1.json', ...
    'config/method_aligned_selected_parameters_v1.json', ...
    'config/sf12NoLdroSf11FlowConfig.m'};
hashText='';
for k=1:numel(sourceFiles)
    hashText=[hashText sourceFiles{k} '=' ...
        v4Sha256(fullfile(root,sourceFiles{k})) ';']; %#ok<AGROW>
end
sourceHash=v4Sha256(hashText);
signature=v4Sha256(sprintf( ...
    'huang-v8-test|source=%s|case=%d|snr=%d|N=%d|seed=884000000', ...
    sourceHash,caseIndex,snrDb,n));
folder=fullfile(root,'results','method_aligned','huang_v8_test', ...
    sprintf('case%d',caseIndex),sprintf('snr_%+03d',snrDb));
if ~isfolder(folder),mkdir(folder),end
finalPath=fullfile(folder,'test_cell.mat');
checkpoint=fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    x=load(finalPath,'result');
    if strcmp(x.result.signature,signature),result=x.result;return,end
    error('V4:HuangV8TestSignature','Existing test signature mismatch.');
end
if isfile(checkpoint)
    state=v4LoadCheckpoint(checkpoint,signature);
else
    state=struct('completed',0,'packetErrors',zeros(n,2,'uint16'), ...
        'staticSelected',false(n,1));
end
for packetId=state.completed+1:n
    key=struct('planVersion','unified-v16-test','phase','paired-grid', ...
        'track','B-method-aligned','channel','AWGN', ...
        'comparisonMode','case-anchor-controlled','snrDb',snrDb, ...
        'replicateId',packetId,'packetId',packetId, ...
        'eventType','paired-frame','eventIndex',caseIndex*100+snrIndex, ...
        'sampleIndex',0);
    ledger=v4EventRandomLedger(884000000,key);
    frame=v4GenerateBCaseAnchorFrame(c,cases(caseIndex),snrDb,ledger);
    huang=v4HuangPrecUnifiedDecodeV8(frame.observation,c);
    state.packetErrors(packetId,:)=[sum(huang.detectedPhysicalBins~= ...
        frame.truth.payloadPhysicalBins),sum(huang.hardDecodedDataBits(:)~= ...
        frame.truth.dataBits(:))];
    state.staticSelected(packetId)=huang.modeEvidence.staticSelected;
    state.completed=packetId;
    if mod(packetId,25)==0||packetId==n
        v4WriteCheckpointAtomic(checkpoint,state,signature);
        fprintf('Huang V8 test Case %d SNR %g: %d/%d\n', ...
            caseIndex,snrDb,packetId,n);
    end
end
raw=sum(double(state.packetErrors),1);den=[n*112 n*768];
result=struct('status','COMPLETE','identity','huang-v8-test', ...
    'methodId','huang-prec-unified-v8', ...
    'algorithmVersion','Huang-PREC-frozen-project-continuous-phase-v8', ...
    'caseIndex',caseIndex,'caseStartTimeSec',cases(caseIndex), ...
    'snrDb',snrDb,'fixedPackets',n,'signature',signature, ...
    'sourceHash',sourceHash,'sourceFiles',{sourceFiles}, ...
    'rawErrors',raw,'denominators',den,'metrics',raw./den, ...
    'packetErrors',state.packetErrors, ...
    'staticSelectedPackets',sum(state.staticSelected), ...
    'dynamicSelectedPackets',sum(~state.staticSelected), ...
    'mlBerComputed',false,'conditionsFrozen',true, ...
    'pairedWithUnifiedV16',true);
save(finalPath,'result','-v7.3');small=rmfield(result,'packetErrors');
file=fopen(fullfile(folder,'test_cell.json'),'w','n','UTF-8');
cleaner=onCleanup(@()fclose(file));fprintf(file,'%s\n', ...
    jsonencode(small,'PrettyPrint',true));clear cleaner
end
