function candidate=v4TrackACandidate(dataIndex,row,centerTime,availableTime, ...
        predictedCfo,likelihood,residual,parameters)
%V4TRACKACANDIDATE Freeze one receiver-visible candidate exactly once.
quality=v4TrackASymbolQuality(likelihood,residual,parameters);
candidate=struct('candidateId',dataIndex,'dataIndex',dataIndex,'physicalRow',row, ...
    'hardLabel',likelihood.physicalBin,'measurementTimeSec',centerTime, ...
    'decisionAtSec',availableTime,'availableAtSec',availableTime, ...
    'cfoCandidateBins',predictedCfo+residual.offsetBins, ...
    'predictedCfoBins',predictedCfo,'peakRatio',quality.peakRatio, ...
    'entropyNormalized',quality.entropyNormalized, ...
    'residualPeakRatio',quality.residualPeakRatio, ...
    'innovationBins',quality.innovationBins,'qualityPassed',quality.accept, ...
    'status','PENDING','rejectionReason','');
end
