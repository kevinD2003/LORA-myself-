function quality = v4TrackASymbolQuality(likelihood,residual,parameters)
%V4TRACKASYMBOLQUALITY Independent symbol-level quality gate (no Hamming).
probability = exp(likelihood.logProbability);
entropyNormalized = -sum(probability.*log(max(probability,realmin)))/log(numel(probability));
quality = struct('peakRatio',likelihood.peakRatio, ...
    'entropyNormalized',entropyNormalized,'residualPeakRatio',residual.peakRatio, ...
    'innovationBins',abs(residual.offsetBins),'residualAtBoundary',residual.peakAtBoundary);
quality.accept = isfinite(entropyNormalized) && ...
    likelihood.peakRatio >= parameters.decisionPeakRatioThreshold && ...
    entropyNormalized <= parameters.maximumNormalizedEntropy && ...
    residual.peakRatio >= parameters.residualPeakRatioThreshold && ...
    abs(residual.offsetBins) <= parameters.innovationLimitBins && ...
    ~residual.peakAtBoundary;
end
