fprintf("Channel: %s\n", channelModel);
fprintf("Doppler-rate profile: %.1f to %.1f Hz/s; PREC step=%.1f bin\n", ...
    min(variableRateProfile), max(variableRateProfile), ...
    cfg.residualSearchOffsets(2) - cfg.residualSearchOffsets(1));

for snrIdx = 1:numel(sampleSnrDb)
    for trialIdx = 1:trialsPerSnr(snrIdx)
        trueBins = generateCodedFrameBins( ...
            cfg, frameSymbolCount, confidenceCfg);
        rxSymbols = generateDopplerLoRaSymbols( ...
            trueBins, cfg.sf, variableCfoBins, sampleSnrDb(snrIdx));
