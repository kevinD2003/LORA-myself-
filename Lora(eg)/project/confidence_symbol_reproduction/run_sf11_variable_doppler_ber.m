symbolDurationSeconds = 2 ^ cfg.sf / bandwidthHz;
binSpacingHz = bandwidthHz / (2 ^ cfg.sf);
symbolIndex = (1:frameSymbolCount).';

% The BER experiment uses a nonconstant rate over the frame (250...750 Hz/s).
variableRateProfile = 500 + 250 * sin( ...
    2 * pi * (symbolIndex - 1) / (frameSymbolCount - 1));
[variableCfoBins, variableDopplerHz, symbolTimeSeconds] = ...
    buildDopplerCfoTrajectory(frameSymbolCount, cfg.sf, bandwidthHz, ...
    initialDopplerHz, variableRateProfile);

% This constant-rate case is retained only to validate the supplied figure.
referenceRateHzPerSecond = 500;
[referenceCfoBins, referenceDopplerHz] = ...
    buildDopplerCfoTrajectory(frameSymbolCount, cfg.sf, bandwidthHz, ...
    initialDopplerHz, referenceRateHzPerSecond);
halfBinBoundary = find(referenceCfoBins >= 0.5, 1, "first");

sampleSnrDb = (-23:1:-15).';
trialsPerSnr = 120 * ones(size(sampleSnrDb));
trialsPerSnr(end) = 600;
