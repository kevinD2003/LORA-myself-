function [detectedSets, confidenceSummary] = ...
    demodulateConfidenceDrivenMethods( ...
    rxSymbols, trueBins, trueCfoBins, cfg, confidenceCfg)
numSymbols = numel(trueBins);
payloadRange = (cfg.bootstrapPilotCount + 1):numSymbols;

% Iterate compensation and confidence extraction as in paper Algorithm 2.
confidencePilotMask = false(numSymbols, 1);
confidenceDriven = [];
for iterationIdx = 1:confidenceCfg.maxIterations
    iterationPrediction = predictiveDopplerCompensate( ...
        rxSymbols, trueBins, cfg, confidencePilotMask);
    if iterationIdx == 1
        pilotOnly = iterationPrediction;
    end
    [~, ~, iterationSpectra] = hardDemodLoRaWithCfo( ...
        iterationPrediction.compensatedSymbols, cfg.sf, 0);
    confidenceResult = detectContinuousSymbolSequence( ...
        iterationSpectra(payloadRange, :), ...
        iterationSpectra(1:cfg.bootstrapPilotCount, :), ...
        confidenceCfg, trueBins(payloadRange));

    nextMask = confidencePilotMask;
    nextMask(payloadRange) = nextMask(payloadRange) | ...
        confidenceResult.confidentFlag;
    if isequal(nextMask, confidencePilotMask)
        confidenceDriven = iterationPrediction;
        break;
    end
    confidencePilotMask = nextMask;
end
if isempty(confidenceDriven)
    confidenceDriven = predictiveDopplerCompensate( ...
        rxSymbols, trueBins, cfg, confidencePilotMask);
end

oracleUpperBound = predictiveDopplerCompensate(rxSymbols, trueBins, cfg);
noCompBins = hardDemodLoRaWithCfo( ...
    rxSymbols, cfg.sf, zeros(numSymbols, 1));
staticBins = hardDemodLoRaWithCfo( ...
    rxSymbols, cfg.sf, pilotOnly.staticCfoEstimate);
idealBins = hardDemodLoRaWithCfo(rxSymbols, cfg.sf, trueCfoBins);

detectedSets = {noCompBins, staticBins, ...
    confidenceDriven.detectedBins, oracleUpperBound.detectedBins, idealBins};
confidenceSummary = struct();
selectedPayload = confidencePilotMask(payloadRange);
selectedCorrect = selectedPayload & ...
    confidenceDriven.detectedBins(payloadRange) == trueBins(payloadRange);
confidenceSummary.numConfident = sum(selectedPayload);
confidenceSummary.numAcceptedCorrect = sum(selectedCorrect);
confidenceSummary.numFalseAccept = sum(selectedPayload & ~selectedCorrect);
confidenceSummary.numReady = sum(confidenceResult.confidenceReadyFlag);
end

function detectedSets = demodulateUpperBoundMethods( ...
    rxSymbols, trueBins, trueCfoBins, cfg)
predictive = predictiveDopplerCompensate(rxSymbols, trueBins, cfg);
numSymbols = numel(trueBins);
noCompBins = hardDemodLoRaWithCfo( ...
    rxSymbols, cfg.sf, zeros(numSymbols, 1));
staticBins = hardDemodLoRaWithCfo( ...
    rxSymbols, cfg.sf, predictive.staticCfoEstimate);
idealBins = hardDemodLoRaWithCfo(rxSymbols, cfg.sf, trueCfoBins);
detectedSets = {noCompBins, staticBins, predictive.detectedBins, idealBins};
end

function trueBins = generateCodedFrameBins(cfg, numSymbols, confidenceCfg)
payloadCount = numSymbols - cfg.bootstrapPilotCount;
blockSize = 4 + cfg.cr;
numBlocks = ceil(payloadCount / blockSize);
payloadBins = zeros(numBlocks * blockSize, 1);

for blockIdx = 1:numBlocks
    blockRange = (blockIdx - 1) * blockSize + (1:blockSize);
    payloadBins(blockRange) = nibblesToDemoBins( ...
        randi([0 15], cfg.sf, 1), confidenceCfg);
end

trueBins = [zeros(cfg.bootstrapPilotCount, 1); ...
    payloadBins(1:payloadCount)];
end

function [rawSer, rawBer] = calculateNoiseFreeRawTheory( ...
    normalizedCfo, sf, grayBits)
numBins = 2 ^ sf;
allBins = (0:(numBins - 1)).';
rawSer = zeros(size(normalizedCfo));
rawBer = zeros(size(normalizedCfo));

for symbolIdx = 1:numel(normalizedCfo)
    binShift = round(normalizedCfo(symbolIdx));
    rawSer(symbolIdx) = binShift ~= 0;
    shiftedBins = mod(allBins + binShift, numBins);
    bitErrors = sum(xor(grayBits, grayBits(shiftedBins + 1, :)), 2);
    rawBer(symbolIdx) = mean(bitErrors) / sf;
end
end
