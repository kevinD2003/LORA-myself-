function trajectory = senloraOrbitDopplerTrajectory(timeSec, config)
%SENLORAORBITDOPPLERTRAJECTORY Evaluate shift and rate from orbit geometry.

arguments
    timeSec double
    config (1, 1) struct
end

if any(~isfinite(timeSec), "all")
    error("SenLoRa:InvalidTrajectoryTime", "All times must be finite.");
end
originalSize = size(timeSec);
timeSec = timeSec(:);
orbitRadiusM = config.earthRadiusM + config.orbitHeightM;
omegaSatellite = sqrt(config.gravityMps2*config.earthRadiusM^2/orbitRadiusM^3);
omegaFixed = omegaSatellite - ...
    config.earthRotationRadPerSec*cos(config.inclinationRad);
radiusRatio = config.earthRadiusM/orbitRadiusM;
gammaCentral = acos(radiusRatio*cos(config.theoreticalMaxElevationRad)) - ...
    config.theoreticalMaxElevationRad;
phaseRad = omegaFixed*(timeSec-config.centralVisibilityTimeSec);
cosGamma = cos(gammaCentral)*cos(phaseRad);
cosGamma = min(1, max(-1, cosGamma));
gammaRad = acos(cosGamma);
slantRangeM = sqrt(orbitRadiusM^2+config.earthRadiusM^2- ...
    2*config.earthRadiusM*orbitRadiusM.*cosGamma);
velocityScale = config.earthRadiusM*orbitRadiusM*cos(gammaCentral)*omegaFixed;
radialVelocityMps = velocityScale*sin(phaseRad)./slantRangeM;
radialAccelerationMps2 = velocityScale*( ...
    omegaFixed*cos(phaseRad)./slantRangeM - ...
    sin(phaseRad).*radialVelocityMps./slantRangeM.^2);
dopplerShiftHz = -config.carrierFrequencyHz*radialVelocityMps/config.speedOfLightMps;
dopplerRateHzPerSec = -config.carrierFrequencyHz*radialAccelerationMps2/config.speedOfLightMps;
elevationRad = atan2(orbitRadiusM*cosGamma-config.earthRadiusM, ...
    orbitRadiusM*sin(gammaRad));

trajectory = struct( ...
    "timeSec", reshape(timeSec, originalSize), ...
    "centralAngleRad", reshape(gammaRad, originalSize), ...
    "elevationRad", reshape(elevationRad, originalSize), ...
    "slantRangeM", reshape(slantRangeM, originalSize), ...
    "radialVelocityMps", reshape(radialVelocityMps, originalSize), ...
    "radialAccelerationMps2", reshape(radialAccelerationMps2, originalSize), ...
    "dopplerShiftHz", reshape(dopplerShiftHz, originalSize), ...
    "dopplerRateHzPerSec", reshape(dopplerRateHzPerSec, originalSize), ...
    "omegaFixedRadPerSec", omegaFixed);
end
