function summary = run_senlora_virtual_pilot_demo()
%RUNSENLORA VIRTUAL PILOT DEMO Validate trajectory tracking without truth input.
%
% This stage exercises the tracker with three externally supplied previous
% confidence masks: bootstrap-only, intermittent, and an oracle accepted
% mask. The tracker itself never reads the payload symbol truth.

rootFolder = fileparts(mfilename("fullpath"));
resultFolder = fullfile(rootFolder, "results", "virtual_pilot_tracker");
if ~isfolder(resultFolder)
    mkdir(resultFolder);
end

config = senloraChannelConfig();
numSymbols = config.frameSymbolCount;
payloadBins = mod((1:config.payloadSymbolCount).'*37 + 11, ...
    config.spreadingFactorSamples);
symbolBins = [zeros(config.bootstrapPilotCount,1); payloadBins];

maskBootstrap = false(numSymbols,1);
maskBootstrap(1:config.bootstrapPilotCount) = true;
maskIntermittent = maskBootstrap;
maskIntermittent((config.bootstrapPilotCount+1):end) = ...
    mod((config.bootstrapPilotCount+1:numSymbols).', 3) ~= 0;
maskAllAccepted = true(numSymbols,1);

scenarioCount = numel(config.scenarios);
scenarioSummary = repmat(struct(), scenarioCount, 1);
figureHandle = figure("Visible","off", "Color","w", ...
    "Position",[80,80,1500,980]);
layout = tiledlayout(2, scenarioCount, "TileSpacing","compact", ...
    "Padding","compact");

for scenarioIdx = 1:scenarioCount
    scenario = config.scenarios(scenarioIdx);
    [rxSymbols, ~, truth] = generateSenLoRaOrbitFrame( ...
        symbolBins, config, StartTimeSec=scenario.startTimeSec, ...
        SampleSnrDb=60, NoiseSeed=config.randomSeedNoise+scenarioIdx);

    staticResult = trackSenLoRaVirtualPilots( ...
        rxSymbols, config, zeros(config.bootstrapPilotCount,1), maskBootstrap);
    intermittentResult = trackSenLoRaVirtualPilots( ...
        rxSymbols, config, zeros(config.bootstrapPilotCount,1), ...
        maskIntermittent);
    dynamicResult = trackSenLoRaVirtualPilots( ...
        rxSymbols, config, zeros(config.bootstrapPilotCount,1), ...
        maskAllAccepted);

    symbolTimeSec = truth.symbolStartTimeSec + config.symbolDurationSec/2;
    cfoTruthBins = truth.trueCfoBins;
    rateTruthHzPerSec = truth.trueDopplerRateHzPerSec;

    nexttile(layout, scenarioIdx);
    plot(symbolTimeSec, cfoTruthBins, "k-", "LineWidth",1.7); hold on;
    plot(symbolTimeSec, staticResult.predictedCfoBins, "Color",[0.45 0.45 0.45], ...
        "LineStyle","--", "LineWidth",1.2);
    plot(symbolTimeSec, intermittentResult.predictedCfoBins, "b-.", ...
        "LineWidth",1.2);
    plot(symbolTimeSec, dynamicResult.predictedCfoBins, "r-", ...
        "LineWidth",1.2);
    xline(symbolTimeSec(config.bootstrapPilotCount), ":", "Color",[0.2 0.2 0.2]);
    grid on; box on;
    xlabel("Symbol-center time (s)");
    ylabel("Carrier CFO (bin)");
    title(sprintf("%s: CFO prediction", strrep(scenario.name,"_"," ")));
    if scenarioIdx == 1
        legend("trajectory truth","bootstrap only","intermittent mask", ...
            "all requested updates","bootstrap boundary", ...
            "Location","best");
    end

    nexttile(layout, scenarioIdx + scenarioCount);
    plot(symbolTimeSec, rateTruthHzPerSec, "k-", "LineWidth",1.7); hold on;
    plot(symbolTimeSec, staticResult.predictedRateHzPerSec, ...
        "Color",[0.45 0.45 0.45], "LineStyle","--", "LineWidth",1.2);
    plot(symbolTimeSec, intermittentResult.predictedRateHzPerSec, ...
        "b-.", "LineWidth",1.2);
    plot(symbolTimeSec, dynamicResult.predictedRateHzPerSec, ...
        "r-", "LineWidth",1.2);
    yyaxis right
    stairs(symbolTimeSec, dynamicResult.pilotCount, "m:", "LineWidth",1.2);
    ylabel("Accepted pilot count");
    yyaxis left
    xline(symbolTimeSec(config.bootstrapPilotCount), ":", ...
        "Color",[0.2 0.2 0.2]);
    grid on; box on;
    xlabel("Symbol-center time (s)");
    ylabel("Doppler rate (Hz/s)");
    title(sprintf("%s: rate and pilot history", strrep(scenario.name,"_"," ")));

    scenarioSummary(scenarioIdx).name = scenario.name;
    scenarioSummary(scenarioIdx).startTimeSec = scenario.startTimeSec;
    scenarioSummary(scenarioIdx).truthCfoBins = cfoTruthBins;
    scenarioSummary(scenarioIdx).truthRateHzPerSec = rateTruthHzPerSec;
    scenarioSummary(scenarioIdx).bootstrapOnlyPilotCount = ...
        staticResult.pilotCount(end);
    scenarioSummary(scenarioIdx).intermittentRequestedCount = ...
        sum(maskIntermittent(config.bootstrapPilotCount+1:end));
    scenarioSummary(scenarioIdx).intermittentAcceptedCount = ...
        sum(intermittentResult.pilotUpdateFlag(config.bootstrapPilotCount+1:end));
    scenarioSummary(scenarioIdx).allRequestedCount = ...
        sum(maskAllAccepted(config.bootstrapPilotCount+1:end));
    scenarioSummary(scenarioIdx).allAcceptedCount = ...
        sum(dynamicResult.pilotUpdateFlag(config.bootstrapPilotCount+1:end));
    scenarioSummary(scenarioIdx).bootstrapOnlySymbolErrors = ...
        sum(staticResult.detectedBins ~= symbolBins);
    scenarioSummary(scenarioIdx).intermittentSymbolErrors = ...
        sum(intermittentResult.detectedBins ~= symbolBins);
    scenarioSummary(scenarioIdx).allAcceptedSymbolErrors = ...
        sum(dynamicResult.detectedBins ~= symbolBins);
    scenarioSummary(scenarioIdx).bootstrapOnlyDetectedBins = ...
        staticResult.detectedBins;
    scenarioSummary(scenarioIdx).intermittentDetectedBins = ...
        intermittentResult.detectedBins;
    scenarioSummary(scenarioIdx).allAcceptedDetectedBins = ...
        dynamicResult.detectedBins;
    scenarioSummary(scenarioIdx).allAcceptedResidualPeakRatio = ...
        dynamicResult.residualPeakRatio;
    scenarioSummary(scenarioIdx).allAcceptedPredictedRateHzPerSec = ...
        dynamicResult.predictedRateHzPerSec;
    scenarioSummary(scenarioIdx).allAcceptedMeasuredCfoBins = ...
        dynamicResult.measuredCfoBins;
    scenarioSummary(scenarioIdx).allAcceptedMeasuredResidualBins = ...
        dynamicResult.measuredResidualBins;
    scenarioSummary(scenarioIdx).maxAllAcceptedCfoPredictionErrorBins = ...
        max(abs(dynamicResult.predictedCfoBins( ...
        config.bootstrapPilotCount+1:end)-cfoTruthBins( ...
        config.bootstrapPilotCount+1:end)));
    scenarioSummary(scenarioIdx).maxAllAcceptedRatePredictionErrorHzPerSec = ...
        max(abs(dynamicResult.predictedRateHzPerSec( ...
        config.bootstrapPilotCount+1:end)-rateTruthHzPerSec( ...
        config.bootstrapPilotCount+1:end)));
end

title(layout, "Virtual-pilot tracker diagnostic (SF11, paper piecewise-linear orbit)");
exportgraphics(figureHandle, fullfile(resultFolder, ...
    "virtual_pilot_tracker.png"), "Resolution",180);
close(figureHandle);

summary = struct( ...
    "folder", resultFolder, ...
    "config", config, ...
    "scenario", scenarioSummary, ...
    "symbolBins", symbolBins, ...
    "note", "Masks are controlled tracker diagnostics; SenLoRa confidence generation is the next stage.");
fid = fopen(fullfile(resultFolder, "virtual_pilot_tracker_metadata.json"), "w");
if fid < 0
    error("SenLoRa:MetadataOpenFailed", "Could not create tracker metadata.");
end
cleanup = onCleanup(@() fclose(fid));
fwrite(fid, jsonencode(summary), "char");
end
