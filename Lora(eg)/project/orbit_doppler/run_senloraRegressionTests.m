function report = run_senloraRegressionTests()
%RUNSENLORAREGRESSIONTESTS Check orbit constants, phase continuity, and masks.

rootFolder = fileparts(mfilename("fullpath"));
resultFolder = fullfile(rootFolder,"results","regression_tests");
if ~isfolder(resultFolder)
    mkdir(resultFolder);
end
config = senloraChannelConfig();
window = senloraVisibilityWindow(config.orbit);
regressionStream = RandStream("mt19937ar","Seed",20260804);
payloadBins = senloraGenerateCodedPayloadBins(config,regressionStream);
symbolBins = [zeros(config.bootstrapPilotCount,1);payloadBins];

scenarioReport = repmat(struct(),numel(config.scenarios),1);
maxBoundaryResidual = 0;
maxResidualEstimate = 0;
for scenarioIdx = 1:numel(config.scenarios)
    scenario = config.scenarios(scenarioIdx);
    [rxSymbols,~,truth] = generateSenLoRaOrbitFrame( ...
        symbolBins,config,StartTimeSec=scenario.startTimeSec, ...
        SampleSnrDb=60,NoiseSeed=9000+scenarioIdx);
    boundaryResidual = truth.phaseRad(2:end,1) - ...
        (truth.phaseRad(1:end-1,end) + pi/config.sampleRateHz * ...
        (truth.dopplerHz(1:end-1,end)+truth.dopplerHz(2:end,1)));
    maxBoundaryResidual = max(maxBoundaryResidual,max(abs(boundaryResidual)));
    tracker = trackSenLoRaVirtualPilots( ...
        rxSymbols,config,zeros(config.bootstrapPilotCount,1), ...
        true(config.frameSymbolCount,1));
    residualMask = tracker.pilotUpdateFlag & ...
        ((1:config.frameSymbolCount).' > config.bootstrapPilotCount);
    if any(residualMask)
        maxResidualEstimate = max(maxResidualEstimate, ...
            max(abs(tracker.measuredResidualBins(residualMask))));
    end
    bootstrapOnly = false(config.frameSymbolCount,1);
    bootstrapOnly(1:config.bootstrapPilotCount) = true;
    noUpdate = trackSenLoRaVirtualPilots( ...
        rxSymbols,config,zeros(config.bootstrapPilotCount,1),bootstrapOnly);
    scenarioReport(scenarioIdx).name = scenario.name;
    scenarioReport(scenarioIdx).boundaryResidualRad = max(abs(boundaryResidual));
    scenarioReport(scenarioIdx).bootstrapPilotCount = ...
        sum(noUpdate.pilotUpdateFlag);
    scenarioReport(scenarioIdx).fifthSymbolAutomaticallyAccepted = ...
        noUpdate.pilotUpdateFlag(config.bootstrapPilotCount+1);
    scenarioReport(scenarioIdx).allAcceptedPilotCount = ...
        sum(tracker.pilotUpdateFlag);
    scenarioReport(scenarioIdx).dynamicConfidenceCountAt0Db = NaN;
end

% Deterministic receiver-output check: changing only an evaluation-side
% copy of the payload vector cannot affect the receiver call.
[rxCheck,~,~] = generateSenLoRaOrbitFrame(symbolBins,config, ...
    StartTimeSec=config.scenarios(1).startTimeSec, ...
    SampleSnrDb=0,NoiseSeed=9988);
first = senloraDynamicConfidenceIteration( ...
    rxCheck,config,zeros(config.bootstrapPilotCount,1));
second = senloraDynamicConfidenceIteration( ...
    rxCheck,config,zeros(config.bootstrapPilotCount,1));
receiverDeterministic = isequal(first.detectedBins,second.detectedBins) && ...
    isequal(first.finalMask,second.finalMask);
payloadRows = (config.bootstrapPilotCount+1):config.frameSymbolCount;
bootstrapRows = 1:config.bootstrapPilotCount;
payloadConfidenceCoveragePass = ...
    all(first.confidenceReadyFlag(payloadRows));
bootstrapExcludedFromHammingPass = ...
    ~any(first.confidenceReadyFlag(bootstrapRows));

% Reproduce the former low-SNR bootstrap peak jump.  Pilot four used to
% lock to +256.27 bins although the true CFO was about -58.20 bins.
stressScenario = config.scenarios(2);
stressStream = RandStream("mt19937ar","Seed",102);
stressPayload = randi(stressStream, ...
    [0,config.spreadingFactorSamples-1],config.payloadSymbolCount,1);
stressSymbols = [zeros(config.bootstrapPilotCount,1);double(stressPayload)];
[stressRx,~,stressTruth] = generateSenLoRaOrbitFrame( ...
    stressSymbols,config,StartTimeSec=stressScenario.startTimeSec, ...
    SampleSnrDb=-20,NoiseSeed=202);
stressEstimate = senloraEstimateBootstrapPilots( ...
    stressRx(1:config.bootstrapPilotCount,:), ...
    zeros(config.bootstrapPilotCount,1),config.sf);
stressTrueBins = stressTruth.effectiveDopplerHz( ...
    1:config.bootstrapPilotCount)/config.fftBinSpacingHz;
bootstrapStressMaxErrorBins = max(abs( ...
    stressEstimate.cfoBins-stressTrueBins));

report = struct( ...
    "folder",resultFolder, ...
    "orbitConfig",config.orbit, ...
    "payloadCoding","Hamming block plus transpose interleaver for confidence only", ...
    "visibilityWindow",window, ...
    "scenario",scenarioReport, ...
    "maxContinuousPhaseBoundaryResidualRad",maxBoundaryResidual, ...
    "maxAcceptedResidualEstimateBins",maxResidualEstimate, ...
    "receiverDeterministicWithoutTruth",receiverDeterministic, ...
    "payloadConfidenceCoveragePass",payloadConfidenceCoveragePass, ...
    "bootstrapExcludedFromHammingPass",bootstrapExcludedFromHammingPass, ...
    "bootstrapStressMaxErrorBins",bootstrapStressMaxErrorBins, ...
    "bootstrapStressPass",bootstrapStressMaxErrorBins < 0.5, ...
    "phaseBoundaryPass",maxBoundaryResidual < 1e-10, ...
    "residualPass",maxResidualEstimate < 0.02, ...
    "fifthSymbolNotAutomaticPass",all(~[scenarioReport.fifthSymbolAutomaticallyAccepted]), ...
    "note","Truth is used only for residual evaluation and never passed to receiver functions.");
fid = fopen(fullfile(resultFolder,"regression_metadata.json"),"w");
if fid < 0
    error("SenLoRa:RegressionMetadataOpenFailed","Could not write regression metadata.");
end
cleanup = onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(report),"char");
end
