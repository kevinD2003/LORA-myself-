function outputs = run_senlora_continuous_orbit_demo(options)
%RUN_SENLORA_CONTINUOUSORBITDEMO Generate stage-2 frame diagnostics.

arguments
    options.OutputDirectory (1,1) string = string(fullfile( ...
        fileparts(mfilename("fullpath")), "results", "continuous_frame"))
    options.SampleSnrDb (1,1) double = -15
end

if ~isfolder(options.OutputDirectory)
    mkdir(options.OutputDirectory);
end
config = senloraChannelConfig();
rng(config.randomSeedSymbols, "twister");
payloadBins = randi([0, 2^config.sf-1], config.payloadSymbolCount, 1);
symbolBins = [zeros(config.bootstrapPilotCount, 1); payloadBins];

numScenarios = numel(config.scenarios);
frameResults = cell(numScenarios, 1);
for scenarioIdx = 1:numScenarios
    scenario = config.scenarios(scenarioIdx);
    [rxSymbols, txSymbols, truth] = generateSenLoRaOrbitFrame( ...
        symbolBins, config, StartTimeSec=scenario.startTimeSec, ...
        SampleSnrDb=options.SampleSnrDb, Model=config.dopplerModel, ...
        NoiseSeed=config.randomSeedNoise+scenarioIdx);
    if ~all(truth.visibleSampleMask, "all")
        error("SenLoRa:FrameOutsideVisibility", ...
            "The generated frame leaves the selected visible interval.");
    end
    frameResults{scenarioIdx} = struct( ...
        "name", scenario.name, "rxSymbols", rxSymbols, ...
        "txSymbols", txSymbols, "truth", truth);
end

figureFrame = figure("Visible", "off", "Color", "w", ...
    "Position", [100 80 1260 850]);
layout = tiledlayout(numScenarios, 2, ...
    "TileSpacing", "compact", "Padding", "compact");
for scenarioIdx = 1:numScenarios
    item = frameResults{scenarioIdx};
    truth = item.truth;
    centerIndex = floor(config.spreadingFactorSamples/2)+1;
    relativeTimeMs = (truth.sampleTimeSec(:, centerIndex) ...
        - truth.startTimeSec)*1e3;
    nexttile;
    yyaxis left;
    plot(relativeTimeMs, truth.trueDopplerHz/1e3, "o-", ...
        "Color", [0.10 0.36 0.80], "LineWidth", 1.2, ...
        "MarkerSize", 3, "DisplayName", "Doppler shift");
    ylabel("Doppler shift (kHz)");
    yyaxis right;
    plot(relativeTimeMs, truth.trueDopplerRateHzPerSec, "s--", ...
        "Color", [0.85 0.25 0.08], "LineWidth", 1.1, ...
        "MarkerSize", 3, "DisplayName", "Doppler rate");
    ylabel("Doppler rate (Hz/s)");
    grid on;
    xlabel("Time from frame start (ms)");
    title(sprintf("%s: continuous dynamic Doppler", item.name), ...
        "Interpreter", "none");
    if scenarioIdx == 1
        legend("Location", "best");
    end

    nexttile;
    plot(1:config.frameSymbolCount, truth.phaseStartRad/(2*pi), "o-", ...
        "Color", [0.52 0.20 0.72], "LineWidth", 1.2, ...
        "MarkerSize", 3);
    grid on;
    xlabel("Frame symbol index");
    ylabel("Cumulative phase start (cycles)");
    title(sprintf("phase continuity; final start %.3g cycles", ...
        truth.phaseStartRad(end)/(2*pi)));
end
title(layout, sprintf('Single-device orbit channel, SF=%d, BW=%.0f kHz, sample SNR=%g dB', ...
    config.sf, config.bandwidthHz/1e3, options.SampleSnrDb));
figureFile = fullfile(options.OutputDirectory, "continuous_frame_doppler.png");
exportgraphics(figureFrame, figureFile, "Resolution", 180);
close(figureFrame);

metadata = struct( ...
    "sf", config.sf, "bandwidthHz", config.bandwidthHz, ...
    "carrierFrequencyHz", config.carrierFrequencyHz, ...
    "sampleSnrDb", options.SampleSnrDb, ...
    "dopplerModel", config.dopplerModel, ...
    "frameSymbolCount", config.frameSymbolCount, ...
    "bootstrapPilotCount", config.bootstrapPilotCount, ...
    "payloadSymbolCount", config.payloadSymbolCount, ...
    "scenarioNames", {string({config.scenarios.name})}, ...
    "startTimesSec", [config.scenarios.startTimeSec]);
metadataFile = fullfile(options.OutputDirectory, "continuous_frame_metadata.json");
fid = fopen(metadataFile, "w", "n", "UTF-8");
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, "%s", jsonencode(metadata));
clear cleanup;

save(fullfile(options.OutputDirectory, "continuous_frame_smoke.mat"), ...
    "config", "symbolBins", "frameResults", "metadata", "-v7.3");
outputs = struct("figure", string(figureFile), ...
    "metadata", string(metadataFile), "mat", string(fullfile( ...
    options.OutputDirectory, "continuous_frame_smoke.mat")), ...
    "config", config, "metadataStruct", metadata);
end
