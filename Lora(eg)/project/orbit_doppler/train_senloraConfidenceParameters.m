function result = train_senloraConfidenceParameters(options)
%TRAIN_SENLORACONFIDENCEPARAMETERS Train and validate adaptive thresholds.
%
% Simulation truth is used only in this offline supervised tuning routine.
% The deployed receiver switches thresholds using its preamble-based SNR
% estimate and never receives the configured SNR or transmitted payload.

arguments
    options.OutputDirectory (1,1) string = ""
    options.TrainingFramesPerPoint (1,1) double {mustBePositive} = 6
    options.ValidationFramesPerPoint (1,1) double {mustBePositive} = 12
    options.SnrDb (:,1) double = [-22;-20;-19;-18;-16]
    options.SwitchSnrDb (1,:) double = [-19.5,-19.0,-18.5]
    options.ThresholdScale (1,:) double = [0.50,0.65,0.80]
    options.DecisionPeakRatio (1,:) double = [1.5,1.8,2.0]
    options.FalseAcceptPenalty (1,1) double {mustBeNonnegative} = 50
    options.LowSnrDegradationPenalty (1,1) double {mustBeNonnegative} = 20
end

rootFolder = fileparts(mfilename("fullpath"));
if strlength(options.OutputDirectory)==0
    outputFolder = fullfile(rootFolder,"results","confidence_training");
else
    outputFolder = char(options.OutputDirectory);
end
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

baseConfig = senloraChannelConfig();
baseConfig.adaptiveConfidenceEnabled = false;
trainingSeed = 240000;
validationSeed = 340000;
baselineTrain = evaluateConfig(baseConfig,options.SnrDb, ...
    options.TrainingFramesPerPoint,trainingSeed);
lowSnrMask = baselineTrain.snrDb <= -20;
baselineLowErrors = sum(baselineTrain.bitErrors(lowSnrMask));

candidateCount = numel(options.SwitchSnrDb)* ...
    numel(options.ThresholdScale)*numel(options.DecisionPeakRatio);
rowTemplate = struct( ...
    "switchSnrDb",NaN, ...
    "thresholdScale",NaN, ...
    "decisionPeakRatio",NaN, ...
    "trainingBitErrors",NaN, ...
    "trainingLowSnrBitErrors",NaN, ...
    "trainingFalseAcceptCount",NaN, ...
    "trainingMeanPayloadPilotCount",NaN, ...
    "trainingScore",NaN);
rows = repmat(rowTemplate,candidateCount,1);
candidateIdx = 0;
for switchSnr = options.SwitchSnrDb
    for thresholdScale = options.ThresholdScale
        for peakRatio = options.DecisionPeakRatio
            candidateIdx = candidateIdx+1;
            candidateConfig = baseConfig;
            candidateConfig.adaptiveConfidenceEnabled = true;
            candidateConfig.adaptiveConfidenceSwitchSnrDb = switchSnr;
            candidateConfig.highSnrConfidenceThresholdScale = thresholdScale;
            candidateConfig.highSnrDecisionPeakRatioThreshold = peakRatio;
            metrics = evaluateConfig(candidateConfig,options.SnrDb, ...
                options.TrainingFramesPerPoint,trainingSeed);
            lowErrors = sum(metrics.bitErrors(lowSnrMask));
            totalErrors = sum(metrics.bitErrors);
            totalFalse = sum(metrics.falseAcceptCount);
            degradation = max(0,lowErrors-baselineLowErrors);
            score = totalErrors + ...
                options.FalseAcceptPenalty*totalFalse + ...
                options.LowSnrDegradationPenalty*degradation;
            rows(candidateIdx) = struct( ...
                "switchSnrDb",switchSnr, ...
                "thresholdScale",thresholdScale, ...
                "decisionPeakRatio",peakRatio, ...
                "trainingBitErrors",totalErrors, ...
                "trainingLowSnrBitErrors",lowErrors, ...
                "trainingFalseAcceptCount",totalFalse, ...
                "trainingMeanPayloadPilotCount", ...
                    mean(metrics.meanPayloadPilotCount), ...
                "trainingScore",score);
        end
    end
end

trainingTable = sortrows(struct2table(rows), ...
    ["trainingScore","trainingFalseAcceptCount","trainingBitErrors"]);
best = trainingTable(1,:);
bestConfig = baseConfig;
bestConfig.adaptiveConfidenceEnabled = true;
bestConfig.adaptiveConfidenceSwitchSnrDb = best.switchSnrDb;
bestConfig.highSnrConfidenceThresholdScale = best.thresholdScale;
bestConfig.highSnrDecisionPeakRatioThreshold = best.decisionPeakRatio;

baselineValidation = evaluateConfig(baseConfig,options.SnrDb, ...
    options.ValidationFramesPerPoint,validationSeed);
bestValidation = evaluateConfig(bestConfig,options.SnrDb, ...
    options.ValidationFramesPerPoint,validationSeed);
validationTable = [addMethodLabel(baselineValidation,"baseline"); ...
    addMethodLabel(bestValidation,"trained_adaptive")];
baselineValidationErrors = sum(baselineValidation.bitErrors);
trainedValidationErrors = sum(bestValidation.bitErrors);
baselineValidationFalse = sum(baselineValidation.falseAcceptCount);
trainedValidationFalse = sum(bestValidation.falseAcceptCount);
validationPass = trainedValidationErrors < baselineValidationErrors && ...
    trainedValidationFalse <= baselineValidationFalse;

writetable(trainingTable,fullfile(outputFolder,"training_grid.csv"));
writetable(validationTable,fullfile(outputFolder,"validation_points.csv"));
save(fullfile(outputFolder,"confidence_training.mat"), ...
    "trainingTable","validationTable","bestConfig","baseConfig", ...
    "options","validationPass");
metadata = struct( ...
    "trainingSeed",trainingSeed, ...
    "validationSeed",validationSeed, ...
    "bestSwitchSnrDb",best.switchSnrDb, ...
    "bestThresholdScale",best.thresholdScale, ...
    "bestDecisionPeakRatio",best.decisionPeakRatio, ...
    "baselineValidationErrors",baselineValidationErrors, ...
    "trainedValidationErrors",trainedValidationErrors, ...
    "baselineValidationFalseAccepts",baselineValidationFalse, ...
    "trainedValidationFalseAccepts",trainedValidationFalse, ...
    "validationPass",validationPass);
fid = fopen(fullfile(outputFolder,"confidence_training.json"),"w");
if fid < 0
    error("SenLoRa:TrainingMetadataOpenFailed", ...
        "Could not write confidence training metadata.");
end
cleanup = onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(metadata),"char");

result = struct( ...
    "folder",outputFolder, ...
    "trainingTable",trainingTable, ...
    "validationTable",validationTable, ...
    "bestConfig",bestConfig, ...
    "validationPass",validationPass, ...
    "metadata",metadata);
end

function metrics = evaluateConfig(config,snrGrid,framesPerPoint,seedBase)
pointCount = numel(config.scenarios)*numel(snrGrid);
scenario = strings(pointCount,1);
snrDb = zeros(pointCount,1);
bitErrors = zeros(pointCount,1);
falseAcceptCount = zeros(pointCount,1);
meanPayloadPilotCount = zeros(pointCount,1);
totalBits = zeros(pointCount,1);
row = 0;
for scenarioIdx = 1:numel(config.scenarios)
    for snrIdx = 1:numel(snrGrid)
        row = row+1;
        symbolStream = RandStream("mt19937ar","Seed", ...
            seedBase+10000*scenarioIdx+100*snrIdx);
        for frameIdx = 1:framesPerPoint
            payloadBins = senloraGenerateCodedPayloadBins(config,symbolStream);
            symbolBins = [zeros(config.bootstrapPilotCount,1);payloadBins];
            [rxSymbols,~,~] = generateSenLoRaOrbitFrame( ...
                symbolBins,config, ...
                StartTimeSec=config.scenarios(scenarioIdx).startTimeSec, ...
                SampleSnrDb=snrGrid(snrIdx), ...
                NoiseSeed=seedBase+100000*scenarioIdx+ ...
                    1000*snrIdx+frameIdx);
            detected = senloraDynamicConfidenceIteration( ...
                rxSymbols,config,zeros(config.bootstrapPilotCount,1));
            payloadRows = (config.bootstrapPilotCount+1):config.frameSymbolCount;
            bitErrors(row) = bitErrors(row)+senloraCountBitErrors( ...
                symbolBins(payloadRows),detected.detectedBins(payloadRows), ...
                config.sf);
            accepted = detected.pilotUpdateFlag(payloadRows);
            falseAcceptCount(row) = falseAcceptCount(row)+sum( ...
                accepted & detected.detectedBins(payloadRows)~= ...
                symbolBins(payloadRows));
            meanPayloadPilotCount(row) = meanPayloadPilotCount(row)+sum(accepted);
        end
        scenario(row) = string(config.scenarios(scenarioIdx).name);
        snrDb(row) = snrGrid(snrIdx);
        totalBits(row) = framesPerPoint*config.payloadSymbolCount*config.sf;
        meanPayloadPilotCount(row) = ...
            meanPayloadPilotCount(row)/framesPerPoint;
    end
end
ber = bitErrors./totalBits;
metrics = table(scenario,snrDb,bitErrors,totalBits,ber, ...
    falseAcceptCount,meanPayloadPilotCount);
end

function labelled = addMethodLabel(metrics,label)
method = repmat(string(label),height(metrics),1);
labelled = addvars(metrics,method,'Before',1);
end
