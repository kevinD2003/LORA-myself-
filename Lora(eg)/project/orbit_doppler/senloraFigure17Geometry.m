function geometry = senloraFigure17Geometry()
%SENLORAFIGURE17GEOMETRY Single-device dynamic Doppler geometry.
%
% This intentionally uses one ground device.  The name is retained so the
% stage-1 demo and later BER runner have a stable interface.

config = senloraOrbitConfig();
window = senloraVisibilityWindow(config);
geometry = struct( ...
    "config", config, ...
    "window", window, ...
    "centralVisibilityTimeSec", config.centralVisibilityTimeSec, ...
    "highShiftTimesSec", [window.intervalsSec(1,1), window.intervalsSec(2,2)], ...
    "highRateTimesSec", [window.intervalsSec(1,2), window.intervalsSec(2,1)], ...
    "highShiftTimeSec", window.intervalsSec(1,1), ...
    "highRateTimeSec", window.intervalsSec(2,1), ...
    "visibleIntervalsSec", window.intervalsSec);
end
