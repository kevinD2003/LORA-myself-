function outputs = runSenLoRaOrbitBer(options)
%RUNSENLORAORBITBER Resumable formal SenLoRa orbit BER entry point.
%
% Default settings follow the requested formal scan: SF11, -30:1:10 dB,
% at least 30800 bits, then 300 bit errors per point or 1e7 bits.  Each checkpoint row records the
% method, common random seeds, raw errors, and exact binomial confidence
% bounds.  No curve fitting or smoothing is performed.

arguments
    options.OutputDirectory (1,1) string = ""
    options.SnrDb (:,1) double = (-30:1:-16).'
    options.TargetBitErrors (1,1) double = 300
    options.MinBitsPerPoint (1,1) double {mustBeNonnegative} = 30800
    options.MaxBitsPerPoint (1,1) double = 1e7
    options.Resume (1,1) logical = true
    options.MaxFramesPerPoint (1,1) double = Inf
end

rootFolder = fileparts(mfilename("fullpath"));
if strlength(options.OutputDirectory) == 0
    resultFolder = fullfile(rootFolder,"results","formal_ber");
else
    resultFolder = char(options.OutputDirectory);
end
if ~isfolder(resultFolder)
    mkdir(resultFolder);
end
config = senloraChannelConfig();
if options.MinBitsPerPoint > options.MaxBitsPerPoint
    error("SenLoRa:InvalidBerBitLimits", ...
        "MinBitsPerPoint must not exceed MaxBitsPerPoint.");
end
methodNames = ["raw","blind_hard","senlora"];
csvPath = fullfile(resultFolder,"senlora_orbit_ber.csv");
pngPath = fullfile(resultFolder,"senlora_orbit_ber.png");
matPath = fullfile(resultFolder,"senlora_orbit_ber.mat");
metadataPath = fullfile(resultFolder,"senlora_orbit_ber_metadata.json");

if options.Resume && isfile(csvPath)
    resultsTable = readtable(csvPath,TextType="string");
    resultsTable = validateOrResetCheckpoint(resultsTable,methodNames);
else
    resultsTable = table();
end

for scenarioIdx = 1:numel(config.scenarios)
    for snrIdx = 1:numel(options.SnrDb)
        snrDb = options.SnrDb(snrIdx);
        if hasCompletePoint(resultsTable,config.scenarios(scenarioIdx).name, ...
                snrDb,methodNames,options)
            continue
        end
        if ~isempty(resultsTable)
            staleMask = string(resultsTable.scenario)== ...
                string(config.scenarios(scenarioIdx).name) & ...
                double(resultsTable.snrDb)==snrDb;
            resultsTable(staleMask,:) = [];
        end
        point = simulateSenLoRaBerPoint( ...
            config,scenarioIdx,snrDb, ...
            TargetBitErrors=options.TargetBitErrors, ...
            MinBits=options.MinBitsPerPoint, ...
            MaxBits=options.MaxBitsPerPoint, ...
            MaxFrames=options.MaxFramesPerPoint,Methods=methodNames);
        trace = point.diagnosticTrace;
        traceFile = fullfile(resultFolder,sprintf( ...
            "trace_%s_%+05.1f.mat",strrep(char(point.scenario),"_","-"),snrDb));
        save(traceFile,"trace","-v7.3");
        pointRows = struct([]);
        theoryAtPoint = senloraTheoreticalBerAwgn(config.sf,snrDb);
        for methodIdx = 1:numel(methodNames)
            method = point.methods(methodIdx);
            [lower95,upper95] = senloraBinomialBounds95( ...
                method.bitErrors,method.totalBits);
            row = struct( ...
                "scenario",string(point.scenario), ...
                "sf",config.sf, ...
                "snrDb",point.snrDb, ...
                "method",methodNames(methodIdx), ...
                "bitErrors",method.bitErrors, ...
                "symbolErrors",method.symbolErrors, ...
                "totalBits",method.totalBits, ...
                "totalSymbols",method.totalSymbols, ...
                "ber",method.ber, ...
                "ser",method.ser, ...
                "berLower95",lower95, ...
                "berUpper95",upper95, ...
                "zeroErrorUpper95",method.berUpper95Zero, ...
                "frameBerStandardError",method.frameBerStandardError, ...
                "frameBerLower95",method.frameBerLower95, ...
                "frameBerUpper95",method.frameBerUpper95, ...
                "theoryBer",theoryAtPoint, ...
                "significantlyBelowTheory95", ...
                    method.frameBerUpper95 < theoryAtPoint, ...
                "meanPayloadPilotCount",method.meanPayloadPilotCount, ...
                "frameCount",point.frameCount, ...
                "seedSymbols",point.seedSymbols, ...
                "seedNoiseBase",point.seedNoiseBase, ...
                "targetBitErrors",options.TargetBitErrors, ...
                "minBitsPerPoint",options.MinBitsPerPoint, ...
                "maxBitsPerPoint",options.MaxBitsPerPoint, ...
                "falseAcceptCount",method.falseAcceptCount, ...
                "meanAbsResidualBins",method.meanAbsResidualBins, ...
                "maxAbsResidualBins",method.maxAbsResidualBins, ...
                "meanPredictedRateHzPerSec",method.meanPredictedRateHzPerSec, ...
                "traceFile",string(traceFile));
            if isempty(pointRows)
                pointRows = row;
            else
                pointRows(methodIdx,1) = row;
            end
        end
        if isempty(resultsTable)
            resultsTable = struct2table(pointRows);
        else
            resultsTable = [resultsTable; struct2table(pointRows)]; %#ok<AGROW>
        end
        resultsTable = sortrows(resultsTable, ...
            ["scenario","snrDb","method"]);
        writetable(resultsTable,csvPath);
        fprintf("SenLoRa BER scenario=%s SNR=%g rows=%d\n", ...
            point.scenario,snrDb,height(resultsTable));
    end
end

if isempty(resultsTable)
    error("SenLoRa:EmptyBerResult","Formal BER scan has no result rows.");
end
save(matPath,"resultsTable","config","options","-v7.3");
exportFormalBerFigure(resultsTable,config,options.SnrDb,pngPath,methodNames);

theory = senloraTheoreticalBerAwgn(config.sf,options.SnrDb);
metadata = struct( ...
    "folder",resultFolder, ...
    "sf",config.sf, ...
    "bandwidthHz",config.bandwidthHz, ...
    "sampleRateHz",config.sampleRateHz, ...
    "carrierFrequencyHz",config.carrierFrequencyHz, ...
    "orbitHeightM",config.orbit.orbitHeightM, ...
    "inclinationDeg",rad2deg(config.orbit.inclinationRad), ...
    "dopplerModel",config.dopplerModel, ...
    "snrDb",options.SnrDb, ...
    "targetBitErrors",options.TargetBitErrors, ...
    "minBitsPerPoint",options.MinBitsPerPoint, ...
    "maxBitsPerPoint",options.MaxBitsPerPoint, ...
    "methods",methodNames, ...
    "diagnosticTraceFiles","trace_<scenario>_<snr>.mat in the same folder", ...
    "zeroErrorUpper95","1-(0.05)^(1/N), stored alongside exact binomial bounds", ...
    "rawMonteCarloOnly",true, ...
    "smoothedOrFitted",false, ...
    "theoryBer",theory);
fid = fopen(metadataPath,"w");
if fid < 0
    error("SenLoRa:BerMetadataOpenFailed","Could not write formal BER metadata.");
end
cleanup = onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(metadata),"char");

outputs = struct( ...
    "results",resultsTable, ...
    "theory",theory, ...
    "csv",csvPath, ...
    "png",pngPath, ...
    "mat",matPath, ...
    "metadata",metadataPath);
end

function results = validateOrResetCheckpoint(results,methodNames)
required = ["scenario","sf","snrDb","method","bitErrors","totalBits", ...
    "falseAcceptCount","traceFile"];
if ~all(ismember(required,string(results.Properties.VariableNames)))
    results = table();
    return
end
methodValues = string(results.method);
if any(~ismember(methodValues,methodNames))
    results = table();
end
end

function tf = hasCompletePoint(results,scenario,snrDb,methodNames,options)
if isempty(results)
    tf = false;
    return
end
mask = string(results.scenario)==string(scenario) & ...
    double(results.snrDb)==snrDb;
if ~isequal(sort(string(results.method(mask))),sort(methodNames))
    tf = false;
    return
end
point = results(mask,:);
enoughBits = all(double(point.totalBits) >= ...
    min(options.MinBitsPerPoint,options.MaxBitsPerPoint));
finishedByErrors = all(double(point.bitErrors) >= options.TargetBitErrors);
finishedByBits = all(double(point.totalBits) >= options.MaxBitsPerPoint);
finishedByFrames = isfinite(options.MaxFramesPerPoint) && ...
    all(double(point.frameCount) >= options.MaxFramesPerPoint);
tf = enoughBits && (finishedByErrors || finishedByBits || finishedByFrames);
end

function exportFormalBerFigure(results,config,snrGrid,pngPath,methodNames)
fig = figure("Visible","off","Color","w","Position",[70,70,1550,650]);
layout = tiledlayout(fig,1,numel(config.scenarios), ...
    "TileSpacing","compact","Padding","compact");
    colors = [0.00 0.45 0.74; 0.85 0.33 0.10; 0.49 0.18 0.56];
    displayNames = ["Dynamic Doppler, no compensation", ...
        "PREC hard-decision virtual pilots", ...
        "SenLoRa confidence virtual pilots"];
    plotFloor = 1e-6;
for scenarioIdx = 1:numel(config.scenarios)
    ax = nexttile(layout,scenarioIdx);
    hold(ax,"on");
    scenarioName = string(config.scenarios(scenarioIdx).name);
    for methodIdx = 1:numel(methodNames)
        mask = string(results.scenario)==scenarioName & ...
            string(results.method)==methodNames(methodIdx);
        subset = sortrows(results(mask,:),"snrDb");
        if isempty(subset)
            continue
        end
        shown = subset.ber;
        zeroMask = subset.bitErrors==0;
        shown(zeroMask) = NaN;
        semilogy(ax,subset.snrDb,shown,"-o", ...
            "Color",colors(methodIdx,:),"LineWidth",1.1, ...
            "MarkerSize",4,"DisplayName",displayNames(methodIdx));
        positiveMask = ~zeroMask & isfinite(subset.frameBerLower95) & ...
            isfinite(subset.frameBerUpper95);
        if any(positiveMask)
            lowerDelta = subset.ber(positiveMask)- ...
                subset.frameBerLower95(positiveMask);
            upperDelta = subset.frameBerUpper95(positiveMask)- ...
                subset.ber(positiveMask);
            errorbar(ax,subset.snrDb(positiveMask), ...
                subset.ber(positiveMask),lowerDelta,upperDelta, ...
                "LineStyle","none","Color",colors(methodIdx,:), ...
                "CapSize",3,"HandleVisibility","off");
        end
        if any(zeroMask)
            zeroShown = max(subset.zeroErrorUpper95(zeroMask),plotFloor);
            semilogy(ax,subset.snrDb(zeroMask), ...
                zeroShown,"v", ...
                "Color",colors(methodIdx,:),"MarkerFaceColor","w", ...
                "HandleVisibility","off");
        end
    end
    denseSnr = linspace(min(snrGrid),max(snrGrid),801).';
    theory = senloraTheoreticalBerAwgn(config.sf,denseSnr);
    semilogy(ax,denseSnr,theory,"k--","LineWidth",1.2, ...
        "DisplayName","ideal AWGN theory");
    set(ax,"YScale","log");
    grid(ax,"on"); box(ax,"on");
    xlabel(ax,"Sample SNR (dB)");
    ylabel(ax,"BER (95% frame-cluster CI; triangles are zero-error bounds)");
    title(ax,strrep(scenarioName,"_"," "));
    if numel(snrGrid) == 1
        xlim(ax,[snrGrid-1,snrGrid+1]);
    else
        xlim(ax,[min(snrGrid),max(snrGrid)]);
    end
    ylim(ax,[plotFloor,1]);
    legend(ax,"Location","southwest","NumColumns",2);
end
title(layout,["SF11 dynamic Doppler BER: AWGN ideal, uncompensated, " ...
    "hard-decision PREC, and SenLoRa"]);
exportgraphics(fig,pngPath,"Resolution",180);
close(fig);
end
