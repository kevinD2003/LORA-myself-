function result = satelliteFig3RateReplaySenLoRaDecode( ...
        rxSymbols,config,knownWaveformBins,options)
%SATELLITEFIG3RATEREPLAYSENLORADECODE Blind frame-level rate acquisition.
%   A short known preamble does not always contain enough curvature SNR to
%   estimate Doppler rate over the complete frame.  This receiver replays a
%   fixed physical rate grid, scores each replay only by normalized soft-
%   Hamming consistency, and then returns the selected quality-gated
%   rolling-8 result.  Payload truth is neither accepted nor available.

arguments
    rxSymbols (:,:) double
    config (1,1) struct
    knownWaveformBins (:,1) double
    options.CandidateRatesBinsPerSec (:,1) double = zeros(0,1)
end

bootstrap = satelliteFig3BootstrapEstimate( ...
    rxSymbols(1:numel(knownWaveformBins),:),knownWaveformBins,config);
orbitPrior = satelliteFig3OrbitRatePriorFromCfo( ...
    bootstrap.coarseCfoBins,config);
if isempty(options.CandidateRatesBinsPerSec)
    % The configured orbit and the coarse known-preamble CFO already
    % identify rate to far better than 0.01 bin/s in the validated window.
    % Use that one physical track for the formal receiver.  SenLoRa soft
    % information remains responsible for virtual-pilot admission, but it
    % must not list-select a trajectory using payload-code evidence.
    candidateInput = orbitPrior.rateBinsPerSec;
    allowJointCandidate = false;
else
    candidateInput = options.CandidateRatesBinsPerSec;
    allowJointCandidate = true;
end
rates = unique(min(config.maxRateBinsPerSec,max( ...
    -config.maxRateBinsPerSec,candidateInput)),'stable');
jointRate = min(config.maxRateBinsPerSec,max( ...
    -config.maxRateBinsPerSec,bootstrap.jointRateBinsPerSec));
jointConsistent = abs(jointRate-orbitPrior.rateBinsPerSec) <= ...
    config.rateReplayPriorHalfWidthBinsPerSec;
if allowJointCandidate && jointConsistent && ...
        ~any(abs(rates-jointRate) < 10*eps(max(1,abs(jointRate))))
    rates = [rates;jointRate];
end

candidateCount = numel(rates);
candidates = cell(candidateCount,1);
score = zeros(candidateCount,1);
acceptedCount = zeros(candidateCount,1);
payloadRows = numel(knownWaveformBins)+1:size(rxSymbols,1);
for candidate = 1:candidateCount
    decoded = satelliteFig3SenLoRaIterativeDecode( ...
        rxSymbols,config,knownWaveformBins, ...
        UseEstimatedSnrGate=false, ...
        MinimumCodewordMarginRatio=config.senloraMinimumMarginRatio, ...
        RequireSoftHardAgreement=config.senloraRequireSoftHardAgreement, ...
        UseSoftDecodedPilotLabels=config.senloraUseSoftDecodedPilotLabels, ...
        UseCausalConfidenceTiming=config.senloraUseCausalConfidenceTiming, ...
        InnovationLimitBins=config.confidenceInnovationLimitBins, ...
        FreezeBootstrapRate=true, ...
        ReleaseBootstrapRateAfterVirtualPilotCount= ...
            config.senloraRateReleasePilotCount, ...
        RateDeviationLimitBinsPerSec= ...
            config.senloraRateTrackingDeviationLimitBinsPerSec, ...
        BootstrapRateOverrideBinsPerSec=rates(candidate));
    marginRatio = decoded.soft.symbolCodewordMargin(payloadRows)./ ...
        max(decoded.soft.tauGlobal(payloadRows),eps);
    % LOG1P limits domination by a single very large noisy block while the
    % complete frame supplies enough coded evidence to rank rate tracks.
    score(candidate) = sum(log1p(max(marginRatio,0)));
    acceptedCount(candidate) = sum(decoded.pilotAccepted(payloadRows));
    candidates{candidate} = decoded;
end

bestScore = max(score);
tied = find(abs(score-bestScore) <= ...
    100*eps(max(1,abs(bestScore))));
if numel(tied) > 1
    [~,nearest] = min(abs(rates(tied)-jointRate));
    selectedIndex = tied(nearest);
else
    selectedIndex = tied;
end
result = candidates{selectedIndex};
sortedScore = sort(score,'descend');
if numel(sortedScore) > 1
    scoreGap = sortedScore(1)-sortedScore(2);
else
    scoreGap = Inf;
end
result.rateReplay = struct( ...
    'candidateRatesBinsPerSec',rates, ...
    'softHammingScore',score, ...
    'acceptedPilotCount',acceptedCount, ...
    'jointBootstrapRateBinsPerSec',jointRate, ...
    'jointBootstrapRateConsistentWithOrbitPrior',jointConsistent, ...
    'orbitPrior',orbitPrior, ...
    'selectedIndex',selectedIndex, ...
    'selectedRateBinsPerSec',rates(selectedIndex), ...
    'scoreGap',scoreGap);
result.rateReplay.selectionUsesPayloadCodeEvidence = numel(rates) > 1;
end
