function report = run_stage55_vp_mechanism_ablation(options)
%RUN_STAGE55_VP_MECHANISM_ABLATION Five-way paired Stage55 VP ablation.
%   The same received frame is decoded by NoVP and a 2-by-2 factorial of
%   VP phase correction and VP-triggered rate release.  Every VP branch
%   still inserts accepted payload CFO observations into the rolling
%   history, so this experiment separates center, phase, and rate effects.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.PassCount (1,1) double ...
        {mustBeInteger,mustBePositive} = 1
    options.FramesPerVisibleSegment (1,1) double = Inf
    options.PayloadSeedBase (1,1) double = 2026350800
    options.NoiseSeedBase (1,1) double = 2026350900
    options.OutputFolderName (1,:) char = ...
        'stage55_vp_mechanism_ablation'
    options.ProgressEveryFrames (1,1) double = 25
    options.WriteFigures (1,1) logical = true
    options.IncludeQualityMode (1,1) logical = false
    options.QualityFinalOnly (1,1) logical = false
end
if ~(isinf(options.FramesPerVisibleSegment) || ( ...
        options.FramesPerVisibleSegment >= 1 && ...
        options.FramesPerVisibleSegment == ...
        round(options.FramesPerVisibleSegment)))
    error('SatelliteFig3:VpAblationFramesPerSegment', ...
        'FramesPerVisibleSegment must be Inf or a positive integer.');
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
trajectory = satelliteFig3Trajectory(schedule.frameCenterTimeSec,config);
driftBinsPerFrame = abs(trajectory.dopplerRateHzPerSec).* ...
    schedule.frameDurationSec/config.fftBinSpacingHz;
segmentEdges = find(diff([false;schedule.fullyVisible(:);false]));
segments = reshape(segmentEdges,2,[]).'+[0 -1];
if isfinite(options.FramesPerVisibleSegment)
    segments(:,2) = min(segments(:,2), ...
        segments(:,1)+options.FramesPerVisibleSegment-1);
end

if options.QualityFinalOnly && ~options.IncludeQualityMode
    error('SatelliteFig3:VpQualityFinalMode', ...
        'QualityFinalOnly requires IncludeQualityMode=true.');
end
if options.QualityFinalOnly
    modes = table({'NoVP';'VP-quality'},[false;true], ...
        [false;true],[false;true],[false;true], ...
        'VariableNames',{'mode','enableVirtualPilots', ...
        'enablePhaseCorrection','enableRateUpdate','qualityAware'});
elseif options.IncludeQualityMode
    modes = table({'NoVP';'VP-legacy';'VP-quality'}, ...
        [false;true;true],[false;true;true],[false;true;true], ...
        [false;false;true], ...
        'VariableNames',{'mode','enableVirtualPilots', ...
        'enablePhaseCorrection','enableRateUpdate','qualityAware'});
else
    modes = table( ...
        {'NoVP';'VP-center';'VP-center-phase';'VP-center-rate';'VP-full'}, ...
        [false;true;true;true;true], ...
        [false;false;true;false;true], ...
        [false;false;false;true;true], ...
        false(5,1), ...
        'VariableNames',{'mode','enableVirtualPilots', ...
        'enablePhaseCorrection','enableRateUpdate','qualityAware'});
end
known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
framesPerPass = sum(segments(:,2)-segments(:,1)+1);
maximumFrames = numel(options.SnrGridDb)*options.PassCount*framesPerPass;
records = localPreallocateRecords(maximumFrames*height(modes));
recordIndex = 0;
frameCounter = 0;

for snrIndex = 1:numel(options.SnrGridDb)
    for passIndex = 1:options.PassCount
        for segmentIndex = 1:size(segments,1)
            crossFrameState = struct();
            phaseStateRad = 0;
            for frameIndex = segments(segmentIndex,1):segments(segmentIndex,2)
                payloadSeed = options.PayloadSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                noiseSeed = options.NoiseSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                payload = satelliteFig3GeneratePayload(config,payloadSeed);
                labels = [known;payload.symbolBins];
                [rx,~,truth] = generateContinuousSatelliteFrame( ...
                    labels,config, ...
                    StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    SampleSnrDb=options.SnrGridDb(snrIndex), ...
                    NoiseSeed=noiseSeed,InitialPhaseRad=phaseStateRad, ...
                    NextSymbolBin=0);
                phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);
                incomingState = crossFrameState;
                decoded = cell(height(modes),1);
                for modeIndex = 1:height(modes)
                    decoded{modeIndex} = ...
                        satelliteFig3SenLoRaVirtualPilotDecode( ...
                        rx,config,known, ...
                        FrameStartTimeSec= ...
                            schedule.frameStartTimeSec(frameIndex), ...
                        CrossFrameState=incomingState, ...
                        EnableVirtualPilots= ...
                            modes.enableVirtualPilots(modeIndex), ...
                        EnableVirtualPilotRateUpdate= ...
                            modes.enableRateUpdate(modeIndex), ...
                        ApplyVirtualPilotPhaseCorrection= ...
                            modes.enablePhaseCorrection(modeIndex), ...
                        UseQualityAwareVirtualPilots= ...
                            modes.qualityAware(modeIndex));
                end
                localAssertPaired(decoded,modes,payloadRows);
                crossFrameState = decoded{end}.crossFrameState;

                if driftBinsPerFrame(frameIndex) >= 0.5
                    region = 'high_doppler_rate';
                else
                    region = 'high_doppler_shift';
                end
                referenceSymbols = labels(payloadRows);
                referenceBits = payload.dataBits(:);
                truthCfoBins = truth.trueDopplerHz(payloadRows)/ ...
                    config.fftBinSpacingHz;
                for modeIndex = 1:height(modes)
                    branch = decoded{modeIndex};
                    hardSymbols = branch.tracker.hardWaveformBins(payloadRows);
                    hardBits = branch.hardDecodedDataBits(:);
                    softBits = branch.decodedDataBits(:);
                    cfoError = branch.tracker.predictedCfoBins(payloadRows)- ...
                        truthCfoBins;
                    accepted = branch.pilotAccepted(payloadRows);
                    rateDelta = branch.tracker.predictedRateBinsPerSec( ...
                        payloadRows)-branch.initialRateBinsPerSec;
                    recordIndex = recordIndex+1;
                    records.snrDb(recordIndex) = options.SnrGridDb(snrIndex);
                    records.passIndex(recordIndex) = passIndex;
                    records.segmentIndex(recordIndex) = segmentIndex;
                    records.frameIndex(recordIndex) = frameIndex;
                    records.frameCenterTimeSec(recordIndex) = ...
                        schedule.frameCenterTimeSec(frameIndex);
                    records.driftBinsPerFrame(recordIndex) = ...
                        driftBinsPerFrame(frameIndex);
                    records.region{recordIndex} = region;
                    records.mode{recordIndex} = modes.mode{modeIndex};
                    records.enableVirtualPilots(recordIndex) = ...
                        modes.enableVirtualPilots(modeIndex);
                    records.enablePhaseCorrection(recordIndex) = ...
                        modes.enablePhaseCorrection(modeIndex);
                    records.enableRateUpdate(recordIndex) = ...
                        modes.enableRateUpdate(modeIndex);
                    records.qualityAware(recordIndex) = ...
                        modes.qualityAware(modeIndex);
                    records.crossFrameHistoryCount(recordIndex) = ...
                        branch.crossFrameRateDiagnostic.historyCount;
                    records.symbolCount(recordIndex) = numel(referenceSymbols);
                    records.symbolErrors(recordIndex) = ...
                        sum(hardSymbols ~= referenceSymbols);
                    records.bitCount(recordIndex) = numel(referenceBits);
                    records.hardBitErrors(recordIndex) = ...
                        sum(hardBits ~= referenceBits);
                    records.softBitErrors(recordIndex) = ...
                        sum(softBits ~= referenceBits);
                    records.softFrameError(recordIndex) = ...
                        records.softBitErrors(recordIndex) > 0;
                    records.cfoSseBins(recordIndex) = sum(cfoError.^2);
                    records.cfoSampleCount(recordIndex) = numel(cfoError);
                    records.acceptedVirtualPilots(recordIndex) = sum(accepted);
                    records.falseAcceptedVirtualPilots(recordIndex) = ...
                        sum(accepted & hardSymbols ~= referenceSymbols);
                    records.updatedSymbolCount(recordIndex) = sum( ...
                        branch.tracker.compensationVirtualPilotCount( ...
                        payloadRows) > 0);
                    records.maxRateDeltaBinsPerSec(recordIndex) = ...
                        max(abs(rateDelta));
                    records.phasePairUsedCount(recordIndex) = sum( ...
                        branch.tracker.phasePairUsed(payloadRows));
                    records.rateObservableSymbolCount(recordIndex) = sum( ...
                        branch.tracker.virtualPilotRateObservable( ...
                        payloadRows));
                end
                frameCounter = frameCounter+1;
                if isfinite(options.ProgressEveryFrames) && ...
                        options.ProgressEveryFrames > 0 && ...
                        mod(frameCounter,options.ProgressEveryFrames) == 0
                    fprintf('Stage55 VP ablation: %d/%d paired frames.\n', ...
                        frameCounter,maximumFrames);
                end
            end
        end
    end
end

records = struct2table(localTrimRecords(records,recordIndex));
summary = localSummary(records,modes,options.SnrGridDb);
frameCsv = fullfile(resultDir,'stage55_vp_ablation_frame_records.csv');
summaryCsv = fullfile(resultDir,'stage55_vp_ablation_summary.csv');
writetable(records,frameCsv);
writetable(summary,summaryCsv);
figureFiles = cell(0,1);
if options.WriteFigures
    figureFiles = localWriteFigures(summary,modes,options.SnrGridDb,resultDir);
end
matFile = fullfile(resultDir,'stage55_vp_mechanism_ablation.mat');
save(matFile,'config','schedule','segments','options','modes','records', ...
    'summary','figureFiles');
report = struct('resultDir',resultDir,'modes',modes,'records',records, ...
    'summary',summary,'figureFiles',{figureFiles},'matFile',matFile);
fprintf('Stage55 VP mechanism ablation: %s\n',resultDir);
disp(summary);
end

function data = localPreallocateRecords(count)
numericFields = {'snrDb','passIndex','segmentIndex','frameIndex', ...
    'frameCenterTimeSec','driftBinsPerFrame','crossFrameHistoryCount', ...
    'symbolCount','symbolErrors','bitCount','hardBitErrors', ...
    'softBitErrors','cfoSseBins','cfoSampleCount', ...
    'acceptedVirtualPilots','falseAcceptedVirtualPilots', ...
    'updatedSymbolCount','maxRateDeltaBinsPerSec', ...
    'phasePairUsedCount','rateObservableSymbolCount'};
for fieldIndex = 1:numel(numericFields)
    data.(numericFields{fieldIndex}) = zeros(count,1);
end
data.region = cell(count,1);
data.mode = cell(count,1);
data.enableVirtualPilots = false(count,1);
data.enablePhaseCorrection = false(count,1);
data.enableRateUpdate = false(count,1);
data.qualityAware = false(count,1);
data.softFrameError = false(count,1);
end

function data = localTrimRecords(data,count)
fields = fieldnames(data);
for fieldIndex = 1:numel(fields)
    data.(fields{fieldIndex}) = data.(fields{fieldIndex})(1:count,:);
end
end

function localAssertPaired(decoded,modes,payloadRows)
reference = decoded{1};
for modeIndex = 1:numel(decoded)
    branch = decoded{modeIndex};
    if branch.initialRateBinsPerSec ~= reference.initialRateBinsPerSec || ...
            branch.commonBootstrap.epsilonHatBins ~= ...
            reference.commonBootstrap.epsilonHatBins || ...
            ~isequaln(branch.crossFrameState,reference.crossFrameState)
        error('SatelliteFig3:VpAblationInitialization', ...
            'An ablation branch changed the common receiver initialization.');
    end
    if branch.virtualPilotsEnabled ~= ...
            modes.enableVirtualPilots(modeIndex) || ...
            branch.virtualPilotPhaseCorrectionEnabled ~= ...
            modes.enablePhaseCorrection(modeIndex) || ...
            branch.virtualPilotRateUpdateEnabled ~= ...
            modes.enableRateUpdate(modeIndex) || ...
            branch.qualityAwareVirtualPilotsEnabled ~= ...
            modes.qualityAware(modeIndex)
        error('SatelliteFig3:VpAblationSwitch', ...
            'An ablation branch does not expose its requested mechanism.');
    end
    if ~modes.enableRateUpdate(modeIndex)
        rateDelta = branch.tracker.predictedRateBinsPerSec(payloadRows)- ...
            branch.initialRateBinsPerSec;
        if any(abs(rateDelta) > 1e-12)
            error('SatelliteFig3:VpAblationRateLeakage', ...
                'A rate-frozen branch changed the payload rate.');
        end
    end
end
if any(reference.pilotAccepted(payloadRows)) || ...
        reference.tracker.acceptedVirtualPilotCount ~= 0
    error('SatelliteFig3:VpAblationNoVpLeakage', ...
        'The NoVP branch admitted a payload virtual pilot.');
end
end

function summary = localSummary(records,modes,snrGrid)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
rows = repmat(struct(),0,1);
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        baseSelected = records.snrDb == snrGrid(snrIndex) & ...
            strcmp(records.region,regionKeys{regionIndex}) & ...
            strcmp(records.mode,'NoVP');
        if ~any(baseSelected), continue; end
        baseSymbols = sum(records.symbolCount(baseSelected));
        baseSer = sum(records.symbolErrors(baseSelected))/baseSymbols;
        baseCfo = sqrt(sum(records.cfoSseBins(baseSelected))/ ...
            sum(records.cfoSampleCount(baseSelected)));
        for modeIndex = 1:height(modes)
            selected = records.snrDb == snrGrid(snrIndex) & ...
                strcmp(records.region,regionKeys{regionIndex}) & ...
                strcmp(records.mode,modes.mode{modeIndex});
            symbols = sum(records.symbolCount(selected));
            bits = sum(records.bitCount(selected));
            frames = sum(selected);
            ser = sum(records.symbolErrors(selected))/symbols;
            cfo = sqrt(sum(records.cfoSseBins(selected))/ ...
                sum(records.cfoSampleCount(selected)));
            row = struct('snrDb',snrGrid(snrIndex), ...
                'region',regionKeys{regionIndex}, ...
                'mode',modes.mode{modeIndex}, ...
                'frameCount',frames,'symbolCount',symbols, ...
                'ser',ser,'serDeltaVsNoVp',ser-baseSer, ...
                'cfoRmseBins',cfo,'cfoDeltaVsNoVp',cfo-baseCfo, ...
                'hardBer',sum(records.hardBitErrors(selected))/bits, ...
                'softBer',sum(records.softBitErrors(selected))/bits, ...
                'softPer',mean(records.softFrameError(selected)), ...
                'meanAcceptedVirtualPilots',mean( ...
                    records.acceptedVirtualPilots(selected)), ...
                'falseAcceptedVirtualPilots',sum( ...
                    records.falseAcceptedVirtualPilots(selected)), ...
                'updatedSymbolCoverage',sum( ...
                    records.updatedSymbolCount(selected))/symbols, ...
                'meanMaxRateDeltaBinsPerSec',mean( ...
                    records.maxRateDeltaBinsPerSec(selected)), ...
                'meanPhasePairUsedCount',mean( ...
                    records.phasePairUsedCount(selected)), ...
                'rateObservableSymbolCoverage',sum( ...
                    records.rateObservableSymbolCount(selected))/symbols);
            paired = localPairedPassStatistics(records,selected, ...
                baseSelected,modes.mode{modeIndex});
            pairedFields = fieldnames(paired);
            for pairedIndex = 1:numel(pairedFields)
                row.(pairedFields{pairedIndex}) = ...
                    paired.(pairedFields{pairedIndex});
            end
            if isempty(rows)
                rows = row;
            else
                rows(end+1,1) = row; %#ok<AGROW>
            end
        end
    end
end
summary = struct2table(rows);
end

function result = localPairedPassStatistics( ...
        records,selected,baseSelected,modeName)
passes = unique(records.passIndex(selected));
serDelta = zeros(numel(passes),1);
softBerDelta = zeros(numel(passes),1);
softPerDelta = zeros(numel(passes),1);
cfoDelta = zeros(numel(passes),1);
for passIndex = 1:numel(passes)
    modeRows = selected & records.passIndex == passes(passIndex);
    baseRows = baseSelected & records.passIndex == passes(passIndex);
    modeSymbols = sum(records.symbolCount(modeRows));
    baseSymbols = sum(records.symbolCount(baseRows));
    modeBits = sum(records.bitCount(modeRows));
    baseBits = sum(records.bitCount(baseRows));
    serDelta(passIndex) = ...
        sum(records.symbolErrors(modeRows))/modeSymbols- ...
        sum(records.symbolErrors(baseRows))/baseSymbols;
    softBerDelta(passIndex) = ...
        sum(records.softBitErrors(modeRows))/modeBits- ...
        sum(records.softBitErrors(baseRows))/baseBits;
    softPerDelta(passIndex) = ...
        mean(records.softFrameError(modeRows))- ...
        mean(records.softFrameError(baseRows));
    cfoDelta(passIndex) = sqrt(sum(records.cfoSseBins(modeRows))/ ...
        sum(records.cfoSampleCount(modeRows)))-sqrt( ...
        sum(records.cfoSseBins(baseRows))/ ...
        sum(records.cfoSampleCount(baseRows)));
end
[serMean,serLower,serUpper] = localMeanCi95(serDelta);
[softBerMean,softBerLower,softBerUpper] = ...
    localMeanCi95(softBerDelta);
[softPerMean,softPerLower,softPerUpper] = ...
    localMeanCi95(softPerDelta);
[cfoMean,cfoLower,cfoUpper] = localMeanCi95(cfoDelta);
if strcmp(modeName,'NoVP')
    serMean = 0; serLower = 0; serUpper = 0;
    softBerMean = 0; softBerLower = 0; softBerUpper = 0;
    softPerMean = 0; softPerLower = 0; softPerUpper = 0;
    cfoMean = 0; cfoLower = 0; cfoUpper = 0;
end
result = struct('independentPassCount',numel(passes), ...
    'pairedSerDeltaMean',serMean, ...
    'pairedSerDeltaCi95Lower',serLower, ...
    'pairedSerDeltaCi95Upper',serUpper, ...
    'pairedSoftBerDeltaMean',softBerMean, ...
    'pairedSoftBerDeltaCi95Lower',softBerLower, ...
    'pairedSoftBerDeltaCi95Upper',softBerUpper, ...
    'pairedSoftPerDeltaMean',softPerMean, ...
    'pairedSoftPerDeltaCi95Lower',softPerLower, ...
    'pairedSoftPerDeltaCi95Upper',softPerUpper, ...
    'pairedCfoRmseDeltaMeanBins',cfoMean, ...
    'pairedCfoRmseDeltaCi95LowerBins',cfoLower, ...
    'pairedCfoRmseDeltaCi95UpperBins',cfoUpper);
end

function [sampleMean,lower,upper] = localMeanCi95(values)
values = values(:);
sampleMean = mean(values);
if numel(values) < 2
    lower = NaN;
    upper = NaN;
    return
end
critical = localTCritical95(numel(values)-1);
halfWidth = critical*std(values,0)/sqrt(numel(values));
lower = sampleMean-halfWidth;
upper = sampleMean+halfWidth;
end

function critical = localTCritical95(degreesFreedom)
% Two-sided 95% Student-t critical values for 1:30 degrees of freedom.
tableValues = [12.7062 4.3027 3.1824 2.7764 2.5706 2.4469 ...
    2.3646 2.3060 2.2622 2.2281 2.2010 2.1788 2.1604 2.1448 ...
    2.1314 2.1199 2.1098 2.1009 2.0930 2.0860 2.0796 2.0739 ...
    2.0687 2.0639 2.0595 2.0555 2.0518 2.0484 2.0452 2.0423];
if degreesFreedom <= numel(tableValues)
    critical = tableValues(degreesFreedom);
else
    critical = 1.96;
end
end

function files = localWriteFigures(summary,modes,snrGrid,resultDir)
files = cell(0,1);
colors = lines(height(modes));
regionKeys = {'high_doppler_rate','high_doppler_shift'};
regionNames = {'High Doppler rate','High Doppler shift'};
for snrIndex = 1:numel(snrGrid)
    figureHandle = figure('Visible','off','Color','w', ...
        'Position',[100 100 1500 850]);
    layout = tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
    title(layout,sprintf(['Stage55 VP mechanism ablation: %.1f dB, ' ...
        'same received frames'],snrGrid(snrIndex)));
    for regionIndex = 1:numel(regionKeys)
        selected = summary.snrDb == snrGrid(snrIndex) & ...
            strcmp(summary.region,regionKeys{regionIndex});
        regionRows = summary(selected,:);
        [~,order] = ismember(modes.mode,regionRows.mode);
        regionRows = regionRows(order,:);
        nexttile(regionIndex);
        b = bar(regionRows.ser,'FaceColor','flat');
        b.CData = colors;
        ylabel('SER'); grid on
        title(sprintf('%s: symbol detection',regionNames{regionIndex}));
        set(gca,'XTick',1:height(modes),'XTickLabel',modes.mode, ...
            'XTickLabelRotation',18);
        nexttile(regionIndex+2);
        b = bar(regionRows.cfoRmseBins,'FaceColor','flat');
        b.CData = colors;
        ylabel('CFO RMSE (bin)'); grid on
        title(sprintf('%s: tracking error',regionNames{regionIndex}));
        set(gca,'XTick',1:height(modes),'XTickLabel',modes.mode, ...
            'XTickLabelRotation',18);
    end
    stem = sprintf('stage55_vp_mechanism_ablation_minus%d_dB', ...
        abs(round(snrGrid(snrIndex))));
    pngFile = fullfile(resultDir,[stem '.png']);
    figFile = fullfile(resultDir,[stem '.fig']);
    exportgraphics(figureHandle,pngFile,'Resolution',180);
    savefig(figureHandle,figFile);
    close(figureHandle);
    files{end+1,1} = pngFile; %#ok<AGROW>
    files{end+1,1} = figFile; %#ok<AGROW>
end
end

function wrapped = localWrapToPi(angleRad)
wrapped = mod(angleRad+pi,2*pi)-pi;
end
