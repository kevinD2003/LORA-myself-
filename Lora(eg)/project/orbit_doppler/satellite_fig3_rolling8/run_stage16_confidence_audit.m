function report = run_stage16_confidence_audit(options)
%RUN_STAGE16_CONFIDENCE_AUDIT Audit virtual pilots independently of BER.
%   Truth is consulted only after all receiver processing.  The audit
%   compares hard PREC, the legacy five-pass SenLoRa route, and the current
%   trusted SenLoRa route in both Figure-3 orbit scenes.

arguments
    options.SnrGridDb (:,1) double = (-24:2:-14).'
    options.FrameCount (1,1) double {mustBeInteger,mustBePositive} = 8
    options.SymbolSeedBase (1,1) double = 2026082200
    options.NoiseSeedBase (1,1) double = 2026082300
    options.OutputFolderName (1,:) char = 'stage16_confidence_audit'
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir)
    mkdir(resultDir);
end

config = satelliteFig3Config();
[window,~] = satelliteFig3VisibilityWindow(config);
scenarioKeys = {'high_doppler_shift','high_doppler_rate'};
scenarioTitles = {'High Doppler shift','High Doppler rate'};
startTimes = [-window.deltaTimeOutSec,window.deltaTimeInSec];
predictionNames = {'Static 8-preamble','Hard PREC', ...
    'Ungated five-pass SenLoRa','Quality-gated SenLoRa','Trusted SenLoRa'};
pilotNames = {'Hard PREC','Ungated five-pass SenLoRa', ...
    'Quality-gated SenLoRa','Trusted SenLoRa'};
scenarioCount = numel(scenarioKeys);
snrCount = numel(options.SnrGridDb);
predictionMethodCount = numel(predictionNames);
pilotMethodCount = numel(pilotNames);
payloadCount = config.payloadSymbolCount;
known = zeros(config.bootstrapPilotCount,1);

predictionSse = zeros(scenarioCount,snrCount,predictionMethodCount);
predictionSecondHalfSse = zeros(size(predictionSse));
predictionSamples = zeros(scenarioCount,snrCount);
predictionSecondHalfSamples = zeros(scenarioCount,snrCount);
acceptedCount = zeros(scenarioCount,snrCount,pilotMethodCount);
falseAcceptedCount = zeros(size(acceptedCount));
noAcceptedFrameCount = zeros(size(acceptedCount));
maximumGapSum = zeros(size(acceptedCount));
lastPilotPositionSum = zeros(size(acceptedCount));
measurementError = cell(scenarioCount,snrCount,pilotMethodCount);
baseCandidateCount = zeros(scenarioCount,snrCount);
quarantineCount = zeros(scenarioCount,snrCount);
anchorCount = zeros(scenarioCount,snrCount);
promotedRequestCount = zeros(scenarioCount,snrCount);
commonNoiseMaxDifference = 0;

for snrIndex = 1:snrCount
    for frame = 1:options.FrameCount
        symbolSeed = options.SymbolSeedBase+1000*snrIndex+frame;
        noiseSeed = options.NoiseSeedBase+1000*snrIndex+frame;
        payload = satelliteFig3GeneratePayload(config,symbolSeed);
        labels = [known;payload.symbolBins];
        payloadRows = config.bootstrapPilotCount+1:numel(labels);
        secondHalf = payloadRows(floor(payloadCount/2)+1:end);
        noiseReference = [];
        for scenario = 1:scenarioCount
            [rx,tx,truth] = generateContinuousSatelliteFrame(labels,config, ...
                StartTimeSec=startTimes(scenario), ...
                SampleSnrDb=options.SnrGridDb(snrIndex), ...
                NoiseSeed=noiseSeed);
            channelNoise = rx-tx.*exp(1i*truth.phaseRad);
            if scenario == 1
                noiseReference = channelNoise;
            else
                commonNoiseMaxDifference = max(commonNoiseMaxDifference, ...
                    max(abs(channelNoise-noiseReference),[],'all'));
            end

            staticTracker = satelliteFig3RollingPilotTracker(rx,config,known);
            hardPrec = satelliteFig3HardPrecDecode(rx,config,known);
            fivePass = satelliteFig3SenLoRaIterativeDecode(rx,config,known, ...
                UseEstimatedSnrGate=false);
            qualityGated = satelliteFig3QualityGatedSenLoRaDecode( ...
                rx,config,known);
            trusted = satelliteFig3TrustedConfidenceDecode(rx,config,known);
            predictionTrackers = {staticTracker,hardPrec.tracker, ...
                fivePass.tracker,qualityGated.tracker, ...
                trusted.virtualPilotTracker};
            pilotTrackers = {hardPrec.tracker,fivePass.tracker, ...
                qualityGated.tracker,trusted.virtualPilotTracker};

            truthCfoBins = truth.trueDopplerHz/config.fftBinSpacingHz;
            for method = 1:predictionMethodCount
                errorBins = predictionTrackers{method}.predictedCfoBins- ...
                    truthCfoBins;
                predictionSse(scenario,snrIndex,method) = ...
                    predictionSse(scenario,snrIndex,method)+ ...
                    sum(errorBins(payloadRows).^2);
                predictionSecondHalfSse(scenario,snrIndex,method) = ...
                    predictionSecondHalfSse(scenario,snrIndex,method)+ ...
                    sum(errorBins(secondHalf).^2);
            end
            predictionSamples(scenario,snrIndex) = ...
                predictionSamples(scenario,snrIndex)+payloadCount;
            predictionSecondHalfSamples(scenario,snrIndex) = ...
                predictionSecondHalfSamples(scenario,snrIndex)+numel(secondHalf);

            for method = 1:pilotMethodCount
                tracker = pilotTrackers{method};
                mask = tracker.pilotAccepted(payloadRows);
                acceptedRows = payloadRows(mask);
                wrong = tracker.detectedWaveformBins(payloadRows(mask)) ~= ...
                    labels(payloadRows(mask));
                acceptedCount(scenario,snrIndex,method) = ...
                    acceptedCount(scenario,snrIndex,method)+sum(mask);
                falseAcceptedCount(scenario,snrIndex,method) = ...
                    falseAcceptedCount(scenario,snrIndex,method)+sum(wrong);
                cfoError = tracker.measuredCfoBins(acceptedRows)- ...
                    truthCfoBins(acceptedRows);
                measurementError{scenario,snrIndex,method} = [ ...
                    measurementError{scenario,snrIndex,method};cfoError(:)];

                positions = find(mask);
                if isempty(positions)
                    noAcceptedFrameCount(scenario,snrIndex,method) = ...
                        noAcceptedFrameCount(scenario,snrIndex,method)+1;
                    maximumGap = payloadCount;
                    lastPosition = 0;
                else
                    gaps = diff([0;positions;payloadCount+1])-1;
                    maximumGap = max(gaps);
                    lastPosition = positions(end);
                end
                maximumGapSum(scenario,snrIndex,method) = ...
                    maximumGapSum(scenario,snrIndex,method)+maximumGap;
                lastPilotPositionSum(scenario,snrIndex,method) = ...
                    lastPilotPositionSum(scenario,snrIndex,method)+lastPosition;
            end

            baseCandidateCount(scenario,snrIndex) = ...
                baseCandidateCount(scenario,snrIndex)+ ...
                sum(trusted.firstFeatures.candidateMask);
            quarantineCount(scenario,snrIndex) = ...
                quarantineCount(scenario,snrIndex)+ ...
                sum(trusted.quarantineMask(payloadRows));
            anchorCount(scenario,snrIndex) = ...
                anchorCount(scenario,snrIndex)+ ...
                sum(trusted.anchorMask(payloadRows));
            promotedRequestCount(scenario,snrIndex) = ...
                promotedRequestCount(scenario,snrIndex)+ ...
                sum(trusted.promotedMask(payloadRows));
        end
    end
end

predictionRmse = sqrt(predictionSse./ ...
    reshape(predictionSamples,scenarioCount,snrCount,1));
predictionSecondHalfRmse = sqrt(predictionSecondHalfSse./ ...
    reshape(predictionSecondHalfSamples,scenarioCount,snrCount,1));
precision = 1-falseAcceptedCount./acceptedCount;
precision(acceptedCount == 0) = NaN;
measurementRmse = nan(size(acceptedCount));
measurementP95 = nan(size(acceptedCount));
for scenario = 1:scenarioCount
    for snrIndex = 1:snrCount
        for method = 1:pilotMethodCount
            values = measurementError{scenario,snrIndex,method};
            if isempty(values)
                continue
            end
            measurementRmse(scenario,snrIndex,method) = ...
                sqrt(mean(values.^2));
            measurementP95(scenario,snrIndex,method) = ...
                localPercentile(abs(values),95);
        end
    end
end

rowCount = scenarioCount*snrCount;
scenarioColumn = cell(rowCount,1);
snrColumn = zeros(rowCount,1);
baseCandidatePerFrame = zeros(rowCount,1);
quarantinePerFrame = zeros(rowCount,1);
anchorPerFrame = zeros(rowCount,1);
promotedPerFrame = zeros(rowCount,1);
acceptedPerFrame = zeros(rowCount,pilotMethodCount);
falseAccepted = zeros(rowCount,pilotMethodCount);
precisionColumn = nan(rowCount,pilotMethodCount);
measurementRmseColumn = nan(rowCount,pilotMethodCount);
measurementP95Column = nan(rowCount,pilotMethodCount);
meanMaximumGap = zeros(rowCount,pilotMethodCount);
meanLastPilot = zeros(rowCount,pilotMethodCount);
framesWithoutPilot = zeros(rowCount,pilotMethodCount);
predictionRmseColumn = zeros(rowCount,predictionMethodCount);
predictionSecondColumn = zeros(rowCount,predictionMethodCount);
row = 0;
for scenario = 1:scenarioCount
    for snrIndex = 1:snrCount
        row = row+1;
        scenarioColumn{row} = scenarioKeys{scenario};
        snrColumn(row) = options.SnrGridDb(snrIndex);
        baseCandidatePerFrame(row) = ...
            baseCandidateCount(scenario,snrIndex)/options.FrameCount;
        quarantinePerFrame(row) = ...
            quarantineCount(scenario,snrIndex)/options.FrameCount;
        anchorPerFrame(row) = anchorCount(scenario,snrIndex)/options.FrameCount;
        promotedPerFrame(row) = ...
            promotedRequestCount(scenario,snrIndex)/options.FrameCount;
        acceptedPerFrame(row,:) = reshape( ...
            acceptedCount(scenario,snrIndex,:),1,[])/options.FrameCount;
        falseAccepted(row,:) = reshape( ...
            falseAcceptedCount(scenario,snrIndex,:),1,[]);
        precisionColumn(row,:) = reshape(precision(scenario,snrIndex,:),1,[]);
        measurementRmseColumn(row,:) = reshape( ...
            measurementRmse(scenario,snrIndex,:),1,[]);
        measurementP95Column(row,:) = reshape( ...
            measurementP95(scenario,snrIndex,:),1,[]);
        meanMaximumGap(row,:) = reshape( ...
            maximumGapSum(scenario,snrIndex,:),1,[])/options.FrameCount;
        meanLastPilot(row,:) = reshape( ...
            lastPilotPositionSum(scenario,snrIndex,:),1,[])/options.FrameCount;
        framesWithoutPilot(row,:) = reshape( ...
            noAcceptedFrameCount(scenario,snrIndex,:),1,[]);
        predictionRmseColumn(row,:) = reshape( ...
            predictionRmse(scenario,snrIndex,:),1,[]);
        predictionSecondColumn(row,:) = reshape( ...
            predictionSecondHalfRmse(scenario,snrIndex,:),1,[]);
    end
end

auditTable = table(scenarioColumn,snrColumn, ...
    baseCandidatePerFrame,quarantinePerFrame,anchorPerFrame,promotedPerFrame, ...
    acceptedPerFrame(:,1),acceptedPerFrame(:,2),acceptedPerFrame(:,3), ...
    acceptedPerFrame(:,4), ...
    falseAccepted(:,1),falseAccepted(:,2),falseAccepted(:,3), ...
    falseAccepted(:,4), ...
    precisionColumn(:,1),precisionColumn(:,2),precisionColumn(:,3), ...
    precisionColumn(:,4), ...
    measurementRmseColumn(:,1),measurementRmseColumn(:,2), ...
    measurementRmseColumn(:,3),measurementRmseColumn(:,4), ...
    measurementP95Column(:,1),measurementP95Column(:,2), ...
    measurementP95Column(:,3),measurementP95Column(:,4), ...
    meanMaximumGap(:,1),meanMaximumGap(:,2),meanMaximumGap(:,3), ...
    meanMaximumGap(:,4), ...
    meanLastPilot(:,1),meanLastPilot(:,2),meanLastPilot(:,3), ...
    meanLastPilot(:,4), ...
    framesWithoutPilot(:,1),framesWithoutPilot(:,2), ...
    framesWithoutPilot(:,3),framesWithoutPilot(:,4), ...
    predictionRmseColumn(:,1),predictionRmseColumn(:,2), ...
    predictionRmseColumn(:,3),predictionRmseColumn(:,4), ...
    predictionRmseColumn(:,5), ...
    predictionSecondColumn(:,1),predictionSecondColumn(:,2), ...
    predictionSecondColumn(:,3),predictionSecondColumn(:,4), ...
    predictionSecondColumn(:,5), ...
    'VariableNames',{'scenario','snrDb','baseCandidatesPerFrame', ...
    'quarantinePerFrame','anchorsPerFrame','promotedPerFrame', ...
    'acceptedHardPerFrame','acceptedFivePassPerFrame', ...
    'acceptedQualityPerFrame','acceptedTrustedPerFrame', ...
    'falseHard','falseFivePass','falseQuality','falseTrusted', ...
    'precisionHard','precisionFivePass','precisionQuality','precisionTrusted', ...
    'measurementRmseHard','measurementRmseFivePass', ...
    'measurementRmseQuality','measurementRmseTrusted', ...
    'measurementP95Hard','measurementP95FivePass', ...
    'measurementP95Quality','measurementP95Trusted', ...
    'meanMaxGapHard','meanMaxGapFivePass','meanMaxGapQuality', ...
    'meanMaxGapTrusted','meanLastPilotHard','meanLastPilotFivePass', ...
    'meanLastPilotQuality','meanLastPilotTrusted', ...
    'framesNoPilotHard','framesNoPilotFivePass','framesNoPilotQuality', ...
    'framesNoPilotTrusted','predictionRmseStatic','predictionRmseHard', ...
    'predictionRmseFivePass','predictionRmseQuality','predictionRmseTrusted', ...
    'secondHalfRmseStatic','secondHalfRmseHard','secondHalfRmseFivePass', ...
    'secondHalfRmseQuality','secondHalfRmseTrusted'});
writetable(auditTable,fullfile(resultDir,'confidence_audit.csv'));

fig = figure('Visible','off','Color','w','Position',[60 40 1500 1040]);
tiledlayout(3,2,'TileSpacing','compact','Padding','compact');
pilotStyles = {'o-','s-','d-','^-'};
predictionStyles = {'o--','s-','d-','^-','v-'};
for scenario = 1:scenarioCount
    rows = (scenario-1)*snrCount+(1:snrCount);
    nexttile(scenario);
    hold on;
    for method = 1:pilotMethodCount
        plot(options.SnrGridDb,acceptedPerFrame(rows,method), ...
            pilotStyles{method},'LineWidth',1.25,'MarkerSize',6);
    end
    grid on;
    ylabel('Accepted pilots / frame');
    title(scenarioTitles{scenario});
    legend(pilotNames,'Location','northwest');

    nexttile(2+scenario);
    hold on;
    for method = 1:pilotMethodCount
        plot(options.SnrGridDb,precisionColumn(rows,method), ...
            pilotStyles{method},'LineWidth',1.25,'MarkerSize',6);
    end
    grid on;
    ylim([0 1.05]);
    ylabel('Accepted-pilot precision');
    legend(pilotNames,'Location','southeast');

    nexttile(4+scenario);
    hold on;
    for method = 1:predictionMethodCount
        semilogy(options.SnrGridDb, ...
            predictionRmseColumn(rows,method),predictionStyles{method}, ...
            'LineWidth',1.25,'MarkerSize',6);
    end
    grid on;
    xlabel('Sample SNR (dB)');
    ylabel('CFO prediction RMSE (bins)');
    legend(predictionNames,'Location','best');
end
sgtitle(sprintf(['Virtual-pilot confidence audit: %d frames/point, ' ...
    'truth used after receiver processing'],options.FrameCount));
imagePath = fullfile(resultDir,'confidence_audit.png');
exportgraphics(fig,imagePath,'Resolution',180);
savefig(fig,fullfile(resultDir,'confidence_audit.fig'));
close(fig);

save(fullfile(resultDir,'confidence_audit.mat'), ...
    'config','options','scenarioKeys','startTimes','predictionNames', ...
    'pilotNames','acceptedCount','falseAcceptedCount','precision', ...
    'measurementError','measurementRmse','measurementP95', ...
    'predictionRmse','predictionSecondHalfRmse','auditTable', ...
    'commonNoiseMaxDifference');
report = struct('resultDir',resultDir,'imagePath',imagePath, ...
    'table',auditTable,'acceptedCount',acceptedCount, ...
    'falseAcceptedCount',falseAcceptedCount,'precision',precision, ...
    'measurementRmse',measurementRmse,'measurementP95',measurementP95, ...
    'predictionRmse',predictionRmse, ...
    'predictionSecondHalfRmse',predictionSecondHalfRmse, ...
    'commonNoiseMaxDifference',commonNoiseMaxDifference);
fprintf('Stage 16 confidence audit: %s\n',resultDir);
fprintf('Maximum cross-scenario noise mismatch: %.3g\n', ...
    commonNoiseMaxDifference);
end

function value = localPercentile(samples,percent)
samples = sort(samples(:));
if isempty(samples)
    value = NaN;
    return
end
position = 1+(numel(samples)-1)*percent/100;
lowerIndex = floor(position);
upperIndex = ceil(position);
weight = position-lowerIndex;
value = (1-weight)*samples(lowerIndex)+weight*samples(upperIndex);
end
