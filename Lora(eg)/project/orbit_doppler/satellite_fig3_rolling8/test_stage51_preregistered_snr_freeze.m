classdef test_stage51_preregistered_snr_freeze < SenLoRaStageTestCase
    %TEST_STAGE51_PREREGISTERED_SNR_FREEZE MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage51_preregistered_snr_freeze();
        end
    end
end

function check_test_stage51_preregistered_snr_freeze()
%TEST_STAGE51_PREREGISTERED_SNR_FREEZE Theory-only deterministic selection.

before = rng;
report = run_stage51_preregistered_snr_freeze( ...
    OutputFolderName='stage51_preregistered_snr_freeze_wiring_test');
after = rng;
assert(isequal(before,after), ...
    'The deterministic theory-only SNR freeze consumed random numbers.');
assert(isequal(report.candidateTable.snrDb,(-23:-19).'), ...
    'The registered Stage 51 candidate grid changed.');
assert(report.mainSnrDb == -21, ...
    'The theory-only main target must freeze at -21 dB.');
assert(report.supplementalSnrDb == -20, ...
    'The theory-only supplemental target must freeze at -20 dB.');
assert(~report.freeze.receiverOutputsUsedForSelection && ...
    ~report.freeze.randomNumbersUsedForSelection, ...
    'The freeze record does not state the required independence.');
assert(report.selectionTable.selectedTheoryBer(1) > 1e-3 && ...
    report.selectionTable.selectedTheoryBer(2) > 1e-4, ...
    'Unexpected analytical BER values entered the freeze.');
assert(isfile(report.imagePath) && isfile(report.candidateCsvPath) && ...
    isfile(report.selectionCsvPath) && isfile(report.jsonPath) && ...
    isfile(report.matPath), ...
    'A Stage 51 audit artifact is missing.');
fprintf('Stage 51 preregistered SNR-freeze test passed.\n');
end
