classdef test_stage55_vp_quality_aware < SenLoRaStageTestCase
    %TEST_STAGE55_VP_QUALITY_AWARE MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage55_vp_quality_aware();
        end
    end
end

function check_test_stage55_vp_quality_aware()
%TEST_STAGE55_VP_QUALITY_AWARE Exercise fused CFO and observable VP rate.

config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
known = zeros(config.bootstrapPilotCount,1);
labels = zeros(config.frameSymbolCount,1);
[rx,~,~] = generateContinuousSatelliteFrame(labels,config, ...
    StartTimeSec=schedule.frameStartTimeSec(1),SampleSnrDb=Inf, ...
    NoiseSeed=2026460901,NextSymbolBin=0);
requested = false(config.frameSymbolCount,1);
requested(1:config.bootstrapPilotCount) = true;
requested(config.bootstrapPilotCount+1:7:end) = true;
tracker = satelliteFig3RollingPilotTracker(rx,config,known, ...
    AcceptedMask=requested,ForceAccept=true, ...
    FreezeBootstrapRate=true, ...
    RateDeviationLimitBinsPerSec= ...
        config.senloraRateTrackingDeviationLimitBinsPerSec, ...
    VirtualPilotInnovationGain= ...
        config.senloraVirtualPilotInnovationGain, ...
    EnableVirtualPilotPhasePairCfo=true, ...
    VirtualPilotPhasePairInnovationGain= ...
        config.senloraPhasePairInnovationGain, ...
    PhasePairInnovationLimitBins= ...
        config.senloraPhasePairInnovationLimitBins, ...
    PhasePairAgreementLimitBins= ...
        config.senloraPhasePairAgreementLimitBins, ...
    UseObservableVirtualPilotRate=true, ...
    VirtualPilotCfoStdBins=config.senloraVirtualPilotCfoStdBins, ...
    VirtualPilotRateStdLimitBinsPerSec= ...
        config.senloraVirtualPilotRateStdLimitBinsPerSec);

payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
accepted = payloadRows(tracker.pilotAccepted(payloadRows));
assert(numel(accepted) >= 8, ...
    'The deterministic quality-aware test lacks VP evidence.');
assert(any(tracker.phasePairUsed(accepted)), ...
    'No guarded phase-pair CFO observation was used.');
assert(any(tracker.virtualPilotRateObservable(payloadRows)), ...
    'The long VP baseline did not release an observable rate.');

singleRows = accepted(~tracker.phasePairUsed(accepted));
singleRows = singleRows(isfinite( ...
    tracker.rawSingleVirtualPilotCfoBins(singleRows)));
expectedSingle = tracker.predictedCfoBins(singleRows)+ ...
    config.senloraVirtualPilotInnovationGain*( ...
    tracker.rawSingleVirtualPilotCfoBins(singleRows)- ...
    tracker.predictedCfoBins(singleRows));
assert(max(abs(expectedSingle- ...
        tracker.virtualPilotMeasurementCfoBins(singleRows))) < 1e-12, ...
    'Single-symbol VP innovation fusion is inconsistent.');

pairRows = accepted(tracker.phasePairUsed(accepted));
expectedPair = tracker.predictedCfoBins(pairRows)+ ...
    config.senloraPhasePairInnovationGain*( ...
    tracker.phasePairCandidateCfoBins(pairRows)- ...
    tracker.predictedCfoBins(pairRows));
assert(max(abs(expectedPair- ...
        tracker.virtualPilotMeasurementCfoBins(pairRows))) < 1e-12, ...
    'Phase-pair VP innovation fusion is inconsistent.');

decoded = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(1), ...
    UseQualityAwareVirtualPilots=true);
assert(decoded.qualityAwareVirtualPilotsEnabled && ...
        decoded.tracker.virtualPilotPhasePairCfoEnabled, ...
    'The Stage55 wrapper did not wire the quality-aware mode.');
fprintf('Stage 55 quality-aware VP test passed: %d VPs, %d phase pairs.\n', ...
    numel(accepted),sum(tracker.phasePairUsed(accepted)));
end
