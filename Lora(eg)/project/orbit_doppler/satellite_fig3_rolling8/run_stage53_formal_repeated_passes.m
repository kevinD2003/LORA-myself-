function report = run_stage53_formal_repeated_passes(options)
%RUN_STAGE53_FORMAL_REPEATED_PASSES Frozen formal time-axis experiment.
%   The default processes one complete 508-frame pass per call.  Reinvoke
%   with Resume=true until report.allCompleted is true.  These seeds are
%   intentionally disjoint from the Stage 50/52 wiring inspections.

arguments
    options.FrameBudgetThisCall (1,1) double = 508
    options.Resume (1,1) logical = true
    options.WriteArtifacts (1,1) logical = true
    options.ProgressEveryFrames (1,1) double = 100
    options.DryRun (1,1) logical = false
end

frozen = struct( ...
    'SnrGridDb',[-21;-20], ...
    'MinCompletePasses',5, ...
    'MaxCompletePasses',20, ...
    'TargetBitErrorsPerMethod',300, ...
    'CheckpointEveryFrames',10, ...
    'PayloadSeedBase',2026150800, ...
    'NoiseSeedBase',2026150900, ...
    'WindowDurationSec',10, ...
    'BootstrapReplicates',10000, ...
    'BootstrapSeed',2026151000, ...
    'OutputFolderName','stage53_formal_repeated_passes');
if options.DryRun
    report = struct('frozenOptions',frozen,'allCompleted',false, ...
        'framesUsedThisCall',0);
    return
end

report = run_stage52_continuous_pass_formal( ...
    SnrGridDb=frozen.SnrGridDb, ...
    MinCompletePasses=frozen.MinCompletePasses, ...
    MaxCompletePasses=frozen.MaxCompletePasses, ...
    TargetBitErrorsPerMethod=frozen.TargetBitErrorsPerMethod, ...
    FrameBudgetThisCall=options.FrameBudgetThisCall, ...
    CheckpointEveryFrames=frozen.CheckpointEveryFrames, ...
    PayloadSeedBase=frozen.PayloadSeedBase, ...
    NoiseSeedBase=frozen.NoiseSeedBase, ...
    WindowDurationSec=frozen.WindowDurationSec, ...
    BootstrapReplicates=frozen.BootstrapReplicates, ...
    BootstrapSeed=frozen.BootstrapSeed, ...
    OutputFolderName=frozen.OutputFolderName,Resume=options.Resume, ...
    WriteArtifacts=options.WriteArtifacts, ...
    ProgressEveryFrames=options.ProgressEveryFrames);
report.frozenOptions = frozen;
end
