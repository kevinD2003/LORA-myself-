classdef test_stage52_continuous_pass_checkpoint < SenLoRaStageTestCase
    %TEST_STAGE52_CONTINUOUS_PASS_CHECKPOINT MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage52_continuous_pass_checkpoint();
        end
    end
end

function check_test_stage52_continuous_pass_checkpoint()
%TEST_STAGE52_CONTINUOUS_PASS_CHECKPOINT Resume must equal one-shot state.

common = {'SnrGridDb',-21,'MinCompletePasses',1, ...
    'MaxCompletePasses',1,'TargetBitErrorsPerMethod',1, ...
    'WriteArtifacts',false,'ProgressEveryFrames',Inf, ...
    'CheckpointEveryFrames',2};
first = run_stage52_continuous_pass_formal(common{:}, ...
    'FrameBudgetThisCall',2,'Resume',false, ...
    'OutputFolderName','stage52_checkpoint_resume_test');
assert(first.framesUsedThisCall == 2 && ...
    first.state.pointerFrameIndex == 3, ...
    'The first checkpoint call did not stop at the registered frame budget.');
second = run_stage52_continuous_pass_formal(common{:}, ...
    'FrameBudgetThisCall',3,'Resume',true, ...
    'OutputFolderName','stage52_checkpoint_resume_test');
assert(second.state.pointerFrameIndex == 6 && ...
    second.state.totalFramesProcessed == 5, ...
    'The resumed call did not continue from the next frame.');

oneShot = run_stage52_continuous_pass_formal(common{:}, ...
    'FrameBudgetThisCall',5,'Resume',false, ...
    'OutputFolderName','stage52_checkpoint_oneshot_test');
fields = {'processed','payloadSeed','noiseSeed','bitCount', ...
    'staticBitErrors','senBitErrors','staticFrameError','senFrameError', ...
    'staticCfoSseBins','senCfoSseBins','cfoSampleCount', ...
    'senAcceptedPilots','senFalseAcceptedPilots', ...
    'maxPhaseBridgeErrorRad','maxPhasePropagationErrorRad', ...
    'maxTimeGapErrorSec','pointerSnrIndex','pointerPassIndex', ...
    'pointerFrameIndex','phaseStateRad','previousLastPhaseRad', ...
    'previousLastDopplerHz','previousLastTimeSec', ...
    'previousNextFrameStartPhaseRad','totalFramesProcessed'};
for fieldIndex = 1:numel(fields)
    field = fields{fieldIndex};
    assert(isequaln(second.state.(field),oneShot.state.(field)), ...
        'Resumed and one-shot Stage 52 state differ in %s.',field);
end

mismatchCaught = false;
try
    run_stage52_continuous_pass_formal(common{:}, ...
        'NoiseSeedBase',2026120901,'FrameBudgetThisCall',1, ...
        'Resume',true, ...
        'OutputFolderName','stage52_checkpoint_resume_test');
catch exception
    mismatchCaught = strcmp(exception.identifier, ...
        'SatelliteFig3:Stage52ResumeMismatch');
end
assert(mismatchCaught, ...
    'A changed Stage 52 seed did not invalidate the checkpoint.');
assert(second.state.commonBootstrapCfoMaxDifferenceBins == 0 && ...
    second.state.commonPayloadStartPhaseMaxDifferenceRad == 0, ...
    'The formal receiver pair did not share the required initialization.');
fprintf('Stage 52 continuous-pass checkpoint test passed.\n');
end
