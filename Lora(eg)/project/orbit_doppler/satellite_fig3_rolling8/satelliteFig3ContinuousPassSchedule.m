function schedule = satelliteFig3ContinuousPassSchedule(config,options)
%SATELLITEFIG3CONTINUOUSPASSSCHEDULE Contiguous complete frames in one pass.
%   The schedule spans acquisition to loss of the Figure-3 outer window.
%   It also records the central model-defined blind interval.  Frame end
%   time is exclusive, so the last sample occurs one sample period earlier.

arguments
    config (1,1) struct
    options.PassStartTimeSec (1,1) double = NaN
    options.PassEndTimeSec (1,1) double = NaN
end

[window,~] = satelliteFig3VisibilityWindow(config);
passStartTimeSec = options.PassStartTimeSec;
passEndTimeSec = options.PassEndTimeSec;
if ~isfinite(passStartTimeSec)
    passStartTimeSec = config.centralVisibilityTimeSec- ...
        window.deltaTimeOutSec;
end
if ~isfinite(passEndTimeSec)
    passEndTimeSec = config.centralVisibilityTimeSec+ ...
        window.deltaTimeOutSec;
end
if passEndTimeSec <= passStartTimeSec
    error('SatelliteFig3:PassScheduleBounds', ...
        'Pass end time must be later than pass start time.');
end

frameDurationSec = config.frameSymbolCount*config.symbolDurationSec;
frameSampleCount = config.frameSymbolCount*config.samplesPerSymbol;
spanSec = passEndTimeSec-passStartTimeSec;
frameCount = floor(spanSec/frameDurationSec+ ...
    10*eps(max(1,spanSec/frameDurationSec)));
frameIndex = (1:frameCount).';
frameStartTimeSec = passStartTimeSec+(frameIndex-1)*frameDurationSec;
frameEndTimeSec = frameStartTimeSec+frameDurationSec;
frameLastSampleTimeSec = frameEndTimeSec-1/config.sampleRateHz;
frameCenterTimeSec = frameStartTimeSec+frameDurationSec/2;

visibleDurationSec = zeros(frameCount,1);
for intervalIndex = 1:size(window.intervalsSec,1)
    overlapStart = max(frameStartTimeSec,window.intervalsSec(intervalIndex,1));
    overlapEnd = min(frameEndTimeSec,window.intervalsSec(intervalIndex,2));
    visibleDurationSec = visibleDurationSec+max(0,overlapEnd-overlapStart);
end
visibleFraction = min(1,max(0,visibleDurationSec/frameDurationSec));
tolerance = 100*eps(max(1,frameDurationSec));
fullyVisible = visibleFraction >= 1-tolerance;
fullyBlind = visibleFraction <= tolerance;
transitionFrame = ~fullyVisible & ~fullyBlind;
[~,centerVisible] = satelliteFig3VisibilityWindow(config,frameCenterTimeSec);

frameTable = table(frameIndex,frameStartTimeSec,frameCenterTimeSec, ...
    frameLastSampleTimeSec,frameEndTimeSec,visibleFraction, ...
    fullyVisible,fullyBlind,transitionFrame,centerVisible);
schedule = struct( ...
    'passStartTimeSec',passStartTimeSec, ...
    'passEndTimeSec',passEndTimeSec, ...
    'passSpanSec',spanSec, ...
    'frameDurationSec',frameDurationSec, ...
    'frameSampleCount',frameSampleCount, ...
    'frameCount',frameCount, ...
    'frameIndex',frameIndex, ...
    'frameStartTimeSec',frameStartTimeSec, ...
    'frameCenterTimeSec',frameCenterTimeSec, ...
    'frameLastSampleTimeSec',frameLastSampleTimeSec, ...
    'frameEndTimeSec',frameEndTimeSec, ...
    'visibleFraction',visibleFraction, ...
    'fullyVisible',fullyVisible, ...
    'fullyBlind',fullyBlind, ...
    'transitionFrame',transitionFrame, ...
    'centerVisible',centerVisible, ...
    'completeFrameRemainderSec',passEndTimeSec-frameEndTimeSec(end), ...
    'window',window, ...
    'frameTable',frameTable);
end
