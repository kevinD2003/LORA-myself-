function report = run_stage24_rate_replay_audit(options)
%RUN_STAGE24_RATE_REPLAY_AUDIT Independent audit of blind rate replay.

arguments
    options.SnrGridDb (:,1) double = (-24:2:-14).'
    options.FrameCount (1,1) double {mustBeInteger,mustBePositive} = 8
    options.SymbolSeedBase (1,1) double = 2026090800
    options.NoiseSeedBase (1,1) double = 2026090900
    options.OutputFolderName (1,:) char = 'stage24_rate_replay_audit'
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
[window,~] = satelliteFig3VisibilityWindow(config);
scenarioKeys = {'high_doppler_shift','high_doppler_rate'};
scenarioTitles = {'High Doppler shift','High Doppler rate'};
startTimes = [-window.deltaTimeOutSec,window.deltaTimeInSec];
methodNames = {'Joint preamble rate','Adaptive soft-Hamming replay'};
scenarioCount = numel(scenarioKeys);
snrCount = numel(options.SnrGridDb);
known = zeros(config.bootstrapPilotCount,1);

errors = zeros(scenarioCount,snrCount,2);
bits = zeros(scenarioCount,snrCount);
predictionSse = zeros(scenarioCount,snrCount,2);
accepted = zeros(scenarioCount,snrCount,2);
falseAccepted = zeros(scenarioCount,snrCount,2);
selectedRateErrorSse = zeros(scenarioCount,snrCount);
scoreGapSum = zeros(scenarioCount,snrCount);
replayTriggered = zeros(scenarioCount,snrCount);
commonNoiseMaxDifference = 0;

for snrIndex = 1:snrCount
    for frame = 1:options.FrameCount
        payload = satelliteFig3GeneratePayload(config, ...
            options.SymbolSeedBase+1000*snrIndex+frame);
        labels = [known;payload.symbolBins];
        payloadRows = config.bootstrapPilotCount+1:numel(labels);
        noiseReference = [];
        for scenario = 1:scenarioCount
            [rx,tx,truth] = generateContinuousSatelliteFrame(labels,config, ...
                StartTimeSec=startTimes(scenario), ...
                SampleSnrDb=options.SnrGridDb(snrIndex), ...
                NoiseSeed=options.NoiseSeedBase+1000*snrIndex+frame);
            channelNoise = rx-tx.*exp(1i*truth.phaseRad);
            if scenario == 1
                noiseReference = channelNoise;
            else
                commonNoiseMaxDifference = max(commonNoiseMaxDifference, ...
                    max(abs(channelNoise-noiseReference),[],'all'));
            end
            baseline = satelliteFig3QualityGatedSenLoRaDecode(rx,config,known);
            replay = satelliteFig3AdaptiveRateReplaySenLoRaDecode( ...
                rx,config,known);
            routes = {baseline,replay};
            truthBins = truth.trueDopplerHz/config.fftBinSpacingHz;
            centerTime = ((0:numel(labels)-1).'+0.5)* ...
                config.symbolDurationSec;
            trueFit = polyfit(centerTime,truthBins,1);
            selectedRateErrorSse(scenario,snrIndex) = ...
                selectedRateErrorSse(scenario,snrIndex)+( ...
                replay.rateReplay.selectedRateBinsPerSec-trueFit(1))^2;
            replayScoreGap = replay.rateReplay.scoreGap;
            if ~isfinite(replayScoreGap), replayScoreGap = 0; end
            scoreGapSum(scenario,snrIndex) = ...
                scoreGapSum(scenario,snrIndex)+replayScoreGap;
            replayTriggered(scenario,snrIndex) = ...
                replayTriggered(scenario,snrIndex)+ ...
                replay.rateReplay.triggered;
            for method = 1:2
                route = routes{method};
                errors(scenario,snrIndex,method) = ...
                    errors(scenario,snrIndex,method)+sum( ...
                    route.soft.decodedDataBits(:) ~= payload.dataBits(:));
                delta = route.tracker.predictedCfoBins(payloadRows)- ...
                    truthBins(payloadRows);
                predictionSse(scenario,snrIndex,method) = ...
                    predictionSse(scenario,snrIndex,method)+sum(delta.^2);
                mask = route.pilotAccepted(payloadRows);
                accepted(scenario,snrIndex,method) = ...
                    accepted(scenario,snrIndex,method)+sum(mask);
                falseAccepted(scenario,snrIndex,method) = ...
                    falseAccepted(scenario,snrIndex,method)+sum(mask & ...
                    route.detectedWaveformBins(payloadRows) ~= ...
                    labels(payloadRows));
            end
            bits(scenario,snrIndex) = bits(scenario,snrIndex)+ ...
                numel(payload.dataBits);
        end
    end
end

bitScale = repmat(reshape(bits,scenarioCount,snrCount,1),1,1,2);
[shownBer,lower95,upper95] = satelliteFig3BerInterval95(errors,bitScale);
predictionRmse = sqrt(predictionSse/( ...
    options.FrameCount*config.payloadSymbolCount));
precision = 1-falseAccepted./accepted;
precision(accepted == 0) = NaN;
rateRmse = sqrt(selectedRateErrorSse/options.FrameCount);
meanScoreGap = scoreGapSum/options.FrameCount;

rows = cell(scenarioCount*snrCount,1);
row = 0;
for scenario = 1:scenarioCount
    for snrIndex = 1:snrCount
        row = row+1;
        rows{row} = {scenarioKeys{scenario},options.SnrGridDb(snrIndex), ...
            bits(scenario,snrIndex), ...
            errors(scenario,snrIndex,1),errors(scenario,snrIndex,2), ...
            shownBer(scenario,snrIndex,1),shownBer(scenario,snrIndex,2), ...
            lower95(scenario,snrIndex,1),lower95(scenario,snrIndex,2), ...
            upper95(scenario,snrIndex,1),upper95(scenario,snrIndex,2), ...
            predictionRmse(scenario,snrIndex,1), ...
            predictionRmse(scenario,snrIndex,2), ...
            accepted(scenario,snrIndex,1),accepted(scenario,snrIndex,2), ...
            falseAccepted(scenario,snrIndex,1), ...
            falseAccepted(scenario,snrIndex,2), ...
            precision(scenario,snrIndex,1),precision(scenario,snrIndex,2), ...
            rateRmse(scenario,snrIndex),meanScoreGap(scenario,snrIndex), ...
            replayTriggered(scenario,snrIndex)};
    end
end
resultTable = cell2table(vertcat(rows{:}),'VariableNames',{ ...
    'scenario','snrDb','bits','errBaseline','errReplay', ...
    'berBaseline','berReplay','lower95Baseline','lower95Replay', ...
    'upper95Baseline','upper95Replay','cfoRmseBaseline','cfoRmseReplay', ...
    'acceptedBaseline','acceptedReplay','falseBaseline','falseReplay', ...
    'precisionBaseline','precisionReplay','selectedRateRmse','meanScoreGap', ...
    'replayTriggeredFrames'});
writetable(resultTable,fullfile(resultDir,'rate_replay_audit.csv'));

fig = figure('Visible','off','Color','w','Position',[60 40 1500 900]);
tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
for scenario = 1:scenarioCount
    nexttile;
    for method = 1:2
        semilogy(options.SnrGridDb, ...
            reshape(shownBer(scenario,:,method),[],1),'o-', ...
            'LineWidth',1.2,'DisplayName',methodNames{method}); hold on;
    end
    grid on; ylim([1e-4 1]); xlabel('Sample SNR (dB)');
    ylabel('Payload BER'); title(scenarioTitles{scenario}); legend;
end
for scenario = 1:scenarioCount
    nexttile;
    for method = 1:2
        semilogy(options.SnrGridDb, ...
            reshape(predictionRmse(scenario,:,method),[],1),'o-', ...
            'LineWidth',1.2,'DisplayName',methodNames{method}); hold on;
    end
    grid on; xlabel('Sample SNR (dB)'); ylabel('CFO prediction RMSE (bins)');
    title([scenarioTitles{scenario},' tracking']); legend;
end
sgtitle(sprintf('Blind rate-replay audit: %d independent frames/point', ...
    options.FrameCount));
imagePath = fullfile(resultDir,'rate_replay_audit.png');
exportgraphics(fig,imagePath,'Resolution',180);
savefig(fig,fullfile(resultDir,'rate_replay_audit.fig'));
close(fig);
save(fullfile(resultDir,'rate_replay_audit.mat'), ...
    'config','options','scenarioKeys','startTimes','methodNames', ...
    'errors','bits','shownBer','lower95','upper95','predictionRmse', ...
    'accepted','falseAccepted','precision','rateRmse','meanScoreGap', ...
    'replayTriggered', ...
    'commonNoiseMaxDifference','resultTable');
report = struct('resultDir',resultDir,'imagePath',imagePath, ...
    'table',resultTable,'errors',errors,'bits',bits, ...
    'shownBer',shownBer,'predictionRmse',predictionRmse, ...
    'commonNoiseMaxDifference',commonNoiseMaxDifference);
fprintf('Stage 24 rate-replay audit: %s\n',resultDir);
fprintf('Accepted replay pilots: %d; false: %d; noise mismatch %.3g.\n', ...
    sum(accepted(:,:,2),'all'),sum(falseAccepted(:,:,2),'all'), ...
    commonNoiseMaxDifference);
end
