classdef test_stage49_continuous_pass_frames < SenLoRaStageTestCase
    %TEST_STAGE49_CONTINUOUS_PASS_FRAMES MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage49_continuous_pass_frames();
        end
    end
end

function check_test_stage49_continuous_pass_frames()
%TEST_STAGE49_CONTINUOUS_PASS_FRAMES Exact time/phase across frame edges.

config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
[window,~] = satelliteFig3VisibilityWindow(config);
expectedCount = floor((2*window.deltaTimeOutSec)/( ...
    config.frameSymbolCount*config.symbolDurationSec));
assert(schedule.frameCount == expectedCount, ...
    'The pass schedule has the wrong number of complete frames.');
assert(abs(schedule.frameStartTimeSec(1)+window.deltaTimeOutSec) < 1e-12, ...
    'The first frame does not start at acquisition.');
assert(max(abs(diff(schedule.frameStartTimeSec)- ...
    config.frameSymbolCount*config.symbolDurationSec)) < 1e-11, ...
    'Frames are not contiguous in time.');
assert(schedule.frameEndTimeSec(end) <= window.deltaTimeOutSec+1e-12, ...
    'The final complete frame extends beyond the pass span.');
assert(schedule.frameEndTimeSec(end)+ ...
    config.frameSymbolCount*config.symbolDurationSec > ...
    window.deltaTimeOutSec, ...
    'One additional complete frame unexpectedly fits in the pass span.');
assert(any(schedule.fullyVisible) && any(schedule.fullyBlind) && ...
    any(schedule.transitionFrame), ...
    'Visible, blind, and boundary-transition frames were not distinguished.');

known = zeros(config.bootstrapPilotCount,1);
payload1 = satelliteFig3GeneratePayload(config,2026120201);
payload2 = satelliteFig3GeneratePayload(config,2026120202);
labels1 = [known;payload1.symbolBins];
labels2 = [known;payload2.symbolBins];
startTimeSec = window.deltaTimeInSec;
initialPhaseRad = 1.23456789;

[rxJoint,~,truthJoint] = generateContinuousSatelliteFrame( ...
    [labels1;labels2],config,StartTimeSec=startTimeSec, ...
    SampleSnrDb=Inf,InitialPhaseRad=initialPhaseRad);
[rx1,~,truth1] = generateContinuousSatelliteFrame(labels1,config, ...
    StartTimeSec=startTimeSec,SampleSnrDb=Inf, ...
    InitialPhaseRad=initialPhaseRad,NextSymbolBin=labels2(1));
[rx2,~,truth2] = generateContinuousSatelliteFrame(labels2,config, ...
    StartTimeSec=truth1.nextFrameStartTimeSec,SampleSnrDb=Inf, ...
    InitialPhaseRad=truth1.nextFrameStartPhaseRad);

m = config.samplesPerSymbol;
frameSamples = config.frameSymbolCount*m;
jointSerial = reshape(rxJoint.',[],1);
splitSerial = [reshape(rx1.',[],1);reshape(rx2.',[],1)];
assert(max(abs(jointSerial-splitSerial)) < 1e-8, ...
    'Split-frame waveform differs from the joint continuous reference.');
jointPhase = reshape(truthJoint.phaseRad.',[],1);
splitPhase = [reshape(truth1.phaseRad.',[],1); ...
    reshape(truth2.phaseRad.',[],1)];
assert(max(abs(jointPhase-splitPhase)) < 1e-8, ...
    'Split-frame phase differs from the joint continuous reference.');
assert(abs(truth2.sampleTimeSec(1,1)-truth1.sampleTimeSec(end,end)- ...
    1/config.sampleRateHz) < 1e-12, ...
    'There is a time gap or duplicated sample at the frame boundary.');
assert(abs(truth2.phaseRad(1,1)-truth1.nextFrameStartPhaseRad) < 1e-12, ...
    'The propagated phase was not applied to the next frame.');
expectedBridge = pi/config.sampleRateHz*( ...
    truth1.dopplerHz(end,end)+truth2.dopplerHz(1,1));
bridgeError = truth2.phaseRad(1,1)-truth1.phaseRad(end,end)-expectedBridge;
assert(abs(bridgeError) < 1e-10, ...
    'The trapezoidal Doppler phase bridge is discontinuous.');
assert(numel(jointSerial) == 2*frameSamples, ...
    'The two-frame reference has an unexpected sample count.');

fprintf('Stage 49 continuous-pass frame test passed.\n');
end
