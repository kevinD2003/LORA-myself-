classdef test_stage55_vp_control_wiring < SenLoRaStageTestCase
    %TEST_STAGE55_VP_CONTROL_WIRING MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage55_vp_control_wiring();
        end
    end
end

function check_test_stage55_vp_control_wiring()
%TEST_STAGE55_VP_CONTROL_WIRING Exercise paired SER/BER/PER accounting.

report = run_stage55_vp_control_comparison( ...
    SnrGridDb=-20,PassCount=1,FramesPerVisibleSegment=1, ...
    OutputFolderName='stage55_vp_control_wiring_test', ...
    ProgressEveryFrames=Inf,WriteFigures=false);
records = report.records;

assert(height(records) == 2, ...
    'The smoke run did not process one frame from both visible segments.');
assert(all(records.noVpAcceptedPilots == 0), ...
    'The NoVP control admitted payload pilots.');
assert(all(records.symbolCount == 112) && ...
    all(records.bitCount == 704), ...
    'The paired control uses an unexpected payload size.');
assert(all(records.noVpSymbolErrors >= 0 & ...
    records.noVpSymbolErrors <= records.symbolCount) && ...
    all(records.vpSymbolErrors >= 0 & ...
    records.vpSymbolErrors <= records.symbolCount), ...
    'SER accounting is outside the payload bounds.');
assert(~isempty(report.regionSummary) && ...
    ismember('noVpSer',report.regionSummary.Properties.VariableNames) && ...
    ismember('vpSer',report.regionSummary.Properties.VariableNames), ...
    'The control summary does not publish paired SER.');
regionCount = height(report.regionSummary);
assert(height(report.symbolPosition) == 112*regionCount && ...
    height(report.blockPosition) == 16*regionCount, ...
    'The payload-position SER summaries are incomplete.');
fprintf('Stage 55 paired VP control-wiring test passed.\n');
end
