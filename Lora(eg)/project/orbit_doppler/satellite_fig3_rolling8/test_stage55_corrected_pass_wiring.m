classdef test_stage55_corrected_pass_wiring < SenLoRaStageTestCase
    %TEST_STAGE55_CORRECTED_PASS_WIRING MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage55_corrected_pass_wiring();
        end
    end
end

function check_test_stage55_corrected_pass_wiring()
%TEST_STAGE55_CORRECTED_PASS_WIRING Verify state, rolling-8, and soft output.

report = run_stage55_corrected_pass_validation( ...
    SnrGridDb=-20,PassCount=1,FramesPerVisibleSegment=2, ...
    OutputFolderName='stage55_corrected_pass_wiring_test', ...
    ProgressEveryFrames=Inf);
records = report.records;
assert(height(records) == 4, ...
    'The two visible segments were not both exercised.');
assert(all(records.minimumActiveHistoryCount == 8), ...
    'A payload symbol was compensated with fewer than eight active pilots.');
assert(all(records.updatedSymbolCount >= 0 & ...
        records.updatedSymbolCount <= 112), ...
    'Updated virtual-pilot influence coverage is outside the frame.');
assert(report.summary.updatedSymbolCoverage == ...
        sum(records.updatedSymbolCount)/(112*height(records)), ...
    'The report does not publish the measured VP influence coverage.');
assert(all(records.crossFrameHistoryCount == repmat([1;2],2,1)), ...
    'Cross-frame state was not inherited and reset at segment boundaries.');
assert(report.summary.softBitErrors == ...
        sum(records.softBitErrors), ...
    'The published BER path is not the final soft-decoded payload.');
fprintf('Stage 55 corrected-pass wiring test passed.\n');
end
