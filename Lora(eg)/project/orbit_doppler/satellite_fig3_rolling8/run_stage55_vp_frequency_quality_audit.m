function report = run_stage55_vp_frequency_quality_audit(options)
%RUN_STAGE55_VP_FREQUENCY_QUALITY_AUDIT Calibrate receiver-only VP CFO error.
%   This audit uses seed bases disjoint from the Stage55 mechanism ablation.
%   Receiver decisions produce the uncertainty predictor; channel truth is
%   read only after decoding to audit calibration and is never fed back.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.PassCount (1,1) double ...
        {mustBeInteger,mustBePositive} = 1
    options.FramesPerVisibleSegment (1,1) double = Inf
    options.PayloadSeedBase (1,1) double = 2026450800
    options.NoiseSeedBase (1,1) double = 2026450900
    options.OutputFolderName (1,:) char = ...
        'stage55_vp_frequency_quality_audit'
    options.ProgressEveryFrames (1,1) double = 50
    options.WriteFigures (1,1) logical = true
end
if ~(isinf(options.FramesPerVisibleSegment) || ( ...
        options.FramesPerVisibleSegment >= 1 && ...
        options.FramesPerVisibleSegment == ...
        round(options.FramesPerVisibleSegment)))
    error('SatelliteFig3:VpQualityAuditFrames', ...
        'FramesPerVisibleSegment must be Inf or a positive integer.');
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
trajectory = satelliteFig3Trajectory(schedule.frameCenterTimeSec,config);
driftBinsPerFrame = abs(trajectory.dopplerRateHzPerSec).* ...
    schedule.frameDurationSec/config.fftBinSpacingHz;
segmentEdges = find(diff([false;schedule.fullyVisible(:);false]));
segments = reshape(segmentEdges,2,[]).'+[0 -1];
if isfinite(options.FramesPerVisibleSegment)
    segments(:,2) = min(segments(:,2), ...
        segments(:,1)+options.FramesPerVisibleSegment-1);
end

known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
samples = repmat(struct(),0,1);
frameRows = repmat(struct(),0,1);
frameCounter = 0;
for snrIndex = 1:numel(options.SnrGridDb)
    for passIndex = 1:options.PassCount
        for segmentIndex = 1:size(segments,1)
            crossFrameState = struct();
            phaseStateRad = 0;
            for frameIndex = segments(segmentIndex,1):segments(segmentIndex,2)
                payloadSeed = options.PayloadSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                noiseSeed = options.NoiseSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                payload = satelliteFig3GeneratePayload(config,payloadSeed);
                labels = [known;payload.symbolBins];
                [rx,~,truth] = generateContinuousSatelliteFrame( ...
                    labels,config, ...
                    StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    SampleSnrDb=options.SnrGridDb(snrIndex), ...
                    NoiseSeed=noiseSeed,InitialPhaseRad=phaseStateRad, ...
                    NextSymbolBin=0);
                phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);
                decoded = satelliteFig3SenLoRaVirtualPilotDecode( ...
                    rx,config,known, ...
                    FrameStartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    CrossFrameState=crossFrameState, ...
                    EnableVirtualPilots=true, ...
                    UseQualityAwareVirtualPilots=false);
                crossFrameState = decoded.crossFrameState;
                if driftBinsPerFrame(frameIndex) >= 0.5
                    region = 'high_doppler_rate';
                else
                    region = 'high_doppler_shift';
                end

                acceptedRows = payloadRows(decoded.pilotAccepted(payloadRows));
                frameRow = struct('snrDb',options.SnrGridDb(snrIndex), ...
                    'passIndex',passIndex,'segmentIndex',segmentIndex, ...
                    'frameIndex',frameIndex, ...
                    'frameCenterTimeSec',schedule.frameCenterTimeSec(frameIndex), ...
                    'region',region, ...
                    'crossFrameHistoryCount', ...
                        decoded.crossFrameRateDiagnostic.historyCount, ...
                    'acceptedVirtualPilots',numel(acceptedRows), ...
                    'rateReleased',numel(acceptedRows) >= ...
                        config.senloraRateReleasePilotCount);
                if isempty(frameRows)
                    frameRows = frameRow;
                else
                    frameRows(end+1,1) = frameRow; %#ok<AGROW>
                end

                for acceptedIndex = 1:numel(acceptedRows)
                    rowIndex = acceptedRows(acceptedIndex);
                    payloadPosition = rowIndex-config.bootstrapPilotCount;
                    trueCfo = truth.trueDopplerHz(rowIndex)/ ...
                        config.fftBinSpacingHz;
                    measuredCfo = decoded.tracker.measuredCfoBins(rowIndex);
                    predictedStd = ...
                        decoded.tracker.residualFrequencyStdBins(rowIndex);
                    measurementError = measuredCfo-trueCfo;
                    sample = struct( ...
                        'snrDb',options.SnrGridDb(snrIndex), ...
                        'passIndex',passIndex, ...
                        'segmentIndex',segmentIndex, ...
                        'frameIndex',frameIndex, ...
                        'frameCenterTimeSec', ...
                            schedule.frameCenterTimeSec(frameIndex), ...
                        'region',region, ...
                        'crossFrameHistoryCount', ...
                            decoded.crossFrameRateDiagnostic.historyCount, ...
                        'payloadSymbolPosition',payloadPosition, ...
                        'acceptedIndexInFrame',acceptedIndex, ...
                        'acceptedCountInFrame',numel(acceptedRows), ...
                        'detectedBin', ...
                            decoded.tracker.hardWaveformBins(rowIndex), ...
                        'trueBin',labels(rowIndex), ...
                        'labelCorrect', ...
                            decoded.tracker.hardWaveformBins(rowIndex) == ...
                            labels(rowIndex), ...
                        'predictedCfoBins', ...
                            decoded.tracker.predictedCfoBins(rowIndex), ...
                        'predictedRateBinsPerSec', ...
                            decoded.tracker.predictedRateBinsPerSec(rowIndex), ...
                        'predictedPhaseStartRad', ...
                            decoded.tracker.predictedPhaseStartRad(rowIndex), ...
                        'measuredCfoBins',measuredCfo, ...
                        'trueCfoBins',trueCfo, ...
                        'residualOffsetBins', ...
                            decoded.tracker.measuredResidualBins(rowIndex), ...
                        'measuredResidualPhaseRad', ...
                            decoded.tracker.measuredResidualPhaseRad(rowIndex), ...
                        'measuredPhaseStartRad', ...
                            decoded.tracker.predictedPhaseStartRad(rowIndex)+ ...
                            decoded.tracker.measuredResidualPhaseRad(rowIndex), ...
                        'truePhaseStartRad',truth.phaseRad(rowIndex,1), ...
                        'wrappedPhaseErrorRad',angle(exp(1i*( ...
                            decoded.tracker.predictedPhaseStartRad(rowIndex)+ ...
                            decoded.tracker.measuredResidualPhaseRad(rowIndex)- ...
                            truth.phaseRad(rowIndex,1)))), ...
                        'measurementErrorBins',measurementError, ...
                        'absoluteMeasurementErrorBins',abs(measurementError), ...
                        'predictedFrequencyStdBins',predictedStd, ...
                        'normalizedAbsoluteError', ...
                            abs(measurementError)/max(predictedStd,eps), ...
                        'residualPeakRatio', ...
                            decoded.tracker.residualPeakRatio(rowIndex), ...
                        'decisionPeakRatio', ...
                            decoded.tracker.peakRatio(rowIndex), ...
                        'confidence',decoded.confidence(rowIndex));
                    if isempty(samples)
                        samples = sample;
                    else
                        samples(end+1,1) = sample; %#ok<AGROW>
                    end
                end
                frameCounter = frameCounter+1;
                if isfinite(options.ProgressEveryFrames) && ...
                        options.ProgressEveryFrames > 0 && ...
                        mod(frameCounter,options.ProgressEveryFrames) == 0
                    fprintf('Stage55 VP quality audit: %d frames.\n', ...
                        frameCounter);
                end
            end
        end
    end
end

if isempty(samples)
    error('SatelliteFig3:VpQualityAuditEmpty', ...
        'The audit produced no accepted virtual pilots.');
end
samples = struct2table(samples);
frameRecords = struct2table(frameRows);
calibration = localCalibration(samples,options.SnrGridDb);
overall = localOverall(samples,options.SnrGridDb);
phasePairs = localPhasePairs(samples,config);
phasePairOverall = localPhasePairOverall(phasePairs,options.SnrGridDb);
writetable(samples,fullfile(resultDir, ...
    'stage55_vp_frequency_quality_samples.csv'));
writetable(frameRecords,fullfile(resultDir, ...
    'stage55_vp_frequency_quality_frames.csv'));
writetable(calibration,fullfile(resultDir, ...
    'stage55_vp_frequency_quality_calibration.csv'));
writetable(overall,fullfile(resultDir, ...
    'stage55_vp_frequency_quality_overall.csv'));
writetable(phasePairs,fullfile(resultDir, ...
    'stage55_vp_phase_pair_samples.csv'));
writetable(phasePairOverall,fullfile(resultDir, ...
    'stage55_vp_phase_pair_overall.csv'));
figureFiles = cell(0,1);
if options.WriteFigures
    figureFiles = localWriteFigure(calibration,overall, ...
        options.SnrGridDb,resultDir);
end
matFile = fullfile(resultDir,'stage55_vp_frequency_quality_audit.mat');
save(matFile,'config','schedule','segments','options','samples', ...
    'frameRecords','calibration','overall','phasePairs', ...
    'phasePairOverall','figureFiles');
report = struct('resultDir',resultDir,'samples',samples, ...
    'frameRecords',frameRecords,'calibration',calibration, ...
    'overall',overall,'phasePairs',phasePairs, ...
    'phasePairOverall',phasePairOverall, ...
    'figureFiles',{figureFiles},'matFile',matFile);
fprintf('Stage55 VP frequency-quality audit: %s\n',resultDir);
disp(overall);
disp(calibration);
disp(phasePairOverall);
end

function pairs = localPhasePairs(samples,config)
% Two accepted virtual pilots provide a receiver-visible phase baseline.
% Truth below is used only to audit that measurement after decoding.
[group,~,~,~,~] = findgroups(samples.snrDb,samples.passIndex, ...
    samples.segmentIndex,samples.frameIndex);
rows = repmat(struct(),0,1);
for groupIndex = 1:max(group)
    frame = samples(group == groupIndex,:);
    [~,order] = sort(frame.payloadSymbolPosition);
    frame = frame(order,:);
    for pairIndex = 2:height(frame)
        first = frame(pairIndex-1,:);
        second = frame(pairIndex,:);
        gapSymbols = second.payloadSymbolPosition- ...
            first.payloadSymbolPosition;
        measuredAverage = (second.measuredPhaseStartRad- ...
            first.measuredPhaseStartRad)/(2*pi*gapSymbols);
        trueAverage = (second.truePhaseStartRad- ...
            first.truePhaseStartRad)/(2*pi*gapSymbols);
        predictedAverage = (second.predictedPhaseStartRad- ...
            first.predictedPhaseStartRad)/(2*pi*gapSymbols);
        endpointEstimate = measuredAverage+0.5* ...
            second.predictedRateBinsPerSec* ...
            gapSymbols*config.symbolDurationSec;
        row = struct('snrDb',second.snrDb, ...
            'passIndex',second.passIndex, ...
            'segmentIndex',second.segmentIndex, ...
            'frameIndex',second.frameIndex, ...
            'frameCenterTimeSec',second.frameCenterTimeSec, ...
            'region',second.region, ...
            'crossFrameHistoryCount',second.crossFrameHistoryCount, ...
            'firstPayloadSymbolPosition', ...
                first.payloadSymbolPosition, ...
            'secondPayloadSymbolPosition', ...
                second.payloadSymbolPosition, ...
            'gapSymbols',gapSymbols, ...
            'baselineSec',gapSymbols*config.symbolDurationSec, ...
            'measuredAverageCfoBins',measuredAverage, ...
            'predictedAverageCfoBins',predictedAverage, ...
            'trueAverageCfoBins',trueAverage, ...
            'averageMeasurementErrorBins', ...
                measuredAverage-trueAverage, ...
            'receiverInnovationBins', ...
                measuredAverage-predictedAverage, ...
            'endpointCfoEstimateBins',endpointEstimate, ...
            'trueEndpointCfoBins',second.trueCfoBins, ...
            'endpointMeasurementErrorBins', ...
                endpointEstimate-second.trueCfoBins, ...
            'secondSingleSymbolErrorBins', ...
                second.measurementErrorBins, ...
            'firstWrappedPhaseErrorRad',first.wrappedPhaseErrorRad, ...
            'secondWrappedPhaseErrorRad',second.wrappedPhaseErrorRad);
        if isempty(rows)
            rows = row;
        else
            rows(end+1,1) = row; %#ok<AGROW>
        end
    end
end
if isempty(rows)
    pairs = table();
else
    pairs = struct2table(rows);
end
end

function overall = localPhasePairOverall(pairs,snrGrid)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
rows = repmat(struct(),0,1);
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        selected = pairs.snrDb == snrGrid(snrIndex) & ...
            strcmp(pairs.region,regionKeys{regionIndex});
        group = pairs(selected,:);
        if isempty(group), continue; end
        averageError = group.averageMeasurementErrorBins;
        endpointError = group.endpointMeasurementErrorBins;
        singleError = group.secondSingleSymbolErrorBins;
        row = struct('snrDb',snrGrid(snrIndex), ...
            'region',regionKeys{regionIndex}, ...
            'pairCount',height(group), ...
            'meanGapSymbols',mean(group.gapSymbols), ...
            'medianGapSymbols',median(group.gapSymbols), ...
            'phaseAverageBiasBins',mean(averageError), ...
            'phaseAverageRmseBins',sqrt(mean(averageError.^2)), ...
            'phaseEndpointRmseBins',sqrt(mean(endpointError.^2)), ...
            'singleSymbolRmseBins',sqrt(mean(singleError.^2)), ...
            'phaseEndpointBetterFraction', ...
                mean(abs(endpointError) < abs(singleError)), ...
            'cycleSlipLikeFraction',mean(abs(averageError) > 0.15));
        if isempty(rows)
            rows = row;
        else
            rows(end+1,1) = row; %#ok<AGROW>
        end
    end
end
overall = struct2table(rows);
end

function calibration = localCalibration(samples,snrGrid)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
rows = repmat(struct(),0,1);
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        selected = samples.snrDb == snrGrid(snrIndex) & ...
            strcmp(samples.region,regionKeys{regionIndex});
        group = samples(selected,:);
        if isempty(group), continue; end
        [~,order] = sort(group.predictedFrequencyStdBins);
        count = height(group);
        for quartile = 1:4
            first = floor((quartile-1)*count/4)+1;
            last = floor(quartile*count/4);
            bin = group(order(first:last),:);
            errorValues = bin.measurementErrorBins;
            row = struct('snrDb',snrGrid(snrIndex), ...
                'region',regionKeys{regionIndex}, ...
                'uncertaintyQuartile',quartile, ...
                'sampleCount',height(bin), ...
                'minimumPredictedStdBins', ...
                    min(bin.predictedFrequencyStdBins), ...
                'meanPredictedStdBins', ...
                    mean(bin.predictedFrequencyStdBins), ...
                'maximumPredictedStdBins', ...
                    max(bin.predictedFrequencyStdBins), ...
                'actualBiasBins',mean(errorValues), ...
                'actualRmseBins',sqrt(mean(errorValues.^2)), ...
                'meanAbsoluteErrorBins',mean(abs(errorValues)), ...
                'coverageWithinOneStd',mean(abs(errorValues) <= ...
                    bin.predictedFrequencyStdBins), ...
                'coverageWithinTwoStd',mean(abs(errorValues) <= ...
                    2*bin.predictedFrequencyStdBins), ...
                'labelErrorCount',sum(~bin.labelCorrect));
            if isempty(rows)
                rows = row;
            else
                rows(end+1,1) = row; %#ok<AGROW>
            end
        end
    end
end
calibration = struct2table(rows);
end

function overall = localOverall(samples,snrGrid)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
rows = repmat(struct(),0,1);
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        selected = samples.snrDb == snrGrid(snrIndex) & ...
            strcmp(samples.region,regionKeys{regionIndex});
        group = samples(selected,:);
        if isempty(group), continue; end
        errorValues = group.measurementErrorBins;
        predictor = group.predictedFrequencyStdBins;
        row = struct('snrDb',snrGrid(snrIndex), ...
            'region',regionKeys{regionIndex}, ...
            'sampleCount',height(group), ...
            'labelErrorCount',sum(~group.labelCorrect), ...
            'meanPredictedStdBins',mean(predictor), ...
            'actualBiasBins',mean(errorValues), ...
            'actualRmseBins',sqrt(mean(errorValues.^2)), ...
            'absoluteErrorCorrelation',corr(predictor,abs(errorValues)), ...
            'coverageWithinOneStd',mean(abs(errorValues) <= predictor), ...
            'coverageWithinTwoStd',mean(abs(errorValues) <= 2*predictor));
        if isempty(rows)
            rows = row;
        else
            rows(end+1,1) = row; %#ok<AGROW>
        end
    end
end
overall = struct2table(rows);
end

function files = localWriteFigure(calibration,overall,snrGrid,resultDir)
figureHandle = figure('Visible','off','Color','w', ...
    'Position',[100 100 1500 800]);
layout = tiledlayout(numel(snrGrid),2,'TileSpacing','compact', ...
    'Padding','compact');
title(layout,'Receiver-only VP CFO uncertainty calibration');
regionKeys = {'high_doppler_rate','high_doppler_shift'};
regionNames = {'High Doppler rate','High Doppler shift'};
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        selected = calibration.snrDb == snrGrid(snrIndex) & ...
            strcmp(calibration.region,regionKeys{regionIndex});
        rows = calibration(selected,:);
        nexttile;
        plot(rows.meanPredictedStdBins,rows.actualRmseBins, ...
            '-o','LineWidth',1.6,'MarkerFaceColor',[0 0.447 0.741]);
        hold on
        limits = [min([rows.meanPredictedStdBins;rows.actualRmseBins]), ...
            max([rows.meanPredictedStdBins;rows.actualRmseBins])];
        plot(limits,limits,'k--','LineWidth',1);
        grid on; axis square
        xlabel('Mean predicted CFO std (bin)');
        ylabel('Audited CFO RMSE (bin)');
        auditRow = overall(overall.snrDb == snrGrid(snrIndex) & ...
            strcmp(overall.region,regionKeys{regionIndex}),:);
        title(sprintf('%.0f dB, %s, corr=%.2f',snrGrid(snrIndex), ...
            regionNames{regionIndex},auditRow.absoluteErrorCorrelation));
    end
end
pngFile = fullfile(resultDir,'stage55_vp_frequency_quality_calibration.png');
figFile = fullfile(resultDir,'stage55_vp_frequency_quality_calibration.fig');
exportgraphics(figureHandle,pngFile,'Resolution',180);
savefig(figureHandle,figFile);
close(figureHandle);
files = {pngFile;figFile};
end

function wrapped = localWrapToPi(angleRad)
wrapped = mod(angleRad+pi,2*pi)-pi;
end
