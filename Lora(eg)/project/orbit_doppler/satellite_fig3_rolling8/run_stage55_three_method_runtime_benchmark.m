function report = run_stage55_three_method_runtime_benchmark(options)
%RUN_STAGE55_THREE_METHOD_RUNTIME_BENCHMARK Controlled fresh-frame timing.
%   Receiver time excludes payload/waveform generation.  Selected frames
%   are evenly spread over all SNR/region groups in pass 1.  The complete
%   preceding frame sequence is regenerated so the Stage55 branches see
%   their proper causal rolling-eight preamble-CFO state.  Method order is
%   rotated between samples after one untimed warm-up.

arguments
    options.FreshResultFolder (1,:) char = fullfile(fileparts( ...
        mfilename('fullpath')),'results', ...
        'stage55_vp_quality_fresh_rerun_20260812')
    options.FramesPerSnrRegion (1,1) double ...
        {mustBeInteger,mustBePositive} = 4
    options.ProgressEveryFrames (1,1) double = 100
    options.Force (1,1) logical = false
end

sampleCsv = fullfile(options.FreshResultFolder, ...
    'stage55_three_method_runtime_samples.csv');
summaryCsv = fullfile(options.FreshResultFolder, ...
    'stage55_three_method_runtime_summary.csv');
matFile = fullfile(options.FreshResultFolder, ...
    'stage55_three_method_runtime_benchmark.mat');
if ~options.Force && isfile(sampleCsv) && isfile(summaryCsv) && ...
        isfile(matFile)
    samples = readtable(sampleCsv);
    summary = readtable(summaryCsv);
    report = struct('samples',samples,'summary',summary, ...
        'sampleCsv',sampleCsv,'summaryCsv',summaryCsv,'matFile',matFile);
    fprintf('Reusing fresh three-method runtime benchmark: %s\n',sampleCsv);
    return
end

sourceFile = fullfile(options.FreshResultFolder, ...
    'stage55_vp_mechanism_ablation.mat');
seniorFile = fullfile(options.FreshResultFolder, ...
    'stage55_fresh_senior_prec_records.mat');
if ~isfile(sourceFile) || ~isfile(seniorFile)
    error('SatelliteFig3:FreshRuntimeSource', ...
        'Both fresh Stage55 and fresh Senior-PREC MAT files are required.');
end
source = load(sourceFile);
senior = load(seniorFile);
localValidateSources(source,senior);
config = source.config;
schedule = source.schedule;
known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
methodNames = {'Senior-PREC','Stage55-NoVP','Stage55-VP-quality'};

noVpRows = source.records(source.records.passIndex == 1 & ...
    strcmp(source.records.mode,'NoVP'),:);
regionKeys = {'high_doppler_rate','high_doppler_shift'};
benchmarkKeys = table();
for snrIndex = 1:numel(source.options.SnrGridDb)
    for regionIndex = 1:numel(regionKeys)
        candidates = noVpRows(noVpRows.snrDb == ...
            source.options.SnrGridDb(snrIndex) & ...
            strcmp(noVpRows.region,regionKeys{regionIndex}),:);
        candidates = sortrows(candidates,{'segmentIndex','frameIndex'});
        sampleCount = min(options.FramesPerSnrRegion,height(candidates));
        positions = unique(round(linspace(1,height(candidates),sampleCount)));
        selected = candidates(positions, ...
            {'snrDb','passIndex','segmentIndex','frameIndex','region'});
        benchmarkKeys = [benchmarkKeys;selected]; %#ok<AGROW>
    end
end
benchmarkKeys = sortrows(benchmarkKeys, ...
    {'snrDb','segmentIndex','frameIndex'});

% Untimed compilation/JIT warm-up; it is deliberately excluded.
firstFrame = source.segments(1,1);
payload = satelliteFig3GeneratePayload(config, ...
    source.options.PayloadSeedBase+1000000+10000+firstFrame);
labels = [known;payload.symbolBins];
[warmRx,~,~] = generateContinuousSatelliteFrame(labels,config, ...
    StartTimeSec=schedule.frameStartTimeSec(firstFrame), ...
    SampleSnrDb=source.options.SnrGridDb(1), ...
    NoiseSeed=source.options.NoiseSeedBase+1000000+10000+firstFrame, ...
    InitialPhaseRad=0,NextSymbolBin=0);
satelliteFig3PaperPrecDecode(warmRx,config,known);
satelliteFig3SenLoRaVirtualPilotDecode(warmRx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(firstFrame), ...
    CrossFrameState=struct(),EnableVirtualPilots=false, ...
    EnableVirtualPilotRateUpdate=false, ...
    ApplyVirtualPilotPhaseCorrection=false, ...
    UseQualityAwareVirtualPilots=false);
satelliteFig3SenLoRaVirtualPilotDecode(warmRx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(firstFrame), ...
    CrossFrameState=struct(),EnableVirtualPilots=true, ...
    EnableVirtualPilotRateUpdate=true, ...
    ApplyVirtualPilotPhaseCorrection=true, ...
    UseQualityAwareVirtualPilots=true);
clear warmRx payload labels

maximumSamples = height(benchmarkKeys)*numel(methodNames);
sampleData = localPreallocateSamples(maximumSamples);
sampleRow = 0;
physicalCounter = 0;
for snrIndex = 1:numel(source.options.SnrGridDb)
    snrDb = source.options.SnrGridDb(snrIndex);
    for segmentIndex = 1:size(source.segments,1)
        phaseStateRad = 0;
        crossFrameState = struct();
        for frameIndex = source.segments(segmentIndex,1): ...
                source.segments(segmentIndex,2)
            payloadSeed = source.options.PayloadSeedBase+ ...
                1000000*snrIndex+10000+frameIndex;
            noiseSeed = source.options.NoiseSeedBase+ ...
                1000000*snrIndex+10000+frameIndex;
            payload = satelliteFig3GeneratePayload(config,payloadSeed);
            labels = [known;payload.symbolBins];
            [rx,~,truth] = generateContinuousSatelliteFrame( ...
                labels,config, ...
                StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                SampleSnrDb=snrDb,NoiseSeed=noiseSeed, ...
                InitialPhaseRad=phaseStateRad,NextSymbolBin=0);
            phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);

            selectedKey = benchmarkKeys.snrDb == snrDb & ...
                benchmarkKeys.segmentIndex == segmentIndex & ...
                benchmarkKeys.frameIndex == frameIndex;
            if any(selectedKey)
                physicalCounter = physicalCounter+1;
                incomingState = crossFrameState;
                decoded = cell(3,1);
                runtime = nan(3,1);
                order = mod(physicalCounter-1+(0:2),3)+1;
                for orderIndex = 1:3
                    methodIndex = order(orderIndex);
                    clock = tic;
                    if methodIndex == 1
                        decoded{methodIndex} = ...
                            satelliteFig3PaperPrecDecode(rx,config,known);
                    elseif methodIndex == 2
                        decoded{methodIndex} = ...
                            satelliteFig3SenLoRaVirtualPilotDecode( ...
                            rx,config,known, ...
                            FrameStartTimeSec= ...
                                schedule.frameStartTimeSec(frameIndex), ...
                            CrossFrameState=incomingState, ...
                            EnableVirtualPilots=false, ...
                            EnableVirtualPilotRateUpdate=false, ...
                            ApplyVirtualPilotPhaseCorrection=false, ...
                            UseQualityAwareVirtualPilots=false);
                    else
                        decoded{methodIndex} = ...
                            satelliteFig3SenLoRaVirtualPilotDecode( ...
                            rx,config,known, ...
                            FrameStartTimeSec= ...
                                schedule.frameStartTimeSec(frameIndex), ...
                            CrossFrameState=incomingState, ...
                            EnableVirtualPilots=true, ...
                            EnableVirtualPilotRateUpdate=true, ...
                            ApplyVirtualPilotPhaseCorrection=true, ...
                            UseQualityAwareVirtualPilots=true);
                    end
                    runtime(methodIndex) = toc(clock);
                end
                if ~isequaln(decoded{2}.crossFrameState, ...
                        decoded{3}.crossFrameState)
                    error('SatelliteFig3:FreshRuntimePairedState', ...
                        'NoVP and VP-quality changed the common frame state.');
                end
                crossFrameState = decoded{3}.crossFrameState;
                localValidateSelected(decoded,source,senior,payload,labels, ...
                    truth,payloadRows,snrDb,segmentIndex,frameIndex,config);

                region = benchmarkKeys.region{find(selectedKey,1)};
                for methodIndex = 1:3
                    sampleRow = sampleRow+1;
                    sampleData.snrDb(sampleRow) = snrDb;
                    sampleData.passIndex(sampleRow) = 1;
                    sampleData.segmentIndex(sampleRow) = segmentIndex;
                    sampleData.frameIndex(sampleRow) = frameIndex;
                    sampleData.region{sampleRow} = region;
                    sampleData.method{sampleRow} = methodNames{methodIndex};
                    sampleData.receiverRuntimeSec(sampleRow) = ...
                        runtime(methodIndex);
                    sampleData.frameDurationSec(sampleRow) = ...
                        schedule.frameDurationSec;
                    sampleData.deadlineMiss(sampleRow) = ...
                        runtime(methodIndex) > schedule.frameDurationSec;
                    sampleData.callOrder(sampleRow) = ...
                        find(order == methodIndex);
                end
            else
                bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
                    rx(1:config.bootstrapPilotCount,:),known,config);
                fallbackRate = min(config.maxRateBinsPerSec,max( ...
                    -config.maxRateBinsPerSec, ...
                    bootstrap.jointRateBinsPerSec));
                measurementTimeSec = schedule.frameStartTimeSec(frameIndex)+ ...
                    0.5*config.bootstrapPilotCount*config.symbolDurationSec;
                [~,crossFrameState] = satelliteFig3CrossFrameRateUpdate( ...
                    crossFrameState,measurementTimeSec, ...
                    bootstrap.epsilonHatBins,fallbackRate,config);
            end
            if isfinite(options.ProgressEveryFrames) && ...
                    options.ProgressEveryFrames > 0 && ...
                    mod(frameIndex-source.segments(segmentIndex,1)+1, ...
                    options.ProgressEveryFrames) == 0
                fprintf(['Runtime state reconstruction %.1f dB segment %d: ' ...
                    '%d frames.\n'],snrDb,segmentIndex, ...
                    frameIndex-source.segments(segmentIndex,1)+1);
            end
        end
    end
end

samples = struct2table(localTrimSamples(sampleData,sampleRow));
if sampleRow ~= maximumSamples
    error('SatelliteFig3:FreshRuntimeSampleCount', ...
        'The runtime benchmark did not time every selected method/frame.');
end
summary = localRuntimeSummary(samples,methodNames,schedule.frameDurationSec);
writetable(samples,sampleCsv);
writetable(summary,summaryCsv);
save(matFile,'samples','summary','benchmarkKeys','methodNames','options');
report = struct('samples',samples,'summary',summary, ...
    'benchmarkKeys',benchmarkKeys,'sampleCsv',sampleCsv, ...
    'summaryCsv',summaryCsv,'matFile',matFile);
fprintf('Fresh three-method runtime benchmark complete: %s\n',sampleCsv);
end

function localValidateSources(source,senior)
required = {'config','schedule','segments','options','records','modes'};
for index = 1:numel(required)
    if ~isfield(source,required{index})
        error('SatelliteFig3:FreshRuntimeStage55Field', ...
            'Fresh Stage55 MAT is missing %s.',required{index});
    end
end
if ~isfield(senior,'records') || ~isfield(senior,'options') || ...
        ~isequaln(source.config,senior.config) || ...
        ~isequal(source.segments,senior.segments) || ...
        ~isequal(source.options.SnrGridDb,senior.options.SnrGridDb) || ...
        source.options.PassCount ~= senior.options.PassCount || ...
        source.options.PayloadSeedBase ~= senior.options.PayloadSeedBase || ...
        source.options.NoiseSeedBase ~= senior.options.NoiseSeedBase
    error('SatelliteFig3:FreshRuntimeSourceMismatch', ...
        'The two fresh experiment sources do not share one frame ledger.');
end
end

function localValidateSelected(decoded,source,senior,payload,labels,truth, ...
        payloadRows,snrDb,segmentIndex,frameIndex,config)
referenceSymbols = labels(payloadRows);
referenceBits = payload.dataBits(:);
truthCfoBins = truth.trueDopplerHz(payloadRows)/config.fftBinSpacingHz;

seniorRows = senior.records.snrDb == snrDb & ...
    senior.records.passIndex == 1 & ...
    senior.records.segmentIndex == segmentIndex & ...
    senior.records.frameIndex == frameIndex;
if nnz(seniorRows) ~= 1
    error('SatelliteFig3:FreshRuntimeSeniorLedger', ...
        'Fresh Senior-PREC benchmark key is missing or duplicated.');
end
seniorDecoded = decoded{1};
seniorSymbolErrors = sum( ...
    seniorDecoded.detectedWaveformBins(payloadRows) ~= referenceSymbols);
seniorBits = seniorDecoded.decodedDataBits(:);
seniorBitErrors = sum(seniorBits ~= referenceBits);
seniorCfoSse = sum((seniorDecoded.epsilonHatBins-truthCfoBins).^2);
if seniorSymbolErrors ~= senior.records.symbolErrors(seniorRows) || ...
        seniorBitErrors ~= senior.records.deliveredBitErrors(seniorRows) || ...
        ~localClose(seniorCfoSse,senior.records.cfoSseBins(seniorRows))
    error('SatelliteFig3:FreshRuntimeSeniorMismatch', ...
        'Timed Senior-PREC does not reproduce its fresh replay record.');
end

modeNames = {'NoVP','VP-quality'};
for branchIndex = 1:2
    branch = decoded{branchIndex+1};
    sourceRows = source.records.snrDb == snrDb & ...
        source.records.passIndex == 1 & ...
        source.records.segmentIndex == segmentIndex & ...
        source.records.frameIndex == frameIndex & ...
        strcmp(source.records.mode,modeNames{branchIndex});
    if nnz(sourceRows) ~= 1
        error('SatelliteFig3:FreshRuntimeStage55Ledger', ...
            'Fresh Stage55 benchmark key is missing or duplicated.');
    end
    hardSymbols = branch.tracker.hardWaveformBins(payloadRows);
    hardBits = branch.hardDecodedDataBits(:);
    softBits = branch.decodedDataBits(:);
    cfoSse = sum((branch.tracker.predictedCfoBins(payloadRows)- ...
        truthCfoBins).^2);
    accepted = branch.pilotAccepted(payloadRows);
    if sum(hardSymbols ~= referenceSymbols) ~= ...
            source.records.symbolErrors(sourceRows) || ...
            sum(hardBits ~= referenceBits) ~= ...
            source.records.hardBitErrors(sourceRows) || ...
            sum(softBits ~= referenceBits) ~= ...
            source.records.softBitErrors(sourceRows) || ...
            sum(accepted) ~= ...
            source.records.acceptedVirtualPilots(sourceRows) || ...
            sum(accepted & hardSymbols ~= referenceSymbols) ~= ...
            source.records.falseAcceptedVirtualPilots(sourceRows) || ...
            ~localClose(cfoSse,source.records.cfoSseBins(sourceRows))
        error('SatelliteFig3:FreshRuntimeStage55Mismatch', ...
            'Timed Stage55 branch does not reproduce its fresh record.');
    end
end
end

function tf = localClose(actual,expected)
tf = abs(actual-expected) <= 1e-9*max([1,abs(actual),abs(expected)]);
end

function data = localPreallocateSamples(count)
numericFields = {'snrDb','passIndex','segmentIndex','frameIndex', ...
    'receiverRuntimeSec','frameDurationSec','callOrder'};
for index = 1:numel(numericFields)
    data.(numericFields{index}) = zeros(count,1);
end
data.region = cell(count,1);
data.method = cell(count,1);
data.deadlineMiss = false(count,1);
end

function data = localTrimSamples(data,count)
fields = fieldnames(data);
for index = 1:numel(fields)
    data.(fields{index}) = data.(fields{index})(1:count,:);
end
end

function summary = localRuntimeSummary(samples,methodNames,frameDurationSec)
rowCount = numel(methodNames);
method = methodNames(:);
sampleCount = zeros(rowCount,1);
meanRuntimeSec = zeros(rowCount,1);
medianRuntimeSec = zeros(rowCount,1);
p95RuntimeSec = zeros(rowCount,1);
maximumRuntimeSec = zeros(rowCount,1);
ratioToSeniorMedian = zeros(rowCount,1);
realTimeMarginAtMedian = zeros(rowCount,1);
deadlineMissRate = zeros(rowCount,1);
for index = 1:rowCount
    selected = strcmp(samples.method,methodNames{index});
    value = samples.receiverRuntimeSec(selected);
    sampleCount(index) = numel(value);
    meanRuntimeSec(index) = mean(value);
    medianRuntimeSec(index) = median(value);
    p95RuntimeSec(index) = localPercentile(value,0.95);
    maximumRuntimeSec(index) = max(value);
    deadlineMissRate(index) = mean(samples.deadlineMiss(selected));
end
ratioToSeniorMedian = medianRuntimeSec/medianRuntimeSec(1);
realTimeMarginAtMedian = frameDurationSec./medianRuntimeSec;
summary = table(method,sampleCount,meanRuntimeSec,medianRuntimeSec, ...
    p95RuntimeSec,maximumRuntimeSec,ratioToSeniorMedian, ...
    realTimeMarginAtMedian,deadlineMissRate, ...
    repmat(frameDurationSec,rowCount,1), ...
    'VariableNames',{'method','sampleCount','meanRuntimeSec', ...
    'medianRuntimeSec','p95RuntimeSec','maximumRuntimeSec', ...
    'ratioToSeniorMedian','realTimeMarginAtMedian', ...
    'deadlineMissRate','frameDurationSec'});
end

function value = localPercentile(samples,fraction)
samples = sort(samples(:));
position = 1+(numel(samples)-1)*fraction;
lower = floor(position);
upper = ceil(position);
weight = position-lower;
value = (1-weight)*samples(lower)+weight*samples(upper);
end

function angleRad = localWrapToPi(angleRad)
angleRad = mod(angleRad+pi,2*pi)-pi;
end
