function report = run_stage49_continuous_pass_validation(options)
%RUN_STAGE49_CONTINUOUS_PASS_VALIDATION Time/visibility/phase inspection.
%   This stage validates the complete-frame schedule and several exact
%   split-versus-joint frame boundaries.  It does not decode payloads or
%   estimate BER.

arguments
    options.ProbeSeedBase (1,1) double = 2026120200
    options.OutputFolderName (1,:) char = ...
        'stage49_continuous_pass_validation'
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
window = schedule.window;
writetable(schedule.frameTable,fullfile(resultDir, ...
    'stage49_continuous_pass_schedule.csv'));

targetTimes = [schedule.frameCenterTimeSec(1); ...
    config.centralVisibilityTimeSec-window.deltaTimeInSec; ...
    config.centralVisibilityTimeSec; ...
    config.centralVisibilityTimeSec+window.deltaTimeInSec; ...
    schedule.frameCenterTimeSec(end-1)];
probeFrameIndex = zeros(numel(targetTimes),1);
for probe = 1:numel(targetTimes)
    [~,probeFrameIndex(probe)] = min(abs( ...
        schedule.frameCenterTimeSec-targetTimes(probe)));
end
probeFrameIndex = unique(min(schedule.frameCount-1,max(1, ...
    probeFrameIndex)),'stable');
probeCount = numel(probeFrameIndex);
boundaryTimeSec = zeros(probeCount,1);
timeGapErrorSec = zeros(probeCount,1);
phaseBridgeErrorRad = zeros(probeCount,1);
splitJointPhaseMaxErrorRad = zeros(probeCount,1);
splitJointWaveformMaxError = zeros(probeCount,1);
boundaryVisible = false(probeCount,1);

known = zeros(config.bootstrapPilotCount,1);
for probe = 1:probeCount
    frameIndex = probeFrameIndex(probe);
    payload1 = satelliteFig3GeneratePayload(config, ...
        options.ProbeSeedBase+10*probe+1);
    payload2 = satelliteFig3GeneratePayload(config, ...
        options.ProbeSeedBase+10*probe+2);
    labels1 = [known;payload1.symbolBins];
    labels2 = [known;payload2.symbolBins];
    initialPhaseRad = 1e6+0.123456789*probe;
    startTimeSec = schedule.frameStartTimeSec(frameIndex);

    [rxJoint,~,truthJoint] = generateContinuousSatelliteFrame( ...
        [labels1;labels2],config,StartTimeSec=startTimeSec, ...
        SampleSnrDb=Inf,InitialPhaseRad=initialPhaseRad);
    [rx1,~,truth1] = generateContinuousSatelliteFrame(labels1,config, ...
        StartTimeSec=startTimeSec,SampleSnrDb=Inf, ...
        InitialPhaseRad=initialPhaseRad,NextSymbolBin=labels2(1));
    [rx2,~,truth2] = generateContinuousSatelliteFrame(labels2,config, ...
        StartTimeSec=truth1.nextFrameStartTimeSec,SampleSnrDb=Inf, ...
        InitialPhaseRad=truth1.nextFrameStartPhaseRad);

    jointPhase = reshape(truthJoint.phaseRad.',[],1);
    splitPhase = [reshape(truth1.phaseRad.',[],1); ...
        reshape(truth2.phaseRad.',[],1)];
    jointWaveform = reshape(rxJoint.',[],1);
    splitWaveform = [reshape(rx1.',[],1);reshape(rx2.',[],1)];
    boundaryTimeSec(probe) = truth2.sampleTimeSec(1,1);
    timeGapErrorSec(probe) = truth2.sampleTimeSec(1,1)- ...
        truth1.sampleTimeSec(end,end)-1/config.sampleRateHz;
    expectedBridge = pi/config.sampleRateHz*( ...
        truth1.dopplerHz(end,end)+truth2.dopplerHz(1,1));
    phaseBridgeErrorRad(probe) = truth2.phaseRad(1,1)- ...
        truth1.phaseRad(end,end)-expectedBridge;
    splitJointPhaseMaxErrorRad(probe) = max(abs( ...
        splitPhase-jointPhase));
    splitJointWaveformMaxError(probe) = max(abs( ...
        splitWaveform-jointWaveform));
    [~,boundaryVisible(probe)] = satelliteFig3VisibilityWindow( ...
        config,boundaryTimeSec(probe));
end

probeTable = table(probeFrameIndex,boundaryTimeSec,boundaryVisible, ...
    timeGapErrorSec,phaseBridgeErrorRad,splitJointPhaseMaxErrorRad, ...
    splitJointWaveformMaxError);
writetable(probeTable,fullfile(resultDir, ...
    'stage49_frame_boundary_probes.csv'));

trajectoryTimeSec = (schedule.passStartTimeSec: ...
    config.trajectoryTimeStepSec:schedule.passEndTimeSec).';
if trajectoryTimeSec(end) < schedule.passEndTimeSec
    trajectoryTimeSec(end+1,1) = schedule.passEndTimeSec;
end
trajectory = satelliteFig3Trajectory(trajectoryTimeSec,config);

fig = figure('Visible','off','Color','w','Position',[70 35 1370 920]);
tiledlayout(4,1,'TileSpacing','compact','Padding','compact');

ax1 = nexttile;
plot(trajectoryTimeSec,trajectory.dopplerShiftHz/1e3, ...
    'Color',[0 0.45 0.74],'LineWidth',1.6);
grid on; grid minor;
ylabel('Doppler shift (kHz)');
title('Figure-3 trajectory over one acquisition-to-loss pass', ...
    'FontWeight','normal');
localMarkBlind(ax1,window,schedule);

ax2 = nexttile;
plot(trajectoryTimeSec,trajectory.dopplerRateHzPerSec, ...
    'Color',[0.85 0.33 0.10],'LineWidth',1.6);
grid on; grid minor;
ylabel('Doppler rate (Hz/s)');
localMarkBlind(ax2,window,schedule);

ax3 = nexttile;
stairs(schedule.frameCenterTimeSec,schedule.visibleFraction, ...
    'k-','LineWidth',1.15,'DisplayName','Visible fraction per frame');
hold on;
transition = schedule.transitionFrame;
plot(schedule.frameCenterTimeSec(transition), ...
    schedule.visibleFraction(transition),'mo','MarkerFaceColor','none', ...
    'DisplayName','Boundary-transition frame');
ylim([-0.05 1.08]);
grid on; grid minor;
ylabel('Visible fraction');
legend('Location','southwest','FontSize',8,'Box','on');
localMarkBlind(ax3,window,schedule);

ax4 = nexttile;
semilogy(boundaryTimeSec,max(abs(phaseBridgeErrorRad),realmin), ...
    'bo-','LineWidth',1.2,'MarkerFaceColor','none', ...
    'DisplayName','Trapezoidal phase-bridge error');
hold on;
semilogy(boundaryTimeSec,max(splitJointPhaseMaxErrorRad,realmin), ...
    'rs--','LineWidth',1.2,'MarkerFaceColor','none', ...
    'DisplayName','Split/joint phase max difference');
semilogy(boundaryTimeSec,max(splitJointWaveformMaxError,realmin), ...
    'kd-.','LineWidth',1.2,'MarkerFaceColor','none', ...
    'DisplayName','Split/joint waveform max difference');
ylim([1e-12 3e-8]);
yline(1e-10,'b:','1e-10 phase-bridge threshold', ...
    'LabelHorizontalAlignment','left','HandleVisibility','off');
yline(1e-8,'r:','1e-8 split/joint tolerance', ...
    'LabelHorizontalAlignment','right','HandleVisibility','off');
grid on; grid minor;
ylabel('Absolute error');
xlabel('Time relative to closest pass point (s)');
legend('Location','best','FontSize',8,'Box','on');
localMarkBlind(ax4,window,schedule);

axesList = [ax1 ax2 ax3 ax4];
for ax = axesList
    xlim(ax,[schedule.passStartTimeSec,schedule.passEndTimeSec]);
    set(ax,'FontName','Times New Roman','FontSize',10,'Box','on', ...
        'GridLineStyle',':','MinorGridLineStyle',':');
end
sgtitle(sprintf(['Stage 49 continuous frames: %d complete frames, ' ...
    'T_{frame}=%.5f s, remainder %.5f s'], ...
    schedule.frameCount,schedule.frameDurationSec, ...
    schedule.completeFrameRemainderSec), ...
    'FontName','Times New Roman','FontWeight','normal');

imagePath = fullfile(resultDir,'stage49_continuous_pass_validation.png');
exportgraphics(fig,imagePath,'Resolution',180);
savefig(fig,fullfile(resultDir,'stage49_continuous_pass_validation.fig'));
close(fig);
save(fullfile(resultDir,'stage49_continuous_pass_validation.mat'), ...
    'config','options','schedule','trajectoryTimeSec','trajectory', ...
    'probeTable','window');

report = struct('resultDir',resultDir,'imagePath',imagePath, ...
    'schedule',schedule,'probeTable',probeTable, ...
    'maxPhaseBridgeErrorRad',max(abs(phaseBridgeErrorRad)), ...
    'maxSplitJointPhaseErrorRad',max(splitJointPhaseMaxErrorRad), ...
    'maxSplitJointWaveformError',max(splitJointWaveformMaxError));
fprintf('Stage 49 continuous-pass validation: %s\n',resultDir);
fprintf(['Frames=%d, fully visible=%d, fully blind=%d, transitions=%d, ' ...
    'remainder=%.9f s\n'],schedule.frameCount,sum(schedule.fullyVisible), ...
    sum(schedule.fullyBlind),sum(schedule.transitionFrame), ...
    schedule.completeFrameRemainderSec);
fprintf(['Max bridge error %.3g rad; split/joint phase %.3g rad; ' ...
    'waveform %.3g\n'],report.maxPhaseBridgeErrorRad, ...
    report.maxSplitJointPhaseErrorRad,report.maxSplitJointWaveformError);
end

function localMarkBlind(ax,window,schedule)
hold(ax,'on');
limits = ylim(ax);
blind = window.blindIntervalSec;
patch(ax,[blind(1) blind(2) blind(2) blind(1)], ...
    [limits(1) limits(1) limits(2) limits(2)], ...
    [0.88 0.88 0.88],'FaceAlpha',0.28,'EdgeColor','none', ...
    'HandleVisibility','off');
xline(ax,blind(1),'Color',[0.45 0.45 0.45], ...
    'LineStyle',':','HandleVisibility','off');
xline(ax,blind(2),'Color',[0.45 0.45 0.45], ...
    'LineStyle',':','HandleVisibility','off');
xlim(ax,[schedule.passStartTimeSec,schedule.passEndTimeSec]);
ylim(ax,limits);
end
