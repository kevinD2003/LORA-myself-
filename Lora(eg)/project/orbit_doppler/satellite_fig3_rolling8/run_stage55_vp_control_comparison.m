function report = run_stage55_vp_control_comparison(options)
%RUN_STAGE55_VP_CONTROL_COMPARISON Paired Stage-55 virtual-pilot ablation.
%   The NoVP and VP branches receive the same waveform, Huang bootstrap,
%   causal cross-frame preamble-CFO rate, compensation law, and final ML
%   soft-Hamming decoder.  The only treatment variable is whether reliable
%   payload decisions may enter the rolling-eight tracking history.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.PassCount (1,1) double ...
        {mustBeInteger,mustBePositive} = 1
    options.FramesPerVisibleSegment (1,1) double = Inf
    options.PayloadSeedBase (1,1) double = 2026350800
    options.NoiseSeedBase (1,1) double = 2026350900
    options.WindowDurationSec (1,1) double {mustBePositive} = 10
    options.OutputFolderName (1,:) char = ...
        'stage55_vp_control_comparison'
    options.ProgressEveryFrames (1,1) double = 50
    options.WriteFigures (1,1) logical = true
end
if ~(isinf(options.FramesPerVisibleSegment) || ( ...
        options.FramesPerVisibleSegment >= 1 && ...
        options.FramesPerVisibleSegment == ...
        round(options.FramesPerVisibleSegment)))
    error('SatelliteFig3:VpControlFramesPerSegment', ...
        'FramesPerVisibleSegment must be Inf or a positive integer.');
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
trajectory = satelliteFig3Trajectory(schedule.frameCenterTimeSec,config);
driftBinsPerFrame = abs(trajectory.dopplerRateHzPerSec).* ...
    schedule.frameDurationSec/config.fftBinSpacingHz;
segmentEdges = find(diff([false;schedule.fullyVisible(:);false]));
segments = reshape(segmentEdges,2,[]).'+[0 -1];
if isfinite(options.FramesPerVisibleSegment)
    segments(:,2) = min(segments(:,2), ...
        segments(:,1)+options.FramesPerVisibleSegment-1);
end

known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
framesPerPass = sum(segments(:,2)-segments(:,1)+1);
maximumRecords = numel(options.SnrGridDb)*options.PassCount*framesPerPass;
recordData = localPreallocateRecords(maximumRecords);
positionNoVpErrors = zeros(numel(options.SnrGridDb),2, ...
    config.payloadSymbolCount);
positionVpErrors = zeros(size(positionNoVpErrors));
positionFrameCount = zeros(numel(options.SnrGridDb),2);

recordIndex = 0;
for snrIndex = 1:numel(options.SnrGridDb)
    for passIndex = 1:options.PassCount
        for segmentIndex = 1:size(segments,1)
            crossFrameState = struct();
            phaseStateRad = 0;
            for frameIndex = segments(segmentIndex,1):segments(segmentIndex,2)
                payloadSeed = options.PayloadSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                noiseSeed = options.NoiseSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                payload = satelliteFig3GeneratePayload(config,payloadSeed);
                labels = [known;payload.symbolBins];
                [rx,~,truth] = generateContinuousSatelliteFrame( ...
                    labels,config, ...
                    StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    SampleSnrDb=options.SnrGridDb(snrIndex), ...
                    NoiseSeed=noiseSeed,InitialPhaseRad=phaseStateRad, ...
                    NextSymbolBin=0);
                phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);

                incomingState = crossFrameState;
                noVp = satelliteFig3SenLoRaVirtualPilotDecode( ...
                    rx,config,known, ...
                    FrameStartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    CrossFrameState=incomingState,EnableVirtualPilots=false, ...
                    UseQualityAwareVirtualPilots=false);
                vp = satelliteFig3SenLoRaVirtualPilotDecode( ...
                    rx,config,known, ...
                    FrameStartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    CrossFrameState=incomingState,EnableVirtualPilots=true, ...
                    UseQualityAwareVirtualPilots=false);
                localAssertPairedControl(noVp,vp,payloadRows);
                crossFrameState = vp.crossFrameState;

                referenceSymbols = labels(payloadRows);
                noVpSymbols = noVp.tracker.hardWaveformBins(payloadRows);
                vpSymbols = vp.tracker.hardWaveformBins(payloadRows);
                noVpSymbolError = noVpSymbols ~= referenceSymbols;
                vpSymbolError = vpSymbols ~= referenceSymbols;
                referenceBits = payload.dataBits(:);
                noVpHardBits = noVp.hardDecodedDataBits(:);
                vpHardBits = vp.hardDecodedDataBits(:);
                noVpSoftBits = noVp.decodedDataBits(:);
                vpSoftBits = vp.decodedDataBits(:);

                truthCfoBins = truth.trueDopplerHz(payloadRows)/ ...
                    config.fftBinSpacingHz;
                noVpResidual = noVp.tracker.predictedCfoBins(payloadRows)- ...
                    truthCfoBins;
                vpResidual = vp.tracker.predictedCfoBins(payloadRows)- ...
                    truthCfoBins;
                vpAccepted = vp.pilotAccepted(payloadRows);
                vpFalseAccepted = vpAccepted & vpSymbols ~= referenceSymbols;
                vpUsed = vp.tracker.compensationVirtualPilotCount(payloadRows);

                if driftBinsPerFrame(frameIndex) >= 0.5
                    region = 'high_doppler_rate';
                    regionIndex = 1;
                else
                    region = 'high_doppler_shift';
                    regionIndex = 2;
                end
                positionNoVpErrors(snrIndex,regionIndex,:) = ...
                    positionNoVpErrors(snrIndex,regionIndex,:) + ...
                    reshape(double(noVpSymbolError),1,1,[]);
                positionVpErrors(snrIndex,regionIndex,:) = ...
                    positionVpErrors(snrIndex,regionIndex,:) + ...
                    reshape(double(vpSymbolError),1,1,[]);
                positionFrameCount(snrIndex,regionIndex) = ...
                    positionFrameCount(snrIndex,regionIndex)+1;

                recordIndex = recordIndex+1;
                recordData.snrDb(recordIndex) = options.SnrGridDb(snrIndex);
                recordData.passIndex(recordIndex) = passIndex;
                recordData.segmentIndex(recordIndex) = segmentIndex;
                recordData.frameIndex(recordIndex) = frameIndex;
                recordData.region{recordIndex} = region;
                recordData.frameCenterTimeSec(recordIndex) = ...
                    schedule.frameCenterTimeSec(frameIndex);
                recordData.driftBinsPerFrame(recordIndex) = ...
                    driftBinsPerFrame(frameIndex);
                recordData.crossFrameHistoryCount(recordIndex) = ...
                    vp.crossFrameRateDiagnostic.historyCount;
                recordData.symbolCount(recordIndex) = numel(referenceSymbols);
                recordData.noVpSymbolErrors(recordIndex) = sum(noVpSymbolError);
                recordData.vpSymbolErrors(recordIndex) = sum(vpSymbolError);
                recordData.bitCount(recordIndex) = numel(referenceBits);
                recordData.noVpHardBitErrors(recordIndex) = ...
                    sum(noVpHardBits ~= referenceBits);
                recordData.vpHardBitErrors(recordIndex) = ...
                    sum(vpHardBits ~= referenceBits);
                recordData.noVpSoftBitErrors(recordIndex) = ...
                    sum(noVpSoftBits ~= referenceBits);
                recordData.vpSoftBitErrors(recordIndex) = ...
                    sum(vpSoftBits ~= referenceBits);
                recordData.noVpSoftFrameError(recordIndex) = ...
                    recordData.noVpSoftBitErrors(recordIndex) > 0;
                recordData.vpSoftFrameError(recordIndex) = ...
                    recordData.vpSoftBitErrors(recordIndex) > 0;
                recordData.noVpCfoSseBins(recordIndex) = sum(noVpResidual.^2);
                recordData.vpCfoSseBins(recordIndex) = sum(vpResidual.^2);
                recordData.cfoSampleCount(recordIndex) = numel(vpResidual);
                recordData.noVpAcceptedPilots(recordIndex) = ...
                    sum(noVp.pilotAccepted(payloadRows));
                recordData.vpAcceptedPilots(recordIndex) = sum(vpAccepted);
                recordData.vpFalseAcceptedPilots(recordIndex) = ...
                    sum(vpFalseAccepted);
                recordData.vpRateReleased(recordIndex) = ...
                    vp.tracker.acceptedVirtualPilotCount >= ...
                    config.senloraRateReleasePilotCount;
                recordData.vpUpdatedSymbolCount(recordIndex) = sum(vpUsed > 0);
                recordData.vpVirtualPilotsUsedSum(recordIndex) = sum(vpUsed);
                recordData.vpFullyVirtualSymbolCount(recordIndex) = sum( ...
                    vpUsed == config.virtualPilotHistoryLength);

                if isfinite(options.ProgressEveryFrames) && ...
                        options.ProgressEveryFrames > 0 && ...
                        mod(recordIndex,options.ProgressEveryFrames) == 0
                    fprintf('Stage55 VP control: %d/%d paired frames.\n', ...
                        recordIndex,maximumRecords);
                end
            end
        end
    end
end

recordData = localTrimRecords(recordData,recordIndex);
records = struct2table(recordData);
regionSummary = localRegionSummary(records,config,schedule, ...
    options.SnrGridDb);
windowStatistics = localWindowStatistics(records,config,schedule, ...
    options.SnrGridDb,options.WindowDurationSec);
[symbolPosition,blockPosition] = localPositionStatistics( ...
    positionNoVpErrors,positionVpErrors,positionFrameCount, ...
    options.SnrGridDb,config);

frameCsv = fullfile(resultDir,'stage55_vp_control_frame_records.csv');
regionCsv = fullfile(resultDir,'stage55_vp_control_region_summary.csv');
windowCsv = fullfile(resultDir,'stage55_vp_control_window_statistics.csv');
symbolCsv = fullfile(resultDir,'stage55_vp_control_symbol_position_ser.csv');
blockCsv = fullfile(resultDir,'stage55_vp_control_block_position_ser.csv');
writetable(records,frameCsv);
writetable(regionSummary,regionCsv);
writetable(windowStatistics,windowCsv);
writetable(symbolPosition,symbolCsv);
writetable(blockPosition,blockCsv);

figureRecords = repmat(struct(),0,1);
if options.WriteFigures
    figureRecords = localWriteFigures(resultDir,records,windowStatistics, ...
        blockPosition,config,schedule,options);
end
matFile = fullfile(resultDir,'stage55_vp_control_comparison.mat');
save(matFile,'config','schedule','options','segments','records', ...
    'regionSummary','windowStatistics','symbolPosition','blockPosition', ...
    'figureRecords');
report = struct('resultDir',resultDir,'records',records, ...
    'regionSummary',regionSummary,'windowStatistics',windowStatistics, ...
    'symbolPosition',symbolPosition,'blockPosition',blockPosition, ...
    'figures',{figureRecords},'matFile',matFile);
fprintf('Stage55 paired VP control comparison: %s\n',resultDir);
disp(regionSummary);
end

function data = localPreallocateRecords(count)
numericFields = {'snrDb','passIndex','segmentIndex','frameIndex', ...
    'frameCenterTimeSec','driftBinsPerFrame','crossFrameHistoryCount', ...
    'symbolCount','noVpSymbolErrors','vpSymbolErrors','bitCount', ...
    'noVpHardBitErrors','vpHardBitErrors','noVpSoftBitErrors', ...
    'vpSoftBitErrors','noVpCfoSseBins','vpCfoSseBins','cfoSampleCount', ...
    'noVpAcceptedPilots','vpAcceptedPilots','vpFalseAcceptedPilots', ...
    'vpUpdatedSymbolCount','vpVirtualPilotsUsedSum', ...
    'vpFullyVirtualSymbolCount'};
data = struct();
for index = 1:numel(numericFields)
    data.(numericFields{index}) = zeros(count,1);
end
data.region = cell(count,1);
data.noVpSoftFrameError = false(count,1);
data.vpSoftFrameError = false(count,1);
data.vpRateReleased = false(count,1);
end

function data = localTrimRecords(data,count)
fields = fieldnames(data);
for index = 1:numel(fields)
    data.(fields{index}) = data.(fields{index})(1:count,:);
end
end

function localAssertPairedControl(noVp,vp,payloadRows)
if noVp.virtualPilotsEnabled || ~vp.virtualPilotsEnabled
    error('SatelliteFig3:VpControlSwitch', ...
        'The paired virtual-pilot switch is not wired correctly.');
end
if noVp.initialRateBinsPerSec ~= vp.initialRateBinsPerSec || ...
        noVp.commonBootstrap.epsilonHatBins ~= ...
        vp.commonBootstrap.epsilonHatBins || ...
        ~isequaln(noVp.crossFrameState,vp.crossFrameState)
    error('SatelliteFig3:VpControlInitialization', ...
        'NoVP and VP do not share the same receiver-visible initialization.');
end
if any(noVp.pilotAccepted(payloadRows)) || ...
        noVp.tracker.acceptedVirtualPilotCount ~= 0 || ...
        any(noVp.tracker.compensationVirtualPilotCount(payloadRows) ~= 0)
    error('SatelliteFig3:VpControlLeakage', ...
        'The NoVP control branch admitted a payload-derived observation.');
end
end

function summary = localRegionSummary(records,config,schedule,snrGrid)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
rows = repmat(struct(),0,1);
nominalRate = localPayloadBitCount(config)/schedule.frameDurationSec;
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        selected = records.snrDb == snrGrid(snrIndex) & ...
            strcmp(records.region,regionKeys{regionIndex});
        if ~any(selected), continue; end
        frames = sum(selected);
        symbols = sum(records.symbolCount(selected));
        bits = sum(records.bitCount(selected));
        cfoSamples = sum(records.cfoSampleCount(selected));
        noVpSer = sum(records.noVpSymbolErrors(selected))/symbols;
        vpSer = sum(records.vpSymbolErrors(selected))/symbols;
        noVpSoftPer = mean(records.noVpSoftFrameError(selected));
        vpSoftPer = mean(records.vpSoftFrameError(selected));
        row = struct( ...
            'snrDb',snrGrid(snrIndex), ...
            'region',regionKeys{regionIndex}, ...
            'frameCount',frames, ...
            'symbolCount',symbols, ...
            'noVpSer',noVpSer, ...
            'vpSer',vpSer, ...
            'serGainRatio',localRatio(noVpSer,vpSer), ...
            'noVpHardBer',sum(records.noVpHardBitErrors(selected))/bits, ...
            'vpHardBer',sum(records.vpHardBitErrors(selected))/bits, ...
            'noVpSoftBer',sum(records.noVpSoftBitErrors(selected))/bits, ...
            'vpSoftBer',sum(records.vpSoftBitErrors(selected))/bits, ...
            'noVpSoftPer',noVpSoftPer, ...
            'vpSoftPer',vpSoftPer, ...
            'noVpCfoRmseBins',sqrt(sum( ...
                records.noVpCfoSseBins(selected))/cfoSamples), ...
            'vpCfoRmseBins',sqrt(sum( ...
                records.vpCfoSseBins(selected))/cfoSamples), ...
            'meanAcceptedVirtualPilots',mean( ...
                records.vpAcceptedPilots(selected)), ...
            'falseAcceptedVirtualPilots',sum( ...
                records.vpFalseAcceptedPilots(selected)), ...
            'rateReleaseFraction',mean(records.vpRateReleased(selected)), ...
            'updatedSymbolCoverage',sum( ...
                records.vpUpdatedSymbolCount(selected))/symbols, ...
            'noVpSoftGoodputBps',nominalRate*(1-noVpSoftPer), ...
            'vpSoftGoodputBps',nominalRate*(1-vpSoftPer));
        if isempty(rows)
            rows = row;
        else
            rows(end+1,1) = row; %#ok<AGROW>
        end
    end
end
summary = struct2table(rows);
end

function value = localRatio(numerator,denominator)
if denominator == 0
    if numerator == 0
        value = 1;
    else
        value = Inf;
    end
else
    value = numerator/denominator;
end
end

function statistics = localWindowStatistics( ...
        records,config,schedule,snrGrid,windowDurationSec)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
edges = (schedule.passStartTimeSec:windowDurationSec: ...
    schedule.passEndTimeSec).';
if edges(end) < schedule.passEndTimeSec
    edges(end+1,1) = schedule.passEndTimeSec;
else
    edges(end) = schedule.passEndTimeSec;
end
nominalRate = localPayloadBitCount(config)/schedule.frameDurationSec;
rows = repmat(struct(),0,1);
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        for windowIndex = 1:numel(edges)-1
            selected = records.snrDb == snrGrid(snrIndex) & ...
                strcmp(records.region,regionKeys{regionIndex}) & ...
                records.frameCenterTimeSec >= edges(windowIndex) & ...
                records.frameCenterTimeSec < edges(windowIndex+1);
            if ~any(selected), continue; end
            frames = sum(selected);
            symbols = sum(records.symbolCount(selected));
            bits = sum(records.bitCount(selected));
            cfoSamples = sum(records.cfoSampleCount(selected));
            noVpSymbolErrors = sum(records.noVpSymbolErrors(selected));
            vpSymbolErrors = sum(records.vpSymbolErrors(selected));
            [noVpSerShown,noVpSerLower,noVpSerUpper] = ...
                satelliteFig3BerInterval95(noVpSymbolErrors,symbols);
            [vpSerShown,vpSerLower,vpSerUpper] = ...
                satelliteFig3BerInterval95(vpSymbolErrors,symbols);
            noVpSoftErrors = sum(records.noVpSoftBitErrors(selected));
            vpSoftErrors = sum(records.vpSoftBitErrors(selected));
            [noVpBerShown,noVpBerLower,noVpBerUpper] = ...
                satelliteFig3BerInterval95(noVpSoftErrors,bits);
            [vpBerShown,vpBerLower,vpBerUpper] = ...
                satelliteFig3BerInterval95(vpSoftErrors,bits);
            noVpFrameErrors = sum(records.noVpSoftFrameError(selected));
            vpFrameErrors = sum(records.vpSoftFrameError(selected));
            [~,noVpPerLower,noVpPerUpper] = ...
                satelliteFig3BerInterval95(noVpFrameErrors,frames);
            [~,vpPerLower,vpPerUpper] = ...
                satelliteFig3BerInterval95(vpFrameErrors,frames);
            noVpPer = noVpFrameErrors/frames;
            vpPer = vpFrameErrors/frames;
            centerTime = 0.5*(edges(windowIndex)+edges(windowIndex+1));
            orbit = satelliteFig3Trajectory(centerTime,config);
            row = struct( ...
                'snrDb',snrGrid(snrIndex), ...
                'region',regionKeys{regionIndex}, ...
                'windowIndex',windowIndex, ...
                'windowStartTimeSec',edges(windowIndex), ...
                'windowCenterTimeSec',centerTime, ...
                'windowEndTimeSec',edges(windowIndex+1), ...
                'frameCount',frames, ...
                'trueDopplerHz',orbit.dopplerShiftHz, ...
                'trueDopplerRateHzPerSec',orbit.dopplerRateHzPerSec, ...
                'noVpSerRaw',noVpSymbolErrors/symbols, ...
                'vpSerRaw',vpSymbolErrors/symbols, ...
                'noVpSerShown',noVpSerShown, ...
                'vpSerShown',vpSerShown, ...
                'noVpSerLower95',noVpSerLower, ...
                'vpSerLower95',vpSerLower, ...
                'noVpSerUpper95',noVpSerUpper, ...
                'vpSerUpper95',vpSerUpper, ...
                'noVpSoftBerRaw',noVpSoftErrors/bits, ...
                'vpSoftBerRaw',vpSoftErrors/bits, ...
                'noVpSoftBerShown',noVpBerShown, ...
                'vpSoftBerShown',vpBerShown, ...
                'noVpSoftBerLower95',noVpBerLower, ...
                'vpSoftBerLower95',vpBerLower, ...
                'noVpSoftBerUpper95',noVpBerUpper, ...
                'vpSoftBerUpper95',vpBerUpper, ...
                'noVpSoftPer',noVpPer, ...
                'vpSoftPer',vpPer, ...
                'noVpSoftPerLower95',noVpPerLower, ...
                'vpSoftPerLower95',vpPerLower, ...
                'noVpSoftPerUpper95',noVpPerUpper, ...
                'vpSoftPerUpper95',vpPerUpper, ...
                'noVpCfoRmseBins',sqrt(sum( ...
                    records.noVpCfoSseBins(selected))/cfoSamples), ...
                'vpCfoRmseBins',sqrt(sum( ...
                    records.vpCfoSseBins(selected))/cfoSamples), ...
                'meanAcceptedVirtualPilots',mean( ...
                    records.vpAcceptedPilots(selected)), ...
                'noVpSoftGoodputBps',nominalRate*(1-noVpPer), ...
                'vpSoftGoodputBps',nominalRate*(1-vpPer));
            if isempty(rows)
                rows = row;
            else
                rows(end+1,1) = row; %#ok<AGROW>
            end
        end
    end
end
statistics = struct2table(rows);
end

function [symbolTable,blockTable] = localPositionStatistics( ...
        noVpErrors,vpErrors,frameCount,snrGrid,config)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
symbolRows = repmat(struct(),0,1);
blockRows = repmat(struct(),0,1);
blockLength = 4+config.cr;
blockCount = config.payloadSymbolCount/blockLength;
for snrIndex = 1:numel(snrGrid)
    for regionIndex = 1:numel(regionKeys)
        frames = frameCount(snrIndex,regionIndex);
        if frames == 0, continue; end
        for position = 1:config.payloadSymbolCount
            noVpCount = noVpErrors(snrIndex,regionIndex,position);
            vpCount = vpErrors(snrIndex,regionIndex,position);
            [noVpShown,noVpLower,noVpUpper] = ...
                satelliteFig3BerInterval95(noVpCount,frames);
            [vpShown,vpLower,vpUpper] = ...
                satelliteFig3BerInterval95(vpCount,frames);
            row = struct('snrDb',snrGrid(snrIndex), ...
                'region',regionKeys{regionIndex}, ...
                'payloadSymbolPosition',position, ...
                'observationCount',frames, ...
                'noVpSymbolErrors',noVpCount, ...
                'vpSymbolErrors',vpCount, ...
                'noVpSerRaw',noVpCount/frames, ...
                'vpSerRaw',vpCount/frames, ...
                'noVpSerShown',noVpShown,'vpSerShown',vpShown, ...
                'noVpSerLower95',noVpLower,'vpSerLower95',vpLower, ...
                'noVpSerUpper95',noVpUpper,'vpSerUpper95',vpUpper);
            if isempty(symbolRows)
                symbolRows = row;
            else
                symbolRows(end+1,1) = row; %#ok<AGROW>
            end
        end
        for block = 1:blockCount
            positions = (block-1)*blockLength+(1:blockLength);
            noVpCount = sum(noVpErrors(snrIndex,regionIndex,positions));
            vpCount = sum(vpErrors(snrIndex,regionIndex,positions));
            observations = frames*blockLength;
            [noVpShown,noVpLower,noVpUpper] = ...
                satelliteFig3BerInterval95(noVpCount,observations);
            [vpShown,vpLower,vpUpper] = ...
                satelliteFig3BerInterval95(vpCount,observations);
            row = struct('snrDb',snrGrid(snrIndex), ...
                'region',regionKeys{regionIndex}, ...
                'payloadBlock',block, ...
                'firstPayloadSymbol',positions(1), ...
                'lastPayloadSymbol',positions(end), ...
                'observationCount',observations, ...
                'noVpSymbolErrors',noVpCount, ...
                'vpSymbolErrors',vpCount, ...
                'noVpSerRaw',noVpCount/observations, ...
                'vpSerRaw',vpCount/observations, ...
                'noVpSerShown',noVpShown,'vpSerShown',vpShown, ...
                'noVpSerLower95',noVpLower,'vpSerLower95',vpLower, ...
                'noVpSerUpper95',noVpUpper,'vpSerUpper95',vpUpper);
            if isempty(blockRows)
                blockRows = row;
            else
                blockRows(end+1,1) = row; %#ok<AGROW>
            end
        end
    end
end
symbolTable = struct2table(symbolRows);
blockTable = struct2table(blockRows);
end

function figureRecords = localWriteFigures(resultDir,records,windows, ...
        blocks,config,schedule,options)
regionKeys = {'high_doppler_rate','high_doppler_shift'};
figureRecords = repmat(struct(),0,1);
colors = [0.82 0.20 0.16;0.00 0.35 0.85];
styles = {'s--','o-'};
names = {'Stage55-NoVP','Stage55-VP'};
for snrIndex = 1:numel(options.SnrGridDb)
    snrDb = options.SnrGridDb(snrIndex);
    for regionIndex = 1:numel(regionKeys)
        region = regionKeys{regionIndex};
        selectedWindow = windows.snrDb == snrDb & ...
            strcmp(windows.region,region);
        if ~any(selectedWindow), continue; end
        w = windows(selectedWindow,:);
        w = sortrows(w,'windowCenterTimeSec');
        selectedBlock = blocks.snrDb == snrDb & ...
            strcmp(blocks.region,region);
        b = sortrows(blocks(selectedBlock,:),'payloadBlock');
        selectedFrames = records.snrDb == snrDb & ...
            strcmp(records.region,region);

        fig = figure('Visible','off','Color','w', ...
            'Position',[40 20 1780 1320]);
        layout = tiledlayout(fig,5,1,'TileSpacing','compact', ...
            'Padding','compact');

        ax1 = nexttile(layout); hold(ax1,'on');
        denseTime = linspace(schedule.passStartTimeSec, ...
            schedule.passEndTimeSec,1200).';
        orbit = satelliteFig3Trajectory(denseTime,config);
        yyaxis(ax1,'left');
        plot(ax1,denseTime,orbit.dopplerShiftHz/1e3, ...
            'Color',[0.00 0.45 0.74],'LineWidth',1.5);
        ylabel(ax1,'Shift (kHz)');
        yyaxis(ax1,'right');
        plot(ax1,denseTime,orbit.dopplerRateHzPerSec, ...
            'Color',[0.85 0.33 0.10],'LineWidth',1.5);
        ylabel(ax1,'Rate (Hz/s)'); grid(ax1,'on');
        localShadeBlind(ax1,schedule.window);
        localTargetLines(ax1,localRegionIntervals( ...
            unique(records.frameIndex(selectedFrames)),schedule));
        title(ax1,localRegionTitle(region,records(selectedFrames,:), ...
            config,schedule),'FontWeight','normal');

        ax2 = nexttile(layout); hold(ax2,'on'); set(ax2,'YScale','log');
        localBand(ax2,w.windowCenterTimeSec,max(w.noVpSerLower95,1e-7), ...
            w.noVpSerUpper95,colors(1,:));
        localBand(ax2,w.windowCenterTimeSec,max(w.vpSerLower95,1e-7), ...
            w.vpSerUpper95,colors(2,:));
        semilogy(ax2,w.windowCenterTimeSec,w.noVpSerShown,styles{1}, ...
            'Color',colors(1,:),'LineWidth',1.5,'MarkerSize',5, ...
