function report = run_stage55_admission_root_cause_audit(options)
%RUN_STAGE55_ADMISSION_ROOT_CAUSE_AUDIT Gate-by-gate SenLoRa VP audit.
%   Uses seeds that are disjoint from the frozen Stage 52/53 experiments.
%   Transmitted labels and Doppler truth are consulted only after receiver
%   processing to audit pilot precision, BER, and residual-CFO prediction.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.FramesPerRegion (1,1) double ...
        {mustBeInteger,mustBePositive} = 8
    options.PayloadSeedBase (1,1) double = 2026260800
    options.NoiseSeedBase (1,1) double = 2026260900
    options.MinimumMarginRatio (1,1) double = NaN
    options.ConfidenceThresholdScale (1,1) double = NaN
    options.RequireSoftHardAgreement (1,1) double = NaN
    options.UseSoftDecodedPilotLabels (1,1) double = NaN
    options.OutputFolderName (1,:) char = ...
        'stage55_admission_root_cause_baseline'
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
if isfinite(options.ConfidenceThresholdScale)
    if options.ConfidenceThresholdScale <= 0
        error('SatelliteFig3:Stage55AuditConfidenceScale', ...
            'ConfidenceThresholdScale must be positive or NaN.');
    end
    config.confidenceThresholdScale = options.ConfidenceThresholdScale;
end
minimumMarginRatio = config.senloraMinimumMarginRatio;
if isfinite(options.MinimumMarginRatio)
    if options.MinimumMarginRatio < 0
        error('SatelliteFig3:Stage55AuditMargin', ...
            'MinimumMarginRatio must be nonnegative or NaN.');
    end
    minimumMarginRatio = options.MinimumMarginRatio;
end
requireAgreement = config.senloraRequireSoftHardAgreement;
if isfinite(options.RequireSoftHardAgreement)
    if ~ismember(options.RequireSoftHardAgreement,[0 1])
        error('SatelliteFig3:Stage55AuditAgreement', ...
            'RequireSoftHardAgreement must be zero, one, or NaN.');
    end
    requireAgreement = logical(options.RequireSoftHardAgreement);
end
useSoftPilotLabels = config.senloraUseSoftDecodedPilotLabels;
if isfinite(options.UseSoftDecodedPilotLabels)
    if ~ismember(options.UseSoftDecodedPilotLabels,[0 1])
        error('SatelliteFig3:Stage55AuditPilotLabels', ...
            'UseSoftDecodedPilotLabels must be zero, one, or NaN.');
    end
    useSoftPilotLabels = logical(options.UseSoftDecodedPilotLabels);
end
schedule = satelliteFig3ContinuousPassSchedule(config);
centerTrajectory = satelliteFig3Trajectory( ...
    schedule.frameCenterTimeSec,config);
driftBinsPerFrame = abs(centerTrajectory.dopplerRateHzPerSec).* ...
    schedule.frameDurationSec/config.fftBinSpacingHz;
visible = find(schedule.fullyVisible);
low = visible(driftBinsPerFrame(visible) < 0.5);
high = visible(driftBinsPerFrame(visible) >= 0.5);
selected = [localEvenSample(low,options.FramesPerRegion); ...
    localEvenSample(high,options.FramesPerRegion)];
region = [repmat({'low_dynamic'},options.FramesPerRegion,1); ...
    repmat({'high_dynamic'},options.FramesPerRegion,1)];

known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
records = localEmptyRecords();
pilotSamples = localEmptyPilotSamples();
for snrIndex = 1:numel(options.SnrGridDb)
    for sampleIndex = 1:numel(selected)
        frameIndex = selected(sampleIndex);
        payloadSeed = options.PayloadSeedBase+10000*snrIndex+frameIndex;
        noiseSeed = options.NoiseSeedBase+10000*snrIndex+frameIndex;
        payload = satelliteFig3GeneratePayload(config,payloadSeed);
        labels = [known;payload.symbolBins];
        [rx,~,truth] = generateContinuousSatelliteFrame(labels,config, ...
            StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
            SampleSnrDb=options.SnrGridDb(snrIndex), ...
            NoiseSeed=noiseSeed,InitialPhaseRad=0,NextSymbolBin=0);
        bootstrap = satelliteFig3HuangPrecCpBootstrapEstimate( ...
            rx(1:config.bootstrapPilotCount,:),known,config);
        initialRate = min(config.maxRateBinsPerSec,max( ...
            -config.maxRateBinsPerSec,bootstrap.jointRateBinsPerSec));
        trueBootstrapRate = mean(truth.trueDopplerRateHzPerSec( ...
            1:config.bootstrapPilotCount))/config.fftBinSpacingHz;
        rateStandardError = localBootstrapRateStandardError( ...
            bootstrap.joint,config);
        decoded = satelliteFig3SenLoRaIterativeDecode( ...
            rx,config,known,UseEstimatedSnrGate=false, ...
            MinimumCodewordMarginRatio=minimumMarginRatio, ...
            RequireSoftHardAgreement=requireAgreement, ...
            UseSoftDecodedPilotLabels=useSoftPilotLabels, ...
            UseCausalConfidenceTiming=config.senloraUseCausalConfidenceTiming, ...
            InnovationLimitBins=config.confidenceInnovationLimitBins, ...
            FreezeBootstrapRate=true, ...
            ReleaseBootstrapRateAfterVirtualPilotCount= ...
                config.senloraRateReleasePilotCount, ...
            RateDeviationLimitBinsPerSec= ...
                config.senloraRateTrackingDeviationLimitBinsPerSec, ...
            BootstrapRateOverrideBinsPerSec=initialRate, ...
            BootstrapOverride=bootstrap);
        tracker = decoded.tracker;
        finalIteration = decoded.iterationHistory(end);
        firstIteration = decoded.iterationHistory(1);
        firstSoft = firstIteration.soft;
        firstMarginRatio = firstSoft.symbolCodewordMargin(payloadRows)./ ...
            max(firstSoft.tauGlobal(payloadRows),eps);
        firstConfident = firstSoft.confidentMask(payloadRows) & ...
            firstSoft.readyMask(payloadRows);
        firstMarginPass = firstMarginRatio >= ...
            minimumMarginRatio;
        firstAgreement = firstSoft.decodedWaveformBins(payloadRows) == ...
            firstIteration.tracker.hardWaveformBins(payloadRows);

        requested = finalIteration.requestedMask(payloadRows);
        available = tracker.pilotAvailabilityRows(payloadRows) <= ...
            config.frameSymbolCount;
        measured = isfinite(tracker.measuredResidualBins(payloadRows));
        residualPeakPass = tracker.residualPeakRatio(payloadRows) >= ...
            config.residualPeakRatioThreshold;
        boundaryPass = ~tracker.residualPeakAtBoundary(payloadRows);
        innovationPass = abs(tracker.measuredResidualBins(payloadRows)) <= ...
            config.confidenceInnovationLimitBins;
        decisionPeakPass = tracker.peakRatio(payloadRows) >= ...
            config.decisionPeakRatioThreshold;
        accepted = tracker.pilotAccepted(payloadRows);
        falseAccepted = accepted & ...
            decoded.detectedWaveformBins(payloadRows) ~= labels(payloadRows);

        acceptedRows = payloadRows(accepted);
        if ~isempty(acceptedRows)
            sourceIndex = max(1,numel(decoded.iterationHistory)-1);
            sourceSoft = decoded.iterationHistory(sourceIndex).soft;
            tau = sourceSoft.tauGlobal(acceptedRows);
            truthCfoAll = truth.trueDopplerHz/config.fftBinSpacingHz;
            count = numel(acceptedRows);
            pilotBlock = table( ...
                repmat(options.SnrGridDb(snrIndex),count,1), ...
                repmat(frameIndex,count,1), ...
                repmat(region(sampleIndex),count,1), ...
                acceptedRows-config.bootstrapPilotCount, ...
                sourceSoft.symbolCodewordMargin(acceptedRows)./max(tau,eps), ...
                sourceSoft.confidence(acceptedRows)./max(tau,eps), ...
                sourceSoft.decodedWaveformBins(acceptedRows) == ...
                    sourceSoft.hardWaveformBins(acceptedRows), ...
                decoded.detectedWaveformBins(acceptedRows),labels(acceptedRows), ...
                decoded.detectedWaveformBins(acceptedRows) == labels(acceptedRows), ...
                tracker.measuredResidualBins(acceptedRows), ...
                tracker.residualPeakRatio(acceptedRows), ...
                tracker.peakRatio(acceptedRows), ...
                tracker.measuredCfoBins(acceptedRows)-truthCfoAll(acceptedRows), ...
                'VariableNames',pilotSamples.Properties.VariableNames);
            pilotSamples = [pilotSamples;pilotBlock]; %#ok<AGROW>
        end

        truthCfoBins = truth.trueDopplerHz(payloadRows)/ ...
            config.fftBinSpacingHz;
        cfoResidual = tracker.predictedCfoBins(payloadRows)-truthCfoBins;
        hardBits = decoded.hardDecodedDataBits(:);
        softBits = decoded.decodedDataBits(:);
        referenceBits = payload.dataBits(:);
        row = table( ...
            options.SnrGridDb(snrIndex),frameIndex,region(sampleIndex), ...
            schedule.frameCenterTimeSec(frameIndex), ...
            driftBinsPerFrame(frameIndex),initialRate,trueBootstrapRate, ...
            initialRate-trueBootstrapRate,rateStandardError, ...
            decoded.iterations, ...
            sum(firstConfident),sum(firstMarginPass), ...
            sum(firstAgreement),sum(firstConfident & firstMarginPass), ...
            sum(firstConfident & firstMarginPass & firstAgreement), ...
            sum(firstIteration.proposedMask(payloadRows)), ...
            sum(finalIteration.proposedMask(payloadRows)), ...
            sum(finalIteration.stableMask(payloadRows)),sum(requested), ...
            sum(requested & available),sum(requested & measured), ...
            sum(requested & measured & residualPeakPass), ...
            sum(requested & measured & residualPeakPass & boundaryPass), ...
            sum(requested & measured & residualPeakPass & boundaryPass & ...
                innovationPass), ...
            sum(requested & measured & residualPeakPass & boundaryPass & ...
                innovationPass & decisionPeakPass), ...
            sum(accepted),sum(falseAccepted), ...
            tracker.acceptedVirtualPilotCount >= ...
                config.senloraRateReleasePilotCount, ...
            sqrt(mean(cfoResidual.^2)), ...
            sum(hardBits ~= referenceBits),sum(softBits ~= referenceBits), ...
            'VariableNames',records.Properties.VariableNames);
        records = [records;row]; %#ok<AGROW>
    end
end

summary = groupsummary(records,{'snrDb','region'},'mean', ...
    {'firstConfident','firstMarginPass','firstAgreement', ...
    'firstConfidenceAndMargin','firstAllProposalGates','firstProposed', ...
    'finalProposed','finalStable','requested', ...
    'availableRequested','residualMeasured','accepted','falseAccepted', ...
    'rateReleased','initialRateErrorBinsPerSec','rateStandardErrorBinsPerSec', ...
    'cfoRmseBins','hardBitErrors','softBitErrors'});
writetable(records,fullfile(resultDir,'stage55_gate_records.csv'));
writetable(summary,fullfile(resultDir,'stage55_gate_summary.csv'));
writetable(pilotSamples,fullfile(resultDir,'stage55_accepted_pilots.csv'));
save(fullfile(resultDir,'stage55_gate_audit.mat'), ...
    'config','options','minimumMarginRatio','requireAgreement', ...
    'useSoftPilotLabels','schedule','selected','region','records','summary', ...
    'pilotSamples');
report = struct('resultDir',resultDir,'records',records, ...
    'summary',summary,'pilotSamples',pilotSamples, ...
    'selectedFrameIndices',selected);
fprintf('Stage 55 admission root-cause audit: %s\n',resultDir);
disp(summary);
end

function selected = localEvenSample(indices,count)
if numel(indices) < count
    error('SatelliteFig3:Stage55AuditFrames', ...
        'The requested dynamic region does not contain enough frames.');
end
positions = round(linspace(1,numel(indices),count));
selected = indices(positions);
end

function records = localEmptyRecords()
records = table(zeros(0,1),zeros(0,1),cell(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),false(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1), ...
    'VariableNames',{'snrDb','frameIndex','region','frameCenterTimeSec', ...
    'driftBinsPerFrame','initialRateBinsPerSec','trueRateBinsPerSec', ...
    'initialRateErrorBinsPerSec','rateStandardErrorBinsPerSec', ...
    'iterations','firstConfident','firstMarginPass', ...
    'firstAgreement','firstConfidenceAndMargin','firstAllProposalGates', ...
    'firstProposed','finalProposed', ...
    'finalStable','requested','availableRequested','residualMeasured', ...
    'residualPeakPass','boundaryPass','innovationPass','allQualityPass', ...
    'accepted','falseAccepted','rateReleased','cfoRmseBins', ...
    'hardBitErrors','softBitErrors'});
end

function standardError = localBootstrapRateStandardError(joint,config)
design = [ones(numel(joint.symbolCenter),1),joint.symbolCenter, ...
    0.5*joint.symbolCenter.^2];
weight = abs(joint.coherentPilotPhasor).^2;
residualCycles = joint.phaseResidualRad/(2*pi);
dof = max(1,size(design,1)-size(design,2));
weightedVariance = sum(weight.*residualCycles.^2)/dof;
information = design.'*(design.*weight);
covariance = weightedVariance*pinv(information);
standardError = sqrt(max(covariance(3,3),0))/ ...
    config.symbolDurationSec;
end

function samples = localEmptyPilotSamples()
samples = table(zeros(0,1),zeros(0,1),cell(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),false(0,1),zeros(0,1),zeros(0,1), ...
    false(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    'VariableNames',{'snrDb','frameIndex','region','payloadSymbolIndex', ...
    'marginRatio','confidenceRatio','softHardAgreement','detectedBin', ...
    'trueBin','correct','residualBins','residualPeakRatio', ...
    'hardPeakRatio','measurementErrorBins'});
end
