function features = satelliteFig3PilotConfidenceFeatures(tracker, soft, config)
%SATELLITEFIG3PILOTCONFIDENCEFEATURES Receiver-visible virtual-pilot features.
%   This function never takes transmitted symbols or channel truth.  It is
%   shared by offline calibration and the eventual deployed confidence gate.

nSymbols = numel(tracker.detectedWaveformBins);
payloadRows = config.bootstrapPilotCount+(1:(nSymbols-config.bootstrapPilotCount));
nPayload = numel(payloadRows);
hardPeakRatio = tracker.peakRatio(payloadRows);
confidenceRatio = soft.confidence(payloadRows)./soft.tauGlobal(payloadRows);
residualPeakRatio = nan(nPayload,1);
residualAtBoundary = true(nPayload,1);
residualOffsetBins = nan(nPayload,1);
softHardAgreement = soft.decodedWaveformBins(payloadRows) == ...
    tracker.hardWaveformBins(payloadRows);
codewordMargin = soft.symbolCodewordMargin(payloadRows);
for idx = 1:nPayload
    row = payloadRows(idx);
    residual = satelliteFig3PhaseRotationEstimate( ...
        tracker.compensatedSymbols(row,:),soft.decodedWaveformBins(row),config, ...
        CandidateOffsets=config.residualSearchBins,LocalOnly=true);
    residualPeakRatio(idx) = residual.peakRatio;
    residualAtBoundary(idx) = residual.peakAtBoundary;
    residualOffsetBins(idx) = residual.offsetBins;
end
ready = soft.readyMask(payloadRows);
candidate = soft.confidentMask(payloadRows) & ready;
matrix = [ ...
    log(max(hardPeakRatio,1)), ...
    log(max(confidenceRatio,eps)), ...
    log(max(residualPeakRatio,1)), ...
    double(~residualAtBoundary), ...
    double(softHardAgreement)];
features = struct( ...
    'payloadRows',payloadRows(:), 'candidateMask',candidate, ...
    'hardPeakRatio',hardPeakRatio, 'confidenceRatio',confidenceRatio, ...
    'residualPeakRatio',residualPeakRatio, ...
    'residualAtBoundary',residualAtBoundary, ...
    'residualOffsetBins',residualOffsetBins, ...
    'softHardAgreement',softHardAgreement, ...
    'codewordMargin',codewordMargin, 'matrix',matrix);
end
