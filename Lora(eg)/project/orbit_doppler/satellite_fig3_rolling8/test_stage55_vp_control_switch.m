classdef test_stage55_vp_control_switch < SenLoRaStageTestCase
    %TEST_STAGE55_VP_CONTROL_SWITCH MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage55_vp_control_switch();
        end
    end
end

function check_test_stage55_vp_control_switch()
%TEST_STAGE55_VP_CONTROL_SWITCH Isolate the virtual-pilot treatment switch.

config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
known = zeros(config.bootstrapPilotCount,1);
payload = satelliteFig3GeneratePayload(config,2026360801);
labels = [known;payload.symbolBins];
[rx,~,~] = generateContinuousSatelliteFrame(labels,config, ...
    StartTimeSec=schedule.frameStartTimeSec(1),SampleSnrDb=-20, ...
    NoiseSeed=2026360901,NextSymbolBin=0);

noVp = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(1), ...
    EnableVirtualPilots=false);
vp = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(1), ...
    EnableVirtualPilots=true,UseQualityAwareVirtualPilots=false);
defaultVp = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(1));
qualityVp = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known, ...
    FrameStartTimeSec=schedule.frameStartTimeSec(1), ...
    UseQualityAwareVirtualPilots=true);
payloadRows = config.bootstrapPilotCount+1:config.frameSymbolCount;

assert(~noVp.virtualPilotsEnabled && vp.virtualPilotsEnabled, ...
    'The explicit VP treatment switch is not exposed by the wrapper.');
assert(~vp.qualityAwareVirtualPilotsEnabled && ...
        defaultVp.qualityAwareVirtualPilotsEnabled && ...
        qualityVp.qualityAwareVirtualPilotsEnabled, ...
    'The validated quality-aware Stage55 default is not exposed.');
assert(noVp.initialRateBinsPerSec == vp.initialRateBinsPerSec && ...
    noVp.commonBootstrap.epsilonHatBins == ...
    vp.commonBootstrap.epsilonHatBins, ...
    'NoVP and VP do not share the same bootstrap and initial rate.');
assert(isequaln(noVp.crossFrameState,vp.crossFrameState), ...
    'The payload treatment changed the preamble-only cross-frame state.');
assert(~any(noVp.pilotAccepted(payloadRows)) && ...
    noVp.tracker.acceptedVirtualPilotCount == 0 && ...
    ~any(noVp.tracker.compensationVirtualPilotCount(payloadRows)), ...
    'The NoVP branch leaked a payload-derived tracking observation.');
assert(isequal(qualityVp.decodedDataBits,defaultVp.decodedDataBits) && ...
    isequal(qualityVp.tracker.hardWaveformBins, ...
    defaultVp.tracker.hardWaveformBins) && ...
    isequaln(qualityVp.tracker.predictedCfoBins, ...
    defaultVp.tracker.predictedCfoBins), ...
    'The default Stage55 path is not the validated quality-aware mode.');
fprintf('Stage 55 paired VP control-switch test passed.\n');
end
