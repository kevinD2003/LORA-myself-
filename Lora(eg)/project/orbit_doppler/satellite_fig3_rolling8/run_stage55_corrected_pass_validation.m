function report = run_stage55_corrected_pass_validation(options)
%RUN_STAGE55_CORRECTED_PASS_VALIDATION Corrected continuous-pass receiver.
%   Each selected segment is processed in causal frame order.  SenLoRa
%   inherits only receiver-observed Huang preamble CFOs across frames,
%   keeps an eight-entry rolling state, admits the validated higher-density
%   virtual pilots, and delivers ML soft-Hamming payload bits.  Truth is
%   consulted only after decoding for audits and never enters the receiver.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.PassCount (1,1) double ...
        {mustBeInteger,mustBePositive} = 1
    options.FramesPerVisibleSegment (1,1) double = Inf
    options.PayloadSeedBase (1,1) double = 2026320800
    options.NoiseSeedBase (1,1) double = 2026320900
    options.OutputFolderName (1,:) char = ...
        'stage55_corrected_pass_validation'
    options.ProgressEveryFrames (1,1) double = 50
end
if ~(isinf(options.FramesPerVisibleSegment) || ( ...
        options.FramesPerVisibleSegment >= 1 && ...
        options.FramesPerVisibleSegment == ...
        round(options.FramesPerVisibleSegment)))
    error('SatelliteFig3:Stage55FramesPerSegment', ...
        'FramesPerVisibleSegment must be Inf or a positive integer.');
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
trajectory = satelliteFig3Trajectory(schedule.frameCenterTimeSec,config);
driftBinsPerFrame = abs(trajectory.dopplerRateHzPerSec).* ...
    schedule.frameDurationSec/config.fftBinSpacingHz;
segmentEdges = find(diff([false;schedule.fullyVisible(:);false]));
segments = reshape(segmentEdges,2,[]).'+[0 -1];
if isfinite(options.FramesPerVisibleSegment)
    segments(:,2) = min(segments(:,2), ...
        segments(:,1)+options.FramesPerVisibleSegment-1);
end

known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
records = localEmptyRecords();
processed = 0;
for snrIndex = 1:numel(options.SnrGridDb)
    for passIndex = 1:options.PassCount
        for segmentIndex = 1:size(segments,1)
            crossFrameState = struct();
            phaseStateRad = 0;
            for frameIndex = segments(segmentIndex,1):segments(segmentIndex,2)
                payloadSeed = options.PayloadSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                noiseSeed = options.NoiseSeedBase+ ...
                    1000000*snrIndex+10000*passIndex+frameIndex;
                payload = satelliteFig3GeneratePayload(config,payloadSeed);
                labels = [known;payload.symbolBins];
                [rx,~,truth] = generateContinuousSatelliteFrame( ...
                    labels,config, ...
                    StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    SampleSnrDb=options.SnrGridDb(snrIndex), ...
                    NoiseSeed=noiseSeed,InitialPhaseRad=phaseStateRad, ...
                    NextSymbolBin=0);
                phaseStateRad = localWrapToPi( ...
                    truth.nextFrameStartPhaseRad);

                decoded = satelliteFig3SenLoRaVirtualPilotDecode( ...
                    rx,config,known, ...
                    FrameStartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
                    CrossFrameState=crossFrameState);
                crossFrameState = decoded.crossFrameState;
                referenceBits = payload.dataBits(:);
                hardBits = decoded.hardDecodedDataBits(:);
                softBits = decoded.decodedDataBits(:);
                if numel(hardBits) ~= numel(referenceBits) || ...
                        numel(softBits) ~= numel(referenceBits)
                    error('SatelliteFig3:Stage55BitCount', ...
                        'The corrected receiver returned a wrong bit count.');
                end
                if any(decoded.tracker.activeHistoryCount(payloadRows) ~= ...
                        config.virtualPilotHistoryLength)
                    error('SatelliteFig3:Stage55RollingHistory', ...
                        'Every payload symbol must use a full rolling-8 state.');
                end

                trueRate = mean(truth.trueDopplerRateHzPerSec( ...
                    1:config.bootstrapPilotCount))/ ...
                    config.fftBinSpacingHz;
                truthCfo = truth.trueDopplerHz(payloadRows)/ ...
                    config.fftBinSpacingHz;
                cfoResidual = decoded.tracker.predictedCfoBins(payloadRows)- ...
                    truthCfo;
                accepted = decoded.pilotAccepted(payloadRows);
                falseAccepted = accepted & ...
                    decoded.detectedWaveformBins(payloadRows) ~= ...
                    labels(payloadRows);
                virtualPilotsUsed = ...
                    decoded.tracker.compensationVirtualPilotCount(payloadRows);
                updatedSymbolCount = sum(virtualPilotsUsed > 0);
                fullyVirtualSymbolCount = sum(virtualPilotsUsed == ...
                    config.virtualPilotHistoryLength);
                % In quality-aware Stage55, a payload rate is released
                % only when the VP time baseline meets the receiver-only
                % slope-standard-error requirement.  Pilot count alone is
                % no longer evidence that the rate is observable.
                rateReleased = any( ...
                    decoded.tracker.virtualPilotRateObservable(payloadRows));
                if driftBinsPerFrame(frameIndex) < 0.5
                    region = {'low_dynamic'};
                else
                    region = {'high_dynamic'};
                end
                row = table(options.SnrGridDb(snrIndex),passIndex, ...
                    segmentIndex,frameIndex,region, ...
                    decoded.crossFrameRateDiagnostic.historyCount, ...
                    decoded.isolatedFrameRateBinsPerSec, ...
                    decoded.initialRateBinsPerSec,trueRate, ...
                    decoded.initialRateBinsPerSec-trueRate, ...
                    sum(accepted),sum(falseAccepted), ...
                    rateReleased, ...
                    sum(cfoResidual.^2),numel(cfoResidual), ...
                    sum(hardBits ~= referenceBits), ...
                    sum(softBits ~= referenceBits), ...
                    numel(referenceBits), ...
                    min(decoded.tracker.activeHistoryCount(payloadRows)), ...
                    updatedSymbolCount,sum(virtualPilotsUsed), ...
                    fullyVirtualSymbolCount, ...
                    'VariableNames',records.Properties.VariableNames);
                records = [records;row]; %#ok<AGROW>
                processed = processed+1;
                if isfinite(options.ProgressEveryFrames) && ...
                        mod(processed,options.ProgressEveryFrames) == 0
                    fprintf('Stage 55 corrected validation: %d frames.\n', ...
                        processed);
                end
            end
        end
    end
end

summary = localSnrSummary(records,config,options.SnrGridDb);
regionSummary = groupsummary(records,{'snrDb','region'},'mean', ...
    {'acceptedPilots','falseAcceptedPilots','rateReleased', ...
    'rateErrorBinsPerSec','hardBitErrors','softBitErrors'});
writetable(records,fullfile(resultDir,'stage55_corrected_frame_records.csv'));
writetable(summary,fullfile(resultDir,'stage55_corrected_snr_summary.csv'));
writetable(regionSummary, ...
    fullfile(resultDir,'stage55_corrected_region_summary.csv'));
save(fullfile(resultDir,'stage55_corrected_validation.mat'), ...
    'config','options','schedule','segments','records','summary', ...
    'regionSummary');
report = struct('resultDir',resultDir,'records',records, ...
    'summary',summary,'regionSummary',regionSummary,'segments',segments);
fprintf('Stage 55 corrected pass validation: %s\n',resultDir);
disp(summary);
end

function summary = localSnrSummary(records,config,snrGrid)
[theoryBer,~] = satelliteFig3TheoreticalHammingBerAwgn( ...
    config.sf,snrGrid);
summary = table(snrGrid,theoryBer,zeros(size(snrGrid)), ...
    zeros(size(snrGrid)),zeros(size(snrGrid)),zeros(size(snrGrid)), ...
    zeros(size(snrGrid)),zeros(size(snrGrid)),zeros(size(snrGrid)), ...
    zeros(size(snrGrid)),zeros(size(snrGrid)),zeros(size(snrGrid)), ...
    zeros(size(snrGrid)),zeros(size(snrGrid)),zeros(size(snrGrid)), ...
    zeros(size(snrGrid)), ...
    'VariableNames',{'snrDb','hardHammingTheoryBer','bitCount', ...
    'hardBitErrors','softBitErrors','hardBer','softBer', ...
    'acceptedPilotsPerFrame','virtualPilotCoverage', ...
    'falseAcceptedPilots','rateReleaseFraction','cfoRmseBins', ...
    'updatedSymbolsPerFrame','updatedSymbolCoverage', ...
    'meanVirtualPilotsUsedPerSymbol','fullyVirtualHistoryCoverage'});
for snrIndex = 1:numel(snrGrid)
    selected = records.snrDb == snrGrid(snrIndex);
    bits = sum(records.bitCount(selected));
    cfoCount = sum(records.cfoSampleCount(selected));
    summary.bitCount(snrIndex) = bits;
    summary.hardBitErrors(snrIndex) = ...
        sum(records.hardBitErrors(selected));
    summary.softBitErrors(snrIndex) = ...
        sum(records.softBitErrors(selected));
    summary.hardBer(snrIndex) = summary.hardBitErrors(snrIndex)/bits;
    summary.softBer(snrIndex) = summary.softBitErrors(snrIndex)/bits;
    summary.acceptedPilotsPerFrame(snrIndex) = ...
        mean(records.acceptedPilots(selected));
    summary.virtualPilotCoverage(snrIndex) = ...
        sum(records.acceptedPilots(selected))/(sum(selected)* ...
        config.payloadSymbolCount);
    summary.falseAcceptedPilots(snrIndex) = ...
        sum(records.falseAcceptedPilots(selected));
    summary.rateReleaseFraction(snrIndex) = ...
        mean(records.rateReleased(selected));
    summary.cfoRmseBins(snrIndex) = sqrt( ...
        sum(records.cfoSseBins(selected))/cfoCount);
    payloadSymbolTotal = sum(selected)*config.payloadSymbolCount;
    summary.updatedSymbolsPerFrame(snrIndex) = ...
        sum(records.updatedSymbolCount(selected))/sum(selected);
    summary.updatedSymbolCoverage(snrIndex) = ...
        sum(records.updatedSymbolCount(selected))/payloadSymbolTotal;
    summary.meanVirtualPilotsUsedPerSymbol(snrIndex) = ...
        sum(records.virtualPilotsUsedSum(selected))/payloadSymbolTotal;
    summary.fullyVirtualHistoryCoverage(snrIndex) = ...
        sum(records.fullyVirtualSymbolCount(selected))/payloadSymbolTotal;
end
end

function records = localEmptyRecords()
records = table(zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    cell(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),false(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1),zeros(0,1), ...
    zeros(0,1),zeros(0,1),zeros(0,1), ...
    'VariableNames',{'snrDb','passIndex','segmentIndex','frameIndex', ...
    'region','crossFrameHistoryCount','isolatedRateBinsPerSec', ...
    'inheritedRateBinsPerSec','trueRateBinsPerSec', ...
    'rateErrorBinsPerSec','acceptedPilots','falseAcceptedPilots', ...
    'rateReleased','cfoSseBins','cfoSampleCount','hardBitErrors', ...
    'softBitErrors','bitCount','minimumActiveHistoryCount', ...
    'updatedSymbolCount','virtualPilotsUsedSum', ...
    'fullyVirtualSymbolCount'});
end

function phaseRad = localWrapToPi(phaseRad)
phaseRad = mod(phaseRad+pi,2*pi)-pi;
end
