classdef test_stage26_formal_checkpoint < SenLoRaStageTestCase
    %TEST_STAGE26_FORMAL_CHECKPOINT MATLAB unit-test wrapper for this stage regression.

    methods (Test)
        function runRegression(~)
            check_test_stage26_formal_checkpoint();
        end
    end
end

function check_test_stage26_formal_checkpoint()
%TEST_STAGE26_FORMAL_CHECKPOINT Verify bounded work and exact resume.

folder = 'stage26_formal_checkpoint_test';
first = run_stage26_formal_ber(SnrGridDb=-20,TargetBitErrors=300, ...
    MaxBitsPerPoint=1408,FrameBudgetThisCall=1, ...
    SymbolSeedBase=2026100300,NoiseSeedBase=2026100400, ...
    OutputFolderName=folder,Resume=false);
assert(first.framesUsedThisCall == 1 && ~first.allCompleted, ...
    'The first bounded formal call did not stop after one frame.');
assert(isfile(first.checkpointPath), ...
    'The formal runner did not create its checkpoint.');

second = run_stage26_formal_ber(SnrGridDb=-20,TargetBitErrors=300, ...
    MaxBitsPerPoint=1408,FrameBudgetThisCall=1, ...
    SymbolSeedBase=2026100300,NoiseSeedBase=2026100400, ...
    OutputFolderName=folder,Resume=true);
assert(second.allCompleted && second.state.frameCount == 2, ...
    'The resumed formal run did not continue at the next frame.');
assert(second.state.bits == 1408, ...
    'The formal max-bit stopping rule is incorrect.');
assert(second.state.commonNoiseMaxDifference < 1e-10, ...
    'The formal two-scenario run did not preserve common noise.');
required = {'berTheoryHamming','berNoComp','berHardPrec','berSenLoRa', ...
    'lower95NoComp','upper95SenLoRa','senFalseAccepted', ...
    'senRateReplayTriggeredFrames'};
required{end+1} = 'senRateReleasedFrames';
assert(all(ismember(required,second.table.Properties.VariableNames)), ...
    'The formal output table is missing required result or audit fields.');
assert(isfile(second.imagePath) && height(second.seedTable) == 1, ...
    'The formal plot or random-seed ledger is missing.');
fprintf('Stage 26 formal-checkpoint test passed.\n');
end
