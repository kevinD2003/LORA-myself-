classdef test_stage52_formal_artifact_wiring < SenLoRaStageTestCase
    %TEST_STAGE52_FORMAL_ARTIFACT_WIRING MATLAB unit-test wrapper for this regression.

    methods (Test)
        function runRegression(~)
            check_test_stage52_formal_artifact_wiring();
        end
    end
end

function check_test_stage52_formal_artifact_wiring()
%TEST_STAGE52_FORMAL_ARTIFACT_WIRING Synthetic complete-pass table/plot test.

config=satelliteFig3Config();
schedule=satelliteFig3ContinuousPassSchedule(config);
snrCount=1; passCount=1; frameCount=schedule.frameCount;
shape=[snrCount,passCount,frameCount];
visible=reshape(schedule.fullyVisible,1,1,[]);
state=struct('processed',true(shape), ...
    'payloadSeed',2026130000+reshape(1:frameCount,shape), ...
    'noiseSeed',2026140000+reshape(1:frameCount,shape), ...
    'bitCount',704*visible,'staticBitErrors',nan(shape), ...
    'senBitErrors',nan(shape),'staticFrameError',nan(shape), ...
    'senFrameError',nan(shape),'staticCfoSseBins',nan(shape), ...
    'senCfoSseBins',nan(shape),'cfoSampleCount',112*visible, ...
    'senAcceptedPilots',nan(shape),'senFalseAcceptedPilots',nan(shape), ...
    'staticRuntimeSec',nan(shape),'senRuntimeSec',nan(shape), ...
    'passCompleted',true,'snrCompleted',true, ...
    'completionReason',{{'synthetic_wiring'}}, ...
    'maxPhaseBridgeErrorRad',1e-12, ...
    'maxPhasePropagationErrorRad',1e-12,'maxTimeGapErrorSec',1e-14, ...
    'commonBootstrapCfoMaxDifferenceBins',0, ...
    'commonPayloadStartPhaseMaxDifferenceRad',0);
v=find(schedule.fullyVisible);
state.staticBitErrors(1,1,v)=mod((1:numel(v)).',17)==0;
state.senBitErrors(1,1,v)=mod((1:numel(v)).',23)==0;
state.staticFrameError(1,1,v)=state.staticBitErrors(1,1,v)>0;
state.senFrameError(1,1,v)=state.senBitErrors(1,1,v)>0;
state.staticCfoSseBins(1,1,v)=112*0.25^2;
state.senCfoSseBins(1,1,v)=112*0.10^2;
state.senAcceptedPilots(1,1,v)=2;
state.senFalseAcceptedPilots(1,1,v)=0;
state.staticRuntimeSec(1,1,v)=0.03;
state.senRuntimeSec(1,1,v)=0.20;
options=struct('SnrGridDb',-21,'WindowDurationSec',10, ...
    'BootstrapReplicates',100,'BootstrapSeed',2026121000, ...
    'PayloadSeedBase',2026120800,'NoiseSeedBase',2026120900);
root=fileparts(mfilename('fullpath'));
resultDir=fullfile(root,'results','stage52_formal_artifact_wiring_test');
artifacts=satelliteFig3Stage52WriteArtifacts(resultDir,state,options, ...
    config,schedule,{'Huang-PREC-static-CP','SenLoRa-VP'});
assert(height(artifacts.summaryTable)==2, ...
    'The synthetic formal summary must contain both methods.');
assert(all(artifacts.frameTable.includedInFormalStatistics == ...
    (artifacts.frameTable.fullyVisible & ...
    artifacts.frameTable.passCompleted)), ...
    'Blind or incomplete frames entered formal statistics.');
assert(all(artifacts.windowTable.completedPasses==1), ...
    'The synthetic window table lost the complete-pass count.');
assert(all(artifacts.windowTable.confidenceUnit == ...
    "single_complete_pass_wilson_wiring_only"), ...
    'A single pass was incorrectly labelled as formal bootstrap evidence.');
assert(~any(artifacts.pairedTable.formalPassBootstrapAvailable) && ...
    ~any(artifacts.pairedTable.senBerAdvantage95) && ...
    ~any(artifacts.pairedTable.senPerAdvantage95), ...
    'A single pass was incorrectly labelled as a 95%% paired advantage.');
assert(isfile(artifacts.imagePaths{1}) && isfile(artifacts.matPath) && ...
    isfile(artifacts.windowCsvPath) && isfile(artifacts.regionCsvPath), ...
    'A Stage 52 formal wiring artifact is missing.');
fprintf('Stage 52 formal artifact-wiring test passed.\n');
end
