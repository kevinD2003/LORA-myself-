function outputs = run_senlora_ber_smoke()
%RUNSENLORABERSMOKE Small raw-Monte-Carlo BER checkpoint.
%
% The grid is intentionally short.  It verifies common-random-number
% fairness before the formal -30:1:10 dB scan.

rootFolder = fileparts(mfilename("fullpath"));
resultFolder = fullfile(rootFolder,"results","ber_smoke");
if ~isfolder(resultFolder)
    mkdir(resultFolder);
end
config = senloraChannelConfig();
snrGrid = (-30:2:-10).';
minBitsPerPoint = 30800;
methodNames = ["raw","blind_hard","senlora"];
rows = struct([]);
for scenarioIdx = 1:numel(config.scenarios)
    for snrIdx = 1:numel(snrGrid)
        point = simulateSenLoRaBerPoint( ...
            config,scenarioIdx,snrGrid(snrIdx), ...
            TargetBitErrors=100,MinBits=minBitsPerPoint, ...
            MaxBits=minBitsPerPoint,MaxFrames=100,Methods=methodNames);
        for methodIdx = 1:numel(methodNames)
            method = point.methods(methodIdx);
            row = struct( ...
                "scenario",string(point.scenario), ...
                "snrDb",point.snrDb, ...
                "method",methodNames(methodIdx), ...
                "bitErrors",method.bitErrors, ...
                "symbolErrors",method.symbolErrors, ...
                "totalBits",method.totalBits, ...
                "totalSymbols",method.totalSymbols, ...
                "ber",method.ber, ...
                "ser",method.ser, ...
                "berUpper95Zero",method.berUpper95Zero, ...
                "frameBerLower95",method.frameBerLower95, ...
                "frameBerUpper95",method.frameBerUpper95, ...
                "meanPayloadPilotCount",method.meanPayloadPilotCount, ...
                "frameCount",point.frameCount, ...
                "seedSymbols",point.seedSymbols, ...
                "seedNoiseBase",point.seedNoiseBase);
            if isempty(rows)
                rows = row;
            else
                rows(end+1,1) = row; %#ok<AGROW>
            end
        end
    end
end
tableRows = struct2table(rows);
writetable(tableRows,fullfile(resultFolder,"ber_smoke.csv"));
theory = senloraTheoreticalBerAwgn(config.sf,snrGrid);
save(fullfile(resultFolder,"ber_smoke.mat"),"tableRows","theory","config");

fig = figure("Visible","off","Color","w","Position",[80,80,1450,620]);
layout = tiledlayout(1,numel(config.scenarios),"TileSpacing","compact", ...
    "Padding","compact");
colors = lines(numel(methodNames));
for scenarioIdx = 1:numel(config.scenarios)
    nexttile(layout,scenarioIdx); hold on;
    scenarioName = string(config.scenarios(scenarioIdx).name);
    for methodIdx = 1:numel(methodNames)
        mask = string(tableRows.scenario)==scenarioName & ...
            string(tableRows.method)==methodNames(methodIdx);
        subset = sortrows(tableRows(mask,:), "snrDb");
        shown = subset.ber;
        zeroMask = subset.bitErrors==0;
        shown(zeroMask) = NaN;
        semilogy(subset.snrDb,shown,"-o","Color",colors(methodIdx,:), ...
            "LineWidth",1.1,"MarkerSize",4,"DisplayName",methodNames(methodIdx));
        if any(zeroMask)
            semilogy(subset.snrDb(zeroMask), ...
                subset.berUpper95Zero(zeroMask),"v", ...
                "Color",colors(methodIdx,:),"MarkerFaceColor","w", ...
                "HandleVisibility","off");
        end
    end
    denseSnr = linspace(min(snrGrid),max(snrGrid),401).';
    denseTheory = senloraTheoreticalBerAwgn(config.sf,denseSnr);
    semilogy(denseSnr,denseTheory,"k--","LineWidth",1.2, ...
        "DisplayName","AWGN theory");
    grid on; box on;
    set(gca,"YScale","log");
    xlabel("Sample SNR (dB)");
    ylabel("BER / zero-error 95% upper bound");
    title(strrep(scenarioName,"_"," "));
    ylim([1e-6,1]);
    legend("Location","southwest","NumColumns",2);
end
title(layout,"BER smoke checkpoint: same frame/noise/trajectory, raw Monte Carlo");
exportgraphics(fig,fullfile(resultFolder,"ber_smoke.png"),"Resolution",180);
close(fig);

metadata = struct( ...
    "folder",resultFolder, ...
    "snrDb",snrGrid, ...
    "methods",methodNames, ...
    "targetBitErrors",100, ...
    "minBitsPerPoint",minBitsPerPoint, ...
    "maxBitsPerPoint",minBitsPerPoint, ...
    "dopplerModel",config.dopplerModel, ...
    "scenarios",config.scenarios, ...
    "zeroErrorPlot","3/totalBits one-sided 95% upper-bound convention", ...
    "note","Equal-bit raw Monte Carlo; zero-error bounds are markers only; no fitted or smoothed curves.");
fid = fopen(fullfile(resultFolder,"ber_smoke_metadata.json"),"w");
if fid < 0
    error("SenLoRa:BerMetadataOpenFailed","Could not write BER metadata.");
end
cleanup = onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(metadata),"char");

outputs = struct("table",tableRows,"theory",theory, ...
    "figure",fullfile(resultFolder,"ber_smoke.png"), ...
    "csv",fullfile(resultFolder,"ber_smoke.csv"), ...
    "metadata",fullfile(resultFolder,"ber_smoke_metadata.json"));
end
