function nkserExportPlan()
%NKSEREXPORTPLAN Write the immutable Rician plan and registered seed policy.
roots=nkserSetup();[points,configs]=nkserProjectConditions();
endpoints=[10 20 25 35 45 50];
plan=struct('experimentId','normalized-k10-receiver-ser-v1','points',points, ...
    'configs',{configs},'count',50,'gateLocalIndices',endpoints, ...
    'gatePackets',100,'formalPackets',1000,'pairedDiagnosticPackets',100, ...
    'seedRoots',struct('gate100',3000000000,'formal1000',3100000000, ...
        'pairedHalf100',3200000000),'packetSeedStride',8, ...
    'shards',4,'checkpointPackets',5,'methods', ...
    {{'prec','vp','paper','idealNative','idealPaper'}}, ...
    'metric','pre-FEC FFT hard decision over 112 data chirps; no BER output', ...
    'profileSha256',nkserHash(roots.profilePath));
content=jsonencode(plan,PrettyPrint=true);file=fullfile(roots.root,'POINTS.json');
if isfile(file)
    assert(strcmp(fileread(file),content),'NkSer:PlanChanged','Existing plan differs.');
else
    writeText(file,content);
end
end

function writeText(file,content)
fid=fopen(file,'w','n','UTF-8');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s',content);
end
