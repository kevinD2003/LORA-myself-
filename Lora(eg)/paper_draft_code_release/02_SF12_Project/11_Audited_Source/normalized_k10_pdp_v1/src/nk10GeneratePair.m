function pair=nk10GeneratePair(config,startSec,snrDb,seeds)
%NK10GENERATEPAIR Native/Paper V4 frames through the registered K10 channel.
arguments
    config (1,1) struct
    startSec (1,1) double {mustBeFinite}
    snrDb (1,1) double {mustBeFinite}
    seeds (1,1) struct
end
c=config.parent;profile=nk10Profile();
assert(c.physicalSf==c.effectiveDataSf&&ismember(c.physicalSf,[7 12])&& ...
    c.samplesPerSymbol==2^c.physicalSf&&c.sampleRateHz==125e3&& ...
    c.bandwidthHz==125e3&&c.carrierFrequencyHz==868e6&& ...
    c.orbitHeightM==550e3&&c.cr==3&&c.payloadSymbolCount==112&& ...
    c.ricianKDb==10,'Nk10:ProjectProfile','Unexpected user project PHY/orbit.');
required={'payloadSeed','noiseSeed','channelSeed','paperExtraNoiseSeed'};
assert(all(isfield(seeds,required)),'Nk10:Seeds','Four explicit seed domains are required.');
values=cellfun(@(name)double(seeds.(name)),required);
assert(all(values>=0&values==fix(values)&values<=2^32-1)&& ...
    numel(unique(values))==4,'Nk10:Seeds','Seeds must be distinct uint32-range integers.');
initialPhase=config.initialChannelPhaseRad;
native=v4GenerateNativeFrame(c,startSec,Inf,seeds,initialPhase,'AWGN',false);
pilot=v4GenerateNativeFrame(c,startSec,Inf,seeds,initialPhase,'AWGN',true);
assert(native.observation.layout.physicalSymbolCount==120&& ...
    pilot.observation.layout.physicalSymbolCount==120+c.paperMidambleCount, ...
    'Nk10:Layout','Unexpected native/Paper layout.');
assert(isequal(native.truth.payloadPhysicalBins,pilot.truth.payloadPhysicalBins)&& ...
    isequal(native.truth.dataBits,pilot.truth.dataBits),'Nk10:Payload','Paired payload mismatch.');
[taps,delays]=nk10DrawTaps(seeds.channelSeed);
variance=10^(-snrDb/10);
[nativeNoise,pilotNoise]=pairedNoise(native.observation.layout,pilot.observation.layout, ...
    c.samplesPerSymbol,variance,seeds.noiseSeed,seeds.paperExtraNoiseSeed);
[native,nativePhase,nativePower]=propagate(native,nativeNoise);
[pilot,pilotPhase,pilotPower]=propagate(pilot,pilotNoise);
purpose='offline-common-Doppler-removal-only-retain-normalized-K10-PDP-and-noise';
pair=struct('native',native,'pilot',pilot, ...
    'nativeIdeal',struct('rxPhysical',native.observation.rxPhysical.*exp(-1i*nativePhase),'purpose',purpose), ...
    'pilotIdeal',struct('rxPhysical',pilot.observation.rxPhysical.*exp(-1i*pilotPhase),'purpose',purpose), ...
    'ledger',seeds);
pair.power=struct('txPower',1,'noiseVariance',variance, ...
    'realizedTapEnergy',sum(abs(taps).^2), ...
    'measuredNativeCleanPower',nativePower,'measuredPilotCleanPower',pilotPower, ...
    'ensembleChannelPower',1,'linkMarginDb',0);
pair.channelExperiment=struct('cohortId','normalized-k10-pdp-v1', ...
    'model','packet-constant-normalized-K10-zero-plus-delayed-diffuse-PDP', ...
    'actualKDb',10,'ensembleMeanPower',1,'losPower',10/11,'diffusePower',1/11, ...
    'profile',profile,'pathDelaysSamples',delays, ...
    'pathDelaysSec',delays/c.sampleRateHz,'perPacketPowerNormalization',false, ...
    'linkMarginDb',0,'noiseVariance',variance, ...
    'noiseScaling','fixed-from-nominal-SNR-independent-of-realized-taps', ...
    'commonOrbitalDoppler',true,'extraDiffuseDopplerHz',0, ...
    'timeline','native-120-and-Paper-own-129-or-157-physical-rows', ...
    'paperCodeBoundary','public-code-Rician-LOS/scatter-normalization', ...
    'projectAdaptationBoundary','causal-LoRa-PDP-not-present-in-public-multibeam-code');

    function [frame,phase,cleanPower]=propagate(frame,noise)
        layout=frame.observation.layout;
        phase=prefecPacketOraclePhase(c,frame.truth.payloadPhysicalBins,layout,startSec,initialPhase);
        bins=zeros(layout.physicalSymbolCount,1);bins(layout.dataRows)=frame.truth.payloadPhysicalBins;
        tx=complex(zeros(layout.physicalSymbolCount,c.samplesPerSymbol));
        for row=1:layout.physicalSymbolCount,tx(row,:)=v4ModulateSymbol(bins(row),c);end
        clean=nk10ApplyChannel(tx,taps,delays);
        rx=clean.*exp(1i*phase)+noise;
        frame.observation.rxPhysical=rx;frame.observation.noiseVariance=variance;
        frame.observation.sampleFingerprint=[sum(abs(rx(:)).^2) sum(real(rx(:))) sum(imag(rx(:)))];
        frame.truth.channelModel='normalized-K10-zero-plus-delayed-diffuse-PDP';
        frame.truth.channelTaps=taps;frame.truth.channelDelaysSamples=delays;
        frame.truth.oraclePhasePhysicalRad=phase;
        cleanPower=mean(abs(clean(:)).^2);
    end
end

function [nativeNoise,pilotNoise]=pairedNoise(nativeLayout,pilotLayout,m,variance,commonSeed,extraSeed)
common=RandStream('mt19937ar','Seed',commonSeed);
nativeNoise=sqrt(variance/2)*(randn(common,nativeLayout.physicalSymbolCount,m)+ ...
    1i*randn(common,nativeLayout.physicalSymbolCount,m));
pilotNoise=complex(zeros(pilotLayout.physicalSymbolCount,m));
pilotNoise(pilotLayout.bootstrapRows,:)=nativeNoise(nativeLayout.bootstrapRows,:);
pilotNoise(pilotLayout.dataRows,:)=nativeNoise(nativeLayout.dataRows,:);
extra=RandStream('mt19937ar','Seed',extraSeed);shape=[numel(pilotLayout.midambleRows),m];
pilotNoise(pilotLayout.midambleRows,:)=sqrt(variance/2)*(randn(extra,shape)+1i*randn(extra,shape));
end

