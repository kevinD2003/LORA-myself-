function v4ValidateReceiverParameters(parameters)
%V4VALIDATERECEIVERPARAMETERS Validate mechanism parameters without freezing them.

required = {'searchStepBins','residualSearchBins','historyDecay', ...
    'huberThresholdBins','residualPeakRatioThreshold', ...
    'decisionPeakRatioThreshold','innovationLimitBins', ...
    'singleSymbolInnovationGain','phasePairInnovationGain', ...
    'phasePairInnovationLimitBins','phasePairAgreementLimitBins', ...
    'virtualPilotCfoStdBins','virtualPilotRateStdLimitBinsPerSec', ...
    'rateDeviationLimitBinsPerSec','maximumRateBinsPerSec', ...
    'confidenceAlpha','confidenceThresholdScale','softHammingMarginRatio', ...
    'minimumCrossFrameHistoryForVirtualPilots'};
for index = 1:numel(required)
    name = required{index};
    if ~isfield(parameters,name) || any(~isfinite(parameters.(name)),'all')
        error('V4:ReceiverParameter','Missing or nonfinite receiver parameter %s.',name);
    end
end
if ~isfield(parameters,'requireSoftHardAgreement') || ...
        ~islogical(parameters.requireSoftHardAgreement) || ...
        ~isscalar(parameters.requireSoftHardAgreement)
    error('V4:ReceiverParameter','requireSoftHardAgreement must be scalar logical.');
end
if parameters.historyDecay <= 0 || parameters.historyDecay > 1 || ...
        parameters.singleSymbolInnovationGain < 0 || ...
        parameters.singleSymbolInnovationGain > 1 || ...
        parameters.phasePairInnovationGain < 0 || ...
        parameters.phasePairInnovationGain > 1
    error('V4:ReceiverParameterRange','Receiver parameter is outside its valid range.');
end
if parameters.minimumCrossFrameHistoryForVirtualPilots < 1 || ...
        parameters.minimumCrossFrameHistoryForVirtualPilots ~= ...
        floor(parameters.minimumCrossFrameHistoryForVirtualPilots)
    error('V4:ReceiverParameterRange','Minimum cross-frame history must be positive integer.');
end
end
