function estimate = v4PaperRefinedPointEstimate(symbolSamples,knownPhysicalBin,c)
%V4PAPERREFINEDPOINTESTIMATE Integer FFT acquisition plus local refinement.
coarse = v4PaperIntegerPointEstimate(symbolSamples,knownPhysicalBin,c);
candidates = coarse.offsetBins+(-0.5:0.25:0.5).';
refined = v4PhaseRotationEstimate( ...
    symbolSamples,knownPhysicalBin,c,candidates);
estimate = struct('offsetBins',refined.offsetBins, ...
    'coarseIntegerBins',coarse.offsetBins, ...
    'phaseRad',refined.phaseRad,'peakMetric',refined.peakMetric, ...
    'peakRatio',refined.peakRatio,'peakAtBoundary',refined.peakAtBoundary, ...
    'resolutionBins',0.25,'usesPayloadTruth',false,'usesOrbitTruth',false);
end
