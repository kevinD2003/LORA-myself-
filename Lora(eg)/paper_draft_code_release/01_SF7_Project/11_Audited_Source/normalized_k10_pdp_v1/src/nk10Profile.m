function profile=nk10Profile()
%NK10PROFILE Registered no-margin unit-power K10 LEO-LoRa PDP adaptation.
root=fileparts(fileparts(mfilename('fullpath')));
value=jsondecode(fileread(fullfile(root,'CHANNEL_PROFILE.json')));
profile=struct('id',value.id,'kLinear',double(value.ricianKLinear), ...
    'kDb',double(value.ricianKDb),'ensembleTotalPower',double(value.ensembleTotalPower), ...
    'losPhaseRad',double(value.losPhaseRad), ...
    'delaysSamples',double(value.delaysSamples(:).'), ...
    'diffuseRelativePowers',double(value.diffuseRelativePowers(:).'), ...
    'linkMarginDb',double(value.linkMarginDb), ...
    'perPacketPowerNormalization',logical(value.perPacketPowerNormalization), ...
    'overallRmsDelayMicroseconds',double(value.overallRmsDelayMicroseconds), ...
    'provenance',value.provenance);
assert(profile.kLinear==10&&profile.kDb==10&&profile.ensembleTotalPower==1&& ...
    profile.linkMarginDb==0&&~profile.perPacketPowerNormalization, ...
    'Nk10:ProfilePower','Profile must be normalized K10 with zero margin.');
assert(isequal(profile.delaysSamples,0:4)&& ...
    all(profile.diffuseRelativePowers>0)&& ...
    abs(sum(profile.diffuseRelativePowers)-1)<1e-12, ...
    'Nk10:ProfilePdp','Expected one zero-delay plus four normalized diffuse taps.');
end

