function measurement = senloraSymbolVpMeasure( ...
        samples,chosen,firstCfo,jointCfo,c,parameters,blockSearchRatio)
%SENLORASYMBOLVPMEASURE Independent waveform measurements after block ML.
% codewordMargin is a row-level SHARED coding guard, not symbol confidence.
% All effectiveDataSf rows participate in each diagonal-interleaved symbol.
% Do not claim independent coding evidence for the seven symbols.
n = size(samples,1);
sharedMarginRatio = min(chosen.codewordMargin)/ ...
    max(mean(abs(chosen.bestCodewordScore)),eps);
sharedGuard = isfinite(sharedMarginRatio) && ...
    sharedMarginRatio>=parameters.softHammingMarginRatio && ...
    isfinite(blockSearchRatio) && ...
    blockSearchRatio>=parameters.residualPeakRatioThreshold;
measurement = struct('accepted',false(n,1), ...
    'knownPhysicalBins',chosen.softReencodedPhysicalBins(:), ...
    'hardPhysicalBins',chosen.hardPhysicalBins(:), ...
    'labelAgreement',chosen.softReencodedPhysicalBins(:)== ...
        chosen.hardPhysicalBins(:), ...
    'decisionPeakRatio',chosen.decisionPeakRatio(:), ...
    'residualCfoBins',zeros(n,1),'correctionCfoBins',zeros(n,1), ...
    'residualPhaseRad',zeros(n,1),'residualPeakRatio',ones(n,1), ...
    'residualPeakMetric',zeros(n,1),'residualAtBoundary',false(n,1), ...
    'residualInRange',false(n,1),'confidence',ones(n,1), ...
    'sharedCodingMarginRatio',sharedMarginRatio, ...
    'sharedBlockGuard',sharedGuard,'sampleFingerprint',zeros(n,3));
for k = 1:n
    residual = v4PhaseRotationEstimate(samples(k,:), ...
        measurement.knownPhysicalBins(k),c,parameters.residualSearchBins);
    % Positive received rotation is estimated positive and compensated negative.
    % history stores correction relative to FIRST PASS, never absolute CFO.
    z = jointCfo(k)-firstCfo(k)+residual.offsetBins;
    measurement.residualCfoBins(k) = residual.offsetBins;
    measurement.correctionCfoBins(k) = z;
    measurement.residualPhaseRad(k) = residual.phaseRad;
    measurement.residualPeakRatio(k) = residual.peakRatio;
    measurement.residualPeakMetric(k) = residual.peakMetric;
    measurement.residualAtBoundary(k) = residual.peakAtBoundary;
    measurement.residualInRange(k) = ...
        abs(residual.offsetBins)<=parameters.innovationLimitBins;
    measurement.sampleFingerprint(k,:) = [sum(abs(samples(k,:)).^2), ...
        sum(real(samples(k,:))),sum(imag(samples(k,:)))];
    quality = min(measurement.decisionPeakRatio(k)/ ...
        parameters.decisionPeakRatioThreshold,residual.peakRatio/ ...
        parameters.residualPeakRatioThreshold);
    measurement.confidence(k) = min(4,max(1,quality));
    finite = all(isfinite([z residual.offsetBins residual.phaseRad ...
        residual.peakRatio residual.peakMetric quality]));
    measurement.accepted(k) = sharedGuard && finite && ...
        measurement.labelAgreement(k) && ...
        measurement.decisionPeakRatio(k)>=parameters.decisionPeakRatioThreshold && ...
        residual.peakRatio>=parameters.residualPeakRatioThreshold && ...
        measurement.residualInRange(k) && ~residual.peakAtBoundary;
end
end
