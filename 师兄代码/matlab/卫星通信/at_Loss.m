f = 1; % 载波频率，单位为GHz
p = 1007.25; % 干燥空气压力，单位为hPa
T = 288; % 温度，单位为开尔文
lo = 26; % 水汽密度，单位为g/m3
% lo = 0;

e = lo * T / 216.7; % 水汽压力，单位为hPa

sita = 300 / T;

d = 5.6 * 10^(-4) * (p + e) * sita^(0.8); % 宽度参数

N_D = f * p * sita^2 * (6.14 * 10^(-5) / (d * (1 + (f / d)^2)) + 1.4 * 10^(-12) * p * sita^(1.5) / (1 + 1.9 * 10^(-5) * f^1.5));

R = 0.1820 * f * N_D; % 衰减值，单位为dB/km
