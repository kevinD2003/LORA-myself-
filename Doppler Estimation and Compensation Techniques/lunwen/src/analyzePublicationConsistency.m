function analysis = analyzePublicationConsistency(cfg)
%ANALYZEPUBLICATIONCONSISTENCY Test Table 3 against realizable frames.

arguments
    cfg (1,1) struct
end

layout = buildFrameLayout(cfg);
symbolDurationS = cfg.radio.symbolDurationS;
payloadSymbols = layout.payloadSymbols;
spacing = cfg.frame.midambleSpacingDataSymbols;
fractionalMidambleCount = payloadSymbols/spacing;
floorMidambleCount = floor(fractionalMidambleCount);
ceilingMidambleCount = ceil(fractionalMidambleCount);

analysis.symbolDurationS = symbolDurationS;
analysis.payloadSymbols = payloadSymbols;
analysis.midambleSpacingDataSymbols = spacing;
analysis.fractionalMidambleCount = fractionalMidambleCount;
analysis.floorMidambleCount = floorMidambleCount;
analysis.equation20MidambleCount = ceilingMidambleCount;
analysis.implementedMidambleCount = layout.numberOfMidambles;
analysis.pointToaS = layout.pointToaS;
analysis.paperTableMidamblePointToaS = ...
    cfg.paper.midamblePointToaS;
analysis.fractionalApproximationToaS = layout.pointToaS + ...
    fractionalMidambleCount*symbolDurationS;
analysis.floorRealizableToaS = layout.pointToaS + ...
    floorMidambleCount*symbolDurationS;
analysis.ceilingRealizableToaS = layout.pointToaS + ...
    ceilingMidambleCount*symbolDurationS;
analysis.implementedToaS = layout.midamblePointToaS;
analysis.tableVsFractionalDifferenceS = ...
    cfg.paper.midamblePointToaS-analysis.fractionalApproximationToaS;
analysis.tableVsImplementedDifferenceS = ...
    cfg.paper.midamblePointToaS-layout.midamblePointToaS;
analysis.roundingToleranceS = 0.5e-3;
analysis.fractionalCountIsNoninteger = ...
    fractionalMidambleCount ~= floorMidambleCount;
analysis.tableMatchesFractionalApproximation = ...
    abs(analysis.tableVsFractionalDifferenceS) <= ...
    analysis.roundingToleranceS;
analysis.tableMatchesImplementedFrame = ...
    abs(analysis.tableVsImplementedDifferenceS) <= ...
    analysis.roundingToleranceS;
analysis.implementationMatchesEquation20 = ...
    layout.numberOfMidambles == ceilingMidambleCount;
analysis.tableBetweenAdjacentRealizableFrames = ...
    cfg.paper.midamblePointToaS > analysis.floorRealizableToaS && ...
    cfg.paper.midamblePointToaS < analysis.ceilingRealizableToaS;
analysis.paperInternalConflictProved = ...
    analysis.fractionalCountIsNoninteger && ...
    analysis.tableMatchesFractionalApproximation && ...
    ~analysis.tableMatchesImplementedFrame && ...
    analysis.implementationMatchesEquation20 && ...
    analysis.tableBetweenAdjacentRealizableFrames;
end
