%VALIDATEPAPERCALIBRATION Validate fitted parameters with an unseen seed.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
outputFolder = fullfile(projectRoot, 'results', 'calibrated', 'validation');
if ~isfolder(outputFolder)
    mkdir(outputFolder);
end
addpath(fullfile(projectRoot, 'config'));
addpath(fullfile(projectRoot, 'src'));

limits = struct('batchPackets', 32, 'minimumPackets', 5000, ...
    'maximumPackets', 5000, 'minimumSymbolErrors', 0);
reference = readtable(fullfile(projectRoot, 'reference', ...
    'paperEndpointAcceptance.csv'), 'TextType', 'string');
rows = table();

for spreadingFactor = [7, 12]
    if spreadingFactor == 7
        cfg = calibratedPaperSf7Config();
    else
        cfg = calibratedPaperSf12Config();
    end
    selectedReference = reference( ...
        reference.spreadingFactor == spreadingFactor, :);
    for rowIndex = 1:height(selectedReference)
        paperRow = selectedReference(rowIndex, :);
        result = simulateSerPoint(cfg, paperRow.caseName, ...
            paperRow.strategy, paperRow.snrDb, limits);
        isMatch = result.ser >= paperRow.serLow && ...
            result.ser <= paperRow.serHigh;
        newRow = table(spreadingFactor, paperRow.caseName, ...
            paperRow.strategy, paperRow.snrDb, result.ser, ...
            result.ci95Low, result.ci95High, result.symbolErrors, ...
            result.totalSymbols, result.packets, result.randomSeed, ...
            paperRow.serLow, paperRow.serHigh, isMatch, true, ...
            'VariableNames', {'spreadingFactor', 'caseName', ...
            'strategy', 'snrDb', 'ser', 'ci95Low', 'ci95High', ...
            'symbolErrors', 'totalSymbols', 'packets', 'randomSeed', ...
            'paperLow', 'paperHigh', 'withinPaperBand', ...
            'fittedOrTuned'});
        rows = [rows; newRow]; %#ok<AGROW>
        fprintf('SF=%d %s %s SER=%g match=%d\n', ...
            spreadingFactor, paperRow.caseName, paperRow.strategy, ...
            result.ser, isMatch);
    end
end

writetable(rows, fullfile(outputFolder, ...
    'calibrated_endpoint_validation.csv'));
audit = struct();
audit.state = "calibration_validation_completed";
audit.randomSeed = 314159;
audit.seedUsedDuringSearch = false;
audit.packetsPerEndpoint = 5000;
audit.matchCount = nnz(rows.withinPaperBand);
audit.referenceCount = height(rows);
audit.allEndpointsWithinPaperBands = all(rows.withinPaperBand);
audit.fittedOrTuned = true;
audit.completeIndependentReproductionClaimed = false;
audit.parameters = struct('ricianKDb', 12.75, ...
    'estimatorFftPaddingFactor', 4, ...
    'midambleEstimatorFftPaddingFactor', 1, ...
    'midambleUpdateDelayDataSymbols', 1, ...
    'midambleEstimatorSnrOffsetSf7Db', -0.5, ...
    'midambleEstimatorSnrOffsetSf12Db', -0.25, ...
    'frameDopplerTimeScale', 0.5, ...
    'commonRandomNumbersAcrossStrategies', true);
fileId = fopen(fullfile(outputFolder, ...
    'calibration_validation_audit.json'), 'w');
assert(fileId >= 0);
closeFile = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s', jsonencode(audit));
assert(audit.allEndpointsWithinPaperBands, ...
    'Calibrated profile failed independent endpoint validation.');
