resultsFolder = fullfile(projectRoot, 'results');

startTime = tic;
runReproductionCase(cfg, "case1", cfg.monteCarlo.snrDb, ...
    limits, resultsFolder, "");
runReproductionCase(cfg, "case2", cfg.monteCarlo.snrDb, ...
    limits, resultsFolder, "");
combineCaseFigureFiles( ...
    fullfile(resultsFolder, 'case1_sf11.png'), ...
    fullfile(resultsFolder, 'case2_sf11.png'), ...
    fullfile(resultsFolder, ...
    'sf11_midamble_point_case1_case2.png'));
fprintf('Full SF=11 experiment completed in %.1f s.\n', ...
    toc(startTime));
