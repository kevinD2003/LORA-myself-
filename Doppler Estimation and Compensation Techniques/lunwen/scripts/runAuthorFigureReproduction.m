%RUNAUTHORFIGUREREPRODUCTION Reproduce the public author-source figure profile.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'config'));
addpath(fullfile(projectRoot, 'src'));
resultsFolder = fullfile(projectRoot, 'results');
limits7 = monteCarloLimits(authorFigureSf7Config(), "full");
limits12 = monteCarloLimits(authorFigureSf12Config(), "full");

startTime = tic;
cfg7 = authorFigureSf7Config();
runReproductionCase(cfg7, "case1", cfg7.monteCarlo.snrDb, ...
    limits7, resultsFolder, "_author_source");
runReproductionCase(cfg7, "case2", cfg7.monteCarlo.snrDb, ...
    limits7, resultsFolder, "_author_source");

cfg12 = authorFigureSf12Config();
runReproductionCase(cfg12, "case1", cfg12.monteCarlo.snrDb, ...
    limits12, resultsFolder, "_author_source");
runReproductionCase(cfg12, "case2", cfg12.monteCarlo.snrDb, ...
    limits12, resultsFolder, "_author_source");

combineCaseFigureFiles( ...
    fullfile(resultsFolder, 'case1_sf7_author_source.png'), ...
    fullfile(resultsFolder, 'case2_sf7_author_source.png'), ...
    fullfile(resultsFolder, 'author_source_sf7_case1_case2.png'));
combineCaseFigureFiles( ...
    fullfile(resultsFolder, 'case1_sf12_author_source.png'), ...
    fullfile(resultsFolder, 'case2_sf12_author_source.png'), ...
    fullfile(resultsFolder, 'author_source_sf12_case1_case2.png'));
fprintf('Author-source reproduction completed in %.1f s.\n', ...
    toc(startTime));
