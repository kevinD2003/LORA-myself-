%RENDERCALIBRATEDFIGURES Merge held-out endpoints and render fitted curves.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
outputFolder = fullfile(projectRoot, 'results', 'calibrated', 'curves');
validation = readtable(fullfile(projectRoot, 'results', 'calibrated', ...
    'validation', 'calibrated_endpoint_validation.csv'), ...
    'TextType', 'string');
addpath(fullfile(projectRoot, 'config'));
addpath(fullfile(projectRoot, 'src'));

for spreadingFactor = [7, 12]
    if spreadingFactor == 7
        cfg = calibratedPaperSf7Config();
    else
        cfg = calibratedPaperSf12Config();
    end
    endpointSnrDb = max(cfg.monteCarlo.snrDb);
    for caseName = ["case1", "case2"]
        inputCsv = fullfile(outputFolder, ...
            caseName + "_sf" + spreadingFactor + "_calibrated.csv");
        data = readtable(inputCsv, 'TextType', 'string');
        for strategy = ["no_doppler", "point", "midamble_point"]
            curveRow = data.strategy == strategy & ...
                data.snrDb == endpointSnrDb;
            validationRow = validation.spreadingFactor == ...
                spreadingFactor & validation.caseName == caseName & ...
                validation.strategy == strategy;
            assert(nnz(curveRow) == 1 && nnz(validationRow) == 1);
            copiedNames = ["ser", "ci95Low", "ci95High", ...
                "symbolErrors", "totalSymbols", "packets", "randomSeed"];
            for variableName = copiedNames
                data.(variableName)(curveRow) = ...
                    validation.(variableName)(validationRow);
            end
        end
        writetable(data, inputCsv);
        outputPng = fullfile(outputFolder, ...
            caseName + "_sf" + spreadingFactor + "_calibrated.png");
        plotSerResults(inputCsv, outputPng, ...
            "Calibrated (fitted) " + caseName + ...
            " - SF = " + spreadingFactor, cfg, true);
    end
    combineCaseFigureFiles( ...
        fullfile(outputFolder, ...
        "case1_sf" + spreadingFactor + "_calibrated.png"), ...
        fullfile(outputFolder, ...
        "case2_sf" + spreadingFactor + "_calibrated.png"), ...
        fullfile(outputFolder, ...
        "figure10_11_sf" + spreadingFactor + "_calibrated.png"));
end
fprintf('Calibrated figures rendered from held-out endpoint data.\n');
