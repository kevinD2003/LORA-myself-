%COMBINEALLSFFIGURES Stack the audited SF=7, SF=11 and SF=12 panels.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
resultsFolder = fullfile(projectRoot, 'results');
sf7 = imread(fullfile(resultsFolder, ...
    'figure10_11_sf7_midamble_point.png'));
sf11 = imread(fullfile(resultsFolder, ...
    'sf11_midamble_point_case1_case2.png'));
sf12 = imread(fullfile(resultsFolder, ...
    'figure10_11_sf12_midamble_point.png'));
maxWidth = max([size(sf7, 2), size(sf11, 2), size(sf12, 2)]);
panelHeight = size(sf7, 1);
assert(size(sf11, 1) == panelHeight && ...
    size(sf12, 1) == panelHeight, ...
    'Combined SF figures must have equal heights.');
summaryImage = uint8(255*ones(3*panelHeight, maxWidth, 3));
sf7Start = floor((maxWidth-size(sf7, 2))/2) + 1;
sf11Start = floor((maxWidth-size(sf11, 2))/2) + 1;
sf12Start = floor((maxWidth-size(sf12, 2))/2) + 1;
summaryImage(1:panelHeight, ...
    sf7Start:sf7Start+size(sf7, 2)-1, :) = sf7;
summaryImage(panelHeight+1:2*panelHeight, ...
    sf11Start:sf11Start+size(sf11, 2)-1, :) = sf11;
summaryImage(2*panelHeight+1:3*panelHeight, ...
    sf12Start:sf12Start+size(sf12, 2)-1, :) = sf12;
imwrite(summaryImage, fullfile(resultsFolder, ...
    'sf7_sf11_sf12_midamble_summary.png'));
