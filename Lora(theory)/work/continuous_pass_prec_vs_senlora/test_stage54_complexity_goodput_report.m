function test_stage54_complexity_goodput_report()
%TEST_STAGE54_COMPLEXITY_GOODPUT_REPORT Verify frozen complexity metrics.

report = run_stage54_complexity_goodput_report(WriteArtifacts=false);
complexity = report.complexityTable;
runtime = report.runtimeTable;
dynamic = report.dynamicTable;

huang = strcmp(complexity.method,'Huang-PREC-static-CP');
sen = strcmp(complexity.method,'SenLoRa-VP');
assert(complexity.totalLengthMFFTsLower(huang) == 200 && ...
    complexity.totalLengthMFFTsUpper(huang) == 200, ...
    'Huang code-level FFT count changed.');
assert(complexity.totalLengthMFFTsLower(sen) == 552 && ...
    complexity.totalLengthMFFTsUpper(sen) == 1248, ...
    'SenLoRa 2-to-5 iteration FFT bounds changed.');
assert(complexity.residualOffsetCandidateCount(sen) == 11 && ...
    complexity.rollingHistoryLength(sen) == 8, ...
    'SenLoRa residual-search or rolling-history dimensions changed.');

assert(height(runtime) == 4 && all(runtime.formalFrameCount == 5*432), ...
    'Runtime table must use all five complete passes at both SNR points.');
assert(all(runtime.meanRuntimeSecPerFrame < 0.25) && ...
    all(runtime.processingDeadlineMissRate == 0) && ...
    all(runtime.realTimeMarginFrames > 1), ...
    'A formal receiver path no longer meets the 0.98304 s frame deadline.');
for snrDb = [-21,-20]
    static = runtime.snrDb == snrDb & ...
        strcmp(runtime.method,'Huang-PREC-static-CP');
    senRow = runtime.snrDb == snrDb & strcmp(runtime.method,'SenLoRa-VP');
    assert(runtime.runtimeRatioToHuang(static) == 1 && ...
        runtime.runtimeRatioToHuang(senRow) > 5, ...
        'Measured complexity separation is missing at %g dB.',snrDb);
    expectedGoodput = report.nominalPayloadRateBps*(1-runtime.per);
    assert(max(abs(runtime.activeLinkPacketGoodputBps-expectedGoodput)) < 1e-10, ...
        'Packet-goodput definition is inconsistent with PER.');

    for region = {'low_dynamic_lt_0p5_bin_per_frame', ...
            'high_dynamic_ge_0p5_bin_per_frame'}
        staticRegion = dynamic.snrDb == snrDb & ...
            strcmp(dynamic.dynamicRegion,region{1}) & ...
            strcmp(dynamic.method,'Huang-PREC-static-CP');
        senRegion = dynamic.snrDb == snrDb & ...
            strcmp(dynamic.dynamicRegion,region{1}) & ...
            strcmp(dynamic.method,'SenLoRa-VP');
        if startsWith(region{1},'low_')
            assert(dynamic.activeLinkGoodputBps(staticRegion) > ...
                dynamic.activeLinkGoodputBps(senRegion), ...
                'Huang low-dynamic goodput advantage disappeared.');
        else
            assert(dynamic.activeLinkGoodputBps(senRegion) > ...
                dynamic.activeLinkGoodputBps(staticRegion), ...
                'SenLoRa high-dynamic goodput advantage disappeared.');
        end
    end
end

fprintf(['Stage 54 complexity/goodput test passed: analytical counts, ' ...
    'runtime deadline, and dynamic-region delivery tradeoff.\n']);
end
