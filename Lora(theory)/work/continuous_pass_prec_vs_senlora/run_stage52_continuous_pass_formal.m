function report = run_stage52_continuous_pass_formal(options)
%RUN_STAGE52_CONTINUOUS_PASS_FORMAL Checkpointed repeated full-pass study.
%   Each repeat advances all complete frame slots from acquisition to loss
%   of visibility.  Only fully visible frames enter communication metrics.
%   The two receivers see the exact same waveform.  A fixed-SNR point is
%   complete only after a whole pass and the registered repeat/error rule.

arguments
    options.SnrGridDb (:,1) double = [-21;-20]
    options.MinCompletePasses (1,1) double ...
        {mustBeInteger,mustBePositive} = 5
    options.MaxCompletePasses (1,1) double ...
        {mustBeInteger,mustBePositive} = 20
    options.TargetBitErrorsPerMethod (1,1) double ...
        {mustBeInteger,mustBePositive} = 300
    options.FrameBudgetThisCall (1,1) double = Inf
    options.CheckpointEveryFrames (1,1) double ...
        {mustBeInteger,mustBePositive} = 10
    options.PayloadSeedBase (1,1) double = 2026120800
    options.NoiseSeedBase (1,1) double = 2026120900
    options.WindowDurationSec (1,1) double {mustBePositive} = 10
    options.BootstrapReplicates (1,1) double ...
        {mustBeInteger,mustBePositive} = 10000
    options.BootstrapSeed (1,1) double = 2026121000
    options.OutputFolderName (1,:) char = ...
        'stage52_formal_continuous_pass'
    options.Resume (1,1) logical = true
    options.WriteArtifacts (1,1) logical = true
    options.ProgressEveryFrames (1,1) double = 50
end
localValidateOptions(options);

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
checkpointPath = fullfile(resultDir,'stage52_checkpoint.mat');
config = satelliteFig3Config();
schedule = satelliteFig3ContinuousPassSchedule(config);
methodNames = {'Huang-PREC-static-CP','SenLoRa-VP'};
signature = localSignature(root,options,config,schedule);

if options.Resume && isfile(checkpointPath)
    loaded = load(checkpointPath,'state','savedSignature');
    if ~isequaln(loaded.savedSignature,signature)
        error('SatelliteFig3:Stage52ResumeMismatch', ...
            ['The Stage 52 checkpoint does not match the requested SNR, ' ...
            'pass/error limits, seeds, physical model, or receiver source.']);
    end
    state = loaded.state;
else
    state = localInitialState(numel(options.SnrGridDb), ...
        options.MaxCompletePasses,schedule.frameCount);
end

known = zeros(config.bootstrapPilotCount,1);
payloadRows = (config.bootstrapPilotCount+1:config.frameSymbolCount).';
framesUsedThisCall = 0;
while state.pointerSnrIndex <= numel(options.SnrGridDb) && ...
        framesUsedThisCall < options.FrameBudgetThisCall
    snrIndex = state.pointerSnrIndex;
    passIndex = state.pointerPassIndex;
    frameIndex = state.pointerFrameIndex;
    payloadSeed = localFrameSeed(options.PayloadSeedBase, ...
        passIndex,frameIndex);
    noiseSeed = localFrameSeed(options.NoiseSeedBase, ...
        passIndex,frameIndex);
    payload = satelliteFig3GeneratePayload(config,payloadSeed);
    labels = [known;payload.symbolBins];
    [rx,~,truth] = generateContinuousSatelliteFrame(labels,config, ...
        StartTimeSec=schedule.frameStartTimeSec(frameIndex), ...
        SampleSnrDb=options.SnrGridDb(snrIndex), ...
        NoiseSeed=noiseSeed,InitialPhaseRad=state.phaseStateRad, ...
        NextSymbolBin=0);

    if frameIndex > 1
        timeError = truth.sampleTimeSec(1,1)- ...
            state.previousLastTimeSec-1/config.sampleRateHz;
        expectedBridge = pi/config.sampleRateHz*( ...
            state.previousLastDopplerHz+truth.dopplerHz(1,1));
        bridgeError = localWrapToPi(truth.phaseRad(1,1)- ...
            state.previousLastPhaseRad-expectedBridge);
        propagationError = localWrapToPi(truth.initialPhaseRad- ...
            state.previousNextFrameStartPhaseRad);
        state.maxTimeGapErrorSec(snrIndex,passIndex) = max( ...
            state.maxTimeGapErrorSec(snrIndex,passIndex),abs(timeError));
        state.maxPhaseBridgeErrorRad(snrIndex,passIndex) = max( ...
            state.maxPhaseBridgeErrorRad(snrIndex,passIndex), ...
            abs(bridgeError));
        state.maxPhasePropagationErrorRad(snrIndex,passIndex) = max( ...
            state.maxPhasePropagationErrorRad(snrIndex,passIndex), ...
            abs(propagationError));
    end
    state.phaseStateRad = localWrapToPi(truth.nextFrameStartPhaseRad);
    state.previousLastPhaseRad = truth.phaseRad(end,end);
    state.previousLastDopplerHz = truth.dopplerHz(end,end);
    state.previousLastTimeSec = truth.sampleTimeSec(end,end);
    state.previousNextFrameStartPhaseRad = truth.nextFrameStartPhaseRad;

    state.processed(snrIndex,passIndex,frameIndex) = true;
    state.payloadSeed(snrIndex,passIndex,frameIndex) = payloadSeed;
    state.noiseSeed(snrIndex,passIndex,frameIndex) = noiseSeed;
    if schedule.fullyVisible(frameIndex)
        staticTimer = tic;
        staticPrec = satelliteFig3HuangPrecStaticCpDecode(rx,config,known);
        state.staticRuntimeSec(snrIndex,passIndex,frameIndex) = ...
            toc(staticTimer);
        senTimer = tic;
        senlora = satelliteFig3SenLoRaVirtualPilotDecode(rx,config,known);
        state.senRuntimeSec(snrIndex,passIndex,frameIndex) = toc(senTimer);

        referenceBits = payload.dataBits(:);
        staticBits = staticPrec.decodedDataBits(:);
        senBits = senlora.hardDecodedDataBits(:);
        if numel(staticBits) ~= numel(referenceBits) || ...
                numel(senBits) ~= numel(referenceBits)
            error('SatelliteFig3:Stage52BitCount', ...
                'A receiver returned an unexpected decoded payload length.');
        end
        staticErrors = sum(staticBits ~= referenceBits);
        senErrors = sum(senBits ~= referenceBits);
        state.bitCount(snrIndex,passIndex,frameIndex) = ...
            numel(referenceBits);
        state.staticBitErrors(snrIndex,passIndex,frameIndex) = staticErrors;
        state.senBitErrors(snrIndex,passIndex,frameIndex) = senErrors;
        state.staticFrameError(snrIndex,passIndex,frameIndex) = ...
            staticErrors > 0;
        state.senFrameError(snrIndex,passIndex,frameIndex) = senErrors > 0;

        truthBins = truth.trueDopplerHz(payloadRows)/ ...
            config.fftBinSpacingHz;
        staticResidual = staticPrec.tracker.predictedCfoBins(payloadRows)- ...
            truthBins;
        senResidual = senlora.tracker.predictedCfoBins(payloadRows)- ...
            truthBins;
        state.staticCfoSseBins(snrIndex,passIndex,frameIndex) = ...
            sum(staticResidual.^2);
        state.senCfoSseBins(snrIndex,passIndex,frameIndex) = ...
            sum(senResidual.^2);
        state.cfoSampleCount(snrIndex,passIndex,frameIndex) = ...
            numel(payloadRows);
        accepted = senlora.pilotAccepted(payloadRows);
        state.senAcceptedPilots(snrIndex,passIndex,frameIndex) = ...
            sum(accepted);
        state.senFalseAcceptedPilots(snrIndex,passIndex,frameIndex) = ...
            sum(accepted & senlora.detectedWaveformBins(payloadRows) ~= ...
            labels(payloadRows));
        state.commonBootstrapCfoMaxDifferenceBins = max( ...
            state.commonBootstrapCfoMaxDifferenceBins,abs( ...
            staticPrec.bootstrap.epsilonHatBins- ...
            senlora.commonBootstrap.epsilonHatBins));
        firstSenTracker = senlora.iterationHistory(1).tracker;
        state.commonPayloadStartPhaseMaxDifferenceRad = max( ...
            state.commonPayloadStartPhaseMaxDifferenceRad,abs( ...
            staticPrec.tracker.predictedPhaseStartRad(payloadRows(1))- ...
            firstSenTracker.predictedPhaseStartRad(payloadRows(1))));
    end

    framesUsedThisCall = framesUsedThisCall+1;
    state.totalFramesProcessed = state.totalFramesProcessed+1;
    state = localAdvancePointer(state,options,schedule);
    if mod(state.totalFramesProcessed,options.CheckpointEveryFrames) == 0
        localSaveCheckpoint(checkpointPath,state,signature,options, ...
            config,schedule,methodNames);
    end
    if isfinite(options.ProgressEveryFrames) && ( ...
            mod(framesUsedThisCall,options.ProgressEveryFrames) == 0 || ...
            state.pointerSnrIndex > numel(options.SnrGridDb))
        fprintf(['Stage 52 call frames=%d, total=%d, completed passes=' ...
            '%s, completed SNR=%d/%d.\n'],framesUsedThisCall, ...
            state.totalFramesProcessed,mat2str(sum(state.passCompleted,2).'), ...
            sum(state.snrCompleted),numel(options.SnrGridDb));
    end
end
localSaveCheckpoint(checkpointPath,state,signature,options,config, ...
    schedule,methodNames);

artifacts = struct();
if options.WriteArtifacts && any(state.passCompleted,'all')
    artifacts = satelliteFig3Stage52WriteArtifacts(resultDir,state, ...
        options,config,schedule,methodNames);
end
report = struct('resultDir',resultDir,'checkpointPath',checkpointPath, ...
    'state',state,'signature',signature,'artifacts',artifacts, ...
    'framesUsedThisCall',framesUsedThisCall, ...
    'allCompleted',all(state.snrCompleted));
fprintf(['Stage 52 checkpoint: processed %d frames this call; ' ...
    'complete passes %s; complete SNR %d/%d.\n'],framesUsedThisCall, ...
    mat2str(sum(state.passCompleted,2).'),sum(state.snrCompleted), ...
    numel(options.SnrGridDb));
end

function localValidateOptions(options)
if isempty(options.SnrGridDb) || any(~isfinite(options.SnrGridDb)) || ...
        any(diff(options.SnrGridDb) <= 0)
    error('SatelliteFig3:Stage52SnrGrid', ...
        'SnrGridDb must be a nonempty strictly increasing vector.');
end
if options.MaxCompletePasses < options.MinCompletePasses
    error('SatelliteFig3:Stage52PassLimits', ...
        'MaxCompletePasses must be at least MinCompletePasses.');
end
if ~(isinf(options.FrameBudgetThisCall) || ( ...
        isfinite(options.FrameBudgetThisCall) && ...
        options.FrameBudgetThisCall >= 1 && ...
        options.FrameBudgetThisCall == round(options.FrameBudgetThisCall)))
    error('SatelliteFig3:Stage52FrameBudget', ...
        'FrameBudgetThisCall must be Inf or a positive integer.');
end
if ~(isinf(options.ProgressEveryFrames) || ( ...
        isfinite(options.ProgressEveryFrames) && ...
        options.ProgressEveryFrames >= 1 && ...
        options.ProgressEveryFrames == round(options.ProgressEveryFrames)))
    error('SatelliteFig3:Stage52Progress', ...
        'ProgressEveryFrames must be Inf or a positive integer.');
end
end

function state = localInitialState(snrCount,maxPasses,frameCount)
shape = [snrCount,maxPasses,frameCount];
state = struct( ...
    'processed',false(shape), ...
    'payloadSeed',nan(shape),'noiseSeed',nan(shape), ...
    'bitCount',zeros(shape), ...
    'staticBitErrors',nan(shape),'senBitErrors',nan(shape), ...
    'staticFrameError',nan(shape),'senFrameError',nan(shape), ...
    'staticCfoSseBins',nan(shape),'senCfoSseBins',nan(shape), ...
    'cfoSampleCount',zeros(shape), ...
    'senAcceptedPilots',nan(shape), ...
    'senFalseAcceptedPilots',nan(shape), ...
    'staticRuntimeSec',nan(shape),'senRuntimeSec',nan(shape), ...
    'passCompleted',false(snrCount,maxPasses), ...
    'snrCompleted',false(snrCount,1), ...
    'completionReason',{repmat({''},snrCount,1)}, ...
    'maxPhaseBridgeErrorRad',zeros(snrCount,maxPasses), ...
    'maxPhasePropagationErrorRad',zeros(snrCount,maxPasses), ...
    'maxTimeGapErrorSec',zeros(snrCount,maxPasses), ...
    'commonBootstrapCfoMaxDifferenceBins',0, ...
    'commonPayloadStartPhaseMaxDifferenceRad',0, ...
    'pointerSnrIndex',1,'pointerPassIndex',1,'pointerFrameIndex',1, ...
    'phaseStateRad',0,'previousLastPhaseRad',NaN, ...
    'previousLastDopplerHz',NaN,'previousLastTimeSec',NaN, ...
    'previousNextFrameStartPhaseRad',NaN, ...
    'totalFramesProcessed',0);
end

function state = localAdvancePointer(state,options,schedule)
snrIndex = state.pointerSnrIndex;
passIndex = state.pointerPassIndex;
frameIndex = state.pointerFrameIndex;
if frameIndex < schedule.frameCount
    state.pointerFrameIndex = frameIndex+1;
    return
end

state.passCompleted(snrIndex,passIndex) = true;
staticErrors = localCompletedErrorTotal( ...
    state.staticBitErrors,snrIndex,state.passCompleted(snrIndex,:));
senErrors = localCompletedErrorTotal( ...
    state.senBitErrors,snrIndex,state.passCompleted(snrIndex,:));
enoughPasses = passIndex >= options.MinCompletePasses;
errorTargetReached = staticErrors >= options.TargetBitErrorsPerMethod && ...
    senErrors >= options.TargetBitErrorsPerMethod;
maximumReached = passIndex >= options.MaxCompletePasses;
if enoughPasses && errorTargetReached
    state.snrCompleted(snrIndex) = true;
    state.completionReason{snrIndex} = 'min_passes_and_error_target';
elseif maximumReached
    state.snrCompleted(snrIndex) = true;
    state.completionReason{snrIndex} = 'maximum_complete_passes';
end

if state.snrCompleted(snrIndex)
    state.pointerSnrIndex = snrIndex+1;
    state.pointerPassIndex = 1;
else
    state.pointerPassIndex = passIndex+1;
end
state.pointerFrameIndex = 1;
state.phaseStateRad = 0;
state.previousLastPhaseRad = NaN;
state.previousLastDopplerHz = NaN;
state.previousLastTimeSec = NaN;
state.previousNextFrameStartPhaseRad = NaN;
end

function total = localCompletedErrorTotal(values,snrIndex,completedPassMask)
selected = values(snrIndex,completedPassMask,:);
total = sum(selected(:),'omitnan');
end

function seed = localFrameSeed(base,passIndex,frameIndex)
seed = base+10000*passIndex+frameIndex;
end

function signature = localSignature(root,options,config,schedule)
signature = struct( ...
    'snrGridDb',options.SnrGridDb, ...
    'minCompletePasses',options.MinCompletePasses, ...
    'maxCompletePasses',options.MaxCompletePasses, ...
    'targetBitErrorsPerMethod',options.TargetBitErrorsPerMethod, ...
    'payloadSeedBase',options.PayloadSeedBase, ...
    'noiseSeedBase',options.NoiseSeedBase, ...
    'windowDurationSec',options.WindowDurationSec, ...
    'bootstrapReplicates',options.BootstrapReplicates, ...
    'bootstrapSeed',options.BootstrapSeed, ...
    'methodNames',{{'Huang-PREC-static-CP','SenLoRa-VP'}}, ...
    'sf',config.sf,'bandwidthHz',config.bandwidthHz, ...
    'sampleRateHz',config.sampleRateHz, ...
    'carrierFrequencyHz',config.carrierFrequencyHz, ...
    'orbitHeightM',config.orbitHeightM, ...
    'inclinationRad',config.inclinationRad, ...
    'bootstrapPilotCount',config.bootstrapPilotCount, ...
    'payloadSymbolCount',config.payloadSymbolCount, ...
    'frameCount',schedule.frameCount, ...
    'passStartTimeSec',schedule.passStartTimeSec, ...
    'passEndTimeSec',schedule.passEndTimeSec, ...
    'fullyVisibleMask',schedule.fullyVisible);
configFields = {'virtualPilotHistoryLength','maxSenLoRaIterations', ...
    'confidenceAlpha','confidenceThresholdScale','amendLlrMix', ...
    'senloraMinimumMarginRatio','senloraRequireSoftHardAgreement', ...
    'confidenceInnovationLimitBins','residualPeakRatioThreshold', ...
    'decisionPeakRatioThreshold','historyDecay','huberThresholdBins', ...
    'maxRateBinsPerSec','senloraRateReleasePilotCount', ...
    'senloraUseCausalConfidenceTiming','senloraUseSoftDecodedPilotLabels'};
for fieldIndex = 1:numel(configFields)
    field = configFields{fieldIndex};
    signature.(field) = config.(field);
end
sourceFiles = {'run_stage52_continuous_pass_formal.m', ...
    'satelliteFig3Stage52WriteArtifacts.m', ...
    'generateContinuousSatelliteFrame.m', ...
    'satelliteFig3HuangPrecCpBootstrapEstimate.m', ...
    'satelliteFig3HuangPrecStaticCpDecode.m', ...
    'satelliteFig3SenLoRaVirtualPilotDecode.m', ...
    'satelliteFig3RollingPilotTracker.m', ...
    'satelliteFig3SenLoRaIterativeDecode.m'};
signature.sourceFiles = sourceFiles;
signature.sourceText = cell(size(sourceFiles));
for fileIndex = 1:numel(sourceFiles)
    signature.sourceText{fileIndex} = fileread( ...
        fullfile(root,sourceFiles{fileIndex}));
end
end

function localSaveCheckpoint(path,state,signature,options,config, ...
        schedule,methodNames)
savedSignature = signature;
temporaryPath = [path '.tmp.mat'];
save(temporaryPath,'state','savedSignature','options','config', ...
    'schedule','methodNames','-v7');
[moved,message] = movefile(temporaryPath,path,'f');
if ~moved
    error('SatelliteFig3:Stage52CheckpointWrite', ...
        'Could not replace Stage 52 checkpoint: %s',message);
end
end

function phaseRad = localWrapToPi(phaseRad)
phaseRad = mod(phaseRad+pi,2*pi)-pi;
end
