function report = run_stage51_preregistered_snr_freeze(options)
%RUN_STAGE51_PREREGISTERED_SNR_FREEZE Freeze fixed-SNR time experiments.
%   Selection depends only on the analytical AWGN Hamming(7,4) reference.
%   Neither receiver output nor orbit-tracking performance enters the rule.

arguments
    options.CandidateSnrDb (:,1) double = (-23:-19).'
    options.MainTargetBer (1,1) double {mustBePositive} = 1e-3
    options.SupplementalTargetBer (1,1) double {mustBePositive} = 1e-4
    options.OutputFolderName (1,:) char = ...
        'stage51_preregistered_snr_freeze'
end
if isempty(options.CandidateSnrDb) || ...
        any(~isfinite(options.CandidateSnrDb)) || ...
        any(diff(options.CandidateSnrDb) <= 0)
    error('SatelliteFig3:Stage51CandidateGrid', ...
        'CandidateSnrDb must be a nonempty strictly increasing grid.');
end

root = fileparts(mfilename('fullpath'));
resultDir = fullfile(root,'results',options.OutputFolderName);
if ~isfolder(resultDir), mkdir(resultDir); end
config = satelliteFig3Config();
snrDb = options.CandidateSnrDb(:);
[codedBer,uncodedBer] = satelliteFig3TheoreticalHammingBerAwgn( ...
    config.sf,snrDb);
mainLogDistance = abs(log10(codedBer)-log10(options.MainTargetBer));
supplementalLogDistance = abs(log10(codedBer)- ...
    log10(options.SupplementalTargetBer));
[~,mainIndex] = min(mainLogDistance);
[~,supplementalIndex] = min(supplementalLogDistance);
mainSnrDb = snrDb(mainIndex);
supplementalSnrDb = snrDb(supplementalIndex);
isMainSelection = false(size(snrDb));
isSupplementalSelection = false(size(snrDb));
isMainSelection(mainIndex) = true;
isSupplementalSelection(supplementalIndex) = true;

candidateTable = table(snrDb,uncodedBer,codedBer,mainLogDistance, ...
    supplementalLogDistance,isMainSelection,isSupplementalSelection);
candidateCsvPath = fullfile(resultDir,'stage51_snr_candidates.csv');
writetable(candidateTable,candidateCsvPath);

selectionRole = {'main';'supplemental'};
targetBer = [options.MainTargetBer;options.SupplementalTargetBer];
selectedSnrDb = [mainSnrDb;supplementalSnrDb];
selectedTheoryBer = [codedBer(mainIndex);codedBer(supplementalIndex)];
selectedLogDistance = [mainLogDistance(mainIndex); ...
    supplementalLogDistance(supplementalIndex)];
selectionTable = table(selectionRole,targetBer,selectedSnrDb, ...
    selectedTheoryBer,selectedLogDistance);
selectionCsvPath = fullfile(resultDir,'stage51_snr_selection.csv');
writetable(selectionTable,selectionCsvPath);

selectionRule = ['For each registered target independently, choose the ' ...
    'first SNR on the strictly increasing candidate grid that minimizes ' ...
    'abs(log10(theoretical coded AWGN BER)-log10(target BER)).'];
freeze = struct('sf',config.sf,'candidateSnrDb',snrDb.', ...
    'mainTargetBer',options.MainTargetBer, ...
    'supplementalTargetBer',options.SupplementalTargetBer, ...
    'mainSnrDb',mainSnrDb,'supplementalSnrDb',supplementalSnrDb, ...
    'mainTheoreticalBer',codedBer(mainIndex), ...
    'supplementalTheoreticalBer',codedBer(supplementalIndex), ...
    'selectionRule',selectionRule, ...
    'receiverOutputsUsedForSelection',false, ...
    'randomNumbersUsedForSelection',false);
jsonPath = fullfile(resultDir,'stage51_snr_freeze.json');
file = fopen(jsonPath,'w');
if file < 0
    error('SatelliteFig3:Stage51Json', ...
        'Could not open the Stage 51 freeze record for writing.');
end
cleanup = onCleanup(@() fclose(file));
fwrite(file,jsonencode(freeze),'char');
clear cleanup;

imagePath = fullfile(resultDir,'stage51_preregistered_snr_freeze.png');
fig = figure('Visible','off','Color','w','Position',[90 90 920 600]);
semilogy(snrDb,uncodedBer,'^-.','Color',[0.45 0.45 0.45], ...
    'LineWidth',1.15,'MarkerSize',7,'MarkerFaceColor','none', ...
    'DisplayName','Uncoded orthogonal-CSS reference');
hold on;
semilogy(snrDb,codedBer,'ko-','LineWidth',1.5,'MarkerSize',6, ...
    'MarkerFaceColor','w','DisplayName','Hamming(7,4) hard-decision theory');
yline(options.MainTargetBer,'b:','Main target 10^{-3}', ...
    'LineWidth',1.1,'LabelHorizontalAlignment','left', ...
    'HandleVisibility','off');
yline(options.SupplementalTargetBer,'r:','Supplemental target 10^{-4}', ...
    'LineWidth',1.1,'LabelHorizontalAlignment','left', ...
    'HandleVisibility','off');
semilogy(mainSnrDb,codedBer(mainIndex),'bs','LineWidth',1.5, ...
    'MarkerSize',10,'MarkerFaceColor','none', ...
    'DisplayName',sprintf('Frozen main SNR: %g dB',mainSnrDb));
semilogy(supplementalSnrDb,codedBer(supplementalIndex),'rd', ...
    'LineWidth',1.5,'MarkerSize',10,'MarkerFaceColor','none', ...
    'DisplayName',sprintf('Frozen supplemental SNR: %g dB', ...
    supplementalSnrDb));
grid on; grid minor; box on;
xlim([snrDb(1)-0.3 snrDb(end)+0.3]);
ylim([1e-6 3e-1]);
xticks(snrDb);
xlabel('Sample SNR (dB)');
ylabel('Analytical BER');
title({'Stage 51 preregistered fixed-SNR freeze', ...
    'Selection uses theory only; receiver curves are not inspected'}, ...
    'FontWeight','normal');
legend('Location','southwest','Box','on');
set(gca,'FontName','Times New Roman','FontSize',11, ...
    'GridLineStyle',':','MinorGridLineStyle',':');
exportgraphics(fig,imagePath,'Resolution',220);
savefig(fig,fullfile(resultDir,'stage51_preregistered_snr_freeze.fig'));
close(fig);

matPath = fullfile(resultDir,'stage51_preregistered_snr_freeze.mat');
save(matPath,'config','options','candidateTable','selectionTable','freeze');
report = struct('resultDir',resultDir,'imagePath',imagePath, ...
    'candidateCsvPath',candidateCsvPath, ...
    'selectionCsvPath',selectionCsvPath,'jsonPath',jsonPath, ...
    'matPath',matPath,'candidateTable',candidateTable, ...
    'selectionTable',selectionTable,'freeze',freeze, ...
    'mainSnrDb',mainSnrDb,'supplementalSnrDb',supplementalSnrDb);
fprintf('Stage 51 fixed-SNR freeze: main=%g dB, supplemental=%g dB.\n', ...
    mainSnrDb,supplementalSnrDb);
disp(selectionTable);
end
