function test_stage53_formal_result_acceptance()
%TEST_STAGE53_FORMAL_RESULT_ACCEPTANCE Audit the frozen formal artifacts.

projectFolder = fileparts(mfilename('fullpath'));
resultFolder = fullfile(projectFolder,'results', ...
    'stage53_formal_repeated_passes');
matPath = fullfile(resultFolder,'stage52_formal_time_latest.mat');

requiredFiles = { ...
    'stage52_checkpoint.mat', ...
    'stage52_complete_pass_summary.csv', ...
    'stage52_dynamic_region_summary.csv', ...
    'stage52_formal_time_latest.mat', ...
    'stage52_frame_records.csv', ...
    'stage52_overall_summary.csv', ...
    'stage52_paired_differences.csv', ...
    'stage52_random_seed_ledger.csv', ...
    'stage52_time_main_minus21_dB.png', ...
    'stage52_time_supplemental_minus20_dB.png', ...
    'stage52_time_window_statistics.csv'};
for fileIndex = 1:numel(requiredFiles)
    path = fullfile(resultFolder,requiredFiles{fileIndex});
    assert(isfile(path) && dir(path).bytes > 0, ...
        'Missing or empty Stage 53 artifact: %s',path);
end

result = load(matPath);
assert(isequal(result.methodNames, ...
    {'Huang-PREC-static-CP','SenLoRa-VP'}), ...
    'The formal comparison no longer contains exactly the two frozen methods.');
assert(isequal(result.options.SnrGridDb,[-21;-20]), ...
    'The formal result does not use the preregistered SNR points.');
assert(all(result.state.snrCompleted), ...
    'At least one formal SNR point is incomplete.');

completedPasses = sum(result.state.passCompleted,2);
assert(all(completedPasses >= 5), ...
    'Each SNR must contain at least five complete passes.');
assert(all(result.summaryTable.completedPasses >= 5), ...
    'Summary table reports fewer than five complete passes.');
assert(all(result.summaryTable.bitErrors >= 300), ...
    'Every method/SNR pair must contain at least 300 payload bit errors.');

assert(result.schedule.frameCount == 508, ...
    'The full continuous pass must contain 508 complete frame slots.');
assert(sum(result.schedule.fullyVisible) == 432 && ...
    sum(result.schedule.fullyBlind) == 74 && ...
    sum(result.schedule.transitionFrame) == 2, ...
    'The frozen visibility partition changed.');
expectedRecordCount = sum(completedPasses) * result.schedule.frameCount;
assert(height(result.frameTable) == expectedRecordCount, ...
    'Frame ledger does not cover every frame of every complete pass.');
assert(isequal(result.frameTable.includedInFormalStatistics, ...
    result.frameTable.fullyVisible & result.frameTable.passCompleted), ...
    'Blind or transition frames entered formal BER/PER statistics.');

confidenceUnits = unique(result.windowTable.confidenceUnit);
assert(numel(confidenceUnits) == 1 && strcmp(confidenceUnits{1}, ...
    'paired_complete_pass_bootstrap_95'), ...
    'Time-window confidence intervals are not paired complete-pass bootstrap intervals.');
assert(all(result.pairedTable.formalPassBootstrapAvailable), ...
    'Formal paired-pass bootstrap statistics are unavailable.');
for snrIndex = 1:numel(result.options.SnrGridDb)
    rows = result.windowTable.snrIndex == snrIndex;
    visibleBits = 704 * 432 * completedPasses(snrIndex);
    assert(sum(result.windowTable.staticBits(rows)) == visibleBits && ...
        sum(result.windowTable.senBits(rows)) == visibleBits, ...
        'Time windows do not partition the fully visible payload bits exactly once.');
end

expectedPayloadSeeds = result.options.PayloadSeedBase + ...
    10000*result.seedTable.passIndex + result.seedTable.frameIndex;
expectedNoiseSeeds = result.options.NoiseSeedBase + ...
    10000*result.seedTable.passIndex + result.seedTable.frameIndex;
assert(isequal(result.seedTable.payloadSeed,expectedPayloadSeeds) && ...
    isequal(result.seedTable.noiseSeed,expectedNoiseSeeds), ...
    'Seed ledger violates the frozen complete-pass seed formula.');
assert(min(result.seedTable.payloadSeed) > 2026130000 && ...
    min(result.seedTable.noiseSeed) > 2026130000, ...
    'Formal seeds overlap the Stage 52 one-pass wiring seed range.');
seedPairs = unique(result.seedTable(:, ...
    {'passIndex','frameIndex','payloadSeed','noiseSeed'}),'rows');
assert(height(seedPairs) == 508*min(completedPasses), ...
    'Common-random-number seeds are not shared across SNR points.');

maxBridgeError = max(result.state.maxPhaseBridgeErrorRad,[], ...
    'all','omitnan');
maxPropagationError = max(result.state.maxPhasePropagationErrorRad,[], ...
    'all','omitnan');
maxTimeError = max(result.state.maxTimeGapErrorSec,[], ...
    'all','omitnan');
assert(maxBridgeError < 1e-10 && maxPropagationError < 1e-10 && ...
    maxTimeError < 1e-12, ...
    'Continuous-time or continuous-phase acceptance limits failed.');
assert(max(result.state.commonBootstrapCfoMaxDifferenceBins,[], ...
    'all','omitnan') == 0 && ...
    max(result.state.commonPayloadStartPhaseMaxDifferenceRad,[], ...
    'all','omitnan') == 0, ...
    'The two receivers did not receive identical bootstrap initialization.');

mainRow = result.pairedTable.snrDb == -21;
supplementalRow = result.pairedTable.snrDb == -20;
assert(result.pairedTable.deltaBerUpper95(mainRow) < 0 && ...
    result.pairedTable.deltaBerLower95(supplementalRow) > 0, ...
    'The preregistered paired BER results are not statistically distinguishable.');

for snrDb = [-21,-20]
    lowStatic = regionValue(result.regionTable,snrDb, ...
        'low_dynamic_lt_0p5_bin_per_frame','Huang-PREC-static-CP','ber');
    lowSen = regionValue(result.regionTable,snrDb, ...
        'low_dynamic_lt_0p5_bin_per_frame','SenLoRa-VP','ber');
    highStatic = regionValue(result.regionTable,snrDb, ...
        'high_dynamic_ge_0p5_bin_per_frame','Huang-PREC-static-CP','ber');
    highSen = regionValue(result.regionTable,snrDb, ...
        'high_dynamic_ge_0p5_bin_per_frame','SenLoRa-VP','ber');
    assert(lowStatic < lowSen && highSen < highStatic, ...
        'Low/high-dynamic BER tradeoff is not exposed at %g dB.',snrDb);
end

fprintf(['Stage 53 formal-result acceptance passed: 5 complete passes/SNR, ' ...
    'paired statistics, continuous phase, fair seeds, and distinct regimes.\n']);
end

function value = regionValue(tableData,snrDb,regionName,methodName,columnName)
rows = tableData.snrDb == snrDb & ...
    strcmp(tableData.dynamicRegion,regionName) & ...
    strcmp(tableData.method,methodName);
assert(nnz(rows) == 1, ...
    'Expected one dynamic-region row for %g dB / %s / %s.', ...
    snrDb,regionName,methodName);
value = tableData.(columnName)(rows);
end
