function test_stage50_continuous_pass_smoke_wiring()
%TEST_STAGE50_CONTINUOUS_PASS_SMOKE_WIRING Full pass, sparse decode wiring.

report = run_stage50_continuous_pass_smoke( ...
    SampleSnrDb=Inf,DecodeStride=64,WindowDurationSec=20, ...
    MaxDecodedFrames=8,ProgressEveryFrames=Inf, ...
    OutputFolderName='stage50_continuous_pass_smoke_wiring_test');
assert(report.generatedFrameCount == report.schedule.frameCount, ...
    'The smoke runner did not generate every continuous frame slot.');
assert(report.decodedFrameCount > 0 && report.decodedFrameCount <= 8, ...
    'The smoke test decoded an unexpected number of frames.');
assert(all(report.schedule.fullyVisible(report.decodedFrameMask)), ...
    'A blind or transition frame entered communication statistics.');
assert(report.maxPhaseBridgeErrorRad < 1e-10, ...
    'The smoke runner broke cross-frame phase continuity.');
assert(report.maxPhasePropagationErrorRad < 1e-10, ...
    'The propagated frame-start phase is not physically equivalent.');
assert(all(report.frameTable.bitCount(report.decodedFrameMask) == 704), ...
    'Decoded frames did not use the common 704 information bits.');
assert(all(isfinite(report.frameTable.staticBitErrors( ...
    report.decodedFrameMask))) && ...
    all(isfinite(report.frameTable.senBitErrors( ...
    report.decodedFrameMask))), ...
    'A decoded method is missing paired error statistics.');
assert(isfile(report.imagePath) && isfile(report.frameCsvPath) && ...
    isfile(report.windowCsvPath), ...
    'The Stage 50 audit artifacts were not written.');

fprintf('Stage 50 continuous-pass smoke wiring test passed.\n');
end
