function test_stage53_formal_wrapper_policy()
%TEST_STAGE53_FORMAL_WRAPPER_POLICY Formal seeds/budget must stay frozen.

report = run_stage53_formal_repeated_passes(DryRun=true);
frozen = report.frozenOptions;
assert(isequal(frozen.SnrGridDb,[-21;-20]), ...
    'Stage 53 did not preserve the Stage 51 SNR freeze.');
assert(frozen.MinCompletePasses == 5 && ...
    frozen.MaxCompletePasses == 20 && ...
    frozen.TargetBitErrorsPerMethod == 300, ...
    'Stage 53 formal pass/error limits changed.');
assert(frozen.PayloadSeedBase == 2026150800 && ...
    frozen.NoiseSeedBase == 2026150900 && ...
    frozen.BootstrapSeed == 2026151000, ...
    'Stage 53 formal seed policy changed.');
assert(frozen.PayloadSeedBase ~= 2026120800 && ...
    frozen.NoiseSeedBase ~= 2026120900, ...
    'Stage 53 formal data overlap the Stage 52 wiring seeds.');
assert(strcmp(frozen.OutputFolderName,'stage53_formal_repeated_passes'), ...
    'Stage 53 formal output folder changed.');
fprintf('Stage 53 frozen formal-wrapper policy test passed.\n');
end
