function test_stage23_four_curve_ber_wiring()
%TEST_STAGE23_FOUR_CURVE_BER_WIRING Check final-method and CI wiring.

[shown,lower,upper] = satelliteFig3BerInterval95([0 5],[1000 1000]);
assert(abs(shown(1)-(1-0.05^(1/1000))) < 1e-14, ...
    'Zero-error BER is not using the exact one-sided 95% upper bound.');
assert(lower(1) == 0 && upper(1) == shown(1), ...
    'Zero-error confidence bounds are inconsistent.');
assert(lower(2) < shown(2) && shown(2) < upper(2), ...
    'Nonzero BER is not enclosed by its Wilson interval.');

folder = 'stage23_four_curve_ber_wiring_test';
report = run_stage23_four_curve_ber_smoke( ...
    SnrGridDb=[-22;-18],FrameCount=1, ...
    SymbolSeedBase=2026090400,NoiseSeedBase=2026090500, ...
    OutputFolderName=folder);
assert(isequal(size(report.errors),[2 2 3]), ...
    'The BER runner does not contain exactly three simulated receiver arms.');
assert(report.commonNoiseMaxDifference < 1e-10, ...
    'The two scenarios did not reuse the same noise realization.');
required = {'berTheoryHamming','berNoComp','berHardPrec','berSenLoRa', ...
    'lower95NoComp','lower95HardPrec','lower95SenLoRa', ...
    'upper95NoComp','upper95HardPrec','upper95SenLoRa', ...
    'senRateReplayTriggeredFrames'};
assert(all(ismember(required,report.table.Properties.VariableNames)), ...
    'The four-curve output table is missing BER or confidence fields.');
assert(isfile(report.imagePath), ...
    'The four-curve BER smoke image was not generated.');
fprintf('Stage 23 four-curve BER wiring test passed.\n');
end
