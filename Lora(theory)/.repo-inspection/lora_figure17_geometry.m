function geometry = lora_figure17_geometry()
%LORA_FIGURE17_GEOMETRY 推导论文 Figure 17 的共享可见窗口。
%   GEOMETRY = LORA_FIGURE17_GEOMETRY() 返回设备 A、设备 B 配置、
%   两个单设备窗口、第一段共享窗口及 high-shift/high-rate 候选时刻。
%   所有模型角度均以弧度保存。

configA = lora_orbit_doppler_config();
configA.orbitHeightM = 550e3;
configA.inclinationRad = deg2rad(15);
configA.carrierFrequencyHz = 868e6;
configA.theoreticalMaxElevationRad = deg2rad(89);
configA.minimumElevationRad = deg2rad(10);
configA.maximumElevationRad = deg2rad(88);
configA.centralVisibilityTimeSec = 0;

configB = configA;
configB.theoreticalMaxElevationRad = deg2rad(89.2);

earthRadiusM = configA.earthRadiusM;
orbitRadiusM = earthRadiusM + configA.orbitHeightM;
omegaSatellite = sqrt(configA.gravityMps2*earthRadiusM^2/ ...
    orbitRadiusM^3);
omegaFixed = omegaSatellite - ...
    configA.earthRotationRadPerSec*cos(configA.inclinationRad);

gammaA = elevation_to_central_angle( ...
    configA.theoreticalMaxElevationRad, configA);
gammaB = elevation_to_central_angle( ...
    configB.theoreticalMaxElevationRad, configB);
groundDeviceDistanceM = 10e3;
inverseCosineArgument = ( ...
    cos(groundDeviceDistanceM/earthRadiusM) - ...
    sin(gammaB)*sin(gammaA))/(cos(gammaB)*cos(gammaA));
inverseCosineArgument = min(1, max(-1, inverseCosineArgument));
deltaTimeABSec = acos(inverseCosineArgument)/omegaFixed;
configB.centralVisibilityTimeSec = ...
    configA.centralVisibilityTimeSec + deltaTimeABSec;

windowA = lora_visibility_window(configA);
windowB = lora_visibility_window(configB);
sharedFirstSec = [ ...
    max(windowA.intervalsSec(1, 1), windowB.intervalsSec(1, 1)), ...
    min(windowA.intervalsSec(1, 2), windowB.intervalsSec(1, 2))];

if sharedFirstSec(1) >= sharedFirstSec(2)
    error("lora:NoSharedVisibility", ...
        "The first visibility intervals do not overlap.");
end

geometry = struct( ...
    "configA", configA, ...
    "configB", configB, ...
    "windowA", windowA, ...
    "windowB", windowB, ...
    "groundDeviceDistanceM", groundDeviceDistanceM, ...
    "deltaTimeABSec", deltaTimeABSec, ...
    "singleDeviceAFirstSec", windowA.intervalsSec(1, :), ...
    "sharedFirstSec", sharedFirstSec, ...
    "highShiftTimeSec", sharedFirstSec(1), ...
    "highRateTimeSec", sharedFirstSec(2), ...
    "paperReportedApproximateHighShiftTimeSec", -254.9, ...
    "paperReportedApproximateHighRateTimeSec", -2.345);
end

function gammaRad = elevation_to_central_angle(elevationRad, config)
radiusRatio = config.earthRadiusM/ ...
    (config.earthRadiusM + config.orbitHeightM);
gammaRad = acos(radiusRatio*cos(elevationRad)) - elevationRad;
end
