function trajectory = lora_orbit_doppler_trajectory(timeSec, config)
%LORA_ORBIT_DOPPLER_TRAJECTORY Evaluate orbit geometry and dynamic Doppler.
%   TRAJECTORY = LORA_ORBIT_DOPPLER_TRAJECTORY(TIMESEC, CONFIG) evaluates
%   the paper circular-orbit model at TIMESEC. The returned structure
%   contains central angle, elevation, slant range, radial velocity,
%   carrier-only Doppler shift, and Doppler rate.
%
%   Doppler is defined as f_D(t) = -f_c*v(t)/c. Doppler rate is evaluated
%   analytically from the derivative of the radial-velocity expression.

arguments
    timeSec double
    config (1, 1) struct
end

if any(~isfinite(timeSec), "all")
    error("lora:InvalidTime", "All trajectory times must be finite.");
end

originalSize = size(timeSec);
timeSec = timeSec(:);
orbitRadiusM = config.earthRadiusM + config.orbitHeightM;

omegaSatellite = sqrt( ...
    config.gravityMps2*config.earthRadiusM^2/orbitRadiusM^3);
omegaFixed = omegaSatellite - ...
    config.earthRotationRadPerSec*cos(config.inclinationRad);

radiusRatio = config.earthRadiusM/orbitRadiusM;
gammaCentralRad = acos( ...
    radiusRatio*cos(config.theoreticalMaxElevationRad)) - ...
    config.theoreticalMaxElevationRad;
phaseRad = omegaFixed*(timeSec - config.centralVisibilityTimeSec);
cosGamma = cos(gammaCentralRad).*cos(phaseRad);
cosGamma = min(1, max(-1, cosGamma));
gammaRad = acos(cosGamma);

slantRangeM = sqrt( ...
    orbitRadiusM^2 + config.earthRadiusM^2 - ...
    2*config.earthRadiusM*orbitRadiusM.*cosGamma);

velocityScale = config.earthRadiusM*orbitRadiusM* ...
    cos(gammaCentralRad)*omegaFixed;
radialVelocityMps = velocityScale*sin(phaseRad)./slantRangeM;

radialAccelerationMps2 = velocityScale*( ...
    omegaFixed*cos(phaseRad)./slantRangeM - ...
    sin(phaseRad).*radialVelocityMps./slantRangeM.^2);

dopplerShiftHz = -config.carrierFrequencyHz* ...
    radialVelocityMps/config.speedOfLightMps;
dopplerRateHzPerSec = -config.carrierFrequencyHz* ...
    radialAccelerationMps2/config.speedOfLightMps;

elevationRad = atan2( ...
    orbitRadiusM*cosGamma - config.earthRadiusM, ...
    orbitRadiusM*sin(gammaRad));

trajectory = struct( ...
    "timeSec", reshape(timeSec, originalSize), ...
    "centralAngleRad", reshape(gammaRad, originalSize), ...
    "elevationRad", reshape(elevationRad, originalSize), ...
    "slantRangeM", reshape(slantRangeM, originalSize), ...
    "radialVelocityMps", reshape(radialVelocityMps, originalSize), ...
    "radialAccelerationMps2", ...
        reshape(radialAccelerationMps2, originalSize), ...
    "dopplerShiftHz", reshape(dopplerShiftHz, originalSize), ...
    "dopplerRateHzPerSec", ...
        reshape(dopplerRateHzPerSec, originalSize));
end
