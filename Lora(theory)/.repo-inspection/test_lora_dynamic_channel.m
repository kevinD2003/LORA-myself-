    tx, symbol, sf, startTimeSec, config, ...
    BandwidthHz=bandwidthHz, SNRdB=Inf, ...
    Mode="carrier_only_approximation");

carrierHz = carrierDiagnostics.dopplerFrequencyHz;
fullHz = fullDiagnostics.dopplerFrequencyHz;
nonzeroVelocity = abs(carrierHz) > 1e-6;
