unwrappedPhaseRad = unwrap(wrappedPhaseRad);
recoveredFrequencyHz = diff(unwrappedPhaseRad)* ...
    bandwidthHz/(2*pi);
expectedIntervalFrequencyHz = 0.5*( ...
    diagnostics.dopplerFrequencyHz(1:end-1) + ...
    diagnostics.dopplerFrequencyHz(2:end));

