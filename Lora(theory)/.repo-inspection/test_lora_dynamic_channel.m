function testInstantaneousFrequencyRangeAndWrap(testCase)
sf = 7;
m = 2^sf;
symbol = uint32(17);
bandwidthHz = 250e3;
sampleIndex = (0:m-1).';
expectedHz = bandwidthHz*( ...
    mod(sampleIndex + double(symbol), m)/m - 0.5);

frequencyHz = lora_symbol_instantaneous_frequency( ...
    symbol, sf, bandwidthHz);

verifySize(testCase, frequencyHz, [m, 1]);
verifyEqual(testCase, frequencyHz, expectedHz, "AbsTol", 1e-12);
verifyGreaterThanOrEqual(testCase, min(frequencyHz), -bandwidthHz/2);
verifyLessThan(testCase, max(frequencyHz), bandwidthHz/2);

wrapIndex = m - double(symbol) + 1;
verifyEqual(testCase, frequencyHz(wrapIndex), -bandwidthHz/2, ...
    "AbsTol", 1e-12);
verifyEqual(testCase, ...
    frequencyHz(wrapIndex) - frequencyHz(wrapIndex-1), ...
    -bandwidthHz + bandwidthHz/m, "AbsTol", 1e-10);
end

function testFullRfFormulaAndTrapezoidalPhase(testCase)
[tx, symbol, sf, startTimeSec, config, bandwidthHz] = ...
    deterministic_fixture();
m = 2^sf;

[rx, diagnostics] = apply_lora_dynamic_doppler( ...
    tx, symbol, sf, startTimeSec, config, ...
    BandwidthHz=bandwidthHz, SNRdB=Inf, Mode="full_rf");

sampleTimeSec = startTimeSec + (0:m-1).'/bandwidthHz;
orbit = lora_orbit_doppler_trajectory(sampleTimeSec, config);
sampleIndex = (0:m-1).';
basebandHz = bandwidthHz*( ...
    mod(sampleIndex + double(symbol), m)/m - 0.5);
expectedRfHz = config.carrierFrequencyHz + basebandHz;
expectedDopplerHz = -expectedRfHz.* ...
    orbit.radialVelocityMps/config.speedOfLightMps;
expectedPhaseRad = [0; cumsum( ...
    pi/bandwidthHz*( ...
    expectedDopplerHz(1:end-1) + expectedDopplerHz(2:end)))];

verifyEqual(testCase, diagnostics.sampleTimeSec, ...
    sampleTimeSec, "AbsTol", 1e-14);
verifyEqual(testCase, diagnostics.basebandFrequencyHz, ...
    basebandHz, "AbsTol", 1e-12);
verifyEqual(testCase, diagnostics.instantaneousRfHz, ...
    expectedRfHz, "AbsTol", 1e-9);
verifyEqual(testCase, diagnostics.dopplerFrequencyHz, ...
    expectedDopplerHz, "AbsTol", 1e-9);
verifyEqual(testCase, diagnostics.dopplerPhaseRad, ...
    expectedPhaseRad, "AbsTol", 1e-12);
verifyEqual(testCase, diagnostics.integrationRule, "trapezoidal");
verifyEqual(testCase, diagnostics.mode, "full_rf");
verifyEqual(testCase, diagnostics.noiseVariance, 0);
verifyEqual(testCase, rx, tx.*exp(1i*expectedPhaseRad), ...
    "AbsTol", 1e-12);
end

function testCarrierOnlyApproximationAndError(testCase)
[tx, symbol, sf, startTimeSec, config, bandwidthHz] = ...
    deterministic_fixture();

[~, fullDiagnostics] = apply_lora_dynamic_doppler( ...
    tx, symbol, sf, startTimeSec, config, ...
    BandwidthHz=bandwidthHz, SNRdB=Inf, Mode="full_rf");
[~, carrierDiagnostics] = apply_lora_dynamic_doppler( ...
    tx, symbol, sf, startTimeSec, config, ...
    BandwidthHz=bandwidthHz, SNRdB=Inf, ...
    Mode="carrier_only_approximation");

expectedCarrierHz = -config.carrierFrequencyHz.* ...
    carrierDiagnostics.radialVelocityMps/config.speedOfLightMps;
expectedDifferenceHz = -fullDiagnostics.basebandFrequencyHz.* ...
    fullDiagnostics.radialVelocityMps/config.speedOfLightMps;
actualDifferenceHz = fullDiagnostics.dopplerFrequencyHz - ...
    carrierDiagnostics.dopplerFrequencyHz;

verifyEqual(testCase, carrierDiagnostics.instantaneousRfHz, ...
    repmat(config.carrierFrequencyHz, 2^sf, 1), "AbsTol", 1e-9);
verifyEqual(testCase, carrierDiagnostics.dopplerFrequencyHz, ...
    expectedCarrierHz, "AbsTol", 1e-9);
verifyEqual(testCase, actualDifferenceHz, ...
    expectedDifferenceHz, "AbsTol", 1e-9);
verifyGreaterThan(testCase, max(abs(actualDifferenceHz)), 0);
verifyLessThan(testCase, max(abs(actualDifferenceHz)), 5);
verifyEqual(testCase, carrierDiagnostics.mode, ...
    "carrier_only_approximation");
end

