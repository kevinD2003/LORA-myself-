function testComplexAwgnMatchesSnrConvention(testCase)
config = lora_orbit_doppler_config();
window = lora_visibility_window(config);
sf = 12;
symbol = uint32(731);
bandwidthHz = 250e3;
snrDb = 10;
tx = lora_css_modulate(symbol, sf);
rng(314159, "twister");

[rx, diagnostics] = apply_lora_dynamic_doppler( ...
    tx, symbol, sf, window.intervalsSec(1, 1), config, ...
    BandwidthHz=bandwidthHz, SNRdB=snrDb);

noiselessRx = tx.*diagnostics.phaseRotation;
noise = rx - noiselessRx;
expectedVariance = 10^(-snrDb/10);

verifyEqual(testCase, diagnostics.noiseVariance, expectedVariance, ...
    "AbsTol", 1e-15);
verifyLessThan(testCase, ...
    abs(mean(abs(noise).^2)/expectedVariance - 1), 0.05);
verifyLessThan(testCase, ...
    abs(var(real(noise), 1)/(expectedVariance/2) - 1), 0.08);
verifyLessThan(testCase, ...
    abs(var(imag(noise), 1)/(expectedVariance/2) - 1), 0.08);
verifyLessThan(testCase, ...
    abs(mean(real(noise))), 0.05*sqrt(expectedVariance));
verifyLessThan(testCase, ...
    abs(mean(imag(noise))), 0.05*sqrt(expectedVariance));
end

function testDynamicWrapperUsesOriginalUncompensatedDetector(testCase)
[tx, symbol, sf, startTimeSec, config, bandwidthHz] = ...
    deterministic_fixture();
[rx, diagnostics] = apply_lora_dynamic_doppler( ...
    tx, symbol, sf, startTimeSec, config, ...
    BandwidthHz=bandwidthHz, SNRdB=Inf);

wrapperDetected = lora_css_demodulate_dynamic_channel(rx, sf);
originalDetected = lora_css_demodulate(rx, sf);

m = 2^sf;
sampleIndex = (0:m-1).';
baseUpChirp = exp(1i*2*pi*( ...
    sampleIndex.^2/(2*m) - sampleIndex/2));
spectrum = fft(rx.*conj(baseUpChirp), m, 1);
[~, peakIndex] = max(abs(spectrum).^2, [], 1);
manualDetected = uint32(peakIndex - 1);

verifyEqual(testCase, wrapperDetected, originalDetected);
verifyEqual(testCase, wrapperDetected, manualDetected);
verifyGreaterThan(testCase, norm(rx - tx), 0.1);
verifyGreaterThan(testCase, ...
    max(abs(diagnostics.dopplerPhaseRad)), 0.1);
end

