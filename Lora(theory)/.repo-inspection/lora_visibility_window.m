function [window, isVisible] = lora_visibility_window(config, timeSec)
%LORA_VISIBILITY_WINDOW Compute the paper single-device visibility window.
%   WINDOW = LORA_VISIBILITY_WINDOW(CONFIG) returns the two visibility
%   intervals implied by the minimum, maximum, and theoretical maximum
%   elevation angles.
%
%   [WINDOW, ISVISIBLE] = LORA_VISIBILITY_WINDOW(CONFIG, TIMESEC) also
%   returns a logical array indicating which requested times are visible.
%
%   For maximumElevation < theoreticalMaxElevation, the result is
%       [t_cv-deltaOut, t_cv-deltaIn] U
%       [t_cv+deltaIn,  t_cv+deltaOut].

arguments
    config (1, 1) struct
    timeSec double = []
end

validate_config(config);

orbitRadiusM = config.earthRadiusM + config.orbitHeightM;
omegaSatellite = sqrt( ...
    config.gravityMps2*config.earthRadiusM^2/orbitRadiusM^3);
omegaFixed = omegaSatellite - ...
    config.earthRotationRadPerSec*cos(config.inclinationRad);

gammaCentral = elevation_to_central_angle( ...
    config.theoreticalMaxElevationRad, config);
gammaMinimum = elevation_to_central_angle( ...
    config.minimumElevationRad, config);
gammaMaximum = elevation_to_central_angle( ...
    config.maximumElevationRad, config);

deltaOutSec = boundary_time(gammaMinimum, gammaCentral, omegaFixed);
deltaInSec = boundary_time(gammaMaximum, gammaCentral, omegaFixed);
centralTimeSec = config.centralVisibilityTimeSec;

intervalsSec = [ ...
    centralTimeSec - deltaOutSec, centralTimeSec - deltaInSec; ...
    centralTimeSec + deltaInSec, centralTimeSec + deltaOutSec];

window = struct( ...
    "omegaSatelliteRadPerSec", omegaSatellite, ...
    "omegaFixedRadPerSec", omegaFixed, ...
    "gammaCentralRad", gammaCentral, ...
    "gammaMinimumRad", gammaMinimum, ...
    "gammaMaximumRad", gammaMaximum, ...
    "deltaTimeOutSec", deltaOutSec, ...
    "deltaTimeInSec", deltaInSec, ...
    "intervalsSec", intervalsSec, ...
    "blindIntervalSec", [ ...
        centralTimeSec - deltaInSec, centralTimeSec + deltaInSec], ...
    "totalVisibleDurationSec", 2*(deltaOutSec - deltaInSec));

offsetSec = abs(timeSec - centralTimeSec);
isVisible = (offsetSec >= deltaInSec) & (offsetSec <= deltaOutSec);
end

function validate_config(config)
requiredFields = [ ...
    "gravityMps2", ...
    "earthRadiusM", ...
    "earthRotationRadPerSec", ...
    "orbitHeightM", ...
    "inclinationRad", ...
    "theoreticalMaxElevationRad", ...
    "minimumElevationRad", ...
    "maximumElevationRad", ...
    "centralVisibilityTimeSec"];

for fieldName = requiredFields
    if ~isfield(config, fieldName)
        error("lora:MissingConfigurationField", ...
            "Configuration field '%s' is required.", fieldName);
    end
end

if config.minimumElevationRad < 0 || ...
        config.minimumElevationRad >= config.maximumElevationRad || ...
        config.maximumElevationRad >= ...
        config.theoreticalMaxElevationRad || ...
        config.theoreticalMaxElevationRad >= pi/2
    error("lora:InvalidElevationLimits", ...
        ["Elevation limits must satisfy 0 <= theta_min < theta_max " ...
        "< theta_c < pi/2."]);
end
end

function gammaRad = elevation_to_central_angle(elevationRad, config)
radiusRatio = config.earthRadiusM / ...
    (config.earthRadiusM + config.orbitHeightM);
gammaRad = acos(radiusRatio*cos(elevationRad)) - elevationRad;
end

function deltaTimeSec = boundary_time(gammaRad, gammaCentral, omegaFixed)
inverseCosineArgument = cos(gammaRad)/cos(gammaCentral);
inverseCosineArgument = min(1, max(-1, inverseCosineArgument));
deltaTimeSec = abs(acos(inverseCosineArgument)/omegaFixed);
end
