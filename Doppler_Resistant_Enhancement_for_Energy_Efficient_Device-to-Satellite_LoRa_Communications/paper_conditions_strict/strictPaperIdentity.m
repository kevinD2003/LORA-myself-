function identity = strictPaperIdentity(config,runnerName)
%STRICTPAPERIDENTITY Hash every calculation dependency; never migrate caches.
folder = strictPaperSetup();
parent = fileparts(folder);
names = {'strictPaperConfig.m','strictPaperSetup.m', ...
    'strictPaperIdentity.m','strictPaperGenerateIQ.m', ...
    'strictPaperScorePayload.m','strictPaperDecodePayload.m', ...
    'strictPaperCentroids.m','strictPaperRawBatch.m', ...
    'strictPaperNativeCentroids.cpp','compile_strict_native.m', ...
    ['strictPaperNativeCentroids.' mexext],'native_build.json',runnerName};
paths = cellfun(@(name)fullfile(folder,name),names,'UniformOutput',false);
helpers = {'drePaperOrbit.m','dreModulateSymbols.m', ...
    'dreEstimatePaperCentroids10.m','dreDecodeLinearRegressionBatch.m', ...
    'dreGenerateFullPhyPayload.m','dreDecodeFullPhyPayload.m', ...
    'dreFullPhyCodebook.m','dreCrc16Ccitt.m','dreWhiteningSequence.m', ...
    'dreGrayEncode.m','dreGrayDecode.m','dreConfigurationSignature.m', ...
    'dreCircularSymbolDistance.m'};
paths = [paths cellfun(@(name)fullfile(parent,'src',name), ...
    helpers,'UniformOutput',false)];
paths = [paths {fullfile(parent,'config','drePaperConfig.m'), ...
    fullfile(parent,'config','dreFullPhyConfig.m'), ...
    fullfile(folder,'vendor','pyfftw','libfftw3-3.dll')}];
hashes = strings(numel(paths),2);
for index=1:numel(paths)
    handle=fopen(paths{index},'rb');
    if handle<0,error('StrictPaper:MissingSource','Missing source: %s',paths{index});end
    closer=onCleanup(@()fclose(handle));bytes=fread(handle,Inf,'*uint8');
    digest=java.security.MessageDigest.getInstance('SHA-256');digest.update(bytes);
    raw=typecast(digest.digest(),'uint8');
    hashes(index,:)=[string(paths{index}), ...
        string(lower(reshape(dec2hex(raw,2).',1,[])))];
    clear closer
end
build=jsondecode(fileread(fullfile(folder,'native_build.json')));
sourceIndex=hashes(:,1)==string(fullfile(folder,'strictPaperNativeCentroids.cpp'));
binaryIndex=hashes(:,1)==string(fullfile(folder,['strictPaperNativeCentroids.' mexext]));
if ~strcmp(build.sourceSha256,hashes(sourceIndex,2)) || ...
        ~strcmp(build.binarySha256,hashes(binaryIndex,2))
    error('StrictPaper:StaleNativeBuild','Rebuild native kernel before simulation.');
end
identity=struct('config',config,'sourceHashes',hashes);
end
