function detail = summarizePacketLossV6(detected,tx,cr,c)
%SUMMARIZEPACKETLOSSV6 Post-receiver Gold diagnostics; no receiver feedback.
% CRC/header outcomes come only from the unchanged v6 decoder.
rx=referencePhyV6Decode(detected,cr,c);
score=referencePhyV6Score(detected,tx,cr,c);
layout=tx.layout;packets=size(detected,2);
wordErrors=zeros(layout.totalNibbles,packets);
decoded=zeros(layout.totalNibbles,packets,'uint8');
for block=1:numel(layout.rows)
    wi=layout.wordStarts(block)+(0:layout.actualCounts(block)-1);
    difference=bitxor(rx.receivedCodedWords(wi,:),tx.codedWords(wi,:));
    for bit=1:layout.widths(block)
        wordErrors(wi,:)=wordErrors(wi,:)+double(bitget(difference,bit));
    end
    decoded(wi,:)=referencePhyV6Hamming(rx.receivedCodedWords(wi,:), ...
        layout.rates(block),'decode');
end
histogram=arrayfun(@(n)sum(wordErrors(:)==n),(0:8).');
assert(sum(histogram)==layout.totalNibbles*packets);
assert(sum((0:8).'.*histogram)==score.codedErrorsAll);
wrongNibble=decoded~=tx.nibbles;
offset=5*double(c.explicitHeader);
header=1:offset;payload=offset+(1:2*c.payloadBytes);
crc=offset+2*c.payloadBytes+(1:4*double(c.hasCrc));
rejected=~rx.crcPass;
headerRejected=~rx.headerValid;
crcRejected=rx.headerValid & rejected;
wrongPayload=any(rx.payloadBytes~=tx.payloadBytes,1) | ...
    rx.decodedPayloadLengths~=c.payloadBytes;
symbolErrors=detected~=tx.logicalBins;
stats=struct('packetCount',packets,'acceptedPackets',sum(rx.crcPass), ...
    'rejectedPackets',sum(rejected), ...
    'headerRejectedPackets',sum(headerRejected), ...
    'crcRejectedValidHeaderPackets',sum(crcRejected), ...
    'rejectedWithMultiBitWordPackets',sum(rejected & any(wordErrors>=2,1)), ...
    'rejectedWithSingleBitWordsOnlyPackets',sum(rejected & all(wordErrors<=1,1)), ...
    'rejectedWithDecodedHeaderErrorPackets',sum(rejected & any(wrongNibble(header,:),1)), ...
    'rejectedWithDecodedPayloadErrorPackets',sum(rejected & any(wrongNibble(payload,:),1)), ...
    'rejectedWithDecodedCrcErrorPackets',sum(rejected & any(wrongNibble(crc,:),1)), ...
    'rejectedWithoutDecodedNibbleErrorPackets',sum(rejected & ~any(wrongNibble,1)), ...
    'acceptedWithWrongPayloadPackets',sum(rx.crcPass & wrongPayload), ...
    'acceptedWithCodedErrorPackets',sum(rx.crcPass & score.perPacketCodedErrorsAll>0), ...
    'packetsWithSymbolErrors',sum(any(symbolErrors,1)), ...
    'symbolErrors',sum(symbolErrors(:)), ...
    'decodedWrongNibbles',sum(wrongNibble(:)), ...
    'payloadWrongDecodedNibbles',sum(wrongNibble(payload,:),'all'));
assert(stats.acceptedPackets+stats.headerRejectedPackets+ ...
    stats.crcRejectedValidHeaderPackets==packets);
assert(isequal(rx.crcPass,score.crcPass));
detail=struct('stats',stats,'wordErrorHistogram',histogram,'score',score, ...
    'crcPass',rx.crcPass,'headerValid',rx.headerValid, ...
    'receiverUsesPayloadTruth',false,'goldUsedOnlyForPosthocDiagnostics',true);
end
