function metrics = referenceSoftScore(rx,hard,tx)
%REFERENCESOFTSCORE Primary common LR-hard coded-bit stream, soft CRC mask.
% LLR-sign BER is separate diagnostic; it never replaces the primary BER.
layout=tx.layout;packets=size(tx.codedWords,2);pass=rx.crcPass;
if ~islogical(pass) || ~isequal(size(pass),[1 packets]) || ...
        ~isequal(size(rx.headerValid),[1 packets]) || ...
        ~isequal(size(rx.receivedCodedWords),size(tx.codedWords)) || ...
        ~isequal(size(hard.perPacketCodedErrorsAll),[1 packets]) || ...
        ~isequal(size(hard.perPacketCodedBitsAll),[1 packets]) || ...
        any(hard.perPacketCodedBitsAll~=layout.codedBitsPerPacket)
    error('ReferenceSoft:Score','Inconsistent scoring shapes.');
end
llrErrors=zeros(1,packets);
for block=1:numel(layout.rows)
    wi=layout.wordStarts(block)+(0:layout.actualCounts(block)-1);
    difference=bitxor(rx.receivedCodedWords(wi,:),tx.codedWords(wi,:));
    for bit=1:layout.widths(block),llrErrors=llrErrors+sum(double(bitget(difference,bit)),1);end
end
errors=hard.perPacketCodedErrorsAll;bits=hard.perPacketCodedBitsAll;
wrongPayload=any(rx.payloadBytes~=tx.payloadBytes,1) | rx.decodedPayloadLengths~=size(tx.payloadBytes,1);
metrics=struct('codedErrorsAccepted',sum(errors(pass)),'codedBitsAccepted',sum(bits(pass)), ...
    'codedErrorsAll',sum(errors),'codedBitsAll',sum(bits), ...
    'packetLosses',sum(~pass),'headerLosses',sum(~rx.headerValid), ...
    'llrSignErrorsAccepted',sum(llrErrors(pass)),'llrSignErrorsAll',sum(llrErrors), ...
    'acceptedWrongPayload',sum(pass & wrongPayload),'crcPass',pass, ...
    'perPacketCodedErrorsAccepted',errors.*pass,'perPacketCodedBitsAccepted',bits.*pass, ...
    'perPacketCodedErrorsAll',errors,'perPacketCodedBitsAll',bits, ...
    'perPacketPacketLosses',double(~pass),'perPacketHeaderLosses',double(~rx.headerValid), ...
    'perPacketLlrSignErrorsAccepted',llrErrors.*pass,'perPacketLlrSignErrorsAll',llrErrors, ...
    'perPacketAcceptedWrongPayload',double(pass & wrongPayload));
end
