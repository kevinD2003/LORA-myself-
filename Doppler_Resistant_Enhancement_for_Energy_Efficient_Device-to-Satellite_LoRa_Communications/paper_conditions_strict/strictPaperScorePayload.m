function metrics = strictPaperScorePayload(detectedBins,transmitted,cr,config)
%STRICTPAPERSCOREPAYLOAD Score only after hard decoding and independent CRC.
% Transmitted data enters error accounting, never the LR or CRC decision.
decoded=strictPaperDecodePayload(detectedBins,cr,config);
pass=decoded.crcPass;
codedErrors=reshape(sum(sum(sum(xor(decoded.receivedCodedBits, ...
    transmitted.codedBits),1),2),3),1,[]);
codedBitsPerPacket=config.sf*(4+cr)*config.hammingBlockCount;
payloadErrors=sum(xor(decoded.payloadBits,transmitted.payloadBits),1);
metrics=struct('codedErrorsAccepted',sum(codedErrors(pass)), ...
    'codedBitsAccepted',sum(pass)*codedBitsPerPacket, ...
    'codedErrorsAll',sum(codedErrors), ...
    'codedBitsAll',numel(pass)*codedBitsPerPacket, ...
    'payloadErrorsAccepted',sum(payloadErrors(pass)), ...
    'payloadBitsAccepted',sum(pass)*config.payloadBitCount, ...
    'packetLosses',sum(~pass),'packetCount',numel(pass), ...
    'acceptedPackets',sum(pass),'crcPass',pass, ...
    'decodedPayloadBits',decoded.payloadBits, ...
    'perPacketCodedErrorsAccepted',codedErrors.*pass, ...
    'perPacketCodedBitsAccepted',double(pass)*codedBitsPerPacket, ...
    'perPacketCodedErrorsAll',codedErrors, ...
    'perPacketCodedBitsAll',codedBitsPerPacket*ones(size(pass)), ...
    'perPacketPayloadErrorsAccepted',payloadErrors.*pass, ...
    'perPacketPayloadBitsAccepted',double(pass)*config.payloadBitCount, ...
    'perPacketPacketLosses',double(~pass));
end
