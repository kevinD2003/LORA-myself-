function metrics = referencePhyV6Score(detected,tx,cr,c)
%REFERENCEPHYV6SCORE Gold data only scores errors; CRC is decided independently.
rx=referencePhyV6Decode(detected,cr,c);layout=tx.layout;
packets=size(detected,2);errors=zeros(1,packets);
for block=1:numel(layout.rows)
    wi=layout.wordStarts(block)+(0:layout.actualCounts(block)-1);
    differences=bitxor(rx.receivedCodedWords(wi,:),tx.codedWords(wi,:));
    for bit=1:layout.widths(block),errors=errors+sum(double(bitget(differences,bit)),1);end
end
pass=rx.crcPass;
metrics=struct('codedErrorsAccepted',sum(errors(pass)), ...
    'codedBitsAccepted',sum(pass)*layout.codedBitsPerPacket, ...
    'codedErrorsAll',sum(errors),'codedBitsAll',packets*layout.codedBitsPerPacket, ...
    'packetLosses',sum(~pass),'headerLosses',sum(~rx.headerValid), ...
    'packetCount',packets,'crcPass',pass,'decodedPayloadBytes',rx.payloadBytes, ...
    'usesPayloadTruth',rx.usesPayloadTruth, ...
    'perPacketCodedErrorsAccepted',errors.*pass, ...
    'perPacketCodedBitsAccepted',double(pass)*layout.codedBitsPerPacket, ...
    'perPacketCodedErrorsAll',errors, ...
    'perPacketCodedBitsAll',layout.codedBitsPerPacket*ones(1,packets), ...
    'perPacketPacketLosses',double(~pass),'perPacketHeaderLosses',double(~rx.headerValid));
end
