function localVerifyNumericTable(expected,actual)
assert(isequal(expected.Properties.VariableNames,actual.Properties.VariableNames));
for column = 1:width(expected)
    a = expected{:,column};
    b = actual{:,column};
    if isnumeric(a) || islogical(a)
        assert(isequal(size(a),size(b)) && all(abs(double(a)-double(b))<1e-11,'all'));
    else
        assert(isequal(string(a),string(b)));
    end
end
end

function value = localSha256(path)
