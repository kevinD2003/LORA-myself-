function orbit = drePaperOrbit(timeSec,config)
%DREPAPERORBIT Circular overhead pass used by the WSA 2025 paper.

if any(~isfinite(timeSec),'all')
    error('DRE:InvalidTime','Orbit time must be finite.');
end
shape = size(timeSec);
t = double(timeSec(:));
re = config.earthRadiusM;
rs = re+config.orbitHeightM;
omega = sqrt(config.gravityMps2*re^2/rs^3);
theta = omega*t;
rangeM = sqrt(rs^2+re^2-2*rs*re*cos(theta));
radialVelocityMps = re*rs*omega*sin(theta)./rangeM;
radialAccelerationMps2 = re*rs*omega^2*cos(theta)./rangeM- ...
    re*rs*omega*sin(theta).*radialVelocityMps./rangeM.^2;
dopplerHz = config.carrierFrequencyHz*radialVelocityMps/ ...
    config.speedOfLightMps;
dopplerRateHzPerSec = config.carrierFrequencyHz*radialAccelerationMps2/ ...
    config.speedOfLightMps;
horizonAngleRad = acos(re/rs);
orbit = struct('timeSec',reshape(t,shape), ...
    'rangeM',reshape(rangeM,shape), ...
    'radialVelocityMps',reshape(radialVelocityMps,shape), ...
    'radialAccelerationMps2',reshape(radialAccelerationMps2,shape), ...
    'dopplerHz',reshape(dopplerHz,shape), ...
    'dopplerRateHzPerSec',reshape(dopplerRateHzPerSec,shape), ...
    'angularRateRadPerSec',omega, ...
    'horizonTimeSec',horizonAngleRad/omega);
end

