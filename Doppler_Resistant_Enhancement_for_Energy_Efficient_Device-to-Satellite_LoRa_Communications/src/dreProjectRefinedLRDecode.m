function result = dreProjectRefinedLRDecode(observation,projectConfig, ...
        historyLength,fitMethod,rawBins)
%DREPROJECTREFINEDLRDECODE Ten-point no-midamble causal receiver variant.

c = projectConfig.v4;
rows = [observation.layout.bootstrapRows;observation.layout.dataRows];
if nargin < 5
    centroidConfig = struct('samplesPerSymbol',c.samplesPerSymbol, ...
        'zeroPaddingFactor',4);
    estimate = dreEstimatePaperCentroids10( ...
        observation.rxPhysical(rows,:),centroidConfig);
    rawBins = estimate.rawBins;
end
decoderConfig = struct('samplesPerSymbol',c.samplesPerSymbol, ...
    'preambleSymbolCount',c.bootstrapPilotCount);
decoded = dreDecodeRefinedAdaptiveLR(rawBins, ...
    zeros(c.bootstrapPilotCount,1),decoderConfig,rows-1, ...
    historyLength,fitMethod);
bits = dreDecodeProjectHardBits(decoded.detectedSymbols,c);
result = struct('methodName',sprintf('Dietl refined LR, %s, H=%d', ...
    char(fitMethod),historyLength), ...
    'methodId',sprintf('dietl-refined-%s-h%d', ...
    char(fitMethod),historyLength), ...
    'detectedPhysicalBins',decoded.detectedSymbols, ...
    'hardDecodedDataBits',bits,'linearRegression',decoded, ...
    'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'knownMidamblesUsed',0,'centroidSampleCount',10);
end
