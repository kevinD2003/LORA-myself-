function condition = dreRunFullPhyCondition(cr,snrDb,config,calibration,overpasses,maximumPackets)
%DRERUNFULLPHYCONDITION Vectorized overpass ensemble for one CR/SNR cell.

lengthCode = 4+cr;
dataSymbolCount = config.hammingBlockCount*lengthCode;
packetSymbolCount = config.preambleSymbolCount+dataSymbolCount+ ...
    config.paddingSymbolCount;
orbit = drePaperOrbit(0,config);
packetDuration = packetSymbolCount*config.symbolDurationSec;
starts = (-orbit.horizonTimeSec:packetDuration: ...
    (orbit.horizonTimeSec-packetDuration)).';
if isfinite(maximumPackets) && numel(starts)>maximumPackets
    selection = unique(round(linspace(1,numel(starts),maximumPackets)));
    starts = starts(selection);
end
packetCount = numel(starts);
methodNames = {'adaptive','fixed'};
codedErrors = zeros(1,2);
codedDenominators = zeros(1,2);
codedErrorsAll = zeros(1,2);
codedDenominatorsAll = zeros(1,2);
lostPackets = zeros(1,2);
trajectoryBer = nan(packetCount,2);
trajectoryPlr = nan(packetCount,2);
stream = RandStream('mt19937ar','Seed',config.randomSeed+ ...
    cr*1000000+round((snrDb+100)*1000)+overpasses);
calibrationErrors = calibration.errorsBins;
for packetIndex = 1:packetCount
    transmitted = dreGenerateFullPhyPayload(overpasses,cr,config,stream);
    trueSymbols = [zeros(config.preambleSymbolCount,overpasses); ...
        transmitted.logicalBins;zeros(config.paddingSymbolCount,overpasses)];
    deterministicError = dreFullPhyNoiselessTrajectory( ...
        starts(packetIndex),packetSymbolCount,config);
    sampleIndex = randi(stream,numel(calibrationErrors), ...
        packetSymbolCount,overpasses);
    measurementError = reshape(calibrationErrors(sampleIndex), ...
        packetSymbolCount,overpasses);
    raw = mod(trueSymbols+deterministicError+measurementError, ...
        config.samplesPerSymbol);
    for methodIndex = 1:2
        receiver = dreDecodeLinearRegressionBatch(raw, ...
            config.preambleSymbolCount,config.samplesPerSymbol, ...
            methodNames{methodIndex});
        detectedData = receiver.detectedSymbols(1:dataSymbolCount,:);
        decoded = dreDecodeFullPhyPayload(detectedData,transmitted,cr,config);
        codedErrors(methodIndex) = codedErrors(methodIndex)+ ...
            decoded.acceptedCodedErrors;
        codedDenominators(methodIndex) = codedDenominators(methodIndex)+ ...
            decoded.acceptedCodedBitCount;
        lostPackets(methodIndex) = lostPackets(methodIndex)+decoded.packetLossCount;
        codedErrorsAll(methodIndex) = codedErrorsAll(methodIndex)+ ...
            decoded.totalCodedErrors;
        codedDenominatorsAll(methodIndex) = codedDenominatorsAll(methodIndex)+ ...
            decoded.totalCodedBitCount;
        trajectoryBer(packetIndex,methodIndex) = decoded.totalCodedErrors/ ...
            decoded.totalCodedBitCount;
        trajectoryPlr(packetIndex,methodIndex) = decoded.packetLossCount/overpasses;
    end
    if mod(packetIndex,25)==0 || packetIndex==packetCount
        fprintf('Full PHY CR%d SNR %+g: %d/%d packets, %d overpasses\n', ...
            cr,snrDb,packetIndex,packetCount,overpasses);
    end
end
centerTime = starts+packetDuration/2;
doppler = drePaperOrbit(centerTime,config);
condition = struct('cr',cr,'snrDb',snrDb,'overpasses',overpasses, ...
    'packetCount',packetCount,'packetSymbolCount',packetSymbolCount, ...
    'packetStartTimeSec',starts, ...
    'codedBer',codedErrorsAll./max(codedDenominatorsAll,1), ...
    'crcFilteredCodedBer',codedErrors./max(codedDenominators,1), ...
    'plr',lostPackets/(packetCount*overpasses), ...
    'codedErrors',codedErrors,'codedDenominators',codedDenominators, ...
    'codedErrorsAll',codedErrorsAll, ...
    'codedDenominatorsAll',codedDenominatorsAll, ...
    'lostPackets',lostPackets,'trajectoryBer',trajectoryBer, ...
    'trajectoryPlr',trajectoryPlr,'dopplerHz',doppler.dopplerHz, ...
    'calibrationRmsBins',calibration.rmsBins);
end
