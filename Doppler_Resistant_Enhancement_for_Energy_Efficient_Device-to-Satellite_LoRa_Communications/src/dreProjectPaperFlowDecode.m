function result = dreProjectPaperFlowDecode(observation,projectConfig,mode,rawBins)
%DREPROJECTPAPERFLOWDECODE Paper LR on all V4 physical symbols.
%   Known midambles are existing symbols in the shared received frame.

c = projectConfig.v4;
if nargin < 4
    estimatorConfig = struct('samplesPerSymbol',c.samplesPerSymbol, ...
        'zeroPaddingFactor',projectConfig.zeroPaddingFactor, ...
        'centroidSampleCount',projectConfig.centroidSampleCount);
    estimate = dreEstimateCentroids(observation.rxPhysical,estimatorConfig);
    rawBins = estimate.rawBins;
end
decoded = dreDecodePaperFlowOnLayout(rawBins,observation.layout,c,mode);
hardBits = dreDecodeProjectHardBits(decoded.detectedSymbols,c);
result = struct('methodName',['Dietl ' char(lower(string(mode))) ...
    ' LR with known V4 midambles'], ...
    'methodId',['dietl-' char(lower(string(mode))) '-lr-full-symbol-v2'], ...
    'detectedPhysicalBins',decoded.detectedSymbols, ...
    'hardDecodedDataBits',hardBits,'linearRegression',decoded, ...
    'knownMidambleCount',decoded.knownMidambleCount, ...
    'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'usesPayloadFeedback',strcmpi(mode,'adaptive'), ...
    'fftCount',observation.layout.physicalSymbolCount);
end
