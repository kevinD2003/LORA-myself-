        function codeAidedReplayUsesNoMidamblesOrTruth(testCase)
            dreSetupPaths(true);
            p=dreProjectConfig();p.v4=sf12NoLdroSf11FlowConfig();
            for caseIndex=1:2
                key=struct('planVersion','dre-code-aided-test', ...
                    'phase','unit-test','track','B-method-aligned', ...
                    'channel','AWGN','comparisonMode', ...
                    'case-anchor-controlled','snrDb',Inf, ...
                    'replicateId',caseIndex,'packetId',caseIndex, ...
                    'eventType','paired-frame','eventIndex',caseIndex, ...
                    'sampleIndex',0);
                ledger=v4EventRandomLedger(p.randomSeedRoot,key);
                frame=v4GenerateBCaseAnchorFrame(p.v4, ...
                    p.caseStartTimeSec(caseIndex),Inf,ledger);
                receiver=dreProjectCodeAidedReplayDecode( ...
                    frame.observation,p);
                testCase.verifyFalse(receiver.usesPayloadTruth);
                testCase.verifyFalse(receiver.usesOrbitTruth);
                testCase.verifyFalse(receiver.usesSnrInput);
                testCase.verifyEqual(receiver.knownMidamblesUsed,0);
                testCase.verifyEqual(receiver.detectedPhysicalBins, ...
                    frame.truth.payloadPhysicalBins);
                altered=frame.observation;
                altered.rxPhysical(altered.layout.midambleRows,:)=0;
                repeated=dreProjectCodeAidedReplayDecode(altered,p);
                testCase.verifyEqual(repeated.detectedPhysicalBins, ...
                    receiver.detectedPhysicalBins);
                snrAltered=frame.observation;
                snrAltered.noiseVariance=1e12;
                repeatedNoise=dreProjectCodeAidedReplayDecode(snrAltered,p);
                testCase.verifyEqual(repeatedNoise.detectedPhysicalBins, ...
                    receiver.detectedPhysicalBins);
                testCase.verifyEqual(repeatedNoise.hardDecodedDataBits, ...
                    receiver.hardDecodedDataBits);
                testCase.verifyEqual(repeatedNoise.softDecodedDataBits, ...
                    receiver.softDecodedDataBits);
            end
        end
