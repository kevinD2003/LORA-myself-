        function refinedEightSymbolLeastSquaresMatchesPaper(testCase)
            config = struct('samplesPerSymbol',128,'preambleSymbolCount',8);
            known = zeros(8,1);
            bins = [known;(3:3:36).'];
            positions = [0:7 9:20].';
            raw = mod(bins+5.2+0.12*positions,128);
            paper = dreDecodeLinearRegression(raw,known,config, ...
                'adaptive',positions);
            refined = dreDecodeRefinedAdaptiveLR(raw,known,config, ...
                positions,8,'ordinary');
            testCase.verifyEqual(refined.detectedSymbols, ...
                paper.detectedSymbols);
            modified = raw; modified(end)=mod(modified(end)+20,128);
            rerun = dreDecodeRefinedAdaptiveLR(modified,known,config, ...
                positions,8,'ordinary');
            testCase.verifyEqual(rerun.detectedSymbols(1:end-1), ...
                refined.detectedSymbols(1:end-1));
        end

