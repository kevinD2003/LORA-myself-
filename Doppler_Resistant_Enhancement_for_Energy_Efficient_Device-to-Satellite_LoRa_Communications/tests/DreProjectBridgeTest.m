classdef DreProjectBridgeTest < matlab.unittest.TestCase
    methods(Test)
        function projectReceiverHasExpectedContract(testCase)
            root = dreSetupPaths(true); %#ok<NASGU>
            p = dreProjectConfig();
            p.v4 = sf12NoLdroSf11FlowConfig();
            key = struct('planVersion',p.identity,'phase','unit-test', ...
                'track','B-method-aligned','channel','AWGN', ...
                'comparisonMode','case-anchor-controlled','snrDb',Inf, ...
                'replicateId',1,'packetId',1,'eventType','paired-frame', ...
                'eventIndex',1,'sampleIndex',0);
            ledger = v4EventRandomLedger(p.randomSeedRoot,key);
            frame = v4GenerateBCaseAnchorFrame(p.v4,0,Inf,ledger);
            receiver = dreProjectLinearRegressionDecode(frame.observation,p,'adaptive');
            testCase.verifySize(receiver.detectedPhysicalBins, ...
                [p.v4.payloadSymbolCount 1]);
            testCase.verifySize(receiver.hardDecodedDataBits,size(frame.truth.dataBits));
            testCase.verifyFalse(receiver.usesPayloadTruth);
            testCase.verifyFalse(receiver.usesOrbitTruth);
            selected = [frame.observation.layout.bootstrapRows; ...
                frame.observation.layout.dataRows];
            centroidConfig = struct('samplesPerSymbol',p.v4.samplesPerSymbol, ...
                'zeroPaddingFactor',p.zeroPaddingFactor, ...
                'centroidSampleCount',p.centroidSampleCount);
            estimate = dreEstimateCentroids( ...
                frame.observation.rxPhysical(selected,:),centroidConfig);
            shared = dreProjectLinearRegressionDecode( ...
                frame.observation,p,'adaptive',estimate.rawBins);
            testCase.verifyEqual(shared.detectedPhysicalBins, ...
                receiver.detectedPhysicalBins);
        end

        function paperFlowConsumesKnownMidamblesWithoutTruth(testCase)
            dreSetupPaths(true);
            p = dreProjectConfig();
            p.v4 = sf12NoLdroSf11FlowConfig();
            key = struct('planVersion','dre-paper-flow-test','phase','unit-test', ...
                'track','B-method-aligned','channel','AWGN', ...
                'comparisonMode','case-anchor-controlled','snrDb',Inf, ...
                'replicateId',2,'packetId',2,'eventType','paired-frame', ...
                'eventIndex',2,'sampleIndex',0);
            ledger = v4EventRandomLedger(p.randomSeedRoot,key);
            frame = v4GenerateBCaseAnchorFrame(p.v4,0,Inf,ledger);
            receiver = dreProjectPaperFlowDecode(frame.observation,p,'adaptive');
            testCase.verifyEqual(receiver.knownMidambleCount, ...
                p.v4.paperMidambleCount);
            testCase.verifyFalse(receiver.usesPayloadTruth);
            testCase.verifyFalse(receiver.usesOrbitTruth);
            testCase.verifyEqual(receiver.detectedPhysicalBins, ...
                frame.truth.payloadPhysicalBins);
            estimatorConfig = struct('samplesPerSymbol',p.v4.samplesPerSymbol, ...
                'zeroPaddingFactor',p.zeroPaddingFactor, ...
                'centroidSampleCount',p.centroidSampleCount);
            centroid = dreEstimateCentroids( ...
                frame.observation.rxPhysical,estimatorConfig);
            altered = centroid.rawBins;
            firstMidamble = frame.observation.layout.midambleRows(1);
            altered(firstMidamble) = mod(altered(firstMidamble)+1, ...
                p.v4.samplesPerSymbol);
            rerun = dreDecodePaperFlowOnLayout(altered, ...
                frame.observation.layout,p.v4,'adaptive');
            earlierData = frame.observation.layout.dataRows < firstMidamble;
            testCase.verifyEqual(rerun.detectedSymbols(earlierData), ...
                receiver.detectedPhysicalBins(earlierData));
            testCase.verifyTrue(rerun.knownPilotUsed(firstMidamble));
        end

        function paperFlowMatchesEquationWithoutMidambles(testCase)
            m = 128; n = 8; payloadCount = 12;
            kind = [repmat("bootstrap",n,1);repmat("data",payloadCount,1)];
            layout = struct('physicalSymbolCount',n+payloadCount, ...
                'bootstrapRows',(1:n).','dataRows',(n+1:n+payloadCount).', ...
                'midambleRows',zeros(0,1),'kind',kind, ...
                'dataIndex',[nan(n,1);(1:payloadCount).']);
            config = struct('samplesPerSymbol',m,'bootstrapPilotCount',n, ...
                'payloadSymbolCount',payloadCount,'preambleSymbolCount',n);
            symbols = [zeros(n,1);(3:3:3*payloadCount).'];
            position = (0:n+payloadCount-1).';
            raw = mod(symbols+5.2+0.1*position,m);
            for mode = ["fixed" "adaptive"]
                old = dreDecodeLinearRegression(raw,zeros(n,1),config,mode);
                new = dreDecodePaperFlowOnLayout(raw,layout,config,mode);
                testCase.verifyEqual(new.detectedSymbols,old.detectedSymbols);
                changed = raw;
                changed(end) = mod(changed(end)+20,m);
                rerun = dreDecodePaperFlowOnLayout(changed,layout,config,mode);
                testCase.verifyEqual(rerun.detectedSymbols(1:end-1), ...
                    new.detectedSymbols(1:end-1));
            end
        end

