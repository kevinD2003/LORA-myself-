function outputs = run_lora_dynamic_doppler_ber_smoke(options)
%RUN_LORA_DYNAMIC_DOPPLER_BER_SMOKE 运行动态 Doppler BER smoke。
%   OUTPUTS = RUN_LORA_DYNAMIC_DOPPLER_BER_SMOKE() 运行配置中的场景、
%   SF 和 SNR 网格，生成 CSV 与中文 Markdown 报告。本函数不生成
%   Figure 17 图像。

arguments
    options.OutputDirectory (1, 1) string = string(pwd)
    options.Config (1, 1) struct = ...
        lora_dynamic_doppler_ber_config()
end

outputDirectory = options.OutputDirectory;
config = options.Config;
if ~isfolder(outputDirectory)
    mkdir(outputDirectory);
end

scenarioNames = string({config.orbitScenarios.name});
numberPoints = numel(scenarioNames)* ...
    numel(config.spreadingFactors)*numel(config.snrDb);
pointResults = cell(numberPoints, 1);
pointIndex = 0;

for scenarioIndex = 1:numel(scenarioNames)
    orbitScenario = scenarioNames(scenarioIndex);
    for sf = config.spreadingFactors
        for snrDb = config.snrDb
            pointIndex = pointIndex + 1;
            pointResults{pointIndex} = ...
                simulate_lora_dynamic_doppler_ber_point( ...
                config.profile, orbitScenario, config.timeMode, ...
                config.dopplerModel, sf, snrDb, config);
            current = pointResults{pointIndex};
            progressFormat = ...
                "BER_SMOKE %d/%d scenario=%s SF=%d SNR=%.1f " + ...
                "BER=%.6g SER=%.6g bits=%d batches=%d " + ...
                "elapsed=%.3fs\n";
            fprintf(char(progressFormat), ...
                pointIndex, numberPoints, orbitScenario, sf, snrDb, ...
                current.ber, current.ser, current.total_bits, ...
                current.monte_carlo_batches, ...
                current.elapsed_seconds);
        end
    end
end

results = struct2table(vertcat(pointResults{:}));
csvPath = fullfile(outputDirectory, ...
    "dynamic_doppler_ber_smoke.csv");
reportPath = fullfile(outputDirectory, ...
    "dynamic_doppler_ber_smoke_report.md");
writetable(results, csvPath);
write_chinese_report(results, config, reportPath);

outputs = struct( ...
    "results", results, ...
    "csvPath", csvPath, ...
    "reportPath", reportPath, ...
    "berSweepRun", true, ...
    "finalFigure17Generated", false);
end

function write_chinese_report(results, config, reportPath)
fileId = fopen(reportPath, "w", "n", "UTF-8");
if fileId < 0
    error("lora:ReportOpenFailed", ...
        "Cannot open the smoke report for writing.");
end
cleanup = onCleanup(@() fclose(fileId));

fprintf(fileId, "# 动态 Doppler BER Smoke 报告\n\n");
fprintf(fileId, "## 仿真范围\n\n");
fprintf(fileId, "- 配置：`%s`\n", char(config.profile));
fprintf(fileId, "- Doppler 模型：`%s`\n", ...
    char(config.dopplerModel));
fprintf(fileId, "- 时间模式：`%s`\n", char(config.timeMode));
fprintf(fileId, "- 接收机：%s\n", char(config.receiver));
fprintf(fileId, "- 信道：%s\n", char(config.channel));
fprintf(fileId, "- bit 映射：%s\n", char(config.mapping));
fprintf(fileId, "- 目标 bit 错误数：%d\n", ...
    config.targetBitErrors);
fprintf(fileId, "- 每点最大 bit 数：%d\n", ...
    config.maxBitsPerPoint);
fprintf(fileId, "- 复采样批上限：%d\n", ...
    config.maxComplexSamplesPerBatch);
fprintf(fileId, "- 最终 Figure 17：未生成\n\n");
assumptionText = ...
    "论文没有完整公开 Figure 17 的接收机和 SNR 细节。本报告采用" + ...
    "本项目已验证的单位平均采样功率、复基带 AWGN、理想符号边界、" + ...
    "无 Doppler 补偿以及非相干 dechirp-FFT-argmax 判决。\n\n";
fprintf(fileId, "%s", char(replace( ...
    assumptionText, "\n", newline)));

geometry = config.geometry;
fprintf(fileId, "## 公式推导场景\n\n");
fprintf(fileId, ...
    "- shared visibility window 第一段：`[%.12f, %.12f] s`\n", ...
    geometry.sharedFirstSec(1), geometry.sharedFirstSec(2));
fprintf(fileId, ...
    "- high Doppler shift 起始时刻：`%.12f s`\n", ...
    geometry.highShiftTimeSec);
fprintf(fileId, ...
    "- high Doppler rate 起始时刻：`%.12f s`\n\n", ...
    geometry.highRateTimeSec);

fprintf(fileId, "## 每点结果\n\n");
headerText = ...
    "| 场景 | SF | SNR(dB) | BER | SER | bit数 | 批数 | 秒 | " + ...
    "MATLAB峰值(MiB) | MATLAB增量(MiB) | 保守估算(MiB) | 停止原因 |\n";
separatorText = ...
    "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|" + ...
    "---:|---|\n";
fprintf(fileId, "%s", char(replace(headerText, "\n", newline)));
fprintf(fileId, "%s", char(replace( ...
    separatorText, "\n", newline)));
for rowIndex = 1:height(results)
    row = results(rowIndex, :);
    rowFormat = ...
        "| %s | %d | %.1f | %.6g | %.6g | %d | %d | " + ...
        "%.3f | %.2f | %.2f | %.2f | %s |\n";
    fprintf(fileId, char(rowFormat), ...
        char(row.orbit_scenario), row.sf, row.snr_db, ...
        row.ber, row.ser, row.total_bits, ...
        row.monte_carlo_batches, row.elapsed_seconds, ...
        row.peak_matlab_memory_bytes/2^20, ...
        row.peak_matlab_memory_delta_bytes/2^20, ...
        row.estimated_peak_memory_bytes/2^20, ...
        char(row.stop_reason));
end

hasNonfinite = any(~isfinite(results.ber)) || ...
    any(~isfinite(results.ser));
hasEmptyBatch = any(results.monte_carlo_batches < 1) || ...
    any(results.total_symbols < 1);
fftMappingValid = all(results.fft_bin_mapping_valid);
fprintf(fileId, "\n## 完整性审查\n\n");
fprintf(fileId, "- BER/SER 出现 NaN 或 Inf：%s\n", ...
    chinese_boolean(hasNonfinite));
fprintf(fileId, "- 出现空批次：%s\n", ...
    chinese_boolean(hasEmptyBatch));
fprintf(fileId, "- FFT bin 映射全部有效：%s\n", ...
    chinese_boolean(fftMappingValid));
fprintf(fileId, "- 使用 AWGN order-statistic 主算法：否\n");
fprintf(fileId, "- 使用 Doppler 补偿或人工 FFT-bin 平移：否\n");
fprintf(fileId, "- continuous-sequence diagnostic：本次未运行\n");
fprintf(fileId, "- 最终 Figure 17 已生成：否\n");

clear cleanup
end

function text = chinese_boolean(value)
if value
    text = "是";
else
    text = "否";
end
end
