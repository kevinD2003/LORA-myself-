function run_lora_css_awgn_reproduction()
%RUN_LORA_CSS_AWGN_REPRODUCTION Reproduce the LoRa CSS part of Fig. 4.
%   Run this file to execute tests, simulate SF7-SF12 over complex AWGN,
%   and export the requested compact data, figures, metadata, and report.

projectFolder = fileparts(mfilename('fullpath'));
addpath(projectFolder);
config = lora_css_awgn_config();

fprintf('LoRa CSS AWGN reproduction\n');
fprintf('Project folder: %s\n', projectFolder);
fprintf('Running unit tests before Monte Carlo simulation...\n');
testSuite = matlab.unittest.TestSuite.fromFile( ...
    fullfile(projectFolder, 'test_lora_css_awgn.m'));
testResults = run(testSuite);
write_test_summary(testResults, ...
    fullfile(projectFolder, 'test_results.txt'));
if ~all([testResults.Passed])
    error('lora:TestsFailed', ...
        'At least one unit test failed. Simulation was not started.');
end
fprintf('All %d unit tests passed.\n', numel(testResults));

numberPoints = numel(config.spreadingFactors) * numel(config.snrDb);
resultCells = cell(numberPoints, 1);
resultIndex = 0;
simulationTimer = tic;

for sf = config.spreadingFactors
    fprintf('Simulating SF%d...\n', sf);
    for snrDb = config.snrDb
        resultIndex = resultIndex + 1;
        pointResult = simulate_lora_css_awgn_point( ...
            sf, snrDb, config);
        resultCells{resultIndex} = pointResult;
        if ~isnan(pointResult.ber) && ...
                pointResult.ber <= config.targetBerFloor && ...
                pointResult.bit_errors >= config.minimumTailBitErrors
            fprintf(['  Tail target reached at %.2f dB: ' ...
                'BER=%.3g with %d errors.\n'], ...
                snrDb, pointResult.ber, pointResult.bit_errors);
            break;
        end
    end
end
elapsedSeconds = toc(simulationTimer);

resultStruct = vertcat(resultCells{1:resultIndex});
results = struct2table(resultStruct);
results.theoretical_ber = NaN(height(results), 1);
for sf = config.spreadingFactors
    rows = results.sf == sf;
    results.theoretical_ber(rows) = ...
        lora_css_theoretical_ber(sf, results.snr_db(rows));
end
csvPath = fullfile(projectFolder, ...
    'ber_css_awgn_sf7_sf12.csv');
writetable(results, csvPath);

[pngPath, pdfPath] = export_ber_figure(results, config, projectFolder);
metadataPath = write_metadata( ...
    config, testResults, results, elapsedSeconds, projectFolder);
reportPath = write_reproduction_report( ...
    config, testResults, results, elapsedSeconds, projectFolder);

fprintf('Simulation completed in %.2f seconds.\n', elapsedSeconds);
fprintf('CSV: %s\n', csvPath);
fprintf('Metadata: %s\n', metadataPath);
fprintf('PNG: %s\n', pngPath);
fprintf('PDF: %s\n', pdfPath);
fprintf('Report: %s\n', reportPath);
end

function write_test_summary(testResults, outputPath)
fileId = fopen(outputPath, 'w');
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, 'LoRa CSS AWGN MATLAB test results\n');
fprintf(fileId, 'Generated: %s\n\n', ...
    char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss Z')));
for index = 1:numel(testResults)
    fprintf(fileId, '%s: %s (%.3f s)\n', ...
        testResults(index).Name, ...
        pass_fail(testResults(index).Passed), ...
        testResults(index).Duration);
end
fprintf(fileId, '\nPassed: %d/%d\n', ...
    nnz([testResults.Passed]), numel(testResults));
clear cleanup;
end

function label = pass_fail(passed)
if passed
    label = 'PASS';
else
    label = 'FAIL';
end
end

function [pngPath, pdfPath] = export_ber_figure( ...
        results, config, projectFolder)
figureHandle = figure( ...
    'Color', 'white', ...
    'Position', [100, 100, 1000, 650], ...
    'Visible', 'on', ...
    'Name', 'LoRa CSS AWGN BER: SF7-SF12', ...
    'NumberTitle', 'off');
axesHandle = axes(figureHandle);
hold(axesHandle, 'on');

colors = lines(numel(config.spreadingFactors));
markers = {'o', 's', '^', 'd', 'v', '>'};
lineHandles = gobjects(numel(config.spreadingFactors), 1);
markerStride = max(1, round(1/config.snrStepDb));

for index = 1:numel(config.spreadingFactors)
    sf = config.spreadingFactors(index);
    rows = results.sf == sf;
    sfResults = results(rows, :);
    [~, order] = sort(sfResults.snr_db);
    sfResults = sfResults(order, :);

    actualBer = sfResults.ber;
    validRows = ~isnan(actualBer) & actualBer > 0;
    validSnr = sfResults.snr_db(validRows);
    validBer = actualBer(validRows);

    theorySnr = config.snrDb(:);
    theoryBer = lora_css_theoretical_ber(sf, theorySnr);
    validTheory = theoryBer > 0 & isfinite(theoryBer);
    theorySnr = theorySnr(validTheory);
    theoryBer = theoryBer(validTheory);
    denseSnr = linspace(theorySnr(1), theorySnr(end), ...
        max(800, 20*numel(theorySnr))).';
    denseLogBer = interp1(theorySnr, log10(theoryBer), ...
        denseSnr, 'pchip');

    lineHandles(index) = semilogy(axesHandle, ...
        denseSnr, 10.^denseLogBer, ...
        'Color', colors(index, :), ...
        'LineWidth', 1.6, ...
        'DisplayName', sprintf('CSS, SF=%d', sf));

    markerRows = unique([ ...
        1:markerStride:numel(validSnr), numel(validSnr)]);
    semilogy(axesHandle, ...
        validSnr(markerRows), validBer(markerRows), ...
        'LineStyle', 'none', ...
        'Marker', markers{index}, ...
        'MarkerSize', 5, ...
        'Color', colors(index, :), ...
        'HandleVisibility', 'off');

    upperRows = sfResults.is_upper_bound;
    if any(upperRows)
        semilogy(axesHandle, ...
            sfResults.snr_db(upperRows), ...
            sfResults.ber_upper_bound(upperRows), ...
            'LineStyle', 'none', ...
            'Marker', 'v', ...
            'MarkerSize', 6, ...
            'Color', colors(index, :), ...
            'HandleVisibility', 'off');
    end
end

grid(axesHandle, 'on');
axesHandle.YScale = 'log';
axesHandle.FontSize = 11;
axesHandle.LineWidth = 1;
xlim(axesHandle, [config.snrDb(1), config.snrDb(end)]);
ylim(axesHandle, [1e-6, 1e-1]);
xticks(axesHandle, config.snrDb(1):2:config.snrDb(end));
xlabel(axesHandle, 'SNR (dB)');
ylabel(axesHandle, 'BER');
title(axesHandle, ...
    {'LoRa CSS BER under complex AWGN', ...
     'Uncoded, perfect synchronization, SF7-SF12'});
legend(axesHandle, lineHandles, 'Location', 'southwest');

pngPath = fullfile(projectFolder, ...
    'ber_css_awgn_sf7_sf12.png');
pdfPath = fullfile(projectFolder, ...
    'ber_css_awgn_sf7_sf12.pdf');
exportgraphics(figureHandle, pngPath, 'Resolution', 300);
exportgraphics(figureHandle, pdfPath, 'ContentType', 'vector');
drawnow;
figure(figureHandle);
end

function metadataPath = write_metadata( ...
        config, testResults, results, elapsedSeconds, projectFolder)
metadata = struct();
metadata.generatedAt = char(datetime( ...
    'now', 'Format', 'yyyy-MM-dd''T''HH:mm:ssXXX'));
metadata.matlabVersion = version;
metadata.platform = computer;
metadata.paper = struct( ...
    'citation', ['M. A. Ben Temim, G. Ferre, and R. Tajan, ' ...
        '"A New LoRa-like Transceiver Suited for LEO Satellite ' ...
        'Communications," Sensors, vol. 22, no. 5, Art. 1830, 2022.'], ...
    'doi', config.paperDoi, ...
    'targetFigure', config.paperFigure);
metadata.configuration = config;
metadata.totalSimulationSeconds = elapsedSeconds;
metadata.unitTestsPassed = all([testResults.Passed]);
metadata.unitTestCount = numel(testResults);
metadata.numberOfMonteCarloPoints = height(results);
metadata.numberOfZeroErrorPoints = nnz(results.is_upper_bound);
metadata.codeFiles = { ...
    'lora_css_awgn_config.m', ...
    'lora_css_modulate.m', ...
    'lora_css_demodulate.m', ...
    'lora_css_theoretical_ber.m', ...
    'simulate_lora_css_awgn_point.m', ...
    'test_lora_css_awgn.m', ...
    'run_lora_css_awgn_reproduction.m'};

metadataPath = fullfile(projectFolder, 'simulation_metadata.json');
fileId = fopen(metadataPath, 'w');
cleanup = onCleanup(@() fclose(fileId));
fwrite(fileId, jsonencode(metadata, 'PrettyPrint', true), 'char');
clear cleanup;
end

function reportPath = write_reproduction_report( ...
        config, testResults, results, elapsedSeconds, projectFolder)
thresholdBer = 1e-4;
crossingSnr = NaN(size(config.spreadingFactors));
for index = 1:numel(config.spreadingFactors)
    sf = config.spreadingFactors(index);
    rows = results.sf == sf & ~isnan(results.ber);
    crossingSnr(index) = estimate_snr_at_ber( ...
        results.snr_db(rows), results.ber(rows), thresholdBer);
end

reportPath = fullfile(projectFolder, 'reproduction_report.md');
fileId = fopen(reportPath, 'w');
cleanup = onCleanup(@() fclose(fileId));

fprintf(fileId, '# LoRa CSS AWGN BER reproduction report\n\n');
fprintf(fileId, 'Generated with MATLAB %s on %s.\n\n', ...
    version, char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss Z')));
fprintf(fileId, '## Target and outcome\n\n');
fprintf(fileId, ['This project reproduces the standard LoRa CSS portion ' ...
    'of Figure 4 in Ben Temim, Ferre, and Tajan, Sensors 22(5), ' ...
    '1830 (2022), DOI: 10.3390/s22051830. ' ...
    'All %d unit tests passed and %d Monte Carlo points were produced ' ...
    'in %.2f seconds.\n\n'], ...
    numel(testResults), height(results), elapsedSeconds);

fprintf(fileId, '## Implemented model\n\n');
fprintf(fileId, ['The simulation uses uncoded LoRa CSS with SF7-SF12, ' ...
    'B=125 kHz, Fs=B, M=2^SF samples per symbol, natural binary ' ...
    'mapping, unit sample power, perfect synchronization, and complex ' ...
    'AWGN only. SNR is Esample/N0sample, so the complex-noise variance ' ...
    'is 10^(-SNR_dB/10). Detection is dechirping followed by an ' ...
    'M-point FFT magnitude maximum.\n\n']);
fprintf(fileId, ['No DCSS, Doppler, CFO, STO, fading, multipath, ' ...
    'interference, FEC, interleaving, whitening, CRC, frame header, ' ...
    'or LoRaWAN packet structure is present.\n\n']);

fprintf(fileId, '## Monte Carlo method\n\n');
fprintf(fileId, ['The waveform chain is implemented and directly tested. ' ...
    'The full sweep samples its exact FFT-domain sufficient statistics ' ...
    'to avoid very large waveform arrays. The correct FFT bin is a ' ...
    'noncentral complex Gaussian random variable and the maximum of ' ...
    'the M-1 noise-only bins is sampled from its exact order-statistic ' ...
    'distribution. Wrong-bin indices are sampled uniformly and bit ' ...
    'errors are counted from the natural-binary labels. No reference ' ...
    'curve, fitted BER formula, or manual SNR shift is used.\n\n']);
fprintf(fileId, ['For presentation only, the plotted lines use ' ...
    'the exact theoretical BER of the same noncoherent dechirp-FFT AWGN ' ...
    'detector. Monte Carlo markers remain unmodified, and both simulated ' ...
    'and theoretical BER values are stored in the CSV. No empirical fit ' ...
    'or SNR shift is applied.\n\n']);
fprintf(fileId, ['Monte Carlo sampling is adaptive. Each SF/SNR point ' ...
    'uses batches of %d random symbols and stops after %d observed bit ' ...
    'errors or %.0f simulated bits. The SNR sweep for each SF stops ' ...
    'after a BER at or below %.1e is supported by at least %d errors. ' ...
    'A zero-error point has BER=NaN in the CSV and is represented only ' ...
    'by the one-count upper bound 1/total_bits.\n\n'], ...
    config.batchSymbols, config.targetBitErrors, ...
    config.maxBitsPerPoint, config.targetBerFloor, ...
    config.minimumTailBitErrors);

fprintf(fileId, '## BER=10^-4 crossing estimates\n\n');
fprintf(fileId, '| SF | Estimated SNR (dB) |\n');
fprintf(fileId, '|---:|---:|\n');
for index = 1:numel(config.spreadingFactors)
    fprintf(fileId, '| %d | %.3f |\n', ...
        config.spreadingFactors(index), crossingSnr(index));
end
fprintf(fileId, '\n');

validCrossings = crossingSnr(~isnan(crossingSnr));
if numel(validCrossings) >= 2
    adjacentGain = -diff(validCrossings);
    fprintf(fileId, ['The median leftward shift per SF step at ' ...
        'BER=10^-4 is %.3f dB; the expected processing-gain trend is ' ...
        'approximately 3.01 dB per step.\n\n'], median(adjacentGain));
end

fprintf(fileId, '## Consistency with Figure 4\n\n');
fprintf(fileId, ['The reproduced curves should have the same qualitative ' ...
    'ordering and near-3 dB spacing as the paper: higher SF moves the ' ...
    'BER waterfall toward lower sample SNR, and no error floor appears. ' ...
    'The comparison is intentionally limited to the CSS curves; the ' ...
    'paper''s DCSS curves are excluded.\n\n']);

fprintf(fileId, '## Sources of possible numerical difference\n\n');
fprintf(fileId, ['The paper does not publish its random seed, number of ' ...
    'trials, stopping rule, exact bit-label convention, or Figure 4 ' ...
    'source data. The paper also describes an oversampled receiver ' ...
    'front end elsewhere, while the ideal synchronized CSS detector ' ...
    'operates at Fs=B. This reproduction therefore cannot claim ' ...
    'point-for-point identity, but it preserves the published signal ' ...
    'model and SNR trend without empirical curve alignment.\n\n']);

fprintf(fileId, '## Files\n\n');
fprintf(fileId, ['- `ber_css_awgn_sf7_sf12.csv`: counts, BER/SER, seeds, ' ...
    'upper bounds, and stopping reasons.\n']);
fprintf(fileId, ['- `simulation_metadata.json`: complete assumptions and ' ...
    'runtime configuration.\n']);
fprintf(fileId, ['- `ber_css_awgn_sf7_sf12.png` and `.pdf`: 300 dpi raster ' ...
    'and vector result figures.\n']);
fprintf(fileId, '- `test_results.txt`: MATLAB unit-test summary.\n');
clear cleanup;
end

function snrAtTarget = estimate_snr_at_ber(snrDb, ber, targetBer)
snrDb = snrDb(:);
ber = ber(:);
[snrDb, order] = sort(snrDb);
ber = ber(order);
logBer = log10(ber);
target = log10(targetBer);

crossing = find( ...
    (logBer(1:end-1) - target) .* ...
    (logBer(2:end) - target) <= 0, 1, 'first');
if isempty(crossing)
    snrAtTarget = NaN;
    return;
end

snrAtTarget = interp1( ...
    logBer(crossing:crossing+1), ...
    snrDb(crossing:crossing+1), target);
end
