function outputs = run_lora_doppler_figure3()
%RUN_LORA_DOPPLER_FIGURE3 Generate the paper Figure 3 type reproduction.
%   OUTPUTS = RUN_LORA_DOPPLER_FIGURE3() computes the carrier-only orbit
%   Doppler trajectory, plots visible portions with solid lines and blind
%   portions with dashed lines, and exports PNG, PDF, CSV, and JSON files.

projectFolder = fileparts(mfilename("fullpath"));
config = lora_orbit_doppler_config();
[window, ~] = lora_visibility_window(config);

regularTimeSec = (-config.plotHalfSpanSec: ...
    config.timeStepSec:config.plotHalfSpanSec).';
boundaryTimeSec = [ ...
    window.intervalsSec(:); ...
    config.centralVisibilityTimeSec];
timeSec = unique([regularTimeSec; boundaryTimeSec]);

trajectory = lora_orbit_doppler_trajectory(timeSec, config);
[~, isVisible] = lora_visibility_window(config, timeSec);

highShiftTimeSec = window.intervalsSec([1, 4]);
highRateTimeSec = window.intervalsSec([2, 3]);
highShiftTrajectory = lora_orbit_doppler_trajectory( ...
    highShiftTimeSec, config);
highRateTrajectory = lora_orbit_doppler_trajectory( ...
    highRateTimeSec, config);

figureHandle = create_figure( ...
    trajectory, isVisible, highShiftTrajectory, ...
    highRateTrajectory, config);

pngPath = fullfile(projectFolder, "dynamic_doppler_figure3.png");
pdfPath = fullfile(projectFolder, "dynamic_doppler_figure3.pdf");
csvPath = fullfile(projectFolder, "dynamic_doppler_trajectory.csv");
metadataPath = fullfile(projectFolder, "dynamic_doppler_metadata.json");

exportgraphics(figureHandle, pngPath, "Resolution", 300);
exportgraphics(figureHandle, pdfPath, "ContentType", "vector");

visibilityRegion = repmat("blind", numel(timeSec), 1);
visibilityRegion(isVisible) = "visible";
trajectoryTable = table( ...
    timeSec, ...
    rad2deg(trajectory.elevationRad), ...
    trajectory.centralAngleRad, ...
    trajectory.slantRangeM, ...
    trajectory.radialVelocityMps, ...
    trajectory.radialAccelerationMps2, ...
    trajectory.dopplerShiftHz, ...
    trajectory.dopplerRateHzPerSec, ...
    isVisible, ...
    visibilityRegion, ...
    'VariableNames', { ...
        'time_s', ...
        'elevation_deg', ...
        'central_angle_rad', ...
        'slant_range_m', ...
        'radial_velocity_mps', ...
        'radial_acceleration_mps2', ...
        'doppler_shift_hz', ...
        'doppler_rate_hz_per_s', ...
        'is_visible', ...
        'visibility_region'});
writetable(trajectoryTable, csvPath);

metadata = create_metadata( ...
    config, window, highShiftTrajectory, highRateTrajectory);
fileId = fopen(metadataPath, "w");
if fileId < 0
    error("lora:MetadataWriteFailed", ...
        "Unable to open metadata output: %s", metadataPath);
end
cleanup = onCleanup(@() fclose(fileId));
fwrite(fileId, jsonencode(metadata, "PrettyPrint", true), "char");
clear cleanup;

outputs = struct( ...
    "pngPath", pngPath, ...
    "pdfPath", pdfPath, ...
    "csvPath", csvPath, ...
    "metadataPath", metadataPath, ...
    "figureHandle", figureHandle, ...
    "window", window);

fprintf("Dynamic Doppler Figure 3 reproduction completed.\n");
fprintf("Visible intervals: [%.6f, %.6f] U [%.6f, %.6f] s\n", ...
    window.intervalsSec(1, 1), window.intervalsSec(1, 2), ...
    window.intervalsSec(2, 1), window.intervalsSec(2, 2));
fprintf("Total visible duration: %.6f s\n", ...
    window.totalVisibleDurationSec);
fprintf("PNG: %s\n", pngPath);
fprintf("PDF: %s\n", pdfPath);
fprintf("CSV: %s\n", csvPath);
fprintf("Metadata: %s\n", metadataPath);
end

function figureHandle = create_figure( ...
        trajectory, isVisible, highShiftTrajectory, ...
        highRateTrajectory, config)
timeSec = trajectory.timeSec;
visibleShiftKhz = masked_values( ...
    trajectory.dopplerShiftHz/1e3, isVisible);
blindShiftKhz = masked_values( ...
    trajectory.dopplerShiftHz/1e3, ~isVisible);
visibleRate = masked_values( ...
    trajectory.dopplerRateHzPerSec, isVisible);
blindRate = masked_values( ...
    trajectory.dopplerRateHzPerSec, ~isVisible);

figureHandle = figure( ...
    "Color", "white", ...
    "Position", config.figurePosition, ...
    "Visible", "on", ...
    "Name", "LoRa satellite dynamic Doppler - Figure 3", ...
    "NumberTitle", "off");
axesHandle = axes(figureHandle);
hold(axesHandle, "on");

shiftColor = [0, 0.4470, 0.7410];
rateColor = [0.8500, 0.3250, 0.0980];

yyaxis(axesHandle, "left");
shiftVisibleHandle = plot( ...
    axesHandle, timeSec, visibleShiftKhz, ...
    "-", "Color", shiftColor, "LineWidth", 1.8, ...
    "DisplayName", "Doppler shift - visible");
shiftBlindHandle = plot( ...
    axesHandle, timeSec, blindShiftKhz, ...
    "--", "Color", shiftColor, "LineWidth", 1.2, ...
    "DisplayName", "Doppler shift - blind");
highShiftHandle = scatter( ...
    axesHandle, highShiftTrajectory.timeSec, ...
    highShiftTrajectory.dopplerShiftHz/1e3, ...
    60, "d", "MarkerEdgeColor", [0.1, 0.1, 0.1], ...
    "MarkerFaceColor", shiftColor, ...
    "DisplayName", "High Doppler shift candidates");
ylabel(axesHandle, "Doppler shift (kHz)");

yyaxis(axesHandle, "right");
rateVisibleHandle = plot( ...
    axesHandle, timeSec, visibleRate, ...
    "-", "Color", rateColor, "LineWidth", 1.8, ...
    "DisplayName", "Doppler rate - visible");
rateBlindHandle = plot( ...
    axesHandle, timeSec, blindRate, ...
    "--", "Color", rateColor, "LineWidth", 1.2, ...
    "DisplayName", "Doppler rate - blind");
highRateHandle = scatter( ...
    axesHandle, highRateTrajectory.timeSec, ...
    highRateTrajectory.dopplerRateHzPerSec, ...
    65, "^", "MarkerEdgeColor", [0.1, 0.1, 0.1], ...
    "MarkerFaceColor", rateColor, ...
    "DisplayName", "High Doppler rate candidates");
ylabel(axesHandle, "Doppler rate (Hz/s)");

xlabel(axesHandle, "Time relative to t_{cv} (s)");
title(axesHandle, [ ...
    "Dynamic Doppler over a single visibility window", ...
    "f_c = 868 MHz, H = 550 km, i = 15 deg"]);
xlim(axesHandle, [-config.plotHalfSpanSec, config.plotHalfSpanSec]);
grid(axesHandle, "on");
axesHandle.FontSize = 11;
axesHandle.LineWidth = 1;

legend(axesHandle, [ ...
    shiftVisibleHandle, shiftBlindHandle, ...
    rateVisibleHandle, rateBlindHandle, ...
    highShiftHandle, highRateHandle], ...
    "Location", "southwest");
drawnow();
end

function values = masked_values(values, mask)
values(~mask) = NaN;
end

function metadata = create_metadata( ...
        config, window, highShiftTrajectory, highRateTrajectory)
endpointTimesSec = window.intervalsSec(:);
endpointTrajectory = lora_orbit_doppler_trajectory( ...
    endpointTimesSec, config);
visibleAbsShiftHz = abs(endpointTrajectory.dopplerShiftHz);
visibleAbsRateHzPerSec = abs(endpointTrajectory.dopplerRateHzPerSec);

formulaDerivedValue = struct( ...
    "omegaSatelliteRadPerSec", window.omegaSatelliteRadPerSec, ...
    "omegaFixedRadPerSec", window.omegaFixedRadPerSec, ...
    "gammaCentralRad", window.gammaCentralRad, ...
    "deltaTimeOutSec", window.deltaTimeOutSec, ...
    "deltaTimeInSec", window.deltaTimeInSec, ...
    "intervalsSec", window.intervalsSec, ...
    "blindIntervalSec", window.blindIntervalSec, ...
    "visibleDurationSec", window.totalVisibleDurationSec, ...
    "dopplerShiftAbsRangeHz", [ ...
        min(visibleAbsShiftHz), max(visibleAbsShiftHz)], ...
    "dopplerRateAbsRangeHzPerSec", [ ...
        min(visibleAbsRateHzPerSec), max(visibleAbsRateHzPerSec)]);

metadata = struct();
metadata.generatedAt = char(datetime( ...
    "now", "Format", "yyyy-MM-dd'T'HH:mm:ssXXX"));
metadata.matlabVersion = version();
metadata.model = "carrier_only_orbit_doppler";
metadata.dopplerDefinition = "f_D(t) = -f_c*v(t)/c";
metadata.internalAngleUnit = config.internalAngleUnit;
metadata.constants = struct( ...
    "speedOfLightMps", config.speedOfLightMps, ...
    "gravityMps2", config.gravityMps2, ...
    "earthRadiusM", config.earthRadiusM, ...
    "earthRotationRadPerSec", config.earthRotationRadPerSec);
metadata.orbit = struct( ...
    "heightM", config.orbitHeightM, ...
    "inclinationRad", config.inclinationRad, ...
    "carrierFrequencyHz", config.carrierFrequencyHz, ...
    "centralVisibilityTimeSec", config.centralVisibilityTimeSec);
metadata.elevationLimitsRad = struct( ...
    "theoreticalMaximum", config.theoreticalMaxElevationRad, ...
    "minimum", config.minimumElevationRad, ...
    "maximum", config.maximumElevationRad);
metadata.paperParameterDegrees = config.paperParameterDegrees;
metadata.formula_derived_value = formulaDerivedValue;
metadata.paper_reported_approximate_value = ...
    config.paperReportedApproximateValue;
metadata.paperComparison = struct( ...
    "visibleDurationDifferenceSec", ...
        formulaDerivedValue.visibleDurationSec - ...
        config.paperReportedApproximateValue.visibleDurationSec, ...
    "minimumAbsShiftDifferenceHz", ...
        formulaDerivedValue.dopplerShiftAbsRangeHz(1) - ...
        config.paperReportedApproximateValue.dopplerShiftAbsRangeHz(1), ...
    "maximumAbsShiftDifferenceHz", ...
        formulaDerivedValue.dopplerShiftAbsRangeHz(2) - ...
        config.paperReportedApproximateValue.dopplerShiftAbsRangeHz(2), ...
    "minimumAbsRateDifferenceHzPerSec", ...
        formulaDerivedValue.dopplerRateAbsRangeHzPerSec(1) - ...
        config.paperReportedApproximateValue.dopplerRateAbsRangeHzPerSec(1), ...
    "maximumAbsRateDifferenceHzPerSec", ...
        formulaDerivedValue.dopplerRateAbsRangeHzPerSec(2) - ...
        config.paperReportedApproximateValue.dopplerRateAbsRangeHzPerSec(2), ...
    "assessment", "consistent_with_paper_within_test_tolerances");
metadata.candidatePoints = struct( ...
    "highDopplerShiftTimeSec", highShiftTrajectory.timeSec, ...
    "highDopplerShiftHz", highShiftTrajectory.dopplerShiftHz, ...
    "highDopplerRateTimeSec", highRateTrajectory.timeSec, ...
    "highDopplerRateHzPerSec", ...
        highRateTrajectory.dopplerRateHzPerSec);
metadata.outputs = [ ...
    "dynamic_doppler_figure3.png", ...
    "dynamic_doppler_figure3.pdf", ...
    "dynamic_doppler_trajectory.csv", ...
    "dynamic_doppler_metadata.json"];
end
