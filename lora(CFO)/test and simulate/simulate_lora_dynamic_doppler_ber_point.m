function [result, diagnostics] = ...
        simulate_lora_dynamic_doppler_ber_point( ...
        profile, orbitScenario, timeMode, dopplerModel, ...
        sf, snrDb, config)
%SIMULATE_LORA_DYNAMIC_DOPPLER_BER_POINT 仿真一个动态 Doppler BER 点。
%   RESULT = SIMULATE_LORA_DYNAMIC_DOPPLER_BER_POINT(...) 使用完整时域
%   LoRa CSS 波形、已验证的 Doppler 相位、复基带 AWGN 和原始
%   dechirp-FFT-argmax 接收机。该函数不使用 AWGN order-statistic 方法。

profile = string(profile);
orbitScenario = string(orbitScenario);
timeMode = string(timeMode);
dopplerModel = string(dopplerModel);
validate_inputs(profile, orbitScenario, timeMode, ...
    dopplerModel, sf, snrDb, config);

scenarioNames = string({config.orbitScenarios.name});
scenarioIndex = find(scenarioNames == orbitScenario, 1);
orbitStartTimeSec = ...
    config.orbitScenarios(scenarioIndex).startTimeSec;
orbitConfig = config.geometry.configA;
orbitStart = lora_orbit_doppler_trajectory( ...
    orbitStartTimeSec, orbitConfig);

m = 2^sf;
symbolDurationSec = m/config.bandwidthHz;
fftBinSpacingHz = config.bandwidthHz/m;
halfBinToleranceHz = fftBinSpacingHz/2;
batchSymbols = min(config.maxSymbolsPerBatch, ...
    max(1, floor(config.maxComplexSamplesPerBatch/m)));

modelIndex = find(config.allowedDopplerModels == dopplerModel, 1);
timeModeIndex = find(config.allowedTimeModes == timeMode, 1);
if isinf(snrDb)
    snrIndex = 999;
else
    snrIndex = round(10*(snrDb + 100));
end
seedSymbols = config.baseSeedSymbols + ...
    100000*scenarioIndex + 1000*modelIndex + ...
    100*timeModeIndex + 10*sf + snrIndex;
seedNoise = config.baseSeedNoise + ...
    100000*scenarioIndex + 1000*modelIndex + ...
    100*timeModeIndex + 10*sf + snrIndex;
symbolStream = RandStream("mt19937ar", "Seed", seedSymbols);
noiseStream = RandStream("mt19937ar", "Seed", seedNoise);
collectDiagnostics = nargout > 1;
fixedPhaseCache = zeros(m, 0);
if timeMode == "fixed_orbit_start_independent_symbols" && ...
        m*m <= config.maxComplexSamplesPerBatch
    fixedPhaseCache = zeros(m, m);
    for symbolValue = 0:m-1
        trace = lora_doppler_piecewise_linear( ...
            symbolValue, sf, orbitStartTimeSec, orbitConfig, ...
            BandwidthHz=config.bandwidthHz);
        [~, selectedPhaseRad] = select_trace(trace, dopplerModel);
        fixedPhaseCache(:, symbolValue + 1) = selectedPhaseRad;
    end
end

bitErrors = 0;
symbolErrors = 0;
totalBits = 0;
totalSymbols = 0;
completedBatches = 0;
peakComplexSamples = 0;
estimatedPeakMemoryBytes = 0;
baselineMatlabMemoryBytes = current_matlab_memory_bytes();
peakMatlabMemoryBytes = baselineMatlabMemoryBytes;
fftBinMappingValid = true;
hasPreviousContinuousSample = false;
previousLastFrequencyHz = 0;
previousLastPhaseRad = 0;
diagnosticTransmittedSymbols = zeros(1, 0, "uint32");
diagnosticStartTimeSec = zeros(1, 0);
diagnosticInitialPhaseRad = zeros(1, 0);
diagnosticBoundaryResidualRad = zeros(1, 0);
diagnosticNoiseChecksum = complex(0);
timer = tic;

while bitErrors < config.targetBitErrors && ...
        totalBits < config.maxBitsPerPoint
    remainingSymbols = floor( ...
        (config.maxBitsPerPoint - totalBits)/sf);
    if remainingSymbols < 1
        break
    end
    numberSymbols = min(batchSymbols, remainingSymbols);
    transmitted = randi(symbolStream, [0, m-1], ...
        1, numberSymbols, "uint32");
    tx = lora_css_modulate(transmitted, sf);
    peakMatlabMemoryBytes = max(peakMatlabMemoryBytes, ...
        current_matlab_memory_bytes());

    phaseRad = zeros(m, numberSymbols);
    batchStartTimeSec = zeros(1, numberSymbols);
    batchInitialPhaseRad = zeros(1, numberSymbols);
    batchBoundaryResidualRad = zeros(1, numberSymbols);
    batchBoundaryCount = 0;
    if timeMode == "fixed_orbit_start_independent_symbols"
        if ~isempty(fixedPhaseCache)
            phaseRad = fixedPhaseCache(:, ...
                double(transmitted) + 1);
        else
            uniqueSymbols = unique(transmitted);
            for symbolValue = uniqueSymbols
                trace = lora_doppler_piecewise_linear( ...
                    symbolValue, sf, orbitStartTimeSec, orbitConfig, ...
                    BandwidthHz=config.bandwidthHz);
                [~, selectedPhaseRad] = select_trace( ...
                    trace, dopplerModel);
                symbolMask = transmitted == symbolValue;
                phaseRad(:, symbolMask) = repmat( ...
                    selectedPhaseRad, 1, nnz(symbolMask));
            end
        end
        batchStartTimeSec(:) = orbitStartTimeSec;
    else
        for columnIndex = 1:numberSymbols
            globalSymbolIndex = totalSymbols + columnIndex - 1;
            symbolStartTimeSec = orbitStartTimeSec + ...
                globalSymbolIndex*symbolDurationSec;
            trace = lora_doppler_piecewise_linear( ...
                transmitted(columnIndex), sf, ...
                symbolStartTimeSec, orbitConfig, ...
                BandwidthHz=config.bandwidthHz);
            [selectedFrequencyHz, localPhaseRad] = ...
                select_trace(trace, dopplerModel);
            if hasPreviousContinuousSample
                boundaryIncrementRad = pi/config.bandwidthHz*( ...
                    previousLastFrequencyHz + ...
                    selectedFrequencyHz(1));
                firstPhaseRad = previousLastPhaseRad + ...
                    boundaryIncrementRad;
                continuousPhaseRad = localPhaseRad + firstPhaseRad;
                batchBoundaryCount = batchBoundaryCount + 1;
                batchBoundaryResidualRad(batchBoundaryCount) = ...
                    continuousPhaseRad(1) - ( ...
                    previousLastPhaseRad + boundaryIncrementRad);
            else
                continuousPhaseRad = localPhaseRad;
                hasPreviousContinuousSample = true;
            end
            phaseRad(:, columnIndex) = continuousPhaseRad;
            batchStartTimeSec(columnIndex) = symbolStartTimeSec;
            batchInitialPhaseRad(columnIndex) = ...
                continuousPhaseRad(1);
            previousLastFrequencyHz = selectedFrequencyHz(end);
            previousLastPhaseRad = continuousPhaseRad(end);
        end
        batchBoundaryResidualRad = ...
            batchBoundaryResidualRad(1:batchBoundaryCount);
    end
    phaseRotation = exp(1i*phaseRad);
    noiselessRx = tx.*phaseRotation;
    peakMatlabMemoryBytes = max(peakMatlabMemoryBytes, ...
        current_matlab_memory_bytes());

    if isinf(snrDb)
        noiseVariance = 0;
        noise = complex(zeros(m, numberSymbols));
    else
        noiseVariance = 10^(-snrDb/10);
        noise = sqrt(noiseVariance/2)*( ...
            randn(noiseStream, m, numberSymbols) + ...
            1i*randn(noiseStream, m, numberSymbols));
    end
    if collectDiagnostics
        diagnosticTransmittedSymbols = [ ...
            diagnosticTransmittedSymbols, transmitted]; %#ok<AGROW>
        diagnosticStartTimeSec = [ ...
            diagnosticStartTimeSec, batchStartTimeSec]; %#ok<AGROW>
        diagnosticInitialPhaseRad = [ ...
            diagnosticInitialPhaseRad, ...
            batchInitialPhaseRad]; %#ok<AGROW>
        diagnosticBoundaryResidualRad = [ ...
            diagnosticBoundaryResidualRad, ...
            batchBoundaryResidualRad]; %#ok<AGROW>
        diagnosticNoiseChecksum = diagnosticNoiseChecksum + ...
            sum(real(noise), "all") + 1i*sum(imag(noise), "all");
    end
    rx = noiselessRx + noise;
    peakMatlabMemoryBytes = max(peakMatlabMemoryBytes, ...
        current_matlab_memory_bytes());
    detected = lora_css_demodulate(rx, sf);
    peakMatlabMemoryBytes = max(peakMatlabMemoryBytes, ...
        current_matlab_memory_bytes());

    if any(detected(:) > uint32(m-1))
        error("lora:InvalidDetectedSymbol", ...
            "FFT detector returned a symbol outside [0,M-1].");
    end

    xorValues = bitxor(transmitted(:), detected(:));
    errorsThisBatch = 0;
    for bitIndex = 1:sf
        errorsThisBatch = errorsThisBatch + ...
            nnz(bitget(xorValues, bitIndex));
    end
    bitErrors = bitErrors + errorsThisBatch;
    symbolErrors = symbolErrors + ...
        nnz(transmitted(:) ~= detected(:));
    totalSymbols = totalSymbols + numberSymbols;
    totalBits = totalBits + numberSymbols*sf;
    completedBatches = completedBatches + 1;
    peakComplexSamples = max( ...
        peakComplexSamples, m*numberSymbols);
    estimatedPeakMemoryBytes = max( ...
        estimatedPeakMemoryBytes, ...
        128*m*numberSymbols + 8*numel(fixedPhaseCache));

    clear tx phaseRad phaseRotation noiselessRx noise rx detected
end

if bitErrors >= config.targetBitErrors
    stopReason = "target_bit_errors";
else
    stopReason = "maximum_bits";
end

ber = bitErrors/totalBits;
ser = symbolErrors/totalSymbols;
orbitInitialDopplerHz = orbitStart.dopplerShiftHz;
orbitInitialRateHzPerSec = orbitStart.dopplerRateHzPerSec;
dopplerChangeOverSymbolHz = ...
    orbitInitialRateHzPerSec*symbolDurationSec;

result = struct( ...
    "profile", profile, ...
    "orbit_scenario", orbitScenario, ...
    "time_mode", timeMode, ...
    "doppler_model", dopplerModel, ...
    "sf", sf, ...
    "snr_db", snrDb, ...
    "orbit_start_time_s", orbitStartTimeSec, ...
    "orbit_initial_doppler_hz", orbitInitialDopplerHz, ...
    "orbit_initial_doppler_rate_hz_per_s", ...
        orbitInitialRateHzPerSec, ...
    "symbol_duration_s", symbolDurationSec, ...
    "fft_bin_spacing_hz", fftBinSpacingHz, ...
    "half_bin_tolerance_hz", halfBinToleranceHz, ...
    "normalized_initial_bin_offset", ...
        orbitInitialDopplerHz/fftBinSpacingHz, ...
    "doppler_change_over_symbol_hz", ...
        dopplerChangeOverSymbolHz, ...
    "normalized_rate_sweep_bins", ...
        dopplerChangeOverSymbolHz/fftBinSpacingHz, ...
    "quadratic_phase_span_rad", ...
        pi*orbitInitialRateHzPerSec*symbolDurationSec^2, ...
    "ber", ber, ...
    "ber_upper_bound", 1/totalBits, ...
    "bit_errors", bitErrors, ...
    "total_bits", totalBits, ...
    "ser", ser, ...
    "ser_upper_bound", 1/totalSymbols, ...
    "symbol_errors", symbolErrors, ...
    "total_symbols", totalSymbols, ...
    "monte_carlo_batches", completedBatches, ...
    "symbols_per_batch", batchSymbols, ...
    "seed_symbols", seedSymbols, ...
    "seed_noise", seedNoise, ...
    "stop_reason", stopReason, ...
    "elapsed_seconds", toc(timer), ...
    "peak_complex_samples_per_batch", peakComplexSamples, ...
    "estimated_peak_memory_bytes", estimatedPeakMemoryBytes, ...
    "peak_matlab_memory_bytes", peakMatlabMemoryBytes, ...
    "peak_matlab_memory_delta_bytes", max(0, ...
        peakMatlabMemoryBytes - baselineMatlabMemoryBytes), ...
    "fft_bin_mapping_valid", fftBinMappingValid);

if timeMode == "continuous_symbol_sequence"
    timeModeLabel = "continuous-sequence diagnostic";
else
    timeModeLabel = "fixed independent-symbol trials";
end
diagnostics = struct( ...
    "timeModeLabel", timeModeLabel, ...
    "noiseVariance", noiseVariance, ...
    "transmittedSymbols", diagnosticTransmittedSymbols, ...
    "symbolStartTimeSec", diagnosticStartTimeSec, ...
    "symbolInitialPhaseRad", diagnosticInitialPhaseRad, ...
    "phaseBoundaryResidualRad", ...
        diagnosticBoundaryResidualRad, ...
    "noiseChecksum", diagnosticNoiseChecksum);
end

function validate_inputs(profile, orbitScenario, timeMode, ...
        dopplerModel, sf, snrDb, config)
requiredConfigFields = [ ...
    "profile", ...
    "bandwidthHz", ...
    "orbitScenarios", ...
    "allowedDopplerModels", ...
    "allowedTimeModes", ...
    "targetBitErrors", ...
    "maxBitsPerPoint", ...
    "maxComplexSamplesPerBatch", ...
    "maxSymbolsPerBatch", ...
    "baseSeedSymbols", ...
    "baseSeedNoise", ...
    "geometry"];
if ~all(isfield(config, requiredConfigFields))
    error("lora:InvalidBerConfiguration", ...
        "The BER configuration is missing required fields.");
end
if profile ~= string(config.profile)
    error("lora:InvalidBerProfile", ...
        "The requested profile does not match the configuration.");
end
scenarioNames = string({config.orbitScenarios.name});
if ~any(scenarioNames == orbitScenario)
    error("lora:InvalidOrbitScenario", ...
        "Unknown orbit scenario.");
end
if ~any(config.allowedTimeModes == timeMode)
    error("lora:InvalidTimeMode", ...
        "Unsupported Monte Carlo time mode.");
end
if ~any(config.allowedDopplerModels == dopplerModel)
    error("lora:InvalidDopplerModel", ...
        "Unsupported Doppler model.");
end
validateattributes(sf, {'numeric'}, ...
    {'scalar', 'integer', '>=', 1, '<=', 20}, ...
    mfilename, "sf");
if ~isnumeric(snrDb) || ~isscalar(snrDb) || ...
        isnan(snrDb) || snrDb == -Inf
    error("lora:InvalidSnr", ...
        "SNR must be finite or positive infinity.");
end
positiveScalarFields = [ ...
    "bandwidthHz", ...
    "targetBitErrors", ...
    "maxBitsPerPoint", ...
    "maxComplexSamplesPerBatch", ...
    "maxSymbolsPerBatch"];
for fieldName = positiveScalarFields
    fieldValue = config.(fieldName);
    if ~isnumeric(fieldValue) || ~isscalar(fieldValue) || ...
            ~isfinite(fieldValue) || fieldValue <= 0
        error("lora:InvalidBerConfiguration", ...
            "Configuration field '%s' must be positive.", ...
            fieldName);
    end
end
end

function [frequencyHz, phaseRad] = select_trace(trace, model)
if model == "paper_piecewise_linear"
    frequencyHz = trace.linearDopplerHz;
    phaseRad = trace.linearPhaseRad;
elseif model == "exact_orbit_sampled"
    frequencyHz = trace.exactDopplerHz;
    phaseRad = trace.exactPhaseRad;
else
    error("lora:InvalidDopplerModel", ...
        "Unsupported Doppler model.");
end
end

function bytes = current_matlab_memory_bytes()
try
    userView = memory;
    bytes = double(userView.MemUsedMATLAB);
catch
    bytes = 0;
end
if ~isfinite(bytes) || bytes < 0
    bytes = 0;
end
end
