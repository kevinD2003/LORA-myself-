function result = lora_doppler_piecewise_linear( ...
        symbol, sf, startTimeSec, orbitConfig, options)
%LORA_DOPPLER_PIECEWISE_LINEAR 比较精确与论文分段线性 Doppler。
%   RESULT = LORA_DOPPLER_PIECEWISE_LINEAR(SYMBOL, SF, STARTTIMESEC,
%   ORBITCONFIG) 在一个 LoRa 符号内计算逐采样完整 RF Doppler、论文
%   式（18）至式（20）的分段线性近似、梯形积分相位和误差统计。
%
%   Name-value:
%     BandwidthHz - LoRa 带宽及采样率，默认 250e3 Hz。

arguments
    symbol
    sf
    startTimeSec (1, 1) double
    orbitConfig (1, 1) struct
    options.BandwidthHz (1, 1) double = 250e3
end

if ~isfinite(startTimeSec)
    error("lora:InvalidStartTime", ...
        "The symbol start time must be finite.");
end
if ~isfinite(options.BandwidthHz) || options.BandwidthHz <= 0
    error("lora:InvalidBandwidth", ...
        "Bandwidth must be a positive finite scalar in hertz.");
end

requiredFields = ["carrierFrequencyHz", "speedOfLightMps"];
for fieldName = requiredFields
    if ~isfield(orbitConfig, fieldName)
        error("lora:MissingOrbitConfiguration", ...
            "Orbit configuration field '%s' is required.", fieldName);
    end
end

sampleRateHz = options.BandwidthHz;
basebandFrequencyHz = lora_symbol_instantaneous_frequency( ...
    symbol, sf, sampleRateHz);
m = numel(basebandFrequencyHz);
symbolValue = double(symbol);
sampleIndex = (0:m-1).';
timeWithinSymbolSec = sampleIndex/sampleRateHz;
sampleTimeSec = startTimeSec + timeWithinSymbolSec;
orbit = lora_orbit_doppler_trajectory(sampleTimeSec, orbitConfig);

instantaneousRfHz = orbitConfig.carrierFrequencyHz + ...
    basebandFrequencyHz;
exactDopplerHz = -instantaneousRfHz.* ...
    orbit.radialVelocityMps/orbitConfig.speedOfLightMps;

[wrapIndex, slopeSampleIndices] = select_slope_samples( ...
    symbolValue, m);
cdHzPerSec = ( ...
    exactDopplerHz(slopeSampleIndices(2)) - ...
    exactDopplerHz(slopeSampleIndices(1)))*sampleRateHz;
vdHz = exactDopplerHz(1);
linearDopplerHz = vdHz + cdHzPerSec*timeWithinSymbolSec;

if wrapIndex <= m
    wrapTimeSec = startTimeSec + ...
        (wrapIndex-1)/sampleRateHz;
    wrapOrbit = lora_orbit_doppler_trajectory( ...
        wrapTimeSec, orbitConfig);
    paperPrintedBvOverCHz = sampleRateHz* ...
        wrapOrbit.radialVelocityMps/ ...
        orbitConfig.speedOfLightMps;
    appliedDeltaFkHz = -paperPrintedBvOverCHz;
    linearDopplerHz(wrapIndex:end) = ...
        linearDopplerHz(wrapIndex:end) - appliedDeltaFkHz;
else
    wrapTimeSec = NaN;
    paperPrintedBvOverCHz = 0;
    appliedDeltaFkHz = 0;
end

exactPhaseRad = trapezoidal_phase( ...
    exactDopplerHz, sampleRateHz);
linearPhaseRad = trapezoidal_phase( ...
    linearDopplerHz, sampleRateHz);
dopplerErrorHz = linearDopplerHz - exactDopplerHz;
phaseErrorRad = linearPhaseRad - exactPhaseRad;

result = struct( ...
    "symbol", uint32(symbolValue), ...
    "spreadingFactor", sf, ...
    "sampleRateHz", sampleRateHz, ...
    "symbolPeriodSec", m/sampleRateHz, ...
    "startTimeSec", startTimeSec, ...
    "sampleIndex", sampleIndex, ...
    "timeWithinSymbolSec", timeWithinSymbolSec, ...
    "sampleTimeSec", sampleTimeSec, ...
    "basebandFrequencyHz", basebandFrequencyHz, ...
    "instantaneousRfHz", instantaneousRfHz, ...
    "radialVelocityMps", orbit.radialVelocityMps, ...
    "exactDopplerHz", exactDopplerHz, ...
    "linearDopplerHz", linearDopplerHz, ...
    "exactPhaseRad", exactPhaseRad, ...
    "linearPhaseRad", linearPhaseRad, ...
    "dopplerErrorHz", dopplerErrorHz, ...
    "phaseErrorRad", phaseErrorRad, ...
    "vdHz", vdHz, ...
    "cdHzPerSec", cdHzPerSec, ...
    "wrapIndex", wrapIndex, ...
    "wrapTimeSec", wrapTimeSec, ...
    "slopeSampleIndices", slopeSampleIndices, ...
    "paperPrintedBvOverCHz", paperPrintedBvOverCHz, ...
    "appliedDeltaFkHz", appliedDeltaFkHz, ...
    "velocityConvention", "range_rate_positive_receding", ...
    "meanAbsErrorHz", mean(abs(dopplerErrorHz)), ...
    "maxAbsErrorHz", max(abs(dopplerErrorHz)), ...
    "rmseHz", sqrt(mean(dopplerErrorHz.^2)), ...
    "phaseRmseRad", sqrt(mean(phaseErrorRad.^2)), ...
    "integrationRule", "trapezoidal");
end

function [wrapIndex, slopeSampleIndices] = select_slope_samples( ...
        symbol, m)
if symbol == 0
    wrapIndex = m + 1;
    slopeSampleIndices = [1, 2];
    return
end

wrapIndex = m - symbol + 1;
preWrapCount = wrapIndex - 1;
postWrapCount = m - wrapIndex + 1;

if postWrapCount >= preWrapCount && postWrapCount >= 2
    slopeSampleIndices = [wrapIndex, wrapIndex + 1];
elseif preWrapCount >= 2
    slopeSampleIndices = [wrapIndex - 2, wrapIndex - 1];
elseif postWrapCount >= 2
    slopeSampleIndices = [wrapIndex, wrapIndex + 1];
else
    error("lora:InsufficientSlopeSamples", ...
        "At least two samples are required within one non-wrap segment.");
end
end

function phaseRad = trapezoidal_phase(frequencyHz, sampleRateHz)
phaseIncrementRad = pi/sampleRateHz*( ...
    frequencyHz(1:end-1) + frequencyHz(2:end));
phaseRad = [0; cumsum(phaseIncrementRad)];
end
