function outputs = run_lora_doppler_approx_validation(options)
%RUN_LORA_DOPPLER_APPROX_VALIDATION 生成 Doppler 近似验证图和数据。
%   OUTPUTS = RUN_LORA_DOPPLER_APPROX_VALIDATION() 运行 Figure 5 风格
%   单符号验证以及 50 个连续符号的漂移验证，并将结果写入当前目录。
%
%   Name-value:
%     OutputDirectory - 输出目录，默认当前目录。
%     SymbolCount     - 连续符号数，默认 50。
%     FigureVisible   - "on" 或 "off"，默认 "off"。

arguments
    options.OutputDirectory (1, 1) string = string(pwd)
    options.SymbolCount (1, 1) double = 50
    options.FigureVisible (1, 1) string = "off"
end

if ~isfinite(options.SymbolCount) || ...
        options.SymbolCount < 1 || ...
        options.SymbolCount ~= floor(options.SymbolCount)
    error("lora:InvalidSymbolCount", ...
        "SymbolCount must be a positive finite integer.");
end
if ~any(options.FigureVisible == ["on", "off"])
    error("lora:InvalidFigureVisibility", ...
        "FigureVisible must be 'on' or 'off'.");
end
if ~isfolder(options.OutputDirectory)
    mkdir(options.OutputDirectory);
end
if exist("lora_css_modulate", "file") ~= 2 || ...
        exist("lora_css_demodulate", "file") ~= 2
    error("lora:MissingOriginalCssFunctions", ...
        "Original LoRa modulation and demodulation functions are required.");
end

geometry = lora_figure17_geometry();
bandwidthHz = 250e3;
tolerances = approximation_tolerances();
cases = validation_cases(geometry);

singleSymbolTable = run_single_symbol_cases( ...
    cases, geometry, bandwidthHz, tolerances, ...
    options.OutputDirectory, options.FigureVisible);
symbolwiseTable = run_symbolwise_cases( ...
    cases, geometry, bandwidthHz, options.SymbolCount, ...
    tolerances, options.OutputDirectory, options.FigureVisible);

singleCsvPath = fullfile(options.OutputDirectory, ...
    "doppler_approx_single_symbol_metrics.csv");
singleJsonPath = fullfile(options.OutputDirectory, ...
    "doppler_approx_single_symbol_metrics.json");
symbolwiseCsvPath = fullfile(options.OutputDirectory, ...
    "doppler_symbolwise_validation.csv");
symbolwiseJsonPath = fullfile(options.OutputDirectory, ...
    "doppler_symbolwise_validation.json");
writetable(singleSymbolTable, singleCsvPath);
writetable(symbolwiseTable, symbolwiseCsvPath);

metadata = output_metadata( ...
    geometry, bandwidthHz, options.SymbolCount, tolerances);
singlePayload = struct( ...
    "metadata", metadata, ...
    "rows", table2struct(singleSymbolTable));
symbolwisePayload = struct( ...
    "metadata", metadata, ...
    "rows", table2struct(symbolwiseTable));
write_json(singleJsonPath, singlePayload);
write_json(symbolwiseJsonPath, symbolwisePayload);

outputs = struct( ...
    "outputDirectory", options.OutputDirectory, ...
    "symbolCount", options.SymbolCount, ...
    "singleSymbolTable", singleSymbolTable, ...
    "symbolwiseTable", symbolwiseTable, ...
    "singleSymbolCsvPath", singleCsvPath, ...
    "singleSymbolJsonPath", singleJsonPath, ...
    "symbolwiseCsvPath", symbolwiseCsvPath, ...
    "symbolwiseJsonPath", symbolwiseJsonPath, ...
    "berSweepRun", false);
end

function cases = validation_cases(geometry)
scenario = [ ...
    "high_shift"; ...
    "high_rate"; ...
    "high_shift"; ...
    "high_rate"];
sf = [7; 7; 12; 12];
symbol = 2.^(sf-1);
startTimeSec = [ ...
    geometry.highShiftTimeSec; ...
    geometry.highRateTimeSec; ...
    geometry.highShiftTimeSec; ...
    geometry.highRateTimeSec];
cases = table(scenario, sf, symbol, startTimeSec);
end

function outputTable = run_single_symbol_cases( ...
        cases, geometry, bandwidthHz, tolerances, ...
        outputDirectory, figureVisible)
caseCount = height(cases);
meanAbsErrorHz = zeros(caseCount, 1);
maxAbsErrorHz = zeros(caseCount, 1);
rmseHz = zeros(caseCount, 1);
phaseRmseRad = zeros(caseCount, 1);
vdExactHz = zeros(caseCount, 1);
cdExactHzPerSec = zeros(caseCount, 1);
paperPrintedBvOverCHz = zeros(caseCount, 1);
appliedDeltaFkHz = zeros(caseCount, 1);
fftRelativeDifference = zeros(caseCount, 1);
exactDetectedBin = zeros(caseCount, 1);
linearDetectedBin = zeros(caseCount, 1);

for caseIndex = 1:caseCount
    sf = cases.sf(caseIndex);
    symbol = uint32(cases.symbol(caseIndex));
    result = lora_doppler_piecewise_linear( ...
        symbol, sf, cases.startTimeSec(caseIndex), ...
        geometry.configA, BandwidthHz=bandwidthHz);
    [fftDifference, exactBin, linearBin] = ...
        waveform_fft_diagnostics(result, symbol, sf);
    assert_single_symbol_tolerances( ...
        result, fftDifference, exactBin, linearBin, ...
        tolerances, cases.scenario(caseIndex), sf, 0);

    meanAbsErrorHz(caseIndex) = result.meanAbsErrorHz;
    maxAbsErrorHz(caseIndex) = result.maxAbsErrorHz;
    rmseHz(caseIndex) = result.rmseHz;
    phaseRmseRad(caseIndex) = result.phaseRmseRad;
    vdExactHz(caseIndex) = result.vdHz;
    cdExactHzPerSec(caseIndex) = result.cdHzPerSec;
    paperPrintedBvOverCHz(caseIndex) = ...
        result.paperPrintedBvOverCHz;
    appliedDeltaFkHz(caseIndex) = result.appliedDeltaFkHz;
    fftRelativeDifference(caseIndex) = fftDifference;
    exactDetectedBin(caseIndex) = double(exactBin);
    linearDetectedBin(caseIndex) = double(linearBin);

    plot_single_symbol_result( ...
        result, cases.scenario(caseIndex), sf, ...
        outputDirectory, figureVisible);
end

outputTable = table( ...
    cases.scenario, ...
    cases.sf, ...
    cases.symbol, ...
    cases.startTimeSec, ...
    vdExactHz, ...
    cdExactHzPerSec, ...
    paperPrintedBvOverCHz, ...
    appliedDeltaFkHz, ...
    meanAbsErrorHz, ...
    maxAbsErrorHz, ...
    rmseHz, ...
    phaseRmseRad, ...
    fftRelativeDifference, ...
    exactDetectedBin, ...
    linearDetectedBin, ...
    VariableNames=[ ...
        "scenario", ...
        "sf", ...
        "symbol", ...
        "start_time_s", ...
        "vd_exact_hz", ...
        "cd_exact_hz_per_s", ...
        "paper_printed_Bv_over_c_hz", ...
        "applied_delta_f_k_hz", ...
        "mean_abs_error_hz", ...
        "max_abs_error_hz", ...
        "rmse_hz", ...
        "phase_rmse_rad", ...
        "fft_relative_difference", ...
        "exact_detected_peak_bin", ...
        "linear_detected_peak_bin"]);
end

function outputTable = run_symbolwise_cases( ...
        cases, geometry, bandwidthHz, symbolCount, tolerances, ...
        outputDirectory, figureVisible)
rowCount = height(cases)*symbolCount;
scenario = strings(rowCount, 1);
sfColumn = zeros(rowCount, 1);
symbolColumn = zeros(rowCount, 1);
symbolIndexColumn = zeros(rowCount, 1);
symbolStartTimeSec = zeros(rowCount, 1);
vdExactHz = zeros(rowCount, 1);
cdExactHzPerSec = zeros(rowCount, 1);
carrierDopplerRateHzPerSec = zeros(rowCount, 1);
paperPrintedBvOverCHz = zeros(rowCount, 1);
appliedDeltaFkHz = zeros(rowCount, 1);
meanAbsErrorHz = zeros(rowCount, 1);
maxAbsErrorHz = zeros(rowCount, 1);
rmseHz = zeros(rowCount, 1);
phaseRmseRad = zeros(rowCount, 1);
exactDetectedBin = zeros(rowCount, 1);
linearDetectedBin = zeros(rowCount, 1);

rowIndex = 0;
for caseIndex = 1:height(cases)
    sf = cases.sf(caseIndex);
    symbol = uint32(cases.symbol(caseIndex));
    symbolPeriodSec = 2^sf/bandwidthHz;
    caseFirstRow = rowIndex + 1;

    for symbolIndex = 0:symbolCount-1
        rowIndex = rowIndex + 1;
        startTimeSec = cases.startTimeSec(caseIndex) + ...
            symbolIndex*symbolPeriodSec;
        result = lora_doppler_piecewise_linear( ...
            symbol, sf, startTimeSec, geometry.configA, ...
            BandwidthHz=bandwidthHz);
        [fftDifference, exactBin, linearBin] = ...
            waveform_fft_diagnostics(result, symbol, sf);
        assert_single_symbol_tolerances( ...
            result, fftDifference, exactBin, linearBin, ...
            tolerances, cases.scenario(caseIndex), ...
            sf, symbolIndex);
        orbitStart = lora_orbit_doppler_trajectory( ...
            startTimeSec, geometry.configA);

        scenario(rowIndex) = cases.scenario(caseIndex);
        sfColumn(rowIndex) = sf;
        symbolColumn(rowIndex) = double(symbol);
        symbolIndexColumn(rowIndex) = symbolIndex;
        symbolStartTimeSec(rowIndex) = startTimeSec;
        vdExactHz(rowIndex) = result.vdHz;
        cdExactHzPerSec(rowIndex) = result.cdHzPerSec;
        carrierDopplerRateHzPerSec(rowIndex) = ...
            orbitStart.dopplerRateHzPerSec;
        paperPrintedBvOverCHz(rowIndex) = ...
            result.paperPrintedBvOverCHz;
        appliedDeltaFkHz(rowIndex) = result.appliedDeltaFkHz;
        meanAbsErrorHz(rowIndex) = result.meanAbsErrorHz;
        maxAbsErrorHz(rowIndex) = result.maxAbsErrorHz;
        rmseHz(rowIndex) = result.rmseHz;
        phaseRmseRad(rowIndex) = result.phaseRmseRad;
        exactDetectedBin(rowIndex) = double(exactBin);
        linearDetectedBin(rowIndex) = double(linearBin);
    end

    caseLastRow = rowIndex;
    caseRows = caseFirstRow:caseLastRow;
    assert_symbolwise_continuity( ...
        vdExactHz(caseRows), ...
        cdExactHzPerSec(caseRows), ...
        appliedDeltaFkHz(caseRows), ...
        carrierDopplerRateHzPerSec(caseRows), ...
        symbolPeriodSec, tolerances, ...
        cases.scenario(caseIndex), sf);
end

outputTable = table( ...
    scenario, ...
    sfColumn, ...
    symbolColumn, ...
    symbolIndexColumn, ...
    symbolStartTimeSec, ...
    vdExactHz, ...
    cdExactHzPerSec, ...
    carrierDopplerRateHzPerSec, ...
    paperPrintedBvOverCHz, ...
    appliedDeltaFkHz, ...
    meanAbsErrorHz, ...
    maxAbsErrorHz, ...
    rmseHz, ...
    phaseRmseRad, ...
    exactDetectedBin, ...
    linearDetectedBin, ...
    VariableNames=[ ...
        "scenario", ...
        "sf", ...
        "symbol", ...
        "symbol_index", ...
        "symbol_start_time_s", ...
        "vd_exact_hz", ...
        "cd_exact_hz_per_s", ...
        "carrier_doppler_rate_hz_per_s", ...
        "paper_printed_Bv_over_c_hz", ...
        "applied_delta_f_k_hz", ...
        "mean_abs_error_hz", ...
        "max_abs_error_hz", ...
        "rmse_hz", ...
        "phase_rmse_rad", ...
        "exact_detected_peak_bin", ...
        "linear_detected_peak_bin"]);

for caseIndex = 1:height(cases)
    rows = outputTable.scenario == cases.scenario(caseIndex) & ...
        outputTable.sf == cases.sf(caseIndex);
    plot_symbolwise_drift( ...
        outputTable(rows, :), cases.scenario(caseIndex), ...
        cases.sf(caseIndex), outputDirectory, figureVisible);
    plot_symbolwise_error( ...
        outputTable(rows, :), cases.scenario(caseIndex), ...
        cases.sf(caseIndex), outputDirectory, figureVisible);
end
end

function [relativeDifference, exactBin, linearBin] = ...
        waveform_fft_diagnostics(result, symbol, sf)
tx = lora_css_modulate(symbol, sf);
exactRx = tx.*exp(1i*result.exactPhaseRad);
linearRx = tx.*exp(1i*result.linearPhaseRad);
exactBin = lora_css_demodulate(exactRx, sf);
linearBin = lora_css_demodulate(linearRx, sf);

m = 2^sf;
sampleIndex = (0:m-1).';
baseUpChirp = exp(1i*2*pi*( ...
    sampleIndex.^2/(2*m) - sampleIndex/2));
exactFft = fft(exactRx.*conj(baseUpChirp), m, 1);
linearFft = fft(linearRx.*conj(baseUpChirp), m, 1);
relativeDifference = norm(exactFft - linearFft)/norm(exactFft);
end

function assert_single_symbol_tolerances( ...
        result, fftDifference, exactBin, linearBin, ...
        tolerances, scenario, sf, symbolIndex)
diagnostic = sprintf( ...
    "scenario=%s, SF=%d, symbol_index=%d", ...
    scenario, sf, symbolIndex);
if result.meanAbsErrorHz > tolerances.meanAbsErrorHz || ...
        result.maxAbsErrorHz > tolerances.maxAbsErrorHz || ...
        result.rmseHz > tolerances.rmseHz || ...
        result.phaseRmseRad > tolerances.phaseRmseRad || ...
        fftDifference > tolerances.fftRelativeDifference || ...
        exactBin ~= linearBin
    message = "Doppler approximation exceeded tolerance: %s; " + ...
        "mean=%g Hz, max=%g Hz, rmse=%g Hz, phase=%g rad, " + ...
        "fft=%g, bins=%d/%d.";
    error("lora:ApproximationToleranceExceeded", message, ...
        diagnostic, result.meanAbsErrorHz, ...
        result.maxAbsErrorHz, result.rmseHz, ...
        result.phaseRmseRad, fftDifference, ...
        exactBin, linearBin);
end
end

function assert_symbolwise_continuity( ...
        vdHz, cdHzPerSec, appliedDeltaFkHz, ...
        carrierRateHzPerSec, symbolPeriodSec, tolerances, ...
        scenario, sf)
if numel(vdHz) < 2
    return
end

expectedVdStepHz = 0.5*( ...
    carrierRateHzPerSec(1:end-1) + ...
    carrierRateHzPerSec(2:end))*symbolPeriodSec;
vdResidualHz = diff(vdHz) - expectedVdStepHz;
[maximumVdResidualHz, vdIndex] = max(abs(vdResidualHz));
if maximumVdResidualHz > tolerances.vdStepHz
    message = "v_d continuity failed: scenario=%s, SF=%d, " + ...
        "symbol_index=%d, residual=%g Hz.";
    error("lora:VdContinuityFailure", message, ...
        scenario, sf, vdIndex-1, maximumVdResidualHz);
end

[maximumCdStep, cdIndex] = max(abs(diff(cdHzPerSec)));
if maximumCdStep > tolerances.cdStepHzPerSec
    message = "c_d continuity failed: scenario=%s, SF=%d, " + ...
        "symbol_index=%d, step=%g Hz/s.";
    error("lora:CdContinuityFailure", message, ...
        scenario, sf, cdIndex-1, maximumCdStep);
end

[maximumDeltaStep, deltaIndex] = max( ...
    abs(diff(appliedDeltaFkHz)));
if maximumDeltaStep > tolerances.deltaFkStepHz
    message = "Delta_f_k continuity failed: scenario=%s, SF=%d, " + ...
        "symbol_index=%d, step=%g Hz.";
    error("lora:DeltaFkContinuityFailure", message, ...
        scenario, sf, deltaIndex-1, maximumDeltaStep);
end
end

function plot_single_symbol_result( ...
        result, scenario, sf, outputDirectory, figureVisible)
figureHandle = figure( ...
    "Visible", figureVisible, ...
    "Color", "white", ...
    "Position", [100, 100, 960, 560]);
cleanupFigure = onCleanup(@() close(figureHandle));

plot(result.timeWithinSymbolSec, result.exactDopplerHz, ...
    "b-", "LineWidth", 1.5);
hold on
markerIndices = approximation_marker_indices( ...
    numel(result.sampleIndex), result.wrapIndex);
plot(result.timeWithinSymbolSec(markerIndices), ...
    result.linearDopplerHz(markerIndices), ...
    "ro", "LineStyle", "none", ...
    "MarkerSize", 4.5, "LineWidth", 0.8);
grid on
xlabel("Time within one symbol period (s)");
ylabel("Doppler shift (Hz)");
title(sprintf( ...
    "Figure 5-like Doppler approximation: %s, SF%d", ...
    strrep(scenario, "_", " "), sf));
legend("Exact sampled-orbit Doppler", ...
    "Paper piecewise-linear approximation", ...
    "Location", "best");

stem = sprintf( ...
    "doppler_approx_figure5_like_%s_sf%d", scenario, sf);
exportgraphics(figureHandle, ...
    fullfile(outputDirectory, stem + ".png"), ...
    "Resolution", 200);
exportgraphics(figureHandle, ...
    fullfile(outputDirectory, stem + ".pdf"), ...
    "ContentType", "vector");
clear cleanupFigure
end

function markerIndices = approximation_marker_indices(m, wrapIndex)
markerStep = max(1, floor(m/80));
markerIndices = (1:markerStep:m).';
wrapNeighborhood = (wrapIndex-2:wrapIndex+2).';
wrapNeighborhood = wrapNeighborhood( ...
    wrapNeighborhood >= 1 & wrapNeighborhood <= m);
markerIndices = unique([markerIndices; wrapNeighborhood; m]);
end

function plot_symbolwise_drift( ...
        data, scenario, sf, outputDirectory, figureVisible)
figureHandle = figure( ...
    "Visible", figureVisible, ...
    "Color", "white", ...
    "Position", [100, 100, 960, 560]);
cleanupFigure = onCleanup(@() close(figureHandle));

yyaxis left
plot(data.symbol_index, data.vd_exact_hz, ...
    "b-o", "LineWidth", 1.2, "MarkerSize", 3.5);
ylabel("v_d exact (Hz)");
yyaxis right
plot(data.symbol_index, data.cd_exact_hz_per_s, ...
    "r-s", "LineWidth", 1.2, "MarkerSize", 3.5);
ylabel("c_d (Hz/s)");
xlabel("Symbol index");
grid on
title(sprintf( ...
    "Symbol-to-symbol Doppler drift: %s, SF%d", ...
    strrep(scenario, "_", " "), sf));
legend("v_d exact", "c_d", "Location", "best");

stem = sprintf( ...
    "doppler_symbol_to_symbol_drift_%s_sf%d.png", ...
    scenario, sf);
exportgraphics(figureHandle, ...
    fullfile(outputDirectory, stem), ...
    "Resolution", 200);
clear cleanupFigure
end

