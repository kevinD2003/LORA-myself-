function tolerances = approximation_tolerances()
tolerances = struct( ...
    "meanAbsErrorHz", 5e-4, ...
    "maxAbsErrorHz", 1e-3, ...
    "rmseHz", 6e-4, ...
    "phaseRmseRad", 2e-5, ...
    "fftRelativeDifference", 1e-4, ...
    "vdStepHz", 1e-4, ...
    "cdStepHzPerSec", 5, ...
    "deltaFkStepHz", 0.01);
end

function metadata = output_metadata( ...
        geometry, bandwidthHz, symbolCount, tolerances)
metadata = struct( ...
    "model", "paper_piecewise_linear_equations_18_to_20", ...
    "exactModel", "full_rf_exact_orbit_sampled", ...
    "bandwidthHz", bandwidthHz, ...
    "symbolCount", symbolCount, ...
    "formulaDerivedSingleDeviceAFirstSec", ...
        geometry.singleDeviceAFirstSec, ...
    "formulaDerivedSharedFirstSec", ...
        geometry.sharedFirstSec, ...
    "formulaDerivedDeltaTimeABSec", ...
        geometry.deltaTimeABSec, ...
    "paperReportedApproximateHighShiftTimeSec", ...
        geometry.paperReportedApproximateHighShiftTimeSec, ...
    "paperReportedApproximateHighRateTimeSec", ...
        geometry.paperReportedApproximateHighRateTimeSec, ...
    "velocityConvention", "range_rate_positive_receding", ...
    "wrapSignConvention", ...
        "applied_delta_f_k_hz_equals_negative_Bv_over_c", ...
    "phaseIntegrationRule", "trapezoidal", ...
    "tolerances", tolerances, ...
    "berSweepRun", false);
end

function write_json(filePath, value)
fileIdentifier = fopen(filePath, "w");
if fileIdentifier == -1
    error("lora:JsonOpenFailure", ...
        "Unable to open JSON file '%s'.", filePath);
end
cleanupFile = onCleanup(@() fclose(fileIdentifier));
fprintf(fileIdentifier, "%s\n", jsonencode(value));
clear cleanupFile
end
