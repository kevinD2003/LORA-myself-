function path=localCasePlot(data,path,titleText)
methods=unique(data.method,'stable');f=figure('Visible','off','Color','w');
for method=1:numel(methods)
    d=sortrows(data(strcmp(data.method,methods{method}),:),'snrDb');
    semilogy(d.snrDb,max(d.ser,0.5./d.symbolCount),'-o','LineWidth',1.4, ...
        'DisplayName',methods{method});hold on
end
grid on;xlabel('SNR (dB)');ylabel('SER');title(titleText);legend('Location','best');
exportgraphics(f,path,'Resolution',220);close(f);
end

function path=localOrbitPlot(data,review,path)
snrs=unique(data.snrDb,'stable');methods=unique(data.method,'stable');
f=figure('Visible','off','Color','w','Position',[100 100 1200 480]);
tiledlayout(f,1,numel(snrs),'TileSpacing','compact');
for si=1:numel(snrs)
