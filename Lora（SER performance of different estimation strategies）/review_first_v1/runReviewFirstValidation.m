function metrics=localPaperShapeMetrics(summary,review)
paper=summary(strcmp(summary.phase,'orbit_preview')& ...
    strcmp(summary.method,'Paper')&abs(summary.snrDb+21.12)<1e-6& ...
    ismember(summary.orbitStartSec,review.paperReferenceOrbitSec),:);
paper=sortrows(paper,'orbitStartSec');
reference=review.paperReferenceMidamblePointSer(:);
u=(log10(reference)-log10(reference(1)))/ ...
    (log10(reference(end))-log10(reference(1)));
c1=paper.ser(paper.orbitStartSec==-366);c2=paper.ser(paper.orbitStartSec==0);
target=10.^(log10(c1)+u*(log10(c2)-log10(c1)));
deviation=log10(max(paper.ser,eps))-log10(max(target,eps));
metrics=struct('orbitStartSec',review.paperReferenceOrbitSec, ...
    'digitizedReferenceSer',reference.','mappedTargetSer',target.', ...
    'measuredPaperSer',paper.ser.','rmseDecade',sqrt(mean(deviation.^2)), ...
    'maxPointDeviationDecade',max(abs(deviation)), ...
    'passesRmse',sqrt(mean(deviation.^2))<=review.paperShapeRmseLimitDecade, ...
    'passesPoint',max(abs(deviation))<=review.paperPointLimitDecade);
end

