function outputs = runReviewFirstValidation(options)
%RUNREVIEWFIRSTVALIDATION Execute G1; optionally execute G2, then stop.

arguments
    options.RunG2 (1,1) logical = false
end

paths = exp1SetupPaths();
config = exp1Config();
parentAudit = exp1ValidateFrozenParent(config);
review = reviewFirstConfig(config);
codeDigest = localCodeDigest();
localG0Audit(paths,config,review,parentAudit,codeDigest);
root = fullfile(paths.resultsRoot,review.resultNamespace);
if ~isfolder(root),mkdir(root);end

cellIndex = 0;
for caseIndex = 1:2
    t0 = [-366 0];
    for snrIndex = 1:numel(review.smokeSnrDb)
        cellIndex = cellIndex+1;
        localRunCell(paths,config,review,parentAudit,codeDigest,'smoke', ...
            t0(caseIndex),review.smokeSnrDb(snrIndex), ...
            review.smokePackets,cellIndex);
    end
end
localAuditSmoke(root,review);
if ~options.RunG2
    outputs = struct('status','G1_SMOKE_PASS','identity',review.identity, ...
        'resultRoot',root,'formalStarted',false);
    return
end

cellIndex = 1000;
for caseIndex = 1:2
    t0 = [-366 0];
    for snrIndex = 1:numel(review.caseSnrDb)
        cellIndex = cellIndex+1;
        localRunCell(paths,config,review,parentAudit,codeDigest,'case_preview', ...
            t0(caseIndex),review.caseSnrDb(snrIndex), ...
            review.reviewPackets,cellIndex);
    end
end
cellIndex = 2000;
for positionIndex = 1:numel(review.orbitPositionsSec)
    for snrIndex = 1:numel(review.orbitSnrDb)
        cellIndex = cellIndex+1;
        localRunCell(paths,config,review,parentAudit,codeDigest,'orbit_preview', ...
            review.orbitPositionsSec(positionIndex), ...
            review.orbitSnrDb(snrIndex),review.reviewPackets,cellIndex);
    end
end
outputs = localAggregate(paths,config,review,parentAudit,codeDigest);
end

function localRunCell(paths,config,review,parentAudit,codeDigest,phase,t0,snrDb,n,cellIndex)
methodNames = {'Huang','Paper','CurrentStage55','ReviewStage55','Ideal'};
cellId = exp1CellId(t0,snrDb);
folder = fullfile(paths.resultsRoot,review.resultNamespace,phase,cellId);
if ~isfolder(folder),mkdir(folder);end
signatureData = struct('identity',review.identity,'receiver', ...
    review.receiverVersion,'phase',phase,'t0',t0,'snrDb',snrDb, ...
    'packets',n,'cellIndex',cellIndex,'codeDigest',codeDigest, ...
    'parentManifest',parentAudit.manifestSha256);
signature = exp1Sha256(jsonencode(signatureData));
finalPath = fullfile(folder,'cell_result.mat');
checkpointPath = fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    loaded = load(finalPath,'result');
    if strcmp(loaded.result.signature,signature),return;end
    error('EXP3:ResultSignature','Result signature mismatch: %s',finalPath);
end
if isfile(checkpointPath)
    loaded = load(checkpointPath,'state','signature');
    if ~strcmp(loaded.signature,signature)
        error('EXP3:CheckpointSignature','Checkpoint signature mismatch.');
    end
    state = loaded.state;
else
    state = localInitialState(n,numel(methodNames),config.parent.payloadSymbolCount);
end
for packetId = state.completed+1:n
    ledger = reviewFirstSeedPlan(config,review, ...
        localSeedPhase(phase),cellIndex,snrDb,packetId);
    frame = exp1GenerateFrame(config,t0,snrDb,ledger);
    base = exp1EvaluatePacket(frame,config,config.methodNames);
    destination = [1 2 3 5];
    for method = 1:4
        column = destination(method);
        state.symbolErrors(packetId,column) = base.symbolErrors(method);
        state.hardBitErrors(packetId,column) = base.hardBitErrors(method);
        state.mlBitErrors(packetId,column) = base.mlBitErrors(method);
        state.symbolErrorMask(packetId,column,:) = reshape( ...
            base.symbolErrorMask(method,:),1,1,[]);
        state.cfoResidualBins(packetId,column,:) = reshape( ...
            base.cfoResidualBins(method,:),1,1,[]);
        state.acceptedVp(packetId,column) = base.acceptedVp(method);
        state.falseVp(packetId,column) = base.falseVp(method);
        state.failed(packetId,column) = base.failed(method);
    end
    parameters = v4LoadMethodAlignedR3ParametersV1();
    common = v4CommonBootstrap(frame.observation.rxPhysical(1:8,:), ...
        config.parent,SearchStepBins=parameters.searchStepBins);
    try
        candidate = reviewFirstStage55Decode(frame.observation,common,config,review);
        symbolMask = candidate.detectedPhysicalBins(:) ~= ...
            frame.truth.payloadPhysicalBins(:);
        hardMask = candidate.hardDecodedDataBits(:) ~= frame.truth.dataBits(:);
        mlMask = candidate.softDecodedDataBits(:) ~= frame.truth.dataBits(:);
        residual = candidate.estimatedCfoBins(:)-frame.truth.dataCfoBins(:);
        accepted = logical(candidate.monitor.vpAccepted(:));
        vpFalse = accepted & (candidate.dynamicHypothesis.tracker.hardPhysicalBins(:) ~= ...
            frame.truth.payloadPhysicalBins(:));
        state.symbolErrors(packetId,4) = uint16(sum(symbolMask));
        state.hardBitErrors(packetId,4) = uint16(sum(hardMask));
        state.mlBitErrors(packetId,4) = uint16(sum(mlMask));
        state.symbolErrorMask(packetId,4,:) = reshape(symbolMask,1,1,[]);
        state.cfoResidualBins(packetId,4,:) = reshape(single(residual),1,1,[]);
        state.acceptedVp(packetId,4) = uint16(sum(accepted));
        state.falseVp(packetId,4) = uint16(sum(vpFalse));
        state.monitorAppliedCfo(packetId,:) = candidate.monitor.appliedCompensationBins;
        state.monitorSymbolIndex(packetId,:) = candidate.monitor.symbolIndex;
        state.monitorAbsoluteTime(packetId,:) = ...
            t0+candidate.monitor.absoluteTimeSec;
        state.monitorPredictedRate(packetId,:) = candidate.monitor.predictedRateBinsPerSec;
        state.monitorRateUncertainty(packetId,:) = candidate.monitor.rateUncertainty;
        state.monitorStaticLikelihood(packetId,:) = candidate.monitor.staticLikelihood;
        state.monitorDynamicLikelihood(packetId,:) = candidate.monitor.dynamicLikelihood;
        state.monitorSelectedDynamic(packetId,:) = candidate.monitor.selectedHypothesis;
        state.monitorDecisionPeakRatio(packetId,:) = candidate.monitor.decisionPeakRatio;
        state.monitorVpCandidate(packetId,:) = candidate.monitor.vpCandidate;
        state.monitorVpAccepted(packetId,:) = accepted;
        state.monitorVpFalse(packetId,:) = vpFalse;
        state.monitorInnovation(packetId,:) = candidate.monitor.innovationBins;
        state.monitorInnovationAccepted(packetId,:) = candidate.monitor.innovationAccepted;
        state.monitorPhasePair(packetId,:) = candidate.monitor.phasePairUsed;
        state.monitorHistoryCount(packetId,:) = candidate.monitor.historyCount;
        state.monitorRollback(packetId,:) = candidate.monitor.rollbackTriggered;
        state.monitorHardError(packetId,:) = symbolMask;
        state.dynamicSelectedRatio(packetId) = candidate.dynamicSelectedRatio;
        state.rollbackCount(packetId) = candidate.rollbackCount;
        state.rateEvidenceCount(packetId) = ...
            candidate.dynamicHypothesis.tracker.virtualPilotRateEvidenceCount;
        state.packetDecisionReason{packetId} = candidate.packetDecision.reason;
        state.packetLikelihoodGainPerSymbol(packetId) = ...
            candidate.packetDecision.packetLikelihoodGainPerSymbol;
        state.packetStrongEvidence(packetId) = ...
            candidate.packetDecision.strongPreambleEvidence;
        state.packetModerateEvidence(packetId) = ...
            candidate.packetDecision.moderatePreambleEvidence;
        state.packetPayloadEvidence(packetId) = ...
            candidate.packetDecision.payloadEvidence;
        state.packetCompleteReplay(packetId) = ...
            candidate.packetDecision.completePayloadReplay;
        state.packetMixedCodeBlocks(packetId) = ...
            candidate.packetDecision.mixedCodeBlocks;
    catch exception
        state.symbolErrors(packetId,4) = uint16(config.parent.payloadSymbolCount);
        state.hardBitErrors(packetId,4) = uint16(config.parent.informationBitCount);
        state.mlBitErrors(packetId,4) = uint16(config.parent.informationBitCount);
        state.symbolErrorMask(packetId,4,:) = true;
        state.failed(packetId,4) = true;
        state.failureMessage{packetId} = sprintf('%s: %s', ...
            exception.identifier,exception.message);
    end
    state.monitorTrueCfo(packetId,:) = frame.truth.dataCfoBins;
    state.monitorResidual(packetId,:) = reshape( ...
        state.cfoResidualBins(packetId,4,:),1,[]);
    state.fingerprint(packetId,:) = frame.observation.sampleFingerprint;
    state.ledgerHash{packetId} = ledger.ledgerHash;
    state.payloadSeed(packetId) = ledger.payloadSeed;
    state.noiseSeed(packetId) = ledger.noiseSeed;
    state.channelSeed(packetId) = ledger.channelSeed;
    state.completed = packetId;
    if mod(packetId,5)==0 || packetId==n
        localAtomicSave(checkpointPath,state,signature);
        fprintf('EXP3 %s %s: %d/%d packets\n',phase,cellId,packetId,n);
    end
end
result = struct('status','COMPLETE','identity',review.identity, ...
    'receiverVersion',review.receiverVersion,'phase',phase, ...
    'signature',signature,'cellId',cellId,'t0',t0,'snrDb',snrDb, ...
    'packetCount',n,'methodNames',{methodNames}, ...
    'symbolErrors',state.symbolErrors,'hardBitErrors',state.hardBitErrors, ...
    'mlBitErrors',state.mlBitErrors,'symbolErrorMask',state.symbolErrorMask, ...
    'cfoResidualBins',state.cfoResidualBins, ...
    'acceptedVp',state.acceptedVp,'falseVp',state.falseVp, ...
    'failed',state.failed,'failureMessage',{state.failureMessage}, ...
    'dynamicSelectedRatio',state.dynamicSelectedRatio, ...
    'rollbackCount',state.rollbackCount,'rateEvidenceCount',state.rateEvidenceCount, ...
    'packetDecisionReason',{state.packetDecisionReason}, ...
    'packetLikelihoodGainPerSymbol',state.packetLikelihoodGainPerSymbol, ...
    'packetStrongEvidence',state.packetStrongEvidence, ...
    'packetModerateEvidence',state.packetModerateEvidence, ...
    'packetPayloadEvidence',state.packetPayloadEvidence, ...
    'packetCompleteReplay',state.packetCompleteReplay, ...
    'packetMixedCodeBlocks',state.packetMixedCodeBlocks, ...
    'monitorAppliedCfo',state.monitorAppliedCfo,'monitorTrueCfo',state.monitorTrueCfo, ...
    'monitorSymbolIndex',state.monitorSymbolIndex, ...
    'monitorAbsoluteTime',state.monitorAbsoluteTime, ...
    'monitorResidual',state.monitorResidual, ...
    'monitorPredictedRate',state.monitorPredictedRate, ...
    'monitorRateUncertainty',state.monitorRateUncertainty, ...
    'monitorStaticLikelihood',state.monitorStaticLikelihood, ...
    'monitorDynamicLikelihood',state.monitorDynamicLikelihood, ...
    'monitorSelectedDynamic',state.monitorSelectedDynamic, ...
    'monitorDecisionPeakRatio',state.monitorDecisionPeakRatio, ...
    'monitorVpCandidate',state.monitorVpCandidate, ...
    'monitorVpAccepted',state.monitorVpAccepted, ...
    'monitorVpFalse',state.monitorVpFalse, ...
    'monitorInnovation',state.monitorInnovation, ...
    'monitorInnovationAccepted',state.monitorInnovationAccepted, ...
    'monitorPhasePair',state.monitorPhasePair, ...
    'monitorHistoryCount',state.monitorHistoryCount, ...
    'monitorRollback',state.monitorRollback, ...
    'monitorHardError',state.monitorHardError, ...
    'fingerprint',state.fingerprint,'ledgerHash',{state.ledgerHash}, ...
    'payloadSeed',state.payloadSeed,'noiseSeed',state.noiseSeed, ...
    'channelSeed',state.channelSeed, ...
    'usesPayloadTruthInReceiver',false,'usesOrbitTruthInReceiver',false);
localAtomicResult(finalPath,result);
end

