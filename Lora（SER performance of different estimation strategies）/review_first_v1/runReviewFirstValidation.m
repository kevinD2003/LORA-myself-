function localAuditSmoke(root,review)
files = dir(fullfile(root,'smoke','orbit_*','cell_result.mat'));
if numel(files)~=6,error('EXP3:SmokeCells','Expected six smoke cells.');end
for index = 1:numel(files)
    x=load(fullfile(files(index).folder,files(index).name),'result');r=x.result;
    if any(r.failed,'all') || size(r.monitorAppliedCfo,2)~=112
        error('EXP3:SmokeFailure','Smoke failed in %s.',r.cellId);
    end
    selected = logical(r.monitorSelectedDynamic);
    if any(selected~=selected(:,1),'all') || ...
            any(r.packetMixedCodeBlocks) || ~all(r.packetCompleteReplay)
        error('EXP3:MixedPayload','A smoke payload mixed hypotheses.');
    end
    expectedDynamic = r.t0==0;
    if any(selected(:,1)~=expectedDynamic)
        error('EXP3:EndpointSelection', ...
            'Endpoint packet selection was not uniform in %s.',r.cellId);
    end
    if ~isequal(r.symbolErrorMask(:,3,:),r.symbolErrorMask(:,4,:))
        error('EXP3:EndpointReplay', ...
            'Packet replay did not reproduce Current Stage55 in %s.',r.cellId);
    end
end
file=fullfile(root,'SMOKE_PASS.txt');
fid=fopen(file,'w');cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'PASS %s smokePackets=%d\n',review.identity,review.smokePackets);
clear cleanup
end

function outputs = localAggregate(paths,config,review,parentAudit,codeDigest)
root=fullfile(paths.resultsRoot,review.resultNamespace);
files=[dir(fullfile(root,'case_preview','orbit_*','cell_result.mat')); ...
    dir(fullfile(root,'orbit_preview','orbit_*','cell_result.mat'))];
rows={};vpRows={};symbolRows={};monitorRows={};deltaRows={}; ...
    rr=0;vr=0;sr=0;mr=0;dr=0;
for index=1:numel(files)
    x=load(fullfile(files(index).folder,files(index).name),'result');r=x.result;
    packetSer=double(r.symbolErrors)/config.parent.payloadSymbolCount;
    for method=1:numel(r.methodNames)
        rr=rr+1;
        rows(rr,:)={r.phase,r.cellId,r.t0,r.snrDb,r.methodNames{method}, ...
            r.packetCount,sum(double(r.symbolErrors(:,method))), ...
            r.packetCount*config.parent.payloadSymbolCount, ...
            mean(packetSer(:,method)),sum(r.failed(:,method)),r.signature}; %#ok<AGROW>
        residual=reshape(double(r.cfoResidualBins(:,method,:)), ...
            r.packetCount,config.parent.payloadSymbolCount);
        errors=reshape(double(r.symbolErrorMask(:,method,:)), ...
            r.packetCount,config.parent.payloadSymbolCount);
        for data=1:config.parent.payloadSymbolCount
            sr=sr+1;symbolRows(sr,:)={r.phase,r.t0,r.snrDb, ...
                r.methodNames{method},data,mean(errors(:,data)), ...
                sqrt(mean(residual(:,data).^2))*config.parent.fftBinSpacingHz}; %#ok<AGROW>
        end
    end
    accepted=double(r.monitorVpAccepted);falseVp=double(r.monitorVpFalse);
    first=nan(r.packetCount,1);gap=nan(r.packetCount,1);
    for packet=1:r.packetCount
        idx=find(accepted(packet,:));
        if ~isempty(idx),first(packet)=idx(1);gap(packet)=max(diff([0 idx 113]));end
    end
    vr=vr+1;vpRows(vr,:)={r.phase,r.cellId,r.t0,r.snrDb,r.packetCount, ...
        sum(r.monitorVpCandidate,'all'),sum(accepted,'all'),sum(falseVp,'all'), ...
        sum(falseVp,'all')/max(sum(accepted,'all'),1),mean(first,'omitnan'), ...
        max(gap,[],'omitnan'),sum(r.rateEvidenceCount),sum(r.rollbackCount), ...
        mean(r.dynamicSelectedRatio),sum(r.packetStrongEvidence), ...
        sum(r.packetModerateEvidence),sum(r.packetPayloadEvidence), ...
        mean(r.packetLikelihoodGainPerSymbol,'omitnan'), ...
        sum(r.failed(:,4))}; %#ok<AGROW>
    comparisons={2,4,'Paper-minus-ReviewStage55'; ...
        3,4,'Current-minus-ReviewStage55'};
    for comparison=1:size(comparisons,1)
        [difference,ci]=exp1PairedDifferenceCI( ...
            packetSer(:,comparisons{comparison,1}), ...
            packetSer(:,comparisons{comparison,2}),10000, ...
            991000000+index*10+comparison);
        dr=dr+1;deltaRows(dr,:)={r.phase,r.cellId,r.t0,r.snrDb, ...
            comparisons{comparison,3},r.packetCount,difference,ci(1),ci(2)}; %#ok<AGROW>
    end
    for packet=1:r.packetCount
        for data=1:config.parent.payloadSymbolCount
            mr=mr+1;
            monitorRows(mr,:)={r.phase,r.cellId,r.t0,r.snrDb,packet, ...
                r.monitorSymbolIndex(packet,data), ...
                r.monitorAbsoluteTime(packet,data), ...
                r.monitorTrueCfo(packet,data), ...
                r.monitorAppliedCfo(packet,data), ...
                r.monitorResidual(packet,data), ...
                r.monitorPredictedRate(packet,data), ...
                r.monitorRateUncertainty(packet,data), ...
                r.monitorStaticLikelihood(packet,data), ...
                r.monitorDynamicLikelihood(packet,data), ...
                r.monitorSelectedDynamic(packet,data), ...
                r.monitorDecisionPeakRatio(packet,data), ...
                r.monitorVpCandidate(packet,data), ...
                r.monitorVpAccepted(packet,data), ...
                r.monitorVpFalse(packet,data), ...
                r.monitorInnovation(packet,data), ...
                r.monitorInnovationAccepted(packet,data), ...
                r.monitorPhasePair(packet,data), ...
                r.monitorHistoryCount(packet,data), ...
                r.monitorRollback(packet,data), ...
                r.monitorHardError(packet,data)}; %#ok<AGROW>
        end
    end
end
summary=cell2table(rows,'VariableNames',{'phase','cellId','orbitStartSec', ...
    'snrDb','method','packets','symbolErrors','symbolCount','ser', ...
    'failedPackets','cellSignature'});
vp=cell2table(vpRows,'VariableNames',{'phase','cellId','orbitStartSec', ...
    'snrDb','packets','vpCandidates','acceptedVp','falseVp','falseVpRate', ...
    'meanFirstAcceptedVp','maximumVpGap','rateEvidenceCount','rollbackCount', ...
    'dynamicSelectedRatio','strongPreamblePackets', ...
    'moderatePreamblePackets','payloadEvidencePackets', ...
    'meanPacketLikelihoodGainPerSymbol','failedPackets'});
symbol=cell2table(symbolRows,'VariableNames',{'phase','orbitStartSec','snrDb', ...
    'method','dataSymbolIndex','ser','cfoRmseHz'});
delta=cell2table(deltaRows,'VariableNames',{'phase','cellId','orbitStartSec', ...
    'snrDb','comparison','packets','deltaSer','ciLow','ciHigh'});
monitor=cell2table(monitorRows,'VariableNames',{'phase','cellId', ...
    'orbitStartSec','snrDb','packetId','symbolIndex','absoluteTimeSec', ...
    'trueCfoBins','appliedCompensationBins','residualCfoBins', ...
    'predictedRateBinsPerSec','rateUncertainty','staticLikelihood', ...
    'dynamicLikelihood','selectedHypothesis','decisionPeakRatio', ...
    'vpCandidate','vpAccepted','vpFalse','innovationBins', ...
    'innovationAccepted','phasePairUsed','historyCount', ...
    'rollbackTriggered','hardSymbolError'});
out=fullfile(root,'review_outputs');if ~isfolder(out),mkdir(out);end
summaryPath=fullfile(out,'REVIEW_VALIDATION_SUMMARY.csv');
vpPath=fullfile(out,'REVIEW_VP_DIAGNOSTICS.csv');
symbolPath=fullfile(out,'REVIEW_SYMBOL_MONITOR.csv');
deltaPath=fullfile(out,'REVIEW_PAIRED_DIFFERENCES.csv');
monitorPath=fullfile(out,'REVIEW_SYMBOL_STATE.csv');
writetable(summary,summaryPath);writetable(vp,vpPath);writetable(symbol,symbolPath);
writetable(delta,deltaPath);
writetable(monitor,monitorPath);
paperShape=localPaperShapeMetrics(summary,review);
configPath=fullfile(out,'REVIEW_CONFIG_AND_SEEDS.json');
configIdentity=struct('experimentId',config.experimentId, ...
    'sf',config.parent.physicalSf,'bandwidthHz',config.parent.bandwidthHz, ...
    'sampleRateHz',config.parent.sampleRateHz,'cr',config.parent.cr, ...
    'payloadSymbols',config.parent.payloadSymbolCount, ...
    'commonTimelineSymbols',config.parent.commonTimelineSymbolCount, ...
    'review',review);
configHash=exp1Sha256(jsonencode(configIdentity));
seedRanges=struct('gateCalibrationRoot',review.calibrationRootSeed, ...
    'vpCalibrationRoot',review.vpCalibrationRootSeed, ...
    'smokeRoot',review.smokeRootSeed,'reviewRoot',review.reviewRootSeed, ...
    'formalRootReserved',review.formalRootSeed, ...
    'refinementRootReserved',review.refinementRootSeed, ...
    'smokePacketIds',[1 review.smokePackets], ...
    'reviewPacketIds',[1 review.reviewPackets]);
metadata=struct('identity',review.identity,'receiver',review.receiverVersion, ...
    'parentManifestSha256',parentAudit.manifestSha256,'codeDigest',codeDigest, ...
    'configHash',configHash,'seedRanges',seedRanges, ...
    'review',review,'paperShape',paperShape, ...
    'formalStarted',false,'status','AWAITING_USER_REVIEW');
localWriteText(configPath,jsonencode(metadata,'PrettyPrint',true));
figures=localPlots(root,out,summary,symbol,review,config);
gatePath=fullfile(out,'USER_REVIEW_GATE.md');
localReviewGate(gatePath,summary,vp,delta,symbol,paperShape,review, ...
    parentAudit,codeDigest,configHash,seedRanges,figures);
outputs=struct('status','AWAITING_USER_REVIEW','summaryPath',summaryPath, ...
    'vpPath',vpPath,'symbolPath',symbolPath,'deltaPath',deltaPath, ...
    'monitorPath',monitorPath, ...
    'configPath',configPath, ...
    'gatePath',gatePath,'figures',figures);
end

