function result = reviewFirstStage55Decode(observation,common,config,review)
%REVIEWFIRSTSTAGE55DECODE Buffer both hypotheses and select one whole payload.

c = config.parent;
pilots = observation.rxPhysical(1:c.bootstrapPilotCount,:);
modeParameters = struct('maximumRateBinsPerSec',20, ...
    'modeLargeToCentralRatio',0.75);
mode = v4Stage55ObservableModeSelectorV10(pilots,c,modeParameters);
parameters = v4BCalibrationCandidates();
parameters = parameters(2);
joint = v4Stage55JointPreambleMlBootstrap(pilots,c, ...
    MaximumRateBinsPerSec=parameters.maximumRateBinsPerSec);
split = reviewEstimateSplitRate(pilots,c,parameters.maximumRateBinsPerSec);
sigmaRate = max(review.rateSigmaFloorBinsPerSec,split.sigmaRateBinsPerSec);
rateLower = max(0,abs(joint.rateBinsPerSec)- ...
    review.rateConfidenceK*sigmaRate);
bootstrap = v4Stage55BootstrapFromJointPreambleMl(common,joint,c);
static = reviewStaticHypothesis(observation,common,c);
dynamic = v4Stage55Decode(observation,bootstrap,c,parameters, ...
    CrossFrameRateBinsPerSec=joint.rateBinsPerSec, ...
    CrossFrameHistoryCount=1);

n = c.payloadSymbolCount;
dynamicRatio = nan(n,1);
for data = 1:n
    likelihood = v4SymbolLikelihood(dynamic.tracker.compensatedData(data,:), ...
        c,common.noisePower);
    dynamicRatio(data) = likelihood.peakRatio;
end
dynamicDecoded = v4DecodePayload(dynamic.tracker.compensatedData,c, ...
    common.noisePower);
[staticLog,dynamicLog,staticBlock,dynamicBlock] = localCodedLikelihood( ...
    static.decoded,dynamicDecoded,c);
packetLikelihoodGain = sum(dynamicBlock-staticBlock);
packetLikelihoodGainPerSymbol = packetLikelihoodGain/n;

candidate = false(n,1);
for iteration = 1:numel(dynamic.iterationHistory)
    candidate = candidate | ...
        logical(dynamic.iterationHistory(iteration).proposedMask(:));
end
accepted = logical(dynamic.virtualPilotAccepted(:));
innovation = nan(n,1);
innovationAccepted = false(n,1);
for data = find(candidate).'
    knownBin = dynamic.tracker.hardPhysicalBins(data);
    residual = v4PhaseRotationEstimate( ...
        dynamic.tracker.compensatedData(data,:),knownBin,c, ...
        parameters.residualSearchBins);
    innovation(data) = residual.offsetBins;
    innovationAccepted(data) = accepted(data) && ...
        abs(residual.offsetBins)<=parameters.innovationLimitBins;
end

layout = observation.layout;
remainingTime = layout.physicalCenterTimeSec(layout.dataRows(end))- ...
    layout.physicalCenterTimeSec(layout.dataRows);
driftLower = rateLower*max(remainingTime,0);
acceptedSoFar = 0;
lastInnovationSign = 0;
vpTrendConsistent = false(n,1);
for data = 1:n
    if accepted(data)
        acceptedSoFar = acceptedSoFar+1;
        currentSign = sign(innovation(data));
        if acceptedSoFar>=2 && currentSign~=0 && currentSign==lastInnovationSign
            vpTrendConsistent(data) = true;
        end
        if currentSign~=0,lastInnovationSign=currentSign;end
    elseif data>1
        vpTrendConsistent(data) = vpTrendConsistent(data-1);
    end
end

splitTolerance = max(review.splitRateConsistencyBinsPerSec, ...
    review.splitRateRelativeTolerance*abs(joint.rateBinsPerSec));
preambleConsistent = split.sameSign && ...
    split.differenceBinsPerSec<=splitTolerance;
strongRateEvidence = abs(joint.rateBinsPerSec)>= ...
    review.strongRateThresholdBinsPerSec;
strongPreambleEvidence = strongRateEvidence && ~mode.staticSelected;
moderatePreambleEvidence = preambleConsistent && rateLower>0 && ...
    max(driftLower)>review.packetDriftThresholdBins;
reliableVpCount = sum(innovationAccepted);
consistentVpCount = sum(innovationAccepted & vpTrendConsistent);
payloadEvidence = packetLikelihoodGainPerSymbol> ...
    review.packetLikelihoodGainPerSymbol && ...
    reliableVpCount>=review.packetMinimumReliableVp && ...
    consistentVpCount>=review.packetMinimumConsistentVp;
packetDynamic = strongPreambleEvidence || ...
    (moderatePreambleEvidence && payloadEvidence);
selectedDynamic = repmat(packetDynamic,n,1);
rollback = false(n,1);
rollback(end) = moderatePreambleEvidence && ~packetDynamic;

if packetDynamic
    decoded = dynamicDecoded;
    appliedCfo = dynamic.estimatedCfoBins(:);
    selectedPeak = dynamicRatio;
    decisionReason = 'strong-preamble-dynamic';
    if ~strongPreambleEvidence
        decisionReason = 'completed-payload-dynamic';
    end
else
    decoded = static.decoded;
    appliedCfo = static.estimatedCfoBins(:);
    selectedPeak = static.peakRatio;
    decisionReason = 'insufficient-evidence-static';
end
historyCount = zeros(n,1);
phasePair = false(n,1);
if isfield(dynamic,'activeHistoryCount')
    historyCount = dynamic.activeHistoryCount(:);
end
if isfield(dynamic,'phasePairUsed')
    phasePair = logical(dynamic.phasePairUsed(:));
end

monitor = struct('symbolIndex',(1:n).', ...
    'absoluteTimeSec',layout.physicalCenterTimeSec(layout.dataRows), ...
    'appliedCompensationBins',appliedCfo, ...
    'predictedRateBinsPerSec',repmat(joint.rateBinsPerSec,n,1), ...
    'rateUncertainty',repmat(sigmaRate,n,1), ...
    'staticLikelihood',staticLog,'dynamicLikelihood',dynamicLog, ...
    'selectedHypothesis',selectedDynamic, ...
    'decisionPeakRatio',selectedPeak,'vpCandidate',candidate, ...
    'vpAccepted',accepted,'innovationBins',innovation, ...
    'innovationAccepted',innovationAccepted, ...
    'phasePairUsed',phasePair,'historyCount',historyCount, ...
    'rollbackTriggered',rollback,'driftLowerBins',driftLower, ...
    'vpTrendConsistent',vpTrendConsistent, ...
    'packetDecisionAvailable',[(false(n-1,1));true], ...
    'packetLikelihoodGainPerSymbol', ...
        repmat(packetLikelihoodGainPerSymbol,n,1), ...
    'preambleConsistent',repmat(preambleConsistent,n,1));
decision = struct('selectedDynamic',packetDynamic,'reason',decisionReason, ...
    'decisionAvailableAfterSymbol',n, ...
    'strongRateEvidence',strongRateEvidence, ...
    'cfoDomainSupportsDynamic',~mode.staticSelected, ...
    'strongPreambleEvidence',strongPreambleEvidence, ...
    'preambleConsistent',preambleConsistent, ...
    'moderatePreambleEvidence',moderatePreambleEvidence, ...
    'payloadEvidence',payloadEvidence, ...
    'packetLikelihoodGain',packetLikelihoodGain, ...
    'packetLikelihoodGainPerSymbol',packetLikelihoodGainPerSymbol, ...
    'reliableVpCount',reliableVpCount, ...
    'consistentVpCount',consistentVpCount, ...
    'completePayloadReplay',true,'mixedCodeBlocks',false);
result = struct('methodName','Stage55-PacketReplay-DualHypothesis', ...
    'methodId','stage55-v19-packet-replay','algorithmVersion', ...
        review.receiverVersion,'detectedPhysicalBins',decoded.hardPhysicalBins, ...
    'hardDecodedDataBits',decoded.hardDataBits, ...
    'softDecodedDataBits',decoded.softDataBits, ...
    'estimatedCfoBins',appliedCfo, ...
    'virtualPilotAccepted',accepted & packetDynamic, ...
    'shadowVirtualPilotAccepted',accepted, ...
    'explicitMidambleAccepted',false(c.paperMidambleCount,1), ...
    'monitor',monitor,'staticHypothesis',static, ...
    'dynamicHypothesis',dynamic,'jointPreambleEstimate',joint, ...
    'splitRateEstimate',split,'modeEvidence',mode, ...
    'rateLowerBinsPerSec',rateLower,'packetDecision',decision, ...
    'dynamicSelectedRatio',mean(selectedDynamic), ...
    'rollbackCount',sum(rollback),'usesPayloadTruth',false, ...
    'usesOrbitTruth',false,'usesCaseIdentity',false,'usesSnrInput',false);
end

function [staticCausal,dynamicCausal,staticBlock,dynamicBlock] = ...
        localCodedLikelihood(static,dynamic,c)
n = c.payloadSymbolCount;
blockSize = c.hammingCodewordLength;
blockCount = c.hammingBlockCount;
staticBlock = zeros(blockCount,1);
dynamicBlock = zeros(blockCount,1);
for block = 1:blockCount
    rows = (block-1)*blockSize+(1:blockSize);
    staticLabels = static.confidenceReencodedPhysicalBins(rows)+1;
    dynamicLabels = dynamic.confidenceReencodedPhysicalBins(rows)+1;
    staticIndex = sub2ind(size(static.symbolLogProbability), ...
        rows(:),staticLabels(:));
    dynamicIndex = sub2ind(size(dynamic.symbolLogProbability), ...
        rows(:),dynamicLabels(:));
    staticBlock(block) = sum(static.symbolLogProbability(staticIndex));
    dynamicBlock(block) = sum(dynamic.symbolLogProbability(dynamicIndex));
end
staticCausal = zeros(n,1);
dynamicCausal = zeros(n,1);
for block = 2:blockCount
    rows = (block-1)*blockSize+(1:blockSize);
    staticCausal(rows) = staticBlock(block-1);
    dynamicCausal(rows) = dynamicBlock(block-1);
end
end
