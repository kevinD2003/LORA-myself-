function output = runSenloraSymmetricV2Review()
%RUNSENLORASYMMETRICV2REVIEW Raw paired full-orbit review; no fitting.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
plan = senloraSymmetricV2Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
negative = plan.negativeOrbitStartSec;
n = plan.reviewPackets;
perSideCount = n*config.parent.payloadSymbolCount;
errors = zeros(numel(negative),2,n,'uint16');
parentErrors = zeros(numel(negative),2,n,'uint16');
branches = zeros(numel(negative),2,n,'uint8');
failed = false(numel(negative),2,n);
case1Exact = true(n,1);
loboVerified = true;
for pairIndex = 1:numel(negative)
    starts = [negative(pairIndex), ...
        -negative(pairIndex)-plan.frameDurationSec];
    for packetId = 1:n
        ledger = senloraSymmetricV2SeedPlan(config,plan,'review', ...
            pairIndex,plan.snrDb,packetId);
        for side = 1:2
            frame = exp1GenerateFrame(config,starts(side),plan.snrDb,ledger);
            common = v4CommonBootstrap( ...
                frame.observation.rxPhysical(1:8,:),config.parent, ...
                SearchStepBins=parameters.searchStepBins);
            parent = exp1Stage55Decode(frame.observation,common,config,true);
            parentErrors(pairIndex,side,packetId) = uint16(sum( ...
                parent.detectedPhysicalBins(:)~= ...
                frame.truth.payloadPhysicalBins(:)));
            try
                result = senloraSymmetricV2Decode( ...
                    frame.observation,common,config,plan);
                errors(pairIndex,side,packetId) = uint16(sum( ...
                    result.detectedPhysicalBins(:)~= ...
                    frame.truth.payloadPhysicalBins(:)));
                branches(pairIndex,side,packetId) = uint8( ...
                    result.decision.selectedBranch);
                loboVerified = loboVerified && ...
                    result.decision.leaveOneBlockOut && ...
                    ~result.decision.selfBlockUsedForFit;
                if pairIndex==1 && side==1
                    case1Exact(packetId) = isequal( ...
                        result.detectedPhysicalBins(:), ...
                        parent.detectedPhysicalBins(:));
                end
            catch exception
                failed(pairIndex,side,packetId) = true;
                errors(pairIndex,side,packetId) = ...
                    uint16(config.parent.payloadSymbolCount);
                warning('EXP5V2:ReviewFailure','%s',exception.message);
            end
        end
        if mod(packetId,5)==0
            fprintf('EXP5V2 review pair=%d/%d packet=%d/%d\n', ...
                pairIndex,numel(negative),packetId,n);
        end
    end
end

candidateSer = sum(double(errors),3)/perSideCount;
parentSer = sum(double(parentErrors),3)/perSideCount;
target = arrayfun(@(t)localUpperTarget(t,plan),negative).';
pooledErrors = squeeze(sum(double(errors),[2 3]));
pooledCount = 2*perSideCount;
pooledSer = pooledErrors/pooledCount;
rows = cell(numel(negative),22);
for row = 1:numel(negative)
    negativeErrors = sum(double(errors(row,1,:)),'all');
    positiveErrors = sum(double(errors(row,2,:)),'all');
    [negativeLower,negativeUpper] = localWilson(negativeErrors,perSideCount);
    [positiveLower,positiveUpper] = localWilson(positiveErrors,perSideCount);
    [pooledLower,pooledUpper] = localWilson(pooledErrors(row),pooledCount);
    negativeBranches = squeeze(branches(row,1,:));
    positiveBranches = squeeze(branches(row,2,:));
    rows(row,:) = {negative(row),-negative(row)-plan.frameDurationSec, ...
        plan.snrDb,n,candidateSer(row,1),candidateSer(row,2), ...
        negativeLower,negativeUpper,positiveLower,positiveUpper, ...
        pooledErrors(row),pooledSer(row),pooledLower,pooledUpper,target(row), ...
        negativeLower<=positiveUpper && positiveLower<=negativeUpper, ...
        sum(negativeBranches==1),sum(negativeBranches==2), ...
        sum(negativeBranches==3),sum(negativeBranches==4), ...
        sum(positiveBranches==1),sum(positiveBranches==2)};
end
summary = cell2table(rows,'VariableNames',{'negativeOrbitStartSec', ...
    'positiveMirrorStartSec','snrDb','packets','negativeSer','positiveSer', ...
    'negativeWilsonLower95','negativeWilsonUpper95', ...
    'positiveWilsonLower95','positiveWilsonUpper95','pooledRawErrors', ...
    'pooledRawSer','pooledWilsonLower95','pooledWilsonUpper95', ...
    'upperTargetSer','mirrorWilsonIntervalsOverlap', ...
    'negativeStaticPackets','negativeBaseDynamicPackets', ...
    'negativeRateBankPackets','negativeLoboPackets', ...
    'positiveStaticPackets','positiveBaseDynamicPackets'});

floorValue = 0.5/pooledCount;
pooledLog = log10(max(pooledSer,floorValue));
firstDifference = diff(pooledLog);
secondDifference = diff(pooledLog,2);
noSignificantReverse = true;
for row = 1:height(summary)-1
    if summary.pooledWilsonUpper95(row+1)< ...
            summary.pooledWilsonLower95(row)
        noSignificantReverse = false;
    end
end
shape = struct('usesRawMeasuredPointsOnly',true,'curveFitted',false, ...
    'smoothingApplied',false,'pooledFirstDifferenceDecade',firstDifference, ...
    'pooledSecondDifferenceDecade',secondDifference, ...
    'maximumPooledSecondDifferenceDecade', ...
        max(abs(secondDifference),[],'omitnan'), ...
    'allPointEstimatesBelowUpper',all(candidateSer<=target,'all'), ...
    'allPooledWilsonUpperBelowUpper',all( ...
        summary.pooledWilsonUpper95<=target), ...
    'allMirrorWilsonIntervalsOverlap',all( ...
        summary.mirrorWilsonIntervalsOverlap), ...
    'noStatisticallySignificantReverseJump',noSignificantReverse, ...
    'case1ExactPackets',sum(case1Exact), ...
    'case2ParentSer',parentSer(end,1), ...
    'case2CandidateSer',candidateSer(end,1), ...
    'case2NotWorse',candidateSer(end,1)<=parentSer(end,1), ...
    'leaveOneBlockOutVerified',loboVerified, ...
    'failedPackets',sum(failed,'all'));

root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','review');
if ~isfolder(root),mkdir(root);end
csvPath = fullfile(root,'RAW_SYMMETRIC_REVIEW.csv');
matPath = fullfile(root,'RAW_SYMMETRIC_REVIEW.mat');
figurePath = fullfile(root,'RAW_SYMMETRIC_REVIEW.png');
writetable(summary,csvPath);
save(matPath,'summary','shape','plan','errors','parentErrors', ...
    'branches','failed','case1Exact','-v7.3');
localPlot(summary,figurePath,pooledCount);
output = struct('status','AWAITING_USER_REVIEW','summary',summary, ...
    'shape',shape,'csvPath',csvPath,'matPath',matPath, ...
    'figurePath',figurePath,'formalStarted',false);
end

function target = localUpperTarget(t0,plan)
u = min(1,max(0,(t0-plan.negativeOrbitStartSec(1))/ ...
    abs(plan.negativeOrbitStartSec(1))));
target = 10^(log10(plan.targetCase1Ser)+u*( ...
    log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
end

function [lower,upper] = localWilson(errors,total)
z = 1.95996398454005;
p = errors/total;
denominator = 1+z^2/total;
center = (p+z^2/(2*total))/denominator;
radius = z*sqrt(p*(1-p)/total+z^2/(4*total^2))/denominator;
lower = max(0,center-radius);
upper = min(1,center+radius);
end

function localPlot(summary,path,total)
floorValue = 0.5/total;
f = figure('Visible','off','Color','w','Position',[100 100 1050 620]);
semilogy(summary.negativeOrbitStartSec,max(summary.negativeSer,floorValue), ...
    '-o','Color',[0.75 0.80 0.90],'LineWidth',0.9, ...
    'DisplayName','Raw negative pass');hold on
semilogy(summary.negativeOrbitStartSec,max(summary.positiveSer,floorValue), ...
    '--s','Color',[0.90 0.75 0.68],'LineWidth',0.9, ...
    'DisplayName','Raw mirrored positive pass');
semilogy(summary.negativeOrbitStartSec,max(summary.pooledRawSer,floorValue), ...
    '-o','Color',[0 0.35 0.70],'LineWidth',2.0,'MarkerFaceColor','w', ...
    'DisplayName','Raw symmetry-pooled SER');
semilogy(summary.negativeOrbitStartSec,summary.upperTargetSer,':d', ...
    'Color',[0.90 0.60 0],'LineWidth',1.8, ...
    'DisplayName','Analytical upper envelope');
grid on;grid minor;xlabel('Negative-pass frame start t_0 (s)');ylabel('SER');
title('SenLoRa V2 raw full-orbit review (no fitting)');
legend('Location','best');
exportgraphics(f,path,'Resolution',220);close(f);
end
