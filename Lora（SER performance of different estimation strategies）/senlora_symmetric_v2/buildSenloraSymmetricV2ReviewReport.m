function report = buildSenloraSymmetricV2ReviewReport()
%BUILDSENLORASYMMETRICV2REVIEWREPORT Report accepted raw-count review data.

paths = exp1SetupPaths();
root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','review');
sourcePath = fullfile(root,'RAW_SYMMETRIC_REVIEW.mat');
loaded = load(sourcePath,'summary','shape','plan','errors', ...
    'parentErrors','failed','case1Exact');

summary = loaded.summary;
packetErrors = double(loaded.errors);
perSideCount = loaded.plan.reviewPackets*112;
pooledCount = 2*perSideCount;
negativeErrors = squeeze(sum(packetErrors(:,1,:),3));
positiveErrors = squeeze(sum(packetErrors(:,2,:),3));
pooledErrors = negativeErrors+positiveErrors;
perSideAnalyticalUpperErrors = summary.upperTargetSer*perSideCount;
pooledAnalyticalUpperErrors = summary.upperTargetSer*pooledCount;

rawCounts = table(summary.negativeOrbitStartSec, ...
    summary.positiveMirrorStartSec,negativeErrors,positiveErrors, ...
    pooledErrors,perSideAnalyticalUpperErrors, ...
    pooledAnalyticalUpperErrors,summary.negativeWilsonUpper95, ...
    summary.positiveWilsonUpper95,summary.pooledWilsonUpper95, ...
    summary.upperTargetSer, ...
    summary.negativeWilsonUpper95<=summary.upperTargetSer, ...
    summary.positiveWilsonUpper95<=summary.upperTargetSer, ...
    summary.mirrorWilsonIntervalsOverlap, ...
    'VariableNames',{'negativeOrbitStartSec','positiveMirrorStartSec', ...
    'negativeRawErrors','positiveRawErrors','pooledRawErrors', ...
    'perSideAnalyticalUpperErrorCount', ...
    'pooledAnalyticalUpperErrorCount','negativeWilsonUpper95', ...
    'positiveWilsonUpper95','pooledWilsonUpper95','upperTargetSer', ...
    'negativeWilsonBelowUpper','positiveWilsonBelowUpper', ...
    'mirrorWilsonIntervalsOverlap'});

perSideWilsonPass = rawCounts.negativeWilsonBelowUpper & ...
    rawCounts.positiveWilsonBelowUpper;
exceptionRows = find(~perSideWilsonPass);
report = struct('identity',loaded.plan.identity, ...
    'status','REVIEW_ACCEPTED_WITH_USER_TOLERANCE', ...
    'nextGate','AWAITING_EXPLICIT_FORMAL_APPROVAL', ...
    'acceptanceBasis',[ ...
        'User explicitly accepted the observed per-side Wilson ' ...
        'upper-bound excursions on 2026-09-23.'], ...
    'usesRawErrorCountsOnly',true,'curveFitted',false, ...
    'interpolationApplied',false,'smoothingApplied',false, ...
    'packetsPerSide',loaded.plan.reviewPackets, ...
    'symbolsPerSidePoint',perSideCount, ...
    'symbolsPerPooledPoint',pooledCount, ...
    'allPointEstimatesBelowUpper', ...
        loaded.shape.allPointEstimatesBelowUpper, ...
    'allPerSideWilsonUpperBelowUpper',all(perSideWilsonPass), ...
    'acceptedPerSideWilsonExceptionCount',numel(exceptionRows), ...
    'acceptedPerSideWilsonExceptionRows',exceptionRows, ...
    'allPooledWilsonUpperBelowUpper', ...
        loaded.shape.allPooledWilsonUpperBelowUpper, ...
    'allMirrorWilsonIntervalsOverlap', ...
        loaded.shape.allMirrorWilsonIntervalsOverlap, ...
    'noStatisticallySignificantReverseJump', ...
        loaded.shape.noStatisticallySignificantReverseJump, ...
    'case1ExactPackets',sum(loaded.case1Exact), ...
    'case2ParentSer',loaded.shape.case2ParentSer, ...
    'case2CandidateSer',loaded.shape.case2CandidateSer, ...
    'case2TargetSer',loaded.plan.targetCenterSer, ...
    'case2NotWorse',loaded.shape.case2NotWorse, ...
    'case2BelowTarget', ...
        loaded.shape.case2CandidateSer<=loaded.plan.targetCenterSer, ...
    'leaveOneBlockOutVerified', ...
        loaded.shape.leaveOneBlockOutVerified, ...
    'failedPackets',sum(loaded.failed,'all'), ...
    'formalStarted',false);

csvPath = fullfile(root,'RAW_COUNT_REVIEW.csv');
figurePath = fullfile(root,'RAW_COUNT_REVIEW.png');
reportPath = fullfile(root,'RAW_COUNT_REVIEW.md');
matPath = fullfile(root,'RAW_COUNT_REVIEW.mat');
writetable(rawCounts,csvPath);
localPlot(rawCounts,figurePath);
localMarkdown(reportPath,report,rawCounts);
save(matPath,'rawCounts','report','-v7.3');
report.csvPath = csvPath;
report.figurePath = figurePath;
report.reportPath = reportPath;
report.matPath = matPath;
end

function localPlot(rawCounts,path)
x = rawCounts.negativeOrbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1050 760]);
layout = tiledlayout(f,2,1,'TileSpacing','compact','Padding','compact');

nexttile(layout);
plot(x,rawCounts.negativeRawErrors,'o','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.4,'Color',[0 0.35 0.70], ...
    'DisplayName','Negative pass raw errors');
hold on
plot(x,rawCounts.positiveRawErrors,'s','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.4,'Color',[0.80 0.30 0.12], ...
    'DisplayName','Mirrored positive pass raw errors');
plot(x,rawCounts.perSideAnalyticalUpperErrorCount,':d', ...
    'LineWidth',1.7,'Color',[0.85 0.55 0], ...
    'DisplayName','Analytical per-side upper count');
grid on
ylabel('Symbol error count per side');
title('SenLoRa V2 review: raw side counts');
legend('Location','northwest');

nexttile(layout);
plot(x,rawCounts.pooledRawErrors,'o','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.6,'Color',[0.15 0.45 0.20], ...
    'DisplayName','Raw pooled errors');
hold on
plot(x,rawCounts.pooledAnalyticalUpperErrorCount,':d', ...
    'LineWidth',1.7,'Color',[0.55 0.25 0.75], ...
    'DisplayName','Analytical pooled upper count');
grid on
xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('Pooled symbol error count');
title('Physical-mirror pooled raw counts');
legend('Location','northwest');

title(layout,[ ...
    'Raw error counts and analytical upper bounds only; ' ...
    'no fitting, interpolation, or smoothing']);
exportgraphics(f,path,'Resolution',220);
close(f);
end

function localMarkdown(path,report,rawCounts)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0
    error('EXP5V2:ReportOpen','Cannot open report: %s',message);
end
cleanup = onCleanup(@()fclose(fid));

fprintf(fid,'# SenLoRa V2 raw-count review\n\n');
fprintf(fid,'Status: **%s**  \n',report.status);
fprintf(fid,'Next gate: **%s**  \n',report.nextGate);
fprintf(fid,'Formal started: **NO**\n\n');
fprintf(fid,'## Acceptance basis\n\n%s\n\n',report.acceptanceBasis);
fprintf(fid,[ ...
    'The two per-side Wilson upper-bound excursions remain visible below. ' ...
    'They are accepted exceptions, not recalculated or suppressed passes.\n\n']);
fprintf(fid,'## Review gates\n\n');
fprintf(fid,'- Raw point estimates below the analytical envelope: %d\n', ...
    report.allPointEstimatesBelowUpper);
fprintf(fid,'- Per-side Wilson upper bounds below the envelope: %d\n', ...
    report.allPerSideWilsonUpperBelowUpper);
fprintf(fid,'- User-accepted per-side Wilson exceptions: %d\n', ...
    report.acceptedPerSideWilsonExceptionCount);
fprintf(fid,'- Pooled Wilson upper bounds below the envelope: %d\n', ...
    report.allPooledWilsonUpperBelowUpper);
fprintf(fid,'- All physical-mirror Wilson intervals overlap: %d\n', ...
    report.allMirrorWilsonIntervalsOverlap);
fprintf(fid,'- No statistically significant reverse jump: %d\n', ...
    report.noStatisticallySignificantReverseJump);
fprintf(fid,'- Case1 exact packets: %d/%d\n', ...
    report.case1ExactPackets,report.packetsPerSide);
fprintf(fid,'- Case2 parent/candidate SER: %.9g / %.9g\n', ...
    report.case2ParentSer,report.case2CandidateSer);
fprintf(fid,'- Case2 target SER: %.9g\n',report.case2TargetSer);
fprintf(fid,'- Case2 candidate no worse than parent: %d\n', ...
    report.case2NotWorse);
fprintf(fid,'- Case2 candidate at or below target: %d\n', ...
    report.case2BelowTarget);
fprintf(fid,'- Leave-one-block-out verified: %d\n', ...
    report.leaveOneBlockOutVerified);
fprintf(fid,'- Failed packets: %d\n\n',report.failedPackets);

fprintf(fid,'## Raw counts and statistical audit\n\n');
fprintf(fid,[ ...
    '| Negative t0 (s) | Positive mirror t0 (s) | Negative errors | ' ...
    'Positive errors | Pooled errors | Per-side analytical count upper | ' ...
    'Negative Wilson upper | Positive Wilson upper | Target SER | ' ...
    'Per-side Wilson result |\n']);
fprintf(fid, ...
    '|---:|---:|---:|---:|---:|---:|---:|---:|---:|:---|\n');
for row = 1:height(rawCounts)
    if rawCounts.negativeWilsonBelowUpper(row) && ...
            rawCounts.positiveWilsonBelowUpper(row)
        result = 'PASS';
    else
        result = 'ACCEPTED EXCEPTION';
    end
    fprintf(fid,[ ...
        '| %.6g | %.6g | %d | %d | %d | %.6g | %.9g | %.9g | ' ...
        '%.9g | %s |\n'],rawCounts.negativeOrbitStartSec(row), ...
        rawCounts.positiveMirrorStartSec(row), ...
        rawCounts.negativeRawErrors(row), ...
        rawCounts.positiveRawErrors(row), ...
        rawCounts.pooledRawErrors(row), ...
        rawCounts.perSideAnalyticalUpperErrorCount(row), ...
        rawCounts.negativeWilsonUpper95(row), ...
        rawCounts.positiveWilsonUpper95(row), ...
        rawCounts.upperTargetSer(row),result);
end

fprintf(fid,'\n## Plot policy\n\n');
fprintf(fid,[ ...
    'The figure contains only raw symbol-error counts at the nine measured ' ...
    'orbit pairs and the analytical count upper bounds. No measured point ' ...
    'is fitted, interpolated, smoothed, moved, or replaced.\n']);
clear cleanup
end
