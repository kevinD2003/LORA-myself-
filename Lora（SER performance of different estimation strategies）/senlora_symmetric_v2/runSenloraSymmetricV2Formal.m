function output = runSenloraSymmetricV2Formal(options)
%RUNSENLORASYMMETRICV2FORMAL Checkpointed independent full-orbit Formal.

arguments
    options.StopAfterPacket (1,1) double {mustBeInteger,mustBePositive} = inf
    options.WorkerCount (1,1) double {mustBeInteger,mustBePositive} = 6
end

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
plan = senloraSymmetricV2Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
parentAudit = exp1ValidateFrozenParent(config);

formalPackets = config.formalPackets;
negative = plan.negativeOrbitStartSec(:);
pairCount = numel(negative);
payloadCount = config.parent.payloadSymbolCount;
checkpointEvery = config.checkpointEveryPackets;
root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','formal');
if ~isfolder(root), mkdir(root); end
checkpointPath = fullfile(root,'FORMAL_CHECKPOINT.mat');
signature = localSignature(paths,config,plan,formalPackets,parentAudit);

if isfile(checkpointPath)
    localValidateCheckpointHash(checkpointPath);
    loaded = load(checkpointPath);
    localValidateCheckpoint(loaded,signature,pairCount,formalPackets);
    errors = loaded.errors;
    parentErrors = loaded.parentErrors;
    branches = loaded.branches;
    failed = loaded.failed;
    loboVerified = loaded.loboVerified;
    case1Exact = loaded.case1Exact;
    completed = loaded.completed;
    startedUtc = loaded.startedUtc;
else
    errors = zeros(pairCount,2,formalPackets,'uint16');
    parentErrors = zeros(pairCount,2,formalPackets,'uint16');
    branches = zeros(pairCount,2,formalPackets,'uint8');
    failed = false(pairCount,2,formalPackets);
    loboVerified = false(pairCount,2,formalPackets);
    case1Exact = false(formalPackets,1);
    completed = false(pairCount,formalPackets);
    startedUtc = localUtcNow();
end

maximumPacket = min(formalPackets,options.StopAfterPacket);
if any(~completed(:,1:maximumPacket),'all')
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('local',options.WorkerCount);
    elseif pool.NumWorkers~=options.WorkerCount
        error('EXP5V2:FormalWorkerCount', ...
            'Existing pool has %d workers; requested %d.', ...
            pool.NumWorkers,options.WorkerCount);
    end
end

for blockStart = 1:checkpointEvery:maximumPacket
    packetIds = blockStart:min(maximumPacket, ...
        blockStart+checkpointEvery-1);
    [pairRows,packetColumns] = find(~completed(:,packetIds));
    if isempty(pairRows), continue; end
    jobPairs = pairRows;
    jobPackets = packetIds(packetColumns).';
    jobCount = numel(jobPairs);
    jobErrors = zeros(jobCount,2,'uint16');
    jobParentErrors = zeros(jobCount,2,'uint16');
    jobBranches = zeros(jobCount,2,'uint8');
    jobFailed = false(jobCount,2);
    jobLoboVerified = false(jobCount,2);
    jobCase1Exact = false(jobCount,1);

    parfor job = 1:jobCount
        pairIndex = jobPairs(job);
        packetId = jobPackets(job);
        packet = localEvaluatePairPacket(pairIndex,packetId,negative, ...
            config,plan,parameters,payloadCount);
        jobErrors(job,:) = packet.errors;
        jobParentErrors(job,:) = packet.parentErrors;
        jobBranches(job,:) = packet.branches;
        jobFailed(job,:) = packet.failed;
        jobLoboVerified(job,:) = packet.loboVerified;
        jobCase1Exact(job) = packet.case1Exact;
    end

    for job = 1:jobCount
        pairIndex = jobPairs(job);
        packetId = jobPackets(job);
        errors(pairIndex,:,packetId) = jobErrors(job,:);
        parentErrors(pairIndex,:,packetId) = jobParentErrors(job,:);
        branches(pairIndex,:,packetId) = jobBranches(job,:);
        failed(pairIndex,:,packetId) = jobFailed(job,:);
        loboVerified(pairIndex,:,packetId) = jobLoboVerified(job,:);
        if pairIndex==1
            case1Exact(packetId) = jobCase1Exact(job);
        end
        completed(pairIndex,packetId) = true;
    end
    lastUpdatedUtc = localUtcNow();
    localSaveCheckpoint(checkpointPath,signature,errors,parentErrors, ...
        branches,failed,loboVerified,case1Exact,completed, ...
        startedUtc,lastUpdatedUtc);
    fprintf(['EXP5V2 Formal packets=%d/%d pairsComplete=%d/%d ' ...
        'failures=%d updated=%s\n'],max(packetIds),formalPackets, ...
        sum(completed(:,1:max(packetIds)),'all'), ...
        pairCount*max(packetIds),sum(failed,'all'),lastUpdatedUtc);
end

formalComplete = all(completed,'all');
if ~formalComplete
    output = struct('status','FORMAL_IN_PROGRESS', ...
        'completedPairPackets',sum(completed,'all'), ...
        'totalPairPackets',numel(completed), ...
        'checkpointPath',checkpointPath,'formalStarted',true, ...
        'formalComplete',false);
    return
end

[summary,shape] = localSummarize(errors,parentErrors,branches,failed, ...
    loboVerified,case1Exact,negative,config,plan);
csvPath = fullfile(root,'FORMAL_SYMMETRIC_SUMMARY.csv');
matPath = fullfile(root,'FORMAL_SYMMETRIC_RESULT.mat');
figurePath = fullfile(root,'FORMAL_RAW_COUNT.png');
reportPath = fullfile(root,'FORMAL_REPORT.md');
writetable(summary,csvPath);
save(matPath,'summary','shape','plan','signature','errors', ...
    'parentErrors','branches','failed','loboVerified','case1Exact', ...
    'completed','startedUtc','lastUpdatedUtc','-v7.3');
localPlot(summary,figurePath,formalPackets*payloadCount);
localMarkdown(reportPath,shape,summary,formalPackets);
output = struct('status',shape.status,'summary',summary,'shape',shape, ...
    'csvPath',csvPath,'matPath',matPath,'figurePath',figurePath, ...
    'reportPath',reportPath,'checkpointPath',checkpointPath, ...
    'formalStarted',true,'formalComplete',true);
end

function packet = localEvaluatePairPacket(pairIndex,packetId,negative, ...
        config,plan,parameters,payloadCount)
starts = [negative(pairIndex),-negative(pairIndex)-plan.frameDurationSec];
packetErrors = zeros(1,2,'uint16');
packetParentErrors = zeros(1,2,'uint16');
packetBranches = zeros(1,2,'uint8');
packetFailed = false(1,2);
packetLoboVerified = false(1,2);
packetCase1Exact = true;
ledger = senloraSymmetricV2SeedPlan(config,plan,'formal', ...
    pairIndex,plan.snrDb,packetId);
for side = 1:2
    parentAvailable = false;
    try
        frame = exp1GenerateFrame(config,starts(side),plan.snrDb,ledger);
        common = v4CommonBootstrap( ...
            frame.observation.rxPhysical(1:8,:),config.parent, ...
            SearchStepBins=parameters.searchStepBins);
        parent = exp1Stage55Decode(frame.observation,common,config,true);
        parentAvailable = true;
        packetParentErrors(side) = uint16(sum( ...
            parent.detectedPhysicalBins(:)~= ...
            frame.truth.payloadPhysicalBins(:)));
        result = senloraSymmetricV2Decode( ...
            frame.observation,common,config,plan);
        packetErrors(side) = uint16(sum( ...
            result.detectedPhysicalBins(:)~= ...
            frame.truth.payloadPhysicalBins(:)));
        packetBranches(side) = uint8(result.decision.selectedBranch);
        packetLoboVerified(side) = result.decision.leaveOneBlockOut && ...
            ~result.decision.selfBlockUsedForFit;
        if pairIndex==1 && side==1
            packetCase1Exact = isequal( ...
                result.detectedPhysicalBins(:), ...
                parent.detectedPhysicalBins(:)) && isequal( ...
                result.hardDecodedDataBits(:), ...
                parent.hardDecodedDataBits(:));
        end
    catch exception
        packetFailed(side) = true;
        packetErrors(side) = uint16(payloadCount);
        if ~parentAvailable
            packetParentErrors(side) = uint16(payloadCount);
        end
        packetLoboVerified(side) = false;
        if pairIndex==1 && side==1, packetCase1Exact = false; end
        warning('EXP5V2:FormalPacketFailure', ...
            'Pair %d packet %d side %d failed: %s', ...
            pairIndex,packetId,side,exception.message);
    end
end
packet = struct('errors',packetErrors, ...
    'parentErrors',packetParentErrors,'branches',packetBranches, ...
    'failed',packetFailed,'loboVerified',packetLoboVerified, ...
    'case1Exact',packetCase1Exact);
end

function signature = localSignature(paths,config,plan,formalPackets,parentAudit)
entry = which('runSenloraSymmetricV2Formal');
required = matlab.codetools.requiredFilesAndProducts(entry);
explicitNames = {'runSenloraSymmetricV2Formal', ...
    'senloraSymmetricV2Config','senloraSymmetricV2Decode', ...
    'senloraSymmetricV2SeedPlan','exp1Config','exp1GenerateFrame', ...
    'v4CommonBootstrap','exp1Stage55Decode','reviewStaticHypothesis'};
explicitPaths = strings(numel(explicitNames),1);
for index = 1:numel(explicitNames)
    explicitPaths(index) = string(which(explicitNames{index}));
    if strlength(explicitPaths(index))==0
        error('EXP5V2:FormalDependencyMissing', ...
            'Cannot resolve Formal dependency %s.',explicitNames{index});
    end
end
sourcePaths = unique([string(required(:));explicitPaths]);
inScope = startsWith(sourcePaths,string(paths.projectRoot)+filesep, ...
    'IgnoreCase',true) | ...
    startsWith(sourcePaths,string(config.parentRoot)+filesep, ...
    'IgnoreCase',true);
sourcePaths = sort(sourcePaths(inScope));
if isempty(sourcePaths)
    error('EXP5V2:FormalDependencySet', ...
        'Formal implementation dependency set is empty.');
end
sourceHashes = strings(size(sourcePaths));
for index = 1:numel(sourcePaths)
    sourceHashes(index) = exp1Sha256(sourcePaths(index));
end
signature = struct('identity',plan.identity, ...
    'receiverVersion',plan.receiverVersion, ...
    'formalRootSeed',plan.formalRootSeed, ...
    'formalPackets',formalPackets,'snrDb',plan.snrDb, ...
    'negativeOrbitStartSec',plan.negativeOrbitStartSec, ...
    'frameDurationSec',plan.frameDurationSec, ...
    'payloadSymbolCount',config.parent.payloadSymbolCount, ...
    'parentManifestSha256',parentAudit.manifestSha256, ...
    'implementationSourcePaths',sourcePaths, ...
    'implementationSourceSha256',sourceHashes);
end

function localValidateCheckpoint(loaded,signature,pairCount,formalPackets)
required = {'signature','errors','parentErrors','branches','failed', ...
    'loboVerified','case1Exact','completed','startedUtc', ...
    'lastUpdatedUtc'};
for index = 1:numel(required)
    if ~isfield(loaded,required{index})
        error('EXP5V2:FormalCheckpointField', ...
            'Checkpoint is missing %s.',required{index});
    end
end
if ~isequaln(loaded.signature,signature)
    error('EXP5V2:FormalCheckpointSignature', ...
        'Formal checkpoint signature does not match frozen inputs.');
end
expectedPairSize = [pairCount,2,formalPackets];
if ~isequal(size(loaded.errors),expectedPairSize) || ...
        ~isequal(size(loaded.parentErrors),expectedPairSize) || ...
        ~isequal(size(loaded.branches),expectedPairSize) || ...
        ~isequal(size(loaded.failed),expectedPairSize) || ...
        ~isequal(size(loaded.loboVerified),expectedPairSize) || ...
        ~isequal(size(loaded.completed),[pairCount,formalPackets]) || ...
        ~isequal(size(loaded.case1Exact),[formalPackets,1])
    error('EXP5V2:FormalCheckpointSize', ...
        'Formal checkpoint array dimensions are invalid.');
end
completedSides = repmat(reshape(loaded.completed, ...
    pairCount,1,formalPackets),1,2,1);
completedSuccess = completedSides & ~loaded.failed;
if any(loaded.failed & ~completedSides,'all') || ...
        any(loaded.branches(completedSuccess)<1 | ...
            loaded.branches(completedSuccess)>4,'all') || ...
        ~all(loaded.loboVerified(completedSuccess),'all') || ...
        any(loaded.errors(~completedSides)~=0,'all') || ...
        any(loaded.parentErrors(~completedSides)~=0,'all') || ...
        any(loaded.branches(~completedSides)~=0,'all') || ...
        any(loaded.loboVerified(~completedSides),'all') || ...
        any(loaded.case1Exact(~loaded.completed(1,:).'))
    error('EXP5V2:FormalCheckpointConsistency', ...
        'Formal checkpoint state is inconsistent with its completion mask.');
end
end

function localSaveCheckpoint(path,signature,errors,parentErrors,branches, ...
        failed,loboVerified,case1Exact,completed,startedUtc,lastUpdatedUtc)
temporaryPath = [path '.tmp'];
hashPath = [path '.sha256'];
temporaryHashPath = [hashPath '.tmp'];
save(temporaryPath,'signature','errors','parentErrors','branches', ...
    'failed','loboVerified','case1Exact','completed','startedUtc', ...
    'lastUpdatedUtc','-v7.3');
[moved,message] = movefile(temporaryPath,path,'f');
if ~moved
    error('EXP5V2:FormalCheckpointMove', ...
        'Cannot replace Formal checkpoint: %s',message);
end
localWriteText(temporaryHashPath,exp1Sha256(path));
[moved,message] = movefile(temporaryHashPath,hashPath,'f');
if ~moved
    error('EXP5V2:FormalCheckpointHashMove', ...
        'Cannot replace Formal checkpoint hash: %s',message);
end
end

function localValidateCheckpointHash(path)
hashPath = [path '.sha256'];
if ~isfile(hashPath)
    error('EXP5V2:FormalCheckpointHashMissing', ...
        'Formal checkpoint hash sidecar is missing.');
end
expected = strtrim(fileread(hashPath));
actual = exp1Sha256(path);
if ~strcmpi(expected,actual)
    error('EXP5V2:FormalCheckpointHashMismatch', ...
        'Formal checkpoint content hash does not match its sidecar.');
end
end

function localWriteText(path,value)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0
    error('EXP5V2:FormalCheckpointHashOpen', ...
        'Cannot open checkpoint hash sidecar: %s',message);
end
cleanup = onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',value);
clear cleanup
end

function [summary,shape] = localSummarize(errors,parentErrors,branches, ...
        failed,loboVerified,case1Exact,negative,config,plan)
formalPackets = size(errors,3);
perSideCount = formalPackets*config.parent.payloadSymbolCount;
pooledCount = 2*perSideCount;
candidateSer = sum(double(errors),3)/perSideCount;
parentSer = sum(double(parentErrors),3)/perSideCount;
target = arrayfun(@(t)localUpperTarget(t,plan),negative);
rows = cell(numel(negative),28);
pooledLower = zeros(numel(negative),1);
pooledUpper = zeros(numel(negative),1);
for row = 1:numel(negative)
    negativeErrors = sum(double(errors(row,1,:)),'all');
    positiveErrors = sum(double(errors(row,2,:)),'all');
    pooledErrors = negativeErrors+positiveErrors;
    [negativeLower,negativeUpper] = ...
        localWilson(negativeErrors,perSideCount);
    [positiveLower,positiveUpper] = ...
        localWilson(positiveErrors,perSideCount);
    [pooledLower(row),pooledUpper(row)] = ...
        localWilson(pooledErrors,pooledCount);
    negativeBranches = squeeze(branches(row,1,:));
    positiveBranches = squeeze(branches(row,2,:));
    rows(row,:) = {negative(row),-negative(row)-plan.frameDurationSec, ...
        plan.snrDb,formalPackets,negativeErrors,positiveErrors, ...
        pooledErrors,candidateSer(row,1),candidateSer(row,2), ...
        pooledErrors/pooledCount,negativeLower,negativeUpper, ...
        positiveLower,positiveUpper,pooledLower(row),pooledUpper(row), ...
        target(row),negativeLower<=positiveUpper && ...
        positiveLower<=negativeUpper,sum(negativeBranches==1), ...
        sum(negativeBranches==2),sum(negativeBranches==3), ...
        sum(negativeBranches==4),sum(positiveBranches==1), ...
        sum(positiveBranches==2),sum(positiveBranches==3), ...
        sum(positiveBranches==4),sum(failed(row,:,:),'all'), ...
        all(loboVerified(row,:,:),'all')};
end
summary = cell2table(rows,'VariableNames',{ ...
    'negativeOrbitStartSec','positiveMirrorStartSec','snrDb','packets', ...
    'negativeRawErrors','positiveRawErrors','pooledRawErrors', ...
    'negativeSer','positiveSer','pooledRawSer','negativeWilsonLower95', ...
    'negativeWilsonUpper95','positiveWilsonLower95', ...
    'positiveWilsonUpper95','pooledWilsonLower95', ...
    'pooledWilsonUpper95','upperTargetSer', ...
    'mirrorWilsonIntervalsOverlap','negativeStaticPackets', ...
    'negativeBaseDynamicPackets','negativeRateBankPackets', ...
    'negativeLoboPackets','positiveStaticPackets', ...
    'positiveBaseDynamicPackets','positiveRateBankPackets', ...
    'positiveLoboPackets','failedPackets','leaveOneBlockOutVerified'});

noSignificantReverse = true;
for row = 1:height(summary)-1
    if pooledUpper(row+1)<pooledLower(row)
        noSignificantReverse = false;
    end
end
allPoints = all(candidateSer<=target,'all');
allPerSideWilson = all(summary.negativeWilsonUpper95<=target & ...
    summary.positiveWilsonUpper95<=target);
allPooledWilson = all(summary.pooledWilsonUpper95<=target);
allMirrorOverlap = all(summary.mirrorWilsonIntervalsOverlap);
case1ExactCount = sum(case1Exact);
case2NotWorse = candidateSer(end,1)<=parentSer(end,1);
case2BelowTarget = candidateSer(end,1)<=plan.targetCenterSer;
noFailures = ~any(failed,'all');
allLoboVerified = all(loboVerified,'all');
formalPass = allPoints && allPerSideWilson && allPooledWilson && ...
    allMirrorOverlap && noSignificantReverse && ...
    case1ExactCount==formalPackets && case2NotWorse && ...
    case2BelowTarget && noFailures && allLoboVerified;
if formalPass
    status = 'FORMAL_PASS';
else
    status = 'FORMAL_FAIL';
end
shape = struct('status',status,'usesRawMeasuredCountsOnly',true, ...
    'curveFitted',false,'interpolationApplied',false, ...
    'smoothingApplied',false,'allPointEstimatesBelowUpper',allPoints, ...
    'allPerSideWilsonUpperBelowUpper',allPerSideWilson, ...
    'allPooledWilsonUpperBelowUpper',allPooledWilson, ...
    'allMirrorWilsonIntervalsOverlap',allMirrorOverlap, ...
    'noStatisticallySignificantReverseJump',noSignificantReverse, ...
    'case1ExactPackets',case1ExactCount, ...
    'case1TotalPackets',formalPackets, ...
    'case2ParentSer',parentSer(end,1), ...
    'case2CandidateSer',candidateSer(end,1), ...
    'case2TargetSer',plan.targetCenterSer, ...
    'case2NotWorse',case2NotWorse, ...
    'case2BelowTarget',case2BelowTarget, ...
    'leaveOneBlockOutVerified',allLoboVerified, ...
    'failedPackets',sum(failed,'all'),'formalStarted',true, ...
    'formalComplete',true);
end

function target = localUpperTarget(t0,plan)
u = min(1,max(0,(t0-plan.negativeOrbitStartSec(1))/ ...
    abs(plan.negativeOrbitStartSec(1))));
target = 10^(log10(plan.targetCase1Ser)+u*( ...
    log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
end

function [lower,upper] = localWilson(errorCount,total)
z = 1.95996398454005;
p = errorCount/total;
denominator = 1+z^2/total;
center = (p+z^2/(2*total))/denominator;
radius = z*sqrt(p*(1-p)/total+z^2/(4*total^2))/denominator;
lower = max(0,center-radius);
upper = min(1,center+radius);
end

function localPlot(summary,path,perSideCount)
x = summary.negativeOrbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1050 760]);
layout = tiledlayout(f,2,1,'TileSpacing','compact','Padding','compact');
nexttile(layout);
plot(x,summary.negativeRawErrors,'o','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.4,'Color',[0 0.35 0.70], ...
    'DisplayName','Negative pass raw errors');
hold on
plot(x,summary.positiveRawErrors,'s','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.4,'Color',[0.80 0.30 0.12], ...
    'DisplayName','Mirrored positive pass raw errors');
plot(x,summary.upperTargetSer*perSideCount,':d', ...
    'LineWidth',1.7,'Color',[0.85 0.55 0], ...
    'DisplayName','Analytical per-side upper count');
grid on
ylabel('Symbol error count per side');
title('SenLoRa V2 Formal: raw side counts');
legend('Location','northwest');
nexttile(layout);
plot(x,summary.pooledRawErrors,'o','LineStyle','none', ...
    'MarkerSize',7,'LineWidth',1.6,'Color',[0.15 0.45 0.20], ...
    'DisplayName','Raw pooled errors');
hold on
plot(x,summary.upperTargetSer*(2*perSideCount),':d', ...
    'LineWidth',1.7,'Color',[0.55 0.25 0.75], ...
    'DisplayName','Analytical pooled upper count');
grid on
xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('Pooled symbol error count');
title('Physical-mirror pooled raw counts');
legend('Location','northwest');
title(layout,[ ...
    'Formal raw error counts and analytical upper bounds only; ' ...
    'no fitting, interpolation, or smoothing']);
exportgraphics(f,path,'Resolution',220);
close(f);
end

function localMarkdown(path,shape,summary,formalPackets)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0
    error('EXP5V2:FormalReportOpen','Cannot open report: %s',message);
end
cleanup = onCleanup(@()fclose(fid));
fprintf(fid,'# SenLoRa V2 Formal report\n\n');
fprintf(fid,'Status: **%s**  \nFormal complete: **YES**\n\n',shape.status);
fprintf(fid,'## Formal gates\n\n');
fprintf(fid,'- Packets per side and orbit point: %d\n',formalPackets);
fprintf(fid,'- Raw point estimates below analytical envelope: %d\n', ...
    shape.allPointEstimatesBelowUpper);
fprintf(fid,'- Per-side Wilson upper bounds below envelope: %d\n', ...
    shape.allPerSideWilsonUpperBelowUpper);
fprintf(fid,'- Pooled Wilson upper bounds below envelope: %d\n', ...
    shape.allPooledWilsonUpperBelowUpper);
fprintf(fid,'- All physical-mirror Wilson intervals overlap: %d\n', ...
    shape.allMirrorWilsonIntervalsOverlap);
fprintf(fid,'- No statistically significant reverse jump: %d\n', ...
    shape.noStatisticallySignificantReverseJump);
fprintf(fid,'- Case1 exact packets: %d/%d\n', ...
    shape.case1ExactPackets,shape.case1TotalPackets);
fprintf(fid,'- Case2 parent/candidate/target SER: %.9g / %.9g / %.9g\n', ...
    shape.case2ParentSer,shape.case2CandidateSer,shape.case2TargetSer);
fprintf(fid,'- Case2 candidate no worse than parent: %d\n', ...
    shape.case2NotWorse);
fprintf(fid,'- Case2 candidate at or below target: %d\n', ...
    shape.case2BelowTarget);
fprintf(fid,'- Leave-one-block-out verified: %d\n', ...
    shape.leaveOneBlockOutVerified);
fprintf(fid,'- Failed receiver packets: %d\n\n',shape.failedPackets);
fprintf(fid,'## Per-orbit raw statistics\n\n');
fprintf(fid,[ ...
    '| Negative t0 | Positive mirror t0 | Negative errors | ' ...
    'Positive errors | Pooled errors | Negative SER | Positive SER | ' ...
    'Target SER | Negative Wilson upper | Positive Wilson upper | ' ...
    'Mirror overlap |\n']);
fprintf(fid, ...
    '|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|:---:|\n');
for row = 1:height(summary)
    fprintf(fid,[ ...
        '| %.6g | %.6g | %d | %d | %d | %.9g | %.9g | %.9g | ' ...
        '%.9g | %.9g | %d |\n'],summary.negativeOrbitStartSec(row), ...
        summary.positiveMirrorStartSec(row), ...
        summary.negativeRawErrors(row),summary.positiveRawErrors(row), ...
        summary.pooledRawErrors(row),summary.negativeSer(row), ...
        summary.positiveSer(row),summary.upperTargetSer(row), ...
        summary.negativeWilsonUpper95(row), ...
        summary.positiveWilsonUpper95(row), ...
        summary.mirrorWilsonIntervalsOverlap(row));
end
fprintf(fid,'\n## Plot policy\n\n');
fprintf(fid,[ ...
    'The Formal figure contains only raw symbol-error counts and the ' ...
    'analytical count upper bounds. No measured point is fitted, ' ...
    'interpolated, smoothed, moved, or replaced.\n']);
clear cleanup
end

function text = localUtcNow()
text = char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z'''));
end
