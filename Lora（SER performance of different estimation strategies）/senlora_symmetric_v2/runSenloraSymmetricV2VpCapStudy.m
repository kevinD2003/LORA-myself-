function output = runSenloraSymmetricV2VpCapStudy()
%RUNSENLORASYMMETRICV2VPCAPSTUDY Compare 2/3/4 VP per block.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
basePlan = senloraSymmetricV2Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
caps = [2 3 4];
negative = [-366 -274.5 -183 -91.5 0];
n = 5;
rows = cell(numel(caps)*numel(negative)*2,19);
rowIndex = 0;
for capIndex = 1:numel(caps)
    plan = basePlan;
    plan.maximumMeasurementsPerBlock = caps(capIndex);
    for positionIndex = 1:numel(negative)
        starts = [negative(positionIndex), ...
            -negative(positionIndex)-plan.frameDurationSec];
        for side = 1:2
            symbolErrors = 0;
            loboErrors = 0;
            accepted = 0;
            falseAccepted = 0;
            residualSquaredHz = 0;
            residualCount = 0;
            endResidualSquaredHz = 0;
            selected = zeros(4,1);
            failed = 0;
            case1Exact = true;
            loboVerified = true;
            for packetId = 1:n
                ledger = senloraSymmetricV2SeedPlan( ...
                    config,plan,'mechanism',positionIndex, ...
                    plan.snrDb,packetId);
                frame = exp1GenerateFrame( ...
                    config,starts(side),plan.snrDb,ledger);
                common = v4CommonBootstrap( ...
                    frame.observation.rxPhysical(1:8,:),config.parent, ...
                    SearchStepBins=parameters.searchStepBins);
                parent = exp1Stage55Decode( ...
                    frame.observation,common,config,true);
                try
                    result = senloraSymmetricV2Decode( ...
                        frame.observation,common,config,plan);
                    outputMask = result.detectedPhysicalBins(:)~= ...
                        frame.truth.payloadPhysicalBins(:);
                    loboMask = result.loboHypothesis.decoded.hardPhysicalBins(:)~= ...
                        frame.truth.payloadPhysicalBins(:);
                    symbolErrors = symbolErrors+sum(outputMask);
                    loboErrors = loboErrors+sum(loboMask);
                    selected(result.decision.selectedBranch) = ...
                        selected(result.decision.selectedBranch)+1;
                    loboVerified = loboVerified && ...
                        result.decision.leaveOneBlockOut && ...
                        ~result.decision.selfBlockUsedForFit;
                    vpMask = result.loboHypothesis.acceptedMeasurementMask;
                    vpFalse = vpMask & ...
                        result.loboHypothesis.measurementLabels(:)~= ...
                        frame.truth.payloadPhysicalBins(:);
                    accepted = accepted+sum(vpMask);
                    falseAccepted = falseAccepted+sum(vpFalse);
                    residualHz = (result.loboHypothesis.estimatedCfoBins(:)- ...
                        frame.truth.dataCfoBins(:))*config.parent.fftBinSpacingHz;
                    residualSquaredHz = residualSquaredHz+sum(residualHz.^2);
                    residualCount = residualCount+numel(residualHz);
                    endResidualSquaredHz = endResidualSquaredHz+residualHz(end)^2;
                    if negative(positionIndex)==-366 && side==1
                        case1Exact = case1Exact && isequal( ...
                            result.detectedPhysicalBins(:), ...
                            parent.detectedPhysicalBins(:));
                    end
                catch exception
                    failed = failed+1;
                    symbolErrors = symbolErrors+config.parent.payloadSymbolCount;
                    loboErrors = loboErrors+config.parent.payloadSymbolCount;
                    warning('EXP5V2:VpCapFailure','%s',exception.message);
                end
            end
            rowIndex = rowIndex+1;
            rows(rowIndex,:) = {caps(capIndex),negative(positionIndex), ...
                starts(side),side,plan.snrDb,n, ...
                symbolErrors/(n*112),loboErrors/(n*112),accepted/n, ...
                falseAccepted/max(accepted,1), ...
                sqrt(residualSquaredHz/max(residualCount,1)), ...
                sqrt(endResidualSquaredHz/n),selected(1),selected(2), ...
                selected(3),selected(4),failed,case1Exact, ...
                loboVerified};
            fprintf(['EXP5V2 cap=%d t=%7.2f side=%d output=%.5g ' ...
                'lobo=%.5g vp=%.2f false=%.4f rmse=%.3f end=%.3f\n'], ...
                caps(capIndex),starts(side),side,rows{rowIndex,7}, ...
                rows{rowIndex,8},rows{rowIndex,9},rows{rowIndex,10}, ...
                rows{rowIndex,11},rows{rowIndex,12});
        end
    end
end
summary = cell2table(rows,'VariableNames',{'vpCapPerBlock', ...
    'negativeReferenceStartSec','orbitStartSec','side','snrDb','packets', ...
    'outputSer','loboSer','acceptedVpPerPacket','falseVpRate', ...
    'loboCfoRmseHz','loboEndCfoRmseHz','staticPackets', ...
    'baseDynamicPackets','rateBankPackets','loboPackets', ...
    'failedPackets','case1Exact', ...
    'leaveOneBlockOutVerified'});
aggregate = groupsummary(summary,'vpCapPerBlock',{'mean','sum'}, ...
    {'acceptedVpPerPacket','falseVpRate','loboCfoRmseHz', ...
    'loboEndCfoRmseHz','loboSer','failedPackets'});
root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','vp_cap_study');
if ~isfolder(root),mkdir(root);end
writetable(summary,fullfile(root,'VP_CAP_CELL_SUMMARY.csv'));
writetable(aggregate,fullfile(root,'VP_CAP_AGGREGATE.csv'));
save(fullfile(root,'VP_CAP_STUDY.mat'),'summary','aggregate', ...
    'basePlan','caps','-v7.3');
output = struct('status','MECHANISM_STUDY_COMPLETE', ...
    'summary',summary,'aggregate',aggregate,'formalStarted',false, ...
    'resultRoot',root);
end
