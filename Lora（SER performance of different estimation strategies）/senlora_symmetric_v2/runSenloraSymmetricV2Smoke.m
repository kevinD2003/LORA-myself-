function output = runSenloraSymmetricV2Smoke()
%RUNSENLORASYMMETRICV2SMOKE Fresh-seed half-orbit V2 engineering smoke.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
plan = senloraSymmetricV2Config(config);
positions = plan.negativeOrbitStartSec;
n = plan.smokePackets;
rows = cell(numel(positions),15);
for positionIndex = 1:numel(positions)
    t0 = positions(positionIndex);
    candidateErrors = 0;
    parentErrors = 0;
    failed = 0;
    selected = zeros(4,1);
    endpointExact = true;
    noSelfLeak = true;
    for packetId = 1:n
        ledger = senloraSymmetricV2SeedPlan(config,plan,'smoke', ...
            positionIndex,plan.snrDb,packetId);
        frame = exp1GenerateFrame(config,t0,plan.snrDb,ledger);
        parameters = v4LoadMethodAlignedR3ParametersV1();
        common = v4CommonBootstrap( ...
            frame.observation.rxPhysical(1:8,:),config.parent, ...
            SearchStepBins=parameters.searchStepBins);
        parent = exp1Stage55Decode(frame.observation,common,config,true);
        parentErrors = parentErrors+sum(parent.detectedPhysicalBins(:)~= ...
            frame.truth.payloadPhysicalBins(:));
        try
            result = senloraSymmetricV2Decode( ...
                frame.observation,common,config,plan);
            candidateErrors = candidateErrors+sum( ...
                result.detectedPhysicalBins(:)~= ...
                frame.truth.payloadPhysicalBins(:));
            selected(result.decision.selectedBranch) = ...
                selected(result.decision.selectedBranch)+1;
            noSelfLeak = noSelfLeak && ...
                result.decision.leaveOneBlockOut && ...
                ~result.decision.selfBlockUsedForFit;
            if t0==-366
                endpointExact = endpointExact && isequal( ...
                    result.detectedPhysicalBins(:), ...
                    parent.detectedPhysicalBins(:));
            end
        catch exception
            failed = failed+1;
            candidateErrors = candidateErrors+config.parent.payloadSymbolCount;
            warning('EXP5V2:CandidateFailure','%s',exception.message);
        end
    end
    target = localUpperTarget(t0,plan);
    rows(positionIndex,:) = {t0,plan.snrDb,n, ...
        candidateErrors/(n*112),parentErrors/(n*112),target, ...
        selected(1),selected(2),selected(3),selected(4), ...
        failed,endpointExact, ...
        noSelfLeak,candidateErrors<=n*112*target, ...
        t0~=0 || candidateErrors<=parentErrors};
    fprintf(['EXP5V2 t0=%7.2f candidate=%.6g parent=%.6g ' ...
        'target=%.6g branches=[%d %d %d %d]\n'],t0,rows{positionIndex,4}, ...
        rows{positionIndex,5},target,selected(1),selected(2),selected(3), ...
        selected(4));
end
summary = cell2table(rows,'VariableNames',{'orbitStartSec','snrDb', ...
    'packets','candidateSer','parentStage55Ser','upperTargetSer', ...
    'staticPackets','baseDynamicPackets','rateBankPackets','loboPackets', ...
    'failedPackets', ...
    'case1Exact','leaveOneBlockOutVerified','belowUpperTarget', ...
    'case2NotWorse'});
root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','smoke');
if ~isfolder(root),mkdir(root);end
writetable(summary,fullfile(root,'SMOKE_SUMMARY.csv'));
save(fullfile(root,'SMOKE_SUMMARY.mat'),'summary','plan','-v7.3');
output = struct('status','SMOKE_COMPLETE','summary',summary, ...
    'formalStarted',false,'resultRoot',root);
end

function target = localUpperTarget(t0,plan)
u = min(1,max(0,(t0-plan.negativeOrbitStartSec(1))/ ...
    abs(plan.negativeOrbitStartSec(1))));
target = 10^(log10(plan.targetCase1Ser)+u*( ...
    log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
end
