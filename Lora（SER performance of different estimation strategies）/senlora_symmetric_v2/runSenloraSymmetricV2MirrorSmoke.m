function output = runSenloraSymmetricV2MirrorSmoke()
%RUNSENLORASYMMETRICV2MIRRORSMOKE Paired full-orbit engineering smoke.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
plan = senloraSymmetricV2Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
negative = plan.negativeOrbitStartSec;
n = plan.smokePackets;
rows = cell(numel(negative),17);
for pairIndex = 1:numel(negative)
    starts = [negative(pairIndex), ...
        -negative(pairIndex)-plan.frameDurationSec];
    errors = zeros(1,2);
    parentErrors = zeros(1,2);
    branches = zeros(2,4);
    failed = zeros(1,2);
    case1Exact = true;
    loboVerified = true;
    for packetId = 1:n
        ledger = senloraSymmetricV2SeedPlan(config,plan,'smoke', ...
            100+pairIndex,plan.snrDb,packetId);
        for side = 1:2
            frame = exp1GenerateFrame(config,starts(side),plan.snrDb,ledger);
            common = v4CommonBootstrap( ...
                frame.observation.rxPhysical(1:8,:),config.parent, ...
                SearchStepBins=parameters.searchStepBins);
            parent = exp1Stage55Decode(frame.observation,common,config,true);
            parentErrors(side) = parentErrors(side)+sum( ...
                parent.detectedPhysicalBins(:)~= ...
                frame.truth.payloadPhysicalBins(:));
            try
                result = senloraSymmetricV2Decode( ...
                    frame.observation,common,config,plan);
                errors(side) = errors(side)+sum( ...
                    result.detectedPhysicalBins(:)~= ...
                    frame.truth.payloadPhysicalBins(:));
                branch = result.decision.selectedBranch;
                branches(side,branch) = branches(side,branch)+1;
                loboVerified = loboVerified && ...
                    result.decision.leaveOneBlockOut && ...
                    ~result.decision.selfBlockUsedForFit;
                if pairIndex==1 && side==1
                    case1Exact = case1Exact && isequal( ...
                        result.detectedPhysicalBins(:), ...
                        parent.detectedPhysicalBins(:));
                end
            catch exception
                failed(side) = failed(side)+1;
                errors(side) = errors(side)+config.parent.payloadSymbolCount;
                warning('EXP5V2:MirrorFailure','%s',exception.message);
            end
        end
    end
    ser = errors/(n*config.parent.payloadSymbolCount);
    parentSer = parentErrors/(n*config.parent.payloadSymbolCount);
    target = localUpperTarget(negative(pairIndex),plan);
    floorValue = 0.5/(n*config.parent.payloadSymbolCount);
    symmetry = abs(log10(max(ser(1),floorValue))- ...
        log10(max(ser(2),floorValue)));
    rows(pairIndex,:) = {negative(pairIndex),starts(2),plan.snrDb,n, ...
        ser(1),ser(2),parentSer(1),parentSer(2),target,symmetry, ...
        branches(1,1),branches(1,2),branches(1,3),branches(1,4), ...
        sum(failed),case1Exact,loboVerified};
    fprintf(['EXP5V2 mirror t=[%7.2f,%7.2f] ser=[%.6g,%.6g] ' ...
        'target=%.6g branchesNeg=[%d %d %d %d]\n'], ...
        starts(1),starts(2),ser(1),ser(2),target, ...
        branches(1,1),branches(1,2),branches(1,3),branches(1,4));
end
summary = cell2table(rows,'VariableNames',{'negativeOrbitStartSec', ...
    'positiveMirrorStartSec','snrDb','packets','negativeSer','positiveSer', ...
    'negativeParentSer','positiveParentSer','upperTargetSer', ...
    'symmetryDifferenceDecade','negativeStaticPackets', ...
    'negativeBaseDynamicPackets','negativeRateBankPackets', ...
    'negativeLoboPackets','failedPackets','case1Exact', ...
    'leaveOneBlockOutVerified'});
root = fullfile(paths.resultsRoot,'senlora_symmetric_v2','mirror_smoke');
if ~isfolder(root),mkdir(root);end
writetable(summary,fullfile(root,'MIRROR_SMOKE_SUMMARY.csv'));
save(fullfile(root,'MIRROR_SMOKE_SUMMARY.mat'),'summary','plan','-v7.3');
output = struct('status','MIRROR_SMOKE_COMPLETE','summary',summary, ...
    'formalStarted',false,'resultRoot',root);
end

function target = localUpperTarget(t0,plan)
u = min(1,max(0,(t0-plan.negativeOrbitStartSec(1))/ ...
    abs(plan.negativeOrbitStartSec(1))));
target = 10^(log10(plan.targetCase1Ser)+u*( ...
    log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
end
