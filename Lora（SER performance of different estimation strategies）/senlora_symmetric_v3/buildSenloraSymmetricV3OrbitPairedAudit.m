function audit = buildSenloraSymmetricV3OrbitPairedAudit()
%BUILDSENLORASYMMETRICV3ORBITPAIREDAUDIT Cluster-aware orbit uncertainty.

paths = exp1SetupPaths();
sourceRoot = fullfile(paths.resultsRoot,'senlora_symmetric_v3','orbit_formal');
sourcePath = fullfile(sourceRoot,'ORBIT_FORMAL_RESULT.mat');
loaded = load(sourcePath,'candidateErrors','parentErrors','failed', ...
    'loboVerified','case1Exact','completed','summary','shape','plan');
if ~all(loaded.completed,'all') || any(loaded.failed,'all') || ...
        ~all(loaded.loboVerified,'all')
    error('EXP5V3:PairedAuditSource', ...
        'Orbit Formal source is incomplete or contains receiver failures.');
end

errors = double(loaded.candidateErrors);
parentErrors = double(loaded.parentErrors);
pairCount = size(errors,1);
n = size(errors,3);
symbolsPerSide = n*112;
draws = 10000;
bootstrapSeed = loaded.plan.formalRootSeed+3141;
stream = RandStream('mt19937ar','Seed',bootstrapSeed);
negativeSamples = zeros(pairCount,draws);
positiveSamples = zeros(pairCount,draws);
pooledSamples = zeros(pairCount,draws);
rows = cell(pairCount,22);

for pairIndex = 1:pairCount
    negativeErrors = reshape(errors(pairIndex,1,:),n,1);
    positiveErrors = reshape(errors(pairIndex,2,:),n,1);
    for draw = 1:draws
        sampledPairs = randi(stream,n,n,1);
        negativeSamples(pairIndex,draw) = ...
            sum(negativeErrors(sampledPairs))/symbolsPerSide;
        positiveSamples(pairIndex,draw) = ...
            sum(positiveErrors(sampledPairs))/symbolsPerSide;
        pooledSamples(pairIndex,draw) = ...
            (negativeSamples(pairIndex,draw)+ ...
            positiveSamples(pairIndex,draw))/2;
    end
    negativeBounds = prctile(negativeSamples(pairIndex,:),[2.5 97.5]);
    positiveBounds = prctile(positiveSamples(pairIndex,:),[2.5 97.5]);
    pooledBounds = prctile(pooledSamples(pairIndex,:),[2.5 97.5]);
    mirrorDifference = negativeSamples(pairIndex,:)- ...
        positiveSamples(pairIndex,:);
    mirrorBounds = prctile(mirrorDifference,[2.5 97.5]);
    target = loaded.summary.upperTargetSer(pairIndex);
    observedNegative = sum(negativeErrors)/symbolsPerSide;
    observedPositive = sum(positiveErrors)/symbolsPerSide;
    observedPooled = (observedNegative+observedPositive)/2;
    observedParentNegative = sum(parentErrors(pairIndex,1,:),'all')/ ...
        symbolsPerSide;
    mirrorCompatible = mirrorBounds(1)<=0 && mirrorBounds(2)>=0;
    rows(pairIndex,:) = { ...
        loaded.summary.negativeOrbitStartSec(pairIndex), ...
        loaded.summary.positiveMirrorStartSec(pairIndex),n, ...
        sum(negativeErrors),sum(positiveErrors), ...
        observedNegative,observedPositive,observedPooled, ...
        negativeBounds(1),negativeBounds(2), ...
        positiveBounds(1),positiveBounds(2), ...
        pooledBounds(1),pooledBounds(2), ...
        observedNegative-observedPositive, ...
        mirrorBounds(1),mirrorBounds(2),mirrorCompatible, ...
        target,observedParentNegative, ...
        negativeBounds(2)<=target && positiveBounds(2)<=target, ...
        pooledBounds(2)<=target};
end
summary = cell2table(rows,'VariableNames',{ ...
    'negativeOrbitStartSec','positiveMirrorStartSec','packetsPerSide', ...
    'negativeRawErrors','positiveRawErrors', ...
    'negativeSer','positiveSer','pooledSer', ...
    'negativeClusterLower95','negativeClusterUpper95', ...
    'positiveClusterLower95','positiveClusterUpper95', ...
    'pooledClusterLower95','pooledClusterUpper95', ...
    'mirrorDifferenceSer','mirrorDifferenceLower95', ...
    'mirrorDifferenceUpper95','mirrorCompatible95', ...
    'upperTargetSer','parentNegativeSer', ...
    'bothClusterUppersBelowTarget','pooledClusterUpperBelowTarget'});

transitionRows = cell(pairCount-1,8);
for pairIndex = 1:pairCount-1
    difference = pooledSamples(pairIndex+1,:)- ...
        pooledSamples(pairIndex,:);
    bounds = prctile(difference,[2.5 97.5]);
    transitionRows(pairIndex,:) = { ...
        summary.negativeOrbitStartSec(pairIndex), ...
        summary.negativeOrbitStartSec(pairIndex+1), ...
        summary.pooledSer(pairIndex),summary.pooledSer(pairIndex+1), ...
        summary.pooledSer(pairIndex+1)-summary.pooledSer(pairIndex), ...
        bounds(1),bounds(2),bounds(2)<0};
end
transitions = cell2table(transitionRows,'VariableNames',{ ...
    'fromOrbitStartSec','toOrbitStartSec','fromPooledSer', ...
    'toPooledSer','changeSer','changeLower95','changeUpper95', ...
    'significantReverseJump'});

case1Exact = sum(loaded.case1Exact);
case2Candidate = summary.negativeSer(end);
case2Parent = summary.parentNegativeSer(end);
allPoints = all(summary.negativeSer<=summary.upperTargetSer & ...
    summary.positiveSer<=summary.upperTargetSer);
allPerSide = all(summary.bothClusterUppersBelowTarget);
allPooled = all(summary.pooledClusterUpperBelowTarget);
allMirror = all(summary.mirrorCompatible95);
noReverse = ~any(transitions.significantReverseJump);
formalPass = allPoints && allPerSide && allPooled && allMirror && ...
    noReverse && case1Exact==n && ...
    case2Candidate<=case2Parent && ...
    case2Candidate<=loaded.plan.targetCenterSer;
if formalPass
    status = 'ORBIT_PAIRED_FORMAL_PASS';
else
    status = 'ORBIT_PAIRED_FORMAL_FAIL';
end
audit = struct('status',status, ...
    'unitOfResampling','paired mirror packet', ...
    'bootstrapDraws',draws,'bootstrapSeed',bootstrapSeed, ...
    'sourceFormalStatus',loaded.shape.status, ...
    'allPointEstimatesBelowUpper',allPoints, ...
    'allPerSideClusterUppersBelowUpper',allPerSide, ...
    'allPooledClusterUppersBelowUpper',allPooled, ...
    'allMirrorPairedIntervalsIncludeZero',allMirror, ...
    'noSignificantReverseJump',noReverse, ...
    'significantReverseTransitionCount', ...
        sum(transitions.significantReverseJump), ...
    'case1ExactPackets',case1Exact,'case1TotalPackets',n, ...
    'case2CandidateSer',case2Candidate, ...
    'case2ParentSer',case2Parent, ...
    'case2TargetSer',loaded.plan.targetCenterSer, ...
    'failedFrames',sum(loaded.failed,'all'), ...
    'loboVerified',all(loaded.loboVerified,'all'), ...
    'receiverRerun',false,'receiverModified',false);

out = fullfile(sourceRoot,'paired_audit');
if ~isfolder(out),mkdir(out);end
sourceSha256 = exp1Sha256(sourcePath);
sourceCheckpointSha256 = exp1Sha256( ...
    fullfile(sourceRoot,'ORBIT_FORMAL_CHECKPOINT.mat'));
writetable(summary,fullfile(out,'ORBIT_PAIRED_SUMMARY.csv'));
writetable(transitions,fullfile(out,'ORBIT_PAIRED_TRANSITIONS.csv'));
save(fullfile(out,'ORBIT_PAIRED_AUDIT.mat'), ...
    'summary','transitions','audit','sourceSha256', ...
    'sourceCheckpointSha256','-v7.3');
localReport(fullfile(out,'ORBIT_PAIRED_AUDIT.md'), ...
    audit,summary,transitions,sourceSha256,sourceCheckpointSha256);
end

function localReport(path,audit,summary,transitions,sourceHash,checkpointHash)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0,error('EXP5V3:PairedReportOpen','Cannot open report: %s',message);end
cleanup = onCleanup(@()fclose(fid));
fprintf(fid,'# V3 orbit Formal paired-cluster statistical audit\n\n');
fprintf(fid,'Status: **%s**\n\n',audit.status);
fprintf(fid,['The original Formal receiver run and raw error counts are unchanged. ' ...
    'Its pooled symbol-level Wilson intervals are superseded here because ' ...
    'the two physical mirror sides share payload and noise seeds. ' ...
    'Each bootstrap resamples complete paired packets.\n\n']);
fprintf(fid,'- Resampling unit: %s\n',audit.unitOfResampling);
fprintf(fid,'- Bootstrap draws: %d\n',audit.bootstrapDraws);
fprintf(fid,'- Bootstrap seed: %d\n',audit.bootstrapSeed);
fprintf(fid,'- Original Formal status: %s\n',audit.sourceFormalStatus);
fprintf(fid,'- All raw point estimates below envelope: %d\n', ...
    audit.allPointEstimatesBelowUpper);
fprintf(fid,'- Per-side paired-cluster uppers below envelope: %d\n', ...
    audit.allPerSideClusterUppersBelowUpper);
fprintf(fid,'- Pooled paired-cluster uppers below envelope: %d\n', ...
    audit.allPooledClusterUppersBelowUpper);
fprintf(fid,'- Mirror-difference intervals include zero: %d\n', ...
    audit.allMirrorPairedIntervalsIncludeZero);
fprintf(fid,'- Significant reverse transitions: %d\n', ...
    audit.significantReverseTransitionCount);
fprintf(fid,'- Case1 exact packets: %d/%d\n', ...
    audit.case1ExactPackets,audit.case1TotalPackets);
fprintf(fid,'- Case2 candidate/parent/target SER: %.9g / %.9g / %.9g\n', ...
    audit.case2CandidateSer,audit.case2ParentSer,audit.case2TargetSer);
fprintf(fid,'- Failed frames: %d; LOBO verified: %d\n\n', ...
    audit.failedFrames,audit.loboVerified);
fprintf(fid,'## Significant reverse transitions\n\n');
for row = find(transitions.significantReverseJump).'
    fprintf(fid,['- %.2f -> %.2f s: pooled SER %.9g -> %.9g; ' ...
        'paired-cluster 95%% CI for change [%.9g, %.9g].\n'], ...
        transitions.fromOrbitStartSec(row), ...
        transitions.toOrbitStartSec(row), ...
        transitions.fromPooledSer(row),transitions.toPooledSer(row), ...
        transitions.changeLower95(row),transitions.changeUpper95(row));
end
fprintf(fid,'\n## Significant mirror asymmetries\n\n');
for row = find(~summary.mirrorCompatible95).'
    fprintf(fid,[ ...
        '- Negative t0 %.2f s / positive mirror t0 %.2f s: ' ...
        'negative minus positive SER %.9g; paired-cluster 95%% CI ' ...
        '[%.9g, %.9g].\n'], ...
        summary.negativeOrbitStartSec(row), ...
        summary.positiveMirrorStartSec(row), ...
        summary.mirrorDifferenceSer(row), ...
        summary.mirrorDifferenceLower95(row), ...
        summary.mirrorDifferenceUpper95(row));
end
fprintf(fid,'\n## Source identity\n\n');
fprintf(fid,'- Formal result MAT SHA-256: `%s`\n',sourceHash);
fprintf(fid,'- Formal checkpoint SHA-256: `%s`\n',checkpointHash);
fprintf(fid,'- Orbit points: %d; paired packets per point: %d.\n', ...
    height(summary),summary.packetsPerSide(1));
fprintf(fid,['- Existing raw-count and raw-SER figures remain valid: ' ...
    'their measured values were not fitted, interpolated, or smoothed.\n']);
clear cleanup
end
