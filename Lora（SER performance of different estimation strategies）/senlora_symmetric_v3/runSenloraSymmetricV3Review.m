function output = runSenloraSymmetricV3Review()
%RUNSENLORASYMMETRICV3REVIEW Independent raw-count full-orbit V3 review.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
addpath(fullfile(paths.projectRoot,'senlora_symmetric_v2'));
config = exp1Config();
plan = senloraSymmetricV3Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
negative = plan.negativeOrbitStartSec(:);
n = plan.reviewPackets;
pairCount = numel(negative);
payloadCount = config.parent.payloadSymbolCount;
jobCount = pairCount*n;
jobPairs = repmat((1:pairCount).',n,1);
jobPackets = repelem((1:n).',pairCount);
v2Errors = zeros(jobCount,2,'uint16');
v3Errors = zeros(jobCount,2,'uint16');
parentErrors = zeros(jobCount,2,'uint16');
failed = false(jobCount,2);
loboVerified = false(jobCount,2);
case1Exact = false(jobCount,1);
parentProtected = false(jobCount,2);

pool = gcp('nocreate');
if isempty(pool), parpool('local',6); end
parfor job = 1:jobCount
    pairIndex = jobPairs(job);
    packetId = jobPackets(job);
    starts = [negative(pairIndex), ... %#ok<PFBNS>
        -negative(pairIndex)-plan.frameDurationSec]; %#ok<PFBNS>
    ledger = senloraSymmetricV3SeedPlan(config,plan,'review', ...
        pairIndex,plan.snrDb,packetId);
    localV2 = zeros(1,2,'uint16');
    localV3 = zeros(1,2,'uint16');
    localParent = zeros(1,2,'uint16');
    localFailed = false(1,2);
    localLobo = false(1,2);
    localProtected = false(1,2);
    localCase1Exact = true;
    for side = 1:2
        try
            frame = exp1GenerateFrame(config,starts(side),plan.snrDb,ledger);
            common = v4CommonBootstrap( ...
                frame.observation.rxPhysical(1:8,:),config.parent, ...
                SearchStepBins=parameters.searchStepBins); %#ok<PFBNS>
            result = senloraSymmetricV3Decode( ...
                frame.observation,common,config,plan);
            truth = frame.truth.payloadPhysicalBins(:);
            localV2(side) = uint16(sum( ...
                result.v2CandidateDetectedPhysicalBins(:)~=truth));
            localV3(side) = uint16(sum( ...
                result.detectedPhysicalBins(:)~=truth));
            localParent(side) = uint16(sum( ...
                result.frozenParentHypothesis.detectedPhysicalBins(:)~=truth));
            localLobo(side) = result.decision.leaveOneBlockOut && ...
                ~result.decision.selfBlockUsedForFit;
            localProtected(side) = result.decision.parentStaticProtected;
            if pairIndex==1 && side==1
                localCase1Exact = isequal( ...
                    result.detectedPhysicalBins(:), ...
                    result.frozenParentHypothesis.detectedPhysicalBins(:)) && ...
                    isequal(result.hardDecodedDataBits(:), ...
                    result.frozenParentHypothesis.hardDecodedDataBits(:));
            end
        catch exception
            localFailed(side) = true;
            localV2(side) = uint16(payloadCount);
            localV3(side) = uint16(payloadCount);
            localParent(side) = uint16(payloadCount);
            if pairIndex==1 && side==1, localCase1Exact = false; end
            warning('EXP5V3:ReviewFailure', ...
                'Pair %d packet %d side %d: %s', ...
                pairIndex,packetId,side,exception.message);
        end
    end
    v2Errors(job,:) = localV2;
    v3Errors(job,:) = localV3;
    parentErrors(job,:) = localParent;
    failed(job,:) = localFailed;
    loboVerified(job,:) = localLobo;
    parentProtected(job,:) = localProtected;
    case1Exact(job) = localCase1Exact;
end

perSideCount = n*payloadCount;
pooledCount = 2*perSideCount;
rows = cell(pairCount,26);
pooledLower = zeros(pairCount,1);
pooledUpper = zeros(pairCount,1);
for pairIndex = 1:pairCount
    jobs = jobPairs==pairIndex;
    v2 = sum(double(v2Errors(jobs,:)),1);
    v3 = sum(double(v3Errors(jobs,:)),1);
    parent = sum(double(parentErrors(jobs,:)),1);
    pooled = sum(v3);
    target = localUpperTarget(negative(pairIndex),plan);
    [negativeLower,negativeUpper] = localWilson(v3(1),perSideCount);
    [positiveLower,positiveUpper] = localWilson(v3(2),perSideCount);
    [pooledLower(pairIndex),pooledUpper(pairIndex)] = ...
        localWilson(pooled,pooledCount);
    rows(pairIndex,:) = {negative(pairIndex), ...
        -negative(pairIndex)-plan.frameDurationSec,n, ...
        v3(1),v3(2),pooled,v3(1)/perSideCount,v3(2)/perSideCount, ...
        pooled/pooledCount,negativeLower,negativeUpper, ...
        positiveLower,positiveUpper,pooledLower(pairIndex), ...
        pooledUpper(pairIndex),target, ...
        negativeLower<=positiveUpper && positiveLower<=negativeUpper, ...
        v2(1)/perSideCount,v2(2)/perSideCount, ...
        parent(1)/perSideCount,parent(2)/perSideCount, ...
        sum(parentProtected(jobs,1)),sum(parentProtected(jobs,2)), ...
        sum(failed(jobs,:),'all'),all(loboVerified(jobs,:),'all'), ...
        v3(1)<=perSideCount*target && v3(2)<=perSideCount*target};
end
summary = cell2table(rows,'VariableNames',{ ...
    'negativeOrbitStartSec','positiveMirrorStartSec','packets', ...
    'negativeRawErrors','positiveRawErrors','pooledRawErrors', ...
    'negativeSer','positiveSer','pooledRawSer','negativeWilsonLower95', ...
    'negativeWilsonUpper95','positiveWilsonLower95', ...
    'positiveWilsonUpper95','pooledWilsonLower95', ...
    'pooledWilsonUpper95','upperTargetSer', ...
    'mirrorWilsonIntervalsOverlap','v2NegativeSer','v2PositiveSer', ...
    'parentNegativeSer','parentPositiveSer', ...
    'negativeParentProtectedPackets','positiveParentProtectedPackets', ...
    'failedPackets','leaveOneBlockOutVerified','bothSidesBelowUpper'});
noSignificantReverse = true;
for row = 1:pairCount-1
    if pooledUpper(row+1)<pooledLower(row)
        noSignificantReverse = false;
    end
end
case1Jobs = jobPairs==1;
case2Jobs = jobPairs==pairCount;
case2Candidate = sum(double(v3Errors(case2Jobs,1)))/perSideCount;
case2Parent = sum(double(parentErrors(case2Jobs,1)))/perSideCount;
shape = struct('status','AWAITING_USER_REVIEW', ...
    'usesRawMeasuredCountsOnly',true,'curveFitted',false, ...
    'interpolationApplied',false,'smoothingApplied',false, ...
    'allPointEstimatesBelowUpper',all(summary.bothSidesBelowUpper), ...
    'allPerSideWilsonUpperBelowUpper',all( ...
        summary.negativeWilsonUpper95<=summary.upperTargetSer & ...
        summary.positiveWilsonUpper95<=summary.upperTargetSer), ...
    'allPooledWilsonUpperBelowUpper',all( ...
        summary.pooledWilsonUpper95<=summary.upperTargetSer), ...
    'allMirrorWilsonIntervalsOverlap',all( ...
        summary.mirrorWilsonIntervalsOverlap), ...
    'noStatisticallySignificantReverseJump',noSignificantReverse, ...
    'case1ExactPackets',sum(case1Exact(case1Jobs)), ...
    'case1TotalPackets',n,'case2ParentSer',case2Parent, ...
    'case2CandidateSer',case2Candidate, ...
    'case2TargetSer',plan.targetCenterSer, ...
    'case2NotWorse',case2Candidate<=case2Parent, ...
    'case2BelowTarget',case2Candidate<=plan.targetCenterSer, ...
    'leaveOneBlockOutVerified',all(loboVerified,'all'), ...
    'failedPackets',sum(failed,'all'), ...
    'v2PooledErrors',sum(v2Errors,'all'), ...
    'v3PooledErrors',sum(v3Errors,'all'), ...
    'v3NoWorseOverall',sum(v3Errors,'all')<=sum(v2Errors,'all'), ...
    'formalStarted',false);
root = fullfile(paths.resultsRoot,'senlora_symmetric_v3','review');
if ~isfolder(root), mkdir(root); end
csvPath = fullfile(root,'RAW_REVIEW_SUMMARY.csv');
matPath = fullfile(root,'RAW_REVIEW_RESULT.mat');
figurePath = fullfile(root,'RAW_REVIEW_COUNT.png');
writetable(summary,csvPath);
save(matPath,'summary','shape','plan','v2Errors','v3Errors', ...
    'parentErrors','failed','loboVerified','case1Exact', ...
    'parentProtected','-v7.3');
localPlot(summary,figurePath,perSideCount);
output = struct('status',shape.status,'summary',summary,'shape',shape, ...
    'csvPath',csvPath,'matPath',matPath,'figurePath',figurePath, ...
    'formalStarted',false);
end

function target = localUpperTarget(t0,plan)
u = min(1,max(0,(t0-plan.negativeOrbitStartSec(1))/ ...
    abs(plan.negativeOrbitStartSec(1))));
target = 10^(log10(plan.targetCase1Ser)+u*( ...
    log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
end

function [lower,upper] = localWilson(errorCount,total)
z = 1.95996398454005;
p = errorCount/total;
denominator = 1+z^2/total;
center = (p+z^2/(2*total))/denominator;
radius = z*sqrt(p*(1-p)/total+z^2/(4*total^2))/denominator;
lower = max(0,center-radius);
upper = min(1,center+radius);
end

function localPlot(summary,path,perSideCount)
x = summary.negativeOrbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1050 620]);
plot(x,summary.negativeRawErrors,'o','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'Color',[0 0.35 0.70], ...
    'DisplayName','Negative pass raw errors');
hold on
plot(x,summary.positiveRawErrors,'s','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'Color',[0.80 0.30 0.12], ...
    'DisplayName','Mirrored positive pass raw errors');
plot(x,summary.upperTargetSer*perSideCount,':d','LineWidth',1.8, ...
    'Color',[0.75 0.25 0.75], ...
    'DisplayName','Analytical per-side upper count');
grid on
xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('Symbol error count per side');
title({'SenLoRa V3 raw Review counts', ...
    'No fitting, interpolation, or smoothing'});
legend('Location','northwest');
exportgraphics(f,path,'Resolution',220);
close(f);
end
