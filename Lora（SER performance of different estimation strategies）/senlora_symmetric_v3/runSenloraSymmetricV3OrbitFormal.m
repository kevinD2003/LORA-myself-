function output = runSenloraSymmetricV3OrbitFormal(options)
%RUNSENLORASYMMETRICV3ORBITFORMAL Independent mirrored full-orbit Formal.

arguments
    options.StopAfterPacket (1,1) double {mustBeInteger,mustBePositive} = 1000
    options.WorkerCount (1,1) double {mustBeInteger,mustBePositive} = 6
end

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'review_first_v1'));
addpath(fullfile(paths.projectRoot,'senlora_symmetric_v2'));
config = exp1Config();
plan = senloraSymmetricV3Config(config);
parameters = v4LoadMethodAlignedR3ParametersV1();
parentAudit = exp1ValidateFrozenParent(config);
projectDigest = exp1ImplementationDigest(config);
negative = plan.negativeOrbitStartSec(:);
pairCount = numel(negative);
formalPackets = config.formalPackets;
maximumPacket = min(formalPackets,options.StopAfterPacket);
payloadCount = config.parent.payloadSymbolCount;
checkpointEvery = config.checkpointEveryPackets;
root = fullfile(paths.resultsRoot,'senlora_symmetric_v3','orbit_formal');
if ~isfolder(root),mkdir(root);end
checkpointPath = fullfile(root,'ORBIT_FORMAL_CHECKPOINT.mat');
signature = localSignature(paths,config,plan,parentAudit, ...
    projectDigest,negative,formalPackets);

if isfile(checkpointPath)
    stored = load(checkpointPath);
    localValidateCheckpoint(stored,signature,pairCount,formalPackets);
    candidateErrors = stored.candidateErrors;
    parentErrors = stored.parentErrors;
    failed = stored.failed;
    loboVerified = stored.loboVerified;
    case1Exact = stored.case1Exact;
    completed = stored.completed;
    startedUtc = stored.startedUtc;
    lastUpdatedUtc = stored.lastUpdatedUtc;
else
    candidateErrors = zeros(pairCount,2,formalPackets,'uint16');
    parentErrors = zeros(pairCount,2,formalPackets,'uint16');
    failed = false(pairCount,2,formalPackets);
    loboVerified = false(pairCount,2,formalPackets);
    case1Exact = false(formalPackets,1);
    completed = false(pairCount,formalPackets);
    startedUtc = localUtcNow();
    lastUpdatedUtc = startedUtc;
end

if any(~completed(:,1:maximumPacket),'all')
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('local',options.WorkerCount);
    elseif pool.NumWorkers~=options.WorkerCount
        error('EXP5V3:OrbitFormalWorkerCount', ...
            'Existing pool has %d workers; requested %d.', ...
            pool.NumWorkers,options.WorkerCount);
    end
end

for blockStart = 1:checkpointEvery:maximumPacket
    packetIds = blockStart:min(maximumPacket, ...
        blockStart+checkpointEvery-1);
    [pairRows,packetColumns] = find(~completed(:,packetIds));
    if isempty(pairRows),continue;end
    jobPairs = pairRows;
    jobPackets = packetIds(packetColumns).';
    jobCount = numel(jobPairs);
    jobCandidate = zeros(jobCount,2,'uint16');
    jobParent = zeros(jobCount,2,'uint16');
    jobFailed = false(jobCount,2);
    jobLobo = false(jobCount,2);
    jobCase1Exact = false(jobCount,1);
    parfor job = 1:jobCount
        packet = localEvaluatePair(jobPairs(job),jobPackets(job), ...
            negative,config,plan,parameters,payloadCount);
        jobCandidate(job,:) = packet.candidateErrors;
        jobParent(job,:) = packet.parentErrors;
        jobFailed(job,:) = packet.failed;
        jobLobo(job,:) = packet.loboVerified;
        jobCase1Exact(job) = packet.case1Exact;
    end
    for job = 1:jobCount
        pairIndex = jobPairs(job);
        packetId = jobPackets(job);
        candidateErrors(pairIndex,:,packetId) = jobCandidate(job,:);
        parentErrors(pairIndex,:,packetId) = jobParent(job,:);
        failed(pairIndex,:,packetId) = jobFailed(job,:);
        loboVerified(pairIndex,:,packetId) = jobLobo(job,:);
        if pairIndex==1,case1Exact(packetId) = jobCase1Exact(job);end
        completed(pairIndex,packetId) = true;
    end
    lastUpdatedUtc = localUtcNow();
    localSaveCheckpoint(checkpointPath,signature,candidateErrors, ...
        parentErrors,failed,loboVerified,case1Exact,completed, ...
        startedUtc,lastUpdatedUtc);
    fprintf(['EXP5V3 orbit Formal packets=%d/%d completed=%d/%d ' ...
        'failures=%d case1Exact=%d/%d updated=%s\n'], ...
        max(packetIds),formalPackets, ...
        sum(completed(:,1:max(packetIds)),'all'), ...
        pairCount*max(packetIds),sum(failed,'all'), ...
        sum(case1Exact(1:max(packetIds))),max(packetIds),lastUpdatedUtc);
end

if ~all(completed,'all')
    output = struct('status','ORBIT_FORMAL_IN_PROGRESS', ...
        'completedPairPackets',sum(completed,'all'), ...
        'totalPairPackets',numel(completed), ...
        'failedPackets',sum(failed,'all'), ...
        'checkpointPath',checkpointPath, ...
        'lastUpdatedUtc',lastUpdatedUtc, ...
        'formalStarted',true,'formalComplete',false);
    return
end

[summary,shape] = localSummarize(candidateErrors,parentErrors, ...
    failed,loboVerified,case1Exact,negative,config,plan);
csvPath = fullfile(root,'ORBIT_FORMAL_SUMMARY.csv');
matPath = fullfile(root,'ORBIT_FORMAL_RESULT.mat');
countFigurePath = fullfile(root,'ORBIT_RAW_COUNT.png');
serFigurePath = fullfile(root,'ORBIT_RAW_SER.png');
reportPath = fullfile(root,'ORBIT_FORMAL_REPORT.md');
writetable(summary,csvPath);
save(matPath,'summary','shape','signature','plan','candidateErrors', ...
    'parentErrors','failed','loboVerified','case1Exact', ...
    'completed','startedUtc','lastUpdatedUtc','-v7.3');
localPlot(summary,countFigurePath,serFigurePath, ...
    formalPackets*payloadCount);
localMarkdown(reportPath,summary,shape);
output = struct('status',shape.status,'summary',summary,'shape',shape, ...
    'csvPath',csvPath,'matPath',matPath, ...
    'countFigurePath',countFigurePath,'serFigurePath',serFigurePath, ...
    'reportPath',reportPath,'checkpointPath',checkpointPath, ...
    'lastUpdatedUtc',lastUpdatedUtc, ...
    'formalStarted',true,'formalComplete',true);
end

function packet = localEvaluatePair(pairIndex,packetId,negative, ...
        config,plan,parameters,payloadCount)
starts = [negative(pairIndex), ...
    -negative(pairIndex)-plan.frameDurationSec];
errors = zeros(1,2,'uint16');
parentErrors = zeros(1,2,'uint16');
failed = false(1,2);
lobo = false(1,2);
case1Exact = true;
ledger = senloraSymmetricV3SeedPlan(config,plan,'formal', ...
    100+pairIndex,plan.snrDb,packetId);
for side = 1:2
    parentAvailable = false;
    try
        frame = exp1GenerateFrame(config,starts(side),plan.snrDb,ledger);
        common = v4CommonBootstrap( ...
            frame.observation.rxPhysical(1:8,:),config.parent, ...
            SearchStepBins=parameters.searchStepBins);
        result = senloraSymmetricV3Decode( ...
            frame.observation,common,config,plan);
        parent = result.frozenParentHypothesis;
        parentAvailable = true;
        truth = frame.truth.payloadPhysicalBins(:);
        errors(side) = uint16(sum( ...
            result.detectedPhysicalBins(:)~=truth));
        parentErrors(side) = uint16(sum( ...
            parent.detectedPhysicalBins(:)~=truth));
        lobo(side) = result.decision.leaveOneBlockOut && ...
            ~result.decision.selfBlockUsedForFit;
        if pairIndex==1 && side==1
            case1Exact = isequal(result.detectedPhysicalBins(:), ...
                parent.detectedPhysicalBins(:)) && isequal( ...
                result.hardDecodedDataBits(:),parent.hardDecodedDataBits(:));
        end
    catch exception
        failed(side) = true;
        errors(side) = uint16(payloadCount);
        if ~parentAvailable,parentErrors(side) = uint16(payloadCount);end
        if pairIndex==1 && side==1,case1Exact = false;end
        warning('EXP5V3:OrbitFormalPacketFailure', ...
            'Pair %d packet %d side %d: %s', ...
            pairIndex,packetId,side,exception.message);
    end
end
packet = struct('candidateErrors',errors, ...
    'parentErrors',parentErrors,'failed',failed, ...
    'loboVerified',lobo,'case1Exact',case1Exact);
end

function signature = localSignature(paths,config,plan,parentAudit, ...
        projectDigest,negative,formalPackets)
entry = which('runSenloraSymmetricV3OrbitFormal');
required = string(matlab.codetools.requiredFilesAndProducts(entry));
explicitNames = {'runSenloraSymmetricV3OrbitFormal', ...
    'senloraSymmetricV3Config','senloraSymmetricV3Decode', ...
    'senloraSymmetricV3SeedPlan','senloraSymmetricV2Config', ...
    'senloraSymmetricV2Decode','exp1Config','exp1GenerateFrame', ...
    'exp1Stage55Decode','v4CommonBootstrap', ...
    'v4LoadMethodAlignedR3ParametersV1','reviewStaticHypothesis'};
explicitPaths = strings(numel(explicitNames),1);
for index = 1:numel(explicitNames)
    explicitPaths(index) = string(which(explicitNames{index}));
    if strlength(explicitPaths(index))==0
        error('EXP5V3:OrbitFormalDependencyMissing', ...
            'Cannot resolve dependency %s.',explicitNames{index});
    end
end
allPaths = unique([required(:);explicitPaths]);
inScope = startsWith(allPaths,string(paths.projectRoot)+filesep, ...
    'IgnoreCase',true) | startsWith(allPaths, ...
    string(config.parentRoot)+filesep,'IgnoreCase',true);
sourcePaths = sort(allPaths(inScope));
sourceHashes = strings(size(sourcePaths));
for index = 1:numel(sourcePaths)
    sourceHashes(index) = exp1Sha256(sourcePaths(index));
end
signature = struct('identity',plan.identity, ...
    'receiverVersion',plan.receiverVersion, ...
    'formalRootSeed',plan.formalRootSeed, ...
    'formalPackets',formalPackets,'snrDb',plan.snrDb, ...
    'orbitEventIndexOffset',100, ...
    'negativeOrbitStartSec',negative, ...
    'frameDurationSec',plan.frameDurationSec, ...
    'payloadSymbolCount',config.parent.payloadSymbolCount, ...
    'parentManifestSha256',parentAudit.manifestSha256, ...
    'projectImplementationSha256',projectDigest.sha256, ...
    'sourcePaths',sourcePaths,'sourceHashes',sourceHashes);
end

function localValidateCheckpoint(stored,signature,pairCount,formalPackets)
required = {'signature','candidateErrors','parentErrors','failed', ...
    'loboVerified','case1Exact','completed','startedUtc', ...
    'lastUpdatedUtc','stateDigest'};
for index = 1:numel(required)
    if ~isfield(stored,required{index})
        error('EXP5V3:OrbitCheckpointField', ...
            'Checkpoint is missing %s.',required{index});
    end
end
if ~isequaln(stored.signature,signature)
    error('EXP5V3:OrbitCheckpointSignature', ...
        'Orbit checkpoint signature does not match frozen inputs.');
end
expected = [pairCount,2,formalPackets];
if ~isequal(size(stored.candidateErrors),expected) || ...
        ~isequal(size(stored.parentErrors),expected) || ...
        ~isequal(size(stored.failed),expected) || ...
        ~isequal(size(stored.loboVerified),expected) || ...
        ~isequal(size(stored.completed),[pairCount,formalPackets]) || ...
        ~isequal(size(stored.case1Exact),[formalPackets,1])
    error('EXP5V3:OrbitCheckpointSize', ...
        'Orbit checkpoint array dimensions are invalid.');
end
completedSides = repmat(reshape(stored.completed, ...
    pairCount,1,formalPackets),1,2,1);
success = completedSides & ~stored.failed;
if any(stored.failed & ~completedSides,'all') || ...
        any(stored.candidateErrors(~completedSides)~=0,'all') || ...
        any(stored.parentErrors(~completedSides)~=0,'all') || ...
        any(stored.loboVerified(~completedSides),'all') || ...
        any(stored.case1Exact(~stored.completed(1,:).')) || ...
        ~all(stored.loboVerified(success),'all')
    error('EXP5V3:OrbitCheckpointConsistency', ...
        'Orbit checkpoint conflicts with completion mask.');
end
actual = localStateDigest(stored.signature,stored.candidateErrors, ...
    stored.parentErrors,stored.failed,stored.loboVerified, ...
    stored.case1Exact,stored.completed,stored.startedUtc, ...
    stored.lastUpdatedUtc);
if ~strcmpi(stored.stateDigest,actual)
    error('EXP5V3:OrbitCheckpointDigest', ...
        'Orbit checkpoint digest does not match contents.');
end
end

function localSaveCheckpoint(path,signature,candidateErrors,parentErrors, ...
        failed,loboVerified,case1Exact,completed,startedUtc,lastUpdatedUtc)
stateDigest = localStateDigest(signature,candidateErrors,parentErrors, ...
    failed,loboVerified,case1Exact,completed,startedUtc,lastUpdatedUtc);
temporaryPath = [path '.tmp.' char(java.util.UUID.randomUUID) '.mat'];
save(temporaryPath,'signature','candidateErrors','parentErrors', ...
    'failed','loboVerified','case1Exact','completed', ...
    'startedUtc','lastUpdatedUtc','stateDigest','-v7.3');
probe = load(temporaryPath);
actual = localStateDigest(probe.signature,probe.candidateErrors, ...
    probe.parentErrors,probe.failed,probe.loboVerified, ...
    probe.case1Exact,probe.completed,probe.startedUtc, ...
    probe.lastUpdatedUtc);
if ~strcmpi(probe.stateDigest,actual)
    error('EXP5V3:OrbitTemporaryDigest', ...
        'Temporary checkpoint failed digest verification.');
end
[moved,message] = movefile(temporaryPath,path,'f');
if ~moved
    error('EXP5V3:OrbitCheckpointMove', ...
        'Cannot replace checkpoint: %s',message);
end
end

function hash = localStateDigest(signature,candidateErrors,parentErrors, ...
        failed,loboVerified,case1Exact,completed,startedUtc,lastUpdatedUtc)
digest = java.security.MessageDigest.getInstance('SHA-256');
localDigestText(digest,'signature',jsonencode(signature));
names = {'candidateErrors','parentErrors','failed', ...
    'loboVerified','case1Exact','completed'};
values = {candidateErrors,parentErrors,failed, ...
    loboVerified,case1Exact,completed};
for index = 1:numel(names)
    localDigestArray(digest,names{index},values{index});
end
localDigestText(digest,'startedUtc',startedUtc);
localDigestText(digest,'lastUpdatedUtc',lastUpdatedUtc);
bytes = typecast(digest.digest(),'uint8');
hash = lower(reshape(dec2hex(bytes,2).',1,[]));
end

function localDigestArray(digest,name,value)
localDigestText(digest,[name ':class'],class(value));
dimensions = typecast(uint64(size(value)),'uint8');
digest.update(typecast(dimensions(:),'int8'));
if islogical(value)
    bytes = uint8(value(:));
else
    bytes = typecast(value(:),'uint8');
end
if ~isempty(bytes),digest.update(typecast(bytes(:),'int8'));end
end

function localDigestText(digest,name,value)
bytes = unicode2native([name '=' char(value)],'UTF-8');
if ~isempty(bytes),digest.update(typecast(uint8(bytes(:)),'int8'));end
end

function [summary,shape] = localSummarize(errors,parentErrors,failed, ...
        loboVerified,case1Exact,negative,config,plan)
n = size(errors,3);
perSideCount = n*config.parent.payloadSymbolCount;
pooledCount = 2*perSideCount;
rows = cell(numel(negative),18);
pooledLower = zeros(numel(negative),1);
pooledUpper = zeros(numel(negative),1);
for row = 1:numel(negative)
    neg = sum(double(errors(row,1,:)),'all');
    pos = sum(double(errors(row,2,:)),'all');
    parentNeg = sum(double(parentErrors(row,1,:)),'all');
    parentPos = sum(double(parentErrors(row,2,:)),'all');
    [negLower,negUpper] = localWilson(neg,perSideCount);
    [posLower,posUpper] = localWilson(pos,perSideCount);
    [pooledLower(row),pooledUpper(row)] = ...
        localWilson(neg+pos,pooledCount);
    u = (negative(row)-negative(1))/abs(negative(1));
    target = 10^(log10(plan.targetCase1Ser)+u*( ...
        log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
    rows(row,:) = {negative(row), ...
        -negative(row)-plan.frameDurationSec,n,neg,pos, ...
        neg/perSideCount,pos/perSideCount,(neg+pos)/pooledCount, ...
        negLower,negUpper,posLower,posUpper, ...
        pooledLower(row),pooledUpper(row),target, ...
        negLower<=posUpper && posLower<=negUpper, ...
        parentNeg/perSideCount,parentPos/perSideCount};
end
summary = cell2table(rows,'VariableNames',{ ...
    'negativeOrbitStartSec','positiveMirrorStartSec','packets', ...
    'negativeRawErrors','positiveRawErrors', ...
    'negativeSer','positiveSer','pooledSer', ...
    'negativeWilsonLower95','negativeWilsonUpper95', ...
    'positiveWilsonLower95','positiveWilsonUpper95', ...
    'pooledWilsonLower95','pooledWilsonUpper95','upperTargetSer', ...
    'mirrorWilsonOverlap','parentNegativeSer','parentPositiveSer'});
noReverse = true;
for row = 1:height(summary)-1
    if pooledUpper(row+1)<pooledLower(row),noReverse = false;end
end
allPoints = all(summary.negativeSer<=summary.upperTargetSer & ...
    summary.positiveSer<=summary.upperTargetSer);
allPerSideWilson = all( ...
    summary.negativeWilsonUpper95<=summary.upperTargetSer & ...
    summary.positiveWilsonUpper95<=summary.upperTargetSer);
allPooledWilson = all(summary.pooledWilsonUpper95<=summary.upperTargetSer);
allMirror = all(summary.mirrorWilsonOverlap);
case1Count = sum(case1Exact);
case2Candidate = summary.negativeSer(end);
case2Parent = summary.parentNegativeSer(end);
allLobo = all(loboVerified,'all');
failureCount = sum(failed,'all');
pass = allPoints && allPerSideWilson && allPooledWilson && ...
    allMirror && noReverse && case1Count==n && ...
    case2Candidate<=case2Parent && ...
    case2Candidate<=plan.targetCenterSer && ...
    allLobo && failureCount==0;
if pass,status='ORBIT_FORMAL_PASS';else,status='ORBIT_FORMAL_FAIL';end
shape = struct('status',status,'allPointEstimatesBelowUpper',allPoints, ...
    'allPerSideWilsonUpperBelowUpper',allPerSideWilson, ...
    'allPooledWilsonUpperBelowUpper',allPooledWilson, ...
    'allMirrorWilsonIntervalsOverlap',allMirror, ...
    'noStatisticallySignificantReverseJump',noReverse, ...
    'case1ExactPackets',case1Count,'case1TotalPackets',n, ...
    'case2CandidateSer',case2Candidate,'case2ParentSer',case2Parent, ...
    'case2TargetSer',plan.targetCenterSer, ...
    'loboVerified',allLobo,'failedPackets',failureCount, ...
    'formalStarted',true,'formalComplete',true);
end

function [lower,upper] = localWilson(errors,total)
z = 1.95996398454005;
p = errors/total;
d = 1+z^2/total;
center = (p+z^2/(2*total))/d;
radius = z*sqrt(p*(1-p)/total+z^2/(4*total^2))/d;
lower = max(0,center-radius);
upper = min(1,center+radius);
end

function localPlot(summary,countPath,serPath,perSideCount)
x = summary.negativeOrbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1050 670]);
plot(x,summary.negativeRawErrors,'o','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'Color',[0 0.35 0.70], ...
    'DisplayName','Negative pass raw errors');
hold on
plot(x,summary.positiveRawErrors,'s','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'Color',[0.80 0.30 0.12], ...
    'DisplayName','Mirrored positive pass raw errors');
plot(x,summary.upperTargetSer*perSideCount,':d','LineWidth',1.8, ...
    'Color',[0.75 0.25 0.75], ...
    'DisplayName','Analytical per-side upper count');
grid on;xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('Symbol error count per side');
title({'SenLoRa V3 full-orbit Formal raw counts', ...
    'Measured points are not fitted, interpolated, or smoothed'});
legend('Location','northwest');
exportgraphics(f,countPath,'Resolution',220);close(f);

sideFloor = 0.5/perSideCount;
pooledFloor = 0.5/(2*perSideCount);
f = figure('Visible','off','Color','w','Position',[100 100 1120 680]);
semilogy(x,max(summary.negativeSer,sideFloor),'o', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.5, ...
    'Color',[0 0.35 0.70],'DisplayName','Negative pass raw SER');
hold on
semilogy(x,max(summary.positiveSer,sideFloor),'s', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.5, ...
    'Color',[0.80 0.30 0.12], ...
    'DisplayName','Mirrored positive pass raw SER');
semilogy(x,max(summary.pooledSer,pooledFloor),'^', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.6, ...
    'Color',[0.15 0.50 0.20], ...
    'DisplayName','Physical-mirror pooled raw SER');
semilogy(x,summary.upperTargetSer,':d','LineWidth',2, ...
    'Color',[0.75 0.25 0.75], ...
    'DisplayName','Analytical SER upper envelope');
grid on;grid minor;xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('SER');
title({'SenLoRa V3 full-orbit Formal raw SER', ...
    'Zero counts use a 0.5-count display floor; measured points are not fitted'});
legend('Location','northwest');
exportgraphics(f,serPath,'Resolution',220);close(f);
end

function localMarkdown(path,summary,shape)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0,error('EXP5V3:OrbitReportOpen','Cannot open report: %s',message);end
cleanup = onCleanup(@()fclose(fid));
fprintf(fid,'# SenLoRa V3 full-orbit Formal\n\n');
fprintf(fid,'Status: **%s**  \nFormal complete: **YES**\n\n',shape.status);
fprintf(fid,'- Raw point estimates below upper: %d\n', ...
    shape.allPointEstimatesBelowUpper);
fprintf(fid,'- Per-side Wilson upper bounds below upper: %d\n', ...
    shape.allPerSideWilsonUpperBelowUpper);
fprintf(fid,'- Pooled Wilson upper bounds below upper: %d\n', ...
    shape.allPooledWilsonUpperBelowUpper);
fprintf(fid,'- All mirror Wilson intervals overlap: %d\n', ...
    shape.allMirrorWilsonIntervalsOverlap);
fprintf(fid,'- No significant reverse jump: %d\n', ...
    shape.noStatisticallySignificantReverseJump);
fprintf(fid,'- Case1 exact packets: %d/%d\n', ...
    shape.case1ExactPackets,shape.case1TotalPackets);
fprintf(fid,'- Case2 V3/parent/target SER: %.9g / %.9g / %.9g\n', ...
    shape.case2CandidateSer,shape.case2ParentSer,shape.case2TargetSer);
fprintf(fid,'- LOBO verified: %d\n- Failed frames: %d\n\n', ...
    shape.loboVerified,shape.failedPackets);
fprintf(fid,['| Negative t0 | Positive mirror t0 | Negative errors | ' ...
    'Positive errors | Negative SER | Positive SER | Pooled SER | ' ...
    'Target SER |\n']);
fprintf(fid,'|---:|---:|---:|---:|---:|---:|---:|---:|\n');
for row = 1:height(summary)
    fprintf(fid,'| %.6g | %.6g | %d | %d | %.9g | %.9g | %.9g | %.9g |\n', ...
        summary.negativeOrbitStartSec(row), ...
        summary.positiveMirrorStartSec(row), ...
        summary.negativeRawErrors(row),summary.positiveRawErrors(row), ...
        summary.negativeSer(row),summary.positiveSer(row), ...
        summary.pooledSer(row),summary.upperTargetSer(row));
end
clear cleanup
end

function stamp = localUtcNow()
stamp = char(datetime('now','TimeZone','UTC', ...
    'Format','yyyy-MM-dd''T''HH:mm:ss''Z'''));
end
