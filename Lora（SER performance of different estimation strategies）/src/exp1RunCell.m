function result = exp1RunCell(outputPhase,orbitIndex,snrDb,packetCount,varargin)
%EXP1RUNCELL Resumable paired Monte Carlo cell with strict signatures.

parser = inputParser();
addParameter(parser,'MethodSet','main',@(x)ischar(x)||isstring(x));
addParameter(parser,'SeedPhase',outputPhase,@(x)ischar(x)||isstring(x));
addParameter(parser,'SeedMode','registered',@(x)ischar(x)||isstring(x));
parse(parser,varargin{:});
options = parser.Results;

exp1SetupPaths();
config = exp1Config();
parentAudit = exp1ValidateFrozenParent(config);
implementation = exp1ImplementationDigest(config);
if orbitIndex < 1 || orbitIndex > numel(config.orbitStartSec)
    error('EXP1:OrbitIndex','Orbit index is outside the frozen matrix.');
end
if strcmpi(options.MethodSet,'main')
    methodNames = config.methodNames;
elseif strcmpi(options.MethodSet,'ablation')
    methodNames = config.ablationMethodNames;
else
    error('EXP1:MethodSet','Unknown method set %s.',options.MethodSet);
end
orbitStartSec = config.orbitStartSec(orbitIndex);
cellId = exp1CellId(orbitStartSec,snrDb);
folder = fullfile(config.projectRoot,'results',char(outputPhase),cellId);
if ~isfolder(folder)
    mkdir(folder);
end
signatureInput = struct('experimentId',config.experimentId, ...
    'specVersion',config.specVersion,'parentManifest',parentAudit.manifestSha256, ...
    'implementationSha256',implementation.sha256, ...
    'outputPhase',char(outputPhase),'seedPhase',char(options.SeedPhase), ...
    'seedMode',char(options.SeedMode),'orbitIndex',orbitIndex, ...
    'orbitStartSec',orbitStartSec,'snrDb',snrDb, ...
    'packetCount',packetCount,'methodNames',{methodNames});
signature = exp1Sha256(jsonencode(signatureInput));
finalPath = fullfile(folder,'cell_result.mat');
checkpointPath = fullfile(folder,'checkpoint.mat');
if isfile(finalPath)
    loaded = load(finalPath,'result');
    if strcmp(loaded.result.signature,signature)
        result = loaded.result;
        return
    end
    error('EXP1:ResultSignature','Existing result signature mismatch: %s',finalPath);
end

methodCount = numel(methodNames);
nData = config.parent.payloadSymbolCount;
if isfile(checkpointPath)
    loaded = load(checkpointPath,'state','signature');
    if ~strcmp(loaded.signature,signature)
        error('EXP1:CheckpointSignature', ...
            'Existing checkpoint signature mismatch: %s',checkpointPath);
    end
    state = loaded.state;
else
    state = localInitialState(packetCount,methodCount,nData);
end
timer = tic;
for packetId = state.completed+1:packetCount
    ledger = exp1SeedPlan(config,char(options.SeedPhase),orbitIndex, ...
        snrDb,packetId,char(options.SeedMode));
    frame = exp1GenerateFrame(config,orbitStartSec,snrDb,ledger);
    packet = exp1EvaluatePacket(frame,config,methodNames);
    state.symbolErrors(packetId,:) = packet.symbolErrors;
    state.hardBitErrors(packetId,:) = packet.hardBitErrors;
    state.mlBitErrors(packetId,:) = packet.mlBitErrors;
    state.packetError(packetId,:) = packet.packetError;
    state.hardPacketError(packetId,:) = packet.hardPacketError;
    state.symbolErrorMask(packetId,:,:) = reshape( ...
        packet.symbolErrorMask,1,methodCount,nData);
    state.cfoResidualBins(packetId,:,:) = reshape( ...
        packet.cfoResidualBins,1,methodCount,nData);
    state.cfoRmseBins(packetId,:) = packet.cfoRmseBins;
    state.cfoRmseHz(packetId,:) = packet.cfoRmseHz;
    state.rateRmseBinsPerSec(packetId,:) = packet.rateRmseBinsPerSec;
    state.candidateVp(packetId,:) = packet.candidateVp;
    state.acceptedVp(packetId,:) = packet.acceptedVp;
    state.falseVp(packetId,:) = packet.falseVp;
    state.failed(packetId,:) = packet.failed;
    state.failureMessage(packetId,:) = packet.failureMessage;
    state.fingerprint(packetId,:) = frame.observation.sampleFingerprint;
    state.payloadSeed(packetId) = ledger.payloadSeed;
    state.noiseSeed(packetId) = ledger.noiseSeed;
    state.channelSeed(packetId) = ledger.channelSeed;
    state.ledgerHash{packetId} = ledger.ledgerHash;
    if packetId == 1
        state.algorithmVersion = packet.algorithmVersion;
        state.receiverMode = packet.receiverMode;
        state.physics = localPhysics(frame.truth);
        state.dataSampleTimeSec = frame.truth.dataSampleTimeSec;
    end
    state.completed = packetId;
    if mod(packetId,config.checkpointEveryPackets) == 0 || ...
            packetId == packetCount
        localAtomicSave(checkpointPath,state,signature);
        fprintf('EXP1 %s %s: %d/%d packets\n', ...
            char(outputPhase),cellId,packetId,packetCount);
    end
end

result = struct('status','COMPLETE','experimentId',config.experimentId, ...
    'signature',signature,'parentManifestSha256',parentAudit.manifestSha256, ...
    'parentBaseGitCommit',parentAudit.parentBaseGitCommit, ...
    'parentSourceState',parentAudit.sourceState, ...
    'implementationSha256',implementation.sha256, ...
    'implementationFileCount',implementation.fileCount, ...
    'outputPhase',char(outputPhase),'seedPhase',char(options.SeedPhase), ...
    'seedMode',char(options.SeedMode),'cellId',cellId, ...
    'orbitIndex',orbitIndex,'orbitStartSec',orbitStartSec,'snrDb',snrDb, ...
    'packetCount',packetCount,'methodNames',{methodNames}, ...
    'symbolErrors',state.symbolErrors,'hardBitErrors',state.hardBitErrors, ...
    'mlBitErrors',state.mlBitErrors,'packetError',state.packetError, ...
    'hardPacketError',state.hardPacketError, ...
    'symbolErrorMask',state.symbolErrorMask, ...
    'cfoResidualBins',state.cfoResidualBins, ...
    'cfoRmseBins',state.cfoRmseBins,'cfoRmseHz',state.cfoRmseHz, ...
    'rateRmseBinsPerSec',state.rateRmseBinsPerSec, ...
    'candidateVp',state.candidateVp,'acceptedVp',state.acceptedVp, ...
    'falseVp',state.falseVp,'failed',state.failed, ...
    'failureMessage',{state.failureMessage},'fingerprint',state.fingerprint, ...
    'payloadSeed',state.payloadSeed,'noiseSeed',state.noiseSeed, ...
    'channelSeed',state.channelSeed,'ledgerHash',{state.ledgerHash}, ...
    'algorithmVersion',{state.algorithmVersion}, ...
    'receiverMode',{state.receiverMode},'physics',state.physics, ...
    'dataSampleTimeSec',state.dataSampleTimeSec, ...
    'elapsedSecThisInvocation',toc(timer), ...
    'runtimeEnvironment',localRuntimeEnvironment(), ...
    'failurePolicy',config.failurePolicy,'perDefinition',config.perDefinition);
localAtomicResult(finalPath,result);
localWriteSummary(fullfile(folder,'cell_summary.json'),result,config);
end

function state = localInitialState(packetCount,methodCount,nData)
state = struct('completed',0, ...
    'symbolErrors',zeros(packetCount,methodCount,'uint16'), ...
    'hardBitErrors',zeros(packetCount,methodCount,'uint16'), ...
    'mlBitErrors',zeros(packetCount,methodCount,'uint16'), ...
    'packetError',false(packetCount,methodCount), ...
    'hardPacketError',false(packetCount,methodCount), ...
    'symbolErrorMask',false(packetCount,methodCount,nData), ...
    'cfoResidualBins',nan(packetCount,methodCount,nData,'single'), ...
    'cfoRmseBins',nan(packetCount,methodCount), ...
    'cfoRmseHz',nan(packetCount,methodCount), ...
    'rateRmseBinsPerSec',nan(packetCount,methodCount), ...
    'candidateVp',zeros(packetCount,methodCount,'uint16'), ...
    'acceptedVp',zeros(packetCount,methodCount,'uint16'), ...
    'falseVp',zeros(packetCount,methodCount,'uint16'), ...
    'failed',false(packetCount,methodCount), ...
    'failureMessage',{repmat({''},packetCount,methodCount)}, ...
    'fingerprint',nan(packetCount,3), ...
    'payloadSeed',nan(packetCount,1),'noiseSeed',nan(packetCount,1), ...
    'channelSeed',nan(packetCount,1), ...
    'ledgerHash',{repmat({''},packetCount,1)},'algorithmVersion',{{}}, ...
    'receiverMode',{{}},'physics',struct(),'dataSampleTimeSec',[]);
end

function physics = localPhysics(truth)
names = {'startTimeSec','lastSampleTimeSec','rightBoundaryTimeSec', ...
    'fDStartHz','fDEndLastSampleHz','fDRightBoundaryHz', ...
    'dopplerRateStartHzPerSec','peakAbsDopplerRateHzPerSec', ...
    'frameDriftBins','frameDriftBoundaryBins','frameRangeBins', ...
    'cfoStartBins','initialPhaseRad'};
physics = struct();
for index = 1:numel(names)
    physics.(names{index}) = truth.(names{index});
end
end

function localAtomicSave(path,state,signature)
folder = fileparts(path);
temporary = [tempname(folder) '.mat'];
save(temporary,'state','signature','-v7.3');
[ok,message] = movefile(temporary,path,'f');
if ~ok
    error('EXP1:CheckpointWrite','%s',message);
end
end

function localAtomicResult(path,result)
folder = fileparts(path);
temporary = [tempname(folder) '.mat'];
save(temporary,'result','-v7.3');
[ok,message] = movefile(temporary,path,'f');
if ~ok
    error('EXP1:ResultWrite','%s',message);
end
end

function localWriteSummary(path,result,config)
summary = rmfield(result,{'symbolErrors','hardBitErrors','mlBitErrors', ...
    'packetError','hardPacketError','symbolErrorMask','cfoResidualBins', ...
    'cfoRmseBins','cfoRmseHz','rateRmseBinsPerSec','candidateVp', ...
    'acceptedVp','falseVp','failed','failureMessage','fingerprint', ...
    'payloadSeed','noiseSeed','channelSeed','ledgerHash','dataSampleTimeSec'});
summary.totalSymbolErrors = sum(double(result.symbolErrors),1);
summary.ser = summary.totalSymbolErrors/(result.packetCount* ...
    config.parent.payloadSymbolCount);
summary.totalHardBitErrors = sum(double(result.hardBitErrors),1);
summary.hardBer = summary.totalHardBitErrors/(result.packetCount* ...
    config.parent.informationBitCount);
summary.failedPackets = sum(result.failed,1);
file = fopen(path,'w','n','UTF-8');
if file < 0
    error('EXP1:SummaryWrite','Cannot open %s.',path);
end
cleanup = onCleanup(@()fclose(file));
fprintf(file,'%s\n',jsonencode(summary,'PrettyPrint',true));
clear cleanup
end

function environment = localRuntimeEnvironment()
timestamp = datetime('now','TimeZone','local', ...
    'Format','yyyyMMdd''T''HHmmssZZZZZ');
environment = struct('matlabVersion',version, ...
    'matlabRelease',version('-release'),'computer',computer, ...
    'generatedAtLocal',char(timestamp));
end
