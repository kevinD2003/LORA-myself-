function result = exp1IdealDecode(frame,config)
%EXP1IDEALDECODE Truth-isolated ideal Doppler reference.

c = config.parent;
layout = frame.observation.layout;
compensatedPhysical = frame.observation.rxPhysical.* ...
    exp(-1i*frame.truth.phasePhysicalRad);
payload = compensatedPhysical(layout.dataRows,:);
decoded = v4DecodePayload(payload,c,frame.observation.noiseVariance);
result = struct('methodName','Ideal','methodId','ideal-doppler-v1', ...
    'algorithmVersion','EXP1-Ideal-exact-sample-phase-v1', ...
    'detectedPhysicalBins',decoded.hardPhysicalBins, ...
    'hardDecodedDataBits',decoded.hardDataBits, ...
    'softDecodedDataBits',decoded.softDataBits, ...
    'estimatedCfoBins',frame.truth.dataCfoBins, ...
    'estimatedRateBinsPerSec',frame.truth.dataRateBinsPerSec, ...
    'virtualPilotAccepted',false(c.payloadSymbolCount,1), ...
    'usesPayloadTruth',true,'usesOrbitTruth',true, ...
    'referenceOnly',true);
end

