function outputs = aggregateExp1Results(outputPhase)
%AGGREGATEEXP1RESULTS Recompute CSV summaries from packet-level MAT files.

if nargin < 1
    outputPhase = 'formal';
end
paths = exp1SetupPaths();
config = exp1Config();
phaseRoot = fullfile(paths.resultsRoot,char(outputPhase));
files = dir(fullfile(phaseRoot,'*','cell_result.mat'));
if isempty(files)
    error('EXP1:NoResults','No completed %s cells were found.',outputPhase);
end

packetRows = {};
summaryRows = {};
deltaRows = {};
symbolRows = {};
packetRow = 0;
summaryRow = 0;
deltaRow = 0;
symbolRow = 0;
for fileIndex = 1:numel(files)
    loaded = load(fullfile(files(fileIndex).folder,files(fileIndex).name),'result');
    result = loaded.result;
    if ~strcmp(result.status,'COMPLETE')
        error('EXP1:IncompleteCell','Incomplete cell: %s',result.cellId);
    end
    n = result.packetCount;
    methodCount = numel(result.methodNames);
    packetSer = double(result.symbolErrors)/config.parent.payloadSymbolCount;
    for method = 1:methodCount
        name = result.methodNames{method};
        [ser,serCi] = exp1BootstrapCI(packetSer(:,method), ...
            config.bootstrapDraws,930000000+fileIndex*100+method);
        hardBer = sum(double(result.hardBitErrors(:,method)))/(n* ...
            config.parent.informationBitCount);
        mlBer = sum(double(result.mlBitErrors(:,method)))/(n* ...
            config.parent.informationBitCount);
        per = mean(result.packetError(:,method));
        hardPer = mean(result.hardPacketError(:,method));
        residual = double(squeeze(result.cfoResidualBins(:,method,:)));
        finiteResidual = isfinite(residual);
        if any(finiteResidual,'all')
            cfoRmseBins = sqrt(mean(residual(finiteResidual).^2));
            cfoRmseHz = cfoRmseBins*config.parent.fftBinSpacingHz;
        else
            cfoRmseBins = NaN;
            cfoRmseHz = NaN;
        end
        packetRateRmse = result.rateRmseBinsPerSec(:,method);
        packetRateRmse = packetRateRmse(isfinite(packetRateRmse));
        if isempty(packetRateRmse)
            rateRmse = NaN;
        else
            rateRmse = sqrt(mean(packetRateRmse.^2));
        end
        acceptedVp = sum(double(result.acceptedVp(:,method)));
        falseVp = sum(double(result.falseVp(:,method)));
        if acceptedVp == 0
            falseVpRate = NaN;
        else
            falseVpRate = falseVp/acceptedVp;
        end
        summaryRow = summaryRow+1;
        summaryRows(summaryRow,:) = {char(outputPhase),result.cellId, ...
            result.orbitStartSec,result.snrDb,name,n, ...
            sum(double(result.symbolErrors(:,method))), ...
            n*config.parent.payloadSymbolCount,ser,serCi(1),serCi(2), ...
            hardBer,mlBer,per,hardPer,cfoRmseHz,cfoRmseBins,rateRmse, ...
            sum(double(result.candidateVp(:,method))),acceptedVp,falseVp, ...
            falseVpRate,sum(result.failed(:,method)), ...
            result.physics.fDStartHz,result.physics.fDEndLastSampleHz, ...
            result.physics.dopplerRateStartHzPerSec, ...
            result.physics.peakAbsDopplerRateHzPerSec, ...
            result.physics.cfoStartBins,result.physics.frameDriftBins, ...
            result.physics.frameDriftBoundaryBins, ...
            result.physics.frameRangeBins,result.signature}; %#ok<AGROW>
        for packetId = 1:n
            packetRow = packetRow+1;
            packetRows(packetRow,:) = {char(outputPhase),result.cellId, ...
                result.orbitStartSec,result.snrDb,packetId,name, ...
                double(result.symbolErrors(packetId,method)), ...
                double(result.hardBitErrors(packetId,method)), ...
                double(result.mlBitErrors(packetId,method)), ...
                result.packetError(packetId,method), ...
                result.hardPacketError(packetId,method), ...
                result.cfoRmseHz(packetId,method), ...
                result.cfoRmseBins(packetId,method), ...
                result.rateRmseBinsPerSec(packetId,method), ...
                double(result.candidateVp(packetId,method)), ...
                double(result.acceptedVp(packetId,method)), ...
                double(result.falseVp(packetId,method)), ...
                result.failed(packetId,method), ...
                result.fingerprint(packetId,1), ...
                result.fingerprint(packetId,2), ...
                result.fingerprint(packetId,3), ...
                result.payloadSeed(packetId),result.noiseSeed(packetId), ...
                result.channelSeed(packetId),result.ledgerHash{packetId}, ...
                result.implementationSha256,result.parentManifestSha256}; %#ok<AGROW>
        end
        errorMask = double(squeeze(result.symbolErrorMask(:,method,:)));
        for dataIndex = 1:config.parent.payloadSymbolCount
            symbolRow = symbolRow+1;
            positionResidual = residual(:,dataIndex);
            positionResidual = positionResidual(isfinite(positionResidual));
            if isempty(positionResidual)
                positionRmseHz = NaN;
            else
                positionRmseHz = sqrt(mean(positionResidual.^2))* ...
                    config.parent.fftBinSpacingHz;
            end
            symbolRows(symbolRow,:) = {char(outputPhase),result.cellId, ...
                result.orbitStartSec,result.snrDb,name,dataIndex, ...
                mean(errorMask(:,dataIndex)),positionRmseHz, ...
                result.dataSampleTimeSec(dataIndex)}; %#ok<AGROW>
        end
    end

    stageIndex = find(strcmp(result.methodNames,'Stage55'),1);
    if ~isempty(stageIndex)
        baselines = {'Huang','Paper','Stage55-VP-off'};
        for baselineIndex = 1:numel(baselines)
            index = find(strcmp(result.methodNames,baselines{baselineIndex}),1);
            if isempty(index)
                continue
            end
            [difference,ci] = exp1PairedDifferenceCI( ...
                packetSer(:,index),packetSer(:,stageIndex), ...
                config.bootstrapDraws,940000000+fileIndex*100+baselineIndex);
            deltaRow = deltaRow+1;
            deltaRows(deltaRow,:) = {char(outputPhase),result.cellId, ...
                result.orbitStartSec,result.snrDb,baselines{baselineIndex}, ...
                'Stage55',n,difference,ci(1),ci(2)}; %#ok<AGROW>
        end
    end
end

packetTable = cell2table(packetRows,'VariableNames', ...
    {'phase','cellId','orbitStartSec','snrDb','packetId','method', ...
    'symbolErrors','hardBitErrors','mlBitErrors','packetError', ...
    'hardPacketError','cfoRmseHz','cfoRmseBins','rateRmseBinsPerSec', ...
    'candidateVp','acceptedVp','falseVp','failed', ...
    'fingerprintEnergy','fingerprintReal','fingerprintImag', ...
    'payloadSeed','noiseSeed','channelSeed','ledgerHash', ...
    'implementationSha256','parentManifestSha256'});
summaryTable = cell2table(summaryRows,'VariableNames', ...
    {'phase','cellId','orbitStartSec','snrDb','method','packets', ...
    'symbolErrors','symbolCount','ser','serCiLow','serCiHigh', ...
    'hardBer','mlBer','per','hardPer','cfoRmseHz','cfoRmseBins', ...
    'rateRmseBinsPerSec','candidateVp','acceptedVp','falseVp', ...
    'falseVpRate','failedPackets','fDStartHz','fDEndHz', ...
    'dopplerRateStartHzPerSec','peakAbsDopplerRateHzPerSec', ...
    'cfoStartBins','frameDriftBins','frameDriftBoundaryBins', ...
    'frameRangeBins','cellSignature'});
symbolTable = cell2table(symbolRows,'VariableNames', ...
    {'phase','cellId','orbitStartSec','snrDb','method','dataSymbolIndex', ...
    'ser','cfoRmseHz','absoluteSampleTimeSec'});
if isempty(deltaRows)
    deltaTable = cell2table(cell(0,10),'VariableNames', ...
        {'phase','cellId','orbitStartSec','snrDb','baseline','stageMethod', ...
        'packets','deltaSer','ciLow','ciHigh'});
else
    deltaTable = cell2table(deltaRows,'VariableNames', ...
        {'phase','cellId','orbitStartSec','snrDb','baseline','stageMethod', ...
        'packets','deltaSer','ciLow','ciHigh'});
end

out = fullfile(phaseRoot,'summary');
if ~isfolder(out)
    mkdir(out);
end
packetPath = fullfile(out,'EXP1_PACKET_LEVEL.csv');
summaryPath = fullfile(out,'EXP1_ORBIT_POSITION_SUMMARY.csv');
deltaPath = fullfile(out,'EXP1_PAIRED_DELTA_SER.csv');
symbolPath = fullfile(out,'EXP1_SYMBOL_POSITION_SUMMARY.csv');
writetable(packetTable,packetPath);
writetable(summaryTable,summaryPath);
writetable(deltaTable,deltaPath);
writetable(symbolTable,symbolPath);
outputs = struct('packetPath',packetPath,'summaryPath',summaryPath, ...
    'deltaPath',deltaPath,'symbolPath',symbolPath, ...
    'completedCells',numel(files),'failedPackets',sum(summaryTable.failedPackets));
end
