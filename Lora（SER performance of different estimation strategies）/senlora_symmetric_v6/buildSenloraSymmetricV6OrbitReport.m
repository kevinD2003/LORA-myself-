function audit = buildSenloraSymmetricV6OrbitReport()
%BUILDSENLORASYMMETRICV6ORBITREPORT Audit new-seed full-orbit raw errors.

paths = exp1SetupPaths();
addpath(fullfile(paths.projectRoot,'senlora_symmetric_v2'));
addpath(fullfile(paths.projectRoot,'senlora_symmetric_v3'));
config = exp1Config();
plan = senloraSymmetricV6Config(config);
root = fullfile(paths.resultsRoot,'senlora_symmetric_v6', ...
    'formal','orbit_formal');
resultPath = fullfile(root,'VALIDATION_RESULT.mat');
checkpointPath = fullfile(root,'VALIDATION_CHECKPOINT.mat');
result = load(resultPath);
checkpoint = load(checkpointPath);
[sourceClosureSigned,runnerSnapshotUsed] = ...
    localVerify(result,checkpoint,config,plan,root);

errors = double(result.v6Errors);
v3Errors = double(result.v3Errors);
parentErrors = double(result.parentErrors);
pairCount = size(errors,1);
n = size(errors,3);
symbols = config.parent.payloadSymbolCount;
draws = 10000;
stream = RandStream('mt19937ar','Seed',plan.formalRootSeed+3141);
negativeSamples = zeros(pairCount,draws);
positiveSamples = zeros(pairCount,draws);
pooledSamples = zeros(pairCount,draws);
improvementSamples = zeros(pairCount,draws);
rows = cell(pairCount,24);

for pairIndex = 1:pairCount
    v6Negative = reshape(errors(pairIndex,1,:),n,1);
    v6Positive = reshape(errors(pairIndex,2,:),n,1);
    v3Negative = reshape(v3Errors(pairIndex,1,:),n,1);
    v3Positive = reshape(v3Errors(pairIndex,2,:),n,1);
    for draw = 1:draws
        sampled = randi(stream,n,n,1);
        negativeSamples(pairIndex,draw) = ...
            sum(v6Negative(sampled))/(n*symbols);
        positiveSamples(pairIndex,draw) = ...
            sum(v6Positive(sampled))/(n*symbols);
        pooledSamples(pairIndex,draw) = ...
            (negativeSamples(pairIndex,draw)+ ...
            positiveSamples(pairIndex,draw))/2;
        improvementSamples(pairIndex,draw) = ...
            sum(v6Negative(sampled)+v6Positive(sampled)- ...
            v3Negative(sampled)-v3Positive(sampled))/(2*n*symbols);
    end
    negBounds = prctile(negativeSamples(pairIndex,:),[2.5 97.5]);
    posBounds = prctile(positiveSamples(pairIndex,:),[2.5 97.5]);
    pooledBounds = prctile(pooledSamples(pairIndex,:),[2.5 97.5]);
    mirrorBounds = prctile(negativeSamples(pairIndex,:)- ...
        positiveSamples(pairIndex,:),[2.5 97.5]);
    improvementBounds = prctile(improvementSamples(pairIndex,:), ...
        [2.5 97.5]);
    t0 = plan.negativeOrbitStartSec(pairIndex);
    fraction = (t0-plan.negativeOrbitStartSec(1))/ ...
        abs(plan.negativeOrbitStartSec(1));
    target = 10^(log10(plan.targetCase1Ser)+fraction* ...
        (log10(plan.targetCenterSer)-log10(plan.targetCase1Ser)));
    negativeErrors = sum(v6Negative);
    positiveErrors = sum(v6Positive);
    v3Total = sum(v3Negative)+sum(v3Positive);
    rows(pairIndex,:) = {pairIndex,t0,-t0-plan.frameDurationSec, ...
        n,negativeErrors,positiveErrors, ...
        sum(v3Negative),sum(v3Positive), ...
        negativeErrors/(n*symbols),positiveErrors/(n*symbols), ...
        (negativeErrors+positiveErrors)/(2*n*symbols), ...
        v3Total/(2*n*symbols), ...
        negBounds(1),negBounds(2),posBounds(1),posBounds(2), ...
        pooledBounds(1),pooledBounds(2), ...
        mirrorBounds(1),mirrorBounds(2), ...
        improvementBounds(1),improvementBounds(2),target, ...
        sum(parentErrors(pairIndex,1,:),'all')/(n*symbols)};
end
summary = cell2table(rows,'VariableNames',{ ...
    'pairIndex','negativeOrbitStartSec','positiveMirrorStartSec', ...
    'packetsPerSide','negativeV6RawErrors','positiveV6RawErrors', ...
    'negativeV3RawErrors','positiveV3RawErrors', ...
    'negativeV6Ser','positiveV6Ser','pooledV6Ser','pooledV3Ser', ...
    'negativeClusterLower95','negativeClusterUpper95', ...
    'positiveClusterLower95','positiveClusterUpper95', ...
    'pooledClusterLower95','pooledClusterUpper95', ...
    'mirrorDifferenceLower95','mirrorDifferenceUpper95', ...
    'v6MinusV3Lower95','v6MinusV3Upper95', ...
    'upperTargetSer','parentNegativeSer'});

transitionRows = cell(pairCount-1,6);
for pairIndex = 1:pairCount-1
    changes = pooledSamples(pairIndex+1,:)- ...
        pooledSamples(pairIndex,:);
    bounds = prctile(changes,[2.5 97.5]);
    transitionRows(pairIndex,:) = { ...
        summary.negativeOrbitStartSec(pairIndex), ...
        summary.negativeOrbitStartSec(pairIndex+1), ...
        summary.pooledV6Ser(pairIndex+1)- ...
        summary.pooledV6Ser(pairIndex), ...
        bounds(1),bounds(2),bounds(2)<0};
end
transitions = cell2table(transitionRows,'VariableNames',{ ...
    'fromOrbitStartSec','toOrbitStartSec','changeSer', ...
    'changeLower95','changeUpper95','significantReverseJump'});

allPointBounds = all(summary.negativeV6Ser<=summary.upperTargetSer & ...
    summary.positiveV6Ser<=summary.upperTargetSer);
allClusterBounds = all( ...
    summary.negativeClusterUpper95<=summary.upperTargetSer & ...
    summary.positiveClusterUpper95<=summary.upperTargetSer & ...
    summary.pooledClusterUpper95<=summary.upperTargetSer);
allMirrors = all(summary.mirrorDifferenceLower95<=0 & ...
    summary.mirrorDifferenceUpper95>=0);
noReverse = ~any(transitions.significantReverseJump);
case1Exact = sum(result.case1Exact(1,:));
case2Good = summary.negativeV6Ser(end)<= ...
    summary.parentNegativeSer(end) && ...
    summary.negativeV6Ser(end)<=plan.targetCenterSer;
overallDifference = (sum(errors,'all')-sum(v3Errors,'all'))/ ...
    (pairCount*2*n*symbols);
overallDifferenceBounds = prctile(mean(improvementSamples,1), ...
    [2.5 97.5]);
formalGates = allPointBounds && allClusterBounds && allMirrors && ...
    noReverse && case1Exact==n && case2Good && ...
    ~any(result.failed,'all') && all(result.loboVerified,'all');
improvementObserved = overallDifference<0 && ...
    summary.pooledV6Ser(2)<summary.pooledV3Ser(2);
improvementSupported = overallDifferenceBounds(2)<0;
if formalGates && improvementObserved && improvementSupported && ...
        sourceClosureSigned
    status = 'V6_ORBIT_FORMAL_PASS';
else
    status = 'V6_ORBIT_FORMAL_FAIL';
end
audit = struct('status',status,'formalGatesPass',formalGates, ...
    'allRawPointsBelowUpper',allPointBounds, ...
    'allPairedClusterUppersBelowUpper',allClusterBounds, ...
    'allMirrorDifferencesIncludeZero',allMirrors, ...
    'noSignificantReverseJump',noReverse, ...
    'significantReverseCount',sum(transitions.significantReverseJump), ...
    'case1ExactPackets',case1Exact,'case1TotalPackets',n, ...
    'case2TargetPass',case2Good, ...
    'failedPackets',sum(result.failed,'all'), ...
    'loboVerified',all(result.loboVerified,'all'), ...
    'v6RawErrors',sum(errors,'all'), ...
    'v3RawErrors',sum(v3Errors,'all'), ...
    'overallV6MinusV3Ser',overallDifference, ...
    'overallDifferenceLower95',overallDifferenceBounds(1), ...
    'overallDifferenceUpper95',overallDifferenceBounds(2), ...
    'improvementObserved',improvementObserved, ...
    'improvementSupported95',improvementSupported, ...
    'sourceClosureSigned',sourceClosureSigned, ...
    'runnerSnapshotUsed',runnerSnapshotUsed, ...
    'pairedPacketBootstrapDraws',draws, ...
    'bootstrapSeed',plan.formalRootSeed+3141, ...
    'receiverRerun',false);

writetable(summary,fullfile(root,'ORBIT_PAIRED_SUMMARY.csv'));
writetable(transitions,fullfile(root,'ORBIT_PAIRED_TRANSITIONS.csv'));
save(fullfile(root,'ORBIT_PAIRED_AUDIT.mat'), ...
    'audit','summary','transitions','-v7.3');
localPlot(summary,root,n*symbols);
localReport(fullfile(root,'ORBIT_FORMAL_REPORT.md'),audit, ...
    summary,transitions,exp1Sha256(resultPath), ...
    exp1Sha256(checkpointPath));
end

function [sourceClosureSigned,runnerSnapshotUsed] = ...
        localVerify(result,checkpoint,config,plan,root)
required = {'v6Errors','v3Errors','parentErrors','failed', ...
    'loboVerified','override','case1Exact','completed'};
if ~isequal(result.signature,checkpoint.signature) || ...
        ~strcmp(checkpoint.stateDigest,localDigest(checkpoint))
    error('EXP5V6:FormalDigest','Formal checkpoint digest mismatch.');
end
for index = 1:numel(required)
    name = required{index};
    if ~isequal(result.(name),checkpoint.(name))
        error('EXP5V6:FormalResult','Result/checkpoint mismatch: %s',name);
    end
end
signature = result.signature;
if ~strcmp(signature.phase,'formal') || ...
        signature.packetCount~=1000 || ...
        ~isequal(signature.pairIndices,1:9) || ...
        signature.seedRoot~=plan.formalRootSeed || ...
        ~strcmp(signature.planIdentity,plan.identity) || ...
        ~isequal(signature.projectDigest,exp1ImplementationDigest(config)) || ...
        ~strcmp(signature.v6DecodeSha256, ...
            exp1Sha256(which('senloraSymmetricV6Decode'))) || ...
        ~strcmp(signature.v6ConfigSha256, ...
            exp1Sha256(which('senloraSymmetricV6Config'))) || ...
        ~strcmp(signature.v3DecodeSha256, ...
            exp1Sha256(which('senloraSymmetricV3Decode')))
    error('EXP5V6:FormalSignature','Formal source signature mismatch.');
end
sourceClosureSigned = isfield(signature,'executionSourcePaths') && ...
    isfield(signature,'executionSourceSha256') && ...
    isfield(signature,'parentManifestSha256');
runnerSnapshotUsed = false;
if sourceClosureSigned
    sourcePaths = string(signature.executionSourcePaths(:));
    sourceHashes = string(signature.executionSourceSha256(:));
    if isempty(sourcePaths) || numel(sourcePaths)~=numel(sourceHashes)
        error('EXP5V6:FormalSources','Formal source manifest is invalid.');
    end
    for index = 1:numel(sourcePaths)
        if ~isfile(sourcePaths(index)) || ...
                ~strcmpi(sourceHashes(index),exp1Sha256(sourcePaths(index)))
            error('EXP5V6:FormalSources', ...
                'Formal source mismatch: %s',sourcePaths(index));
        end
    end
    parentAudit = exp1ValidateFrozenParent(config);
    if ~strcmp(signature.parentManifestSha256, ...
            parentAudit.manifestSha256) || ...
            ~strcmp(signature.validationSha256, ...
            exp1Sha256(which('runSenloraSymmetricV6Validation')))
        error('EXP5V6:FormalSources', ...
            'Formal parent or runner signature mismatch.');
    end
else
    frozenRunner = fullfile(root,'FORMAL_RUNNER_SOURCE.txt');
    if ~isfile(frozenRunner) || ...
            ~strcmp(signature.validationSha256,exp1Sha256(frozenRunner))
        error('EXP5V6:FormalSources', ...
            'Historical Formal runner snapshot is missing or mismatched.');
    end
    runnerSnapshotUsed = true;
end
if ~all(result.completed,'all') || any(result.failed,'all') || ...
        ~all(result.loboVerified,'all') || ...
        ~isequal(size(result.v6Errors),[9,2,1000])
    error('EXP5V6:FormalIncomplete','Formal run is incomplete or failed.');
end
end

function hash = localDigest(state)
digest = java.security.MessageDigest.getInstance('SHA-256');
bytes = getByteStreamFromArray({state.signature,state.v6Errors, ...
    state.v3Errors,state.parentErrors,state.failed, ...
    state.loboVerified,state.override, ...
    state.case1Exact,state.completed});
digest.update(typecast(uint8(bytes(:)),'int8'));
hash = lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end

function localPlot(summary,root,perSideSymbols)
x = summary.negativeOrbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1050 670]);
plot(x,summary.negativeV6RawErrors,'o','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'DisplayName','V6 negative raw errors');
hold on
plot(x,summary.positiveV6RawErrors,'s','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'DisplayName','V6 positive raw errors');
plot(x,summary.negativeV3RawErrors,'x','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'DisplayName','V3 negative on same frames');
plot(x,summary.positiveV3RawErrors,'+','LineStyle','none', ...
    'MarkerSize',8,'LineWidth',1.5,'DisplayName','V3 positive on same frames');
plot(x,summary.upperTargetSer*perSideSymbols,':d', ...
    'LineWidth',1.8,'DisplayName','Analytical per-side upper count');
grid on;xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('Raw symbol error count per side');
title({'SenLoRa V6 new-seed full-orbit Formal raw counts', ...
    'Measured points are not fitted, interpolated, or smoothed'});
legend('Location','northwest');
exportgraphics(f,fullfile(root,'ORBIT_RAW_COUNT.png'), ...
    'Resolution',220);close(f);

floorValue = 0.5/perSideSymbols;
f = figure('Visible','off','Color','w','Position',[100 100 1120 680]);
semilogy(x,max(summary.negativeV6Ser,floorValue),'o', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.5, ...
    'DisplayName','V6 negative raw SER');
hold on
semilogy(x,max(summary.positiveV6Ser,floorValue),'s', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.5, ...
    'DisplayName','V6 positive raw SER');
semilogy(x,max(summary.pooledV6Ser,floorValue/2),'^', ...
    'LineStyle','none','MarkerSize',8,'LineWidth',1.5, ...
    'DisplayName','V6 paired pooled raw SER');
semilogy(x,summary.upperTargetSer,':d','LineWidth',1.8, ...
    'DisplayName','Analytical SER upper envelope');
grid on;grid minor;xlabel('Negative-pass reference frame start t_0 (s)');
ylabel('SER');
title({'SenLoRa V6 new-seed full-orbit Formal raw SER', ...
    'Zero counts use a 0.5-count display floor; measured points are not fitted'});
legend('Location','northwest');
exportgraphics(f,fullfile(root,'ORBIT_RAW_SER.png'), ...
    'Resolution',220);close(f);
end

function localReport(path,audit,summary,transitions,resultHash,checkpointHash)
[fid,message] = fopen(path,'w','n','UTF-8');
if fid<0,error('EXP5V6:ReportOpen','%s',message);end
cleanup = onCleanup(@()fclose(fid));
fprintf(fid,'# SenLoRa V6 new-seed full-orbit Formal\n\n');
fprintf(fid,'Status: **%s**\n\n',audit.status);
fprintf(fid,['Original V3 Formal and V5 Case1 Formal are separate frozen ' ...
    'results; neither was changed. V3 comparison below uses the same ' ...
    'new V6 Formal frames, not the old V3 Formal packets.\n\n']);
fprintf(fid,'- Paired mirror packets per point: %d\n', ...
    summary.packetsPerSide(1));
fprintf(fid,'- Raw V6/V3 errors on new frames: %d / %d\n', ...
    audit.v6RawErrors,audit.v3RawErrors);
fprintf(fid,'- Case1 exact packets: %d/%d\n', ...
    audit.case1ExactPackets,audit.case1TotalPackets);
fprintf(fid,'- Failed packets: %d; LOBO verified: %d\n', ...
    audit.failedPackets,audit.loboVerified);
fprintf(fid,'- Raw points below envelope: %d\n', ...
    audit.allRawPointsBelowUpper);
fprintf(fid,'- Paired-cluster upper bounds below envelope: %d\n', ...
    audit.allPairedClusterUppersBelowUpper);
fprintf(fid,'- Mirror-difference intervals include zero: %d\n', ...
    audit.allMirrorDifferencesIncludeZero);
fprintf(fid,'- Significant reverse transitions: %d\n', ...
    audit.significantReverseCount);
fprintf(fid,'- Overall V6 minus V3 SER: %.9g; paired 95%% CI [%.9g, %.9g]\n', ...
    audit.overallV6MinusV3Ser,audit.overallDifferenceLower95, ...
    audit.overallDifferenceUpper95);
fprintf(fid,'- Improvement supported at 95%%: %d\n\n', ...
    audit.improvementSupported95);
fprintf(fid,'- Observed overall and -320.25 s improvement: %d\n', ...
    audit.improvementObserved);
fprintf(fid,'- Full execution dependency closure signed: %d\n', ...
    audit.sourceClosureSigned);
if audit.runnerSnapshotUsed
    fprintf(fid,[ ...
        '- The historical runner matches FORMAL_RUNNER_SOURCE.txt, ' ...
        'but its checkpoint did not sign the full V2/V3 dependency ' ...
        'closure. This cannot be certified retroactively.\n']);
end
fprintf(fid,'\n');
fprintf(fid,'| t0 (s) | V6 negative | V6 positive | V3 negative | V3 positive | V6 pooled SER | V3 pooled SER |\n');
fprintf(fid,'|---:|---:|---:|---:|---:|---:|---:|\n');
for row = 1:height(summary)
    fprintf(fid,'| %.2f | %d | %d | %d | %d | %.9g | %.9g |\n', ...
        summary.negativeOrbitStartSec(row), ...
        summary.negativeV6RawErrors(row), ...
        summary.positiveV6RawErrors(row), ...
        summary.negativeV3RawErrors(row), ...
        summary.positiveV3RawErrors(row), ...
        summary.pooledV6Ser(row),summary.pooledV3Ser(row));
end
fprintf(fid,'\n## Significant reverse transitions\n\n');
for row = find(transitions.significantReverseJump).'
    fprintf(fid,'- %.2f -> %.2f s; change %.9g, 95%% CI [%.9g, %.9g].\n', ...
        transitions.fromOrbitStartSec(row), ...
        transitions.toOrbitStartSec(row),transitions.changeSer(row), ...
        transitions.changeLower95(row),transitions.changeUpper95(row));
end
fprintf(fid,'\n## Source identity\n\n');
fprintf(fid,'- Result MAT SHA-256: `%s`\n',resultHash);
fprintf(fid,'- Checkpoint MAT SHA-256: `%s`\n',checkpointHash);
fprintf(fid,['- The plots contain raw measured points and the analytical ' ...
    'bound only; no fitting or smoothing.\n']);
clear cleanup
end
