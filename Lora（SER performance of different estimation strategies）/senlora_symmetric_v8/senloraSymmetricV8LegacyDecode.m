function result = senloraSymmetricV8LegacyDecode( ...
        observation,common,config,plan)
%SENLORASYMMETRICV8LEGACYDECODE Failed 604-error pre-promotion baseline.

c = config.parent;
layout = observation.layout;
if ~isempty(layout.midambleRows) || ...
        layout.physicalSymbolCount~=plan.nativePhysicalSymbolCount
    error('EXP5V8:NativeFrame', ...
        'Legacy V8 requires the native preamble-plus-payload frame.');
end
pilots = observation.rxPhysical(layout.bootstrapRows,:);
parameters = v4BCalibrationCandidates();
parameters = parameters(2);
joint = v4Stage55JointPreambleMlBootstrap(pilots,c, ...
    MaximumRateBinsPerSec=parameters.maximumRateBinsPerSec);
predictedDrift = abs(joint.rateBinsPerSec)*plan.frameDurationSec;
rateGain = localSmoothStep(predictedDrift, ...
    plan.driftBlendStartBins,plan.driftBlendEndBins);
bootstrap = senloraSymmetricV8BlendBootstrap(common,joint,rateGain,c);
appliedInitialRate = bootstrap.rateBinsPerSec;

emptyMask = false(c.payloadSymbolCount,1);
firstTracker = v4RollingTrackerPass(observation,bootstrap,c,parameters, ...
    emptyMask,InitialRateBinsPerSec=appliedInitialRate);
firstDecoded = v4DecodePayload( ...
    firstTracker.compensatedData,c,common.noisePower);
confidence = v4Stage55Confidence(firstDecoded,c,parameters);
candidateMask = logical(confidence.confidentMask(:));

if ~any(candidateMask)
    finalTracker = firstTracker;
    finalDecoded = firstDecoded;
    passCount = 1;
else
    finalTracker = v4RollingTrackerPass( ...
        observation,bootstrap,c,parameters,candidateMask, ...
        InitialRateBinsPerSec=appliedInitialRate, ...
        CandidatePhysicalBins= ...
            firstDecoded.confidenceReencodedPhysicalBins(:));
    finalDecoded = v4DecodePayload( ...
        finalTracker.compensatedData,c,common.noisePower);
    passCount = 2;
end

n = c.payloadSymbolCount;
monitor = struct('symbolIndex',(1:n).', ...
    'absoluteTimeSec',layout.physicalCenterTimeSec(layout.dataRows), ...
    'appliedCompensationBins',finalTracker.predictedCfoBins(:), ...
    'acceptedMeasurement',logical(finalTracker.pilotAccepted(:)), ...
    'firstPassConfidence',candidateMask, ...
    'firstPassDetectedPhysicalBins',firstDecoded.hardPhysicalBins(:), ...
    'rateGain',repmat(rateGain,n,1), ...
    'preambleRateBinsPerSec',repmat(joint.rateBinsPerSec,n,1), ...
    'appliedInitialRateBinsPerSec',repmat(appliedInitialRate,n,1));
decision = struct('selectedBranchName','legacy-continuous-rate-two-pass', ...
    'predictedFrameDriftBins',predictedDrift, ...
    'rateGain',rateGain, ...
    'preambleRateBinsPerSec',joint.rateBinsPerSec, ...
    'appliedInitialRateBinsPerSec',appliedInitialRate, ...
    'staticCfoAtPayloadBins',bootstrap.staticCfoAtPayloadBins, ...
    'dynamicCfoAtPayloadBins',bootstrap.dynamicCfoAtPayloadBins, ...
    'candidateVirtualPilots',sum(candidateMask), ...
    'acceptedVirtualPilots',sum(finalTracker.pilotAccepted), ...
    'passCount',passCount,'usesExplicitMidambles',false, ...
    'usesOrbitTruth',false,'usesTargetSer',false);
result = struct('methodName','SenLoRa-V8-Legacy-Two-Pass', ...
    'methodId','senlora-symmetric-native-v8-legacy', ...
    'algorithmVersion','SenLoRa-continuous-rate-two-pass-v8-legacy', ...
    'detectedPhysicalBins',finalDecoded.hardPhysicalBins, ...
    'hardDecodedDataBits',finalDecoded.hardDataBits, ...
    'softDecodedDataBits',finalDecoded.softDataBits, ...
    'estimatedCfoBins',finalTracker.predictedCfoBins(:), ...
    'virtualPilotAccepted',logical(finalTracker.pilotAccepted(:)), ...
    'explicitMidambleAccepted',false(0,1), ...
    'monitor',monitor,'decision',decision, ...
    'jointPreambleEstimate',joint,'bootstrap',bootstrap, ...
    'firstPassTracker',firstTracker,'finalTracker',finalTracker, ...
    'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'usesCaseIdentity',false,'usesSnrInput',false, ...
    'usesTargetSer',false,'usesExplicitMidambles',false);
end

function value = localSmoothStep(x,lower,upper)
if ~(isfinite(lower) && isfinite(upper) && upper>lower)
    error('EXP5V8:BlendRange','Invalid drift blending interval.');
end
u = min(1,max(0,(x-lower)/(upper-lower)));
value = u*u*(3-2*u);
end
