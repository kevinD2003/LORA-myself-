function result = senloraSymmetricV8ResidualDecode(observation,common,config,plan)
%SENLORASYMMETRICV8RESIDUALDECODE Fixed-label blockwise residual validation.

c = config.parent;
layout = observation.layout;
if ~isempty(layout.midambleRows) || ...
        layout.physicalSymbolCount~=plan.nativePhysicalSymbolCount
    error('EXP5V8:NativeFrame', ...
        'Residual validation requires the native V8 frame.');
end

parameters = v4BCalibrationCandidates();
parameters = parameters(2);
pilots = observation.rxPhysical(layout.bootstrapRows,:);
joint = v4Stage55JointPreambleMlBootstrap(pilots,c, ...
    MaximumRateBinsPerSec=parameters.maximumRateBinsPerSec);
predictedDrift = abs(joint.rateBinsPerSec)*plan.frameDurationSec;
rateGain = localSmoothStep(predictedDrift, ...
    plan.driftBlendStartBins,plan.driftBlendEndBins);
bootstrap = senloraSymmetricV8BlendBootstrap(common,joint,rateGain,c);

firstTracker = v4RollingTrackerPass( ...
    observation,bootstrap,c,parameters,false(c.payloadSymbolCount,1), ...
    InitialRateBinsPerSec=bootstrap.rateBinsPerSec);
firstDecoded = v4DecodePayload( ...
    firstTracker.compensatedData,c,common.noisePower);
confidence = v4Stage55Confidence(firstDecoded,c,parameters);
candidateMask = localBlockCandidateMask( ...
    firstDecoded,confidence,c,parameters);

residualTracker = senloraSymmetricV8ResidualReplay( ...
    observation,firstTracker,firstDecoded,candidateMask, ...
    bootstrap,c,parameters);
finalDecoded = v4DecodePayload( ...
    residualTracker.compensatedData,c,common.noisePower);

result = struct( ...
    'methodName','SenLoRa-V8-Blockwise-Residual-Replay', ...
    'methodId','senlora-v8-residual-validation', ...
    'algorithmVersion','SenLoRa-V8-residual-replay-validation-v1', ...
    'detectedPhysicalBins',finalDecoded.hardPhysicalBins, ...
    'hardDecodedDataBits',finalDecoded.hardDataBits, ...
    'softDecodedDataBits',finalDecoded.softDataBits, ...
    'estimatedCfoBins',residualTracker.predictedCfoBins, ...
    'virtualPilotAccepted',residualTracker.pilotAccepted, ...
    'firstPassDetectedPhysicalBins',firstDecoded.hardPhysicalBins, ...
    'firstPassEstimatedCfoBins',firstTracker.predictedCfoBins, ...
    'candidateVirtualPilots',sum(candidateMask), ...
    'acceptedVirtualPilots',sum(residualTracker.pilotAccepted), ...
    'rateGain',rateGain,'predictedFrameDriftBins',predictedDrift, ...
    'jointPreambleEstimate',joint,'bootstrap',bootstrap, ...
    'firstPassTracker',firstTracker, ...
    'residualTracker',residualTracker, ...
    'usesPayloadTruth',false,'usesOrbitTruth',false, ...
    'usesCaseIdentity',false,'usesSnrInput',false, ...
    'usesTargetSer',false,'usesExplicitMidambles',false);
end

function value = localSmoothStep(x,lower,upper)
u = min(1,max(0,(x-lower)/(upper-lower)));
value = u*u*(3-2*u);
end

function candidateMask = localBlockCandidateMask( ...
        decoded,confidence,c,parameters)
candidateMask = false(c.payloadSymbolCount,1);
for block = 1:c.hammingBlockCount
    rows = (block-1)*c.hammingCodewordLength+ ...
        (1:c.hammingCodewordLength);
    blockAgreement = isequal(decoded.hardDataBits(:,:,block), ...
        decoded.softDataBits(:,:,block));
    labelAgreement = decoded.softReencodedPhysicalBins(rows)== ...
        decoded.hardPhysicalBins(rows);
    marginRatio = decoded.symbolCodewordMargin(rows)./ ...
        max(confidence.tauGlobal(rows),eps);
    candidateMask(rows) = blockAgreement & all(labelAgreement) & ...
        all(marginRatio>=parameters.softHammingMarginRatio);
end
end
