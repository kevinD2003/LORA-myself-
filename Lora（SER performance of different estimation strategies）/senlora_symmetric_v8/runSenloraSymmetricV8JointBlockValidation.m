function output = runSenloraSymmetricV8JointBlockValidation(options)
%RUNSENLORASYMMETRICV8JOINTBLOCKVALIDATION Same-seed full mechanism replay.

arguments
    options.WorkerCount (1,1) double {mustBeInteger,mustBePositive} = 2
end

here = fileparts(mfilename('fullpath'));
addpath(fullfile(here,'..','scripts'));
addpath(fullfile(here,'..','senlora_symmetric_v3'));
paths = exp1SetupPaths();
addpath(here);
config = exp1Config();
c = config.parent;
plan = senloraSymmetricV8Config(config);
commonParameters = v4LoadMethodAlignedR3ParametersV1();
pairCount = numel(plan.negativeOrbitStartSec);
packetCount = plan.mechanismPacketsPerMirrorPair;
shape = [pairCount,2,packetCount];

root = fullfile(paths.resultsRoot,'senlora_symmetric_v8', ...
    'joint_block_mechanism');
if ~isfolder(root)
    mkdir(root);
end
checkpointPath = fullfile(root,'JOINT_BLOCK_CHECKPOINT.mat');
signature = localSignature(plan);
if isfile(checkpointPath)
    state = load(checkpointPath);
    localValidateCheckpoint(state,signature,shape);
else
    state = struct('signature',signature, ...
        'jointErrors',zeros(shape,'uint16'), ...
        'firstErrors',zeros(shape,'uint16'), ...
        'acceptedBlocks',zeros(shape,'uint8'), ...
        'maximumResidualBins',nan(shape), ...
        'cfoRmseBins',nan(shape), ...
        'failed',false(shape), ...
        'failureMessage',strings(shape), ...
        'usesForbiddenInput',false(shape), ...
        'completed',false(pairCount,packetCount));
end

if any(~state.completed,'all')
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('local',options.WorkerCount);
    elseif pool.NumWorkers~=options.WorkerCount
        error('EXP5V8:WorkerCount','Existing pool has the wrong worker count.');
    end
end

for blockStart = 1:5:packetCount
    packetIds = blockStart:min(packetCount,blockStart+4);
    [pairRows,packetColumns] = find(~state.completed(:,packetIds));
    if isempty(pairRows)
        continue
    end
    jobPairs = pairRows;
    jobPackets = packetIds(packetColumns).';
    jobCount = numel(jobPairs);
    jobJoint = zeros(jobCount,2,'uint16');
    jobFirst = zeros(jobCount,2,'uint16');
    jobAccepted = zeros(jobCount,2,'uint8');
    jobMaximumResidual = nan(jobCount,2);
    jobCfoRmse = nan(jobCount,2);
    jobFailed = false(jobCount,2);
    jobMessage = strings(jobCount,2);
    jobForbidden = false(jobCount,2);
    parfor job = 1:jobCount
        packet = localEvaluate(jobPairs(job),jobPackets(job), ...
            config,plan,commonParameters);
        jobJoint(job,:) = packet.jointErrors;
        jobFirst(job,:) = packet.firstErrors;
        jobAccepted(job,:) = packet.acceptedBlocks;
        jobMaximumResidual(job,:) = packet.maximumResidualBins;
        jobCfoRmse(job,:) = packet.cfoRmseBins;
        jobFailed(job,:) = packet.failed;
        jobMessage(job,:) = packet.failureMessage;
        jobForbidden(job,:) = packet.usesForbiddenInput;
    end
    for job = 1:jobCount
        pair = jobPairs(job);
        packetId = jobPackets(job);
        state.jointErrors(pair,:,packetId) = jobJoint(job,:);
        state.firstErrors(pair,:,packetId) = jobFirst(job,:);
        state.acceptedBlocks(pair,:,packetId) = jobAccepted(job,:);
        state.maximumResidualBins(pair,:,packetId) = ...
            jobMaximumResidual(job,:);
        state.cfoRmseBins(pair,:,packetId) = jobCfoRmse(job,:);
        state.failed(pair,:,packetId) = jobFailed(job,:);
        state.failureMessage(pair,:,packetId) = jobMessage(job,:);
        state.usesForbiddenInput(pair,:,packetId) = jobForbidden(job,:);
        state.completed(pair,packetId) = true;
    end
    localSaveCheckpoint(checkpointPath,state);
    fprintf(['Joint-block mechanism pair-packets=%d/%d; ' ...
        'first/joint errors=%d/%d; failures=%d\n'], ...
        sum(state.completed,'all'),numel(state.completed), ...
        sum(state.firstErrors,'all'),sum(state.jointErrors,'all'), ...
        sum(state.failed,'all'));
end

if ~all(state.completed,'all')
    error('EXP5V8:JointBlockIncomplete','Joint-block validation is incomplete.');
end
[raw,summary] = localTables(state,plan,c,paths);
writetable(raw,fullfile(root,'JOINT_BLOCK_RAW_PACKETS.csv'));
writetable(summary,fullfile(root,'JOINT_BLOCK_RAW_POINTS.csv'));
save(fullfile(root,'JOINT_BLOCK_RESULT.mat'),'-struct','state','-v7.3');
localPlot(summary,root);
output = struct('status','JOINT_BLOCK_MECHANISM_COMPLETE', ...
    'raw',raw,'summary',summary,'root',root, ...
    'jointRawErrors',sum(state.jointErrors,'all'), ...
    'firstRawErrors',sum(state.firstErrors,'all'), ...
    'failedFrames',sum(state.failed,'all'), ...
    'allForbiddenFlagsFalse',~any(state.usesForbiddenInput,'all'));
end

function packet = localEvaluate(pairIndex,packetId,config,plan,parameters)
c = config.parent;
negative = plan.negativeOrbitStartSec(pairIndex);
starts = [negative,-negative-plan.frameDurationSec];
ledger = senloraSymmetricV3SeedPlan( ...
    config,plan,'mechanism',pairIndex,plan.snrDb,packetId);
packet = struct('jointErrors',zeros(1,2,'uint16'), ...
    'firstErrors',zeros(1,2,'uint16'), ...
    'acceptedBlocks',zeros(1,2,'uint8'), ...
    'maximumResidualBins',nan(1,2),'cfoRmseBins',nan(1,2), ...
    'failed',false(1,2),'failureMessage',strings(1,2), ...
    'usesForbiddenInput',false(1,2));
for side = 1:2
    try
        frame = senloraSymmetricV8GenerateFrame( ...
            config,starts(side),plan.snrDb,ledger);
        common = v4CommonBootstrap( ...
            frame.observation.rxPhysical( ...
            frame.observation.layout.bootstrapRows,:),c, ...
            SearchStepBins=parameters.searchStepBins);
        result = senloraSymmetricV8JointBlockDecode( ...
            frame.observation,common,config,plan);
        truth = frame.truth.payloadPhysicalBins(:);
        packet.jointErrors(side) = uint16(sum( ...
            result.detectedPhysicalBins(:)~=truth));
        packet.firstErrors(side) = uint16(sum( ...
            result.firstPassDetectedPhysicalBins(:)~=truth));
        packet.acceptedBlocks(side) = uint8(sum(result.blockAccepted));
        packet.maximumResidualBins(side) = ...
            max(abs(result.selectedResidualBins));
        packet.cfoRmseBins(side) = sqrt(mean( ...
            (result.estimatedCfoBins(:)-frame.truth.dataCfoBins(:)).^2));
        packet.usesForbiddenInput(side) = ...
            localFlag(result,'usesPayloadTruth') || ...
            localFlag(result,'usesOrbitTruth') || ...
            localFlag(result,'usesCaseIdentity') || ...
            localFlag(result,'usesSnrInput') || ...
            localFlag(result,'usesTargetSer') || ...
            localFlag(result,'usesExplicitMidambles');
    catch exception
        packet.jointErrors(side) = uint16(c.payloadSymbolCount);
        packet.firstErrors(side) = uint16(c.payloadSymbolCount);
        packet.failed(side) = true;
        packet.failureMessage(side) = string(exception.message);
    end
end
end

function value = localFlag(result,name)
value = isfield(result,name) && logical(result.(name));
end

function signature = localSignature(plan)
names = {'runSenloraSymmetricV8JointBlockValidation', ...
    'senloraSymmetricV8JointBlockDecode', ...
    'senloraSymmetricV8BlockLikelihood', ...
    'senloraSymmetricV8BlendBootstrap', ...
    'senloraSymmetricV8GenerateFrame'};
hashes = strings(size(names));
for index = 1:numel(names)
    path = which(names{index});
    if isempty(path)
        error('EXP5V8:Dependency','Cannot resolve %s.',names{index});
    end
    hashes(index) = exp1Sha256(path);
end
signature = struct('identity',plan.identity, ...
    'receiverVersion','SenLoRa-V8-joint-block-validation-v1', ...
    'seedRoot',plan.mechanismRootSeed,'snrDb',plan.snrDb, ...
    'negativeOrbitStartSec',plan.negativeOrbitStartSec, ...
    'frameDurationSec',plan.frameDurationSec, ...
    'driftBlendStartBins',plan.driftBlendStartBins, ...
    'driftBlendEndBins',plan.driftBlendEndBins, ...
    'packetsPerPair',plan.mechanismPacketsPerMirrorPair, ...
    'sourceNames',{names},'sourceSha256',hashes);
end

function localValidateCheckpoint(state,signature,shape)
required = {'signature','jointErrors','firstErrors','acceptedBlocks', ...
    'maximumResidualBins','cfoRmseBins','failed','failureMessage', ...
    'usesForbiddenInput','completed'};
for index = 1:numel(required)
    if ~isfield(state,required{index})
        error('EXP5V8:Checkpoint','Checkpoint field %s is missing.', ...
            required{index});
    end
end
if ~strcmp(jsonencode(state.signature),jsonencode(signature)) || ...
        ~isequal(size(state.jointErrors),shape) || ...
        ~isequal(size(state.completed),[shape(1),shape(3)])
    error('EXP5V8:Checkpoint','Joint-block checkpoint is incompatible.');
end
end

function localSaveCheckpoint(path,state)
temporary = path+".tmp";
save(temporary,'-struct','state','-v7.3');
[moved,message] = movefile(temporary,path,'f');
if ~moved
    error('EXP5V8:CheckpointWrite','%s',message);
end
end

function [raw,summary] = localTables(state,plan,c,paths)
baseline = readtable(fullfile(paths.resultsRoot,'senlora_symmetric_v8', ...
    'mechanism','MECHANISM_RAW_PACKETS.csv'));
pairCount = size(state.jointErrors,1);
packetCount = size(state.jointErrors,3);
rawRows = cell(pairCount*2*packetCount,16);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        for packetId = 1:packetCount
            row = row+1;
            old = baseline(baseline.pairIndex==pair & ...
                baseline.sideIndex==side & baseline.packetId==packetId,:);
            rawRows(row,:) = {pair,side,starts(side),packetId, ...
                double(state.jointErrors(pair,side,packetId)), ...
                double(state.firstErrors(pair,side,packetId)), ...
                old.v8RawErrors,old.v6RawErrors,old.idealRawErrors, ...
                double(state.jointErrors(pair,side,packetId))/ ...
                c.payloadSymbolCount, ...
                double(state.acceptedBlocks(pair,side,packetId)), ...
                state.maximumResidualBins(pair,side,packetId), ...
                state.cfoRmseBins(pair,side,packetId), ...
                state.failed(pair,side,packetId), ...
                state.usesForbiddenInput(pair,side,packetId), ...
                state.failureMessage(pair,side,packetId)};
        end
    end
end
raw = cell2table(rawRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packetId', ...
    'jointRawErrors','firstRawErrors','oldV8RawErrors', ...
    'v6RawErrors','idealRawErrors','jointSer','acceptedBlocks', ...
    'maximumResidualBins','cfoRmseBins','failed', ...
    'usesForbiddenInput','failureMessage'});

pointRows = cell(pairCount*2,14);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        row = row+1;
        selected = raw.pairIndex==pair & raw.sideIndex==side;
        pointRows(row,:) = {pair,side,starts(side),packetCount, ...
            sum(raw.jointRawErrors(selected)), ...
            sum(raw.oldV8RawErrors(selected)),sum(raw.v6RawErrors(selected)), ...
            sum(raw.idealRawErrors(selected)), ...
            sum(raw.jointRawErrors(selected))/(packetCount*c.payloadSymbolCount), ...
            sum(raw.oldV8RawErrors(selected))/(packetCount*c.payloadSymbolCount), ...
            mean(raw.acceptedBlocks(selected)), ...
            max(raw.maximumResidualBins(selected)), ...
            sqrt(mean(raw.cfoRmseBins(selected).^2)), ...
            sum(raw.failed(selected))};
    end
end
summary = cell2table(pointRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packets', ...
    'jointRawErrors','oldV8RawErrors','v6RawErrors','idealRawErrors', ...
    'jointSer','oldV8Ser','meanAcceptedBlocks','maximumResidualBins', ...
    'cfoRmseBins','failedFrames'});
summary = sortrows(summary,'orbitStartSec');
end

function localPlot(summary,root)
f = figure('Visible','off','Color','w','Position',[100 100 1080 620]);
plot(summary.orbitStartSec,summary.jointSer,'-o','LineWidth',1.3, ...
    'DisplayName','Joint-block V8');
hold on
plot(summary.orbitStartSec,summary.oldV8Ser,'-s','LineWidth',1.1, ...
    'DisplayName','Original V8');
grid on;xlabel('Frame start time (s)');ylabel('Raw SER');
title({'V8 joint block CFO/Hamming ML mechanism replay', ...
    'Measured points connected directly; no fit or smoothing'});
legend('Location','best');
exportgraphics(f,fullfile(root,'JOINT_BLOCK_RAW_POINTS.png'), ...
    'Resolution',220);
close(f);
end
