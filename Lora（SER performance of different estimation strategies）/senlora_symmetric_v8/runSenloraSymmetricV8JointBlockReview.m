function output = runSenloraSymmetricV8JointBlockReview(options)
%RUNSENLORASYMMETRICV8JOINTBLOCKREVIEW Independent 9-pair Review run.

arguments
    options.WorkerCount (1,1) double {mustBeInteger,mustBePositive} = 2
end

here = fileparts(mfilename('fullpath'));
addpath(fullfile(here,'..','scripts'));
addpath(fullfile(here,'..','senlora_symmetric_v2'));
addpath(fullfile(here,'..','senlora_symmetric_v3'));
addpath(fullfile(here,'..','senlora_symmetric_v6'));
paths = exp1SetupPaths();
addpath(here);
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
c = config.parent;
plan = senloraSymmetricV8Config(config);
v6Plan = senloraSymmetricV6Config(config);
v6Plan.frameDurationSec = plan.frameDurationSec;
commonParameters = v4LoadMethodAlignedR3ParametersV1();

pairCount = numel(plan.negativeOrbitStartSec);
packetCount = 100;
if pairCount~=9
    error('EXP5V8:ReviewScope','Review requires exactly 9 mirror pairs.');
end
shape = [pairCount,2,packetCount];
root = fullfile(paths.resultsRoot,'senlora_symmetric_v8', ...
    'joint_block_review');
if ~isfolder(root)
    mkdir(root);
end
checkpointPath = fullfile(root,'REVIEW_CHECKPOINT.mat');
signature = senloraSymmetricV8ReviewSignature( ...
    plan,v6Plan,config,packetCount,commonParameters);
if isfile(checkpointPath)
    state = load(checkpointPath);
    localValidateCheckpoint(state,signature,shape);
else
    state = struct('signature',signature, ...
        'jointErrors',zeros(shape,'uint16'), ...
        'v6Errors',zeros(shape,'uint16'), ...
        'idealErrors',zeros(shape,'uint16'), ...
        'firstErrors',zeros(shape,'uint16'), ...
        'acceptedBlocks',zeros(shape,'uint8'), ...
        'maximumResidualBins',nan(shape), ...
        'cfoRmseBins',nan(shape), ...
        'rateGain',nan(shape), ...
        'failed',false([shape,3]), ...
        'failureMessage',strings([shape,3]), ...
        'usesForbiddenInput',false(shape), ...
        'payloadSeed',zeros(pairCount,packetCount), ...
        'noiseSeed',zeros(pairCount,packetCount), ...
        'completed',false(pairCount,packetCount));
end

if any(~state.completed,'all')
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('local',options.WorkerCount);
    elseif pool.NumWorkers~=options.WorkerCount
        error('EXP5V8:WorkerCount', ...
            'The existing parallel pool has the wrong worker count.');
    end
end

for blockStart = 1:5:packetCount
    packetIds = blockStart:min(packetCount,blockStart+4);
    [pairRows,packetColumns] = find(~state.completed(:,packetIds));
    if isempty(pairRows)
        continue
    end
    jobPairs = pairRows;
    jobPackets = packetIds(packetColumns).';
    jobCount = numel(jobPairs);
    jobJoint = zeros(jobCount,2,'uint16');
    jobV6 = zeros(jobCount,2,'uint16');
    jobIdeal = zeros(jobCount,2,'uint16');
    jobFirst = zeros(jobCount,2,'uint16');
    jobAccepted = zeros(jobCount,2,'uint8');
    jobMaximumResidual = nan(jobCount,2);
    jobCfoRmse = nan(jobCount,2);
    jobGain = nan(jobCount,2);
    jobFailed = false(jobCount,2,3);
    jobMessage = strings(jobCount,2,3);
    jobForbidden = false(jobCount,2);
    jobPayloadSeed = zeros(jobCount,1);
    jobNoiseSeed = zeros(jobCount,1);
    parfor job = 1:jobCount
        packet = localEvaluate(jobPairs(job),jobPackets(job), ...
            config,plan,v6Plan,commonParameters);
        jobJoint(job,:) = packet.jointErrors;
        jobV6(job,:) = packet.v6Errors;
        jobIdeal(job,:) = packet.idealErrors;
        jobFirst(job,:) = packet.firstErrors;
        jobAccepted(job,:) = packet.acceptedBlocks;
        jobMaximumResidual(job,:) = packet.maximumResidualBins;
        jobCfoRmse(job,:) = packet.cfoRmseBins;
        jobGain(job,:) = packet.rateGain;
        jobFailed(job,:,:) = packet.failed;
        jobMessage(job,:,:) = packet.failureMessage;
        jobForbidden(job,:) = packet.usesForbiddenInput;
        jobPayloadSeed(job) = packet.payloadSeed;
        jobNoiseSeed(job) = packet.noiseSeed;
    end
    for job = 1:jobCount
        pair = jobPairs(job);
        packetId = jobPackets(job);
        state.jointErrors(pair,:,packetId) = jobJoint(job,:);
        state.v6Errors(pair,:,packetId) = jobV6(job,:);
        state.idealErrors(pair,:,packetId) = jobIdeal(job,:);
        state.firstErrors(pair,:,packetId) = jobFirst(job,:);
        state.acceptedBlocks(pair,:,packetId) = jobAccepted(job,:);
        state.maximumResidualBins(pair,:,packetId) = ...
            jobMaximumResidual(job,:);
        state.cfoRmseBins(pair,:,packetId) = jobCfoRmse(job,:);
        state.rateGain(pair,:,packetId) = jobGain(job,:);
        state.failed(pair,:,packetId,:) = ...
            reshape(jobFailed(job,:,:),[1,2,1,3]);
        state.failureMessage(pair,:,packetId,:) = ...
            reshape(jobMessage(job,:,:),[1,2,1,3]);
        state.usesForbiddenInput(pair,:,packetId) = jobForbidden(job,:);
        state.payloadSeed(pair,packetId) = jobPayloadSeed(job);
        state.noiseSeed(pair,packetId) = jobNoiseSeed(job);
        state.completed(pair,packetId) = true;
    end
    localSaveCheckpoint(checkpointPath,state);
    fprintf(['Joint-block Review pair-packets=%d/%d; ' ...
        'errors Joint/V6/Ideal=%d/%d/%d; failures=%d\n'], ...
        sum(state.completed,'all'),numel(state.completed), ...
        sum(state.jointErrors,'all'),sum(state.v6Errors,'all'), ...
        sum(state.idealErrors,'all'),sum(state.failed,'all'));
end

if ~all(state.completed,'all')
    error('EXP5V8:ReviewIncomplete','Joint-block Review is incomplete.');
end
[raw,summary] = localTables(state,plan,c);
[checks,caseTests,mirrors,adjacent] = localChecks(state,summary,c,plan);
writetable(raw,fullfile(root,'REVIEW_RAW_PACKETS.csv'));
writetable(summary,fullfile(root,'REVIEW_RAW_POINTS.csv'));
writetable(caseTests,fullfile(root,'REVIEW_CASE_PAIRED_DIFFERENCES.csv'));
writetable(mirrors,fullfile(root,'REVIEW_MIRROR_DIFFERENCES.csv'));
writetable(adjacent,fullfile(root,'REVIEW_ADJACENT_POINTS.csv'));
save(fullfile(root,'REVIEW_RESULT.mat'),'-struct','state','-v7.3');
save(fullfile(root,'REVIEW_CHECKS.mat'),'checks','caseTests', ...
    'mirrors','adjacent','-v7.3');
localPlot(summary,root);
output = struct('status','JOINT_BLOCK_REVIEW_COMPLETE', ...
    'checks',checks,'caseTests',caseTests,'mirrors',mirrors, ...
    'adjacent',adjacent,'summary',summary,'root',root);
end

function packet = localEvaluate(pairIndex,packetId,config,plan,v6Plan,parameters)
c = config.parent;
negative = plan.negativeOrbitStartSec(pairIndex);
starts = [negative,-negative-plan.frameDurationSec];
ledger = senloraSymmetricV3SeedPlan( ...
    config,plan,'review',pairIndex,plan.snrDb,packetId);
packet = struct('jointErrors',zeros(1,2,'uint16'), ...
    'v6Errors',zeros(1,2,'uint16'), ...
    'idealErrors',zeros(1,2,'uint16'), ...
    'firstErrors',zeros(1,2,'uint16'), ...
    'acceptedBlocks',zeros(1,2,'uint8'), ...
    'maximumResidualBins',nan(1,2),'cfoRmseBins',nan(1,2), ...
    'rateGain',nan(1,2),'failed',false(2,3), ...
    'failureMessage',strings(2,3), ...
    'usesForbiddenInput',false(1,2), ...
    'payloadSeed',ledger.payloadSeed,'noiseSeed',ledger.noiseSeed);
for side = 1:2
    try
        frame = senloraSymmetricV8GenerateFrame( ...
            config,starts(side),plan.snrDb,ledger);
        common = v4CommonBootstrap( ...
            frame.observation.rxPhysical( ...
            frame.observation.layout.bootstrapRows,:),c, ...
            SearchStepBins=parameters.searchStepBins);
    catch exception
        packet.jointErrors(side) = uint16(c.payloadSymbolCount);
        packet.v6Errors(side) = uint16(c.payloadSymbolCount);
        packet.idealErrors(side) = uint16(c.payloadSymbolCount);
        packet.firstErrors(side) = uint16(c.payloadSymbolCount);
        packet.failed(side,:) = true;
        packet.failureMessage(side,:) = string(exception.message);
        continue
    end

    try
        joint = senloraSymmetricV8JointBlockDecode( ...
            frame.observation,common,config,plan);
        truth = frame.truth.payloadPhysicalBins(:);
        packet.jointErrors(side) = uint16(sum( ...
            joint.detectedPhysicalBins(:)~=truth));
        packet.firstErrors(side) = uint16(sum( ...
            joint.firstPassDetectedPhysicalBins(:)~=truth));
        packet.acceptedBlocks(side) = uint8(sum(joint.blockAccepted));
        packet.maximumResidualBins(side) = ...
            max(abs(joint.selectedResidualBins));
        packet.cfoRmseBins(side) = sqrt(mean( ...
            (joint.estimatedCfoBins(:)-frame.truth.dataCfoBins(:)).^2));
        packet.rateGain(side) = joint.rateGain;
        packet.usesForbiddenInput(side) = ...
            localFlag(joint,'usesPayloadTruth') || ...
            localFlag(joint,'usesOrbitTruth') || ...
            localFlag(joint,'usesCaseIdentity') || ...
            localFlag(joint,'usesSnrInput') || ...
            localFlag(joint,'usesTargetSer') || ...
            localFlag(joint,'usesExplicitMidambles');
    catch exception
        packet.jointErrors(side) = uint16(c.payloadSymbolCount);
        packet.firstErrors(side) = uint16(c.payloadSymbolCount);
        packet.failed(side,1) = true;
        packet.failureMessage(side,1) = string(exception.message);
    end

    try
        v6 = senloraSymmetricV6Decode( ...
            frame.observation,common,config,v6Plan);
        packet.v6Errors(side) = uint16(sum( ...
            v6.detectedPhysicalBins(:)~=frame.truth.payloadPhysicalBins(:)));
    catch exception
        packet.v6Errors(side) = uint16(c.payloadSymbolCount);
        packet.failed(side,2) = true;
        packet.failureMessage(side,2) = string(exception.message);
    end

    try
        ideal = exp1IdealDecode(frame,config);
        packet.idealErrors(side) = uint16(sum( ...
            ideal.detectedPhysicalBins(:)~=frame.truth.payloadPhysicalBins(:)));
    catch exception
        packet.idealErrors(side) = uint16(c.payloadSymbolCount);
        packet.failed(side,3) = true;
        packet.failureMessage(side,3) = string(exception.message);
    end
end
end

function value = localFlag(result,name)
value = isfield(result,name) && logical(result.(name));
end

function localValidateCheckpoint(state,signature,shape)
required = {'signature','jointErrors','v6Errors','idealErrors', ...
    'firstErrors','acceptedBlocks','maximumResidualBins','cfoRmseBins', ...
    'rateGain','failed','failureMessage','usesForbiddenInput', ...
    'payloadSeed','noiseSeed','completed'};
for index = 1:numel(required)
    if ~isfield(state,required{index})
        error('EXP5V8:Checkpoint','Review checkpoint field %s is missing.', ...
            required{index});
    end
end
if ~strcmp(jsonencode(state.signature),jsonencode(signature)) || ...
        ~isequal(size(state.jointErrors),shape) || ...
        ~isequal(size(state.failed),[shape,3]) || ...
        ~isequal(size(state.completed),[shape(1),shape(3)])
    error('EXP5V8:Checkpoint','Joint-block Review checkpoint is incompatible.');
end
end

function localSaveCheckpoint(path,state)
temporary = path+".tmp";
save(temporary,'-struct','state','-v7.3');
[moved,message] = movefile(temporary,path,'f');
if ~moved
    error('EXP5V8:CheckpointWrite','%s',message);
end
end

function [raw,summary] = localTables(state,plan,c)
pairCount = size(state.jointErrors,1);
packetCount = size(state.jointErrors,3);
rawRows = cell(pairCount*2*packetCount,23);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        for packetId = 1:packetCount
            row = row+1;
            rawRows(row,:) = {pair,side,starts(side),packetId, ...
                state.payloadSeed(pair,packetId), ...
                state.noiseSeed(pair,packetId), ...
                double(state.jointErrors(pair,side,packetId)), ...
                double(state.v6Errors(pair,side,packetId)), ...
                double(state.idealErrors(pair,side,packetId)), ...
                double(state.firstErrors(pair,side,packetId)), ...
                double(state.jointErrors(pair,side,packetId))/ ...
                    c.payloadSymbolCount, ...
                double(state.v6Errors(pair,side,packetId))/ ...
                    c.payloadSymbolCount, ...
                double(state.idealErrors(pair,side,packetId))/ ...
                    c.payloadSymbolCount, ...
                double(state.acceptedBlocks(pair,side,packetId)), ...
                state.maximumResidualBins(pair,side,packetId), ...
                state.cfoRmseBins(pair,side,packetId), ...
                state.rateGain(pair,side,packetId), ...
                state.failed(pair,side,packetId,1), ...
                state.failed(pair,side,packetId,2), ...
                state.failed(pair,side,packetId,3), ...
                state.usesForbiddenInput(pair,side,packetId), ...
                strjoin(state.failureMessage(pair,side,packetId,:),'; '), ...
                state.signature.seedRoot};
        end
    end
end
raw = cell2table(rawRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packetId', ...
    'payloadSeed','noiseSeed','jointRawErrors','v6RawErrors', ...
    'idealRawErrors','firstRawErrors','jointSer','v6Ser','idealSer', ...
    'acceptedBlocks','maximumResidualBins','cfoRmseBins','rateGain', ...
    'jointFailed','v6Failed','idealFailed','usesForbiddenInput', ...
    'failureMessage','seedRoot'});

pointRows = cell(pairCount*2,19);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        row = row+1;
        joint = double(reshape(state.jointErrors(pair,side,:),[],1));
        v6 = double(reshape(state.v6Errors(pair,side,:),[],1));
        ideal = double(reshape(state.idealErrors(pair,side,:),[],1));
        first = double(reshape(state.firstErrors(pair,side,:),[],1));
        accepted = double(reshape(state.acceptedBlocks(pair,side,:),[],1));
        residual = reshape(state.maximumResidualBins(pair,side,:),[],1);
        cfo = reshape(state.cfoRmseBins(pair,side,:),[],1);
        gain = reshape(state.rateGain(pair,side,:),[],1);
        pointRows(row,:) = {pair,side,starts(side),packetCount, ...
            sum(joint),sum(v6),sum(ideal),sum(first), ...
            sum(joint)/(packetCount*c.payloadSymbolCount), ...
            sum(v6)/(packetCount*c.payloadSymbolCount), ...
            sum(ideal)/(packetCount*c.payloadSymbolCount), ...
            mean(accepted),min(accepted),max(residual), ...
            sqrt(mean(cfo.^2)),mean(gain),min(gain),max(gain), ...
            sum(state.failed(pair,side,:,:),'all')};
    end
end
summary = cell2table(pointRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packets', ...
    'jointRawErrors','v6RawErrors','idealRawErrors','firstRawErrors', ...
    'jointSer','v6Ser','idealSer','meanAcceptedBlocks', ...
    'minimumAcceptedBlocks','maximumResidualBins','cfoRmseBins', ...
    'meanGain','minimumGain','maximumGain','receiverFailures'});
summary = sortrows(summary,'orbitStartSec');
end

function [checks,caseTests,mirrors,adjacent] = ...
        localChecks(state,summary,c,plan)
draws = 10000;
stream = RandStream('mt19937ar','Seed',plan.reviewRootSeed+2718);
symbolsPerPairPacket = 2*c.payloadSymbolCount;

case1Joint = squeeze(sum(double(state.jointErrors(1,:,:)),2));
case1V6 = squeeze(sum(double(state.v6Errors(1,:,:)),2));
case2Joint = squeeze(sum(double(state.jointErrors(end,:,:)),2));
case2Ideal = squeeze(sum(double(state.idealErrors(end,:,:)),2));
case1Difference = (case1Joint(:)-case1V6(:))/symbolsPerPairPacket;
case2Difference = (case2Joint(:)-case2Ideal(:))/symbolsPerPairPacket;
case1Bounds = localPairedBounds(case1Difference,stream,draws);
case2Bounds = localPairedBounds(case2Difference,stream,draws);
caseTests = table(["Case1 V8-V6-native";"Case2 V8-Ideal"], ...
    [mean(case1Difference);mean(case2Difference)], ...
    [case1Bounds(1);case2Bounds(1)], ...
    [case1Bounds(2);case2Bounds(2)], ...
    [case1Bounds(1)>0;case2Bounds(1)>0], ...
    'VariableNames',{'comparison','meanPairedSerDifference', ...
    'lower95','upper95','significantlyWorse'});

pairCount = size(state.jointErrors,1);
mirrorRows = cell(pairCount,9);
for pair = 1:pairCount
    negative = reshape(double(state.jointErrors(pair,1,:)),[],1);
    positive = reshape(double(state.jointErrors(pair,2,:)),[],1);
    difference = (negative-positive)/c.payloadSymbolCount;
    bounds = localPairedBounds(difference,stream,draws);
    mirrorRows(pair,:) = {pair,plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec, ...
        sum(negative),sum(positive),mean(difference), ...
        bounds(1),bounds(2),bounds(1)>0 || bounds(2)<0};
end
mirrors = cell2table(mirrorRows,'VariableNames',{ ...
    'pairIndex','negativeOrbitStartSec','positiveOrbitStartSec', ...
    'negativeRawErrors','positiveRawErrors','meanSerDifference', ...
    'lower95','upper95','significantMirrorDifference'});

pointCount = height(summary);
adjacentRows = cell(pointCount-1,11);
displayFloor = 0.5/(size(state.jointErrors,3)*c.payloadSymbolCount);
for row = 1:pointCount-1
    a = localPointErrors(state,summary.pairIndex(row), ...
        summary.sideIndex(row));
    b = localPointErrors(state,summary.pairIndex(row+1), ...
        summary.sideIndex(row+1));
    bounds = localIndependentBounds( ...
        a/c.payloadSymbolCount,b/c.payloadSymbolCount,stream,draws);
    change = summary.jointSer(row+1)-summary.jointSer(row);
    ratio = max(summary.jointSer(row+1),displayFloor)/ ...
        max(summary.jointSer(row),displayFloor);
    significant = bounds(1)>0 || bounds(2)<0;
    orderJump = ratio>=10 || ratio<=0.1;
    adjacentRows(row,:) = {summary.orbitStartSec(row), ...
        summary.orbitStartSec(row+1),summary.jointRawErrors(row), ...
        summary.jointRawErrors(row+1),change,bounds(1),bounds(2), ...
        ratio,significant,orderJump,significant && orderJump};
end
adjacent = cell2table(adjacentRows,'VariableNames',{ ...
    'fromOrbitStartSec','toOrbitStartSec','fromRawErrors', ...
    'toRawErrors','serChange','lower95','upper95','displayFloorRatio', ...
    'significantDifference','orderMagnitudeJump','obviousAdjacentJump'});

checks = struct( ...
    'status','JOINT_BLOCK_REVIEW_COMPLETE', ...
    'jointRawErrors',sum(state.jointErrors,'all'), ...
    'v6RawErrors',sum(state.v6Errors,'all'), ...
    'idealRawErrors',sum(state.idealErrors,'all'), ...
    'jointSer',sum(state.jointErrors,'all')/numel(state.jointErrors)/ ...
        c.payloadSymbolCount, ...
    'v6Ser',sum(state.v6Errors,'all')/numel(state.v6Errors)/ ...
        c.payloadSymbolCount, ...
    'idealSer',sum(state.idealErrors,'all')/numel(state.idealErrors)/ ...
        c.payloadSymbolCount, ...
    'case1SignificantlyWorse',caseTests.significantlyWorse(1), ...
    'case2SignificantlyWorse',caseTests.significantlyWorse(2), ...
    'significantMirrorCount',sum(mirrors.significantMirrorDifference), ...
    'obviousAdjacentJumpCount',sum(adjacent.obviousAdjacentJump), ...
    'maximumPacketErrors',max(state.jointErrors,[],'all'), ...
    'minimumAcceptedBlocks',min(state.acceptedBlocks,[],'all'), ...
    'maximumResidualBins',max(state.maximumResidualBins,[],'all'), ...
    'maximumCfoRmseBins',max(state.cfoRmseBins,[],'all'), ...
    'receiverFailures',sum(state.failed,'all'), ...
    'allForbiddenFlagsFalse',~any(state.usesForbiddenInput,'all'), ...
    'allGainsFiniteAndBounded',all(isfinite(state.rateGain),'all') && ...
        all(state.rateGain>=0 & state.rateGain<=1,'all'), ...
    'pairedBootstrapDraws',draws, ...
    'bootstrapSeed',plan.reviewRootSeed+2718, ...
    'parametersFrozen',false,'formalRunStarted',false);
end

function errors = localPointErrors(state,pair,side)
errors = reshape(double(state.jointErrors(pair,side,:)),[],1);
end

function bounds = localPairedBounds(difference,stream,draws)
n = numel(difference);
samples = zeros(draws,1);
for draw = 1:draws
    index = randi(stream,n,n,1);
    samples(draw) = mean(difference(index));
end
bounds = prctile(samples,[2.5 97.5]);
end

function bounds = localIndependentBounds(a,b,stream,draws)
nA = numel(a);
nB = numel(b);
samples = zeros(draws,1);
for draw = 1:draws
    indexA = randi(stream,nA,nA,1);
    indexB = randi(stream,nB,nB,1);
    samples(draw) = mean(b(indexB))-mean(a(indexA));
end
bounds = prctile(samples,[2.5 97.5]);
end

function localPlot(summary,root)
x = summary.orbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1180 760]);
tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
nexttile
plot(x,summary.jointSer,'-o','LineWidth',1.2, ...
    'DisplayName','Joint-block V8');
hold on
plot(x,summary.v6Ser,'-s','LineWidth',1.2, ...
    'DisplayName','V6-native');
plot(x,summary.idealSer,'-^','LineWidth',1.2, ...
    'DisplayName','Ideal');
grid on;xlabel('Frame start time (s)');ylabel('Raw SER');
title('Independent Review raw points');legend('Location','best');
nexttile
plot(x,summary.meanGain,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('Mean gain');ylim([-0.05 1.05]);
title('Static-to-Dynamic gain');
nexttile
plot(x,summary.meanAcceptedBlocks,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('Accepted blocks per packet');
title('Quality-gated block updates');
nexttile
plot(x,summary.cfoRmseBins,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('CFO residual RMSE (bins)');
title('Joint-block V8 CFO residual');
sgtitle({'SenLoRa V8 independent Review', ...
    'Measured points connected directly; no fit or smoothing'});
exportgraphics(f,fullfile(root,'REVIEW_RAW_POINTS.png'),'Resolution',220);
close(f);
end
