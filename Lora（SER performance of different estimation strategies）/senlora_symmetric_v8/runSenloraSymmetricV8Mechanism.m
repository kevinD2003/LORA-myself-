function output = runSenloraSymmetricV8Mechanism(options)
%RUNSENLORASYMMETRICV8MECHANISM Fixed 9-pair, 20-packet V8 mechanism run.

arguments
    options.WorkerCount (1,1) double {mustBeInteger,mustBePositive} = 2
end

here = fileparts(mfilename('fullpath'));
addpath(fullfile(here,'..','scripts'));
addpath(fullfile(here,'..','senlora_symmetric_v2'));
addpath(fullfile(here,'..','senlora_symmetric_v3'));
addpath(fullfile(here,'..','senlora_symmetric_v6'));
paths = exp1SetupPaths();
addpath(here);
addpath(fullfile(paths.projectRoot,'review_first_v1'));
config = exp1Config();
c = config.parent;
plan = senloraSymmetricV8Config(config);
v6Plan = senloraSymmetricV6Config(config);
v6Plan.frameDurationSec = plan.frameDurationSec;
commonParameters = v4LoadMethodAlignedR3ParametersV1();

pairCount = numel(plan.negativeOrbitStartSec);
packetCount = plan.mechanismPacketsPerMirrorPair;
if pairCount~=9 || packetCount~=20
    error('EXP5V8:MechanismScope', ...
        'The V8 mechanism run is fixed at 9 mirror pairs and 20 packets.');
end
root = fullfile(paths.resultsRoot,'senlora_symmetric_v8','mechanism');
if ~isfolder(root)
    mkdir(root);
end
checkpointPath = fullfile(root,'MECHANISM_CHECKPOINT.mat');
signature = localSignature(plan,v6Plan,config);

shape = [pairCount,2,packetCount];
nData = c.payloadSymbolCount;
if isfile(checkpointPath)
    state = load(checkpointPath);
    localValidateCheckpoint(state,signature,shape,nData);
else
    state = struct( ...
        'signature',signature, ...
        'v8Errors',zeros(shape,'uint16'), ...
        'v6Errors',zeros(shape,'uint16'), ...
        'idealErrors',zeros(shape,'uint16'), ...
        'rateGain',nan(shape), ...
        'preambleRateBinsPerSec',nan(shape), ...
        'candidateVp',zeros(shape,'uint16'), ...
        'acceptedVp',zeros(shape,'uint16'), ...
        'passCount',zeros(shape,'uint8'), ...
        'v8CfoResidualBins',nan([shape,nData],'single'), ...
        'failed',false([shape,3]), ...
        'failureMessage',strings([shape,3]), ...
        'v8UsageFlags',false([shape,6]), ...
        'payloadSeed',zeros(pairCount,packetCount), ...
        'noiseSeed',zeros(pairCount,packetCount), ...
        'completed',false(pairCount,packetCount));
end

if any(~state.completed,'all')
    pool = gcp('nocreate');
    if isempty(pool)
        parpool('local',options.WorkerCount);
    elseif pool.NumWorkers~=options.WorkerCount
        error('EXP5V8:WorkerCount', ...
            'The existing parallel pool has the wrong worker count.');
    end
end

for blockStart = 1:5:packetCount
    packetIds = blockStart:min(packetCount,blockStart+4);
    [pairRows,packetColumns] = find(~state.completed(:,packetIds));
    if isempty(pairRows)
        continue
    end
    jobPairs = pairRows;
    jobPackets = packetIds(packetColumns).';
    jobCount = numel(jobPairs);
    jobV8 = zeros(jobCount,2,'uint16');
    jobV6 = zeros(jobCount,2,'uint16');
    jobIdeal = zeros(jobCount,2,'uint16');
    jobGain = nan(jobCount,2);
    jobRate = nan(jobCount,2);
    jobCandidate = zeros(jobCount,2,'uint16');
    jobAccepted = zeros(jobCount,2,'uint16');
    jobPasses = zeros(jobCount,2,'uint8');
    jobCfo = nan(jobCount,2,nData,'single');
    jobFailed = false(jobCount,2,3);
    jobMessages = strings(jobCount,2,3);
    jobFlags = false(jobCount,2,6);
    jobPayloadSeed = zeros(jobCount,1);
    jobNoiseSeed = zeros(jobCount,1);
    parfor job = 1:jobCount
        packet = localEvaluate(jobPairs(job),jobPackets(job), ...
            config,plan,v6Plan,commonParameters);
        jobV8(job,:) = packet.v8Errors;
        jobV6(job,:) = packet.v6Errors;
        jobIdeal(job,:) = packet.idealErrors;
        jobGain(job,:) = packet.rateGain;
        jobRate(job,:) = packet.preambleRateBinsPerSec;
        jobCandidate(job,:) = packet.candidateVp;
        jobAccepted(job,:) = packet.acceptedVp;
        jobPasses(job,:) = packet.passCount;
        jobCfo(job,:,:) = packet.v8CfoResidualBins;
        jobFailed(job,:,:) = packet.failed;
        jobMessages(job,:,:) = packet.failureMessage;
        jobFlags(job,:,:) = packet.v8UsageFlags;
        jobPayloadSeed(job) = packet.payloadSeed;
        jobNoiseSeed(job) = packet.noiseSeed;
    end
    for job = 1:jobCount
        pair = jobPairs(job);
        packetId = jobPackets(job);
        state.v8Errors(pair,:,packetId) = jobV8(job,:);
        state.v6Errors(pair,:,packetId) = jobV6(job,:);
        state.idealErrors(pair,:,packetId) = jobIdeal(job,:);
        state.rateGain(pair,:,packetId) = jobGain(job,:);
        state.preambleRateBinsPerSec(pair,:,packetId) = jobRate(job,:);
        state.candidateVp(pair,:,packetId) = jobCandidate(job,:);
        state.acceptedVp(pair,:,packetId) = jobAccepted(job,:);
        state.passCount(pair,:,packetId) = jobPasses(job,:);
        state.v8CfoResidualBins(pair,:,packetId,:) = ...
            reshape(jobCfo(job,:,:),[1,2,1,nData]);
        state.failed(pair,:,packetId,:) = ...
            reshape(jobFailed(job,:,:),[1,2,1,3]);
        state.failureMessage(pair,:,packetId,:) = ...
            reshape(jobMessages(job,:,:),[1,2,1,3]);
        state.v8UsageFlags(pair,:,packetId,:) = ...
            reshape(jobFlags(job,:,:),[1,2,1,6]);
        state.payloadSeed(pair,packetId) = jobPayloadSeed(job);
        state.noiseSeed(pair,packetId) = jobNoiseSeed(job);
        state.completed(pair,packetId) = true;
    end
    localSaveCheckpoint(checkpointPath,state);
    fprintf(['V8 mechanism pair-packets=%d/%d; errors V8/V6/Ideal=' ...
        '%d/%d/%d; receiver failures=%d\n'], ...
        sum(state.completed,'all'),numel(state.completed), ...
        sum(state.v8Errors,'all'),sum(state.v6Errors,'all'), ...
        sum(state.idealErrors,'all'),sum(state.failed,'all'));
end

if ~all(state.completed,'all')
    error('EXP5V8:MechanismIncomplete','The mechanism run is incomplete.');
end
[raw,summary] = localTables(state,plan,c);
gates = localMechanismChecks(state,summary,c);
writetable(raw,fullfile(root,'MECHANISM_RAW_PACKETS.csv'));
writetable(summary,fullfile(root,'MECHANISM_RAW_POINTS.csv'));
save(fullfile(root,'MECHANISM_RESULT.mat'),'-struct','state','-v7.3');
save(fullfile(root,'MECHANISM_CHECKS.mat'),'gates','-v7.3');
localPlot(summary,root);
output = struct('status','MECHANISM_COMPLETE_REQUIRES_REVIEW', ...
    'raw',raw,'summary',summary,'checks',gates,'root',root);
end

function packet = localEvaluate(pairIndex,packetId,config,plan,v6Plan,parameters)
c = config.parent;
negative = plan.negativeOrbitStartSec(pairIndex);
starts = [negative,-negative-plan.frameDurationSec];
ledger = senloraSymmetricV3SeedPlan(config,plan,'mechanism', ...
    pairIndex,plan.snrDb,packetId);
nData = c.payloadSymbolCount;
packet = struct('v8Errors',zeros(1,2,'uint16'), ...
    'v6Errors',zeros(1,2,'uint16'), ...
    'idealErrors',zeros(1,2,'uint16'), ...
    'rateGain',nan(1,2),'preambleRateBinsPerSec',nan(1,2), ...
    'candidateVp',zeros(1,2,'uint16'), ...
    'acceptedVp',zeros(1,2,'uint16'), ...
    'passCount',zeros(1,2,'uint8'), ...
    'v8CfoResidualBins',nan(2,nData,'single'), ...
    'failed',false(2,3),'failureMessage',strings(2,3), ...
    'v8UsageFlags',false(2,6), ...
    'payloadSeed',ledger.payloadSeed,'noiseSeed',ledger.noiseSeed);
for side = 1:2
    try
        frame = senloraSymmetricV8GenerateFrame( ...
            config,starts(side),plan.snrDb,ledger);
        pilots = frame.observation.rxPhysical( ...
            frame.observation.layout.bootstrapRows,:);
        common = v4CommonBootstrap(pilots,c, ...
            SearchStepBins=parameters.searchStepBins);
    catch exception
        packet.v8Errors(side) = uint16(nData);
        packet.v6Errors(side) = uint16(nData);
        packet.idealErrors(side) = uint16(nData);
        packet.failed(side,:) = true;
        packet.failureMessage(side,:) = string(exception.message);
        continue
    end

    try
        v8 = senloraSymmetricV8Decode( ...
            frame.observation,common,config,plan);
        packet.v8Errors(side) = uint16(sum( ...
            v8.detectedPhysicalBins(:)~=frame.truth.payloadPhysicalBins(:)));
        packet.rateGain(side) = v8.decision.rateGain;
        packet.preambleRateBinsPerSec(side) = ...
            v8.decision.preambleRateBinsPerSec;
        packet.candidateVp(side) = uint16( ...
            v8.decision.candidateVirtualPilots);
        packet.acceptedVp(side) = uint16( ...
            v8.decision.acceptedVirtualPilots);
        packet.passCount(side) = uint8(v8.decision.passCount);
        packet.v8CfoResidualBins(side,:) = single( ...
            v8.estimatedCfoBins(:)-frame.truth.dataCfoBins(:));
        packet.v8UsageFlags(side,:) = [ ...
            localFlag(v8,'usesPayloadTruth'), ...
            localFlag(v8,'usesOrbitTruth'), ...
            localFlag(v8,'usesCaseIdentity'), ...
            localFlag(v8,'usesSnrInput'), ...
            localFlag(v8,'usesTargetSer'), ...
            localFlag(v8,'usesExplicitMidambles')];
    catch exception
        packet.v8Errors(side) = uint16(nData);
        packet.failed(side,1) = true;
        packet.failureMessage(side,1) = string(exception.message);
    end

    try
        v6 = senloraSymmetricV6Decode( ...
            frame.observation,common,config,v6Plan);
        packet.v6Errors(side) = uint16(sum( ...
            v6.detectedPhysicalBins(:)~=frame.truth.payloadPhysicalBins(:)));
    catch exception
        packet.v6Errors(side) = uint16(nData);
        packet.failed(side,2) = true;
        packet.failureMessage(side,2) = string(exception.message);
    end

    try
        ideal = exp1IdealDecode(frame,config);
        packet.idealErrors(side) = uint16(sum( ...
            ideal.detectedPhysicalBins(:)~=frame.truth.payloadPhysicalBins(:)));
    catch exception
        packet.idealErrors(side) = uint16(nData);
        packet.failed(side,3) = true;
        packet.failureMessage(side,3) = string(exception.message);
    end
end
end

function value = localFlag(result,name)
value = isfield(result,name) && logical(result.(name));
end

function signature = localSignature(plan,v6Plan,config)
names = {'runSenloraSymmetricV8Mechanism', ...
    'senloraSymmetricV8Config','senloraSymmetricV8GenerateFrame', ...
    'senloraSymmetricV8Decode','senloraSymmetricV8BlendBootstrap', ...
    'senloraSymmetricV6Config','senloraSymmetricV6Decode', ...
    'exp1IdealDecode','senloraSymmetricV3SeedPlan', ...
    'v4CommonBootstrap','v4Stage55JointPreambleMlBootstrap', ...
    'v4Stage55BootstrapFromJointPreambleMl','v4RollingTrackerPass', ...
    'v4Stage55Confidence','v4DecodePayload'};
explicitPaths = strings(numel(names),1);
for index = 1:numel(names)
    path = which(names{index});
    if isempty(path)
        error('EXP5V8:Dependency','Cannot resolve %s.',names{index});
    end
    explicitPaths(index) = string(path);
end
required = string(matlab.codetools.requiredFilesAndProducts( ...
    which('runSenloraSymmetricV8Mechanism')));
allPaths = unique([required(:);explicitPaths]);
inScope = startsWith(allPaths,string(config.projectRoot)+filesep, ...
    'IgnoreCase',true) | startsWith(allPaths, ...
    string(config.parentRoot)+filesep,'IgnoreCase',true);
sourcePaths = sort(allPaths(inScope));
if isempty(sourcePaths)
    error('EXP5V8:Dependency','The runtime dependency closure is empty.');
end
sourceHashes = strings(size(sourcePaths));
for index = 1:numel(sourcePaths)
    sourceHashes(index) = exp1Sha256(sourcePaths(index));
end
signature = struct('identity',plan.identity, ...
    'receiverVersion',plan.receiverVersion, ...
    'seedRoot',plan.mechanismRootSeed,'snrDb',plan.snrDb, ...
    'negativeOrbitStartSec',plan.negativeOrbitStartSec, ...
    'frameDurationSec',plan.frameDurationSec, ...
    'driftBlendStartBins',plan.driftBlendStartBins, ...
    'driftBlendEndBins',plan.driftBlendEndBins, ...
    'packetsPerPair',plan.mechanismPacketsPerMirrorPair, ...
    'v6NativeFrameDurationSec',v6Plan.frameDurationSec, ...
    'executionSourcePaths',sourcePaths, ...
    'executionSourceSha256',sourceHashes);
end

function localValidateCheckpoint(state,signature,shape,nData)
required = {'signature','v8Errors','v6Errors','idealErrors','rateGain', ...
    'preambleRateBinsPerSec','candidateVp','acceptedVp','passCount', ...
    'v8CfoResidualBins','failed','failureMessage','v8UsageFlags', ...
    'payloadSeed','noiseSeed','completed'};
for index = 1:numel(required)
    if ~isfield(state,required{index})
        error('EXP5V8:Checkpoint','Checkpoint field %s is missing.', ...
            required{index});
    end
end
if ~strcmp(jsonencode(state.signature),jsonencode(signature)) || ...
        ~isequal(size(state.v8Errors),shape) || ...
        ~isequal(size(state.v8CfoResidualBins),[shape,nData]) || ...
        ~isequal(size(state.failed),[shape,3]) || ...
        ~isequal(size(state.v8UsageFlags),[shape,6]) || ...
        ~isequal(size(state.completed),[shape(1),shape(3)])
    error('EXP5V8:Checkpoint','The mechanism checkpoint is incompatible.');
end
end

function localSaveCheckpoint(path,state)
temporary = path+".tmp";
save(temporary,'-struct','state','-v7.3');
[moved,message] = movefile(temporary,path,'f');
if ~moved
    error('EXP5V8:CheckpointWrite','%s',message);
end
end

function [raw,summary] = localTables(state,plan,c)
pairCount = size(state.v8Errors,1);
packetCount = size(state.v8Errors,3);
nData = c.payloadSymbolCount;
rawRows = cell(pairCount*2*packetCount,22);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        for packetId = 1:packetCount
            row = row+1;
            residual = double(reshape( ...
                state.v8CfoResidualBins(pair,side,packetId,:),[],1));
            rawRows(row,:) = {pair,side,starts(side),packetId, ...
                state.payloadSeed(pair,packetId), ...
                state.noiseSeed(pair,packetId), ...
                double(state.v8Errors(pair,side,packetId)), ...
                double(state.v6Errors(pair,side,packetId)), ...
                double(state.idealErrors(pair,side,packetId)), ...
                double(state.v8Errors(pair,side,packetId))/nData, ...
                double(state.v6Errors(pair,side,packetId))/nData, ...
                double(state.idealErrors(pair,side,packetId))/nData, ...
                state.rateGain(pair,side,packetId), ...
                state.preambleRateBinsPerSec(pair,side,packetId), ...
                double(state.candidateVp(pair,side,packetId)), ...
                double(state.acceptedVp(pair,side,packetId)), ...
                double(state.passCount(pair,side,packetId)), ...
                mean(residual,'omitnan'),sqrt(mean(residual.^2,'omitnan')), ...
                any(state.failed(pair,side,packetId,:)), ...
                any(state.v8UsageFlags(pair,side,packetId,:)), ...
                strjoin(state.failureMessage(pair,side,packetId,:),'; ')};
        end
    end
end
raw = cell2table(rawRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packetId', ...
    'payloadSeed','noiseSeed','v8RawErrors','v6RawErrors', ...
    'idealRawErrors','v8Ser','v6Ser','idealSer','rateGain', ...
    'preambleRateBinsPerSec','candidateVp','acceptedVp','passCount', ...
    'meanCfoResidualBins','cfoResidualRmseBins','anyReceiverFailure', ...
    'anyV8ForbiddenUse','failureMessage'});

pointRows = cell(pairCount*2,20);
row = 0;
for pair = 1:pairCount
    starts = [plan.negativeOrbitStartSec(pair), ...
        -plan.negativeOrbitStartSec(pair)-plan.frameDurationSec];
    for side = 1:2
        row = row+1;
        v8 = double(reshape(state.v8Errors(pair,side,:),[],1));
        v6 = double(reshape(state.v6Errors(pair,side,:),[],1));
        ideal = double(reshape(state.idealErrors(pair,side,:),[],1));
        gain = reshape(state.rateGain(pair,side,:),[],1);
        candidate = double(reshape(state.candidateVp(pair,side,:),[],1));
        accepted = double(reshape(state.acceptedVp(pair,side,:),[],1));
        residual = double(reshape( ...
            state.v8CfoResidualBins(pair,side,:,:),[],1));
        pointRows(row,:) = {pair,side,starts(side),packetCount, ...
            sum(v8),sum(v6),sum(ideal),sum(v8)/(packetCount*nData), ...
            sum(v6)/(packetCount*nData),sum(ideal)/(packetCount*nData), ...
            mean(gain),min(gain),max(gain),sum(candidate), ...
            mean(candidate),sum(accepted),mean(accepted), ...
            mean(residual,'omitnan'),sqrt(mean(residual.^2,'omitnan')), ...
            sum(state.failed(pair,side,:,:),'all')};
    end
end
summary = cell2table(pointRows,'VariableNames',{ ...
    'pairIndex','sideIndex','orbitStartSec','packets', ...
    'v8RawErrors','v6RawErrors','idealRawErrors','v8Ser','v6Ser', ...
    'idealSer','meanGain','minimumGain','maximumGain', ...
    'candidateVpTotal','candidateVpMean','acceptedVpTotal', ...
    'acceptedVpMean','meanCfoResidualBins','cfoResidualRmseBins', ...
    'receiverFailures'});
summary = sortrows(summary,'orbitStartSec');
end

function checks = localMechanismChecks(state,summary,c)
case1 = summary(summary.pairIndex==1,:);
case2 = summary(summary.pairIndex==9,:);
case1V8 = sum(case1.v8RawErrors)/(sum(case1.packets)*c.payloadSymbolCount);
case1V6 = sum(case1.v6RawErrors)/(sum(case1.packets)*c.payloadSymbolCount);
case2V8 = sum(case2.v8RawErrors)/(sum(case2.packets)*c.payloadSymbolCount);
case2Ideal = sum(case2.idealRawErrors)/(sum(case2.packets)*c.payloadSymbolCount);
if case2Ideal>0
    case2Ratio = case2V8/case2Ideal;
    case2WithinOneOrder = case2Ratio<=10;
elseif case2V8==0
    case2Ratio = 1;
    case2WithinOneOrder = true;
else
    case2Ratio = Inf;
    case2WithinOneOrder = false;
end
adjacentDifference = abs(diff(summary.v8Ser));
adjacentGainDifference = abs(diff(summary.meanGain));
checks = struct( ...
    'status','MECHANISM_COMPLETE_REQUIRES_REVIEW', ...
    'case1V8Ser',case1V8,'case1V6NativeSer',case1V6, ...
    'case1ObservedNotWorse',case1V8<=case1V6, ...
    'case2V8Ser',case2V8,'case2IdealSer',case2Ideal, ...
    'case2V8ToIdealRatio',case2Ratio, ...
    'case2WithinOneOrder',case2WithinOneOrder, ...
    'receiverFailures',sum(state.failed,'all'), ...
    'allV8UseFlagsFalse',~any(state.v8UsageFlags,'all'), ...
    'allGainsFiniteAndBounded',all(isfinite(state.rateGain),'all') && ...
        all(state.rateGain>=0 & state.rateGain<=1,'all'), ...
    'maximumAdjacentRawSerDifference',max(adjacentDifference), ...
    'maximumAdjacentMeanGainDifference',max(adjacentGainDifference), ...
    'd0CandidateBins',state.signature.driftBlendStartBins, ...
    'd1CandidateBins',state.signature.driftBlendEndBins, ...
    'parametersFrozen',false,'reviewRunStarted',false, ...
    'formalRunStarted',false);
end

function localPlot(summary,root)
x = summary.orbitStartSec;
f = figure('Visible','off','Color','w','Position',[100 100 1180 760]);
tiledlayout(2,2,'TileSpacing','compact','Padding','compact');
nexttile
plot(x,summary.v8Ser,'-o','LineWidth',1.2, ...
    'DisplayName','V8');
hold on
plot(x,summary.v6Ser,'-s','LineWidth',1.2, ...
    'DisplayName','V6-native');
plot(x,summary.idealSer,'-^','LineWidth',1.2, ...
    'DisplayName','Ideal');
grid on;xlabel('Frame start time (s)');ylabel('Raw SER');
title('Raw orbit points only');legend('Location','best');
nexttile
plot(x,summary.meanGain,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('Mean gain');ylim([-0.05 1.05]);
title('Continuous Static-to-Dynamic gain');
nexttile
plot(x,summary.acceptedVpMean,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('Accepted VP per packet');
title('Second-pass virtual pilots');
nexttile
plot(x,summary.cfoResidualRmseBins,'-o','LineWidth',1.2);grid on
xlabel('Frame start time (s)');ylabel('CFO residual RMSE (bins)');
title('V8 CFO residual');
sgtitle({'SenLoRa V8 preliminary mechanism run', ...
    'Measured points connected directly; no fit or smoothing'});
exportgraphics(f,fullfile(root,'MECHANISM_RAW_POINTS.png'), ...
    'Resolution',220);
close(f);
end
