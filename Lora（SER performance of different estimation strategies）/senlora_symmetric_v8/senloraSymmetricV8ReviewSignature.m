function signature = senloraSymmetricV8ReviewSignature( ...
        plan,v6Plan,config,packetCount,commonParameters)
%SENLORASYMMETRICV8REVIEWSIGNATURE Bind Review source and parameter inputs.

names = {'runSenloraSymmetricV8JointBlockReview', ...
    'senloraSymmetricV8ReviewSignature', ...
    'senloraSymmetricV8JointBlockDecode', ...
    'senloraSymmetricV8BlockLikelihood', ...
    'senloraSymmetricV8BlendBootstrap', ...
    'senloraSymmetricV8GenerateFrame', ...
    'senloraSymmetricV6Config','senloraSymmetricV6Decode', ...
    'senloraSymmetricV3SeedPlan','exp1IdealDecode', ...
    'v4CommonBootstrap','v4Stage55JointPreambleMlBootstrap', ...
    'v4Stage55BootstrapFromJointPreambleMl','v4RollingTrackerPass', ...
    'v4DecodePayload'};
explicitPaths = strings(numel(names),1);
for index = 1:numel(names)
    path = which(names{index});
    if isempty(path)
        error('EXP5V8:Dependency','Cannot resolve %s.',names{index});
    end
    explicitPaths(index) = string(path);
end
required = string(matlab.codetools.requiredFilesAndProducts( ...
    which('runSenloraSymmetricV8JointBlockReview')));
allPaths = unique([required(:);explicitPaths]);
inScope = startsWith(allPaths,string(config.projectRoot)+filesep, ...
    'IgnoreCase',true) | startsWith(allPaths, ...
    string(config.parentRoot)+filesep,'IgnoreCase',true);
sourcePaths = sort(allPaths(inScope));
if isempty(sourcePaths)
    error('EXP5V8:Dependency','The Review dependency closure is empty.');
end
sourceHashes = strings(size(sourcePaths));
for index = 1:numel(sourcePaths)
    sourceHashes(index) = exp1Sha256(sourcePaths(index));
end

parameterPaths = [string(fullfile(fileparts(which( ...
    'v4LoadMethodAlignedParametersV1')), ...
    'method_aligned_selected_parameters_v1.json')); ...
    string(commonParameters.sourcePath)];
parameterPaths = unique(parameterPaths,'stable');
parameterHashes = strings(size(parameterPaths));
for index = 1:numel(parameterPaths)
    if ~isfile(parameterPaths(index))
        error('EXP5V8:Dependency', ...
            'Cannot resolve parameter source %s.',parameterPaths(index));
    end
    parameterHashes(index) = exp1Sha256(parameterPaths(index));
end

signature = struct('identity',plan.identity, ...
    'receiverVersion','SenLoRa-V8-joint-block-review-v1', ...
    'phase','review','seedRoot',plan.reviewRootSeed, ...
    'snrDb',plan.snrDb, ...
    'negativeOrbitStartSec',plan.negativeOrbitStartSec, ...
    'frameDurationSec',plan.frameDurationSec, ...
    'driftBlendStartBins',plan.driftBlendStartBins, ...
    'driftBlendEndBins',plan.driftBlendEndBins, ...
    'packetsPerPair',packetCount, ...
    'v6NativeFrameDurationSec',v6Plan.frameDurationSec, ...
    'executionSourcePaths',sourcePaths, ...
    'executionSourceSha256',sourceHashes, ...
    'commonSearchStepBins',commonParameters.searchStepBins, ...
    'commonParameterSourcePaths',parameterPaths, ...
    'commonParameterSourceSha256',parameterHashes);
end
